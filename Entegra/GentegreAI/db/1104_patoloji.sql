select g.id, (g.gonderim_no || ' · ' || d.ad)::varchar(240) as ad,
       case when g.durum = 1 then 1 else 0 end::smallint as aktif
  from public.pat_gonderim g join public.lab_dis_lab d on d.id = g.dis_lab_id;

