create or replace function public.tg_pat_rapor_kilit() returns trigger language plpgsql as $$
begin
  if old.durum = 3 and (new.makro is distinct from old.makro or new.mikro is distinct from old.mikro
      or new.tani is distinct from old.tani or new.icdo_topografi is distinct from old.icdo_topografi
      or new.icdo_morfoloji is distinct from old.icdo_morfoloji or new.durum <> 3) then
    raise exception 'Onaylı patoloji raporu değiştirilemez - ek rapor ya da revize rapor ekleyin.'
      using errcode = 'P0001';
  end if;
  return new;
end $$;
drop trigger if exists tg_pat_rapor_kilit on public.pat_rapor;
create trigger tg_pat_rapor_kilit before update on public.pat_rapor
  for each row execute function public.tg_pat_rapor_kilit();

--  ONAYLI RAPOR GELİNCE VAKA "Rapor geldi": rapor zamanı (TAT durur) ve hekime
--  yeniden bildirim için durum 11. Ek / revize rapor görülmüş vakayı da 11'e
--  döndürür - yeni sürüm hekime yeniden gider.
create or replace function public.tg_pat_rapor_vaka() returns trigger language plpgsql as $$
begin
  if new.durum = 3 and (tg_op = 'INSERT' or old.durum <> 3) then
    update public.pat_vaka
       set durum = 11, rapor_zamani = coalesce(rapor_zamani, new.rapor_zamani),
           gordu_zamani = null, gordu_id = 0
     where id = new.vaka_id and durum not in (0, 90);
  end if;
  return new;
end $$;
drop trigger if exists tg_pat_rapor_vaka on public.pat_rapor;
create trigger tg_pat_rapor_vaka after insert or update on public.pat_rapor
  for each row execute function public.tg_pat_rapor_vaka();

