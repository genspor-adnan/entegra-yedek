-- fn_pat_no('PI', 4) -> 'PI-2026/0001' · fn_pat_no('P', 5, true) -> 'P26-00001'
create or replace function public.fn_pat_no(p_onek varchar, p_basamak integer default 4, p_kisa boolean default false)
returns varchar language plpgsql as $$
declare v_yil smallint := extract(year from current_date)::smallint; v_no integer;
begin
  insert into public.pat_sayac (onek, yil, son_no) values (p_onek, v_yil, 1)
  on conflict (onek, yil) do update set son_no = public.pat_sayac.son_no + 1
  returning son_no into v_no;
  if p_kisa then
    return p_onek || lpad((v_yil % 100)::text, 2, '0') || '-' || lpad(v_no::text, greatest(p_basamak, 1), '0');
  end if;
  return p_onek || '-' || v_yil || '/' || lpad(v_no::text, greatest(p_basamak, 1), '0');
end $$;

