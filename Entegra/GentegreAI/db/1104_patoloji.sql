select d.id, (d.ad || case d.baglanti_turu when 1 then ' · API' when 2 then ' · HL7' when 3 then ' · FHIR'
                                           when 4 then ' · portal' else ' · elle' end)::varchar(240) as ad,
       case when d.durum = 0 and d.patoloji = 1 then 1 else 0 end::smallint as aktif
  from public.lab_dis_lab d;
