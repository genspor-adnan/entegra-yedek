-- ------------------------------------------------------------------ tablolar --
create table if not exists public.yil_devri (
    id           integer generated by default as identity primary key,
    sube_id      integer      not null references public.sube(id),
    kaynak_yil   smallint     not null,
    hedef_yil    smallint     not null,
    -- son TAMAMLANAN adım (0 = başlamadı ... 5 = kilitlendi)
    tamam_adim   smallint     not null default 0,
    -- 0 sürüyor · 1 tamamlandı (kilitli)
    durum        smallint     not null default 0,
    secenekler   jsonb        not null default '{}'::jsonb,
    baslatan     integer      not null default 0,
    baslama      timestamptz  not null default now(),
    bitis        timestamptz,
    constraint ux_yil_devri unique (sube_id, kaynak_yil)
);
comment on table public.yil_devri is 'Yıl sonu / başı devri (1155) - şube + kaynak yıl başına bir devir.';

create table if not exists public.yil_devri_gunluk (
    id           bigint generated by default as identity primary key,
    devir_id     integer      not null references public.yil_devri(id) on delete cascade,
    adim         smallint     not null,
    -- yap · geri · not
    islem        varchar(10)  not null,
    aciklama     varchar(500) not null default '',
    kullanici_id integer      not null default 0,
    zaman        timestamptz  not null default now()
);
create index if not exists ix_yil_devri_gunluk on public.yil_devri_gunluk (devir_id, id);

-- Adımın ürettiği / değiştirdiği kayıt - geri alma bunu okur.
create table if not exists public.yil_devri_kayit (
    id           bigint generated by default as identity primary key,
    devir_id     integer      not null references public.yil_devri(id) on delete cascade,
    adim         smallint     not null,
    -- fis · mali_donem · muhasebe_donem · numara_sablonu · izin_hak · kilit · donem_durum
    tur          varchar(20)  not null,
    kayit_id     bigint       not null,
    eski         jsonb
);
create index if not exists ix_yil_devri_kayit on public.yil_devri_kayit (devir_id, adim);

-- -------------------------------------------------------------- yardımcılar --
create or replace function public.fn_yil_devri_hesap(p_kod text)
returns integer language sql stable as $$
    select id from public.hesap_plani where kod = p_kod order by id limit 1
$$;

-- Ayın / yılın 31.12'si itibarıyla döviz alış kuru (VUK 280: TCMB döviz alış). Yoksa null.
create or replace function public.fn_yil_devri_kur(p_doviz text, p_tarih date)
returns numeric language sql stable as $$
    select k.alis from public.doviz_kur k
     where k.doviz_cinsi = p_doviz and k.tarih <= p_tarih and k.alis > 0
     order by k.tarih desc limit 1
$$;

