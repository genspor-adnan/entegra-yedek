-- ----------------------------------------------------------------- 1) kontrol --
create or replace function public.fn_yil_devri_kontrol(p_sube integer, p_yil smallint)
returns table (sira integer, kod text, ad text, tur text, adet bigint, tutar numeric,
               aciklama text, rota text)
language plpgsql stable as $$
declare
    v_bas date := make_date(p_yil, 1, 1);
    v_bit date := make_date(p_yil, 12, 31);
    v_yerel text := public.fn_yerel_para();
    v_eksik text;
    v_n bigint;
begin
    -- 1 Fişlenemeyen belge (192): çözülmemiş hata izi.
    select count(*) into v_n from public.muhasebe_fis_hata h
     where h.cozuldu = 0 and (h.sube_id is null or h.sube_id = p_sube);
    return query select 1, 'fis_hata'::text, 'Muhasebeye aktarılamayan (fişlenemeyen) belge'::text, 'engel'::text,
                        v_n, null::numeric, ''::text, ''::text;

    -- 2 Taslak belge (kesinleşmemiş, yılın içinde).
    select count(*) into v_n from public.belge b
     where b.durum = 1 and b.sube_id = p_sube and b.belge_tarihi::date between v_bas and v_bit;
    return query select 2, 'taslak'::text, 'Taslak (kesinleşmemiş) belge'::text, 'engel'::text,
                        v_n, null::numeric, ''::text, 'fatura'::text;

    -- 3 Kapatılmamış kasa günü: o yıl kasa işlemi olup kapanışı olmayan gün (HBYS gün sonu).
    select count(distinct ki.islem_tarihi::date) into v_n
      from public.kasa_islem ki
     where ki.sube_id = p_sube and ki.islem_tarihi::date between v_bas and v_bit
       and exists (select 1 from public.kasa_gun_kapanis g where g.sube_id = p_sube)   -- gün sonu kullanan kurum
       and not exists (select 1 from public.kasa_gun_kapanis g
                        where g.sube_id = p_sube and g.tarih = ki.islem_tarihi::date and g.durum = 1);
    return query select 3, 'kasa_gun'::text, 'Kapatılmamış kasa günü'::text, 'engel'::text,
                        v_n, null::numeric, ''::text, 'kasa-gun-sonu'::text;

    -- 4 Açık banko oturumu.
    select count(*) into v_n from public.banko_oturum o where o.sube_id = p_sube and o.durum = 2;
    return query select 4, 'banko'::text, 'Açık banko oturumu'::text, 'engel'::text,
                        v_n, null::numeric, ''::text, 'banko-oturum'::text;

    -- 5 31.12 kuru: yıl içinde hareketi olan dövizlerden kuru olmayan.
    select count(*), string_agg(d, ', ') into v_n, v_eksik
      from (select distinct m.doviz_cinsi as d from public.mali_hareket m
             where m.doviz_cinsi <> v_yerel and m.islem_tarihi::date <= v_bit
               and coalesce(m.sube_id, p_sube) = p_sube) x
     -- Yılın SON HAFTASINA ait kur şart (31.12 tatilse son yayımlanan): eski bir kurla
     --   değerleme sessizce yanlış fark üretirdi.
     where not exists (select 1 from public.doviz_kur k where k.doviz_cinsi = x.d and k.alis > 0
                          and k.tarih between v_bit - 6 and v_bit);
    return query select 5, 'kur'::text, ('31.12.' || p_yil || ' döviz kuru (son hafta)')::text, 'engel'::text,
                        v_n, null::numeric,
                        case when v_n > 0 then 'Kuru olmayan: ' || v_eksik else '' end, ''::text;

    -- 6 Hesap planı: devir fişlerinin kullandığı hesaplar.
    select string_agg(k, ', ' order by k) into v_eksik
      from unnest(array['646','656','690','692','590','591','570','580']) k
     where public.fn_yil_devri_hesap(k) is null;
    return query select 6, 'hesap'::text, 'Hesap planında devir hesapları (646 656 690 692 590 591 570 580)'::text,
                        'engel'::text, case when v_eksik is null then 0::bigint
                                            else array_length(string_to_array(v_eksik, ', '), 1)::bigint end,
                        null::numeric, case when v_eksik is null then '' else 'Eksik: ' || v_eksik end,
                        'hesap-plani'::text;

    -- 7 Kaynak yılın Aralık dönemi / hedef yılın Ocak dönemi kilitli mi.
    select count(*) into v_n from public.muhasebe_donem d
     where ((d.yil = p_yil and d.ay = 12) or (d.yil = p_yil + 1 and d.ay = 1)) and d.kilitli = 1
       and (d.sube_id is null or d.sube_id = p_sube);
    return query select 7, 'donem_kilit'::text, ('Aralık ' || p_yil || ' / Ocak ' || (p_yil + 1) || ' dönem kilidi')::text,
                        'engel'::text, v_n, null::numeric,
                        case when v_n > 0 then 'Kilitli dönemde fiş yazılamaz - kilidi açın.' else '' end, ''::text;

    -- 8 e-Belge hazırlanmış ama gönderilmemiş.
    select count(*) into v_n from public.belge b
     where b.sube_id = p_sube and b.belge_tarihi::date between v_bas and v_bit
       and coalesce(b.efatura_durum, 0) > 0 and coalesce(b.efatura_durum, 0) not in (2, 12, 52);
    return query select 8, 'ebelge'::text, 'e-Fatura / e-Arşiv: hazırlanmış, gönderilmemiş'::text, 'uyari'::text,
                        v_n, null::numeric, ''::text, 'fatura'::text;

    -- 9 Medula: kaynak yılın açık (faturalanmamış) dönemi (HBYS).
    select count(*) into v_n from public.medula_donem m
     where m.yil = p_yil and m.sube_id = p_sube and coalesce(m.fatura_sayisi, 0) = 0;
    return query select 9, 'medula'::text, 'Medula: faturalanmamış dönem'::text, 'uyari'::text,
                        v_n, null::numeric, ''::text, 'medula-donem'::text;

    -- 10 Devreden açık işler (bilgi): açık sipariş + faturalanmamış irsaliye.
    return query
    select 10, 'acik_belge'::text, 'Açık sipariş / faturalanmamış irsaliye (yeni yıla devreder)'::text, 'bilgi'::text,
           count(*), coalesce(sum(b.genel_toplam), 0), ''::text, 'siparis'::text
      from public.belge b
     where b.sube_id = p_sube and b.durum <> 2 and b.tur in (14, 19)
       and coalesce(b.kapanma_durum, 0) < 2 and b.belge_tarihi::date <= v_bit;

    -- 11 Portföydeki çek / senet (bilgi).
    return query
    select 11, 'cek'::text, 'Portföydeki / tahsildeki çek - senet'::text, 'bilgi'::text,
           count(*), coalesce(sum(c.yerel_tutar), 0), ''::text, 'cek'::text
      from public.cek_senet c where c.yon = 1 and c.durum in (10, 30, 40);
end $$;

-- ---------------------------------------------------------------- 2) değerleme --
create or replace function public.fn_yil_devri_degerleme(p_sube integer, p_yil smallint)
returns table (kaynak text, kaynak_id integer, ad text, alt text, doviz text,
               doviz_bakiye numeric, yerel_bakiye numeric, kur numeric, degerli numeric,
               fark numeric, hesap_plani_id integer)
language sql stable as $$
    with par as (select make_date(p_yil, 12, 31) as bit, public.fn_yerel_para() as yerel),
    cari as (
        select e.taraf_id, e.doviz_cinsi,
               sum(e.borc - e.alacak) as db, sum(e.yerel_borc - e.yerel_alacak) as yb
          from public.v_cari_ekstre e, par
         where e.bakiye_dahil = 1 and e.doviz_cinsi <> par.yerel
           and e.islem_tarihi::date <= par.bit and e.sube_id = p_sube
         group by 1, 2
        having abs(sum(e.borc - e.alacak)) >= 0.005),
    hes as (
        select m.hesap_id, m.doviz_cinsi,
               sum(m.borc - m.alacak) as db, sum(m.yerel_borc - m.yerel_alacak) as yb
          from public.mali_hareket m, par
         where m.hesap_turu <> 'C' and m.hesap_id is not null and m.doviz_cinsi <> par.yerel
           and m.islem_tarihi::date <= par.bit and coalesce(m.sube_id, p_sube) = p_sube
         group by 1, 2
        having abs(sum(m.borc - m.alacak)) >= 0.005)
    select 'cari'::text, c.taraf_id, coalesce(t.unvan, ''), case when t.musteri = 1 then 'Müşteri' else 'Tedarikçi' end,
           c.doviz_cinsi, round(c.db, 2), round(c.yb, 2), k.kur,
           round(c.db * k.kur, 2), round(c.db * k.kur, 2) - round(c.yb, 2),
           coalesce(t.muh_hesap_id,
                    (select e.hesap_plani_id from public.muhasebe_eslestirme e
                      where e.kural_turu = 'cari' and e.aktif = 1 and e.yon = case when t.musteri = 1 then 1 else 2 end
                      order by e.oncelik limit 1))
      from cari c join public.taraf t on t.id = c.taraf_id
      cross join par
      cross join lateral (select public.fn_yil_devri_kur(c.doviz_cinsi, par.bit) as kur) k
    union all
    select 'hesap'::text, h.hesap_id, coalesce(x.ad, ''),
           case x.tur when 'K' then 'Kasa' when 'B' then 'Banka' when 'P' then 'POS' else 'Hesap' end,
           h.doviz_cinsi, round(h.db, 2), round(h.yb, 2), k.kur,
           round(h.db * k.kur, 2), round(h.db * k.kur, 2) - round(h.yb, 2),
           coalesce(x.muh_hesap_id,
                    (select e.hesap_plani_id from public.muhasebe_eslestirme e
                      where e.kural_turu = 'hesap_turu' and e.aktif = 1 and e.hesap_turu = x.tur
                      order by e.oncelik limit 1))
      from hes h join public.hesap x on x.id = h.hesap_id
      cross join par
      cross join lateral (select public.fn_yil_devri_kur(h.doviz_cinsi, par.bit) as kur) k
$$;

-- --------------------------------------------------------------------- mizan --
-- Şubenin [bas, bit] fiş satırları hesap bazında (iptal + ters fiş birlikte sayılır, net 0).
create or replace function public.fn_yil_devri_mizan(p_sube integer, p_bas date, p_bit date,
                                                    p_haric_fis integer[] default '{}')
returns table (hesap_plani_id integer, kod text, borc numeric, alacak numeric)
language sql stable as $$
    select s.hesap_plani_id, h.kod, sum(s.borc), sum(s.alacak)
      from public.muhasebe_fis f
      join public.muhasebe_fis_satir s on s.fis_id = f.id
      join public.hesap_plani h on h.id = s.hesap_plani_id
     where f.sube_id = p_sube and f.fis_tarihi between p_bas and p_bit
       and not (f.id = any (p_haric_fis))
     group by 1, 2
$$;

-- ------------------------------------------------------------- fiş yardımcısı --
create or replace function public.fn_yil_devri_fis_ac(p_devir integer, p_adim smallint, p_tarih date,
                                                     p_tur smallint, p_kaynak_tur smallint, p_ek smallint,
                                                     p_aciklama text, p_kullanici integer)
returns integer language plpgsql as $$
declare d public.yil_devri; v_fis integer; v_donem integer;
begin
    select * into d from public.yil_devri where id = p_devir;
    perform public.fn_muhasebe_donem_kontrol(p_tarih);
    select id into v_donem from public.muhasebe_donem
     where yil = extract(year from p_tarih)::smallint and ay = extract(month from p_tarih)::smallint
     order by (sube_id is null), id limit 1;
    insert into public.muhasebe_fis (fis_no, fis_tarihi, tur, durum, kaynak_tur, kaynak_id, donem_id,
                                     aciklama, sube_id, ekleyen)
    values ('', p_tarih, p_tur, 1, p_kaynak_tur, p_devir * 10 + p_ek, v_donem, left(p_aciklama, 200),
            d.sube_id, p_kullanici)
    returning id into v_fis;
    insert into public.yil_devri_kayit (devir_id, adim, tur, kayit_id) values (p_devir, p_adim, 'fis', v_fis);
    return v_fis;
end $$;

create or replace function public.fn_yil_devri_satir(p_fis integer, p_hesap integer, p_tutar numeric,
                                                    p_taraf integer, p_aciklama text)
returns void language plpgsql as $$
-- p_tutar > 0 BORÇ, < 0 ALACAK.
begin
    if p_hesap is null then
        raise exception 'Devir fişinde muhasebe hesabı çözülemedi (%). Hesap planını / eşlemeyi tamamlayın.', p_aciklama
              using errcode = 'GK422';
    end if;
    if round(coalesce(p_tutar, 0), 2) = 0 then return; end if;
    insert into public.muhasebe_fis_satir (fis_id, sira, hesap_plani_id, borc, alacak, doviz_cinsi,
                                           doviz_borc, doviz_alacak, doviz_kuru, taraf_id, aciklama)
    values (p_fis, (select coalesce(max(sira), 0) + 1 from public.muhasebe_fis_satir where fis_id = p_fis),
            p_hesap, greatest(round(p_tutar, 2), 0), greatest(round(-p_tutar, 2), 0), public.fn_yerel_para(),
            0, 0, 1, p_taraf, left(coalesce(p_aciklama, ''), 200));
end $$;

-- Fişi kapatır: boşsa siler (kayıtla birlikte), değilse dengeyi doğrular, toplamı ve numarayı yazar.
create or replace function public.fn_yil_devri_fis_kapat(p_fis integer)
returns integer language plpgsql as $$
declare v_b numeric; v_a numeric; v_n integer; v_tarih date;
begin
    select coalesce(sum(borc), 0), coalesce(sum(alacak), 0), count(*) into v_b, v_a, v_n
      from public.muhasebe_fis_satir where fis_id = p_fis;
    if v_n = 0 then
        delete from public.yil_devri_kayit where tur = 'fis' and kayit_id = p_fis;
        delete from public.muhasebe_fis where id = p_fis;
        return null;
    end if;
    if abs(v_b - v_a) > 0.005 then
        raise exception 'Devir fişi dengesiz: borç % / alacak %.', v_b, v_a using errcode = 'GK422';
    end if;
    select fis_tarihi into v_tarih from public.muhasebe_fis where id = p_fis;
    update public.muhasebe_fis
       set toplam_borc = v_b, toplam_alacak = v_a,
           fis_no = public.fn_muhasebe_fis_no_uret(extract(year from v_tarih)::integer)
     where id = p_fis;
    return p_fis;
end $$;

create or replace function public.fn_yil_devri_adim_bitir(p_devir integer, p_adim smallint, p_kullanici integer,
                                                         p_aciklama text)
returns void language plpgsql as $$
begin
    update public.yil_devri set tamam_adim = p_adim where id = p_devir;
    insert into public.yil_devri_gunluk (devir_id, adim, islem, aciklama, kullanici_id)
    values (p_devir, p_adim, 'yap', left(p_aciklama, 500), p_kullanici);
end $$;

create or replace function public.fn_yil_devri_sira(p_devir integer, p_adim smallint)
returns public.yil_devri language plpgsql as $$
declare d public.yil_devri;
begin
    select * into d from public.yil_devri where id = p_devir for update;
    if not found then raise exception 'Devir bulunamadı.' using errcode = 'GK422'; end if;
    if d.durum = 1 then raise exception 'Devir tamamlandı ve kilitlendi.' using errcode = 'GK422'; end if;
    if d.tamam_adim <> p_adim - 1 then
        raise exception 'Önce %. adım tamamlanmalı.', p_adim - 1 using errcode = 'GK422';
    end if;
    return d;
end $$;

-- ---------------------------------------------------------- adım 1: kontrol --
create or replace function public.fn_yil_devri_adim1(p_devir integer, p_kullanici integer)
returns void language plpgsql as $$
declare d public.yil_devri; v_engel text;
begin
    d := public.fn_yil_devri_sira(p_devir, 1::smallint);
    select string_agg(k.ad || ' (' || k.adet || ')', '; ') into v_engel
      from public.fn_yil_devri_kontrol(d.sube_id, d.kaynak_yil) k where k.tur = 'engel' and k.adet > 0;
    if v_engel is not null then
        raise exception 'Ön kontrolde engel var: %', v_engel using errcode = 'GK422';
    end if;
    perform public.fn_yil_devri_adim_bitir(p_devir, 1::smallint, p_kullanici, 'Ön kontrol tamam - engel yok');
end $$;

-- -------------------------------------------------------- adım 2: değerleme --
create or replace function public.fn_yil_devri_adim2(p_devir integer, p_kullanici integer,
                                                    p_cari boolean default true, p_hesap boolean default true)
returns void language plpgsql as $$
declare d public.yil_devri; v_fis integer; r record; v_kar integer; v_zarar integer; v_net numeric := 0; v_n int := 0;
begin
    d := public.fn_yil_devri_sira(p_devir, 2::smallint);
    v_kar := public.fn_yil_devri_hesap('646'); v_zarar := public.fn_yil_devri_hesap('656');
    v_fis := public.fn_yil_devri_fis_ac(p_devir, 2::smallint, make_date(d.kaynak_yil, 12, 31), 1::smallint,
                                        4::smallint, 2::smallint, 'Yıl sonu kur değerlemesi ' || d.kaynak_yil, p_kullanici);
    for r in select * from public.fn_yil_devri_degerleme(d.sube_id, d.kaynak_yil) x
              where ((x.kaynak = 'cari' and p_cari) or (x.kaynak = 'hesap' and p_hesap))
                and x.kur is not null and round(x.fark, 2) <> 0
    loop
        -- Kur farkı > 0: hesap borçlanır, 646 alacak. < 0: 656 borç, hesap alacak.
        perform public.fn_yil_devri_satir(v_fis, r.hesap_plani_id, r.fark,
                                          case when r.kaynak = 'cari' then r.kaynak_id end,
                                          r.ad || ' ' || r.doviz || ' ' || r.doviz_bakiye || ' x ' || r.kur);
        perform public.fn_yil_devri_satir(v_fis, case when r.fark > 0 then v_kar else v_zarar end, -r.fark, null,
                                          'Kur farkı ' || r.ad);
        v_net := v_net + r.fark; v_n := v_n + 1;
    end loop;
    v_fis := public.fn_yil_devri_fis_kapat(v_fis);
    update public.yil_devri set secenekler = secenekler || jsonb_build_object('degerlemeCari', p_cari, 'degerlemeHesap', p_hesap)
     where id = p_devir;
    perform public.fn_yil_devri_adim_bitir(p_devir, 2::smallint, p_kullanici,
        case when v_fis is null then 'Değerleme: kur farkı yok, fiş kesilmedi'
             else 'Değerleme fişi kesildi - ' || v_n || ' hesap, net kur farkı ' || round(v_net, 2) end);
end $$;

-- ---------------------------------------------------------- adım 3: kapanış --
create or replace function public.fn_yil_devri_adim3(p_devir integer, p_kullanici integer,
                                                    p_bilanco boolean default true)
returns void language plpgsql as $$
declare
    d public.yil_devri; v_bas date; v_bit date; v_fis integer; v_bfis integer; r record;
    v_690 integer; v_692 integer; v_590 integer; v_591 integer; v_net numeric;
begin
    d := public.fn_yil_devri_sira(p_devir, 3::smallint);
    v_bas := make_date(d.kaynak_yil, 1, 1); v_bit := make_date(d.kaynak_yil, 12, 31);
    v_690 := public.fn_yil_devri_hesap('690'); v_692 := public.fn_yil_devri_hesap('692');
    v_590 := public.fn_yil_devri_hesap('590'); v_591 := public.fn_yil_devri_hesap('591');

    v_fis := public.fn_yil_devri_fis_ac(p_devir, 3::smallint, v_bit, 5::smallint, 5::smallint, 3::smallint,
                                        'Gelir tablosu kapanışı ' || d.kaynak_yil, p_kullanici);
    -- a) 7/A: 7x0 gider -> 7x1 yansıtma; 7x1 -> gelir tablosu / 151.
    for r in select m.hesap_plani_id, m.kod, m.borc - m.alacak as bak, y.yansitma
               from public.fn_yil_devri_mizan(d.sube_id, v_bas, v_bit) m
               join public.fn_yil_devri_yansitma() y on left(m.kod, 3) = y.gider
              where round(m.borc - m.alacak, 2) <> 0
    loop
        perform public.fn_yil_devri_satir(v_fis, r.hesap_plani_id, -r.bak, null, '7/A kapanış ' || r.kod);
        perform public.fn_yil_devri_satir(v_fis, public.fn_yil_devri_hesap(r.yansitma), r.bak, null, '7/A yansıtma ' || r.kod);
    end loop;
    for r in select m.kod, m.hesap_plani_id, m.borc - m.alacak as bak, y.hedef
               from public.fn_yil_devri_mizan(d.sube_id, v_bas, v_bit) m
               join public.fn_yil_devri_yansitma() y on left(m.kod, 3) = y.yansitma
              where round(m.borc - m.alacak, 2) <> 0
    loop
        perform public.fn_yil_devri_satir(v_fis, r.hesap_plani_id, -r.bak, null, 'Yansıtma kapanışı ' || r.kod);
        perform public.fn_yil_devri_satir(v_fis, public.fn_yil_devri_hesap(r.hedef), r.bak, null, 'Yansıtma -> ' || r.hedef);
    end loop;
    -- b) 6xx (690-692 hariç) -> 690.
    for r in select m.hesap_plani_id, m.kod, m.borc - m.alacak as bak
               from public.fn_yil_devri_mizan(d.sube_id, v_bas, v_bit) m
              where left(m.kod, 1) = '6' and left(m.kod, 3) not in ('690', '691', '692')
                and round(m.borc - m.alacak, 2) <> 0
    loop
        perform public.fn_yil_devri_satir(v_fis, r.hesap_plani_id, -r.bak, null, 'Kapanış ' || r.kod);
        perform public.fn_yil_devri_satir(v_fis, v_690, r.bak, null, 'Kapanış ' || r.kod);
    end loop;
    -- c) 690 -> 692 -> 590 (kâr) / 591 (zarar). Vergi karşılığı (691) mali müşavirin fişi.
    select coalesce(sum(m.borc - m.alacak), 0) into v_net
      from public.fn_yil_devri_mizan(d.sube_id, v_bas, v_bit) m where left(m.kod, 3) = '690';
    if round(v_net, 2) <> 0 then
        perform public.fn_yil_devri_satir(v_fis, v_690, -v_net, null, '690 -> 692');
        perform public.fn_yil_devri_satir(v_fis, v_692, v_net, null, '690 -> 692');
        perform public.fn_yil_devri_satir(v_fis, v_692, -v_net, null, '692 -> ' || case when v_net < 0 then '590' else '591' end);
        perform public.fn_yil_devri_satir(v_fis, case when v_net < 0 then v_590 else v_591 end, v_net, null,
                                          case when v_net < 0 then 'Dönem net kârı' else 'Dönem net zararı' end);
    end if;
    v_fis := public.fn_yil_devri_fis_kapat(v_fis);

    -- d) Bilanço kapanışı (isteğe bağlı): bakiyesi olan BÜTÜN hesaplar sıfırlanır (1-7) - yılın
    --    gelir tablosu yukarıda kapandı; 6-7'de kalan bakiye ÖNCEKİ yıllardan kapanmamış sonuçtur
    --    ve yalnız 1-5'i sıfırlamak fişi dengesiz bırakırdı.
    if p_bilanco then
        v_bfis := public.fn_yil_devri_fis_ac(p_devir, 3::smallint, v_bit, 5::smallint, 5::smallint, 4::smallint,
                                             'Bilanço kapanışı ' || d.kaynak_yil, p_kullanici);
        for r in select m.hesap_plani_id, m.kod, m.borc - m.alacak as bak
                   from public.fn_yil_devri_mizan(d.sube_id, make_date(1900, 1, 1), v_bit) m
                  where left(m.kod, 1) in ('1', '2', '3', '4', '5', '6', '7') and round(m.borc - m.alacak, 2) <> 0
        loop
            perform public.fn_yil_devri_satir(v_bfis, r.hesap_plani_id, -r.bak, null, 'Bilanço kapanışı ' || r.kod);
        end loop;
        v_bfis := public.fn_yil_devri_fis_kapat(v_bfis);
    end if;

    update public.yil_devri set secenekler = secenekler || jsonb_build_object('bilancoKapanis', p_bilanco,
                                                                            'donemSonucu', -v_net)
     where id = p_devir;
    perform public.fn_yil_devri_adim_bitir(p_devir, 3::smallint, p_kullanici,
        'Kapanış fişleri kesildi - dönem ' || case when v_net <= 0 then 'kârı ' else 'zararı ' end || round(abs(v_net), 2)
        || case when p_bilanco then ' · bilanço kapanışı' else '' end);
end $$;

-- ---------------------------------------------------------- adım 4: yeni yıl --
create or replace function public.fn_yil_devri_adim4(p_devir integer, p_kullanici integer,
                                                    p_izin boolean default true)
returns void language plpgsql as $$
declare
    d public.yil_devri; v_id bigint; v_ay int; v_sayi int := 0; v_izin int := 0; r record;
    v_kaynak text; v_hedef text; v_poz int;
begin
    d := public.fn_yil_devri_sira(p_devir, 4::smallint);
    v_kaynak := d.kaynak_yil::text; v_hedef := d.hedef_yil::text;

    -- Mali dönem.
    if not exists (select 1 from public.mali_donem where sube_id = d.sube_id and yil = d.hedef_yil) then
        insert into public.mali_donem (sube_id, yil, ad, baslangic, bitis, tur, durum, ekleyen)
        values (d.sube_id, d.hedef_yil, d.hedef_yil || ' — Normal hesap dönemi',
                make_date(d.hedef_yil, 1, 1), make_date(d.hedef_yil, 12, 31), 1, 0, p_kullanici)
        returning id into v_id;
        insert into public.yil_devri_kayit (devir_id, adim, tur, kayit_id) values (p_devir, 4, 'mali_donem', v_id);
    end if;
    -- 12 aylık dönem (firma geneli satırı yoksa).
    for v_ay in 1..12 loop
        if not exists (select 1 from public.muhasebe_donem where yil = d.hedef_yil and ay = v_ay) then
            insert into public.muhasebe_donem (yil, ay, baslangic, bitis, kilitli, mali_donem_id)
            values (d.hedef_yil, v_ay, make_date(d.hedef_yil, v_ay, 1),
                    (make_date(d.hedef_yil, v_ay, 1) + interval '1 month - 1 day')::date, 0,
                    (select id from public.mali_donem where sube_id = d.sube_id and yil = d.hedef_yil))
            returning id into v_id;
            insert into public.yil_devri_kayit (devir_id, adim, tur, kayit_id) values (p_devir, 4, 'muhasebe_donem', v_id);
        end if;
    end loop;

    -- Yıllı numara şablonları: numarada kaynak yıl geçen, yürürlükteki şablonun yeni yıl kopyası
    --   (yıl değişir, sıra 1'den). Yılsız numaralar sürer - dokunulmaz.
    for r in select distinct on (s.tur, coalesce(s.sube_id, 0)) s.*
               from public.numara_sablonu s
              where s.durum = 1 and s.baslama_tarihi <= make_date(d.kaynak_yil, 12, 31)
              order by s.tur, coalesce(s.sube_id, 0), s.baslama_tarihi desc, s.id desc
    loop
        v_poz := strpos(r.baslama_no, v_kaynak);
        continue when v_poz = 0;
        continue when exists (select 1 from public.numara_sablonu x
                               where x.tur = r.tur and coalesce(x.sube_id, 0) = coalesce(r.sube_id, 0)
                                 and x.baslama_tarihi >= make_date(d.hedef_yil, 1, 1));
        -- hane / baslangic numaradan TÜRETİLEN kolonlar (generated) - yazılmaz.
        insert into public.numara_sablonu (tur, baslama_tarihi, on_ek, baslama_no, sube_id, durum, aciklama,
                                           ekleyen, elle_girilir)
        values (r.tur, make_date(d.hedef_yil, 1, 1), replace(r.on_ek, v_kaynak, v_hedef),
                left(r.baslama_no, v_poz - 1) || v_hedef
                  || lpad('1', length(r.baslama_no) - v_poz - 3, '0'),
                r.sube_id, 1, left('Yıl devri ' || v_kaynak || ' -> ' || v_hedef, 200), p_kullanici,
                r.elle_girilir)
        returning id into v_id;
        insert into public.yil_devri_kayit (devir_id, adim, tur, kayit_id) values (p_devir, 4, 'numara_sablonu', v_id);
        v_sayi := v_sayi + 1;
    end loop;

    -- Yıllık izin devri: kaynak yıl kalan (hak + devir + ek - kullanılan) -> hedef yılın devir günü;
    --   yeni hak kıdeme göre (fn_izin_hak_gun). Hedef yıl satırı varsa dokunulmaz.
    if p_izin then
        for r in select p.id, p.ise_giris_tarihi, p.dogum_tarihi,
                        coalesce(h.hak_gun, public.fn_izin_hak_gun(p.ise_giris_tarihi, d.kaynak_yil, p.dogum_tarihi), 0)
                          + coalesce(h.devir_gun, 0) + coalesce(h.ek_gun, 0)
                          - coalesce((select sum(i.gun) from public.personel_izin i
                                       where i.taraf_id = p.id and i.tur = 1 and i.durum = 2
                                         and extract(year from i.baslangic_tarihi) = d.kaynak_yil), 0) as kalan
                   from public.taraf_personel p
                   join public.taraf t on t.id = p.id and t.personel = 1 and t.durum = 1
                   left join public.personel_izin_hak h on h.taraf_id = p.id and h.yil = d.kaynak_yil
                  where p.isten_cikis_tarihi is null and p.ise_giris_tarihi is not null
                    and (p.sube_id is null or p.sube_id = d.sube_id)
                    and not exists (select 1 from public.personel_izin_hak x where x.taraf_id = p.id and x.yil = d.hedef_yil)
        loop
            insert into public.personel_izin_hak (taraf_id, yil, hak_gun, devir_gun, ek_gun, aciklama, sube_id, ekleyen)
            values (r.id, d.hedef_yil, public.fn_izin_hak_gun(r.ise_giris_tarihi, d.hedef_yil, r.dogum_tarihi),
                    greatest(r.kalan, 0), 0, left('Yıl devri ' || v_kaynak, 200), d.sube_id, p_kullanici)
            returning id into v_id;
            insert into public.yil_devri_kayit (devir_id, adim, tur, kayit_id) values (p_devir, 4, 'izin_hak', v_id);
            v_izin := v_izin + 1;
        end loop;
    end if;

    update public.yil_devri set secenekler = secenekler || jsonb_build_object('izinDevri', p_izin) where id = p_devir;
    perform public.fn_yil_devri_adim_bitir(p_devir, 4::smallint, p_kullanici,
        d.hedef_yil || ' hazırlandı - ' || v_sayi || ' numara şablonu' ||
        case when p_izin then ', ' || v_izin || ' personel izin devri' else '' end);
end $$;

-- ------------------------------------------------------ adım 5: açılış/kilit --
create or replace function public.fn_yil_devri_adim5(p_devir integer, p_kullanici integer,
                                                    p_kilit boolean default true)
returns void language plpgsql as $$
declare
    d public.yil_devri; v_fis integer; r record; v_haric integer[]; v_id bigint;
    v_590 integer; v_591 integer; v_570 integer; v_580 integer; v_hp integer; v_fark numeric;
begin
    d := public.fn_yil_devri_sira(p_devir, 5::smallint);
    v_590 := public.fn_yil_devri_hesap('590'); v_591 := public.fn_yil_devri_hesap('591');
    v_570 := public.fn_yil_devri_hesap('570'); v_580 := public.fn_yil_devri_hesap('580');
    -- Bilanço kapanış fişi bakiyeyi sıfırladı - açılış onun ÖNCESİNDEKİ bakiyeden.
    select coalesce(array_agg(f.id), '{}') into v_haric from public.muhasebe_fis f
     where f.kaynak_tur = 5 and f.kaynak_id = p_devir * 10 + 4;

    v_fis := public.fn_yil_devri_fis_ac(p_devir, 5::smallint, make_date(d.hedef_yil, 1, 1), 4::smallint,
                                        5::smallint, 5::smallint, 'Açılış fişi ' || d.hedef_yil, p_kullanici);
    for r in select m.hesap_plani_id, m.kod, m.borc - m.alacak as bak
               from public.fn_yil_devri_mizan(d.sube_id, make_date(1900, 1, 1), make_date(d.kaynak_yil, 12, 31), v_haric) m
              where left(m.kod, 1) in ('1', '2', '3', '4', '5') and round(m.borc - m.alacak, 2) <> 0
    loop
        -- Dönem sonucu açılışta geçmiş yıllara: 590 -> 570, 591 -> 580.
        v_hp := case when r.hesap_plani_id = v_590 then v_570 when r.hesap_plani_id = v_591 then v_580
                     else r.hesap_plani_id end;
        perform public.fn_yil_devri_satir(v_fis, v_hp, r.bak, null, 'Açılış ' || r.kod);
    end loop;
    -- KAPANMAMIŞ ÖNCEKİ DÖNEM SONUCU: daha önceki yıllar bu ekranla kapanmadıysa 6-7'de bakiye
    --   kalmıştır ve 1-5 açılışı dengesiz olur. Fark geçmiş yıllar kârına (570) / zararına (580).
    select coalesce(sum(borc - alacak), 0) into v_fark from public.muhasebe_fis_satir where fis_id = v_fis;
    if round(v_fark, 2) <> 0 then
        perform public.fn_yil_devri_satir(v_fis, case when v_fark > 0 then v_570 else v_580 end, -v_fark, null,
                                          'Kapanmamış önceki dönem sonucu');
    end if;
    v_fis := public.fn_yil_devri_fis_kapat(v_fis);

    if p_kilit then
        for r in select id, kilitli from public.muhasebe_donem
                  where yil = d.kaynak_yil and (sube_id is null or sube_id = d.sube_id) and kilitli = 0
        loop
            insert into public.yil_devri_kayit (devir_id, adim, tur, kayit_id, eski)
            values (p_devir, 5, 'kilit', r.id, jsonb_build_object('kilitli', r.kilitli));
            update public.muhasebe_donem set kilitli = 1, kilitleyen = p_kullanici, kilit_tarihi = now() where id = r.id;
        end loop;
        for r in select id, durum from public.mali_donem where sube_id = d.sube_id and yil = d.kaynak_yil loop
            insert into public.yil_devri_kayit (devir_id, adim, tur, kayit_id, eski)
            values (p_devir, 5, 'donem_durum', r.id, jsonb_build_object('durum', r.durum, 'devirFisId', null));
            update public.mali_donem set durum = 2, devir_fis_id = v_fis, degistiren = p_kullanici,
                   degistirme_tarihi = now()::timestamp where id = r.id;
        end loop;
        update public.yil_devri set durum = 1, bitis = now() where id = p_devir;
    end if;
    update public.yil_devri set secenekler = secenekler || jsonb_build_object('kilit', p_kilit) where id = p_devir;
    perform public.fn_yil_devri_adim_bitir(p_devir, 5::smallint, p_kullanici,
        'Açılış fişi kesildi' || case when p_kilit then ' · ' || d.kaynak_yil || ' kilitlendi' else ' (kilit yok)' end);
end $$;

-- -------------------------------------------------------------- geri alma --
create or replace function public.fn_yil_devri_geri_al(p_devir integer, p_kullanici integer)
returns void language plpgsql as $$
declare d public.yil_devri; r record; v_adim smallint;
begin
    select * into d from public.yil_devri where id = p_devir for update;
    if not found then raise exception 'Devir bulunamadı.' using errcode = 'GK422'; end if;
    if d.durum = 1 then
        raise exception 'Devir kilitlendi - geri alınamaz. Dönem kilidi ayrı yetkiyle açılır.' using errcode = 'GK422';
    end if;
    v_adim := d.tamam_adim;
    if v_adim = 0 then raise exception 'Geri alınacak adım yok.' using errcode = 'GK422'; end if;

    for r in select * from public.yil_devri_kayit where devir_id = p_devir and adim = v_adim order by id desc loop
        if r.tur = 'fis' then
            perform public.fn_muhasebe_donem_kontrol((select fis_tarihi from public.muhasebe_fis where id = r.kayit_id));
            delete from public.muhasebe_fis_satir where fis_id = r.kayit_id;
            delete from public.muhasebe_fis where id = r.kayit_id;
        elsif r.tur = 'muhasebe_donem' then
            delete from public.muhasebe_donem where id = r.kayit_id;
        elsif r.tur = 'mali_donem' then
            delete from public.mali_donem where id = r.kayit_id;
        elsif r.tur = 'numara_sablonu' then
            delete from public.numara_sablonu where id = r.kayit_id;
        elsif r.tur = 'izin_hak' then
            delete from public.personel_izin_hak where id = r.kayit_id;
        elsif r.tur = 'kilit' then
            update public.muhasebe_donem set kilitli = (r.eski ->> 'kilitli')::smallint where id = r.kayit_id;
        elsif r.tur = 'donem_durum' then
            update public.mali_donem set durum = (r.eski ->> 'durum')::smallint, devir_fis_id = null where id = r.kayit_id;
        end if;
    end loop;
    delete from public.yil_devri_kayit where devir_id = p_devir and adim = v_adim;
    update public.yil_devri set tamam_adim = v_adim - 1 where id = p_devir;
    insert into public.yil_devri_gunluk (devir_id, adim, islem, aciklama, kullanici_id)
    values (p_devir, v_adim, 'geri', v_adim || '. adım geri alındı', p_kullanici);
end $$;

-- -------------------------------------------------------------------- yetki --
insert into public.yetki (kod, ad, grup, tur, sira, urun_modu, modul)
select 'muhasebe.yil_devri', 'Yıl Sonu Devri', 'Muhasebe', 0, y.sira, y.urun_modu, y.modul
  from public.yetki y where y.kod = 'muhasebe_fis'
on conflict (kod) do update set ad = excluded.ad, grup = excluded.grup, aktif = 1;

-- Muhasebe fişinde Değiştir yetkisi olan roller (yönetici dahil) bu ekranı da görür / yürütür.
insert into public.rol_yetki (rol_id, yetki_id, gor, ekle, degistir, sil, deger, kapsam, ekleyen)
select ry.rol_id, yn.id, ry.gor, ry.ekle, ry.degistir, 0, ry.deger, ry.kapsam, 0
  from public.rol_yetki ry
  join public.yetki ye on ye.id = ry.yetki_id and ye.kod = 'muhasebe_fis'
  join public.yetki yn on yn.kod = 'muhasebe.yil_devri'
 where ry.degistir = 1
   and not exists (select 1 from public.rol_yetki x where x.rol_id = ry.rol_id and x.yetki_id = yn.id);

commit;
