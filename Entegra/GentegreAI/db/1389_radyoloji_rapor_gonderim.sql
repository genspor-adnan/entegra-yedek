-- ---- başvurunun hasta payı kalanı -----------------------------------------------------------------------------------
-- HastaIcmalUclari ile AYNI formül: genel toplam - kurum payı (SGK + ÖSS dağılımı) - net tahsilat. Borç kuralının
-- tek kaynağı (gönderim işçisi, bağlantı açılışı, teslim listesi).
create or replace function public.fn_basvuru_hasta_kalan(p_belge_id integer) returns numeric
language sql stable as $$
    select coalesce(be.genel_toplam, 0)
           - least(coalesce((select sum(coalesce(dg.sgk, 0) + coalesce(dg.oss, 0))
                               from public.belge_satir st
                               left join public.belge_satir_dagilim dg on dg.belge_satir_id = st.id
                              where st.belge_id = be.id), 0), coalesce(be.genel_toplam, 0))
           - coalesce((select sum(case when kt.yon > 0 then ki.yerel_tutar else -ki.yerel_tutar end)
                         from public.kasa_islem ki
                         join public.kasa_islem_turu kt on kt.kod = ki.tur
                        where ki.belge_id = be.id and ki.durum not in (0, 1, 4, 9)), 0)
      from public.belge be where be.id = p_belge_id;
$$;

