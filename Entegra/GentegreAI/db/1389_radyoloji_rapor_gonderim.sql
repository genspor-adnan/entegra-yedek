-- 1389: RADYOLOJİ RAPORU HASTAYA / GÖNDEREN DIŞ DOKTORA GÖNDERİM (kullanıcı 20.11.2026; mockup
-- Ekranlar/Radyoloji/radyoloji_rapor_hasta_goruntuleme.html).
--
-- Rapor onaylanınca / e-imzalanınca rapora özel bağlantı üretilir (kâğıt çıktıda karekod, SMS / e-postada bağlantı).
-- Gönderim şube ayarı açıksa ZAMAN KURALLARINA göre planlanır (kod › kategori › tümü; kritik bulguda tek süre).
-- BORÇ KURALI: raporun BAŞVURUSUNUN hasta payı borcu varken ne hastaya ne gönderen dış doktora gider, bağlantı da
-- raporu açmaz; borç kapanınca bekleyenler kendiliğinden gider. Doğrulama adımı YOK (kullanıcı kararı). Hastanın
-- bağlantıyı açması "teslim edildi" sayılır (radyoloji_teslim, dijital).
--
-- Tablolar yeni; mevcut veriye dokunulmaz. Dış doktor tercihi taraf_personel.rapor_bildirim (varsayılan 0 = istemiyor).

-- ---- şube ayarı ---------------------------------------------------------------------------------------------------
create table if not exists public.radyoloji_rapor_gonderim_ayar (
    sube_id            integer     primary key references public.sube(id),
    otomatik           smallint    not null default 0,     -- 1: onayda / imzada kurallara göre planla
    kritik_dakika      integer     not null default 0,     -- kritik bulgulu raporda süre (dk); 0 = otomatik gitmez
    borc_kontrol       smallint    not null default 1,     -- 1: başvurunun borcu varken gönderme / açma
    hasta_sms          smallint    not null default 1,
    hasta_eposta       smallint    not null default 0,
    gecerlilik_gun     integer     not null default 30,    -- bağlantının geçerlilik günü
    degistiren         integer     not null default 0,
    degistirme_tarihi  timestamptz not null default now()
);

-- ---- gönderim zamanı kuralları (grid) -------------------------------------------------------------------------------
create table if not exists public.radyoloji_rapor_gonderim_kural (
    id           integer  primary key generated by default as identity,
    sube_id      integer  not null references public.sube(id),
    kapsam       smallint not null,                        -- 0 tümü · 1 kategori · 2 kod (tetkik)
    kategori_id  integer  references public.kategori(id),
    hizmet_id    integer  references public.hizmet(id),
    zaman_tur    smallint not null default 1,              -- 0 hemen · 1 N saat sonra · 2 ertesi gün saat
    saat         integer  not null default 2,              -- zaman_tur 1: saat sayısı
    gun_dakika   integer  not null default 900,            -- zaman_tur 2: günün dakikası (900 = 15:00)
    aktif        smallint not null default 1,
    ekleyen      integer  not null default 0,
    ekleme_tarihi timestamptz not null default now(),
    constraint ck_rrg_kural_kapsam check (
        (kapsam = 0 and kategori_id is null and hizmet_id is null) or
        (kapsam = 1 and kategori_id is not null and hizmet_id is null) or
        (kapsam = 2 and hizmet_id is not null and kategori_id is null)),
    constraint ck_rrg_kural_zaman check (zaman_tur in (0, 1, 2) and saat between 0 and 720 and gun_dakika between 0 and 1439)
);
-- Aynı kod / kategori iki kez girilemez; "Tümü" şubede tek satır.
create unique index if not exists ux_rrg_kural_tumu     on public.radyoloji_rapor_gonderim_kural (sube_id) where kapsam = 0;
create unique index if not exists ux_rrg_kural_kategori on public.radyoloji_rapor_gonderim_kural (sube_id, kategori_id) where kapsam = 1;
create unique index if not exists ux_rrg_kural_hizmet   on public.radyoloji_rapor_gonderim_kural (sube_id, hizmet_id) where kapsam = 2;

-- ---- gönderim / bağlantı --------------------------------------------------------------------------------------------
create table if not exists public.radyoloji_rapor_gonderim (
    id             integer     primary key generated by default as identity,
    rapor_id       integer     not null references public.radyoloji_rapor(id) on delete cascade,
    istem_id       integer     not null references public.radyoloji_istem(id) on delete cascade,
    sube_id        integer     not null,
    alici_tur      smallint    not null,                   -- 1 hasta · 2 gönderen dış doktor
    taraf_id       integer,
    kod            varchar(24) not null,                   -- bağlantı kodu (tahmin edilemez)
    kanal          smallint    not null default 0,         -- 0 yalnız bağlantı · 1 SMS · 2 e-posta · 3 ikisi
    sms_alici      varchar(30)  not null default '',
    eposta_alici   varchar(200) not null default '',
    planlanan      timestamptz,                            -- null: otomatik gönderim yok (elle)
    kural          varchar(120) not null default '',       -- uygulanan kuralın açıklaması (liste gösterir)
    durum          smallint    not null default 0,         -- 0 hazır (elle) · 1 planlandı · 2 borç bekliyor ·
                                                           -- 3 gönderildi · 4 gönderilemedi · 9 iptal
    gonderim       timestamptz,
    hata           varchar(200) not null default '',
    borca_ragmen   smallint    not null default 0,         -- yetkili "Borca Rağmen Gönder" dedi: bağlantı da açılır
    ilk_acilma     timestamptz,
    son_acilma     timestamptz,
    acilma_sayisi  integer     not null default 0,
    son_gecerli    timestamptz not null,
    ekleyen        integer     not null default 0,
    ekleme_tarihi  timestamptz not null default now(),
    degistiren     integer     not null default 0,
    degistirme_tarihi timestamptz not null default now(),
    constraint ux_rrg_kod unique (kod),
    constraint ux_rrg_rapor_alici unique (rapor_id, alici_tur)
);
create index if not exists ix_rrg_bekleyen on public.radyoloji_rapor_gonderim (planlanan) where durum in (1, 2);
create index if not exists ix_rrg_istem on public.radyoloji_rapor_gonderim (istem_id);

