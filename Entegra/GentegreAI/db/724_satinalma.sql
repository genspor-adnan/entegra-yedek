-- AĞIRLIK KİLİDİ: davet gönderildikten sonra ağırlık değişmez.
create or replace function public.fn_satinalma_agirlik_kilit()
returns trigger language plpgsql as $tg$
begin
    if old.agirlik_kilit = 1
       and (new.agirlik_fiyat is distinct from old.agirlik_fiyat
         or new.agirlik_teslim is distinct from old.agirlik_teslim
         or new.agirlik_garanti is distinct from old.agirlik_garanti
         or new.agirlik_performans is distinct from old.agirlik_performans) then
        raise exception 'Teklif daveti gönderildikten sonra değerlendirme ağırlıkları değiştirilemez.'
              using errcode = 'check_violation';
    end if;
    return new;
end;
$tg$;

drop trigger if exists tg_satinalma_agirlik_kilit on public.satinalma_teklif;
create trigger tg_satinalma_agirlik_kilit
  before update on public.satinalma_teklif
  for each row execute function public.fn_satinalma_agirlik_kilit();

-- ================================================= sipariş süreç katmanı ==
-- `belge` (tür 9) 1:1 uzantısı - `belge_basvuru` ile aynı desen. Siparişin
--   kendisi belgedir; buradaki alanlar SÜREÇTİR.
create table if not exists public.belge_satinalma (
  id            integer primary key references public.belge(id) on delete cascade,
  talep_id      bigint references public.satinalma_talep(id),
  teklif_id     bigint references public.satinalma_teklif(id),
  sozlesme_id   integer,
  -- SÖZ VERİLEN teslim: gecikme bundan sayılır, sipariş tarihinden değil.
  soz_teslim    date,
  ilk_teslim    date,
  son_teslim    date,
  -- Gecikme kaydı ELLE AÇILMAZ: tarih geçtiğinde açılır (uygulama/zamanlı iş).
  gecikme_gun   smallint not null default 0,
  gecikme_bildirim timestamptz,
  -- Ceza HESAPLANIR ama otomatik KESİLMEZ: mahsup kararı insanındır.
  ceza_tutar    numeric(18,2) not null default 0,
  ceza_islendi  smallint not null default 0,
  kismi_kabul   smallint not null default 1,
  -- 0 açık · 1 kısmi teslim · 2 tamamlandı · 8 iptal
