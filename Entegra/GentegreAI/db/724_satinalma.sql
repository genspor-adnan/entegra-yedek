-- =====================================================================
--  724_satinalma.sql
--  SATINALMA — talep ve onay zinciri, teklif/değerlendirme, sipariş takibi,
--  üçlü eşleştirme, tedarikçi sözleşme ve performansı, bütçe.
--
--  Mockup'lar: `Ekranlar/Satinalma/*.html`.
--
--  TEMEL KARAR — SİPARİŞ VE FATURA TABLOSU AÇILMADI. Alış siparişi `belge`
--    tür 9, irsaliye 10, fatura 11'dir; satırlar `belge_satir`, tutarlar
--    `fn_belge_diptoplam`. İkinci bir sipariş tablosu açsaydık para iki yerde
--    hesaplanır ve ikisi zamanla ayrışırdı (CLAUDE.md: "para matematiği tek
--    yerde"). Bu dosya siparişin ÜSTÜNE süreç katmanı koyuyor: teslim
--    taahhüdü, gecikme, ceza, sözleşme bağı.
--
--  TEMEL KARAR — TALEP `belge` DEĞİL. Tür 105 (Stoktan Talep) servis → eczane
--    gibi İÇ taleptir, karşılığı transferdir. Satınalma talebi dışarı çıkar,
--    bütçe ve onay zinciri taşır, henüz bir belge değildir. Aynı türe
--    sıkıştırsaydık iki farklı iş akışı tek listede karışırdı.
--
--  TEMEL KARAR — ONAY ZİNCİRİ SATIR SATIR. Talebe "onaylandı" bayrağı koymak
--    yetmezdi: kim, ne zaman, hangi basamakta, hangi gerekçeyle onayladı -
--    denetimde sorulan budur. Basamakları sistem kurar (tutar + bütçe durumu
--    + malzeme türü), kullanıcı "kime göndereyim" diye sormaz.
--
--  TEMEL KARAR — TEDARİKÇİ SKORU HESAPLANIR, GİRİLMEZ. Her gecikme, kalite
--    uygunsuzluğu ve fatura farkı olay olarak yazılır; skor onlardan türer.
--    Elle girilen skor, dönem sonunda kimin hatırladığına bağlı kalırdı.
-- =====================================================================

-- ============================================================= bütçe ==
-- TAAHHÜT DE HARCAMADIR: açık sipariş henüz faturalanmadı ama parası
--   bağlandı. Kalan bütçe onu düşerek gösterilir - yoksa aynı para iki kez
--   harcanır.
create table if not exists public.butce_kalem (
  id            integer generated by default as identity primary key,
  sube_id       integer not null default 0,
  yil           smallint not null,
  kod           varchar(30) not null,
  ad            varchar(150) not null,
  -- Talep bu kaleme hangi ölçüte göre düşer: malzeme grubu ya da elle seçim.
  grup_kodu     varchar(40) not null default '',
  tutar         numeric(18,2) not null default 0,
  -- Aşım davranışı: 0 uyar · 1 ek onay ister · 2 engeller
  asim_davranis smallint not null default 1,
  aktif         smallint not null default 1,
  aciklama      varchar(300) not null default '',
  ekleyen       integer not null default 0,
  ekleme_tarihi timestamptz not null default now(),
  degistiren    integer not null default 0,
  degistirme_tarihi timestamptz
);
create unique index if not exists ux_butce_kalem
  on public.butce_kalem (sube_id, yil, kod);

-- ============================================================= talep ==
create table if not exists public.satinalma_talep (
  id            bigint generated by default as identity primary key,
  sube_id       integer not null default 0,
  talep_no      varchar(30) not null default '',
  tarih         date not null default current_date,
  -- 1 birim talebi · 2 kritik stok (otomatik) · 3 arıza · 4 periyodik
  -- 5 yatırım · 9 diğer
  kaynak        smallint not null default 1,
  -- Otomatik doğan talebin kaynağı izlenir: hangi sarf/iş emri tetikledi.
  kaynak_tur    smallint not null default 0,
  kaynak_id     bigint,
  isteyen_id    integer references public.taraf(id),
  departman_id  integer references public.departman(id),
  butce_kalem_id integer references public.butce_kalem(id),
  -- 1 acil · 2 yüksek · 3 normal
  oncelik       smallint not null default 3,
  gerekce       varchar(600) not null default '',
  -- MİKTAR HESABI KAYDA GEÇER: tüketim + eldeki + açık sipariş. Onaylayan
  --   neye onay verdiğini görmeli - "gözden" gelen miktar denetlenemez.
  hesap_notu    varchar(400) not null default '',
  tahmini_tutar numeric(18,2) not null default 0,
  -- 0 taslak · 1 onayda · 2 onaylandı · 3 reddedildi · 4 teklifte
  -- 5 siparişe dönüştü · 8 iptal
  durum         smallint not null default 0,
  -- Birleştirme: aynı malzemenin açık talepleri tek siparişte toplanır.
  birlestirilen_id bigint references public.satinalma_talep(id),
  red_neden     varchar(300) not null default '',
  ekleyen       integer not null default 0,
  ekleme_tarihi timestamptz not null default now(),
  degistiren    integer not null default 0,
  degistirme_tarihi timestamptz
);
create unique index if not exists ux_satinalma_talep_no
  on public.satinalma_talep (sube_id, talep_no) where talep_no <> '';
create index if not exists ix_satinalma_talep_acik
  on public.satinalma_talep (sube_id, oncelik, tarih) where durum between 0 and 4;

