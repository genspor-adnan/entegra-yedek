create table if not exists public.tedarikci_belge (
  id            bigint generated by default as identity primary key,
  firma_id      integer not null references public.taraf(id) on delete cascade,
  -- 1 sicil gazetesi · 2 imza sirküleri · 3 vergi borcu yoktur
  -- 4 SGK borcu yoktur · 5 ÜTS firma kaydı · 6 kalite belgesi (ISO)
  -- 7 yasaklılık teyidi · 8 banka hesap teyidi · 99 diğer
  tur           smallint not null default 99,
  ad            varchar(200) not null default '',
  tarih         date,
  -- SÜRESİ DOLAN BELGE SİPARİŞİ DURDURUR: borcu yoktur yazısı bir aylıktır.
  gecerlilik    date,
  dokuman_id    integer references public.dokuman(id),
  aciklama      varchar(300) not null default '',
  ekleyen       integer not null default 0,
  ekleme_tarihi timestamptz not null default now()
);
create index if not exists ix_tedarikci_belge on public.tedarikci_belge (firma_id, tur);
create index if not exists ix_tedarikci_belge_suresi
  on public.tedarikci_belge (gecerlilik) where gecerlilik is not null;

-- =========================================================== görünümler ==
-- BÜTÇE: harcanan + TAAHHÜT (açık sipariş). İkisi ayrı gösterilir ama
--   kalan ikisini birden düşer.
create or replace view public.v_butce_durum as
select b.id, b.sube_id, b.yil, b.kod, b.ad, b.tutar,
       coalesce(h.harcanan, 0) as harcanan,
       coalesce(t.taahhut, 0) as taahhut,
       b.tutar - coalesce(h.harcanan, 0) - coalesce(t.taahhut, 0) as kalan,
       case when b.tutar > 0
            then round((coalesce(h.harcanan, 0) + coalesce(t.taahhut, 0))
                       / b.tutar * 100, 1) else 0 end as kullanim_yuzde
  from public.butce_kalem b
  -- HARCANAN: kesinleşmiş alış faturaları (tür 11).
  left join lateral (
      select sum(f.genel_toplam) as harcanan
        from public.belge f
        join public.satinalma_fatura_kontrol k on k.fatura_belge_id = f.id
        join public.belge s on s.id = k.siparis_belge_id
        join public.belge_satinalma bs on bs.id = s.id
        join public.satinalma_talep tl on tl.id = bs.talep_id
       where f.tur = 11 and f.durum <> 0
         and tl.butce_kalem_id = b.id
         and extract(year from f.belge_tarihi) = b.yil) h on true
  -- TAAHHÜT: açık siparişler (tür 9, takip_durum 0/1).
  left join lateral (
      select sum(s.genel_toplam) as taahhut
        from public.belge s
        join public.belge_satinalma bs on bs.id = s.id
        join public.satinalma_talep tl on tl.id = bs.talep_id
       where s.tur = 9 and s.durum <> 0 and bs.takip_durum in (0, 1)
         and tl.butce_kalem_id = b.id
         and extract(year from s.belge_tarihi) = b.yil) t on true
 where b.aktif = 1;

comment on view public.v_butce_durum is
  '724: butce kalemi durumu. TAAHHUT DE HARCAMADIR - acik siparis faturalanmadi '
  'ama parasi baglandi; kalan ikisini birden duser.';

-- TEDARİKÇİ SKORU: olaylardan türer, son 12 ay.
create or replace view public.v_tedarikci_skor as
select t.id as firma_id, t.unvan,
       coalesce(100 + sum(o.skor_etki) filter (
           where o.zaman >= now() - interval '12 months'), 100)::numeric(6,2) as skor,
       count(*) filter (where o.tur = 1 and o.zaman >= now() - interval '12 months') as gecikme,
       count(*) filter (where o.tur = 2 and o.zaman >= now() - interval '12 months') as uygunsuzluk,
       count(*) filter (where o.tur = 3 and o.zaman >= now() - interval '12 months') as fatura_farki,
       -- Belgesi süresi dolmuş firma yeni sipariş açamaz.
       exists (select 1 from public.tedarikci_belge b
                where b.firma_id = t.id and b.gecerlilik is not null
                  and b.gecerlilik < current_date) as belge_suresi_doldu
  from public.taraf t
  left join public.tedarikci_olay o on o.firma_id = t.id
 where t.tedarikci = 1
 group by t.id, t.unvan;

comment on view public.v_tedarikci_skor is
  '724: skor OLAYLARDAN turer (son 12 ay), elle girilmez. 70 alti izleme, '
  '50 alti askiya alma esigi - esikler uygulamada.';

