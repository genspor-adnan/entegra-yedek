-- =============================================================================
--  1222  AKTARIM SKRS EŞLEME MASASI - HİZMET -> SUT
--
--  Kullanıcı (01.11.2026): "eski müşterilerde gelişigüzel işlem (hizmet) listeleri yapıldı.. yeni programla bakanlığın
--  (SKRS) istediği standarda oturtmak istiyorum.. önceki kod da gösterilsin" (mockup Ekranlar/Aktarim/skrs_esleme_masasi.html).
--  Kararlar: ana hizmet kodu SUT · karşılığı olmayan KURUMA ÖZEL · kullanılmayan eski hizmet aktarılmaz · eşlemeyi hizmet
--  kartını değiştirebilen onaylar.
--
--  aktarim_esleme       masanın satırı: eski hizmet + Bakanlık adayları (jsonb, puanlı) + karar (durum / seçilen kod).
--  hizmet_eski_kod      hizmetin eski kodları (birden çok eski kod tek SUT hizmetinde birleşebilir; aramada bulunur).
--  hizmet.standart      0 incelenmedi · 1 SUT (Bakanlık) · 2 kuruma özel.
--  fn_skrs_sade         ad sadeleştirme (Türkçe harf, noktalama, MR -> MRG, ultrason -> USG ...).
--  fn_skrs_hizmet_adaylari  tür / modalite süzgeçli trigram adayları + "dikkat" (terim farkı, girişimsel terim).
--  fn_aktarim_esleme_doldur aktarılmış hizmetlerden masa satırları (kararlara dokunmaz, adayları tazeler).
--  fn_aktarim_esleme_uygula onaylıları uygular: hizmet YERİNDE SUT kod / ada çevrilir, eski kod hizmet_eski_kod'a;
--    aynı SUT'a düşen ikinci eski hizmet PASİF olur ve ana hareketleri asıl hizmete yönlenir (silme yok).
--  İdempotent.
-- =============================================================================

begin;

create extension if not exists pg_trgm;

alter table public.hizmet add column if not exists standart smallint not null default 0;
comment on column public.hizmet.standart is '1222: 0 incelenmedi · 1 SUT (Bakanlık listesi) · 2 kuruma özel.';

create table if not exists public.hizmet_eski_kod (
    id            integer generated by default as identity primary key,
    hizmet_id     integer      not null references public.hizmet(id) on delete cascade,
    eski_kod      varchar(60)  not null,
    eski_ad       varchar(250) not null default '',
    kaynak        varchar(40)  not null default '',
    ekleme_tarihi timestamptz  not null default now(),
    unique (hizmet_id, eski_kod)
);
create index if not exists ix_hizmet_eski_kod_kod on public.hizmet_eski_kod (lower(eski_kod));
comment on table public.hizmet_eski_kod is '1222: hizmetin eski (aktarım öncesi) kodları - listede / aramada görünür.';

create table if not exists public.aktarim_esleme (
    id            integer generated by default as identity primary key,
    liste         varchar(20)  not null,             -- 'hizmet' (sonra: klinik, brans ...)
    kayit_id      integer      not null,             -- liste = hizmet: hizmet.id (aktarılmış eski hizmet)
    eski_kod      varchar(60)  not null default '',
    eski_ad       varchar(250) not null default '',
    tur           varchar(10)  not null default '',  -- RAD / LAB / DIGER
    modalite      smallint,
    kullanim      integer      not null default 0,
    adaylar       jsonb        not null default '[]'::jsonb,   -- [{kod, ad, puan, dikkat}]
    durum         smallint     not null default 0,   -- 0 bekliyor · 1 onaylı · 2 kuruma özel · 3 aday yok
    secilen_kod   varchar(30),
    notlar        varchar(300) not null default '',
    onaylayan     integer,
    onay_tarihi   timestamptz,
    uygulandi     smallint     not null default 0,
    uygulama_tarihi timestamptz,
    hedef_hizmet_id integer,                         -- uygulamada bağlandığı (birleşmede asıl) hizmet
    ekleme_tarihi timestamptz  not null default now(),
    unique (liste, kayit_id)
);
comment on table public.aktarim_esleme is '1222: SKRS eşleme masası satırı (eski kayıt -> Bakanlık kodu kararı).';

-- --------------------------------------------------------------- sadeleştirme ----
create or replace function public.fn_skrs_sade(p text) returns text language sql immutable parallel safe as $$
  select btrim(regexp_replace(regexp_replace(regexp_replace(regexp_replace(regexp_replace(regexp_replace(
           translate(upper(coalesce(p, '')), 'ÇĞİÖŞÜÂÎÛ', 'CGIOSUAIU'),
           '[^A-Z0-9 ]', ' ', 'g'),
           '\m(MR|MRI|MANYETIK REZONANS)\M', 'MRG', 'g'),
           '\m(US|ULTRASON|ULTRASONOGRAFI|ULTRASONOGRAFIK)\M', 'USG', 'g'),
           '\m(TOMOGRAFI|BILGISAYARLI TOMOGRAFI)\M', 'BT', 'g'),
           '\m(SERUM|PLAZMA|KARSILASTIRMALI|TEK TARAF|TEK|IKI TARAFLI)\M', ' ', 'g'),
           '\s+', ' ', 'g'))
$$;

-- Aday araması 17 bin SUT kaydında: sadeleştirilmiş ada trigram indeksi.
create index if not exists ix_skrs_sut_sade_trgm on public.skrs_sut using gin (public.fn_skrs_sade(ad) gin_trgm_ops);

-- ------------------------------------------------------------------ adaylar ----
-- Tür süzgeci: RAD -> SUT "Tetkik ve Radyoloji Bilgileri", LAB -> "Tahlil İşlemleri", diğer -> malzeme hariç her şey.
-- Modalite: eski hizmet BT/MRG/USG ise aynı önekli SUT kalemi +0.15, başka modalite önekli -0.30.
-- Dikkat: SUT adında eskide olmayan girişimsel terim (ARTROGRAFI, ANJIO, BIYOPSI, KILAVUZ, VENOGRAFI) ya da eskinin
--   ilk kelimesinin SUT'ta ancak parçası olarak geçmesi (PROTROMBIN ~ TROMBIN).
create or replace function public.fn_skrs_hizmet_adaylari(p_ad text, p_tur text, p_modalite smallint, p_n integer default 3)
returns table (kod varchar, ad varchar, puan numeric, dikkat text) language sql stable as $$
  with e as (select public.fn_skrs_sade(p_ad) as s,
                    split_part(public.fn_skrs_sade(p_ad), ' ', 1) as ilk,
                    case p_modalite when 1 then 'BT' when 2 then 'MRG' when 3 then 'USG' else '' end as onek),
  aday as (
    select s.kod, s.ad, public.fn_skrs_sade(s.ad) as ss
      from public.skrs_sut s, e
     where coalesce(s.aktif, 1) = 1
       and case upper(coalesce(p_tur, ''))
             when 'RAD' then s.tip = 'Tetkik ve Radyoloji Bilgileri'
             when 'LAB' then s.tip = 'Tahlil İşlemleri'
             else coalesce(s.tip, '') <> 'Malzemeler' end
       and public.fn_skrs_sade(s.ad) % e.s),
  puanli as (
    select a.kod, a.ad,
           least(1, greatest(0, similarity(a.ss, e.s)
             + case when e.onek <> '' and a.ss like e.onek || ' %' then 0.15
                    when e.onek <> '' and a.ss ~ '^(BT|MRG|USG) ' then -0.30 else 0 end))::numeric(4,2) as puan,
           concat_ws(' · ',
             case when a.ss ~ '\m(ARTROGRAFI|ANJIOGRAFI|ANJIO|BIYOPSI|KILAVUZ\w*|VENOGRAFI)\M'
                   and e.s !~ '\m(ARTROGRAFI|ANJIOGRAFI|ANJIO|BIYOPSI|KILAVUZ\w*|VENOGRAFI)\M'
                  then 'girişimsel / farklı yöntem terimi' end,
             case when length(e.ilk) >= 4 and position(' ' || e.ilk || ' ' in ' ' || a.ss || ' ') = 0
                   and exists (select 1 from regexp_split_to_table(a.ss, ' ') w
                                where length(w) >= 4 and w <> e.ilk and position(w in e.ilk) > 0)
                  then 'terim farkı: ' || e.ilk end) as dikkat
      from aday a, e)
  select kod, ad, puan, nullif(dikkat, '') from puanli order by puan desc, kod limit p_n
$$;

-- -------------------------------------------------------------------- doldur ----
-- Aktarılmış (aktarim_kaynak 2) hizmetlerden satır; karar verilmiş (durum <> 0) ya da uygulanmış satıra dokunulmaz,
--   bekleyenin adayları / kullanımı tazelenir. Dönen: masadaki satır sayısı.
create or replace function public.fn_aktarim_esleme_doldur() returns integer language plpgsql as $$
declare v_n integer;
begin
  insert into public.aktarim_esleme (liste, kayit_id, eski_kod, eski_ad, tur, modalite, kullanim, adaylar, durum)
  select 'hizmet', h.id, h.kod, h.ad,
         case when h.radyoloji = 1 or coalesce(h.modalite, 0) > 0 then 'RAD'
              when h.aciklama like 'Eski HBYS: LAB%' then 'LAB' else 'DIGER' end,
         nullif(h.modalite, 0),
         (select count(*) from public.belge_satir s where s.hizmet_id = h.id), '[]'::jsonb, 0
    from public.hizmet h
   where h.aktarim_kaynak = 2 and h.standart = 0
  on conflict (liste, kayit_id) do update set kullanim = excluded.kullanim
   where public.aktarim_esleme.uygulandi = 0;

  update public.aktarim_esleme e
     set adaylar = coalesce((select jsonb_agg(jsonb_build_object('kod', a.kod, 'ad', a.ad, 'puan', a.puan, 'dikkat', a.dikkat)
                                              order by a.puan desc)
                               from public.fn_skrs_hizmet_adaylari(e.eski_ad, e.tur, e.modalite, 3) a), '[]'::jsonb)
   where e.liste = 'hizmet' and e.uygulandi = 0 and e.durum in (0, 3);
  update public.aktarim_esleme set durum = case when jsonb_array_length(adaylar) = 0 then 3 else 0 end
   where liste = 'hizmet' and uygulandi = 0 and durum in (0, 3);
  select count(*) into v_n from public.aktarim_esleme where liste = 'hizmet';
  return v_n;
end $$;

-- -------------------------------------------------------------------- uygula ----
-- Onaylı (1) ve kuruma özel (2), uygulanmamış satırlar. Dönen: jsonb {sut, birlesen, ozel}.
create or replace function public.fn_aktarim_esleme_uygula(p_kullanici integer) returns jsonb language plpgsql as $$
declare
  r record; v_ana integer; v_sut int := 0; v_bir int := 0; v_ozel int := 0; v_ad varchar;
begin
  for r in select e.*, h.kod as h_kod, h.ad as h_ad from public.aktarim_esleme e join public.hizmet h on h.id = e.kayit_id
            where e.liste = 'hizmet' and e.uygulandi = 0 and e.durum in (1, 2) order by e.kullanim desc, e.id
  loop
    if r.durum = 2 then
      update public.hizmet set standart = 2, degistiren = p_kullanici, degistirme_tarihi = now() where id = r.kayit_id;
      insert into public.hizmet_eski_kod (hizmet_id, eski_kod, eski_ad, kaynak)
      values (r.kayit_id, r.eski_kod, r.eski_ad, 'Eski HBYS') on conflict do nothing;
      v_ozel := v_ozel + 1; v_ana := r.kayit_id;
    else
      select ad into v_ad from public.skrs_sut where kod = r.secilen_kod;
      if v_ad is null then raise exception 'SUT kodu bulunamadı: %', r.secilen_kod; end if;
      select h.id into v_ana from public.hizmet h
       where h.standart = 1 and h.sut_kodu = r.secilen_kod and h.id <> r.kayit_id and coalesce(h.durum, 1) = 1
       order by h.id limit 1;
      if v_ana is null then
        -- Hizmet YERİNDE SUT'a çevrilir.
        update public.hizmet set kod = r.secilen_kod, ad = left(v_ad, 200), sut_kodu = r.secilen_kod, standart = 1,
               degistiren = p_kullanici, degistirme_tarihi = now() where id = r.kayit_id;
        v_ana := r.kayit_id; v_sut := v_sut + 1;
      else
        -- Aynı SUT hizmeti var: bu eski hizmet ona BİRLEŞİR - ana hareketler yönlenir, kendisi pasif kalır.
        update public.belge_satir set hizmet_id = v_ana where hizmet_id = r.kayit_id;
        update public.radyoloji_istem set hizmet_id = v_ana where hizmet_id = r.kayit_id;
        update public.radyoloji_sablon set hizmet_id = v_ana where hizmet_id = r.kayit_id;
        update public.randevu set hizmet_id = v_ana where hizmet_id = r.kayit_id;
        delete from public.fiyat_listesi_satir f where f.hizmet_id = r.kayit_id
           and exists (select 1 from public.fiyat_listesi_satir g where g.liste_id = f.liste_id and g.hizmet_id = v_ana);
        update public.fiyat_listesi_satir set hizmet_id = v_ana where hizmet_id = r.kayit_id;
        delete from public.radyoloji_sablon_hizmet x where x.hizmet_id = r.kayit_id
           and exists (select 1 from public.radyoloji_sablon_hizmet y where y.sablon_id = x.sablon_id and y.hizmet_id = v_ana);
        update public.radyoloji_sablon_hizmet set hizmet_id = v_ana where hizmet_id = r.kayit_id;
        update public.hizmet set durum = 0, standart = 1, sut_kodu = r.secilen_kod,
               aciklama = left('Birleşti -> ' || r.secilen_kod || ' (#' || v_ana || '). ' || coalesce(aciklama, ''), 500),
               degistiren = p_kullanici, degistirme_tarihi = now() where id = r.kayit_id;
        v_bir := v_bir + 1;
      end if;
      insert into public.hizmet_eski_kod (hizmet_id, eski_kod, eski_ad, kaynak)
      values (v_ana, r.eski_kod, r.eski_ad, 'Eski HBYS') on conflict do nothing;
    end if;
    update public.aktarim_esleme set uygulandi = 1, uygulama_tarihi = now(), hedef_hizmet_id = v_ana where id = r.id;
  end loop;
  return jsonb_build_object('sut', v_sut, 'birlesen', v_bir, 'ozel', v_ozel);
end $$;

commit;
