-- ============================================================================
--  Gentegre AI — SATIS FIYAT LISTESI
--  201_satis_listesi.sql
--
--  Bugune kadar fiyat yalniz `stok_fiyat` / `hizmet_fiyat` tablolarindaydi:
--  kalemin uzerinde duran, adi bile olmayan bir kod (`fiyat_adi`) ile ayrilan
--  duz fiyatlar. "Bayi listesi perakendenin %20 altinda", "kampanya listesi
--  1 Ocak - 28 Subat arasi gecerli" gibi bir sey kurulamiyordu.
--
--  Bu goc LISTEYI kendi basina bir varlik yapiyor:
--
--    satis_listesi        - listenin KURALI (taban liste, carpan, yuvarlama,
--                           KDV dahil/haric, gecerlilik araligi)
--    satis_listesi_satir  - listedeki HER kalem icin bir satir (stok ya da
--                           hizmet), fiyati ve o satira ozgu kural ezmesi
--
--  TABAN LISTE ZINCIRI: bir liste baska bir listeyi taban alabilir ("bayi =
--  perakende x 0.80"). Zincir kendine donerse fiyat hesabi sonsuz doner; buna
--  karsi tetikle DONGU KORUMASI var (asagida).
--
--  SATIR MATERYALIZE: kullanici karari - liste uretildiginde her kalem icin
--  satir YAZILIR (hesaplanip birakilmaz). Fiyat okumasi tek sorgu olur; bedeli,
--  taban liste degisince listenin BAYATLAMASIDIR - yeniden uretmek gerekir
--  (202'deki fn_satis_listesi_uret). `yazim = 1 (manuel)` satirlar yeniden
--  uretimde KORUNUR; elle girilen fiyat hesapla ezilmez.
-- ============================================================================
\set ON_ERROR_STOP on

-- ---------------------------------------------------------------------------
--  Kod listeleri (kart combolari)
-- ---------------------------------------------------------------------------
insert into public.kod_liste (kod, ad)
select v.kod, v.ad
  from (values ('satis_listesi.grup',      'Fiyat Listesi Grubu'),
               ('satis_listesi.yuvarlama', 'Yuvarlama'),
               ('satis_listesi.yazim',     'Fiyat Yazımı')) as v(kod, ad)
 where not exists (select 1 from public.kod_liste l where l.kod = v.kod);

insert into public.kod_deger (liste_id, deger, ad, sira, aktif)
select l.id, v.deger, v.ad, v.sira, 1
  from (values
        -- Grup ONERIDIR, kurallari yoktur: kullanici Yonetim > Kod Listeleri'nden
        --   kendi gruplarini ekler. Bunlar yalnizca bos ekranla baslamamak icin.
        ('satis_listesi.grup', 1, 'Perakende', 10),
        ('satis_listesi.grup', 2, 'Bayi',      20),
        ('satis_listesi.grup', 3, 'Toptan',    30),
        ('satis_listesi.grup', 4, 'Kampanya',  40),

        ('satis_listesi.yuvarlama', 0, 'Yok',              10),
        ('satis_listesi.yuvarlama', 1, 'Yukarı Yuvarla',   20),
        ('satis_listesi.yuvarlama', 2, 'Aşağı Yuvarla',    30),
        ('satis_listesi.yuvarlama', 3, 'En Yakın Değere',  40),

        ('satis_listesi.yazim', 1, 'Manuel', 10),
        ('satis_listesi.yazim', 2, 'Hesap',  20)
       ) as v(liste, deger, ad, sira)
  join public.kod_liste l on l.kod = v.liste
 where not exists (select 1 from public.kod_deger d
                    where d.liste_id = l.id and d.deger = v.deger);

-- ---------------------------------------------------------------------------
--  BASLIK
-- ---------------------------------------------------------------------------
create table if not exists public.satis_listesi (
    id                integer generated by default as identity primary key,
    ad                varchar(80)   not null,
    grup              smallint      not null default 0,      -- kod: satis_listesi.grup

    -- TABAN LISTE: bu listenin fiyatlari hangi listeden turetilir. Bos ise
    --   liste KOKTUR ve fiyatlari kalemin kendi fiyatindan (stok_fiyat /
    --   hizmet_fiyat) baslar.
    taban_liste_id    integer,
    carpan            numeric(18,6) not null default 1,
    yuvarlama         smallint      not null default 0,      -- kod: satis_listesi.yuvarlama
    -- "En Yakin Degere" bir ADIM ister: 0,01 kurusa, 1 liraya, 5 liraya...
    --   Adim olmadan "en yakin" tanimsizdir. Yukari/asagi yuvarlama da bu
    --   adima gore yapilir (adim 1 -> tam liraya yukari).
    yuvarlama_birim   numeric(18,4) not null default 1,

    kdv_dahil         smallint      not null default 0,      -- 1 dahil, 0 haric
    durum             smallint      not null default 1,      -- 1 aktif, 0 pasif
    baslangic         date,
    bitis             date,
    aciklama          varchar(200)  not null default '',
    sube_id           integer,

    ekleyen           integer       not null default 0,
    ekleme_tarihi     timestamp     not null default now()::timestamp,
    degistiren        integer       not null default 0,
    degistirme_tarihi timestamp,

    constraint fk_satis_listesi_taban foreign key (taban_liste_id)
        references public.satis_listesi (id),
    constraint fk_satis_listesi_sube foreign key (sube_id)
        references public.sube (id),
    -- Liste KENDISINI taban alamaz. Daha uzun donguler (A->B->A) tetikle
    --   yakalanir; bu check en sik hatayi kaydin kendisinde engeller.
    constraint ck_satis_listesi_taban_kendisi check (taban_liste_id is null or taban_liste_id <> id),
    constraint ck_satis_listesi_carpan check (carpan > 0),
    constraint ck_satis_listesi_yuv_birim check (yuvarlama_birim > 0),
    constraint ck_satis_listesi_tarih check (bitis is null or baslangic is null or bitis >= baslangic)
);

comment on table public.satis_listesi is
  'Satis fiyat listesi basligi (201): taban liste + carpan + yuvarlama kurali, KDV dahil/haric, gecerlilik araligi.';
comment on column public.satis_listesi.taban_liste_id is
  'Fiyatlarin turetildigi liste; bos ise KOK liste (kalemin kendi fiyatindan baslar).';
comment on column public.satis_listesi.yuvarlama_birim is
  'Yuvarlama adimi (0.01 kurus / 1 lira / 5 lira). "En Yakin Degere" bu adima gore.';

create unique index if not exists ux_satis_listesi_ad on public.satis_listesi (lower(ad));
create index if not exists ix_satis_listesi_grup  on public.satis_listesi (grup, durum);
create index if not exists ix_satis_listesi_taban on public.satis_listesi (taban_liste_id)
    where taban_liste_id is not null;

-- ---------------------------------------------------------------------------
--  SATIR
--
--  Kod / Ad / Kategori EKRANDA gorunur ama BURADA TUTULMAZ: stok ve hizmet
--  kartinin kendi alanlaridir, kopyalanirsa kart duzeltilince liste yalan
--  soyler. Liste ekrani bunlari join ile getirir (v_satis_listesi_satir).
-- ---------------------------------------------------------------------------
create table if not exists public.satis_listesi_satir (
    id                integer generated by default as identity primary key,
    liste_id          integer       not null,

    -- Kalem: stok VEYA hizmet (tam biri). belge_satir'daki ayni ikili desen.
    stok_id           integer,
    hizmet_id         integer,

    fiyat             numeric(18,4) not null default 0,
    doviz_cinsi       varchar(5)    not null default 'TL',
    kdv_dahil         smallint      not null default 0,   -- basligin varsayilani, satirda ezilebilir
    birim             smallint      not null default 0,   -- kod: stok.ana_birim
    durum             smallint      not null default 1,   -- 1 aktif, 0 pasif

    -- SATIR SEVIYESI KURAL EZMESI. Bos (null) olan alan icin BASLIGIN degeri
    --   gecerlidir - "listenin kurali, gerekirse kalem bazinda degistirilir".
    yazim             smallint      not null default 2,   -- 1 manuel, 2 hesap
    taban_liste_id    integer,
    carpan            numeric(18,6),
    yuvarlama         smallint,
    yuvarlama_birim   numeric(18,4),

    -- Hesapla uretilen satirda izlenebilirlik: fiyat hangi degerden turetildi.
    taban_fiyat       numeric(18,4) not null default 0,
    uretim_tarihi     timestamp,

    ekleyen           integer       not null default 0,
    ekleme_tarihi     timestamp     not null default now()::timestamp,
    degistiren        integer       not null default 0,
    degistirme_tarihi timestamp,

    constraint fk_sls_liste  foreign key (liste_id) references public.satis_listesi (id) on delete cascade,
    constraint fk_sls_stok   foreign key (stok_id)   references public.stok (id)   on delete cascade,
    constraint fk_sls_hizmet foreign key (hizmet_id) references public.hizmet (id) on delete cascade,
    constraint fk_sls_taban  foreign key (taban_liste_id) references public.satis_listesi (id),
    -- Kalem TAM BIRI olmali: ikisi de dolu satir hangi urunun fiyati belirsiz
    --   birakir, ikisi de bos satir anlamsizdir.
    constraint ck_sls_kalem check ((stok_id is not null) <> (hizmet_id is not null)),
    constraint ck_sls_carpan check (carpan is null or carpan > 0),
    constraint ck_sls_yuv_birim check (yuvarlama_birim is null or yuvarlama_birim > 0)
);

comment on table public.satis_listesi_satir is
  'Fiyat listesi satiri (201): kalem basina fiyat. Kod/Ad/Kategori TUTULMAZ - stok/hizmet kartindan gelir.';
comment on column public.satis_listesi_satir.yazim is
  '1 Manuel (elle girildi, yeniden uretimde KORUNUR) · 2 Hesap (taban x carpan, yeniden uretimde ezilir).';
comment on column public.satis_listesi_satir.taban_fiyat is
  'Hesapla uretilen fiyatin turetildigi taban deger - "bu fiyat nereden cikti" sorusunun cevabi.';

-- Ayni listede ayni kalem ayni birim+dovizden bir kez. (Birim ve doviz
--   ayriminin korunmasi stok_fiyat ile ayni ilke.)
create unique index if not exists ux_sls_stok
    on public.satis_listesi_satir (liste_id, stok_id, birim, doviz_cinsi)
    where stok_id is not null;
create unique index if not exists ux_sls_hizmet
    on public.satis_listesi_satir (liste_id, hizmet_id, doviz_cinsi)
    where hizmet_id is not null;
create index if not exists ix_sls_liste  on public.satis_listesi_satir (liste_id, durum);
create index if not exists ix_sls_stok   on public.satis_listesi_satir (stok_id)   where stok_id is not null;
create index if not exists ix_sls_hizmet on public.satis_listesi_satir (hizmet_id) where hizmet_id is not null;

-- ---------------------------------------------------------------------------
--  DONGU KORUMASI
--
--  A tabani B, B tabani A olursa fiyat hesabi sonsuz doner. `check` yalniz
--  "kendisi" halini yakalayabilir (satir icinde baska satira bakamaz), bu
--  yuzden zincir tetikte yurunur.
-- ---------------------------------------------------------------------------
create or replace function public.fn_satis_listesi_dongu_kontrol()
returns trigger language plpgsql as $$
declare
    v_id     integer := new.taban_liste_id;
    v_adim   integer := 0;
begin
    while v_id is not null loop
        if v_id = new.id then
            raise exception 'Taban liste zinciri kendine donuyor: bu liste dolayli olarak kendini taban aliyor.'
                using errcode = 'GK422';
        end if;
        v_adim := v_adim + 1;
        if v_adim > 50 then
            raise exception 'Taban liste zinciri 50 adimi asti - zincirde dongu var.'
                using errcode = 'GK422';
        end if;
        select s.taban_liste_id into v_id from public.satis_listesi s where s.id = v_id;
    end loop;
    return new;
end $$;

drop trigger if exists trg_satis_listesi_dongu on public.satis_listesi;
create trigger trg_satis_listesi_dongu
    before insert or update of taban_liste_id on public.satis_listesi
    for each row when (new.taban_liste_id is not null)
    execute function public.fn_satis_listesi_dongu_kontrol();

-- Satirdaki taban ezmesi de ayni riski tasir: satir A listesindeyken taban
--   olarak A'yi gosterirse kendi kendini besler.
alter table public.satis_listesi_satir
    drop constraint if exists ck_sls_taban_kendisi;
alter table public.satis_listesi_satir
    add constraint ck_sls_taban_kendisi check (taban_liste_id is null or taban_liste_id <> liste_id);

-- ---------------------------------------------------------------------------
--  Kayit izi tetikleri (standart)
-- ---------------------------------------------------------------------------
drop trigger if exists trg_satis_listesi_degistirme on public.satis_listesi;
create trigger trg_satis_listesi_degistirme before update on public.satis_listesi
    for each row execute function public.fn_degistirme_tarihi();

drop trigger if exists trg_sls_degistirme on public.satis_listesi_satir;
create trigger trg_sls_degistirme before update on public.satis_listesi_satir
    for each row execute function public.fn_degistirme_tarihi();

-- ---------------------------------------------------------------------------
--  EKRAN GORUNUMU: kalemin kod/ad/kategori/birim bilgisi karttan gelir.
-- ---------------------------------------------------------------------------
create or replace view public.v_satis_listesi_satir as
select r.id,
       r.liste_id,
       l.ad                                        as liste_adi,
       case when r.stok_id is not null then 1 else 2 end as kalem_turu,   -- 1 stok, 2 hizmet
       coalesce(s.kod, h.kod, '')                  as kod,
       coalesce(s.ad,  h.ad,  '')                  as ad,
       coalesce(k.ad, '')                          as kategori,
       r.stok_id, r.hizmet_id,
       r.fiyat, r.doviz_cinsi, r.kdv_dahil, r.birim, r.durum,
       r.yazim, r.taban_liste_id,
       coalesce(tl.ad, tb.ad, '')                  as taban_liste_adi,
       -- Satirda ezme yoksa BASLIGIN kurali gosterilir: ekranda "bu satira ne
       --   uygulaniyor" gorunsun, kullanici basliga bakmak zorunda kalmasin.
       coalesce(r.carpan,          l.carpan)       as carpan,
       coalesce(r.yuvarlama,       l.yuvarlama)    as yuvarlama,
       coalesce(r.yuvarlama_birim, l.yuvarlama_birim) as yuvarlama_birim,
       r.taban_fiyat, r.uretim_tarihi,
       l.sube_id
  from public.satis_listesi_satir r
  join public.satis_listesi l  on l.id  = r.liste_id
  left join public.stok      s on s.id  = r.stok_id
  left join public.hizmet    h on h.id  = r.hizmet_id
  left join public.kategori  k on k.id  = s.kategori
  left join public.satis_listesi tl on tl.id = r.taban_liste_id
  left join public.satis_listesi tb on tb.id = l.taban_liste_id;

comment on view public.v_satis_listesi_satir is
  'Fiyat listesi satiri + kalem kimligi (kod/ad/kategori) ve yururlukteki kural (satir ezmesi yoksa baslik).';

-- Lookup: taban liste secimi ve kart combolari.
create or replace view public.v_satis_listesi_lookup as
    select s.id, s.ad::text as ad, s.durum as aktif
      from public.satis_listesi s;

do $$
declare v_l integer; v_d integer;
begin
    select count(*) into v_l from public.kod_liste  where kod like 'satis_listesi.%';
    select count(*) into v_d from public.kod_deger d join public.kod_liste l on l.id = d.liste_id
                              where l.kod like 'satis_listesi.%';
    raise notice '201 tamam: satis_listesi + satis_listesi_satir kuruldu; % kod listesi / % deger.', v_l, v_d;
end $$;
