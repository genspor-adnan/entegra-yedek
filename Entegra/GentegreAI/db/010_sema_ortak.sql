-- ----------------------------------------------------- referans / kod listesi ----
-- Eski GENINI tablosu UCE ayrildi. Olculdu: 4.763 satir, 787 farkli BOLUM;
--   bunlarin 538'i TEK satirlik (= ayar/opsiyon), 249'u COK satirlik (= kod listesi).
--   Tek tabloda tutmanin bedeli: -24121 gibi sihirli sayilar koda gomuluyor,
--   kod listelerine FK verilemiyor, "ayar mi liste mi" ancak satir sayisindan anlasiliyor.
--
-- DIKKAT: kod_deger.deger eski GENINI.DEGER degeriyle KORUNUR. Boylece
--   stok.kategori, taraf.grup, belge.senaryo gibi kolonlar hic donusturulmeden
--   calisir ve istenirse (liste_id, deger) uzerinden FK verilebilir.
create table if not exists public.referans (
    anahtar              varchar(80)  primary key,
    deger                varchar(400) not null default '',
    tip                  varchar(10)  not null default 'metin',   -- metin|sayi|bool|tarih
    kapsam               varchar(10)  not null default 'firma',   -- firma|sube|kullanici
    aciklama             varchar(200) not null default '',
    eski_bolum           integer,                                  -- goc izi (GENINI.BOLUM)
    dil                  smallint     not null default 0,
    guncelleme           timestamp    not null default now()::timestamp
);

create index if not exists ix_referans_eski_bolum on public.referans (eski_bolum) where eski_bolum is not null;

comment on table  public.referans        is 'Uygulama ayarlari/referans degerleri (eski GENINI tek satirlik BOLUM''lari).';
comment on column public.referans.anahtar    is 'Anlamli ad: "efatura.ubl_zip". Gocte otomatik "ops_24121" uretildi, kullanildikca elle duzeltilecek.';
comment on column public.referans.eski_bolum is 'GOC IZI: eski GENINI.BOLUM. Delphi sabitleriyle (Ops_*) eslestirme icin.';

create table if not exists public.kod_liste (
    id                   integer generated by default as identity primary key,
    kod                  varchar(60)  not null unique,   -- 'stok.kategori', 'stok.marka'
    ad                   varchar(100) not null,
    eski_bolum           integer unique                   -- goc izi
);

create table if not exists public.kod_deger (
    liste_id             integer      not null,
    deger                integer      not null,           -- eski GENINI.DEGER (KORUNUR)
    dil                  smallint     not null default 0,
    ad                   varchar(200) not null default '',-- eski GENINI.ANAHTAR
    sira                 smallint     not null default 0,
    aktif                smallint     not null default 1,
    constraint pk_kod_deger primary key (liste_id, deger, dil),
    constraint fk_kod_deger_liste foreign key (liste_id)
        references public.kod_liste (id) on delete cascade
);

create index if not exists ix_kod_deger_liste on public.kod_deger (liste_id, sira);

comment on table  public.kod_liste       is 'Kod listeleri (eski GENINI cok satirlik BOLUM''lari): stok kategorisi, marka, birim, belge durumu ...';
comment on column public.kod_liste.kod   is 'Anlamli ad: "stok.kategori". Gocte otomatik "liste_11110" uretildi, kullanildikca elle duzeltilecek.';
comment on column public.kod_deger.deger is 'Eski GENINI.DEGER - stok.kategori gibi kolonlar bu degeri tasir, donusturulmedi.';

-- -------------------------------------------------------- belge_no_sayac ----
-- Belge numarasi TRANSACTION ICINDE ve BOSLUKSUZ uretilir (e-Belge zorunlulugu).
--   Uretim: select ... for update ile satir kilitlenir, son_no artirilir.
--   Taslak kayit numara TUKETMEZ (numara yalnizca kesinlestirmede alinir).
create table if not exists public.belge_no_sayac (
    anahtar              varchar(200) primary key,   -- 'belge.belge_no|T14|S-1|K1401'
    tablo_adi            varchar(60)  not null default '',
    alan_adi             varchar(60)  not null default '',
    kapsam               varchar(80)  not null default '',   -- tur/sube/kocan/yil ayrimi
    son_no               bigint       not null default 0,
    guncelleme           timestamp    not null default now()::timestamp
);

comment on table public.belge_no_sayac is
  'Belge numarasi sayaci (eski SAYAC). Numara transaction icinde, satir kilidi altinda, BOSLUKSUZ uretilir; taslak numara tuketmez.';
