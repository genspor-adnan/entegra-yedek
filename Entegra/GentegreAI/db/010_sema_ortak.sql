-- ------------------------------------------------------------------ depo ----
create table if not exists public.depo (
    id                   integer generated by default as identity primary key,
    ad                   varchar(50)  not null,
    durum                smallint     not null default 0,   -- 0 aktif, 1 pasif
    varsayilan           smallint     not null default 0,
    maliyeti_etkilesin   smallint     not null default 1,
    son_sayim_tarihi     timestamp,
    sube_id              smallint     not null default 0,
    ekleyen              integer      not null default 0,
    ekleme_tarihi        timestamp    not null default now()::timestamp,
    degistiren           integer      not null default 0,
    degistirme_tarihi    timestamp
);

create unique index if not exists ux_depo_varsayilan
    on public.depo (varsayilan) where varsayilan = 1;

comment on table public.depo is 'Depolar (eski DEPOLAR). Stok durumu ve belge giris/cikis deposu bu tabloya baglanir.';

-- ------------------------------------------------------------- doviz_kur ----
-- Gunluk kur tablosu. Belge kaydinda kur DEGERI belgeye kopyalanir; bu tablo
-- yalnizca oneri/varsayilan kaynagidir (gecmis belge kur degisiminden etkilenmez).
create table if not exists public.doviz_kur (
    id                   integer generated by default as identity primary key,
    doviz_cinsi          varchar(5)   not null,
    tarih                date         not null,
    alis                 numeric(18,6) not null default 0,
    satis                numeric(18,6) not null default 0,
    efektif_alis         numeric(18,6) not null default 0,
    efektif_satis        numeric(18,6) not null default 0,
    ekleyen              integer      not null default 0,
    ekleme_tarihi        timestamp    not null default now()::timestamp,
    constraint ux_doviz_kur unique (doviz_cinsi, tarih)
);

create index if not exists ix_doviz_kur_tarih on public.doviz_kur (tarih desc);

comment on table public.doviz_kur is 'Gunluk doviz kurlari (eski DOVIZ). Belge kaydinda kur degeri belgeye kopyalanir.';

-- -------------------------------------------------------- hizmet / masraf ----
-- Eski MASRAFGELIR tablosu IKIYE bolundu (karar 18.08.2026):
--     hizmet -> satis belgesinde satilan kalemler (nakliye, montaj, danismanlik)
--     masraf -> gider kalemleri (kira, elektrik, komisyon)
--
-- DIKKAT (gocte ele alinmasi gereken): BILIM verisinde 326 kalemin 35'i HEM
--   alis HEM satis belgesinde kullanilmis. Bunlar iki tabloya da KOPYALANIR;
--   goc betigi "goc_kalem_eslesme" tablosunda eski MASRAFGELIR.ID -> yeni
--   (hizmet_id | masraf_id) esleseme kaydini tutar, belge satirlari bu esleme
--   uzerinden dogru tarafa baglanir. Kopyalanan kalemlerin bakimi iki yerde
--   yapilir; ad/KDV degisikligi iki kayda da islenmelidir.
create table if not exists public.hizmet (
    id                   integer generated by default as identity primary key,
    kod                  varchar(40)  not null default '',
    ad                   varchar(200) not null,
    baslik_mi            smallint     not null default 0,   -- agac basligi (eski BASLIK=1)
    ust_id               integer,
    grubu                smallint     not null default 0,
    tur                  smallint     not null default 0,
    kdv                  smallint     not null default 0,
    birim                smallint     not null default 0,
    barkod               varchar(30)  not null default '',
    muh_kodu             varchar(20)  not null default '',
    ozel_kod             varchar(40)  not null default '',
    yetki_kodu           varchar(40)  not null default '',
    aciklama             varchar(80)  not null default '',
    varsayilan           smallint     not null default 0,
    durum                smallint     not null default 0,
    resim                bytea,
    sube_id              smallint     not null default 0,
    ekleyen              integer      not null default 0,
    ekleme_tarihi        timestamp    not null default now()::timestamp,
    degistiren           integer      not null default 0,
    degistirme_tarihi    timestamp,
    constraint fk_hizmet_ust foreign key (ust_id) references public.hizmet (id)
);

create index if not exists ix_hizmet_ad_lower on public.hizmet (lower(ad));
create index if not exists ix_hizmet_kod      on public.hizmet (kod);

create table if not exists public.masraf (
    id                   integer generated by default as identity primary key,
    kod                  varchar(40)  not null default '',
    ad                   varchar(200) not null,
    baslik_mi            smallint     not null default 0,
    ust_id               integer,
    grubu                smallint     not null default 0,
    tur                  smallint     not null default 0,
    kdv                  smallint     not null default 0,
    birim                smallint     not null default 0,
    muh_kodu             varchar(20)  not null default '',
    ozel_kod             varchar(40)  not null default '',
    yetki_kodu           varchar(40)  not null default '',
    aciklama             varchar(80)  not null default '',
    varsayilan           smallint     not null default 0,
    durum                smallint     not null default 0,
    sube_id              smallint     not null default 0,
    ekleyen              integer      not null default 0,
    ekleme_tarihi        timestamp    not null default now()::timestamp,
    degistiren           integer      not null default 0,
    degistirme_tarihi    timestamp,
    constraint fk_masraf_ust foreign key (ust_id) references public.masraf (id)
);

create index if not exists ix_masraf_ad_lower on public.masraf (lower(ad));
create index if not exists ix_masraf_kod      on public.masraf (kod);

comment on table public.hizmet is 'Satilan hizmet kalemleri (eski MASRAFGELIR, satis tarafi).';
comment on table public.masraf is 'Gider kalemleri (eski MASRAFGELIR, gider tarafi). Cift kullanilan kalemler her iki tabloda da bulunur.';

