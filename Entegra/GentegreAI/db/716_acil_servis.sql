-- 716: ACİL SERVİS — triyaj, başvuru, yatak, zaman kritik protokol, çağrı, bildirim.
--
-- Mockup'lar: `Ekranlar/Acil/*.html`.
--
-- TEMEL KARAR — YENİ MUAYENE/TANI/REÇETE TABLOSU AÇILMADI. Acil hastasının
--   muayenesi `muayene`, tanısı `tani`, reçetesi `recete`, tetkiki `lab_istem` /
--   `radyoloji_istem`. Acile özel kopyalar açsaydık hastanın tıbbi geçmişi
--   ikiye bölünür, "bu hastaya daha önce ne verildi" sorusu iki yerden
--   toplanmak zorunda kalırdı. Bu dosya yalnız acilin KENDİ kavramlarını
--   ekliyor: triyaj, yatak, süre hedefi, protokol, çağrı.
--
-- TEMEL KARAR — TRİYAJ GEÇMİŞİ AYRI TABLO. Düzey `acil_basvuru`da güncel
--   değerdir; her değişiklik geçmişe yazılır. Tek kolon tutsaydık "hasta
--   yeşilken kötüleşti mi, yoksa baştan yanlış mı triyajlandı" sorusu
--   yanıtsız kalırdı - ikisi bambaşka sonuçlar doğuruyor. Tetik İZİ garanti
--   eder (doğrudan SQL ile yapılan değişiklik bile geçmişe düşer); gerekçeyi
--   uygulama yazar, çünkü gerekçeyi taşıyacak bir kolon satırda yok.
--
-- TEMEL KARAR — BÜTÜN SÜRELER KAPI SAATİNDEN. `giris_zamani` tek referans;
--   adımların kendi damgaları var ama süre hep kapıdan hesaplanır ve tek
--   yerde (v_acil_sure). Her adımı kendi başlangıcından ölçseydik zincirdeki
--   gecikme görünmez olurdu: BT "çekime alındıktan 6 dk sonra" biter ama hasta
--   kapıdan beri 24 dakikadır beklemektedir. Klinik Kalite İN.G2 de kapı-iğne
--   süresinden hesaplanıyor (bkz 713).
--
-- TEMEL KARAR — SON İYİ GÖRÜLME PROTOKOLDE, BAŞVURUDA DEĞİL. Tromboliz
--   penceresi geliş saatinden değil ondan başlar ve yalnız inme protokolünü
--   ilgilendirir; başvuruya koysaydık her hastada boş duran bir alan olurdu.
--
-- TEMEL KARAR — KİMLİKSİZ HASTA KABUL EDİLİR. `hasta_id` NULL olabilir;
--   geçici ad ile kayıt açılır, kimlik bulununca eşleştirilir. Zorunlu
--   tutsaydık bilinci kapalı hasta kimlik gelene kadar sistemde hiç
--   görünmezdi - ölçülmeyen süre de o sırada işliyor.

-- ================================================================= yatak ==
create table if not exists public.acil_yatak (
  id          integer generated by default as identity primary key,
  sube_id     integer not null default 0,
  kod         varchar(20) not null,
  ad          varchar(80) not null default '',
  -- 1 resüsitasyon · 2 müşahede · 3 yeşil alan · 4 izolasyon · 5 travma
  alan        smallint not null default 2,
  -- 0 boş · 1 dolu · 2 temizlikte · 3 arızalı
  durum       smallint not null default 0,
  sira        smallint not null default 0,
  aktif       smallint not null default 1,
  ekleyen     integer not null default 0,
  ekleme_tarihi timestamptz not null default now(),
  degistiren  integer not null default 0,
  degistirme_tarihi timestamptz
);
create unique index if not exists ux_acil_yatak_kod on public.acil_yatak (sube_id, kod);

-- ============================================================== başvuru ==
create table if not exists public.acil_basvuru (
  id             bigint generated by default as identity primary key,
  sube_id        integer not null default 0,
  protokol_no    varchar(30) not null default '',
  -- Kimliksiz hastada NULL; kimlik bulununca doldurulur (bkz başlık kararı).
  hasta_id       integer references public.taraf(id),
  kimliksiz      smallint not null default 0,
  gecici_ad      varchar(120) not null default '',
  eslesme_zamani timestamptz,
  belge_id       integer references public.belge(id),

  -- KAPI SAATİ: bütün süre hesaplarının tek referansı.
  giris_zamani   timestamptz not null default now(),
  -- 1 kendi imkânı · 2 112 ambulans · 3 özel ambulans · 4 polis/jandarma
  -- 5 başka kurumdan sevk · 9 diğer
  gelis_sekli    smallint not null default 1,
  gelis_notu     varchar(200) not null default '',
  sikayet        text not null default '',

  -- TRİYAJ: güncel düzey burada, değişiklikler acil_triyaj_gecmis'te.
  --   1 kırmızı(resüsitasyon) · 2 turuncu · 3 sarı · 4 yeşil · 5 mavi
  triyaj         smallint not null default 0,
  triyaj_zamani  timestamptz,
  triyaj_yapan_id integer references public.taraf(id),

  yatak_id       integer references public.acil_yatak(id),
  hekim_id       integer references public.taraf(id),
  -- Hekimin hastayı İLK GÖRDÜĞÜ an - "kapı-hekim" süresinin ikinci ucu.
  hekim_gorme    timestamptz,
  muayene_id     integer references public.muayene(id),

  -- ÇIKIŞ: 1 taburcu · 2 servise yatış · 3 yoğun bakım · 4 sevk
  --        5 ölüm · 6 kendi isteğiyle · 7 ameliyathane
  cikis_sekli    smallint not null default 0,
  cikis_zamani   timestamptz,
  -- Çıkış tanısı ZORUNLU (tetikle): ön tanıyla kapatılan dosya ne klinik
  --   kalite göstergesine ne TİG'e girebilir.
  cikis_tani     varchar(20) not null default '',
  cikis_notu     text not null default '',
  hedef_bolum_id integer references public.departman(id),
  yatis_id       integer references public.yatis(id),

  adli_vaka      smallint not null default 0,
  odeyen_kurum_id integer,
  ekleyen        integer not null default 0,
  ekleme_tarihi  timestamptz not null default now(),
  degistiren     integer not null default 0,
  degistirme_tarihi timestamptz
);
-- Açık başvurular: panonun ana sorgusu.
create index if not exists ix_acil_basvuru_acik
  on public.acil_basvuru (sube_id, triyaj, giris_zamani) where cikis_zamani is null;
create index if not exists ix_acil_basvuru_hasta on public.acil_basvuru (hasta_id);
create index if not exists ix_acil_basvuru_gun on public.acil_basvuru (sube_id, giris_zamani);

comment on table public.acil_basvuru is
  'Acil servis başvurusu ve triyajı (716). Süreler giris_zamani (kapı) referanslı.';

-- ===================================================== triyaj geçmişi ==
create table if not exists public.acil_triyaj_gecmis (
  id          bigint generated by default as identity primary key,
  basvuru_id  bigint not null references public.acil_basvuru(id) on delete cascade,
  onceki      smallint not null default 0,
  yeni        smallint not null,
  -- Düşürmede gerekçe beklenir (uygulama yazar); yükseltmede boş kalabilir.
