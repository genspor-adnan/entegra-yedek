  -- FK YOK - bilerek. Diğer denetim alanları (ekleyen/degistiren) gibi düz
  --   integer: tetik bu satırı yazarken kullanıcı kimliği taraf tablosunda
  --   bulunamazsa FK ihlali TRİYAJ GÜNCELLEMESİNİ iptal ederdi. Denetim alanı
  --   yüzünden klinik kayıt engellenmez; iz tutulamıyorsa 0 yazılır.
  yapan_id    integer not null default 0,
  zaman       timestamptz not null default now()
