-- =========================================================== süre görünümü ==
-- BÜTÜN SÜRELER TEK YERDE. Ekran, döküm ve klinik kalite aynı hesabı okusun;
--   iki yerde hesaplansaydı "kapı-hekim" panoda 16, raporda 18 dakika çıkardı.
create or replace view public.v_acil_sure as
select b.id as basvuru_id,
       b.sube_id,
       b.giris_zamani,
       b.triyaj,
       -- Dakika cinsinden, kapıdan itibaren.
       (extract(epoch from (b.triyaj_zamani  - b.giris_zamani)) / 60)::numeric(10,1) as kapi_triyaj_dk,
       (extract(epoch from (b.hekim_gorme    - b.giris_zamani)) / 60)::numeric(10,1) as kapi_hekim_dk,
       (extract(epoch from (coalesce(b.cikis_zamani, now()) - b.giris_zamani)) / 60)::numeric(10,1) as toplam_dk,
       -- Triyaj düzeyinin ilk muayene hedefi (dk). 1 = hemen (0).
       case b.triyaj when 1 then 0 when 2 then 10 when 3 then 60
                     when 4 then 120 when 5 then 240 else null end as hedef_dk,
       case when b.hekim_gorme is null then null
            when b.triyaj = 1 then 1
            when extract(epoch from (b.hekim_gorme - b.giris_zamani)) / 60
                 <= (case b.triyaj when 2 then 10 when 3 then 60
                                   when 4 then 120 when 5 then 240 else 99999 end)
            then 1 else 0 end as hedefe_uyuldu,
       b.cikis_zamani,
       b.cikis_sekli
  from public.acil_basvuru b;

comment on view public.v_acil_sure is
  'Acil süreleri - TEK kaynak (716). Ekran, döküm ve klinik kalite aynı hesabı okur.';

-- ============================================================= kurallar ==
-- 1) ÇIKIŞ TANISI ZORUNLU - çıkış şekli girildiği anda. BEFORE tetiktir:
--    satır yazılmadan reddedilmeli, sonradan "aslında geçersizdi" demek
--    dosyayı zaten kapatmış olur.
create or replace function public.fn_acil_cikis_kontrol()
returns trigger language plpgsql as $tg$
begin
    if new.cikis_sekli <> 0 and coalesce(trim(new.cikis_tani), '') = '' then
        raise exception 'Çıkış tanısı zorunlu (ön tanı ile dosya kapatılamaz).'
              using errcode = 'check_violation';
    end if;
    return new;
end;
$tg$;

drop trigger if exists tg_acil_cikis_kontrol on public.acil_basvuru;
create trigger tg_acil_cikis_kontrol
  before insert or update of cikis_sekli, cikis_tani on public.acil_basvuru
  for each row execute function public.fn_acil_cikis_kontrol();

-- 2) TRİYAJ DEĞİŞİKLİĞİ HER ZAMAN GEÇMİŞE YAZILIR.
--
--    Tetiğin garanti ettiği şey İZDİR, gerekçe değil: gerekçeyi taşıyacak bir
--    kolon satırda yok ve uydurma bir kolon eklemek (son_gerekce gibi) her
--    güncellemede eski gerekçeyi taşımaya zorlardı. Gerekçe uygulama
--    katmanından `acil_triyaj_gecmis.gerekce` alanına yazılır; tetik ise
--    doğrudan SQL ile yapılan değişikliğin bile iz bırakmasını sağlar.
--
--    DÜŞÜRME (sayısal büyüme, 1 en acil) ayrı işaretlenir ki gerekçesiz
--    düşürmeler raporlanabilsin - engellemek yerine görünür kılıyoruz, çünkü
--    acil koşullarda engel, kaydı hiç tutmamaya iter.
create or replace function public.fn_acil_triyaj_iz()
returns trigger language plpgsql as $tg$
begin
    if tg_op = 'INSERT' then
        if coalesce(new.triyaj, 0) > 0 then
            insert into public.acil_triyaj_gecmis (basvuru_id, onceki, yeni, gerekce, yapan_id)
            values (new.id, 0, new.triyaj, 'İlk triyaj', coalesce(new.triyaj_yapan_id, new.ekleyen, 0));
        end if;
    elsif new.triyaj is distinct from old.triyaj then
        insert into public.acil_triyaj_gecmis (basvuru_id, onceki, yeni, gerekce, yapan_id)
        values (new.id, coalesce(old.triyaj, 0), new.triyaj,
                case when new.triyaj > coalesce(old.triyaj, 0)
                     then '(düşürme - gerekçe uygulamadan yazılır)' else '' end,
                coalesce(new.triyaj_yapan_id, new.degistiren, 0));
    end if;
    return new;
end;
$tg$;

drop trigger if exists tg_acil_triyaj_iz on public.acil_basvuru;
create trigger tg_acil_triyaj_iz
  after insert or update of triyaj on public.acil_basvuru
  for each row execute function public.fn_acil_triyaj_iz();

-- =============================================================== lookup ==
create or replace view public.v_acil_yatak_lookup as
select y.id,
       (y.kod || ' · ' || case y.alan when 1 then 'Resüsitasyon' when 2 then 'Müşahede'
              when 3 then 'Yeşil alan' when 4 then 'İzolasyon' when 5 then 'Travma'
              else '' end)::varchar(120) as ad,
       y.sube_id, y.aktif
  from public.acil_yatak y where y.aktif = 1;

