--  · Kontrol listesi (denetimli): reçeteye bağlı ön kontroller (tur 1 - üretim emri serbest bırakma öncesi) ve
--    kalite kontrolleri (tur 2 - üretim fişi karantina → serbest). Emir / fiş açılırken buradan kopyalanır;
--    reçete sonradan değişse açık emir / karantinadaki fiş eski listesiyle biter.
--  · Parti büyüklüğü, raf ömrü (denetimli kimlik alanları).
--  · KİLİT: denetimli seviyede onaylı (2) / kilitli (3) reçetenin bileşen, operasyon, kontrol satırları ve kimlik
--    alanları değiştirilemez - tetikleyici P0001 atar, API 422 İş kuralı olarak döner. Değişiklik = Yeni Sürüm.
-- =============================================================================
\set ON_ERROR_STOP on

alter table public.urun_agaci
    add column if not exists parti_buyuklugu numeric(14,3),
    add column if not exists raf_omru_ay     smallint;

create table if not exists public.urun_agaci_kontrol (
    id                integer generated by default as identity primary key,
    agac_id           integer     not null references public.urun_agaci(id) on delete cascade,
    tur               smallint    not null default 2,      -- 1 ön kontrol (emir) · 2 kalite kontrolü (fiş)
    sira              integer     not null default 0,
    ad                varchar(150) not null,
    olcut             varchar(300) not null default '',    -- nasıl doğrulanır / ölçüt
    orneklem          varchar(40)  not null default '',    -- %100 · 2 / parti · 1 / parti
    zorunlu           smallint    not null default 1,
    otomatik          varchar(40) not null default '',     -- sunucu kontrol kodu (malzeme, agac, lot, ekipman) ya da boş = elle
    ret_islem         varchar(150) not null default '',    -- ret halinde: parti reddedilir / yeniden işlem
    aciklama          varchar(300) not null default '',
    ekleyen           integer,
    ekleme_tarihi     timestamp with time zone not null default now(),
    degistiren        integer,
    degistirme_tarihi timestamp with time zone
);
create index if not exists ix_urun_agaci_kontrol_agac on public.urun_agaci_kontrol (agac_id, tur, sira);
comment on table public.urun_agaci_kontrol is
  'Reçete kontrol listesi (1258): tur 1 ön kontrol (üretim emri serbest bırakma), tur 2 kalite kontrolü (üretim fişi karantina → serbest). Emir / fişe kopyalanır.';

-- ------------------------------------------------------------------- kilit --
create or replace function public.fn_urun_agaci_kilit_denetle(p_agac_id integer)
returns void
language plpgsql as $function$
declare
  v_seviye text;
  v_onay   smallint;
  v_kod    text;
begin
    select deger into v_seviye from public.referans where anahtar = 'uretim.seviye';
    if coalesce(v_seviye, 'basit') <> 'denetimli' then return; end if;
    select onay_durum, kod into v_onay, v_kod from public.urun_agaci where id = p_agac_id;
    if v_onay in (2, 3) then
        raise exception 'Reçete % onaylı / kilitli - bileşen, operasyon ve kontrol listesi değiştirilemez. Değişiklik için "Yeni Sürüm" açın.', v_kod
            using errcode = 'P0001';
    end if;
end;
$function$;

create or replace function public.tg_urun_agaci_detay_kilit()
returns trigger
language plpgsql as $function$
begin
    perform public.fn_urun_agaci_kilit_denetle(coalesce(new.agac_id, old.agac_id));
    return coalesce(new, old);
end;
$function$;

create or replace function public.tg_urun_agaci_baslik_kilit()
returns trigger
language plpgsql as $function$
declare
  v_seviye text;
begin
    select deger into v_seviye from public.referans where anahtar = 'uretim.seviye';
    if coalesce(v_seviye, 'basit') <> 'denetimli' then return new; end if;
    -- Onaylı / kilitli sürümde kimlik alanları donar; durum (pasife alma), varsayılan ve onay alanları uçlardan değişir.
    if old.onay_durum in (2, 3) and new.onay_durum = old.onay_durum and (
         new.stok_id is distinct from old.stok_id or new.cikti_miktar is distinct from old.cikti_miktar
      or new.tur is distinct from old.tur or new.kod is distinct from old.kod or new.ad is distinct from old.ad
      or new.sarf_depo_id is distinct from old.sarf_depo_id or new.mamul_depo_id is distinct from old.mamul_depo_id
      or new.fire_depo_id is distinct from old.fire_depo_id or new.parti_buyuklugu is distinct from old.parti_buyuklugu
      or new.raf_omru_ay is distinct from old.raf_omru_ay) then
        raise exception 'Reçete % onaylı / kilitli - kimlik alanları değiştirilemez. Değişiklik için "Yeni Sürüm" açın.', old.kod
            using errcode = 'P0001';
    end if;
    return new;
end;
$function$;

drop trigger if exists trg_urun_agaci_baslik_kilit on public.urun_agaci;
create trigger trg_urun_agaci_baslik_kilit before update on public.urun_agaci
    for each row execute function public.tg_urun_agaci_baslik_kilit();
drop trigger if exists trg_urun_agaci_satir_kilit on public.urun_agaci_satir;
create trigger trg_urun_agaci_satir_kilit before insert or update or delete on public.urun_agaci_satir
    for each row execute function public.tg_urun_agaci_detay_kilit();
drop trigger if exists trg_urun_agaci_operasyon_kilit on public.urun_agaci_operasyon;
create trigger trg_urun_agaci_operasyon_kilit before insert or update or delete on public.urun_agaci_operasyon
    for each row execute function public.tg_urun_agaci_detay_kilit();
drop trigger if exists trg_urun_agaci_kontrol_kilit on public.urun_agaci_kontrol;
create trigger trg_urun_agaci_kontrol_kilit before insert or update or delete on public.urun_agaci_kontrol
    for each row execute function public.tg_urun_agaci_detay_kilit();

