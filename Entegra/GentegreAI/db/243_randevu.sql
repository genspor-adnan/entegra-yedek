-- 243: RANDEVU modülü (kullanıcı: "hasta menüsü altına Randevu liste ve kartı
-- ekle, günlük/haftalık görünüm, bölüm ve hekim gridde başta; randevu altına
-- Randevu Ayarları - gün saat ayarı").
--
-- Model: bir randevu = (şube, bölüm, hekim, hasta, başlangıç, süre). Bitiş
-- SAKLANMAZ, süreden hesaplanır - iki alanın tutarsız kalması sık bir hata.
-- Bölüm ve hekim kod/ilişki: bölüm kod listesi (yeni), hekim personel kartı
-- (taraf.personel = 1) - ayrı "hekim" tablosu açılmadı, aynı kişi hem personel
-- hem hekim.

create table if not exists public.randevu (
  id                integer generated by default as identity primary key,
  sube_id           integer   not null references public.sube(id),
  bolum             smallint  not null default 0,            -- kod_liste 'randevu.bolum'
  hekim_id          integer   references public.taraf(id),   -- personel
  hasta_id          integer   not null references public.taraf(id),
  baslangic         timestamp not null,
  sure_dk           smallint  not null default 15,
  durum             smallint  not null default 1,            -- 1 planlandı /2 geldi /3 gelmedi /4 iptal
  aciklama          varchar(300) not null default '',
  -- Başvuruya (belge) dönüştüyse izi burada kalır - randevu silinse de belge kalır.
  belge_id          integer   references public.belge(id),
  ekleyen           integer   not null default 0,
  ekleme_tarihi     timestamp not null default now()::timestamp,
  degistiren        integer   not null default 0,
  degistirme_tarihi timestamp
);

comment on table public.randevu is
  'Hasta randevuları (243) - bitiş saati sure_dk''dan hesaplanır, saklanmaz.';

create index if not exists ix_randevu_baslangic on public.randevu (baslangic);
create index if not exists ix_randevu_hekim on public.randevu (hekim_id, baslangic);
create index if not exists ix_randevu_hasta on public.randevu (hasta_id, baslangic);
create index if not exists ix_randevu_sube on public.randevu (sube_id, baslangic);

-- Aynı hekime aynı anda iki randevu verilmesin (iptal edilenler hariç).
create unique index if not exists ux_randevu_hekim_saat
  on public.randevu (hekim_id, baslangic) where hekim_id is not null and durum <> 4;

-- ---------------------------------------------------------------- kod listeleri
insert into public.kod_liste (kod, ad)
select 'randevu.bolum', 'Randevu Bölümü'
 where not exists (select 1 from public.kod_liste where kod = 'randevu.bolum');

insert into public.kod_deger (liste_id, deger, ad, sira, aktif, ekleyen)
select l.id, v.deger, v.ad, v.deger * 10, 1, 0
  from public.kod_liste l
  cross join (values (1, 'Dahiliye'), (2, 'Diş'), (3, 'Göz'), (4, 'Ortopedi'),
                     (5, 'Kadın Doğum'), (6, 'Çocuk'), (7, 'Fizik Tedavi'),
                     (8, 'Genel Cerrahi')) as v(deger, ad)
 where l.kod = 'randevu.bolum'
   and not exists (select 1 from public.kod_deger d where d.liste_id = l.id);

insert into public.kod_liste (kod, ad)
select 'randevu.durum', 'Randevu Durumu'
 where not exists (select 1 from public.kod_liste where kod = 'randevu.durum');

insert into public.kod_deger (liste_id, deger, ad, sira, aktif, ekleyen)
select l.id, v.deger, v.ad, v.deger * 10, 1, 0
  from public.kod_liste l
  cross join (values (1, 'Planlandı'), (2, 'Geldi'), (3, 'Gelmedi'),
                     (4, 'İptal')) as v(deger, ad)
 where l.kod = 'randevu.durum'
   and not exists (select 1 from public.kod_deger d where d.liste_id = l.id);

-- ---------------------------------------------------------------- ayarlar
-- Randevu Ayarları ekranını besleyen referanslar (gün/saat düzeni).
insert into public.referans (anahtar, deger, aciklama)
select v.anahtar, v.deger, v.aciklama
  from (values
    ('randevu.baslangic_saat', '09:00', 'Randevu takviminin başlangıç saati'),
    ('randevu.bitis_saat',     '18:00', 'Randevu takviminin bitiş saati'),
    ('randevu.slot_dk',        '15',    'Randevu aralığı (dakika)'),
    ('randevu.varsayilan_sure','15',    'Yeni randevunun varsayılan süresi (dakika)'),
    ('randevu.calisma_gunleri','1,2,3,4,5,6', 'Çalışılan günler (1 Pzt … 7 Paz)'),
    ('randevu.ogle_baslangic', '',      'Öğle arası başlangıcı (boşsa ara yok)'),
    ('randevu.ogle_bitis',     '',      'Öğle arası bitişi')
  ) as v(anahtar, deger, aciklama)
 where not exists (select 1 from public.referans r where r.anahtar = v.anahtar);

-- ---------------------------------------------------------------- yetki
insert into public.yetki (kod, ad, grup, tur, sira, aktif)
select 'randevu', 'Randevular', 'kart', 0, 15, 1
 where not exists (select 1 from public.yetki where kod = 'randevu');

insert into public.rol_yetki (rol_id, yetki_id, gor, ekle, degistir, sil, ekleyen)
select r.id, y.id, 1, 1, 1, 1, 0
  from public.rol r cross join public.yetki y
 where r.kod = 'yonetici' and y.kod = 'randevu'
   and not exists (select 1 from public.rol_yetki x
                    where x.rol_id = r.id and x.yetki_id = y.id);
