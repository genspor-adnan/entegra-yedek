-- ---------------------------------------------------------------------------
--  CİHAZ TANIMI
--
--  radyoloji_cihaz KALIYOR: o randevu/çekim planlaması için (modalite, oda,
--  slot süresi). Buradaki cihaz ENTEGRASYON kaydıdır - ikisi ayrı sorulara
--  cevap verir; birleştirmek randevu tablosuna port/IP kolonu takmak olurdu.
-- ---------------------------------------------------------------------------
create table if not exists public.cihaz (
    id            integer primary key generated by default as identity,
    kod           varchar(25)  not null,
    ad            varchar(120) not null,
    -- 1 laboratuvar · 2 görüntüleme · 3 göz · 4 vital/monitör · 9 diğer
    tur           smallint not null default 1,
    -- Sürücü kodu: HL7V2 · ASTM · DOSYA · DICOM (Cekirdek/Cihaz altındaki
    --   uygulamalarla birebir; tanımsız kod bağlanmaz, mesaj "sürücü yok"
    --   hatasıyla kuyrukta bekler).
    surucu        varchar(20)  not null default 'HL7V2',
    -- 1 dinleyici (cihaz bize bağlanır) · 2 istemci (biz cihaza bağlanırız)
    --   · 3 klasör izleme
    baglanti_turu smallint not null default 1,
    adres         varchar(120) not null default '',
    port          integer  not null default 0,
    klasor_yolu   varchar(300) not null default '',
    -- İşlenen dosya buraya taşınır; boşsa dosya yerinde bırakılır ve adı
    --   `cihaz_mesaj.kaynak` ile tekrar okunmaması sağlanır.
    arsiv_klasoru varchar(300) not null default '',
    kodlama       varchar(20)  not null default 'utf-8',
    ae_title      varchar(40)  not null default '',
    -- Sürücüye özel ayarlar (alan ayırıcı, dosya deseni, zaman aşımı…).
    ayarlar       jsonb    not null default '{}',
    -- Otomatik başlar mı: kapalı cihaz dinleyici açılışında atlanır.
    otomatik      smallint not null default 0,
    son_mesaj     timestamp,
    son_hata      varchar(300) not null default '',
    sube_id       integer  not null default 0,
    durum         smallint not null default 0,     -- 0 aktif · 1 pasif
    aciklama      varchar(300) not null default '',
    ekleyen       integer  not null default 0,
    ekleme_tarihi timestamp not null default now(),
    degistiren    integer  not null default 0,
    degistirme_tarihi timestamp
);
create unique index if not exists ux_cihaz_kod on public.cihaz(kod);
create index if not exists ix_cihaz_durum on public.cihaz(durum, tur);

-- ---------------------------------------------------------------------------
--  MESAJ KUYRUĞU
--
--  DURUM: 1 alındı · 2 çözümlendi · 3 işlendi (hedef kayda yazıldı) ·
--         4 hata · 5 yok sayıldı.
--  Alınan mesaj ÖNCE saklanır, SONRA çözümlenir: çözümleme çökerse bile
--  cihazın gönderdiği veri kaybolmaz (cihaz çoğu zaman tekrar göndermez).
-- ---------------------------------------------------------------------------
create table if not exists public.cihaz_mesaj (
    id            bigint primary key generated by default as identity,
    cihaz_id      integer  not null references public.cihaz(id),
    -- 1 gelen (cihazdan) · 2 giden (cihaza - host query yanıtı, çalışma listesi)
    yon           smallint not null default 1,
    protokol      varchar(20)  not null default '',
    mesaj_tipi    varchar(20)  not null default '',   -- ORU^R01, OUL^R22…
    kontrol_no    varchar(40)  not null default '',   -- MSH-10: tekillik anahtarı
    -- Cihazın gönderdiği örnek/istem/hasta anahtarları. Lab v1 bunları
    --   lab_istem ile eşleştirecek; şimdilik yalnız saklanır.
    ornek_no      varchar(40)  not null default '',
    istem_no      varchar(40)  not null default '',
    hasta_no      varchar(40)  not null default '',
    cihaz_zamani  timestamp,
    ham           text     not null default '',
    kaynak        varchar(300) not null default '',   -- dosya adı / uzak uç
    durum         smallint not null default 1,
    hata          varchar(400) not null default '',
    deneme        smallint not null default 0,
    kalem_sayisi  integer  not null default 0,
    sube_id       integer  not null default 0,
    ekleme_tarihi timestamp not null default now(),
    islenme       timestamp
);
create index if not exists ix_cihaz_mesaj_cihaz
    on public.cihaz_mesaj(cihaz_id, ekleme_tarihi desc);
create index if not exists ix_cihaz_mesaj_durum
    on public.cihaz_mesaj(durum) where durum in (1, 4);
-- AYNI MESAJ İKİ KEZ İŞLENMEZ: cihaz aynı sonucu tekrar gönderebiliyor
--   (bağlantı koptu sanıp yeniden dener). MSH-10 kontrol numarası cihaz
--   içinde tekildir; boşsa koruma uygulanmaz (bazı ASTM cihazları göndermez).
create unique index if not exists ux_cihaz_mesaj_kontrol
    on public.cihaz_mesaj(cihaz_id, kontrol_no) where kontrol_no <> '';

-- ---------------------------------------------------------------------------
--  ÇÖZÜMLENMİŞ KALEMLER - "hangi test, hangi değer".
--
--  Değer METİN olarak saklanır: cihaz "<0.01", "POZİTİF", "1,25" gönderebilir;
--  sayıya zorlamak bu üçünü de kaybettirirdi. Sayısal karşılık ayrı kolonda,
--  çevrilebiliyorsa doldurulur.
-- ---------------------------------------------------------------------------
create table if not exists public.cihaz_mesaj_kalem (
    id           bigint primary key generated by default as identity,
    mesaj_id     bigint  not null references public.cihaz_mesaj(id) on delete cascade,
    sira         integer not null default 0,
    test_kodu    varchar(40)  not null default '',
    test_adi     varchar(200) not null default '',
    deger        varchar(200) not null default '',
    sayisal      numeric(19,6),
    birim        varchar(30)  not null default '',
    referans     varchar(60)  not null default '',
    -- HL7 OBX-8: N normal · H yüksek · L düşük · HH/LL panik · A anormal
    isaret       varchar(10)  not null default '',
    durum        varchar(20)  not null default '',   -- OBX-11 (F final, P ön)
    olcum_zamani timestamp,
    aciklama     varchar(300) not null default ''
);
create index if not exists ix_cihaz_mesaj_kalem on public.cihaz_mesaj_kalem(mesaj_id);

comment on table public.cihaz_mesaj is
    'Cihaz ara katmani (432): protokolden bagimsiz kanonik mesaj. Ham metin saklanir - cozumleme hatasi sonradan duzeltilip yeniden islenebilsin.';

-- ---------------------------------------------------------------------------
--  KUYRUKTAN ALMA - 399/415/427 deseninin aynısı.
--  Takılı satır kurtarma da aynı: 15 dakikadır "işleniyor" kalan geri alınır.
-- ---------------------------------------------------------------------------
create or replace function public.fn_cihaz_siradakiler(p_adet integer default 50)
returns setof public.cihaz_mesaj language sql as $$
    update public.cihaz_mesaj m
       set durum = 2, deneme = m.deneme + 1
     where m.id in (
         select x.id from public.cihaz_mesaj x
          where (x.durum = 1 or (x.durum = 4 and x.deneme < 3))
          order by x.ekleme_tarihi asc, x.id asc
          limit p_adet
          for update skip locked
     )
    returning m.*;
$$;

-- ---------------------------------------------------------------------------
--  LOOKUP + ZAMANLI İŞ
-- ---------------------------------------------------------------------------
drop view if exists public.v_cihaz_lookup;
create view public.v_cihaz_lookup as
select c.id, c.kod, c.kod || ' · ' || c.ad as ad,
       case when c.durum = 0 then 1 else 0 end::smallint as aktif
  from public.cihaz c;

-- Klasör izleyen cihazlar dakikada bir taranır; TCP dinleyici sürekli açık
--   olduğu için işe ihtiyacı yok.
insert into public.zamanli_is (kod, ad, periyot, gun, saat, dakika, aktif, aciklama)
select 'cihaz.klasor', 'Cihaz klasör tarama', 1, 1, 0, 1, 1,
       'Klasör izleyen cihazların yeni dosyalarını kuyruğa alır.'
 where not exists (select 1 from public.zamanli_is z where z.kod = 'cihaz.klasor');

-- ---------------------------------------------------------------------------
--  YETKİ
-- ---------------------------------------------------------------------------
insert into public.yetki (kod, ad, grup, tur, sira)
select v.kod, v.ad, 'Cihaz', v.tur, v.sira
  from (values ('cihaz',        'Cihaz entegrasyonu',      0::smallint, 440::smallint),
               ('cihaz.isle',   'Cihaz mesajını işle',     1::smallint, 441::smallint))
         as v(kod, ad, tur, sira)
 where not exists (select 1 from public.yetki y where y.kod = v.kod);

insert into public.rol_yetki (rol_id, yetki_id, gor, ekle, degistir, sil)
select r.id, y.id, 1, 1, 1, 1
  from public.rol r, public.yetki y
 where r.ad in ('Yönetici', 'Yonetici')
   and y.kod in ('cihaz', 'cihaz.isle')
   and not exists (select 1 from public.rol_yetki x
                    where x.rol_id = r.id and x.yetki_id = y.id);
