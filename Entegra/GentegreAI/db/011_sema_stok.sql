\set ON_ERROR_STOP on

-- ------------------------------------------------------------------ stok ----
create table if not exists public.stok (
    id                    integer generated by default as identity primary key,
    kod                   varchar(25)  not null default '',
    ad                    varchar(100) not null,              -- eski STOKADI
    -- siniflandirma (GENINI kod listelerine bakar)
    kategori              smallint     not null default 0,
    tipi                  smallint     not null default 0,
    marka                 smallint     not null default 0,
    model                 smallint     not null default 0,
    grubu                 smallint     not null default 0,
    ozellik               smallint     not null default 0,
    kullanim              smallint     not null default 0,
    icerik                smallint     not null default 0,
    -- birim ve olcu
    ana_birim             smallint     not null default 0,
    birim2                smallint     not null default 0,
    birim2_miktar         numeric(18,6) not null default 0,
    min_stok              numeric(18,6) not null default 0,
    -- vergi
    kdv                   smallint     not null default 0,
    otv_yuzde             smallint     not null default 0,
    -- izleme (seri/lot)
    izleme                smallint     not null default 0,    -- 0 yok, >0 seri/lot takibi
    raf_omru_sure         smallint     not null default 0,
    raf_omru_birim        smallint     not null default 0,
    -- diger
    durum                 smallint     not null default 0,    -- 0 aktif, 1 pasif
    urun_no               varchar(20)  not null default '',
    hucre                 varchar(50)  not null default '',
    ozel_kod              varchar(20)  not null default '',
    ozel_kod2             varchar(20)  not null default '',
    muh_kodu              varchar(30)  not null default '',
    detay_bolumu          varchar(20)  not null default '',
    internet_satis        smallint     not null default 0,
    bildirim              smallint     not null default 0,
    fatura_stok_adi       varchar(60)  not null default '',   -- belgede farkli ad yazdirmak icin
    resim                 bytea,
    -- kayit izleri
    sube_id               smallint     not null default 0,
    giris_kaynak          smallint     not null default 0,
    ekleyen               integer      not null default 0,
    ekleme_tarihi         timestamp    not null default now()::timestamp,
    degistiren            integer      not null default 0,
    degistirme_tarihi     timestamp
);

create index if not exists ix_stok_ad_lower on public.stok (lower(ad));
create index if not exists ix_stok_kod      on public.stok (kod);
create index if not exists ix_stok_durum    on public.stok (durum);

comment on table  public.stok                 is 'Stok/hizmet ana verisi (eski STOKLAR).';
comment on column public.stok.fatura_stok_adi is 'Belgeye yazdirilacak farkli urun adi. Bos ise ad kullanilir (taraf.fatura_unvan ile ayni kural).';

-- ---------------------------------------------------------- stok_barkod ----
create table if not exists public.stok_barkod (
    id                    integer generated by default as identity primary key,
    stok_id               integer      not null,
    barkod                varchar(50)  not null,
    barkod_tipi           smallint     not null default 0,
    barkod_birimi         smallint     not null default 0,
    varsayilan            smallint     not null default 0,
    ekleyen               integer      not null default 0,
    ekleme_tarihi         timestamp    not null default now()::timestamp,
    degistiren            integer      not null default 0,
    degistirme_tarihi     timestamp,
    constraint fk_stok_barkod_stok foreign key (stok_id)
        references public.stok (id) on delete cascade
);

create unique index if not exists ux_stok_barkod          on public.stok_barkod (barkod);
create unique index if not exists ux_stok_barkod_varsayilan
    on public.stok_barkod (stok_id) where varsayilan = 1;
create index        if not exists ix_stok_barkod_stok     on public.stok_barkod (stok_id);

-- ----------------------------------------------------------- stok_fiyat ----
create table if not exists public.stok_fiyat (
    id                    integer generated by default as identity primary key,
    stok_id               integer      not null,
    fiyat_adi             smallint     not null default 0,    -- fiyat listesi kodu
    birim                 smallint     not null default 0,
    fiyat                 numeric(18,4) not null default 0,
    doviz_cinsi           varchar(5)   not null default '',
    satis                 smallint     not null default 1,    -- 1 satis, 0 alis
    ekleyen               integer      not null default 0,
    ekleme_tarihi         timestamp    not null default now()::timestamp,
    degistiren            integer      not null default 0,
    degistirme_tarihi     timestamp,
    constraint fk_stok_fiyat_stok foreign key (stok_id)
        references public.stok (id) on delete cascade
);

create unique index if not exists ux_stok_fiyat
    on public.stok_fiyat (stok_id, fiyat_adi, birim, satis, doviz_cinsi);

-- ---------------------------------------------------------- stok_durum ----
-- Depo bazli miktar ozeti. Belge kaydedilirken ayni transaction icinde guncellenir.
create table if not exists public.stok_durum (
    stok_id               integer      not null,
    depo_id               integer      not null,
    giren                 numeric(24,6) not null default 0,
    cikan                 numeric(24,6) not null default 0,
    kalan                 numeric(24,6) not null default 0,
    constraint pk_stok_durum primary key (stok_id, depo_id),
    constraint fk_stok_durum_stok foreign key (stok_id) references public.stok (id) on delete cascade,
    constraint fk_stok_durum_depo foreign key (depo_id) references public.depo (id)
);

comment on table public.stok_durum is
  'Depo bazli stok ozeti (eski STOKDURUM). Kalan = giren - cikan; belge transaction''i icinde guncellenir.';

-- -------------------------------------------------------- stok_seri_lot ----
create table if not exists public.stok_seri_lot (
    id                    integer generated by default as identity primary key,
    stok_id               integer      not null,
    lot_no                varchar(30)  not null default '',
    lot_no_ex             varchar(30)  not null default '',
    seri_no               varchar(30)  not null default '',
    uretim_tarihi         timestamp,
    son_kullanma_tarihi   timestamp,
    constraint fk_stok_seri_lot_stok foreign key (stok_id)
        references public.stok (id) on delete cascade
);

create index if not exists ix_stok_seri_lot_stok on public.stok_seri_lot (stok_id);
create index if not exists ix_stok_seri_lot_lot  on public.stok_seri_lot (lot_no) where lot_no <> '';

-- ---------------------------------------------------------- stok_izleme ----
-- Seri/lot hareketleri. belge_id/belge_satir_id FK'leri 012 uygulandiktan
-- SONRA eklenir (bkz. 012_sema_belge.sql sonu).
create table if not exists public.stok_izleme (
    id                    integer generated by default as identity primary key,
    stok_id               integer      not null,
    seri_lot_id           integer      not null,
    izlem_tur             smallint     not null default 0,   -- giris/cikis
    belge_tur             smallint     not null default 0,
    belge_id              integer,                            -- opsiyonel bag -> NULL serbest
    belge_satir_id        integer,
    adet                  numeric(24,6) not null default 0,
    kalan                 numeric(24,6) not null default 0,
    kaynak_tur            integer      not null default 0,   -- eski YER
    kaynak_id             integer      not null default 0,   -- eski YERID
    donus_id              integer      not null default 0,
    ekleyen               integer      not null default 0,
    ekleme_tarihi         timestamp    not null default now()::timestamp,
    constraint fk_stok_izleme_stok     foreign key (stok_id)     references public.stok (id),
    constraint fk_stok_izleme_seri_lot foreign key (seri_lot_id) references public.stok_seri_lot (id)
);

create index if not exists ix_stok_izleme_stok     on public.stok_izleme (stok_id);
create index if not exists ix_stok_izleme_seri_lot on public.stok_izleme (seri_lot_id);
create index if not exists ix_stok_izleme_belge    on public.stok_izleme (belge_id) where belge_id is not null;
