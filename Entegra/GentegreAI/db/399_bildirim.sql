-- ============================================================================
--  399 - BILDIRIM ALTYAPISI (Faz 0, ortak platform)
--
--  Randevu hatırlatma, panik değer, sonuç hazır, teletıp görüşme bağlantısı,
--  onam isteği, prim dönem kapanışı... hepsi aynı işi ister: "şu kişiye şu
--  kanaldan şu metni gönder, gitti mi kaydet". Faz 0'da bir kez kuruluyor;
--  yoksa her modül kendi SMS çağrısını yazar ve "gitti mi" sorusu modül
--  başına ayrı yerde aranır.
--
--  Üç parça:
--    bildirim_sablon - metnin kendisi + değişkenleri ({{hasta_ad}} gibi)
--    bildirim        - KUYRUK: bir satır = bir gönderim denemesi dizisi
--    bildirim_log    - her denemenin sonucu (sağlayıcı yanıtı, hata)
--
--  SAĞLAYICI = mevcut entegrasyon hesabı (ÜTS, e-Belge, sigorta ile aynı
--  tablo): kimlik/URL orada durur, burada yalnız hangi hesapla gittiği yazar.
-- ============================================================================

create table if not exists public.bildirim_sablon (
    id                integer      primary key generated by default as identity,
    kod               varchar(60)  not null unique,   -- 'randevu.hatirlatma'
    ad                varchar(160) not null,
    -- 1 SMS · 2 e-posta · 3 push · 4 WhatsApp (ileride)
    kanal             smallint     not null default 1,
    konu              varchar(200) not null default '',   -- e-postada başlık
    govde             text         not null default '',
    -- Şablonda kullanılabilen değişkenler: {"hasta_ad":"Hastanın adı", ...}
    degiskenler       jsonb        not null default '{}',
    -- Gönderim penceresi: gece SMS atılmasın (0-23; eşitse sınır yok).
    saat_bas          smallint     not null default 0,
    saat_bit          smallint     not null default 0,
    durum             smallint     not null default 1,
    aciklama          varchar(300) not null default '',
    ekleyen           integer      not null default 0,
    ekleme_tarihi     timestamp    not null default now(),
    degistiren        integer      not null default 0,
    degistirme_tarihi timestamp
);

comment on table public.bildirim_sablon is
    'Bildirim şablonları (399): kanal + metin + değişkenler. Gövde şablonu gönderim anında doldurulur.';

create table if not exists public.bildirim (
    id             bigint       primary key generated by default as identity,
    kanal          smallint     not null default 1,
    sablon_id      integer      references public.bildirim_sablon(id),
    -- Hangi entegrasyon hesabıyla gidecek (SMS sağlayıcısı, SMTP hesabı...).
    hesap_id       integer      references public.entegrasyon_hesap(id),
    -- Alıcı: telefon / e-posta / cihaz jetonu. taraf_id varsa kişi kartına bağlı.
    alici          varchar(200) not null,
    taraf_id       integer      references public.taraf(id),
    kullanici_id   integer,                       -- iç bildirim (personel)
    konu           varchar(200) not null default '',
    govde          text         not null default '',
    -- Kaynak GENERIC (onam ile aynı kalıp): 2 belge/başvuru · 3 muayene
    -- 4 randevu · 5 lab istem · 6 radyoloji · 7 prim/hakediş · 9 diğer
    kaynak_tur     smallint     not null default 9,
    kaynak_id      integer,
    -- 1 kuyrukta · 2 gönderiliyor · 3 gönderildi · 4 hata · 5 iptal · 6 vazgeçildi
    durum          smallint     not null default 1,
    oncelik        smallint     not null default 5,   -- küçük önce (panik değer 1)
    deneme         smallint     not null default 0,
    en_fazla_deneme smallint    not null default 3,
    planlanan      timestamp    not null default now(),   -- ileri tarihli hatırlatma
    gonderim       timestamp,
    saglayici_ref  varchar(80)  not null default '',      -- SMS id / message id
    hata           varchar(400) not null default '',
    sube_id        integer,
    ekleyen        integer      not null default 0,
    ekleme_tarihi  timestamp    not null default now()
);

comment on table public.bildirim is
    'Bildirim kuyruğu (399). Gönderici servis durum=1 ve planlanan<=now olan satırları öncelik sırasıyla alır.';

-- Kuyruk taraması: gönderici yalnız bu indeksle çalışır.
create index if not exists ix_bildirim_kuyruk
    on public.bildirim(durum, planlanan, oncelik) where durum in (1, 2);
create index if not exists ix_bildirim_kaynak on public.bildirim(kaynak_tur, kaynak_id);
create index if not exists ix_bildirim_taraf  on public.bildirim(taraf_id, ekleme_tarihi desc);

create table if not exists public.bildirim_log (
    id            bigint    primary key generated by default as identity,
    bildirim_id   bigint    not null references public.bildirim(id) on delete cascade,
    deneme        smallint  not null default 1,
    basarili      smallint  not null default 0,
    http_durum    smallint  not null default 0,
    sure_ms       integer   not null default 0,
    saglayici_ref varchar(80)  not null default '',
    hata          varchar(400) not null default '',
    yanit         jsonb,
    tarih         timestamp not null default now()
);

create index if not exists ix_bildirim_log_bildirim
    on public.bildirim_log(bildirim_id, tarih desc);

-- ---------------------------------------------------------------- kod listeleri
insert into public.kod_liste (kod, ad)
select 'bildirim.kanal', 'Bildirim Kanalı'
 where not exists (select 1 from public.kod_liste where kod = 'bildirim.kanal');

insert into public.kod_deger (liste_id, deger, ad, sira)
select l.id, v.deger, v.ad, v.sira
  from public.kod_liste l,
       (values (1,'SMS',1), (2,'E-posta',2), (3,'Push',3), (4,'WhatsApp',4)) as v(deger, ad, sira)
 where l.kod = 'bildirim.kanal'
   and not exists (select 1 from public.kod_deger d
                    where d.liste_id = l.id and d.deger = v.deger);

insert into public.kod_liste (kod, ad)
select 'bildirim.durum', 'Bildirim Durumu'
 where not exists (select 1 from public.kod_liste where kod = 'bildirim.durum');

insert into public.kod_deger (liste_id, deger, ad, sira)
select l.id, v.deger, v.ad, v.sira
  from public.kod_liste l,
       (values (1,'Kuyrukta',1), (2,'Gönderiliyor',2), (3,'Gönderildi',3),
               (4,'Hata',4), (5,'İptal',5), (6,'Vazgeçildi',6)) as v(deger, ad, sira)
 where l.kod = 'bildirim.durum'
   and not exists (select 1 from public.kod_deger d
                    where d.liste_id = l.id and d.deger = v.deger);

