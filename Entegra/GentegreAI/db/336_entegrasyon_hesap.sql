-- 336: ENTEGRASYON HESAPLARI - dış servis kimlikleri tek yerde.
--
-- Kullanıcı: "user pass vb ayarlar gerekiyorsa Ayarlar altında Kayıt Kabul
-- menüsü altında Genel yanında Entegrasyon sekmesi oluştur, orada tutalım
-- her bir entegrasyon hesaplarını."
--
-- Bugüne kadar her entegrasyon kendi kimliğini kendi tablosunda tutuyordu
-- (ÜTS `uts_hesap`, e-Belge `sube_ebelge_mukellef`). SKRS/Sağlık.NET,
-- MEDULA, eNabız derken bu dağınıklık büyüyor: aynı ekranda yönetilemiyor,
-- test/canlı ayrımı ve şube kırılımı her tabloda yeniden yazılıyor.
--
-- Bu tablo ORTAK sözleşmedir: kod (hangi entegrasyon) + şube + ortam.
-- Servise özgü ek alanlar `ayarlar` (jsonb) içinde durur - her yeni
-- entegrasyon için şema değişikliği gerekmez.
--
-- ŞİFRELER: bu sürümde düz metin (mevcut e-Belge/ÜTS ile aynı durum).
-- Şifreleme ayrı bir iştir; API şifreyi asla listede/loglarda döndürmez,
-- yalnız "dolu/boş" bilgisini verir.

create table if not exists public.entegrasyon_hesap (
    id             integer generated by default as identity primary key,
    -- Hangi entegrasyon: kod listesi entegrasyon.kod (SKRS, MEDULA, ENABIZ,
    --   UTS, EBELGE, SMS...). Metin tutuluyor - yeni entegrasyon eklemek
    --   icin kod listesine satir yeter.
    kod            varchar(20)  not null,
    ad             varchar(120) not null default '',
    -- Sube BOS = kurum geneli hesap. Sube kaydi varsa o oncelikli
    --   (e-Belge mukellef deseniyle ayni).
    sube_id        integer      references public.sube(id),
    aktif          smallint     not null default 1,
    -- 1 TEST ortami, 0 canli. Yeni kurulum TESTTE baslar.
    test_mi        smallint     not null default 1,
    kullanici_adi  varchar(100) not null default '',
    sifre          varchar(200) not null default '',
    -- SKRS/Saglik.NET "UygulamaKodu", MEDULA tesis kodu gibi ucuncu kimlik.
    uygulama_kodu  varchar(100) not null default '',
    kurum_kodu     varchar(50)  not null default '',
    url            varchar(300) not null default '',
    test_url       varchar(300) not null default '',
    -- Servise ozgu ek alanlar (dogrulama sorusu, sertifika adi, kanal...).
    ayarlar        jsonb        not null default '{}'::jsonb,
    aciklama       varchar(300) not null default '',
    son_kullanim   timestamp,
    son_sonuc      varchar(300) not null default '',
    ekleyen        integer      not null default 0,
    ekleme_tarihi  timestamp    not null default (now())::timestamp,
    degistiren     integer      not null default 0,
    degistirme_tarihi timestamp
);

-- Ayni entegrasyon + sube + ortam icin TEK hesap.
create unique index if not exists ux_entegrasyon_hesap
    on public.entegrasyon_hesap (kod, coalesce(sube_id, 0), test_mi);

comment on table public.entegrasyon_hesap is
  'Dis servis kimlikleri (336): SKRS, MEDULA, eNabiz, UTS... kod+sube+ortam.';
comment on column public.entegrasyon_hesap.ayarlar is
  'Servise ozgu ek alanlar (336) - yeni entegrasyon icin sema degismesin.';

-- ----------------------------------------------------------- secim listesi -
-- kod_deger.deger INTEGER oldugu icin metin kodlu (SKRS, MEDULA...) liste
--   oraya sigmiyor; secim listesi kendi gorunumunden gelir.
create or replace view public.v_entegrasyon_kod_lookup as
    select v.id, v.ad, 1 as aktif
      from (values ('SKRS',   'SKRS / Sağlık.NET Kod Sunucusu'),
                   ('ENABIZ', 'e-Nabız'),
                   ('MEDULA', 'MEDULA (SGK)'),
                   ('UTS',    'ÜTS (Ürün Takip Sistemi)'),
                   ('EBELGE', 'e-Belge Entegratörü'),
                   ('SMS',    'SMS Sağlayıcı')) v(id, ad);

comment on view public.v_entegrasyon_kod_lookup is
  'Entegrasyon secim listesi (336) - kodlar METIN oldugu icin kod_deger yerine gorunum.';

-- ---------------------------------------------------------------- yetki ---
insert into public.yetki (kod, ad, grup, tur, sira) values
    ('entegrasyon', 'Entegrasyon hesaplari', 'kart', 0, 150)
on conflict (kod) do nothing;

insert into public.rol_yetki (rol_id, yetki_id, gor, ekle, degistir, sil)
select r.id, y.id, 1, 1, 1, 1
  from public.rol r cross join public.yetki y
 where r.kod = 'yonetici' and y.kod = 'entegrasyon'
on conflict (rol_id, yetki_id) do update
   set gor = 1, ekle = 1, degistir = 1, sil = 1;

