--  424 - DOKUMAN PAYLASIM LINKLERI (mockup dokuman_karti.html · Paylasim)
--
--  Bugun `dokuman.paylasim_kodu` TEK bir link tutuyor (058) ve o link SONSUZ
--  gecerli: ne son kullanma, ne acilma sayaci, ne iptal var. Bir sozlesmeyi
--  bir kez paylasip sonra geri almanin yolu yok - kod degistirilirse eski
--  alici da kaybediyor ama kimin ne zaman actigi hic bilinmiyordu.
--
--  Cok linkli tabloya gecilir; ESKI KOD SILINMEZ ve ilk satir olarak tasinir:
--  kimliksiz uc (api/dokuman-paylasim/{kod}) aynen calismaya devam etsin.
--
--  OZEL NITELIKLI (gizlilik 4) dokumanda link uretimi ONAY ISTER - kural
--  uygulamada, ama saklama burada: her linkin kim tarafindan, ne icin
--  uretildigi kayitli olmali.
-- ============================================================================

create table if not exists public.dokuman_paylasim (
    id             integer     primary key generated by default as identity,
    dokuman_id     integer     not null references public.dokuman(id) on delete cascade,
    kod            varchar(40) not null,
    olusturan_id   integer     not null default 0,
    olusturma      timestamp   not null default now(),
    son_kullanma   timestamp,
    sifre_hash     varchar(100) not null default '',
    indirme_izni   smallint    not null default 1,
    azami_acilma   integer     not null default 0,     -- 0 = sinirsiz
    acilma_sayisi  integer     not null default 0,
    alici_eposta   varchar(120) not null default '',
    iptal          timestamp,
    constraint ux_dokuman_paylasim_kod unique (kod)
);
create index if not exists ix_dokuman_paylasim_dokuman
    on public.dokuman_paylasim(dokuman_id, olusturma desc);

-- Mevcut tek kodlar ilk satir olarak tasinir (veri kaybi yok).
insert into public.dokuman_paylasim (dokuman_id, kod, olusturan_id, olusturma)
select d.id, d.paylasim_kodu, d.ekleyen, d.ekleme_tarihi
  from public.dokuman d
 where d.paylasim_kodu is not null
   and not exists (select 1 from public.dokuman_paylasim p where p.kod = d.paylasim_kodu);

-- Kartin Paylasim sekmesi: linkin YASAYAN durumu tek yerde hesaplanir -
--   "aktif mi" sorusunu ekranda uc kosulla tekrar yazmak, birini unutunca
--   iptal edilmis linki aktif gostermek olurdu.
create or replace view public.v_dokuman_paylasim as
    select p.*,
           case when p.iptal is not null then 3::smallint          -- iptal
                when p.son_kullanma is not null and p.son_kullanma < now()
                     then 2::smallint                              -- suresi gecti
                when p.azami_acilma > 0 and p.acilma_sayisi >= p.azami_acilma
                     then 2::smallint                              -- kota doldu
                else 1::smallint end as durum
      from public.dokuman_paylasim p;
