-- ============================================================================
--  415 - e-NABIZ / USS KUYRUK CEKIRDEGI (Faz 1 · ortak platform)
--
--  Kaynak: Ekranlar/E-Nabız/enabiz_sureci.html (tasarim notu 03.09.2026).
--
--  Klinik olay -> PAKET -> kuyruk -> gonderim. Paket bir KAYIT nesnesidir,
--  gonderim ise denemedir: ikisini tek tabloda tutmak "kacinci denemede
--  gitti, hangi hatayi aldi" sorusunu cevapsiz birakirdi (399 bildirim
--  kuyrugunda ogrenilen desen).
--
--  IKI SEY VERI OLARAK TUTULUR, KOD OLARAK DEGIL:
--    * USS paket numarasi (101/103/106...) - kilavuz surumune gore degisir
--    * zorunlu alan listesi (jsonb)        - kilavuz guncellenince kod degismesin
--  Paket numarasini koda gomen sistem, her kilavuz surumunde yeniden derlenir.
--
--  IDEMPOTENT: ayni kaynak + ayni icerik icin ikinci paket URETILMEZ
--  (icerik_hash). Muayene her kaydedildiginde yeni paket uretmek, USS'ye ayni
--  muayeneyi onlarca kez gondermek olurdu.
--
--  KAPI: USS test hesabi/KTS tescili henuz yok. Paketler URETILIR ve kuyrukta
--  bekler; gonderici kapi acilinca devreye girer. Uretimi kapiya baglamak,
--  kapi acildiginda gecmis veriyi kaybetmek demekti.
-- ============================================================================

create table if not exists public.enabiz_paket_turu (
    id                smallint primary key generated by default as identity,
    kod               varchar(30)  not null,
    ad                varchar(100) not null,
    -- USS kilavuzundaki paket numarasi: 101 · 103 · 106 ...
    uss_paket_kodu    varchar(20)  not null default '',
    uss_surum         varchar(10)  not null default '',
    -- basvuru_acildi · basvuru_kapandi · muayene_tamamlandi · recete_imzalandi
    tetik_olay        varchar(40)  not null default '',
    aktif             smallint     not null default 1,
    oto_gonder        smallint     not null default 1,
    -- Olaydan itibaren USS zaman siniri (uyari esigi).
    sure_siniri_saat  smallint     not null default 24,
    zorunlu_alanlar   jsonb        not null default '[]'::jsonb,
    constraint ux_enabiz_paket_turu unique (kod)
);

create table if not exists public.enabiz_paket (
    id             bigint      primary key generated by default as identity,
    paket_no       varchar(30) not null default '',
    paket_turu_id  smallint    not null references public.enabiz_paket_turu(id),
    -- 1 ekle · 2 guncelle · 3 sil
    islem          smallint    not null default 1,
    -- Kaynak nesne: 1 belge(basvuru) · 2 muayene · 3 recete · 4 lab · 5 radyoloji
    kaynak_tur     smallint    not null,
    kaynak_id      integer     not null,
    belge_id       integer,
    hasta_id       integer,
    hekim_id       integer,
    sube_id        integer     not null default 0,
    olay_tarihi    timestamp,
    uretim_tarihi  timestamp   not null default now(),
    son_tarih      timestamp,
    -- 0 eksik alan · 1 bekliyor · 2 gonderiliyor · 3 gonderildi · 4 hatali
    -- 5 iptal · 6 USS'de silindi
    durum          smallint    not null default 1,
    deneme         smallint    not null default 0,
    son_deneme     timestamp,
    planlanan      timestamp   not null default now(),
    uss_paket_id   varchar(64) not null default '',
    hata_kodu      varchar(20) not null default '',
    hata_mesaj     varchar(400) not null default '',
    -- 1 veri (kullanici duzeltir) · 2 servis (otomatik tekrar) · 3 yetki
    hata_sinifi    smallint    not null default 0,
    icerik_hash    varchar(64) not null default '',
    ham_xml        text        not null default '',
    onceki_paket_id bigint,
    ekleyen        integer     not null default 0,
    ekleme_tarihi  timestamp   not null default now(),
    degistiren     integer     not null default 0,
    degistirme_tarihi timestamp
);

-- Kuyruk taramasi ve kaynaktan paket bulma.
create index if not exists ix_enabiz_paket_kuyruk
    on public.enabiz_paket(durum, planlanan) where durum in (1, 4);
create index if not exists ix_enabiz_paket_kaynak
    on public.enabiz_paket(kaynak_tur, kaynak_id);
create index if not exists ix_enabiz_paket_hasta
    on public.enabiz_paket(hasta_id, olay_tarihi desc);

-- IDEMPOTENCY: ayni tur + kaynak + islem + icerik icin tek paket.
create unique index if not exists ux_enabiz_paket_icerik
    on public.enabiz_paket(paket_turu_id, kaynak_tur, kaynak_id, islem, icerik_hash);

create table if not exists public.enabiz_paket_alan (
    id           bigint      primary key generated by default as identity,
    paket_id     bigint      not null references public.enabiz_paket(id) on delete cascade,
    uss_alan     varchar(60) not null,
    deger        varchar(400) not null default '',
    -- Hangi tablo.kolondan geldi: eksik alan bildirimi kaynagi gostersin.
    kaynak_alan  varchar(100) not null default '',
    skrs_liste   varchar(60) not null default '',
    gecerli      smallint    not null default 1,
    sorun        varchar(200) not null default '',
    sira         smallint    not null default 0
);
create index if not exists ix_enabiz_paket_alan_paket
    on public.enabiz_paket_alan(paket_id, sira);

create table if not exists public.enabiz_gonderim (
    id           bigint    primary key generated by default as identity,
    paket_id     bigint    not null references public.enabiz_paket(id) on delete cascade,
    zaman        timestamp not null default now(),
    ortam        smallint  not null default 1,
    http_kod     smallint  not null default 0,
    -- 1 basarili · 2 hata
    sonuc        smallint  not null default 2,
    uss_kod      varchar(20) not null default '',
    uss_mesaj    varchar(400) not null default '',
    yanit_ham    text      not null default '',
    sure_ms      integer   not null default 0,
    kullanici_id integer
);
create index if not exists ix_enabiz_gonderim_paket
    on public.enabiz_gonderim(paket_id, zaman desc);

-- ---------------------------------------------------------- kod esleme -----
--  Yerel kod -> SKRS kodu. Hasta cinsiyet/medeni hal/kan grubu gibi alanlar
--  ZATEN SKRS koduyla tutuluyor (340), onlar icin esleme gerekmez; burasi
--  klinik, basvuru turu, gelis sekli gibi yerel tanimlar icin.
create table if not exists public.enabiz_kod_esleme (
    id          integer     primary key generated by default as identity,
    esleme_turu varchar(40) not null,
    yerel_id    integer,
    yerel_kod   varchar(60) not null default '',
    skrs_liste  varchar(60) not null default '',
    skrs_kod    varchar(30) not null default '',
    skrs_ad     varchar(200) not null default '',
    aktif       smallint    not null default 1,
    ekleyen     integer     not null default 0,
    ekleme_tarihi timestamp not null default now(),
    degistiren  integer     not null default 0,
    degistirme_tarihi timestamp
);
create unique index if not exists ux_enabiz_kod_esleme
    on public.enabiz_kod_esleme(esleme_turu, coalesce(yerel_id, 0), yerel_kod);

-- ------------------------------------------------------------ seed ---------
--  Faz 1 kapsamindaki uc paket. Numaralar ve zorunlu alanlar VERIDIR:
--  kilavuz surumu degisince buradan guncellenir, kod derlenmez.
insert into public.enabiz_paket_turu
       (kod, ad, uss_paket_kodu, uss_surum, tetik_olay, sure_siniri_saat, zorunlu_alanlar)
select v.kod, v.ad, v.paket, '2.2', v.tetik, v.sure, v.zorunlu::jsonb
  from (values
      ('HASTA_KABUL', 'Hasta Kayıt (Kabul)', '101', 'basvuru_acildi', 24,
       '["TesisKodu","HastaKimlikNo","ProtokolNo","KabulZamani","KlinikKodu","HekimKimlikNo"]'),
      ('MUAYENE', 'Muayene Bilgisi', '103', 'muayene_tamamlandi', 24,
       '["TesisKodu","HastaKimlikNo","ProtokolNo","MuayeneBaslangicZamani","MuayeneTuru","AnaTani"]'),
      ('HASTA_CIKIS', 'Hasta Çıkış', '106', 'basvuru_kapandi', 24,
       '["TesisKodu","HastaKimlikNo","ProtokolNo","CikisZamani","CikisSekli"]')
  ) as v(kod, ad, paket, tetik, sure, zorunlu)
 where not exists (select 1 from public.enabiz_paket_turu t where t.kod = v.kod);

-- ---------------------------------------------------------------------------
--  KUYRUKTAN ALMA - 399 bildirim kuyrugundaki desenin aynisi:
--  `for update skip locked` ile atomik claim; iki isci ayni paketi almaz.
-- ---------------------------------------------------------------------------
create or replace function public.fn_enabiz_siradakiler(p_adet integer default 20)
returns setof public.enabiz_paket language sql as $$
    update public.enabiz_paket p
       set durum = 2, deneme = p.deneme + 1, son_deneme = now()
     where p.id in (
         select x.id from public.enabiz_paket x
          join public.enabiz_paket_turu t on t.id = x.paket_turu_id
          where x.durum in (1, 4)
            and x.planlanan <= now()
            and t.aktif = 1 and t.oto_gonder = 1
            and x.deneme < 5
          order by x.planlanan asc, x.id asc
          limit p_adet
          for update skip locked
     )
    returning p.*;
$$;

comment on function public.fn_enabiz_siradakiler(integer) is
    'Kuyruktan atomik alma (415). for update skip locked: iki isci ayni paketi almaz.';
