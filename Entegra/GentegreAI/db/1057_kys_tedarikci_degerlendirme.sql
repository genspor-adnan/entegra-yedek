-- =============================================================================
--  1057  KURUMSAL KALİTE - TEDARİKÇİ DEĞERLENDİRME (ISO 9001 md. 8.4, SADE)
--
--  Kullanıcı (12.10.2026): "Kalite 2 ile devam et" - KOBİ için sade set,
--  mockup Ekranlar/Kalite2/tedarikci.html. Yılda bir, üç kriter 1-5:
--    kalite · teslim · fiyat -> puan = ortalama (GENERATED)
--    sonuç (GENERATED): ortalama >= 3,5 Onaylı (1) · >= 2,5 Şartlı (2) · altı Red (3)
--  Tedarikçi = mevcut taraf (cari / satınalma kartı, tedarikci = 1); ayrı
--  tedarikçi kaydı tutulmaz. Ağırlıklı kriter seti, sınıf eşik ayarı YOK.
--  Liste (v_kalite_tedarikci): değerlendirilmiş her tedarikçinin SON
--    değerlendirmesi = onaylı tedarikçi listesi. Uygunsuzluk = tedarikçi
--    kaynaklı DÖF sayısı (kalite_dof kaynak_tur 8, kaynak_id = taraf id;
--    kalite_olay'da tedarikçi bağı yok). "Değerlendirme vakti": son
--    değerlendirme 12 aydan eski.
--  Yetki kys.tedarikci (grup 'Kalite', modul 'kys'), yonetici rolüne tam hak.
--  Temel: 1048 (kys), 1050 (kalite_dof). İdempotent.
-- =============================================================================

begin;

create table if not exists public.kalite_tedarikci_deg (
    id                 integer generated by default as identity primary key,
    taraf_id           integer       not null references public.taraf(id),
    tarih              date          not null default current_date,
    ne_aliniyor        varchar(200)  not null default '',
    kalite             smallint      not null default 3 check (kalite between 1 and 5),
    teslim             smallint      not null default 3 check (teslim between 1 and 5),
    fiyat              smallint      not null default 3 check (fiyat between 1 and 5),
    puan               numeric(3,2)  generated always as (round((kalite + teslim + fiyat)::numeric / 3, 2)) stored,
    sonuc              smallint      generated always as (
                           case when (kalite + teslim + fiyat)::numeric / 3 >= 3.5 then 1
                                when (kalite + teslim + fiyat)::numeric / 3 >= 2.5 then 2
                                else 3 end) stored,
    aciklama           varchar(1000) not null default '',
    dof_id             integer,                                     -- kalite_dof (1050), FK yok
    sube_id            integer       not null default 0,
    ekleyen            integer       not null default 0,
    ekleme_tarihi      timestamptz   not null default now(),
    degistiren         integer       not null default 0,
    degistirme_tarihi  timestamptz
);
comment on table public.kalite_tedarikci_deg is
  'Kurumsal Kalite (1057): tedarikçi değerlendirmesi (ISO 9001 8.4). Puan = 3 kriter ortalaması, sonuç 1 onaylı / 2 şartlı / 3 red (generated).';
create index if not exists ix_kalite_tedarikci_deg_taraf on public.kalite_tedarikci_deg (taraf_id, tarih desc, id desc);

-- Son değerlendirme + uygunsuzluk (tedarikçi kaynaklı DÖF). Satır id'si son
--   değerlendirmenin id'si: listeden kart o değerlendirmeyi açar.
create or replace view public.v_kalite_tedarikci as
select d.id, d.taraf_id,
       public.fn_taraf_ad(t.unvan, t.ad, t.soyad)::varchar(120) as tedarikci_adi,
       d.ne_aliniyor, d.kalite, d.teslim, d.fiyat, d.puan, d.sonuc,
       case d.sonuc when 1 then 'Onaylı' when 2 then 'Şartlı' when 3 then 'Red' end as sonuc_adi,
       d.tarih,
       (d.tarih < current_date - interval '12 months')::int as vakti,
       coalesce(u.adet, 0)::int as uygunsuzluk,
       coalesce(u.son_no, '') as son_dof_no,
       d.aciklama, d.sube_id
  from public.taraf t
  join lateral (select x.* from public.kalite_tedarikci_deg x
                 where x.taraf_id = t.id order by x.tarih desc, x.id desc limit 1) d on true
  left join lateral (select count(*) as adet,
                            (array_agg(f.no order by f.id desc))[1] as son_no
                       from public.kalite_dof f
                      where f.kaynak_tur = 8 and f.kaynak_id = t.id and f.durum <> 9) u on true;

-- ---------------------------------------------------------------- yetki --
insert into public.yetki (kod, ad, grup, tur, sira, aktif, modul)
select 'kys.tedarikci', 'Tedarikçi değerlendirme', 'Kalite', 0, 11, 1, 'kys'
 where not exists (select 1 from public.yetki where kod = 'kys.tedarikci');

insert into public.rol_yetki (rol_id, yetki_id, gor, ekle, degistir, sil, ekleyen)
select r.id, y.id, 1, 1, 1, 1, 0
  from public.rol r cross join public.yetki y
 where r.kod = 'yonetici' and y.kod = 'kys.tedarikci'
   and not exists (select 1 from public.rol_yetki ry where ry.rol_id = r.id and ry.yetki_id = y.id);
update public.rol set yetki_surumu = yetki_surumu + 1 where kod = 'yonetici';

-- ---------------------------------------------------------- yardım kataloğu --
insert into public.ai_rehber_ekran (kaynak, rota, baslik, yol, menu_grup, menu_ad,
                                    yetki_kodu, urun_modu, modul, anahtar, aciklama, aksiyon_ekrani)
select 'kys-tedarikci', '/kys-tedarikci', 'Tedarikçi Değerlendirme', 'Kalite › Tedarikçi Değerlendirme', 'Kalite',
       'Tedarikçi Değerlendirme', 'kys.tedarikci', 0, 'kys',
       'tedarikçi değerlendirme onaylı tedarikçi listesi şartlı red kalite teslim fiyat puan iso 8.4 uygunsuzluk dof',
       'Tedarikçiyi yılda bir kalite, teslim ve fiyat üzerinden 1-5 puanla değerlendirin. Ortalama 3,5 ve üstü Onaylı, 2,5-3,5 Şartlı, altı Red. Liste her tedarikçinin son değerlendirmesini ve tedarikçi kaynaklı DÖF sayısını gösterir; 12 aydan eski değerlendirmeler "Değerlendirme vakti" süzgecindedir. Satırdan DÖF açılır.',
       'kys-tedarikci-liste'
 where not exists (select 1 from public.ai_rehber_ekran e where e.kaynak = 'kys-tedarikci');

commit;
