-- ---------------------------------------------------------------------------
--  PAY DAĞITIMI - provizyon yanıtı belgenin TEK pay kaynağıdır.
--
--  Kullanıcı elle karşılama oranı girse bile provizyon geldiğinde üzerine
--  yazılır: iki farklı doğru olmaz, sigorta ne diyorsa fatura odur.
--
--  Satır bazında: kurum payı = insuranceCompanyAmount, hasta payı = kalan
--  (katılım + istisna + muafiyet + limit üstü). Karşılama oranı ikisinden
--  hesaplanır - elle girilen oran sonradan tutarla çelişirdi.
-- ---------------------------------------------------------------------------
create or replace function public.fn_sigorta_pay_dagit(p_provizyon_id integer)
returns integer language plpgsql as $$
declare
    v_sayi integer := 0;
begin
    update public.belge_satir bs
       set kurum_tutar = round(s.sirket_tutar, 4),
           hasta_tutar = round(greatest(0, s.talep_tutar - s.sirket_tutar), 4),
           karsilama   = case when s.talep_tutar > 0
                              then round(s.sirket_tutar * 100 / s.talep_tutar, 4)
                              else 0 end
      from public.sigorta_provizyon_satir s
     where s.provizyon_id = p_provizyon_id
       and bs.id = s.belge_satir_id;
    get diagnostics v_sayi = row_count;
    return v_sayi;
end $$;

-- ---------------------------------------------------------------------------
--  ÖZET TAZELEME - belge_provizyon.oss_* kolonları ekranların okuduğu ÖZETTİR;
--  tek kaynak sigorta_provizyon'dur, özet ondan türetilir. Ekranları yeni
--  tabloya çevirmek yerine özeti tazelemek, başvuru şeridini ve tamamlanma
--  yüzdesini olduğu gibi çalışır bırakır.
-- ---------------------------------------------------------------------------
create or replace function public.fn_sigorta_ozet_tazele(p_provizyon_id integer)
returns void language plpgsql as $$
declare p record;
begin
    select * into p from public.sigorta_provizyon where id = p_provizyon_id;
    if not found then return; end if;

    insert into public.belge_provizyon (id) values (p.belge_id)
    on conflict (id) do nothing;

    update public.belge_provizyon b
       set oss_kurum_id = coalesce((select h.kurum_id from public.sigorta_hesap h
                                     where h.id = p.hesap_id), b.oss_kurum_id),
           oss_durum = p.durum,
           oss_provizyon_no = p.provizyon_no,
           oss_provizyon_tarihi = p.provizyon_tarihi,
           oss_gecerlilik = p.gecerlilik,
           oss_tutar = p.sirket_payi,
           oss_karsilama = case when p.talep_toplam > 0
                                then round(p.sirket_payi * 100 / p.talep_toplam, 4)
                                else 0 end,
           oss_red_nedeni = p.red_nedeni,
           oss_police_no = coalesce((select pl.police_no from public.sigorta_police pl
                                      where pl.id = p.police_id), b.oss_police_no),
           oss_brans = p.brans_adi,
           degistiren = p.degistiren,
           degistirme_tarihi = now()
     where b.id = p.belge_id;
end $$;

-- ---------------------------------------------------------------------------
--  KURUM REFERANS NUMARASI - hospitalReferenceNo. Merkezi sayaç kullanılır
--  (numaralandırma tek yerde); ön ek yıllı: OSS-2026-000123.
-- ---------------------------------------------------------------------------
create or replace function public.fn_sigorta_ref_no(p_sube_id integer default 0,
                                                    p_tarih date default null)
returns text language plpgsql as $$
declare
    v_tarih date := coalesce(p_tarih, current_date);
    v_yil   text := to_char(v_tarih, 'YYYY');
begin
    return 'OSS-' || v_yil || '-' ||
           public.fn_numara_sirada(
               'sigorta_provizyon.kurum_ref_no|SUBE' || coalesce(p_sube_id, 0)::text
               || '|Y' || v_yil,
               'sigorta_provizyon', 'kurum_ref_no',
               'sube ' || coalesce(p_sube_id, 0)::text || ' / yil ' || v_yil,
               6, 1);
end $$;

