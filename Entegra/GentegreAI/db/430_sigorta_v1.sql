  from public.rol r, public.yetki y
 where r.ad in ('Yönetici', 'Yonetici')
   and y.kod in ('sigorta', 'sigorta.provizyon', 'sigorta.iptal', 'sigorta.ayar')
   and not exists (select 1 from public.rol_yetki x
                    where x.rol_id = r.id and x.yetki_id = y.id);

-- ---------------------------------------------------------------------------
--  LOOKUP GÖRÜNÜMLERİ (KartDeposu beyaz listesine de eklenir).
-- ---------------------------------------------------------------------------
drop view if exists public.v_sigorta_saglayici_lookup;
create view public.v_sigorta_saglayici_lookup as
select s.id, s.kod, s.ad,
       case when s.durum = 0 then 1 else 0 end::smallint as aktif
  from public.sigorta_saglayici s;

drop view if exists public.v_sigorta_hesap_lookup;
create view public.v_sigorta_hesap_lookup as
select h.id, s.kod,
       s.ad || ' · ' || coalesce(k.unvan, '') ||
       case when e.test_mi = 1 then ' (test)' else '' end as ad,
       case when h.durum = 0 then 1 else 0 end::smallint as aktif
  from public.sigorta_hesap h
  join public.sigorta_saglayici s on s.id = h.saglayici_id
  join public.entegrasyon_hesap e on e.id = h.hesap_id
  left join public.taraf k on k.id = h.kurum_id;

-- Entegrasyon hesabı seçici: sigorta hesabı kimlik bilgisini MEVCUT
--   entegrasyon_hesap kaydından alır, kartta o kayıt seçilir.
drop view if exists public.v_entegrasyon_hesap_lookup;
create view public.v_entegrasyon_hesap_lookup as
select e.id, e.kod,
       e.kod || ' · ' || e.ad || case when e.test_mi = 1 then ' (test)' else '' end as ad,
       e.aktif
  from public.entegrasyon_hesap e;
