-- ---------------------------------------------------------------------------
--  4.1 SAĞLAYICI VE HESAP
-- ---------------------------------------------------------------------------
create table if not exists public.sigorta_saglayici (
    id         smallint primary key,
    kod        varchar(30)  not null,
    ad         varchar(120) not null,
    -- Ekranı da bu bayraklar sürer: paketleme desteklemeyen şirkette
    --   "Sigortaya Gönder" düğmesi ÇİZİLMEZ - pasif düğme "neden
    --   çalışmıyor" sorusu doğurur.
    yetenekler jsonb    not null default '{}',
    durum      smallint not null default 0,      -- 0 aktif · 1 pasif
    ekleme_tarihi timestamp not null default now()
);
create unique index if not exists ux_sigorta_saglayici_kod
    on public.sigorta_saglayici(kod);

-- Kurumun o sağlayıcıdaki hesabı. Kimlik/URL bilgisi MEVCUT entegrasyon_hesap
--   tablosunda durur (test_mi, url, test_url, kullanici_adi, sifre,
--   uygulama_kodu = client_id, ayarlar.client_secret) - ikinci bir kimlik
--   tablosu açmak, parolayı iki yerde saklamak olurdu.
create table if not exists public.sigorta_hesap (
    id           integer primary key generated by default as identity,
    saglayici_id smallint not null references public.sigorta_saglayici(id),
    kurum_id     integer  not null references public.taraf(id),
    hesap_id     integer  not null references public.entegrasyon_hesap(id),
    -- Çok şubeli kurumda her şubenin ayrı kurum kodu olabilir; boşsa hesap
    --   bütün şubeler için geçerlidir.
    sube_id      integer,
    varsayilan   smallint not null default 0,
    durum        smallint not null default 0,
    aciklama     varchar(300) not null default '',
    ekleyen      integer  not null default 0,
    ekleme_tarihi timestamp not null default now(),
    degistiren   integer  not null default 0,
    degistirme_tarihi timestamp
);
create unique index if not exists ux_sigorta_hesap_kurum
    on public.sigorta_hesap(saglayici_id, kurum_id, coalesce(sube_id, 0));

-- Erişim jetonu önbelleği: her istekte yeniden token alınmaz. Süreç DIŞINDA
--   (tabloda) tutulur - ölçeklenince ikinci sunucu da aynı jetonu görür ve
--   şirket "çok fazla token isteği" demez.
create table if not exists public.sigorta_oturum (
    hesap_id   integer primary key references public.sigorta_hesap(id) on delete cascade,
    jeton      text      not null,
    bitis      timestamp not null,
    yenileme   text      not null default '',
    guncelleme timestamp not null default now()
);

