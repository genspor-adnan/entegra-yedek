-- ============================================= dönem kapatma =============
-- Açık (başlıksız) hakediş satırlarını bir döneme bağlar ve DONDURUR:
-- durum 2 olan satır artık yeniden hesaplanmaz; sonradan çıkan fark
-- sonraki döneme düzeltme satırı olarak girer.
create or replace function public.fn_hakedis_kapat(
    p_taraf_id integer, p_bas date, p_bit date,
    p_kullanici integer default 0, p_sube integer default null)
returns integer language plpgsql as $$
declare
  v_id     integer;
  v_toplam numeric(19,4);
begin
    select coalesce(sum(tutar), 0) into v_toplam
      from public.hakedis_satir
     where taraf_id = p_taraf_id and hakedis_id is null
       and durum = 1 and tarih between p_bas and p_bit;

    if v_toplam = 0 then
        raise exception 'Bu dönemde bağlanacak açık hakediş satırı yok.'
            using errcode = 'GK422';
    end if;

    insert into public.hakedis (taraf_id, donem_baslangic, donem_bitis, durum,
                                toplam, sube_id, ekleyen)
    values (p_taraf_id, p_bas, p_bit, 2, v_toplam, p_sube, p_kullanici)
    returning id into v_id;

    update public.hakedis_satir
       set hakedis_id = v_id, durum = 2
     where taraf_id = p_taraf_id and hakedis_id is null
       and durum = 1 and tarih between p_bas and p_bit;

    return v_id;
end $$;

comment on function public.fn_hakedis_kapat is
  'Dönemi kapatır (324): açık satırları başlığa bağlar ve dondurur.';

-- --------------------------------------------------------- kişi özeti ----
create or replace view public.v_hakedis_ozet as
select hs.taraf_id,
       coalesce(t.unvan, '')                                  as kisi,
       count(*) filter (where hs.hakedis_id is null)           as acik_satir,
       coalesce(sum(hs.tutar) filter (where hs.hakedis_id is null), 0) as acik_tutar,
       coalesce(sum(hs.tutar) filter (where hs.durum = 2), 0)  as kesin_tutar,
       coalesce(sum(hs.tutar), 0)                              as toplam,
       min(hs.tarih)                                           as ilk_tarih,
       max(hs.tarih)                                           as son_tarih
  from public.hakedis_satir hs
  left join public.taraf t on t.id = hs.taraf_id
 where hs.durum <> 0
 group by hs.taraf_id, t.unvan;

comment on view public.v_hakedis_ozet is
  'Kişi bazında hakediş özeti (324): açık (dönemi kapanmamış) ve kesinleşmiş tutar.';
