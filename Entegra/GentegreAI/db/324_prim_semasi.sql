-- ================================================ belge türü çözümü ======
-- Prim oranı GELİR belgesinin türüne bakar. Başvuru satırı (tür 19) ara
-- kayıttır: fatura/tahakkuk dönüşümle sonra oluşur (belge_satir.kaynak_tur=30).
-- Henüz dönüşmemişse satırın kendi belge türü döner - oran belge kesilince
-- yeniden hesaplanır.
create or replace function public.fn_prim_belge_turu(p_satir_id integer)
returns smallint language sql stable as $$
    select coalesce(
      (select b.tur
         from public.belge_satir h
         join public.belge b on b.id = h.belge_id
        where h.kaynak_tur = 30 and h.kaynak_id = p_satir_id
        order by h.id desc limit 1),
      (select b.tur
         from public.belge_satir s
         join public.belge b on b.id = s.belge_id
        where s.id = p_satir_id));
$$;

-- ================================================ plan satırı eşleşmesi ==
-- EN DAR EŞLEŞME kazanır: dolu kriter sayısı (özgüllük) fazla olan satır,
-- eşitlikte planın önceliği. Kriterler: hedef (hizmet > modalite > grup),
-- belge türü, pay, ödeyen kurum, hekim, şube.
create or replace function public.fn_prim_plan_satiri(
    p_rol        smallint,
    p_taraf_id   integer,
    p_hizmet_id  integer,
    p_modalite   smallint,
    p_belge_tur  smallint,
    p_pay        smallint,
    p_kurum_id   integer,
    p_sube_id    integer,
    p_tarih      date)
returns table (plan_id integer, satir_id integer, oran_tipi smallint,
               deger numeric, alt_sinir numeric, ust_sinir numeric, baz smallint)
language sql stable as $$
    select p.id, s.id, s.oran_tipi, s.deger, s.alt_sinir, s.ust_sinir, p.baz
      from public.prim_plani p
      join public.prim_plani_satir s on s.plan_id = p.id
     where coalesce(p.durum, 1) = 1
       and p.baslangic <= p_tarih
       and (p.bitis is null or p.bitis >= p_tarih)
       and s.rol = p_rol
       -- kapsam
       and (p.hekim_id is null or p.hekim_id = p_taraf_id)
       and (coalesce(p.odeyen_kurum_id, 0) = 0 or p.odeyen_kurum_id = p_kurum_id)
       and (coalesce(p.sube_id, 0) = 0 or p.sube_id = p_sube_id)
       -- hedef
       and (s.hedef_tur = 0
            or (s.hedef_tur = 1 and s.hedef_id = p_hizmet_id)
            or (s.hedef_tur = 2 and s.hedef_id = p_modalite)
            or (s.hedef_tur = 3 and s.hedef_id =
                 (select h.kategori from public.hizmet h where h.id = p_hizmet_id)))
       -- belge türü kriteri (bos = tumu)
       and (s.belge_turleri = ''
            or p_belge_tur is null
            or p_belge_tur::text = any(string_to_array(s.belge_turleri, ',')))
       -- pay kriteri
       and (s.pay = 0 or s.pay = p_pay)
     order by
       -- ozgulluk: dolu kriter sayisi
       (case when s.hedef_tur = 1 then 3 when s.hedef_tur = 2 then 2
             when s.hedef_tur = 3 then 1 else 0 end)
       + (case when s.belge_turleri <> '' then 1 else 0 end)
       + (case when s.pay <> 0 then 1 else 0 end)
       + (case when p.hekim_id is not null then 1 else 0 end)
       + (case when coalesce(p.odeyen_kurum_id, 0) <> 0 then 1 else 0 end) desc,
       p.oncelik desc, s.sira, s.id
     limit 1;
$$;

comment on function public.fn_prim_plan_satiri is
  'Bir kalem-rol için geçerli prim kuralı (324): en dar eşleşme, eşitlikte plan önceliği.';

-- =============================================== hakediş üretimi =========
-- Bir tahsilat dağıtımı için hakediş satırlarını (yeniden) üretir. Yeniden
-- üretim güvenlidir: taslak satırlar silinip yazılır, KESİNLEŞMİŞ satıra
-- dokunulmaz (dönem kapandıysa fark sonraki döneme düzeltme olarak girer).
create or replace function public.fn_prim_uret(p_dagitim_id integer)
returns integer language plpgsql as $$
declare
  d          record;
  r          record;
  kural      record;
  v_matrah   numeric(19,4);
  v_tutar    numeric(19,4);
  v_belgetur smallint;
  v_kurum    integer;
  v_sube     integer;
  v_modalite smallint;
  v_tarih    date;
  v_sayac    integer := 0;
begin
    select d2.id, d2.belge_satir_id, d2.pay, d2.tutar,
           k.islem_tarihi::date as tarih, k.durum, k.iptal_islem_id,
           s.hizmet_id, s.kdv, b.sube_id, bb.odeyen_kurum_id
      into d
      from public.kasa_islem_dagitim d2
      join public.kasa_islem k on k.id = d2.kasa_islem_id
      join public.belge_satir s on s.id = d2.belge_satir_id
      join public.belge b on b.id = s.belge_id
      left join public.belge_basvuru bb on bb.id = b.id
     where d2.id = p_dagitim_id;

    if not found then return 0; end if;

    -- Taslak satirlari temizle (kesinlesmislere dokunma).
    delete from public.hakedis_satir
     where dagitim_id = p_dagitim_id and durum = 1;

    -- Iptal edilmis ya da gerceklesmemis tahsilat prim uretmez.
    if coalesce(d.durum, 0) <> 2 or d.iptal_islem_id is not null then
        return 0;
    end if;

    -- PRIM TABANI: dagitilan tutarin KDV'siz karsiligi (323 karari).
    v_matrah := round(d.tutar / (1 + coalesce(d.kdv, 0) / 100.0), 4);
    v_belgetur := public.fn_prim_belge_turu(d.belge_satir_id);
    v_kurum := d.odeyen_kurum_id;
    v_sube := d.sube_id;
    v_tarih := d.tarih;

    select h.modalite into v_modalite from public.hizmet h where h.id = d.hizmet_id;

    for r in select br.rol, br.taraf_id, br.pay_yuzde
               from public.belge_satir_rol br
              where br.belge_satir_id = d.belge_satir_id
    loop
        select * into kural
          from public.fn_prim_plan_satiri(r.rol, r.taraf_id, d.hizmet_id, v_modalite,
                                          v_belgetur, d.pay, v_kurum, v_sube, v_tarih);
        if not found then continue; end if;

        v_tutar := case when kural.oran_tipi = 2
                        then kural.deger
                        else round(v_matrah * kural.deger / 100.0, 2) end;
        v_tutar := round(v_tutar * coalesce(r.pay_yuzde, 100) / 100.0, 2);

        if kural.alt_sinir is not null and v_tutar < kural.alt_sinir then
            v_tutar := kural.alt_sinir;
        end if;
        if kural.ust_sinir is not null and v_tutar > kural.ust_sinir then
            v_tutar := kural.ust_sinir;
        end if;
        if v_tutar <= 0 then continue; end if;

        insert into public.hakedis_satir
               (taraf_id, rol, dagitim_id, belge_satir_id, plan_id, plan_satir_id,
                tarih, belge_tur, pay, taban, oran_tipi, deger, pay_yuzde, tutar, durum)
        values (r.taraf_id, r.rol, p_dagitim_id, d.belge_satir_id,
                kural.plan_id, kural.satir_id, v_tarih, v_belgetur, d.pay,
                v_matrah, kural.oran_tipi, kural.deger,
                coalesce(r.pay_yuzde, 100), v_tutar, 1)
        -- Kismi benzersiz indeks (dagitim_id is not null) hedeflenirken
        --   AYNI kosul yazilmali - yoksa PG indeksi eslestiremez.
        on conflict (dagitim_id, taraf_id, rol) where dagitim_id is not null
        do update set tutar = excluded.tutar, taban = excluded.taban,
                      deger = excluded.deger, belge_tur = excluded.belge_tur,
                      plan_id = excluded.plan_id, plan_satir_id = excluded.plan_satir_id;

        v_sayac := v_sayac + 1;
    end loop;

    return v_sayac;
end $$;

comment on function public.fn_prim_uret is
  'Bir tahsilat dağıtımından hakediş satırı üretir (324). Taban KDV hariç '
  'matrah, tarih tahsilatın işlem tarihi.';

-- --------------------------------------------------------------- tetik ---
-- Dağıtım yazıldığında/değiştiğinde prim yeniden üretilir; iptal edilen
-- tahsilatın primi de bu yoldan düşer (üretim fonksiyonu durum kontrol eder).
create or replace function public.tg_prim_dagitim()
returns trigger language plpgsql as $$
begin
    if tg_op in ('INSERT', 'UPDATE') then
        perform public.fn_prim_uret(new.id);
    elsif tg_op = 'DELETE' then
        delete from public.hakedis_satir where dagitim_id = old.id and durum = 1;
    end if;
    return null;
end $$;

drop trigger if exists tr_prim_dagitim on public.kasa_islem_dagitim;
create trigger tr_prim_dagitim
  after insert or update or delete on public.kasa_islem_dagitim
  for each row execute function public.tg_prim_dagitim();

-- Kasa işleminin durumu değişince (kesinleşme / iptal) primler tazelenir.
create or replace function public.tg_prim_kasa_durum()
returns trigger language plpgsql as $$
declare r record;
begin
    for r in select id from public.kasa_islem_dagitim where kasa_islem_id = new.id
    loop
        perform public.fn_prim_uret(r.id);
    end loop;
    return null;
end $$;

drop trigger if exists tr_prim_kasa_durum on public.kasa_islem;
create trigger tr_prim_kasa_durum
  after update of durum, iptal_islem_id on public.kasa_islem
  for each row execute function public.tg_prim_kasa_durum();

-- ============================================== rapor görünümleri ========
create or replace view public.v_hakedis_satir as
select hs.id,
       hs.hakedis_id,
       hs.taraf_id,
       coalesce(t.unvan, '')                  as kisi,
       hs.rol,
       coalesce(kr.ad, '')                    as rol_adi,
       hs.tarih,
       hs.belge_tur,
       hs.pay,
       case hs.pay when 2 then 'Kurum payı' else 'Hasta payı' end as pay_adi,
       hs.taban,
       hs.oran_tipi,
       hs.deger,
       hs.pay_yuzde,
       hs.tutar,
       hs.durum,
       hs.belge_satir_id,
       s.belge_id,
       coalesce(hz.ad, st.ad, s.aciklama, '') as kalem,
       coalesce(h2.unvan, '')                 as hasta,
       b.sube_id
  from public.hakedis_satir hs
  left join public.taraf t on t.id = hs.taraf_id
  join public.belge_satir s on s.id = hs.belge_satir_id
  join public.belge b on b.id = s.belge_id
  left join public.taraf h2 on h2.id = b.taraf_id
  left join public.hizmet hz on hz.id = s.hizmet_id
  left join public.stok st on st.id = s.stok_id
  left join public.kod_liste kl on kl.kod = 'prim.rol'
  left join public.kod_deger kr on kr.liste_id = kl.id and kr.deger = hs.rol
 where hs.durum <> 0;

comment on view public.v_hakedis_satir is
  'Hakediş satırı raporu (324): kişi, rol, kalem, taban ve tutar.';

-- ======================================= belge dönüşümünde yeniden hesap ==
-- Prim oranı GELİR belgesinin türüne bakıyor; tahsilat çoğu zaman fatura
-- kesilmeden önce yapılır. Başvuru satırı faturaya/tahakkuka dönüştüğü an
-- (belge_satir.kaynak_tur = 30) o satırın primleri yeniden hesaplanır -
-- "fiş/faturada %10, tahakkukta %12" ancak böyle doğru uygulanır.
create or replace function public.tg_prim_donusum()
returns trigger language plpgsql as $$
declare r record;
begin
