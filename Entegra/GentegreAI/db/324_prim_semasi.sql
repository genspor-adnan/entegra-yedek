-- ----------------------------------------------------- hakediş satırı ----
create table if not exists public.hakedis_satir (
    id             integer generated by default as identity primary key,
    hakedis_id     integer  references public.hakedis(id) on delete set null,
    taraf_id       integer  not null references public.taraf(id),
    rol            smallint not null,
    -- Kaynak zincir: hangi tahsilat dağıtımından, hangi kalemden doğdu.
    dagitim_id     integer  references public.kasa_islem_dagitim(id) on delete cascade,
    belge_satir_id integer  not null references public.belge_satir(id) on delete cascade,
    plan_id        integer  references public.prim_plani(id),
    plan_satir_id  integer  references public.prim_plani_satir(id),
    -- PRİM TARİHİ = tahsilatın işlem tarihi (kullanıcı kararı).
    tarih          date     not null,
    belge_tur      smallint,                            -- gelir belgesinin türü
    pay            smallint not null default 1,         -- 1 hasta / 2 kurum
    -- Taban KDV HARİÇ matrah (323); tutar = taban x oran x kişi payı.
    taban          numeric(19,4) not null default 0,
    oran_tipi      smallint not null default 1,
    deger          numeric(19,4) not null default 0,
    pay_yuzde      numeric(9,4)  not null default 100,
    tutar          numeric(19,4) not null default 0,
    durum          smallint not null default 1,         -- 1 taslak, 2 kesin, 0 iptal
    aciklama       varchar(300) not null default '',
    ekleme_tarihi  timestamp not null default (now())::timestamp
);

