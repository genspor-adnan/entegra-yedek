-- 324: Prim / hakediş şeması.
--
-- Kullanıcı kararları (bu şema onların doğrudan karşılığıdır):
--   * Prim TAHSİL EDİLDİKÇE doğar - hizmet verildiğinde değil.
--   * Prim TARİHİ tahsilatın işlem tarihidir (mahsup günü değil).
--   * Prim TABANI KDV HARİÇ matrahtır (323).
--   * Oran, BELGE TÜRÜNE ve PAYA göre değişebilir (fiş/fatura %10,
--     tahakkuk %12; hasta payı / kurum payı ayrı).
--
-- Zincir:
--   kasa_islem_dagitim (321) -> belge_satir -> belge_satir_rol (kim, hangi rol)
--     -> prim_plani_satir (en dar eşleşme) -> hakedis_satir
--
-- Belge türü, satırın DÖNÜŞTÜĞÜ gelir belgesinden okunur: hasta akışında
-- tahsilat başvuruya (tür 19) bağlanır, fatura/tahakkuk sonra kesilir.

