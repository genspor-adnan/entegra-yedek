-- ================================================================ plan ====
create table if not exists public.prim_plani (
    id                integer generated by default as identity primary key,
    kod               varchar(30)  not null default '',
    ad                varchar(120) not null,
    baslangic         date         not null default current_date,
    bitis             date,
    -- Kapsam: bos alan "tumu" demektir (kampanya karti ile ayni mantik).
    hekim_id          integer      references public.taraf(id),
    hekim_tipi        smallint     not null default 0,   -- 0 tümü, 1 iç, 2 dış
    departman_id      integer,
    odeyen_kurum_id   integer      references public.taraf(id),
    sube_id           integer,
    -- Baz (prim.baz): kullanici karari 4 = tahsil edilen matrah.
    baz               smallint     not null default 4,
    -- KDV: 1 = haric (matrah). Kullanici karari haric.
    kdv_haric         smallint     not null default 1,
    oncelik           smallint     not null default 10,
    durum             smallint     not null default 1,
    aciklama          varchar(300) not null default '',
    ekleyen           integer      not null default 0,
    ekleme_tarihi     timestamp    not null default (now())::timestamp,
    degistiren        integer      not null default 0,
    degistirme_tarihi timestamp
);

create unique index if not exists ux_prim_plani_kod
    on public.prim_plani (lower(kod)) where kod <> '';

comment on table public.prim_plani is
  'Prim planı (324) - kapsam + baz; satırları oran kurallarını taşır.';

-- --------------------------------------------------------- plan satırı ----
create table if not exists public.prim_plani_satir (
    id            integer generated by default as identity primary key,
    plan_id       integer  not null references public.prim_plani(id) on delete cascade,
    rol           smallint not null,                    -- prim.rol
    -- HEDEF: 0 tümü / 1 hizmet / 2 modalite / 3 hizmet grubu
    hedef_tur     smallint not null default 0,
    hedef_id      integer,
    -- BELGE TÜRÜ kriteri (kullanıcı isteği): virgüllü tür listesi, boş = tümü.
    --   Örn '4,14,15' = fiş/irsaliye/fatura, '13,17' = tahakkuk.
    belge_turleri varchar(60) not null default '',
    -- PAY kriteri: 0 tümü / 1 hasta payı / 2 kurum payı
    pay           smallint not null default 0,
    oran_tipi     smallint not null default 1,          -- 1 yüzde, 2 sabit tutar
    deger         numeric(19,4) not null default 0,
    alt_sinir     numeric(19,4),
    ust_sinir     numeric(19,4),
    sira          smallint not null default 1,
    aciklama      varchar(200) not null default ''
);

create index if not exists ix_prim_satir_plan on public.prim_plani_satir (plan_id, rol);

