-- =====================================================================
-- 447 - AI REHBER (Faz 1: yalnız rehberlik)
--
-- Kullanıcı "yeni hasta kaydını nereden açarım", "cariye nasıl fatura
-- keserim" diye sorar; asistan EKRANI, SIRAYI ve KONTROLLERİ söyler.
--
-- FAZ 1'İN SINIRI KESİN: asistan operatör değil REHBERDİR. Kayıt açmaz,
-- değiştirmez, silmez, onaylamaz. Bu yüzden buradaki tabloların hiçbiri
-- iş verisine yazmaz; hepsi METİN ve KATALOG.
--
-- NEDEN AYRI EKRAN KATALOĞU (`ai_rehber_ekran`): menü, rota ve ekran adı
-- bugün YALNIZ istemcide (`web/src/sayfalar/listeTanimlari.ts`). Rehber
-- ekran önerecekse sunucunun da bilmesi gerekir - çünkü öneri YETKİYE göre
-- süzülecek ve yetki sunucudadır. İstemciden gelen listeye güvenmek,
-- "bana şu ekranı öner" diyen bir isteğe güvenmek olurdu.
--
-- KONTÖR (`ai_kontor`): rehber cevabı katalogdan üretildiğinde ücretsizdir
-- (yerel hesap, dış maliyet yok). Dil modeli bağlandığında her çağrı
-- kontör harcar; bakiye ve hareketler bugünden hazır ki model açıldığında
-- ücretlendirme geriye dönük eklenmesin - kullanım ile muhasebe aynı anda
-- başlamalı.
-- =====================================================================

-- ---------------------------------------------------------------------
--  1) EKRAN KATALOĞU
--
--  `yetki_kodu` her satırda: öneri süzgeci sunucuda çalışır. `urun_modu`
--  0 ortak · 1 ERP · 2 HBYS - HBYS ekranını ERP kurulumunda önermek,
--  olmayan bir menüyü tarif etmektir.
-- ---------------------------------------------------------------------
create table if not exists public.ai_rehber_ekran (
    id         integer generated by default as identity primary key,
    kaynak     varchar(60)  not null,
    rota       varchar(120) not null,
    baslik     varchar(120) not null,
    yol        varchar(200) not null default '',
    menu_grup  varchar(60)  not null default '',
    menu_ad    varchar(120) not null default '',
    yetki_kodu varchar(60)  not null default '',
    urun_modu  smallint     not null default 0,
    modul      varchar(40)  not null default '',
    kart_yolu  varchar(120) not null default '',
    menu_gizli smallint     not null default 0,
    -- Serbest arama metni: başlık + menü adı + kaynak kodu birleşimi.
    anahtar    varchar(400) not null default '',
    aciklama   varchar(600) not null default '',
    durum      smallint     not null default 0,
    ekleme_tarihi timestamp not null default now()
);

-- BENZERSIZLIK ROTADA: ayni kaynak birden cok ekranda kullanilir (cari ->
--   Musteriler / Tedarikciler, belge -> Satis / Alis Faturalari). Rota her
--   ekranda tektir.
create unique index if not exists ux_ai_rehber_ekran on public.ai_rehber_ekran (rota);
create index if not exists ix_ai_rehber_ekran_kaynak on public.ai_rehber_ekran (kaynak);
create index if not exists ix_ai_rehber_ekran_ara
    on public.ai_rehber_ekran using gin (public.fn_ara_metin(anahtar) gin_trgm_ops);

-- ---------------------------------------------------------------------
--  2) KONU (nasıl yapılır akışı)
--
--  Adımlar JSONB dizi: [{ "no":1, "metin":"...", "ekran":"hasta" }, ...]
--  Adımın ekranı varsa panel oraya götüren düğme çizer.
--
--  UYARILAR alanı bilinçli: "e-fatura göndermeden önce VKN ve adres dolu
--  olmalı" gibi ön koşullar, adımların içinde kaybolmasın.
-- ---------------------------------------------------------------------
create table if not exists public.ai_rehber_konu (
    id         integer generated by default as identity primary key,
    kod        varchar(60)  not null,
    baslik     varchar(160) not null,
    -- 0 ortak · 1 ERP · 2 HBYS
    urun_modu  smallint     not null default 0,
    modul      varchar(40)  not null default '',
    -- Konunun ANA ekranı: cevabın "şuradan başlayın" satırı.
    ekran_kaynak varchar(60) not null default '',
    -- Konuyu görmek için gereken yetki; boşsa herkese açık.
    yetki_kodu varchar(60)  not null default '',
    anahtar    varchar(600) not null default '',
    adimlar    jsonb        not null default '[]'::jsonb,
    uyarilar   varchar(800) not null default '',
    -- Eşit puanlı konularda önce gösterilecek olan (küçük önce).
    sira       smallint     not null default 100,
    durum      smallint     not null default 0,
    ekleme_tarihi timestamp not null default now(),
    degistirme_tarihi timestamp
);

create unique index if not exists ux_ai_rehber_konu on public.ai_rehber_konu (kod);
create index if not exists ix_ai_rehber_konu_ara
    on public.ai_rehber_konu using gin (public.fn_ara_metin(anahtar) gin_trgm_ops);

-- ---------------------------------------------------------------------
--  3) KONTÖR
--
--  Tek satırlık bakiye (kurulum = kiracı; her müşteri ayrı veritabanı).
--  Hareket tablosu YÜKLEME ve HARCAMA'yı birlikte tutar: bakiye her zaman
--  hareketlerin toplamıdır, tek yerden düzeltilmez.
-- ---------------------------------------------------------------------
create table if not exists public.ai_kontor (
    id            smallint primary key default 1,
    bakiye        numeric(14,2) not null default 0,
    -- Model çağrısı başına düşülecek kontör (katalog cevabı ücretsizdir).
    cagri_ucreti  numeric(14,2) not null default 1,
    -- Bakiye bittiğinde asistan kapanmaz: katalog rehberi çalışmaya devam
    --   eder, yalnız model çağrısı yapılmaz.
    uyari_esigi   numeric(14,2) not null default 20,
    degistirme_tarihi timestamp,
    constraint ck_ai_kontor_tek check (id = 1)
);

insert into public.ai_kontor (id) values (1) on conflict (id) do nothing;

create table if not exists public.ai_kontor_hareket (
    id        bigint generated by default as identity primary key,
    -- 1 yükleme · 2 harcama · 3 düzeltme · 4 iade
    tur       smallint not null,
    miktar    numeric(14,2) not null,
    bakiye    numeric(14,2) not null,
    aciklama  varchar(300) not null default '',
    kullanici_id integer,
    -- Harcamada: hangi çağrı, kaç jeton (model bağlanınca dolar).
    rehber_log_id bigint,
    jeton     integer not null default 0,
    tarih     timestamp not null default now()
);

create index if not exists ix_ai_kontor_hareket_tarih
    on public.ai_kontor_hareket (tarih desc);

-- ---------------------------------------------------------------------
--  4) SORU GÜNLÜĞÜ
--
--  Cevaplanamayan soru, eksik rehber konusu demektir: günlük olmadan
--  "asistan işe yaramıyor" geri bildirimi ölçülemez.
-- ---------------------------------------------------------------------
create table if not exists public.ai_rehber_log (
    id        bigint generated by default as identity primary key,
    kullanici_id integer not null,
    sube_id   integer,
    soru      varchar(600) not null,
    -- Cevabın kaynağı: 1 katalog konusu · 2 ekran eşleşmesi · 3 model ·
    --   0 cevaplanamadı
    kaynak    smallint not null default 0,
    konu_kod  varchar(60) not null default '',
    guven     numeric(4,2) not null default 0,
    aktif_mod smallint not null default 0,
    aktif_sayfa varchar(120) not null default '',
    kontor    numeric(14,2) not null default 0,
    sure_ms   integer not null default 0,
    tarih     timestamp not null default now()
);

create index if not exists ix_ai_rehber_log_tarih on public.ai_rehber_log (tarih desc);
create index if not exists ix_ai_rehber_log_kaynak on public.ai_rehber_log (kaynak, tarih desc);

