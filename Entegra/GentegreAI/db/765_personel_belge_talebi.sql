-- ============================================================================
--  Gentegre AI — MAAŞ / ÇALIŞMA BELGESİ TALEBİ
--  765_personel_belge_talebi.sql
--
--  Kullanıcı: "Personelin banka kredisi veya vize işlemleri için İK'dan
--  resmi yazı talep etmesi (Genelde otomatik onaylanır)."
--
--  ============ ASIL İŞ ONAY DEĞİL, HAZIRLAMAK ===========================
--  Öteki taleplerde (izin, avans, masraf) karar zordur: onaylanır ya da
--  reddedilir. Burada karar kolaydır - çalışan çalışıyorsa belge verilir.
--  Zor olan İŞİN KENDİSİ: yazının hazırlanması, imzalanması, teslimi.
--
--  Bu yüzden durum akışı onayla bitmiyor; "onaylandı" yalnız başlangıç:
--
--      talep -> (onay) -> HAZIRLANACAK -> hazırlandı -> teslim edildi
--
--  Onayı iş listesinin sonu sayan bir tasarım, personelin belgeyi ne zaman
--  alacağını cevapsız bırakırdı - oysa sorduğu tam olarak budur.
--
--  ============ OTOMATİK ONAY AYARLA, KAPATILABİLİR ======================
--  Kullanıcı kararı (17.09.2026): `ik.belge_talep_otomatik` açıkken talep
--  zincir kurulmadan onaylı doğar ve doğrudan İK'nın hazırlık kuyruğuna
--  düşer; kapalıyken tek basamaklı İK onayı çalışır.
--
--  RED YOLU HER İKİ HÂLDE AÇIK: otomatik onay "hiç reddedilemez" demek
--  değil. Deneme süresindeki personele kredi yazısı vermemek gibi haklı
--  gerekçeler var; İK hazırlık aşamasında gerekçesiyle reddedebilir.
--
--  Otomatik onayda zincir HİÇ KURULMAZ - boş bir zincir yazıp hemen
--  kapatmak, gelen kutusunu hiç kimsenin bakmadığı satırlarla doldururdu.
-- ============================================================================
\set ON_ERROR_STOP on

-- ---------------------------------------------------------------------- 1
insert into public.referans (anahtar, deger, aciklama)
select 'ik.belge_talep_otomatik', '1',
       'Belge talebi otomatik onaylansin mi (1 evet - varsayilan, 0 hayir). '
       'Kapaliyken tek basamakli IK onayi calisir; red yolu ikisinde de acik.'
 where not exists (select 1 from public.referans
                    where anahtar = 'ik.belge_talep_otomatik');

-- ---------------------------------------------------------------------- 2
insert into public.yetki (kod, ad, grup, tur, modul, aktif, sira)
select x.kod, x.ad, 'İnsan Kaynakları', x.tur, 'ik', 1, x.sira
  from (values
        ('ik.belge_talep',       'Belge Talebi',            0::smallint, 40::smallint),
        ('ik.belge_talep_onay',  'Belge talebi onayı (İK)', 1::smallint, 41::smallint)
  ) as x(kod, ad, tur, sira)
 where not exists (select 1 from public.yetki y where y.kod = x.kod);

insert into public.rol_yetki (rol_id, yetki_id, gor, ekle, degistir, sil)
select r.id, y.id, 1,
       case when y.tur = 1 then 0 else 1 end,
       case when y.tur = 1 then 0 else 1 end, 0
  from public.rol r cross join public.yetki y
 where r.kod in ('yonetici', 'ik')
   and y.kod in ('ik.belge_talep', 'ik.belge_talep_onay')
   and not exists (select 1 from public.rol_yetki ry
                    where ry.rol_id = r.id and ry.yetki_id = y.id);

-- ---------------------------------------------------------------------- 3
create table if not exists public.personel_belge_talep (
    id                integer      primary key generated by default as identity,
    talep_no          varchar(30)  not null default '',
    taraf_id          integer      not null references public.taraf_personel (id),
    sube_id           integer      not null,
    talep_tarihi      date         not null default current_date,
    -- 1 çalışma belgesi · 2 maaş yazısı (bordro özeti) · 3 vize yazısı
    -- 4 SGK hizmet dökümü talebi · 9 diğer
    tur               smallint     not null default 1,
    -- NEDEN İSTENDİĞİ YAZILIR: "banka kredisi", "Schengen vizesi". Yazının
    --   metni amaca göre değişir (vize yazısı İngilizce ve maaş bilgisi
    --   içerir, çalışma belgesi içermeyebilir).
    amac              varchar(200) not null default '',
    -- Kime hitaben: "T. İş Bankası", "Almanya Başkonsolosluğu". Boş ise
    --   "ilgili makama".
    muhatap           varchar(200) not null default '',
    adet              smallint     not null default 1,
    -- 1 elden · 2 e-posta · 3 kargo
    teslim_sekli      smallint     not null default 1,
    -- 0 taslak · 1 onayda · 2 hazırlanacak (onaylı) · 3 reddedildi
    -- 4 hazırlandı · 5 teslim edildi · 8 iptal
    durum             smallint     not null default 0,
    otomatik_onay     smallint     not null default 0,
    red_neden         varchar(300) not null default '',
    hazirlayan_id     integer,
    hazirlama_tarihi  timestamptz,
    teslim_tarihi     timestamptz,
    aciklama          varchar(300) not null default '',
    ekleyen           integer      not null default 0,
    ekleme_tarihi     timestamptz  not null default now(),
    degistiren        integer      not null default 0,
    degistirme_tarihi timestamptz,
    constraint ck_belge_talep_adet check (adet between 1 and 10)
);
create index if not exists ix_belge_talep_taraf
    on public.personel_belge_talep (taraf_id, talep_tarihi desc);
-- HAZIRLIK KUYRUĞU her açılışta koşar: kısmi indeks dar kalsın.
create index if not exists ix_belge_talep_kuyruk
    on public.personel_belge_talep (sube_id, talep_tarihi) where durum in (1, 2);

comment on table public.personel_belge_talep is
  '765: personelin IK dan resmi yazi talebi (calisma belgesi, maas yazisi, '
  'vize yazisi). Asil is onay degil HAZIRLAMAK - durum onayla bitmez.';
comment on column public.personel_belge_talep.otomatik_onay is
  '765: 1 ise talep ik.belge_talep_otomatik ayari geregi zincir kurulmadan '
  'onayli acildi. Denetimde "bunu kim onayladi" sorusunun cevabi.';

-- ---------------------------------------------------------------------- 4
--  LİSTE GÖRÜNÜMÜ
create or replace view public.v_personel_belge_talep as
select b.id,
       b.talep_no,
       b.taraf_id,
       b.sube_id,
       coalesce(nullif(t.unvan, ''), '')              as personel_ad,
       coalesce(nullif(p.gorev, ''), '')              as gorev_ad,
       b.talep_tarihi,
       b.tur,
       case b.tur when 1 then 'Çalışma Belgesi'
                  when 2 then 'Maaş Yazısı'
                  when 3 then 'Vize Yazısı'
                  when 4 then 'SGK Hizmet Dökümü'
                  else 'Diğer' end                    as tur_adi,
       b.amac,
       b.muhatap,
       b.adet,
       b.teslim_sekli,
       b.durum,
       b.otomatik_onay,
       b.red_neden,
       b.hazirlayan_id,
       coalesce(nullif(hz.unvan, ''), '')             as hazirlayan_ad,
       b.hazirlama_tarihi,
       b.teslim_tarihi,
       -- BEKLEME GÜNÜ: belge talebinde geciken şey onay değil HAZIRLIK.
       --   Teslim edilene kadar sayaç işler - personel belgeyi bekliyor.
       case when b.durum in (4, 5, 3, 8) then 0
            else greatest(0, (current_date - b.talep_tarihi)) end as bekleme_gun,
       (select v.adim_ad from public.v_onay_bekleyen v
         where v.kaynak_tur = 1314 and v.kaynak_id = b.id
         order by v.sira limit 1)                     as bekleyen_basamak,
       b.aciklama,
       b.ekleme_tarihi,
       b.degistirme_tarihi
  from public.personel_belge_talep b
  join public.taraf t               on t.id = b.taraf_id
  left join public.taraf_personel p on p.id = b.taraf_id
  left join public.taraf hz         on hz.id = b.hazirlayan_id;

comment on view public.v_personel_belge_talep is
  '765: belge talebi listesi. bekleme_gun TESLIME kadar isler - personelin '
  'bekledigi sey onay degil belgenin kendisi.';

-- ---------------------------------------------------------------------- 5
--  ONAY AKIŞI — tek basamak İK
--  Ölçü YOK: belge talebinde eşiğe konu bir sayı yok (adet ölçü değil,
--  nüsha sayısı). `olcu_adi` boş - gelen kutusu ölçü sütununu boş gösterir.
insert into public.onay_akis (kod, ad, kaynak_tur, olcu_adi, aktif, aciklama, ekleyen)
select 'personel.belge_talep', 'Belge Talebi Onayı', 1314, '', 1,
       '765: tek basamak IK. ik.belge_talep_otomatik acikken zincir HIC '
       'kurulmaz, talep onayli dogar ve hazirlik kuyruguna duser.', 0
 where not exists (select 1 from public.onay_akis where kod = 'personel.belge_talep');

insert into public.onay_akis_adim
       (akis_id, sira, ad, sahip_turu, rol, esik_alt, bayrak, sure_gun, ekleyen)
select k.id, 1, 'İnsan Kaynakları', 1, 6, null, '', 2, 0
  from public.onay_akis k
 where k.kod = 'personel.belge_talep'
   and not exists (select 1 from public.onay_akis_adim a where a.akis_id = k.id);

-- ---------------------------------------------------------------------- 6
--  GELEN KUTUSU BELGE TALEBİNİ DE TANISIN
create or replace view public.v_onay_kutusu as
select v.adim_id                                as id,
       v.onay_id, v.kaynak_tur, v.kaynak_id, v.sube_id,
       v.akis_kod, v.akis_ad, v.olcu, v.olcu_adi, v.sira, v.adim_ad, v.rol,
       v.atanan_kullanici_id, v.durum, v.gerekce, v.baslama, v.termin,
       v.gecikme_gun,
       case v.kaynak_tur
            when 1241 then coalesce(nullif(t.talep_no, ''), '#' || v.kaynak_id::text)
            when 904  then coalesce(nullif(z.izin_no, ''), 'İzin #' || v.kaynak_id::text)
            when 1224 then coalesce(nullif(w.is_emri_no, ''),
                                    'İş emri #' || v.kaynak_id::text)
            when 1257 then coalesce(nullif(av.avans_no, ''),
                                    'Avans #' || v.kaynak_id::text)
            when 1256 then coalesce(nullif(ib.belge_no, ''),
                                    'Başvuru #' || coalesce(isk.belge_id, 0)::text)
            when 976  then coalesce(nullif(dk.kod, ''), 'DOK-' || dk.id::text)
                           || ' v' || ds.surum_no::text
            when 1312 then coalesce(nullif(ms.beyan_no, ''),
                                    'Masraf #' || v.kaynak_id::text)
            when 1314 then coalesce(nullif(bt.talep_no, ''),
                                    'Belge #' || v.kaynak_id::text)
            else '#' || v.kaynak_id::text
       end                                      as kayit_no,
       case v.kaynak_tur
            when 1241 then coalesce(nullif(t.gerekce, ''), 'Satınalma talebi')
            when 904  then case z.tur when 1 then 'Yıllık izin'
                                      when 2 then 'Mazeret izni'
                                      when 3 then 'Rapor'
                                      when 4 then 'Ücretsiz izin'
                                      else 'İzin' end
                           || ' · ' || to_char(z.baslangic_tarihi, 'DD.MM')
                           || '-' || to_char(z.bitis_tarihi, 'DD.MM.YYYY')
            when 1224 then coalesce(nullif(dm.ad, ''), 'Cihaz')
                           || ' · ' || coalesce(nullif(w.ariza_metni, ''), 'onarım')
            when 1257 then coalesce(nullif(av.gerekce, ''), 'Avans')
                           || ' · ' || av.taksit_sayisi::text || ' taksit'
            when 1256 then coalesce(nullif(isk.gerekce, ''), 'İskonto talebi')
                           || ' · ' || (select count(*)::text
                                          from public.iskonto_talep_satir ts
                                         where ts.talep_id = isk.id) || ' kalem'
            when 976  then coalesce(nullif(dk.ad, ''), 'Doküman')
                           || coalesce(' · ' || nullif(ds.degisiklik_notu, ''), '')
            when 1312 then coalesce(nullif(ms.aciklama, ''), 'Masraf beyanı')
                           || ' · ' || (select count(*)::text
                                          from public.personel_masraf_satir mss
                                         where mss.beyan_id = ms.id) || ' belge'
            -- BELGE TALEBİNDE KONU = TÜR + AMAÇ: İK'nın yazıyı hangi metinle
            --   hazırlayacağını belirleyen şey amaçtır.
            when 1314 then case bt.tur when 1 then 'Çalışma Belgesi'
                                       when 2 then 'Maaş Yazısı'
                                       when 3 then 'Vize Yazısı'
                                       when 4 then 'SGK Hizmet Dökümü'
                                       else 'Belge' end
                           || coalesce(' · ' || nullif(bt.amac, ''), '')
            else ''
       end                                      as konu,
       case v.kaynak_tur
            when 1241 then coalesce(d.ad, '')
            when 904  then coalesce(nullif(zp.gorev, ''), '')
            when 1224 then coalesce(wd.ad, '')
            when 1257 then coalesce(nullif(ap.gorev, ''), '')
            when 1256 then coalesce(ih.unvan, '')
            when 976  then coalesce(dkat.ad, '')
            when 1312 then coalesce(nullif(mp.gorev, ''), '')
            when 1314 then coalesce(nullif(bp.gorev, ''), '')
            else ''
       end                                      as birim,
       case v.kaynak_tur
            when 1241 then coalesce(p.unvan, '')
            when 904  then coalesce(zt.unvan, '')
            when 1224 then coalesce(wb.unvan, '')
            when 1257 then coalesce(at.unvan, '')
            when 1256 then coalesce(ii.unvan, '')
            when 976  then coalesce(dy.unvan, '')
            when 1312 then coalesce(mt.unvan, '')
            when 1314 then coalesce(btt.unvan, '')
            else ''
       end                                      as talep_eden
  from public.v_onay_bekleyen v
  left join public.satinalma_talep t on v.kaynak_tur = 1241 and t.id = v.kaynak_id
  left join public.departman d on d.id = t.departman_id
  left join public.taraf p     on p.id = t.isteyen_id
  left join public.personel_izin z on v.kaynak_tur = 904 and z.id = v.kaynak_id
  left join public.taraf zt          on zt.id = z.taraf_id
  left join public.taraf_personel zp on zp.id = z.taraf_id
  left join public.demirbas_is_emri w on v.kaynak_tur = 1224 and w.id = v.kaynak_id
  left join public.demirbas dm  on dm.id = w.demirbas_id
  left join public.departman wd on wd.id = w.departman_id
  left join public.taraf wb     on wb.id = w.bildiren_id
  left join public.personel_avans av on v.kaynak_tur = 1257 and av.id = v.kaynak_id
  left join public.taraf at          on at.id = av.taraf_id
  left join public.taraf_personel ap on ap.id = av.taraf_id
  left join public.iskonto_talep isk on v.kaynak_tur = 1256 and isk.id = v.kaynak_id
  left join public.belge ib on ib.id = isk.belge_id
  left join public.taraf ih on ih.id = ib.taraf_id
  left join public.taraf ii on ii.id = isk.isteyen_id
  left join public.dokuman_surum ds on v.kaynak_tur = 976 and ds.id = v.kaynak_id
  left join public.dokuman dk        on dk.id = ds.dokuman_id
  left join public.dokuman_kategori dkat on dkat.id = dk.kategori_id
  left join public.taraf dy          on dy.id = ds.yukleyen_id
  left join public.personel_masraf ms on v.kaynak_tur = 1312 and ms.id = v.kaynak_id
  left join public.taraf mt          on mt.id = ms.taraf_id
  left join public.taraf_personel mp on mp.id = ms.taraf_id
  left join public.personel_belge_talep bt on v.kaynak_tur = 1314 and bt.id = v.kaynak_id
  left join public.taraf btt         on btt.id = bt.taraf_id
  left join public.taraf_personel bp on bp.id = bt.taraf_id;

comment on view public.v_onay_kutusu is
  '739/744/752/753/754/755/758/764/765: butun modullerin bekleyen onaylari '
  '(satinalma talebi · izin · masrafli onarim · avans · iskonto · dokuman '
  'surumu · masraf beyani · belge talebi).';

