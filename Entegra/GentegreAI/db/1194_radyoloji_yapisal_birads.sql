-- =============================================================================
--  1194  RADYOLOJİ RAPORU: BİÇİM × GİRİŞ - YAPISAL RAPORLAMA (BI-RADS)
--
--  Kullanıcı (27.10.2026): "tek - yapısal, tek - şablon, parçalı - yapısal, parçalı - şablon olur mu",
--  "v2 yi uygula" (mockup Ekranlar/Radyoloji/radyoloji_birads_v2.html).
--   * Biçim (tek / parçalı) şema istemez: tek parça rapor başlığı 'Rapor' olan tek bölümdür (web raporBicimi).
--   * Giriş: serbest (hekim yazar) / yapısal (form doldurur, BULGULAR + SONUÇ formdan üretilir).
--     Yapısal yalnız şablonda yapisal_tur doluysa açılır (1 = BI-RADS; ileride LI-RADS, PI-RADS ...).
--   * BI-RADS verisi metinden AYRI saklanır: rapor başına kompozisyon, önerilen / son kategori, gerekçe,
--     yönetim önerisi; lezyon başına sözlük seçimleri (radyoloji_rapor_lezyon). Metin yine bölümlerde -
--     çıktı, onay, e-Nabız değişmez.
--   * Örnek BI-RADS şablonları (966: MG-01, US-MEM-01) yalnız kod eşleşirse ve henüz işaretsizse işaretlenir;
--     kurumun kendi şablonlarına dokunulmaz.
--  İdempotent.
-- =============================================================================
\set ON_ERROR_STOP on

begin;

alter table public.radyoloji_sablon add column if not exists yapisal_tur smallint not null default 0;
comment on column public.radyoloji_sablon.yapisal_tur is
  'Yapısal rapor formu: 0 yok, 1 BI-RADS. Doluysa rapor ekranında Giriş = Yapısal seçilebilir.';

alter table public.radyoloji_rapor add column if not exists giris              smallint     not null default 1;
alter table public.radyoloji_rapor add column if not exists birads_kompozisyon varchar(60)  not null default '';
alter table public.radyoloji_rapor add column if not exists birads_oneri       varchar(3)   not null default '';
alter table public.radyoloji_rapor add column if not exists birads_kategori    varchar(3)   not null default '';
alter table public.radyoloji_rapor add column if not exists birads_gerekce     varchar(300) not null default '';
alter table public.radyoloji_rapor add column if not exists birads_yonetim     varchar(120) not null default '';
comment on column public.radyoloji_rapor.giris is 'Raporun yazılış yolu: 1 serbest metin, 2 yapısal form.';
comment on column public.radyoloji_rapor.birads_oneri is 'Sistemin önerdiği BI-RADS kategorisi (0,1,2,3,4A,4B,4C,5,6).';
comment on column public.radyoloji_rapor.birads_kategori is 'Radyoloğun verdiği son BI-RADS kategorisi; öneriden farklıysa gerekçe zorunlu.';

create table if not exists public.radyoloji_rapor_lezyon (
  id             integer generated by default as identity primary key,
  rapor_id       integer not null references public.radyoloji_rapor(id) on delete cascade,
  sira           smallint not null default 1,
  taraf          varchar(4)  not null default '',
  saat           varchar(8)  not null default '',
  uzaklik        varchar(20) not null default '',
  boyut          varchar(30) not null default '',
  sekil          varchar(30) not null default '',
  oryantasyon    varchar(30) not null default '',
  kenar          varchar(30) not null default '',
  eko            varchar(40) not null default '',
  arka           varchar(30) not null default '',
  kalsifikasyon  varchar(40) not null default '',
  buyume         smallint    not null default 0,
  kategori       varchar(3)  not null default ''
);
create index if not exists ix_radyoloji_rapor_lezyon on public.radyoloji_rapor_lezyon (rapor_id);
create index if not exists ix_radyoloji_rapor_birads on public.radyoloji_rapor (birads_kategori)
  where birads_kategori <> '';
comment on table public.radyoloji_rapor_lezyon is
  'BI-RADS lezyonları (1194): rapor başına, sözlük seçimleri + lezyon kategorisi. Rapor kaydında silinip yeniden yazılır.';

update public.radyoloji_sablon set yapisal_tur = 1
 where kod in ('MG-01', 'US-MEM-01') and yapisal_tur = 0;

commit;
