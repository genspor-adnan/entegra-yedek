-- 255: GÖREV TABLOSU (kullanıcı: "personel_gorev tablosu da oluştur: id, ad,
-- departman_id (default 0), durum (default aktif)... görev istenirse departmana
-- bağlanabilir combo ile, isterse bağımsız olur... personel kartında departmana
-- göre bu görev listesi gelecek ve seçilecek").
--
-- Departman gibi (251) görev de kod listesinden TABLOYA taşınıyor: göreve
-- departman bağı gerekiyor, kod_deger'de böyle bir alan yok.
--
-- departman_id = 0 -> BAĞIMSIZ görev: her departmanda seçilebilir (ör. "Müdür").
-- Dolu ise görev yalnız o departmanın personelinde listelenir.
--
-- ID KORUNUR: taraf.gorev_id mevcut sayıları (1..13) aynen kalsın diye satırlar
-- kendi id'leriyle taşınır.

create table if not exists public.personel_gorev (
  id                integer generated by default as identity primary key,
  ad                varchar(100) not null,
  -- 0 = bağımsız (FK yok: 0 gerçek bir departman değil, "hepsi" demek).
  departman_id      integer  not null default 0,
  durum             smallint not null default 1,      -- 1 Aktif / 0 Pasif
  sira              integer  not null default 0,
  ekleyen           integer  not null default 0,
  ekleme_tarihi     timestamp not null default now()::timestamp,
  degistiren        integer  not null default 0,
  degistirme_tarihi timestamp
);

comment on table public.personel_gorev is
  'Personel görevi (255). departman_id = 0 ise bağımsız - her departmanda seçilebilir.';

create index if not exists ix_personel_gorev_departman
  on public.personel_gorev (departman_id, durum);

-- --------------------------------------------------------------- veri göçü --
-- Eski kod listesi 'taraf.gorev' -> tablo; hepsi BAĞIMSIZ başlar (departmanı
--   kullanıcı ekrandan bağlar), taraf.gorev_id değerleri değişmez.
insert into public.personel_gorev (id, ad, departman_id, durum, sira)
select distinct on (lower(d.ad)) d.deger, d.ad, 0, d.aktif, d.sira
  from public.kod_deger d
  join public.kod_liste l on l.id = d.liste_id
 where l.kod = 'taraf.gorev'
   and not exists (select 1 from public.personel_gorev x where x.id = d.deger)
 order by lower(d.ad), d.deger;

select setval(pg_get_serial_sequence('public.personel_gorev', 'id'),
              coalesce((select max(id) from public.personel_gorev), 1));

-- ------------------------------------------------------------------ lookup --
-- Personel kartındaki Görev combosu bunu okur. `ust_id` = departman: kart
--   altyapısı bağlı combo'yu (İl -> İlçe deseni) bu kolondan süzer; bağımsız
--   görevlerde NULL kalır ve her departmanda listelenir.
create or replace view public.v_gorev_lookup as
select g.id,
       g.ad,
       case when g.durum = 1 then 1 else 0 end as aktif,
       nullif(g.departman_id, 0) as ust_id
  from public.personel_gorev g;
