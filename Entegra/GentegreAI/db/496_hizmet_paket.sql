-- =====================================================================
--  496_hizmet_paket.sql
--  PANEL / PAKET İÇERİĞİ: hizmetin içindeki hizmetler.
--
--  Bugüne kadar bir panelin ("OGTT", "Tam Kan Sayımı 18 parametre") ya da
--  check-up paketinin içeriği, HER PANEL İÇİN AYRI BİR HİZMET KAYDI
--  açılarak tutuluyordu: "AST( SGOT )" katalogda 40 kez var (L.B.032 +
--  P.C004.08 + P.S.012.09 ...). Kullanıcı: "tekrarlı tetkik olmasın".
--
--  Doğru model stok tarafında zaten var (`stok_paket`): paket satılabilir
--  bir kayıttır, içeriği KANONİK kalemleri gösteren satırlardır. Bu tablo
--  onun hizmet karşılığı; 497 mevcut kopyaları buraya taşıyıp siler.
--
--  `adet` panelde aynı tetkikin birden çok kez çalışılabilmesi için (OGTT
--  glukozu farklı dakikalarda ister ama onlar AYRI tetkiklerdir; adet
--  yine de paket fiyatlaması için gerekli - stok_paket ile aynı desen).
-- =====================================================================

create table if not exists public.hizmet_paket (
    id                bigint generated by default as identity primary key,
    paket_hizmet_id   integer not null references public.hizmet(id),
    icerik_hizmet_id  integer not null references public.hizmet(id),
    sira              smallint not null default 0,
    adet              numeric(19,4) not null default 1,
    sube_id           integer not null default 0,
    ekleyen           integer not null default 0,
    ekleme_tarihi     timestamp not null default now()::timestamp,
    degistiren        integer not null default 0,
    degistirme_tarihi timestamp,
    constraint ck_hizmet_paket_adet  check (adet > 0),
    constraint ck_hizmet_paket_kendi check (paket_hizmet_id <> icerik_hizmet_id)
);

create unique index if not exists ux_hizmet_paket_satir
    on public.hizmet_paket (paket_hizmet_id, icerik_hizmet_id);
create index if not exists ix_hizmet_paket_icerik
    on public.hizmet_paket (icerik_hizmet_id);
create index if not exists ix_hizmet_paket_ust
    on public.hizmet_paket (paket_hizmet_id, sira);

comment on table public.hizmet_paket is
    'Panel/paket hizmetinin içeriği - stok_paket''in hizmet karşılığı (496).';

-- PAKET Mİ? Kart ekranı "İçerik" sekmesini yalnız içeriği olan ya da
--   içerik eklenebilen hizmette gösterir; liste ekranı da bu bayrakla
--   panelleri süzer. Ayrı bir kolon yerine türetilmiş görünüm: içerik
--   satırı silinince bayrak da kendiliğinden düşer.
create or replace view public.v_hizmet_paket_ozet as
select p.paket_hizmet_id           as hizmet_id,
       count(*)::integer           as icerik_sayisi,
       sum(p.adet)                 as toplam_adet
  from public.hizmet_paket p
 group by p.paket_hizmet_id;
