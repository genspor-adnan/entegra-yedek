\set ON_ERROR_STOP on

-- ------------------------------------------------------------ teklif (18) ---
insert into public.kasa_islem_turu
    (kod, ad, grup, yon, cari_zorunlu, kalem_turu, plan_mi,
     cari_ekstre, hesap_ekstre, bakiye_dahil, fis_mi, fis_turu,
     makbuz_seri, sira, aktif, stok_etkiler, cari_etkiler)
select 18, 'Satış Teklifi', 'belge', 0, 1, 0, 0,
       0, 0, 0, 0, 1,
       'T', 955, 1, 0, 0
 where not exists (select 1 from public.kasa_islem_turu where kod = 18);

-- ---------------------------------------------------------------- demirbas --
create table if not exists public.demirbas (
    id                integer generated by default as identity primary key,
    kod               varchar(40)  not null default '',
    ad                varchar(200) not null,
    kategori          smallint     not null default 0,   -- kod_liste demirbas.kategori
    durum             smallint     not null default 1,   -- 1 Aktif / 0 Pasif
    marka             varchar(80)  not null default '',
    model             varchar(80)  not null default '',
    seri_no           varchar(60)  not null default '',
    barkod            varchar(40)  not null default '',
    model_yili        smallint,
    lokasyon          smallint     not null default 0,   -- kod_liste demirbas.lokasyon
    zimmet_taraf_id   integer      references public.taraf(id),
    sube_id           integer      not null default 1,
    alis_tarihi       date,
    tedarikci_id      integer      references public.taraf(id),
    alis_tutari       numeric(18,2) not null default 0,
    garanti_bitis     date,
    aciklama          varchar(400) not null default '',
    ekleyen           integer      not null default 0,
    ekleme_tarihi     timestamp    not null default now()::timestamp,
    degistiren        integer      not null default 0,
    degistirme_tarihi timestamp
);

comment on table public.demirbas is
  'Demirbas karti (216, Ekranlar/demirbas_karti.html). Zimmet/bakim/amortisman '
  'detaylari ileride; islem_log tablo_id 925.';

create unique index if not exists ux_demirbas_kod
    on public.demirbas (kod) where kod <> '';
create index if not exists ix_demirbas_zimmet
    on public.demirbas (zimmet_taraf_id) where zimmet_taraf_id is not null;

drop trigger if exists trg_demirbas_degistirme on public.demirbas;
create trigger trg_demirbas_degistirme
    before update on public.demirbas
    for each row execute function public.fn_degistirme_tarihi();

-- ------------------------------------------------------------ kod listeleri --
insert into public.kod_liste (kod, ad)
select v.kod, v.ad
  from (values ('demirbas.kategori', 'Demirbaş Kategorisi'),
               ('demirbas.lokasyon', 'Demirbaş Lokasyonu')) as v(kod, ad)
 where not exists (select 1 from public.kod_liste l where l.kod = v.kod);

-- Oneri degerler - kullanici Kod Listeleri'nden kendininkileri ekler.
insert into public.kod_deger (liste_id, deger, ad, sira, aktif)
select l.id, v.deger, v.ad, v.sira, 1
  from (values
        ('demirbas.kategori', 1, 'Bilgisayar / BT',  10),
        ('demirbas.kategori', 2, 'Tıbbi Cihaz',      20),
        ('demirbas.kategori', 3, 'Mobilya',          30),
        ('demirbas.kategori', 4, 'Araç',             40),
        ('demirbas.kategori', 5, 'Diğer',            50),
        ('demirbas.lokasyon', 1, 'Merkez',           10),
        ('demirbas.lokasyon', 2, 'Depo',             20),
        ('demirbas.lokasyon', 3, 'Poliklinik',       30),
        ('demirbas.lokasyon', 4, 'Laboratuvar',      40),
        ('demirbas.lokasyon', 5, 'Saha / Dışarıda',  50)
       ) as v(liste, deger, ad, sira)
  join public.kod_liste l on l.kod = v.liste
 where not exists (select 1 from public.kod_deger d
                    where d.liste_id = l.id and d.deger = v.deger);

-- ----------------------------------------------------------------- yetki ----
insert into public.yetki (kod, ad, grup, tur, sira) values
    ('demirbas', 'Demirbaş', 'genel', 0, 60)
on conflict (kod) do nothing;

insert into public.rol_yetki (rol_id, yetki_id, gor, ekle, degistir, sil)
select r.id, y.id, 1, 1, 1, 1
  from public.rol r cross join public.yetki y
 where r.kod = 'yonetici' and y.kod = 'demirbas'
on conflict (rol_id, yetki_id) do update
   set gor = 1, ekle = 1, degistir = 1, sil = 1;

insert into public.rol_yetki (rol_id, yetki_id, gor)
select r.id, y.id, 1
  from public.rol r cross join public.yetki y
 where r.kod = 'salt_okur' and y.kod = 'demirbas'
on conflict (rol_id, yetki_id) do nothing;

do $$
declare v_tur integer; v_tablo integer;
begin
    select count(*) into v_tur from public.kasa_islem_turu where kod = 18;
    select count(*) into v_tablo from information_schema.tables
     where table_schema = 'public' and table_name = 'demirbas';
    raise notice '216 tamam: Satis Teklifi turu (%), demirbas tablosu (%), kod listeleri + demirbas yetkisi.',
        v_tur, v_tablo;
end $$;
