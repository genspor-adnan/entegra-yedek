--  mockuplarina gore, ilk surum = liste + kart + ekle/sil/degistir):
--
--  1. SATIS TEKLIFI = yeni BELGE TURU 18. Teklif bir taahhut degildir:
--     stok/cari/fis ETKILEMEZ (siparis 19 ile ayni profil), fiyat listesi
--     cozumu satis yonunden calisir (fn_belge_yon alis listesinde degil).
--     Kalem/toplam/cari altyapisi belgeden hazir gelir. Mockup'taki
--     revizyon/onay akisi ILERIDE.
--
--  2. DEMIRBAS = yeni kart tablosu. Mockup'in kimlik/satin alma cekirdegi;
--     zimmet/bakim/amortisman detay gridleri ILERIDE (yer tutucu sekmeler).
