--  Kullanici: "Seri Bilgileri saginda XSLT sekmesi olustur ve grid bilgilerini
--  BILIM'den tasi."
--
--  NE ISE YARAR: e-Belge, GIB'e XML olarak gider; insanin okudugu goruntu
--    (fatura gorseli) o XML'e XSLT sablonu uygulanarak uretilir. Gonderimde
--    sablon XML'in icine GOMULU gider - alici belgeyi bizim tasarimimizla gorur.
--
--  KAYNAK: BILIM.dbo.DOKUMLER, GRUBU = 'XSLT'. Orada belge turu ve yon tek
--    kolonda (RAPORID) kodlanmisti:
--       1 e-Fatura gelen · 2 e-Fatura giden
--      11 e-Arsiv gelen  · 12 e-Arsiv giden
--      51 e-Irsaliye gelen · 52 e-Irsaliye giden
--    Burada IKI kolona ayrildi (belge_turu + yon) - "gelen e-Arsiv" gibi bir
--    kombinasyon aramak icin kod ezberlemek gerekmesin.
--
--  ICERIK BU DOSYADA DEGIL: sablonlar 106 KB - 1,3 MB arasi (toplam ~3,5 MB).
--    Migration'a gomulseler depo sisirdi ve her yayinda tekrar tasinirlardi.
--    Iceriklerini `db/araclar/xslt_aktar.ps1` MSSQL'den okuyup buraya yazar.
-- ============================================================================
\set ON_ERROR_STOP on

create table if not exists public.ebelge_xslt (
    id                   integer generated by default as identity primary key,
    -- 1 e-Fatura · 2 e-Arsiv · 7 e-Irsaliye · 8 e-SMM (156 ile ayni kodlar).
    belge_turu           smallint     not null,
    -- 1 gelen (bize gelen belgeyi goruntulerken) · 2 giden (bizim kestigimiz).
    yon                  smallint     not null default 2,
    ad                   varchar(120) not null,
    -- XSLT'nin kendisi. Bos olabilir: once tanim gelir, icerik sonra yuklenir.
    icerik               text         not null default '',
    -- Bu tur+yon icin SECILI sablon. Ayni ikili icin tek satir 1 olabilir.
    varsayilan           smallint     not null default 0,
    durum                smallint     not null default 1,   -- 1 aktif, 0 pasif
    aciklama             varchar(200) not null default '',
    -- BILIM'deki DOKUMLER.ID - aktarim tekrar calisinca ayni satiri bulsun.
    kaynak_id            integer      not null default 0,
    ekleyen              integer      not null default 0,
    ekleme_tarihi        timestamp    not null default now()::timestamp,
    degistiren           integer      not null default 0,
    degistirme_tarihi    timestamp    null
);

comment on table public.ebelge_xslt is
  'e-Belge goruntuleme sablonlari (159). BILIM.DOKUMLER GRUBU=XSLT karsiligi; gonderimde XML icine gomulur.';
comment on column public.ebelge_xslt.icerik is
  'XSLT metni. Buyuk (100 KB - 1,3 MB); liste sorgularinda SECILMEZ.';
comment on column public.ebelge_xslt.varsayilan is
  'Bu belge turu + yon icin secili sablon. Kismi tekil indeks tek satirla sinirlar.';

create unique index if not exists ux_ebelge_xslt_kaynak
    on public.ebelge_xslt (kaynak_id) where kaynak_id > 0;
-- Bir tur+yon icin YALNIZ BIR varsayilan: ikisi birden secili kalirsa hangi
--   sablonun gonderildigi belirsizlesir.
create unique index if not exists ux_ebelge_xslt_varsayilan
    on public.ebelge_xslt (belge_turu, yon) where varsayilan = 1;
create index if not exists ix_ebelge_xslt_tur on public.ebelge_xslt (belge_turu, yon, durum);

drop trigger if exists tr_ebelge_xslt_degistirme on public.ebelge_xslt;
create trigger tr_ebelge_xslt_degistirme
    before update on public.ebelge_xslt
    for each row execute function public.fn_degistirme_tarihi();

-- ------------------------------------------------------- secim listeleri ----
create or replace view public.v_ebelge_yon_lookup as
    select 1 as id, 'Gelen'::varchar as ad, 1 as aktif
    union all select 2, 'Giden', 1;

comment on view public.v_ebelge_yon_lookup is
  'XSLT sablonunun yonu: gelen belge goruntuleme / giden belge (159).';

-- --------------------------------------------------- gecerli sablon bul -----
create or replace function public.fn_ebelge_xslt_bul(p_belge_turu integer, p_yon integer)
returns integer
language sql stable as $$
    select x.id
      from public.ebelge_xslt x
     where x.belge_turu = p_belge_turu and x.yon = coalesce(p_yon, 2) and x.durum = 1
     order by x.varsayilan desc, x.id
     limit 1
$$;

comment on function public.fn_ebelge_xslt_bul(integer, integer) is
  'Belge turu + yon icin kullanilacak XSLT sablonunun kimligi; varsayilan yoksa ilk aktif satir (159).';

