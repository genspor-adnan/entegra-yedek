\set ON_ERROR_STOP on

create table if not exists public.parola_gecmisi (
    id            integer      generated by default as identity primary key,
    kullanici_id  integer      not null references public.taraf_kullanici(id) on delete cascade,
    parola_hash   varchar(100) not null,
    tarih         timestamp    not null default now()
);
create index if not exists ix_parola_gecmisi_kullanici on public.parola_gecmisi(kullanici_id, tarih desc);

