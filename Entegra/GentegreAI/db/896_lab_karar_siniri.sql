-- =====================================================================
--  896_lab_karar_siniri.sql
--  KARAR SINIRI (CLINICAL DECISION LIMIT) VE SEMBOLÜ
--  (KTS denetim maddesi L15: "Karar sınırının altında/üstünde olduğunu
--   gösteren sembol var mı?")
--
--  BUGÜN NE VAR: `fn_lab_bayrak` referans aralığına göre L / H / LL / HH
--  üretiyor; ekran ve rapor bunu ↓ ↑ ↓↓ ↑↑ sembolleriyle gösteriyor.
--  Sembolün kendisi tamam.
--
--  EKSİK OLAN, KAVRAMIN KENDİSİ: KARAR SINIRI REFERANS ARALIĞI DEĞİLDİR.
--    * Referans aralığı SAĞLIKLI POPÜLASYONUN dağılımıdır ("bu değer
--      olağan mı").
--    * Karar sınırı KILAVUZUN eşiğidir ("bu değerde ne yapmak gerekir"):
--      LDL için hedef < 100 mg/dL, HbA1c ≥ %6,5 diyabet tanısı, eGFR < 60
--      evre 3 böbrek hastalığı, troponin için 99. persentil.
--
--  İkisi aynı testte BİRBİRİNDEN FARKLI cevap verir: LDL 115 mg/dL
--  referans aralığında "normal" görünür ama koroner riskli hastada hedefin
--  ÜSTÜNDEDİR. Bugün rapor "N" yazıyor; hekimin gördüğü tek şey normal
--  işareti oluyor.
--
--  TASARIM:
--    * Sınırlar tetkike bağlı, YÖNLÜ (altında olmalı / üstünde olmalı) ve
--      DAYANAKLI (hangi kılavuz) tanımlanır; yaş/cinsiyet bandı isteğe
--      bağlıdır (eGFR ve ferritin gibi).
--    * Değerlendirme SONUCA DONAR (`lab_sonuc.karar_notu`): kılavuz
--      sonradan değişse bile eski rapor kendi eşiğiyle okunur - referans
--      aralığında (888) verdiğimiz kararın aynısı.
--    * Karar sınırı BAYRAĞI EZMEZ. Ayrı bir bilgidir: "referans aralığında
--      ama hedefin üstünde" ikisinin birden söylenmesiyle anlaşılır.
--      Bayrağı değiştirmek, panik/anormal sayımlarını da bozardı.
--    * SINIR TOHUMLANMAZ: hangi kılavuzun hangi eşiği kullanılacağı kurumun
--      kararıdır (ATP III mü, ESC 2019 mu). Uydurulmuş eşik, hekime yanlış
--      hedef gösterir.
-- =====================================================================

create table if not exists public.lab_karar_siniri (
  id          integer generated by default as identity primary key,
  tetkik_id   integer not null references public.lab_tetkik(id) on delete cascade,
  ad          varchar(80)  not null,             -- "Hedef LDL", "Diyabet eşiği"
  -- 1 bu değerin ALTINDA olmalı (hedef) · 2 ÜSTÜNDE olmalı (koruyucu düzey)
  yon         smallint     not null default 1,
  deger       numeric(19,6) not null,
  -- Boş = herkes. eGFR ve ferritin gibi testlerde yaş/cinsiyet ayrımı şart.
  cinsiyet    smallint     not null default 0,
  yas_alt_gun integer      not null default 0,
  yas_ust_gun integer      not null default 54750,
  dayanak     varchar(120) not null default '',  -- "ESC/EAS 2019", "ADA 2024"
  mesaj       varchar(200) not null default '',  -- boşsa metin üretilir
  sira        smallint     not null default 0,
  aktif       smallint     not null default 1,
  ekleyen     integer      not null default 0,
  ekleme_tarihi timestamptz not null default now(),
  degistiren  integer      not null default 0,
  degistirme_tarihi timestamptz,
  constraint ck_lab_karar_yon check (yon in (1, 2))
);

create index if not exists ix_lab_karar_siniri_tetkik
  on public.lab_karar_siniri (tetkik_id, sira) where aktif = 1;

comment on table public.lab_karar_siniri is
  '896: klinik KARAR SINIRI (KTS L15) - referans araligi degildir. yon 1 '
  'bu degerin ALTINDA olmali (hedef), 2 USTUNDE olmali. Dayanak = kilavuz.';

alter table public.lab_sonuc
  add column if not exists karar_notu varchar(200) not null default '';

comment on column public.lab_sonuc.karar_notu is
  '896: karar sinirlarina gore degerlendirme, sonuca DONAR (kilavuz degisse '
  'bile eski rapor kendi esigiyle okunur). Bos = sinir tanimli degil ya da '
  'deger hedefte.';

/**
 * KARAR SINIRI DEĞERLENDİRMESİ.
 *
 * Hastanın yaş/cinsiyetine uyan AKTİF sınırları sırayla değerlendirir ve
 * yalnız DIŞINDA kalınanları metne döker: "Hedefin üstünde: LDL < 100 mg/dL
 * (ESC/EAS 2019)". Hepsi hedefteyse boş döner - "hedefte" bilgisini her
 * satıra yazmak raporu gürültüye boğardı.
 *
 * <b>Bayrağı EZMEZ</b>: ayrı bilgidir, birlikte okunur.
 */
create or replace function public.fn_lab_karar_notu(p_tetkik_id integer,
                                                    p_hasta_id  integer,
                                                    p_deger     numeric)
returns varchar language plpgsql stable as $fn$
declare
    v_cinsiyet smallint := 0;
    v_yas_gun  integer  := 6570;      -- doğum tarihi yoksa erişkin
    v_parca    text[]   := '{}';
    r          record;
begin
    if p_deger is null then return ''; end if;

    select coalesce(h.cinsiyet, 0),
           coalesce((current_date - h.dogum_tarihi::date), 6570)
      into v_cinsiyet, v_yas_gun
      from public.taraf_hasta h where h.id = p_hasta_id;

    for r in
        select k.* from public.lab_karar_siniri k
         where k.tetkik_id = p_tetkik_id and k.aktif = 1
           and (k.cinsiyet = 0 or k.cinsiyet = coalesce(v_cinsiyet, 0))
           and coalesce(v_yas_gun, 6570) between k.yas_alt_gun and k.yas_ust_gun
         order by k.sira, k.id
    loop
        -- YÖN 1: değer bu sınırın ALTINDA olmalı; üstündeyse uyarılır.
        -- YÖN 2: ÜSTÜNDE olmalı; altındaysa uyarılır.
        if (r.yon = 1 and p_deger > r.deger) or (r.yon = 2 and p_deger < r.deger) then
            v_parca := v_parca || (
                case when coalesce(nullif(r.mesaj, ''), '') <> '' then r.mesaj
                     else (case r.yon when 1 then 'Hedefin üstünde: '
                                      else 'Hedefin altında: ' end)
                          || r.ad || ' '
                          || (case r.yon when 1 then '< ' else '> ' end)
                          || public.fn_lab_sayi_metni(r.deger)
                          || case when coalesce(r.dayanak, '') = '' then ''
                                  else ' (' || r.dayanak || ')' end
                end);
        end if;
    end loop;

    return left(array_to_string(v_parca, ' · '), 200);
end $fn$;

comment on function public.fn_lab_karar_notu(integer, integer, numeric) is
  '896: karar sinirlarina gore metin (KTS L15). Yalniz DISINDA kalinan '
  'sinirlar yazilir; hepsi hedefteyse bos doner. Bayragi ezmez.';

-- Denetim dökümü: hangi testte karar sınırı tanımlı.
create or replace view public.v_lab_karar_siniri as
select k.id, k.tetkik_id, t.kod, t.ad as tetkik, t.birim,
       k.ad, k.yon, k.deger, k.cinsiyet, k.yas_alt_gun, k.yas_ust_gun,
       k.dayanak, k.mesaj, k.sira, k.aktif,
       public.fn_lab_referans_kime(k.cinsiyet, k.yas_alt_gun, k.yas_ust_gun, 0::smallint) as kime
  from public.lab_karar_siniri k
  join public.lab_tetkik t on t.id = k.tetkik_id;

comment on view public.v_lab_karar_siniri is
  '896: karar sinirlari - tetkik, yon, esik, kime (yas/cinsiyet) ve dayanak.';

-- -------------------------------------------------------------- yetki ----
insert into public.yetki (kod, ad, grup, tur, sira, aktif, urun_modu, modul)
select 'lab.karar_siniri', 'Klinik karar sınırları (tanım)', 'Laboratuvar',
       0, 56, 1, 2, 'lab'
 where not exists (select 1 from public.yetki y where y.kod = 'lab.karar_siniri');

insert into public.rol_yetki (rol_id, yetki_id, gor, ekle, degistir, sil, ekleyen)
select r.id, y.id, 1, 1, 1, 1, 0
  from public.rol r cross join public.yetki y
 where r.kod = 'yonetici' and y.kod = 'lab.karar_siniri'
   and not exists (select 1 from public.rol_yetki ry
                    where ry.rol_id = r.id and ry.yetki_id = y.id);
update public.rol set yetki_surumu = yetki_surumu + 1 where kod = 'yonetici';

