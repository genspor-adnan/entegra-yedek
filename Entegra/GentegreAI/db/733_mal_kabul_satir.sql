comment on column public.satinalma_kabul.soguk_zincir is
  '733: sevkiyat soguk zincir gerektiriyor mu (0 hayir - 1 evet).';
comment on column public.satinalma_kabul.soguk_zincir_uygun is
  '733: 0 bilinmiyor - 1 uygun - 2 uygunsuz. Uygunsuz sevkiyat kabul '
  'edilebilir ama tutanaga YAZILIR; karar komisyonun.';

-- ==================================================== kabul satırları
create table if not exists public.satinalma_kabul_satir (
    id             bigint generated by default as identity primary key,
    kabul_id       bigint not null references public.satinalma_kabul(id) on delete cascade,
    sira           smallint not null default 0,
    stok_id        integer references public.stok(id),
    ad             varchar(200) not null default '',
    birim          varchar(20)  not null default '',

    -- ÜÇ MİKTAR (bkz. başlık). `sayilan` muayenede fiilen sayılan.
    siparis_miktar numeric(18,3) not null default 0,
    irsaliye_miktar numeric(18,3) not null default 0,
    sayilan        numeric(18,3) not null default 0,
    birim_fiyat    numeric(18,4) not null default 0,

    -- LOT ve MİAD kalem başına: aynı kalem iki lot hâlinde gelebilir ve
    --   miadı kısa olan kabul edilmeyebilir (sözleşmedeki asgari raf ömrü).
    lot            varchar(60) not null default '',
    skt            date,
    -- RAF ÖMRÜ KOLON DEĞİL: "bugünden kaç gün" üretilmiş kolon olamaz
    --   (`current_date` immutable değil) ve olsaydı da yanlış olurdu -
    --   satırın yazıldığı gün dondurulmuş bir "kalan gün" ertesi gün
    --   yalan söylerdi. Liste SQL'inde `skt - current_date` olarak hesaplanır.

    -- 0 bekliyor · 1 kabul · 2 kısmi kabul · 3 ret
    sonuc          smallint not null default 0,
    uygunsuzluk    varchar(300) not null default '',
    -- İRSALİYE SATIRI BAĞI: hangi satırın muayenesi olduğu. NO ACTION -
    --   `KorunanSatirSql` bu satırı korur, yoksa irsaliye yeniden
    --   kaydedilince bağ kopar ve muayene sahipsiz kalırdı.
    belge_satir_id bigint references public.belge_satir(id),
    aciklama       varchar(300) not null default '',
    ekleyen        integer not null default 0,
    ekleme_tarihi  timestamptz not null default now(),
    degistiren     integer not null default 0,
    degistirme_tarihi timestamptz
);

comment on table public.satinalma_kabul_satir is
  '733: mal kabul muayene satiri. Uc miktar (siparis / irsaliye / sayilan) '
  'ayri tutulur - hangi farkin kime ait oldugu ancak ucu birden yazilirsa '
  'anlasilir. Stoga girisi IRSALIYE yapar, bu tablo muayeneyi yazar.';

create index if not exists ix_satinalma_kabul_satir_ust
  on public.satinalma_kabul_satir (kabul_id, sira);
-- Belge satiri bagi ARANIR (KorunanSatirSql her belge kaydinda sorar).
create index if not exists ix_satinalma_kabul_satir_belge
  on public.satinalma_kabul_satir (belge_satir_id) where belge_satir_id is not null;
create index if not exists ix_satinalma_kabul_satir_stok
  on public.satinalma_kabul_satir (stok_id) where stok_id is not null;

-- ============================================ başlık sonucu satırlardan
-- TUTANAĞIN SONUCU SATIRLARDAN TÜRER: bir satır bile reddedilmişse tutanak
--   "tam kabul" olamaz. Elle seçilebilir bırakıp satırlarla çelişmesine izin
--   verseydik, tutanak kendi satırlarını yalanlardı.
--
--   Karar YÖNÜ TEK TARAFLI: satırlar başlığı aşağı çeker, yukarı çekmez -
--   komisyon "hepsi kabul" satırlarıyla tutanağı yine de reddedebilir
--   (belge eksikliği, sözleşme ihlali gibi kalem dışı sebepler).
create or replace function public.fn_satinalma_kabul_sonuc()
returns trigger language plpgsql as $tg$
declare
  v_kabul bigint := coalesce(new.kabul_id, old.kabul_id);
  v_ret   integer;
  v_kismi integer;
  v_var   integer;
  v_mevcut smallint;
begin
    select count(*) filter (where sonuc = 3),
           count(*) filter (where sonuc = 2),
           count(*)
      into v_ret, v_kismi, v_var
      from public.satinalma_kabul_satir where kabul_id = v_kabul;

    if v_var = 0 then return coalesce(new, old); end if;

    select sonuc into v_mevcut from public.satinalma_kabul where id = v_kabul;

    update public.satinalma_kabul
       set sonuc = case
                     when v_ret = v_var then 3                 -- hepsi ret
                     when v_ret > 0 or v_kismi > 0 then 2      -- kısmi
                     else greatest(coalesce(v_mevcut, 0), 1)   -- tam kabul
                   end
     where id = v_kabul
       -- Komisyonun REDDİNE dokunma (tek taraflılık, bkz. yukarı).
       and coalesce(sonuc, 0) <> 3;

    return coalesce(new, old);
end;
$tg$;

drop trigger if exists tg_satinalma_kabul_sonuc on public.satinalma_kabul_satir;
create trigger tg_satinalma_kabul_sonuc
  after insert or update of sonuc or delete
  on public.satinalma_kabul_satir
  for each row execute function public.fn_satinalma_kabul_sonuc();

-- =============================================== liste için özet görünüm
-- Grid "kaç kalem, kaç eksik, kaç ret" sorusunu satır saymadan yanıtlasın.
create or replace view public.v_satinalma_kabul as
select k.*,
       (select count(*) from public.satinalma_kabul_satir s where s.kabul_id = k.id) as kalem,
       (select count(*) from public.satinalma_kabul_satir s
         where s.kabul_id = k.id and s.sonuc = 3) as ret_kalem,
       (select count(*) from public.satinalma_kabul_satir s
         where s.kabul_id = k.id and s.sayilan < s.irsaliye_miktar) as eksik_kalem,
       -- ASGARİ RAF ÖMRÜ SÖZLEŞMEDEN: miadına üç ay kalmış ilaç teslim
       --   edilirse hastane imhayı da satın almış olur. Sözleşme yoksa
       --   kıyas yapılmaz (0 döner) - uydurulmuş bir eşik kimseyi korumaz.
       (select count(*) from public.satinalma_kabul_satir s
          join public.belge b on b.id = k.siparis_belge_id
          join public.belge_satinalma bs on bs.id = b.id
          join public.tedarikci_sozlesme z on z.id = bs.sozlesme_id
         where s.kabul_id = k.id and s.skt is not null
           and coalesce(z.asgari_raf_omru_ay, 0) > 0
           and s.skt < (current_date + (z.asgari_raf_omru_ay || ' months')::interval)) as kisa_miad,
       -- REDDEDİLEN KALEM TUTARA GİRMEZ: "kabul tutarı" ödenecek olandır.
       --   Reddedilen malı da saysaydık tutanak, geri gönderilen malın
       --   parasını kabul etmiş görünürdü ve fatura eşleştirmesi bu sayıyı
       --   taban alırdı.
       (select coalesce(sum(s.sayilan * s.birim_fiyat) filter (where s.sonuc <> 3), 0)
          from public.satinalma_kabul_satir s where s.kabul_id = k.id) as kabul_tutar
  from public.satinalma_kabul k;

comment on view public.v_satinalma_kabul is
  '733: mal kabul listesi - kalem/eksik/ret sayilari ve kisa miadli kalem. '
  'Asgari raf omru SOZLESMEDEN gelir; sozlesme yoksa kiyas yapilmaz.';
