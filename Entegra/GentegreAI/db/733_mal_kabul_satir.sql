-- =====================================================================
--  733_mal_kabul_satir.sql
--  MAL KABUL: kalem bazlı muayene satırı + soğuk zincir kaydı.
--
--  Mockup: `Ekranlar/Satinalma/satinalma_kabul_fatura.html` (Kalem / Sipariş /
--  İrsaliye / Sayılan / Sonuç) ve `Ekranlar/Eczane/eczane_mal_kabul.html`.
--
--  ============= NEDEN SATIR TABLOSU (bayrak yetmiyor) ==================
--  724'te `satinalma_kabul` yalnız BAŞLIK olarak açılmıştı: komisyon, sonuç,
--  uygunsuzluk. "Kısmi kabul" bir bayraktı - hangi kalemin eksik geldiği,
--  kaç adet sayıldığı, hangi lotun hangi miadla girdiği yazılmıyordu.
--  Bayrakla kalsaydı tutanak "bir şey eksikti" demiş olurdu; muayene
--  tutanağının işi tam olarak NEYİN eksik olduğunu söylemektir.
--
--  ÜÇ MİKTAR AYRI TUTULUR: sipariş · irsaliye · SAYILAN. İkisi yetmez -
--    tedarikçi 100 sipariş edilene 90 irsaliye kesip 85 gönderebilir. Hangi
--    farkın kime ait olduğu (bize mi, taşımaya mı, tedarikçiye mi) ancak üçü
--    birden yazılırsa anlaşılır; fatura eşleştirmesi de bu farkı arıyor.
--
--  ============= STOĞA GİRİŞ BURADA OLMAZ ===============================
--  Malı stoğa alan şey İRSALİYEDİR (belge tür 10) - kaydedildiğinde belge
--  hattı stok hareketini yazar. Kabul tutanağı stok yazmaz, MUAYENEYİ yazar.
--  Tutanağa da stok girişi yaptırsaydık aynı mal iki kez girerdi.
--  "Kabul et ve stoğa al" düğmesi bu yüzden iki ayrı işin adı: irsaliye
--  kaydedilir (stok girer), sonra tutanak açılır (muayene kaydedilir).
--
--  ============= SOĞUK ZİNCİR BAŞLIKTA ==================================
--  Soğuk zincir ölçümü sevkiyatın TAMAMINA aittir (aracın/kutunun sıcaklığı),
--  kaleme değil. Satıra koysaydık aynı ölçüm on satıra kopyalanır ve biri
--  değişince hangisinin doğru olduğu sorulurdu.
-- =====================================================================

