-- 249: ANLAŞMALI KURUMLAR + SÖZLEŞME (kullanıcı: "hastanenin sözleşme yaptığı
-- kurumların listesi... bunlar da bir nevi müşteri, hastanın ödemesini
-- yapacak; başvuruda ödeyen kurum olarak bu listeden seçilecek; kurum kodu,
-- adı, sözleşme başlama/bitiş tarihi, durum, türü (kendi/ÖSS/SGK); bu kurumla
-- yapılan işlemler için fiyat politikası - şu kategoriden %20 indirim gibi
-- satırlar").
--
-- İSİMLENDİRME: satırların adı SÖZLEŞME. Sözleşme = belirli bir kurumla,
-- belirli bir tarih aralığında geçerli fiyat taahhüdü. Kampanya ise kuruma
-- bağlı OLMAYAN, herkese açık dönemsel indirimdir - ayrı bir kavram, ileride
-- ayrı tablo. Buradaki satırlar hep bir kuruma bağlı olduğu için "sözleşme".
--
-- Kurum AYRI BİR TABLO DEĞİL, taraf'ın bir rolü (musteri/tedarikci/personel/
-- hasta deseni): kurum da fatura edilen, tahsilat yapılan bir caridir. Kod ve
-- ad zaten taraf.kod / taraf.unvan'dır; burada yalnız sözleşme bilgisi durur.

alter table public.taraf add column if not exists kurum smallint not null default 0;
comment on column public.taraf.kurum is
  'Anlaşmalı kurum (ödeyen) rolü (249) - ÖSS, SGK, kurumsal müşteri.';

create index if not exists ix_taraf_kurum_rol on public.taraf (kurum) where kurum = 1;

-- ------------------------------------------------------- kurum sözleşmesi ---
create table if not exists public.taraf_kurum (
  id                integer  not null primary key references public.taraf(id) on delete cascade,
  tur               smallint not null default 3,      -- 1 Özel (kendi) / 2 ÖSS / 3 SGK
  sozlesme_no       varchar(40)  not null default '',
  baslangic         date,
  bitis             date,
  durum             smallint not null default 1,      -- 1 Aktif / 0 Pasif
  -- Kuruma özel baz fiyat listesi (opsiyonel): sözleşme satırındaki indirim
  --   bu listenin fiyatı üzerine uygulanır, yoksa normal satış fiyatı üzerine.
  fiyat_listesi_id  integer  references public.fiyat_listesi(id),
  -- Satır bazlı kural yoksa geçerli genel indirim.
  iskonto_yuzde     numeric(9,4) not null default 0,
  aciklama          varchar(300) not null default '',
  ekleyen           integer  not null default 0,
  ekleme_tarihi     timestamp not null default now()::timestamp,
  degistiren        integer  not null default 0,
  degistirme_tarihi timestamp
);

comment on table public.taraf_kurum is
  'Anlaşmalı kurumun sözleşme başlığı (249): tür, süre, durum, fiyat politikası kökü.';

-- ------------------------------------------------- sözleşme fiyat satırları --
-- "Şu kategoriden %20 indirim" satırları. Kapsam daraldıkça öncelik artar:
--   hizmet/stok satırı, kategori satırını; kategori satırı da "tümü"nü ezer.
create table if not exists public.kurum_sozlesme (
  id                integer generated by default as identity primary key,
  kurum_id          integer  not null references public.taraf(id) on delete cascade,
  kapsam            smallint not null default 1,      -- 1 Tümü / 2 Kategori / 3 Stok / 4 Hizmet
  kategori_id       integer  references public.kategori(id),
  stok_id           integer  references public.stok(id),
  hizmet_id         integer  references public.hizmet(id),
  indirim_yuzde     numeric(9,4) not null default 0,
  -- Sabit fiyat verilirse indirim yerine BU uygulanır (paket fiyat anlaşması).
  sabit_fiyat       numeric(24,6),
  -- Satırın kendi süresi; boşsa kurumun sözleşme süresi geçerlidir.
  baslangic         date,
  bitis             date,
  aktif             smallint not null default 1,
  aciklama          varchar(300) not null default '',
  ekleyen           integer  not null default 0,
  ekleme_tarihi     timestamp not null default now()::timestamp,
  degistiren        integer  not null default 0,
  degistirme_tarihi timestamp
);

comment on table public.kurum_sozlesme is
  'Kurum sözleşmesinin fiyat politikası satırları (249): kapsam + indirim/sabit fiyat.';

create index if not exists ix_kurum_sozlesme_kurum
  on public.kurum_sozlesme (kurum_id, aktif);
create index if not exists ix_kurum_sozlesme_kategori
  on public.kurum_sozlesme (kategori_id) where kategori_id is not null;

-- ------------------------------------------------------------- kod listesi ---
insert into public.kod_liste (kod, ad)
select 'kurum.sozlesme_kapsam', 'Sözleşme Kapsamı'
 where not exists (select 1 from public.kod_liste where kod = 'kurum.sozlesme_kapsam');

insert into public.kod_deger (liste_id, deger, ad, sira, aktif, ekleyen)
select l.id, v.deger, v.ad, v.deger * 10, 1, 0
  from public.kod_liste l
  cross join (values (1, 'Tümü'), (2, 'Kategori'), (3, 'Stok'),
                     (4, 'Hizmet')) as v(deger, ad)
 where l.kod = 'kurum.sozlesme_kapsam'
   and not exists (select 1 from public.kod_deger d where d.liste_id = l.id);

-- ------------------------------------------------------------------ lookup ---
-- Hasta poliçesindeki "Kurum / Sigorta" ve başvurudaki "Ödeyen Kurum" bu
--   görünümden seçilir - tüm cariler değil, YALNIZ anlaşmalı kurumlar.
create or replace view public.v_kurum_lookup as
select t.id, t.kod, t.unvan as ad, k.tur, k.durum
  from public.taraf t
  join public.taraf_kurum k on k.id = t.id
 where t.kurum = 1;

-- ------------------------------------------------------- başvuruda ödeyen ---
-- Ödeyen kurum belgeye YAZILIR (hastanın o günkü poliçesinden gelse de):
--   poliçe sonradan değişse bile geçmiş başvurunun kimden tahsil edildiği
--   sabit kalmalı.
alter table public.belge add column if not exists odeyen_kurum_id integer
  references public.taraf(id);
comment on column public.belge.odeyen_kurum_id is
  'Başvuruda ödemeyi üstlenen anlaşmalı kurum (249). Boşsa hasta kendi öder.';

create index if not exists ix_belge_odeyen_kurum
  on public.belge (odeyen_kurum_id) where odeyen_kurum_id is not null;

-- -------------------------------------------------------------------- yetki --
insert into public.yetki (kod, ad, grup, tur, sira, aktif)
select 'kurum', 'Anlaşmalı Kurumlar', 'kart', 0, 16, 1
 where not exists (select 1 from public.yetki where kod = 'kurum');

insert into public.rol_yetki (rol_id, yetki_id, gor, ekle, degistir, sil, ekleyen)
select r.id, y.id, 1, 1, 1, 1, 0
  from public.rol r cross join public.yetki y
 where r.kod = 'yonetici' and y.kod = 'kurum'
   and not exists (select 1 from public.rol_yetki x
                    where x.rol_id = r.id and x.yetki_id = y.id);
