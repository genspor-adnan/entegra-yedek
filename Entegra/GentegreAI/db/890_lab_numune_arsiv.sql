-- =====================================================================
--  890_lab_numune_arsiv.sql
--  NUMUNE ARŞİVİ: FİZİKSEL KONUM + SAKLAMA SÜRESİ + İMHA
--  (KTS denetim maddesi L13: "Offline ve yazılımsal numune arşivleme
--   yapılabiliyor mu?")
--
--  BUGÜN NE VAR: `lab_numune.saklama_yeri` SERBEST METİN (bir ekrandan
--  istemin bütün tüplerine aynı metin yazılıyor), `saklama_sicaklik`, hiç
--  kullanılmayan bir `imha_tarihi` kolonu ve zincir tablosu
--  (`lab_numune_hareket`, olay kodları 433'te: 6 saklamaya · 2 taşındı ·
--  8 imha). Yani "buzdolabı 2" yazılabiliyor ama TÜPÜN HANGİ KUTUNUN HANGİ
--  GÖZÜNDE olduğu, ne kadar saklanacağı ve ne zaman imha edileceği yok.
--
--  DENETİMİN SORDUĞU İKİ ŞEY:
--    * OFFLINE arşivleme = fiziksel arşiv: ünite > raf > kutu > göz. Tekrar
--      çalışma ya da itiraz geldiğinde tüp BULUNABİLMELİ; "buzdolabı 2"
--      yazısı 600 tüpün içinde bir tüpü bulmaya yetmez.
--    * YAZILIMSAL arşivleme = kaydın kendisi: ne zaman kondu, kim koydu, ne
--      kadar saklanacak, ne zaman/kim/niçin çıkardı, imha edildi mi.
--
--  TASARIM KARARLARI:
--
--  1. KONUM AĞACI, TEK TABLO. Ünite (derin dondurucu/buzdolabı), raf ve kutu
--     aynı tabloda `ust_id` ile bağlanır - üç ayrı tablo aynı sorguyu üç kez
--     yazdırırdı. Göz AYRI KAYIT DEĞİL: kutunun satır × sütun ızgarası
--     yeterli, 81 gözlü kutu için 81 satır açmak boş yere veri üretirdi.
--
--  2. BİR GÖZDE BİR TÜP, BİR TÜP BİR YERDE. İkisi de kısmi benzersiz index
--     ile - "arşivde" durumundaki kayıtlar için. Çıkmış/imha edilmiş kayıt
--     TARİHTİR, silinmez: numunenin nerede beklediği denetimde sorulur.
--
--  3. SAKLAMA SÜRESİ POLİTİKADAN. Tetkike özel kural genel kuralı ezer
--     (moleküler numune ile rutin biyokimya tüpü aynı süre saklanmaz).
--     Politika yoksa süre boş kalır ve imha hedefi yazılmaz - uydurulmuş bir
--     tarih, gerçekten saklanması gereken numuneyi erken imha ettirirdi.
--
--  4. ZİNCİRE YAZAR. Arşive koyma/çıkarma/imha `lab_numune_hareket`e 433'ün
--     KENDİ kodlarıyla düşer (6 saklamaya · 2 taşındı · 8 imha); yeni kod
--     uydurulmadı, zincir tek yerden okunmaya devam etsin.
-- =====================================================================

-- ------------------------------------------------------------- konum ----
create table if not exists public.lab_arsiv_konum (
  id        integer generated by default as identity primary key,
  ust_id    integer references public.lab_arsiv_konum(id),
  -- 1 ünite (dolap/derin dondurucu) · 2 raf · 3 kutu
  tur       smallint     not null default 3,
  kod       varchar(20)  not null,
  ad        varchar(80)  not null,
  sicaklik  smallint,                       -- hedef °C (-80, -20, 4 ...)
  satir     smallint     not null default 0,  -- kutu ızgarası
  sutun     smallint     not null default 0,
  aciklama  varchar(200) not null default '',
  sube_id   integer      not null default 0,
  aktif     smallint     not null default 1,
  ekleyen   integer      not null default 0,
  ekleme_tarihi timestamptz not null default now(),
  degistiren integer     not null default 0,
  degistirme_tarihi timestamptz,
  constraint ck_lab_arsiv_konum_tur check (tur in (1, 2, 3)),
  -- KUTUNUN IZGARASI OLMAK ZORUNDA: gözü olmayan kutuya tüp
  --   yerleştirilemez, "kutu" demek zaten gözlü demektir.
  constraint ck_lab_arsiv_konum_izgara
    check (tur <> 3 or (satir > 0 and sutun > 0))
);

create unique index if not exists ux_lab_arsiv_konum_kod
  on public.lab_arsiv_konum (upper(kod));
create index if not exists ix_lab_arsiv_konum_ust
  on public.lab_arsiv_konum (ust_id);

comment on table public.lab_arsiv_konum is
  '890: numune arsivi konum agaci - unite > raf > kutu (ust_id). Goz ayri '
  'kayit degil, kutunun satir x sutun izgarasi.';

-- -------------------------------------------------- saklama politikasi ----
create table if not exists public.lab_saklama_politika (
  id          integer generated by default as identity primary key,
  -- Boş (null) = "hepsi". Tetkike özel kural genel kuralı EZER.
  tetkik_id   integer references public.lab_tetkik(id) on delete cascade,
  numune_tipi smallint,
  gun         integer      not null,
  sicaklik    smallint,
  dayanak     varchar(120) not null default '',   -- SKS/ISO maddesi, kurum kararı
  aciklama    varchar(200) not null default '',
  aktif       smallint     not null default 1,
  ekleyen     integer      not null default 0,
  ekleme_tarihi timestamptz not null default now(),
  degistiren  integer      not null default 0,
  degistirme_tarihi timestamptz,
  constraint ck_lab_saklama_gun check (gun >= 0)
);

create unique index if not exists ux_lab_saklama_politika
  on public.lab_saklama_politika (coalesce(tetkik_id, 0), coalesce(numune_tipi, -1));

comment on table public.lab_saklama_politika is
  '890: numune saklama suresi. tetkik_id/numune_tipi bos = hepsi; EN DAR '
  'kural kazanir (tetkik > numune tipi > genel). Kural yoksa sure yazilmaz.';

-- ------------------------------------------------------ arsiv kaydi ----
create table if not exists public.lab_numune_arsiv (
  id            integer generated by default as identity primary key,
  numune_id     integer not null references public.lab_numune(id) on delete cascade,
  konum_id      integer not null references public.lab_arsiv_konum(id),
  goz           varchar(10)  not null default '',   -- 'A5' - kutu ızgarasında
  giris_zamani  timestamptz  not null default now(),
  giris_id      integer      not null default 0,
  saklama_gun   integer,
  imha_hedef    date,
  cikis_zamani  timestamptz,
  cikis_id      integer,
  -- 1 tekrar çalışma · 2 dış laboratuvara · 3 imha · 4 devir/iade
  cikis_neden   smallint,
  not_metni     varchar(200) not null default '',
  -- 1 arşivde · 2 çıkarıldı · 3 imha edildi
  durum         smallint     not null default 1,
  sube_id       integer      not null default 0,
  constraint ck_lab_numune_arsiv_durum check (durum in (1, 2, 3))
);

-- BİR GÖZDE BİR TÜP: aynı göze ikinci tüp konulamaz - ızgara kaydı,
--   gerçekte olmayan bir yerleşimi anlatamamalı.
create unique index if not exists ux_lab_numune_arsiv_goz
  on public.lab_numune_arsiv (konum_id, upper(goz))
  where durum = 1 and goz <> '';
-- BİR TÜP BİR YERDE: aynı numune iki kutuda görünemez.
create unique index if not exists ux_lab_numune_arsiv_numune
  on public.lab_numune_arsiv (numune_id) where durum = 1;
create index if not exists ix_lab_numune_arsiv_imha
  on public.lab_numune_arsiv (imha_hedef) where durum = 1;

comment on table public.lab_numune_arsiv is
  '890: numunenin arsiv kaydi (nerede, ne zaman kondu, ne zaman imha '
  'edilecek, kim nicin cikardi). Cikmis/imha kayit TARIHTIR, silinmez.';

-- ------------------------------------------------------------ yollar ----
/** Konumun okunur yolu: "Derin dondurucu A / Raf 2 / Kutu 7". */
create or replace function public.fn_lab_arsiv_yol(p_konum_id integer)
returns varchar language sql stable as $$
    with recursive yukari as (
        select k.id, k.ust_id, k.ad, 1 as derinlik
          from public.lab_arsiv_konum k where k.id = p_konum_id
        union all
        select u.id, u.ust_id, u.ad, y.derinlik + 1
          from public.lab_arsiv_konum u
          join yukari y on y.ust_id = u.id
    )
    select string_agg(ad, ' / ' order by derinlik desc)::varchar from yukari;
$$;

/**
 * SAKLAMA SÜRESİ: en dar politika kazanır (tetkik > numune tipi > genel).
 *
 * Numunenin tetkikleri birden çok olabilir; EN UZUN süre geçerlidir - bir
 * tüp, üzerindeki en uzun saklanması gereken teste göre saklanır, yoksa
 * daha kısa kuralla erken imha edilir.
 */
create or replace function public.fn_lab_arsiv_saklama_gun(p_numune_id integer)
returns integer language sql stable as $$
    select max(p.gun)
      from public.lab_numune n
      left join public.lab_istem_satir s on s.numune_id = n.id and s.durum <> 0
      join lateral (
            select pol.gun
              from public.lab_saklama_politika pol
             where pol.aktif = 1
               and (pol.tetkik_id is null or pol.tetkik_id = s.tetkik_id)
               and (pol.numune_tipi is null or pol.numune_tipi = n.numune_tipi)
             order by (pol.tetkik_id is not null) desc,
                      (pol.numune_tipi is not null) desc
             limit 1) p on true
     where n.id = p_numune_id;
$$;

comment on function public.fn_lab_arsiv_saklama_gun(integer) is
  '890: numunenin saklama suresi (gun). En dar politika kazanir; numunenin '
  'testlerinden EN UZUN sure gecerlidir. Politika yoksa NULL.';

-- ------------------------------------------------------ yerlestirme ----
/**
 * ARŞİVE KOY. Dolu göze ya da ızgara dışına yerleştirmeyi reddeder;
 * numune zaten arşivdeyse önce çıkarılmalıdır.
 *
 * Zincire (`lab_numune_hareket`) 433'ün kendi kodu ile yazar: 6 = saklamaya.
 */
create or replace function public.fn_lab_arsiv_koy(p_numune_id integer,
                                                   p_konum_id  integer,
                                                   p_goz       varchar,
                                                   p_kullanici integer default 0)
returns integer language plpgsql as $$
declare
    v_konum   public.lab_arsiv_konum;
    v_gun     integer;
    v_id      integer;
    v_sube    integer;
    v_goz     varchar(10) := upper(trim(coalesce(p_goz, '')));
    v_satir   integer;
    v_sutun   integer;
begin
    select * into v_konum from public.lab_arsiv_konum where id = p_konum_id;
    if v_konum.id is null or v_konum.aktif <> 1 then
        raise exception 'Arşiv konumu bulunamadı ya da pasif.';
    end if;
    if v_konum.tur <> 3 then
        raise exception 'Tüp yalnız KUTUYA yerleştirilir; % bir kutu değil.', v_konum.ad;
    end if;

    -- GÖZ IZGARANIN İÇİNDE OLMALI: 'A5' -> satır A (1), sütun 5. Izgara
    --   dışını kabul etmek, var olmayan bir yeri kayda geçirmek olurdu.
    if v_goz = '' then
        raise exception 'Göz belirtilmeli (örnek: A5).';
    end if;
    if v_goz !~ '^[A-Z][0-9]{1,2}$' then
        raise exception 'Göz biçimi A5 gibi olmalı (harf + sayı): %', v_goz;
    end if;
    v_satir := ascii(left(v_goz, 1)) - 64;
    v_sutun := substring(v_goz from 2)::integer;
    if v_satir > v_konum.satir or v_sutun > v_konum.sutun or v_sutun < 1 then
        raise exception '% kutusu % x % gözlü; % böyle bir göz değil.',
              v_konum.ad, v_konum.satir, v_konum.sutun, v_goz;
    end if;

    if exists (select 1 from public.lab_numune_arsiv a
                where a.numune_id = p_numune_id and a.durum = 1) then
        raise exception 'Numune zaten arşivde - önce çıkarın.';
    end if;
    if exists (select 1 from public.lab_numune_arsiv a
                where a.konum_id = p_konum_id and upper(a.goz) = v_goz and a.durum = 1) then
        raise exception '% gözü dolu.', v_goz;
    end if;

    v_gun := public.fn_lab_arsiv_saklama_gun(p_numune_id);
    select coalesce(sube_id, 0) into v_sube from public.lab_numune where id = p_numune_id;

    insert into public.lab_numune_arsiv
           (numune_id, konum_id, goz, giris_id, saklama_gun, imha_hedef, sube_id)
    values (p_numune_id, p_konum_id, v_goz, p_kullanici, v_gun,
            -- POLİTİKA YOKSA HEDEF DE YOK: uydurulmuş bir tarih, saklanması
            --   gereken numuneyi erken imha ettirirdi.
            case when v_gun is null then null
                 else (current_date + v_gun) end,
            coalesce(v_sube, 0))
    returning id into v_id;

    -- Numunenin kendi alanları da tazelenir: eski ekranlar (istem kartı,
    --   barkod okutma) serbest metin `saklama_yeri` okuyor.
    update public.lab_numune
       set saklama_yeri = left(public.fn_lab_arsiv_yol(p_konum_id) || ' · ' || v_goz, 60),
           saklama_sicaklik = coalesce(v_konum.sicaklik, saklama_sicaklik),
           imha_tarihi = case when v_gun is null then imha_tarihi
                              else (current_date + v_gun) end,
           degistiren = p_kullanici, degistirme_tarihi = now()
     where id = p_numune_id;

    insert into public.lab_numune_hareket (numune_id, olay, kullanici_id, konum, sicaklik, aciklama)
    values (p_numune_id, 6, p_kullanici,
            left(public.fn_lab_arsiv_yol(p_konum_id) || ' · ' || v_goz, 60),
            v_konum.sicaklik, 'Arşive yerleştirildi');

    return v_id;
end $$;

/**
 * ARŞİVDEN ÇIKAR. Neden zorunludur: 1 tekrar çalışma · 2 dış laboratuvara ·
 * 3 imha · 4 devir/iade. İmhada kayıt "imha edildi" (3) olur ve tüp geri
 * konulamaz; ötekilerde "çıkarıldı" (2) - aynı tüp yeniden arşivlenebilir.
 */
create or replace function public.fn_lab_arsiv_cikar(p_numune_id integer,
                                                     p_neden     smallint,
                                                     p_kullanici integer default 0,
                                                     p_not       varchar default '')
returns integer language plpgsql as $$
declare
    v_id    integer;
    v_konum integer;
begin
    if p_neden not in (1, 2, 3, 4) then
        raise exception 'Çıkış nedeni geçersiz (1 tekrar · 2 dış lab · 3 imha · 4 devir).';
    end if;

    select a.id, a.konum_id into v_id, v_konum
      from public.lab_numune_arsiv a
     where a.numune_id = p_numune_id and a.durum = 1
     limit 1;
    if v_id is null then
        raise exception 'Numune arşivde değil.';
    end if;

    update public.lab_numune_arsiv
       set durum = case when p_neden = 3 then 3 else 2 end,
           cikis_zamani = now(), cikis_id = p_kullanici, cikis_neden = p_neden,
           not_metni = left(coalesce(p_not, ''), 200)
     where id = v_id;

    -- Zincirde imha ile taşıma AYRI olaylardır (433: 8 imha · 2 taşındı).
    insert into public.lab_numune_hareket (numune_id, olay, kullanici_id, konum, aciklama)
    values (p_numune_id, case when p_neden = 3 then 8 else 2 end, p_kullanici,
            left(coalesce(public.fn_lab_arsiv_yol(v_konum), ''), 60),
            case p_neden when 1 then 'Arşivden çıkarıldı - tekrar çalışma'
                         when 2 then 'Arşivden çıkarıldı - dış laboratuvara'
                         when 3 then 'İmha edildi'
                         else 'Arşivden çıkarıldı - devir/iade' end
            || case when coalesce(p_not, '') = '' then '' else ' · ' || p_not end);

    if p_neden = 3 then
        update public.lab_numune
           set durum = 9, degistiren = p_kullanici, degistirme_tarihi = now()
         where id = p_numune_id;
    end if;

    update public.lab_numune
       set saklama_yeri = '', degistiren = p_kullanici, degistirme_tarihi = now()
     where id = p_numune_id and p_neden <> 3;

    return v_id;
end $$;

-- ------------------------------------------------------------ dökümler ----
create or replace view public.v_lab_arsiv as
select a.id, a.numune_id, n.barkod, n.hasta_id,
       coalesce(nullif(trim(h.ad || ' ' || h.soyad), ''), h.unvan) as hasta,
       i.istem_no, n.numune_tipi, n.tup_tipi,
       a.konum_id, public.fn_lab_arsiv_yol(a.konum_id) as konum, a.goz,
       k.sicaklik, a.giris_zamani, a.saklama_gun, a.imha_hedef,
       case when a.imha_hedef is null then null
            else (a.imha_hedef - current_date) end as kalan_gun,
       a.durum, a.cikis_zamani, a.cikis_neden, a.not_metni, a.sube_id
  from public.lab_numune_arsiv a
  join public.lab_numune n on n.id = a.numune_id
  join public.lab_istem i on i.id = n.istem_id
  left join public.taraf h on h.id = n.hasta_id
  left join public.lab_arsiv_konum k on k.id = a.konum_id;

comment on view public.v_lab_arsiv is
  '890: arsiv kayitlari - numune, konum yolu, goz, imha hedefi ve kalan gun.';

-- SÜRESİ DOLANLAR: imha listesi ekrandan buradan okunur. "Kalan gun <= 0"
--   demek imha edilmeli demektir; imhayı SİSTEM YAPMAZ - fiziksel iş bitmeden
--   kaydı kapatmak, imha edilmemiş tüpü imha edilmiş göstermek olurdu.
create or replace view public.v_lab_arsiv_imha_bekleyen as
select * from public.v_lab_arsiv
 where durum = 1 and imha_hedef is not null and imha_hedef <= current_date;

comment on view public.v_lab_arsiv_imha_bekleyen is
  '890: saklama suresi dolmus, hala arsivde duran numuneler. Imha kaydi ELLE '
  'kapatilir - fiziksel is bitmeden kaydi kapatmak, imha edilmemis tupu imha '
  'edilmis gostermek olurdu.';

-- KUTU DOLULUĞU: ekran ızgarayı çizerken ve "boş yer var mı" sorusunda.
create or replace view public.v_lab_arsiv_kutu as
select k.id as konum_id, k.kod, k.ad, k.sicaklik, k.satir, k.sutun,
       (k.satir * k.sutun) as goz_sayisi,
       count(a.id) filter (where a.durum = 1) as dolu,
       (k.satir * k.sutun) - count(a.id) filter (where a.durum = 1) as bos,
       public.fn_lab_arsiv_yol(k.id) as yol, k.sube_id, k.aktif
  from public.lab_arsiv_konum k
  left join public.lab_numune_arsiv a on a.konum_id = k.id
 where k.tur = 3
 group by k.id, k.kod, k.ad, k.sicaklik, k.satir, k.sutun, k.sube_id, k.aktif;

-- KONUM SEÇİCİ (kart alanı): ağaçtaki her düğüm, yolu ile birlikte.
--   Kutuyu "Kutu 7" diye seçtirmek, hangi dolabın 7'si olduğunu belirsiz
--   bırakırdı.
create or replace view public.v_lab_arsiv_konum_lookup as
select k.id, k.kod,
       (public.fn_lab_arsiv_yol(k.id))::text as ad,
       k.aktif
  from public.lab_arsiv_konum k;

comment on view public.v_lab_arsiv_konum_lookup is
  '890: arsiv konumu secici - ad olarak TAM YOL doner.';

-- -------------------------------------------------------------- yetki ----
insert into public.yetki (kod, ad, grup, tur, sira, aktif, urun_modu, modul)
select v.kod, v.ad, 'Laboratuvar', v.tur, v.sira, 1, 2, 'lab'
  from (values
    ('lab.arsiv', 'Numune Arşivi', 0::smallint, 48::smallint),
    ('lab.arsiv.imha', 'Numune imhası', 1::smallint, 49::smallint),
    ('lab.arsiv_konum', 'Arşiv konumları (tanım)', 0::smallint, 50::smallint),
    ('lab.saklama_politika', 'Numune saklama süreleri (tanım)', 0::smallint, 51::smallint)
  ) as v(kod, ad, tur, sira)
 where not exists (select 1 from public.yetki y where y.kod = v.kod);

insert into public.rol_yetki (rol_id, yetki_id, gor, ekle, degistir, sil, ekleyen)
select r.id, y.id, 1, 1, 1, 1, 0
  from public.rol r cross join public.yetki y
 where r.kod = 'yonetici'
   and y.kod in ('lab.arsiv', 'lab.arsiv.imha', 'lab.arsiv_konum', 'lab.saklama_politika')
   and not exists (select 1 from public.rol_yetki ry
                    where ry.rol_id = r.id and ry.yetki_id = y.id);
update public.rol set yetki_surumu = yetki_surumu + 1 where kod = 'yonetici';

do $$
begin
    raise notice '890 tamam: % konum, % politika, % arsiv kaydi',
        (select count(*) from public.lab_arsiv_konum),
        (select count(*) from public.lab_saklama_politika),
        (select count(*) from public.lab_numune_arsiv);
end $$;
