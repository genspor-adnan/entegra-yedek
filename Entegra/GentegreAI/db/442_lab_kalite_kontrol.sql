-- ---------------------------------------------------------------------
insert into public.lab_kk_kural (tetkik_id, kural, davranis, sira, aciklama)
select null, v.kural, v.davranis, v.sira, v.acik
  from (values
      ('1_3s', 2::smallint, 10::smallint, 'Tek ölçüm ±3 SD dışında - rastgele hata'),
      ('2_2s', 2::smallint, 20::smallint, 'Ardışık iki ölçüm aynı yönde ±2 SD dışında - sistematik hata'),
      ('R_4s', 2::smallint, 30::smallint, 'Aynı çalışmada iki seviye arası 4 SD açıklık'),
      ('4_1s', 1::smallint, 40::smallint, 'Son dört ölçüm aynı yönde ±1 SD dışında - kayma'),
