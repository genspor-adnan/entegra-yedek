-- ---------------------------------------------------------------------
--  6) WESTGARD DEĞERLENDİRMESİ
--
--  Kurallar seri gerektirir: 2₂ₛ ardışık iki ölçüm, R₄ₛ aynı çalışmadaki
--  iki seviye arasında 4 SD açıklık, 4₁ₛ son dört, 10ₓ son on ölçüm aynı
--  yönde. Tek ölçüme bakan bir kontrol, kaymayı (sistematik hatayı) hiç
--  göremez - asıl tehlike odur; rastgele hata gürültü yapar, kayma sessizce
--  bütün hastaları etkiler.
-- ---------------------------------------------------------------------
create or replace function public.fn_lab_westgard(p_olcum_id bigint)
returns table (durum smallint, ihlaller text[])
language plpgsql as $$
declare
    v_hedef_id integer;
    v_tetkik   integer;
    v_zaman    timestamp;
    v_z        numeric;
    v_ihlal    text[] := '{}';
    v_durum    smallint := 1;
    v_seri     numeric[];
    v_r4s      numeric;
    v_davranis smallint;
begin
    select o.hedef_id, o.tetkik_id, o.olcum_zamani, o.z
      into v_hedef_id, v_tetkik, v_zaman, v_z
      from public.lab_kk_olcum o where o.id = p_olcum_id;

    if v_z is null then
        return query select 1::smallint, '{}'::text[];
        return;
    end if;

    -- Bu ölçüm DAHİL, aynı hedef (lot+tetkik+seviye) için son 10 ölçüm,
    --   yeniden eskiye.
    select array_agg(z order by olcum_zamani desc, id desc)
      into v_seri
      from (select z, olcum_zamani, id
              from public.lab_kk_olcum
             where hedef_id = v_hedef_id and olcum_zamani <= v_zaman
               and z is not null
             order by olcum_zamani desc, id desc
             limit 10) s;

    -- 1_3s: tek ölçüm ±3 SD dışında (rastgele hata, klasik ret kuralı).
    if abs(v_z) > 3 then v_ihlal := array_append(v_ihlal, '1_3s'); end if;

    -- 1_2s: uyarı kuralı - tek başına ret değil, diğer kuralları TETİKLER.
    if abs(v_z) > 2 then v_ihlal := array_append(v_ihlal, '1_2s'); end if;

    -- 2_2s: ardışık iki ölçüm aynı yönde ±2 SD dışında (sistematik hata).
    if cardinality(v_seri) >= 2
       and abs(v_seri[1]) > 2 and abs(v_seri[2]) > 2
       and sign(v_seri[1]) = sign(v_seri[2]) then
        v_ihlal := array_append(v_ihlal, '2_2s');
    end if;

    -- R_4s: AYNI ÇALIŞMADA iki seviye arasında 4 SD açıklık (rastgele hata).
    --   Aynı çalışma = ±2 saat; kontroller birlikte konur.
    select max(abs(o2.z - v_z)) into v_r4s
      from public.lab_kk_olcum o2
      join public.lab_kk_hedef h2 on h2.id = o2.hedef_id
      join public.lab_kk_hedef h1 on h1.id = v_hedef_id
     where h2.lot_id = h1.lot_id and h2.tetkik_id = h1.tetkik_id
       and h2.seviye <> h1.seviye
       and o2.olcum_zamani between v_zaman - interval '2 hours'
                               and v_zaman + interval '2 hours'
       and o2.z is not null;
    if coalesce(v_r4s, 0) > 4 then v_ihlal := array_append(v_ihlal, 'R_4s'); end if;

    -- 4_1s: son dört ölçüm aynı yönde ±1 SD dışında (kayma başlangıcı).
    if cardinality(v_seri) >= 4
       and (v_seri[1] > 1 and v_seri[2] > 1 and v_seri[3] > 1 and v_seri[4] > 1
            or v_seri[1] < -1 and v_seri[2] < -1 and v_seri[3] < -1 and v_seri[4] < -1) then
        v_ihlal := array_append(v_ihlal, '4_1s');
    end if;

    -- 10x: son on ölçüm ortalamanın aynı tarafında (yerleşmiş kayma).
    if cardinality(v_seri) >= 10
       and ((select count(*) from unnest(v_seri) x where x > 0) = 10
            or (select count(*) from unnest(v_seri) x where x < 0) = 10) then
        v_ihlal := array_append(v_ihlal, '10x');
    end if;

    -- DAVRANIŞ kural setinden: teste özel satır varsa o, yoksa varsayılan.
    --   Kapalı (0) kurallar ihlal listesinde KALIR ama durumu değiştirmez -
    --   "bu kural kapalıydı" bilgisi denetimde gerekir.
    if cardinality(v_ihlal) > 0 then
        select max(k.davranis) into v_davranis
          from unnest(v_ihlal) i
          join lateral (
                select davranis from public.lab_kk_kural k
                 where upper(k.kural) = upper(i)
                   and (k.tetkik_id = v_tetkik or k.tetkik_id is null)
                 order by k.tetkik_id nulls last
                 limit 1) k on true;
        -- İKİ AYRI KOD UZAYI: kural davranışı 0 kapalı · 1 uyarı · 2 ret;
        --   ölçüm durumu 1 kabul · 2 uyarı · 3 ret. Doğrudan atamak, ret
        --   kuralını "uyarı" olarak kaydediyordu - yani oto-onay kapanmıyordu.
        v_durum := case coalesce(v_davranis, 0)
                       when 2 then 3::smallint      -- ret
                       when 1 then 2::smallint      -- uyarı
                       else 1::smallint end;        -- kapalı kural = kabul
    end if;

    update public.lab_kk_olcum
       set ihlaller = v_ihlal, durum = v_durum
     where id = p_olcum_id;

    return query select v_durum, v_ihlal;
end $$;

-- ---------------------------------------------------------------------
--  7) KK GEÇERLİLİĞİ - hasta sonucuna bağlanan yer
--
--  Bir testin son KK ölçümü RET ise ve düzeltme sonrası geçerli bir tekrar
--  yoksa, o testin sonuçları OTO-ONAYA GİRMEZ. Kural motorunun "temiz
--  sonuç" kararı cihazın o gün doğru ölçtüğü varsayımına dayanır; kontrol
--  tutmuyorsa varsayım çürümüştür.
--
--  Pencere: son 24 saat. Hiç KK yoksa "geçerli" sayılır - kalite kontrolü
--  tanımlanmamış bir testi çalıştırmamak ayrı bir karardır ve burada
--  zorlanmaz (kurulum aşamasındaki laboratuvarı kilitlerdi).
-- ---------------------------------------------------------------------
create or replace function public.fn_lab_kk_gecerli(p_tetkik_id integer,
                                                    p_zaman timestamp default null)
returns boolean language sql stable as $$
    -- localtimestamp (timestamptz DEĞİL): olcum_zamani saat dilimsiz
    --   tutuluyor; now() ile karşılaştırmak fonksiyonu "timestamp with
    --   time zone" imzasına zorluyor ve çağrılar 42883 ile düşüyordu.
    select coalesce(
        (select o.durum <> 3
           from public.lab_kk_olcum o
          where o.tetkik_id = p_tetkik_id
            and o.olcum_zamani <= coalesce(p_zaman, localtimestamp)
            and o.olcum_zamani >= coalesce(p_zaman, localtimestamp) - interval '24 hours'
          order by o.olcum_zamani desc, o.id desc
          limit 1),
        true);
$$;

comment on function public.fn_lab_kk_gecerli(integer, timestamp) is
    'Testin son 24 saatlik KK olcumu RET degilse true. Oto-onay bu bayraga '
    'bakar: kontrol tutmayan cihazin "temiz" sonucu otomatik onaylanmaz.';

-- ---------------------------------------------------------------------
--  8) KÜMÜLATİF İSTATİSTİK
--
--  Laboratuvarın kendi ortalama/SD'si RET EDİLEN ölçümler hariç tutularak
--  hesaplanır: ret bir ölçüm hatasıdır, hedefi kaydırmamalı.
-- ---------------------------------------------------------------------
create or replace function public.fn_lab_kk_kumulatif(p_hedef_id integer)
returns integer language plpgsql as $$
declare
    v_n integer; v_ort numeric; v_sd numeric;
begin
    select count(*), avg(deger), stddev_samp(deger)
      into v_n, v_ort, v_sd
      from public.lab_kk_olcum
     where hedef_id = p_hedef_id and durum <> 3;

    update public.lab_kk_hedef
       set kumulatif_n = coalesce(v_n, 0),
           kumulatif_ort = v_ort,
           kumulatif_sd = v_sd,
           degistirme_tarihi = now()
     where id = p_hedef_id;

    return coalesce(v_n, 0);
end $$;

-- ---------------------------------------------------------------------
--  9) LOOKUP'LAR ve GÖRÜNÜMLER
-- ---------------------------------------------------------------------
drop view if exists public.v_lab_kk_lot_lookup;
create view public.v_lab_kk_lot_lookup as
select l.id, l.kod, l.kod || ' · ' || l.materyal_ad || ' (lot ' || l.lot || ')' as ad,
       case when l.durum = 0 then 1 else 0 end::smallint as aktif
  from public.lab_kk_lot l;

-- LEVEY-JENNINGS SERİSİ: grafik ekranının kaynağı. Z skoru ölçümle
--   saklandığı için burada yeniden hesaplanmaz.
drop view if exists public.v_lab_kk_lj;
create view public.v_lab_kk_lj as
select o.id, o.hedef_id, o.lot_id, o.tetkik_id, t.kod as tetkik_kod, t.ad as tetkik_ad,
       o.seviye, o.olcum_zamani, o.deger, o.z, o.hedef, o.sd, o.durum, o.ihlaller,
       o.kaynak, o.aksiyon, coalesce(c.kod, '') as cihaz_kod, l.materyal_ad, l.lot,
       o.sube_id
  from public.lab_kk_olcum o
  join public.lab_kk_lot l on l.id = o.lot_id
  join public.lab_tetkik t on t.id = o.tetkik_id
  left join public.cihaz c on c.id = o.cihaz_id;

