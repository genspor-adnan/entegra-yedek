-- ---------------------------------------------------------------------
-- 11) VARSAYILAN WESTGARD SETİ (mockuptaki set)
--
--  1₃ₛ ret · 2₂ₛ ret · R₄ₛ ret · 4₁ₛ uyarı · 10ₓ uyarı · 1₂ₛ uyarı
--  (1₂ₛ tek başına ret DEĞİLDİR: her 20 ölçümden biri şansa ±2 SD dışına
