-- ---------------------------------------------------------------------
--  1) KONTROL LOTU ve HEDEFLERİ
--
--  HEDEF/SD LOT BAŞINADIR: yeni lot açıldığında değerler değişir; tek bir
--  "test hedefi" tutmak, lot geçişinde bütün grafiği kaydırırdı.
--  Üretici değeri başlangıçtır; laboratuvar kendi kümülatif ortalama ve
--  SD'sini biriktirir (20 ölçümden sonra kendi verisi esas alınır).
-- ---------------------------------------------------------------------
create table if not exists public.lab_kk_lot (
    id            integer generated by default as identity primary key,
    kod           varchar(30)  not null,
    materyal_ad   varchar(200) not null,
    lot           varchar(40)  not null,
    uretici       varchar(120) not null default '',
    skt           date,
    seviye_sayisi smallint     not null default 2,
    acilis_tarihi date,
    aciklama      varchar(300) not null default '',
    durum         smallint     not null default 0,   -- 0 aktif · 1 pasif
    sube_id       integer   not null default 0,
    ekleyen       integer   not null default 0,
    ekleme_tarihi timestamp not null default now(),
    degistiren    integer   not null default 0,
    degistirme_tarihi timestamp
);

create unique index if not exists ux_lab_kk_lot_kod
    on public.lab_kk_lot (upper(kod));

create table if not exists public.lab_kk_hedef (
    id            integer generated by default as identity primary key,
    lot_id        integer  not null references public.lab_kk_lot(id) on delete cascade,
    tetkik_id     integer  not null references public.lab_tetkik(id),
    seviye        smallint not null default 1,
    -- Üretici prospektüs değeri: laboratuvar kendi verisini biriktirene
    --   kadar kullanılır.
    uretici_hedef numeric(19,6),
    uretici_sd    numeric(19,6),
    -- Laboratuvarın KENDİ kümülatifi: yöntem, cihaz ve teknisyen etkisini
    --   içerir; üreticininki bunları göremez.
    kumulatif_n   integer  not null default 0,
    kumulatif_ort numeric(19,6),
    kumulatif_sd  numeric(19,6),
    -- Kümülatif geçerli sayılması için en az kaç ölçüm gerekli (CLSI: 20).
    esik_n        integer  not null default 20,
    birim         varchar(20) not null default '',
    durum         smallint not null default 0,
    ekleyen       integer   not null default 0,
    ekleme_tarihi timestamp not null default now(),
    degistiren    integer   not null default 0,
    degistirme_tarihi timestamp
);

create unique index if not exists ux_lab_kk_hedef
    on public.lab_kk_hedef (lot_id, tetkik_id, seviye);

-- YÜRÜRLÜKTEKİ HEDEF: kümülatif eşiği geçtiyse laboratuvarın kendi
--   değeri, geçmediyse üreticininki. Karar tek yerde - ekran, kural
--   motoru ve rapor aynı hedefi görmeli.
create or replace function public.fn_lab_kk_hedef(p_hedef_id integer)
returns table (hedef numeric, sd numeric, kaynak text)
language sql stable as $$
    select case when h.kumulatif_n >= h.esik_n and h.kumulatif_ort is not null
                then h.kumulatif_ort else h.uretici_hedef end,
           case when h.kumulatif_n >= h.esik_n and h.kumulatif_sd is not null
                then h.kumulatif_sd else h.uretici_sd end,
           case when h.kumulatif_n >= h.esik_n and h.kumulatif_sd is not null
                then 'laboratuvar kümülatif (n=' || h.kumulatif_n || ')'
                else 'üretici' end
      from public.lab_kk_hedef h
     where h.id = p_hedef_id;
$$;

-- ---------------------------------------------------------------------
--  2) WESTGARD KURAL SETİ
--
--  Kural seti TEST BAZLI: bir HbA1c ile bir troponinin tolere ettiği
--  sapma aynı değildir. Tetkik boş (null) olan satırlar VARSAYILAN sete
--  aittir; teste özel satır varsa o kazanır.
-- ---------------------------------------------------------------------
create table if not exists public.lab_kk_kural (
    id        integer generated by default as identity primary key,
    tetkik_id integer references public.lab_tetkik(id) on delete cascade,
    -- 1_3s · 2_2s · R_4s · 4_1s · 10x · 1_2s · 2of3_2s
    kural     varchar(12) not null,
    -- 0 kapalı · 1 uyarı · 2 ret
    davranis  smallint not null default 2,
    sira      smallint not null default 0,
    aciklama  varchar(200) not null default '',
    ekleyen       integer   not null default 0,
    ekleme_tarihi timestamp not null default now(),
    degistiren    integer   not null default 0,
    degistirme_tarihi timestamp
);

create unique index if not exists ux_lab_kk_kural
    on public.lab_kk_kural (coalesce(tetkik_id, 0), upper(kural));

-- ---------------------------------------------------------------------
--  3) KK ÖLÇÜMLERİ
--
--  Ölçüm CİHAZDAN (kontrol barkodu) ya da ELLE gelir. Kural sonucu ve
--  ihlal listesi satırda saklanır: kural seti sonradan değişse geçmiş
--  değerlendirme değişmemeli (hasta sonucundaki bayrakla aynı gerekçe).
-- ---------------------------------------------------------------------
create table if not exists public.lab_kk_olcum (
    id            bigint generated by default as identity primary key,
    hedef_id      integer  not null references public.lab_kk_hedef(id),
    lot_id        integer  not null references public.lab_kk_lot(id),
    tetkik_id     integer  not null references public.lab_tetkik(id),
    seviye        smallint not null default 1,
    cihaz_id      integer references public.cihaz(id),
    cihaz_mesaj_id bigint,
    olcum_zamani  timestamp not null default now(),
    deger         numeric(19,6) not null,
    -- Z SKORU saklanır: hedef/SD sonradan güncellenince eski ölçümün
    --   grafikteki yeri kaymamalı (Levey-Jennings geçmişi kayıt defteridir).
    z             numeric(9,3),
    hedef         numeric(19,6),
    sd            numeric(19,6),
    ihlaller      text[] not null default '{}',
    -- 1 kabul · 2 uyarı · 3 ret
    durum         smallint not null default 1,
    -- 1 cihaz · 2 elle
    kaynak        smallint not null default 2,
    tekrar        smallint not null default 0,   -- düzeltme sonrası tekrar ölçümü
    -- RET HÂLİNDE DÜZELTİCİ FAALİYET ZORUNLU (ISO 15189): serbest metin
    --   ama boş bırakılamaz - "ne yaptık" yazılmayan ret, kaydı denetimde
    --   savunulamaz kılar.
    aksiyon       varchar(600) not null default '',
    -- Etkilenen hasta sonuçlarının gözden geçirilmesi: kaç sonuç bakıldı,
    --   kaçı değişti.
    gozden_gecirilen integer not null default 0,
    duzeltilen    integer  not null default 0,
    onay_id       integer,
    onay_zamani   timestamp,
    sube_id       integer   not null default 0,
    ekleyen       integer   not null default 0,
    ekleme_tarihi timestamp not null default now(),
    degistiren    integer   not null default 0,
    degistirme_tarihi timestamp
);

create index if not exists ix_lab_kk_olcum_seri
    on public.lab_kk_olcum (hedef_id, olcum_zamani desc);
create index if not exists ix_lab_kk_olcum_tetkik
    on public.lab_kk_olcum (tetkik_id, olcum_zamani desc);

