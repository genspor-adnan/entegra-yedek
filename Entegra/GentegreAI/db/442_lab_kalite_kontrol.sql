-- NEDEN: hasta sonucunun doğruluğu, o gün cihazın doğru ölçtüğünün
-- kanıtına bağlıdır. Kontrol ölçümü tutmayan bir testin hasta sonucu -
-- normal görünse bile - güvenilmez. ISO 15189'un istediği de budur:
-- lot bazlı hedef/SD, Westgard kural seti, ret hâlinde düzeltici faaliyet
-- ve ETKİLENEN HASTA SONUÇLARININ gözden geçirilmesi.
--
-- EN ÖNEMLİ BAĞ: KK geçersizken o testin hasta sonuçları OTO-ONAYA
-- GİRMEZ (fn_lab_kk_gecerli). Kalite kontrolü ayrı bir kayıt defteri
