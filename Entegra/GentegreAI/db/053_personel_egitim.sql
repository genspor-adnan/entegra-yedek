\set ON_ERROR_STOP on

create table if not exists public.personel_egitim (
    id                  integer generated by default as identity primary key,
    taraf_id            integer not null references public.taraf(id) on delete cascade,
    tur                 smallint not null default 0,
    ad                  character varying(200) not null default '',
    kurum               character varying(150) not null default '',
    tarih               date,
    gecerlilik          character varying(60) not null default '',
    sube_id             integer not null references public.sube(id),
    ekleyen             integer not null default 0,
    ekleme_tarihi       timestamp not null default now()::timestamp,
    degistiren          integer not null default 0,
    degistirme_tarihi   timestamp
);

create index if not exists ix_personel_egitim_taraf on public.personel_egitim (taraf_id);

comment on table public.personel_egitim is
  'Personel eğitim/sertifika/diploma kayıtları (ik_karti.html mockup Eğitim/Sertifika sekmesi).';
