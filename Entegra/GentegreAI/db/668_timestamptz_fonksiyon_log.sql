-- ============================================================================
--  Gentegre AI — timestamptz GEÇİŞİNİN İKİ ARTIĞI
--  668_timestamptz_fonksiyon_log.sql   (667'nin devamı)
--
--  667 tabloları dönüştürdü ama iki şey geride kaldı:
--
--  1) TİMESTAMP PARAMETRELİ FONKSİYONLAR — kolonlar timestamptz olunca çağrı
--     eşleşmiyor ve sorgu patlıyor:
--         42883: function public.fn_hizmet_puan(numeric, timestamp with time
--                zone, numeric) does not exist
--     PostgreSQL timestamptz → timestamp ÖRTÜK dönüşüm yapmaz (bilgi kaybı);
--     imzanın kendisi değişmeli. Sekiz fonksiyon etkileniyor.
--
--  2) islem_log — `tarih` BÖLÜM ANAHTARI olduğu için tipi değiştirilemiyor
--     ("cannot alter column ... part of the partition key"). Tablonun yeniden
--     kurulması gerekiyor: yeni tablo + bölümler, veri kopyası, takas.
--
--  UYARI (müşteri veritabanı): islem_log milyonlarca satır olabilir. Kopyalama
--  tablonun boyutuyla orantılı sürer ve bu süre boyunca log yazılamaz
--  (tablo kilitli). Güncelleme penceresi buna göre seçilmeli.
-- ============================================================================
\set ON_ERROR_STOP on

begin;

-- Fonksiyonlar BİRBİRİNİ çağırıyor (fn_lab_istem_sonuc_zamani ->
--   fn_lab_tetkik_sonuc_zamani). Hepsi aynı anda değişemeyeceği için ara
--   adımda gövde doğrulaması "böyle bir fonksiyon yok" der ve betik durur.
--   Doğrulama bu işlem boyunca kapatılır; çağrı zaten ÇALIŞMA anında çözülür
--   ve son durumda sekizi de timestamptz imzalıdır.
set local check_function_bodies = off;

-- ---------------------------------------------------------------------------
--  1) FONKSİYON İMZALARI
--
--  Tanım veritabanından okunur ve "timestamp without time zone" ifadesi
--  "timestamp with time zone" ile değiştirilip yeniden yaratılır. Fonksiyonlar
--  ADIYLA sayılır: kör tarama yerine sekiz bilinen ad - yarın eklenen bir
--  fonksiyonun gövdesindeki bilinçli `::timestamp` kullanımını sessizce
--  bozmasın.
-- ---------------------------------------------------------------------------
do $$
declare
    r record;
    v_tanim text;
    v_sayi integer := 0;
begin
    for r in
        select p.oid,
               p.proname,
               pg_get_function_identity_arguments(p.oid) as imza
          from pg_proc p
          join pg_namespace n on n.oid = p.pronamespace and n.nspname = 'public'
         where p.proname in ('fn_ebelge_mesajlar', 'fn_gelen_mesajlar', 'fn_hizmet_puan',
                             'fn_lab_calisma_sonuc_zamani', 'fn_lab_istem_sonuc_zamani',
                             'fn_lab_kk_gecerli', 'fn_lab_tetkik_sonuc_zamani',
                             'fn_muhasebe_donem_kontrol')
           and (pg_get_function_arguments(p.oid) ilike '%timestamp without time zone%'
             or pg_get_function_result(p.oid)    ilike '%timestamp without time zone%')
    loop
        v_tanim := replace(pg_get_functiondef(r.oid),
                           'timestamp without time zone', 'timestamp with time zone');

        -- Donus tipi degisiyorsa CREATE OR REPLACE yetmez: once dusurulur.
        execute format('drop function if exists public.%I(%s)', r.proname, r.imza);
        execute v_tanim;
        v_sayi := v_sayi + 1;
        raise notice '668: %(%) timestamptz imzayla yeniden kuruldu', r.proname, r.imza;
    end loop;

    raise notice '668: % fonksiyon guncellendi', v_sayi;
end $$;

-- ---------------------------------------------------------------------------
--  2) islem_log YENİDEN KURULUR
--
--  Sıra: yeni tablo (timestamptz anahtar) → bölümler → veri → eski tabloyu
--  düşür → yeniden adlandır. Kimlik (identity) sayacı veri kopyalandıktan
--  sonra en yüksek id'ye ayarlanır, yoksa ilk yeni log satırı çakışırdı.
--
--  BÖLÜM SINIRLARI timestamptz olarak yazılır: '2026-01-01 00:00:00+00'.
--  Saat dilimsiz yazılsaydı sınır oturumun saat dilimine göre kayar ve yıl
--  sonunda satırlar yanlış bölüme düşerdi.
-- ---------------------------------------------------------------------------
create table public.islem_log_yeni (
    id             bigint      generated by default as identity,
    tarih          timestamptz not null default now(),
    kullanici_id   integer     not null default 0,
    sube_id        smallint    not null default 0,
    ip             varchar(45) not null default '',
    istasyon       varchar(64) not null default '',
    islem_tipi     smallint    not null default 0,
    alt_islem_tipi smallint    not null default 0,
    ust_tablo_id   integer     not null default 0,
    ust_kayit_id   bigint      not null default 0,
    tablo_id       integer     not null default 0,
    kayit_id       bigint      not null default 0,
    taraf_id       integer,
    stok_id        integer,
    bilgi          jsonb,
    constraint pk_islem_log_yeni primary key (id, tarih)
) partition by range (tarih);

create table public.log_2026_yeni partition of public.islem_log_yeni
    for values from ('2026-01-01 00:00:00+00') to ('2027-01-01 00:00:00+00');
create table public.log_2027_yeni partition of public.islem_log_yeni
    for values from ('2027-01-01 00:00:00+00') to ('2028-01-01 00:00:00+00');
create table public.log_diger_yeni partition of public.islem_log_yeni default;

-- Veri: saklanan degerler UTC duvar saati (667 ile ayni kural).
insert into public.islem_log_yeni
    (id, tarih, kullanici_id, sube_id, ip, istasyon, islem_tipi, alt_islem_tipi,
     ust_tablo_id, ust_kayit_id, tablo_id, kayit_id, taraf_id, stok_id, bilgi)
select id, tarih at time zone 'UTC', kullanici_id, sube_id, ip, istasyon,
       islem_tipi, alt_islem_tipi, ust_tablo_id, ust_kayit_id, tablo_id, kayit_id,
       taraf_id, stok_id, bilgi
  from public.islem_log;

drop table public.islem_log cascade;

alter table public.islem_log_yeni rename to islem_log;
alter table public.log_2026_yeni  rename to log_2026;
alter table public.log_2027_yeni  rename to log_2027;
alter table public.log_diger_yeni rename to log_diger;
alter table public.islem_log rename constraint pk_islem_log_yeni to pk_islem_log;

-- Identity sayaci: kopyalanan en yuksek id'nin uzerinden devam etsin.
select setval(pg_get_serial_sequence('public.islem_log', 'id'),
              coalesce((select max(id) from public.islem_log), 0) + 1, false);

-- Indeksler (eski tablodaki ile ayni): log ekrani tablo/kayit, kullanici ve
--   ust kayit uzerinden sorgulaniyor; tarih DESC cunku "son islemler" bakilir.
create index ix_islem_log_kayit     on public.islem_log (tablo_id, kayit_id, tarih desc);
create index ix_islem_log_kullanici on public.islem_log (kullanici_id, tarih desc);
create index ix_islem_log_ust       on public.islem_log (ust_tablo_id, ust_kayit_id, tarih desc);
create index ix_islem_log_taraf     on public.islem_log (taraf_id, tarih desc) where taraf_id is not null;
create index ix_islem_log_stok      on public.islem_log (stok_id, tarih desc)  where stok_id is not null;

-- ---------------------------------------------------------------------------
--  DOĞRULAMA
-- ---------------------------------------------------------------------------
do $$
declare v_kalan integer; v_log bigint;
begin
    select count(*) into v_kalan
      from information_schema.columns c
      join pg_class pc on pc.relname = c.table_name
      join pg_namespace pn on pn.oid = pc.relnamespace and pn.nspname = 'public'
     where c.table_schema = 'public' and c.data_type = 'timestamp without time zone'
       and pc.relkind in ('r', 'p');
    select count(*) into v_log from public.islem_log;

    raise notice '668 tamam: islem_log % satir · kalan timestamp kolon %', v_log, v_kalan;
    if v_kalan > 0 then
        raise warning '668: % kolon hala timestamp', v_kalan;
    end if;
end $$;

commit;
