--  ARIZA / TALEP (hizmet masası) — demirbaş-bağımsız genel arıza bildirimi.
--
--  Bugüne dek arıza yalnız DEMİRBAŞ iş emriyle (biyomedikal, tıbbi cihaz)
--  açılabiliyordu; "pencere açılmıyor / masa kırık / klima çalışmıyor" gibi
--  demirbaşa bağlı OLMAYAN arızaların yeri yoktu. Bu modül:
--    * HERKES self-servis talep açar (yetki: ariza.talep),
--    * kategori → SORUMLU EKİBE otomatik yönlenir,
--    * ekip devralır → çözer → kapatır (yetki: ariza),
--    * isteğe bağlı demirbaşa bağlanır (klima/PC kayıtlıysa geçmişine işler).
--
--  Modül kodu 'ariza'; menüde "Teknik Servis" grubunda (kendi yetki/rota).
-- =====================================================================

-- ------------------------------------------------------ kod listeleri ----
insert into public.kod_liste (kod, ad) select v.kod, v.ad
  from (values ('ariza.kategori','Arıza Kategorisi'),
               ('ariza.ekip','Arıza Ekibi'),
               ('ariza.durum','Arıza Talep Durumu'),
               ('ariza.oncelik','Arıza Önceliği')) v(kod,ad)
 where not exists (select 1 from public.kod_liste l where l.kod = v.kod);

insert into public.kod_deger (liste_id, deger, ad, dil, ekleyen)
select l.id, d.deger, d.ad, 0, 0
  from (values
    ('ariza.kategori',1,'Tıbbi Cihaz'),   ('ariza.kategori',2,'Klima / Mekanik'),
    ('ariza.kategori',3,'Elektrik / Tesisat'), ('ariza.kategori',4,'Bilgisayar / IT'),
    ('ariza.kategori',5,'Mobilya / Demirbaş'), ('ariza.kategori',6,'Bina / Pencere / Kapı'),
    ('ariza.kategori',7,'Temizlik'),      ('ariza.kategori',8,'Güvenlik'),
    ('ariza.kategori',9,'Diğer'),
    ('ariza.ekip',1,'Biyomedikal'),       ('ariza.ekip',2,'Teknik / Tesisat'),
    ('ariza.ekip',3,'Bilgi İşlem'),       ('ariza.ekip',4,'İdari'),
    ('ariza.ekip',5,'Temizlik'),          ('ariza.ekip',6,'Güvenlik'),
    ('ariza.durum',1,'Açık'),             ('ariza.durum',2,'Atandı'),
    ('ariza.durum',3,'İşlemde'),          ('ariza.durum',4,'Çözüldü'),
    ('ariza.durum',5,'Kapandı'),          ('ariza.durum',0,'İptal'),
    ('ariza.oncelik',1,'Düşük'),          ('ariza.oncelik',2,'Normal'),
    ('ariza.oncelik',3,'Yüksek'),         ('ariza.oncelik',4,'Acil')
  ) d(liste,deger,ad)
  join public.kod_liste l on l.kod = d.liste
 where not exists (select 1 from public.kod_deger x
                    where x.liste_id = l.id and x.deger = d.deger and x.dil = 0);

-- --------------------------------------------- kategori -> ekip eşleme ----
create table if not exists public.ariza_kategori_ekip (
  kategori smallint primary key,
  ekip     smallint not null
);
insert into public.ariza_kategori_ekip (kategori, ekip) values
  (1,1),(2,2),(3,2),(4,3),(5,2),(6,2),(7,5),(8,6),(9,4)
 on conflict (kategori) do nothing;

-- --------------------------------------------------------- talep tablo ----
create sequence if not exists public.ariza_talep_no_seq;
create table if not exists public.ariza_talep (
  id            integer generated by default as identity primary key,
  talep_no      varchar(20) not null default '',
  kategori      smallint not null,
  ekip          smallint not null,                 -- kategoriye göre otomatik
  konum         varchar(200) not null default '',  -- bina/kat/oda/departman
  aciklama      varchar(1000) not null,
  oncelik       smallint not null default 2,
  demirbas_id   integer references public.demirbas(id),  -- opsiyonel
  talep_eden    integer not null,                  -- taraf/kullanici
  sorumlu_id    integer,                           -- atanan personel (taraf)
  durum         smallint not null default 1,       -- 1 açık..5 kapandı, 0 iptal
  cozum_notu    varchar(1000) not null default '',
  kapanis_tarihi timestamptz,
  sube_id       integer not null default 0,
  ekleyen       integer not null default 0,
  ekleme_tarihi timestamptz not null default now(),
  degistiren    integer not null default 0,
  degistirme_tarihi timestamptz
);
create index if not exists ix_ariza_talep_durum on public.ariza_talep (durum, ekip);

comment on table public.ariza_talep is
  '911: genel arıza/talep (hizmet masası) - demirbaş-bağımsız, kategori->ekip yönlendirmeli.';

-- --------------------------------------------------------- açış fn'i ----
/**
 * TALEP AÇ + OTOMATİK YÖNLENDİR. Kategoriye göre ekip ariza_kategori_ekip'ten
 * bulunur; talep_no sıra numarasından üretilir. Durum = Açık.
 */
create or replace function public.fn_ariza_talep_ac(
    p_kategori    smallint,
    p_aciklama    varchar,
    p_konum       varchar default '',
    p_oncelik     smallint default 2,
    p_demirbas_id integer default null,
    p_talep_eden  integer default 0,
    p_sube_id     integer default 0)
returns integer language plpgsql as $fn$
declare
    v_ekip smallint;
    v_id   integer;
    v_no   bigint;
begin
    select ekip into v_ekip from public.ariza_kategori_ekip where kategori = p_kategori;
    v_ekip := coalesce(v_ekip, 4);            -- eşleşme yoksa İdari
    v_no := nextval('public.ariza_talep_no_seq');

    insert into public.ariza_talep
           (talep_no, kategori, ekip, konum, aciklama, oncelik, demirbas_id,
            talep_eden, durum, sube_id, ekleyen)
    values ('AT-' || lpad(v_no::text, 6, '0'), p_kategori, v_ekip,
            coalesce(p_konum,''), p_aciklama, coalesce(p_oncelik,2), p_demirbas_id,
            p_talep_eden, 1, coalesce(p_sube_id,0), p_talep_eden)
    returning id into v_id;
    return v_id;
end $fn$;

-- -------------------------------------------------------------- döküm ----
create or replace view public.v_ariza_talep as
select t.id, t.talep_no, t.kategori,
       (select ad from public.kod_deger where liste_id=(select id from public.kod_liste where kod='ariza.kategori') and deger=t.kategori and dil=0) as kategori_adi,
       t.ekip,
       (select ad from public.kod_deger where liste_id=(select id from public.kod_liste where kod='ariza.ekip') and deger=t.ekip and dil=0) as ekip_adi,
       t.konum, t.aciklama, t.oncelik,
       (select ad from public.kod_deger where liste_id=(select id from public.kod_liste where kod='ariza.oncelik') and deger=t.oncelik and dil=0) as oncelik_adi,
       t.demirbas_id, coalesce(d.ad,'') as demirbas_adi,
       t.talep_eden, coalesce(nullif(trim(te.ad||' '||te.soyad),''),te.unvan,'') as talep_eden_adi,
       t.sorumlu_id, coalesce(nullif(trim(so.ad||' '||so.soyad),''),so.unvan,'') as sorumlu_adi,
       t.durum,
       (select ad from public.kod_deger where liste_id=(select id from public.kod_liste where kod='ariza.durum') and deger=t.durum and dil=0) as durum_adi,
       t.cozum_notu, t.kapanis_tarihi, t.sube_id, t.ekleme_tarihi
  from public.ariza_talep t
  left join public.demirbas d on d.id = t.demirbas_id
  left join public.taraf te on te.id = t.talep_eden
  left join public.taraf so on so.id = t.sorumlu_id;

-- ------------------------------------------------------------- yetki ----
insert into public.yetki (kod, ad, grup, tur, sira, aktif, urun_modu, modul)
select v.kod, v.ad, 'Teknik Servis', 0, v.sira, 1, 2, 'servis'
  from (values ('ariza','Arıza Talepleri (ekip)',60),
               ('ariza.talep','Arıza Bildir (self-servis)',61)) v(kod,ad,sira)
 where not exists (select 1 from public.yetki y where y.kod = v.kod);

-- Herkese (tüm rollere) self-servis 'ariza.talep' GÖR+EKLE; ekip yetkisi
--   'ariza' yalnız yöneticide (kurulumda ekiplere verilir).
insert into public.rol_yetki (rol_id, yetki_id, gor, ekle, degistir, sil, ekleyen)
select r.id, y.id, 1, 1, 0, 0, 0
  from public.rol r cross join public.yetki y
 where y.kod = 'ariza.talep'
   and not exists (select 1 from public.rol_yetki x where x.rol_id=r.id and x.yetki_id=y.id);
insert into public.rol_yetki (rol_id, yetki_id, gor, ekle, degistir, sil, ekleyen)
select r.id, y.id, 1, 1, 1, 1, 0
  from public.rol r cross join public.yetki y
 where r.kod = 'yonetici' and y.kod = 'ariza'
   and not exists (select 1 from public.rol_yetki x where x.rol_id=r.id and x.yetki_id=y.id);
update public.rol set yetki_surumu = yetki_surumu + 1;

do $$
begin
    raise notice '911 tamam: ariza_talep tablosu %, kategori-ekip %',
        (select count(*) from public.ariza_talep),
        (select count(*) from public.ariza_kategori_ekip);
end $$;
