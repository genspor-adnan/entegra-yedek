-- Bir muayeneye uygulanan şablonlar. kisisel: 1 doktorun kendi, 0 bölüm ortak,
--   2 muayeneye uygulanmış (bölüm/doktor dışı da olabilir).
create or replace function public.fn_muayene_sablon_kapsami(p_muayene integer)
returns table (sablon_id integer, kisisel smallint)
language sql stable as $$
  select s.id, case when s.hekim_id is not null then 1 else 0 end::smallint
    from public.muayene m
    join public.muayene_sablon s
      on s.durum = 1 and s.bolum_id = m.bolum_id
     and (s.hekim_id is null or s.hekim_id = m.personel_id)
   where m.id = p_muayene
  union
  select m.sablon_id, 2::smallint
    from public.muayene m
   where m.id = p_muayene and m.sablon_id is not null
     and not exists (select 1 from public.muayene_sablon s
                      where s.id = m.sablon_id and s.durum = 1 and s.bolum_id = m.bolum_id
                        and (s.hekim_id is null or s.hekim_id = m.personel_id))
$$;

