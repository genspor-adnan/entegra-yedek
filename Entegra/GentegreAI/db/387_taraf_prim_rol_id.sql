-- ============================================================================
--  387 - taraf_prim_rol'e ID KOLONU
--
--  Personel kartindaki "Prim Rolleri" gridine satir eklemek 500 veriyordu:
--      42703: column "id" does not exist
--
--  Kart cercevesi (KartDeposu.Detay) her detay satirini `id` ile adresler -
--  insert'te `returning id`, update/delete'te `where id = ... and <ust> = ...`.
--  Bu tablonun anahtari (taraf_id, rol) ikilisiydi, `id` kolonu yoktu; yani
--  grid HIC calismiyordu ve bu ancak "İsteyen rolu isaretle" denendiginde
--  ortaya cikti - rol isaretlemek nadir bir islem oldugu icin aylarca sessiz
--  kalabilirdi.
--
--  ANAHTAR BOZULMUYOR: (taraf_id, rol) benzersizligi PK olarak kaliyor; `id`
--  yalnizca satiri adreslemek icin eklenen teknik bir kolon. Ayni kisiye ayni
--  rolu iki kez yazmak hala imkansiz.
-- ============================================================================

alter table public.taraf_prim_rol
  add column if not exists id integer generated by default as identity;

-- Cerceve satiri `id` ile buluyor: benzersiz olmali (PK degil - PK
--   (taraf_id, rol) ikilisi, is kurali orada).
create unique index if not exists ux_taraf_prim_rol_id on public.taraf_prim_rol (id);

comment on column public.taraf_prim_rol.id is
  'Teknik satir kimligi (387): kart cercevesi detay satirlarini id ile '
  'adresler. IS ANAHTARI hala (taraf_id, rol) - ayni role iki kayit yazilamaz.';
