-- =====================================================================
--  738_onay_omurgasi.sql
--  MODÜLDEN BAĞIMSIZ ONAY OMURGASI.
--
--  ============= NEDEN BEŞİNCİ BİR ONAY TABLOSU DEĞİL =================
--  Bugün dört yarım mekanizma var: `satinalma_onay` (tutar/bütçe eşikli
--  zincir, kuralları C# içinde), `dokuman_akis`+`dokuman_onay` (gerçek bir
--  akış motoru ama yalnız dokümana bağlı), `iskonto_talep` (kendi durumu) ve
--  `personel_izin` (yalnız `durum` kolonu - onaylayanı bile yok). İzin, avans
--  ve arıza onarımı için beşincisini yazmak, aynı işi beş yerde bakımı
--  gereken beş koda çevirirdi: vekâlet, süre aşımı, ret dalı, log ve gelen
--  kutusu her birinde ayrı ayrı yazılırdı.
--
--  Buradaki tablolar `dokuman_akis` motorunun genelleştirilmiş hâlidir:
--  tanım (akış + adım) ile yürüyen örnek (onay + adım) ayrı durur.
--
--  ============= KAYNAK BAĞI: tablo_id + kayıt id ======================
--  Onay herhangi bir kayda bağlanır. Bağ için YENİ bir numaralandırma
--  uydurmuyoruz: kurumda zaten `islem_log.tablo_id` var ve katalogdaki her
--  kart/detay onu taşıyor (satınalma talebi 1241, mal kabul 1247...).
--  İkinci bir "kaynak türü" listesi açsaydık aynı tablo iki ayrı numarayla
--  anılır, log ile onay kaydı birbirine bağlanamazdı.
--
--  ============= ADIMIN SAHİBİ: ROL (şimdilik) ========================
--  Adım bir ROLE düşer (`satinalma_onay.rol` ile aynı dil: 1 birim · 2
--  satınalma · 4 mali · 5 üst yönetim) ya da doğrudan bir KULLANICIYA.
--  Kişinin âmirine düşürmek (organizasyon şeması) üçüncü bir seçenek olarak
--  `sahip_turu = 3` ile ayrılmıştır ama HENÜZ ÇÖZÜLMÜYOR - `personel_gorev`
--  ağacında âmir bağı kurulu değil; olmayan bir bağa dayanan akış, ilk
--  talepte "onaylayacak kimse yok" ile dururdu.
-- =====================================================================

-- =========================================================== AKIŞ TANIMI
create table if not exists public.onay_akis (
    id                integer      primary key generated by default as identity,
    kod               varchar(40)  not null,
    ad                varchar(120) not null default '',
    -- KAYNAK TÜRÜ = islem_log.tablo_id (bkz. başlık).
    kaynak_tur        integer      not null,
    -- ÖLÇÜ ADI: adım koşullarının baktığı sayı ne demek ("Tutar (TL)",
    --   "Gün", "Maliyet"). Koşul ekranında kullanıcı neyi eşiklediğini
    --   görsün diye tanımda durur.
    olcu_adi          varchar(40)  not null default '',
    aktif             smallint     not null default 1,
    aciklama          varchar(400) not null default '',
    sube_id           integer,
    ekleyen           integer      not null default 0,
    ekleme_tarihi     timestamptz  not null default now(),
    degistiren        integer      not null default 0,
    degistirme_tarihi timestamptz
);

create unique index if not exists ux_onay_akis_kod on public.onay_akis (kod);
create index if not exists ix_onay_akis_kaynak on public.onay_akis (kaynak_tur, aktif);

comment on table public.onay_akis is
  '738: modulden bagimsiz onay akisi tanimi. kaynak_tur = islem_log.tablo_id.';

create table if not exists public.onay_akis_adim (
    id                integer      primary key generated by default as identity,
    akis_id           integer      not null references public.onay_akis (id) on delete cascade,
    sira              smallint     not null default 1,
    ad                varchar(60)  not null default '',
    -- SAHİP: 1 rol · 2 kullanıcı · 3 âmir (bkz. başlık - henüz çözülmüyor).
    sahip_turu        smallint     not null default 1,
    rol               smallint     not null default 0,
    kullanici_id      integer,
    -- KOŞUL: adım yalnız ölçü eşiği aşılınca eklenir. `esik_alt` null ise
    --   adım HER talepte vardır (birim sorumlusu gibi).
    --   Eşik KURALIN YANINDA, koda gömülü değil: satınalmada üç eşik C#
    --   içinde `if` idi; izinde gün, avansta maaş katı olacak - üç ayrı
    --   dal yazmak yerine aynı karşılaştırma tabloda duruyor.
    esik_alt          numeric(18,4),
    -- BAYRAK KOŞULU: sayıya sığmayan durum ("bütçe aşıldı"). Motor bunu
    --   çağırandan bayrak kümesi olarak alır; adım bu bayrak varsa eklenir.
    bayrak            varchar(40)  not null default '',
    -- 0 onay/ret · 1 yalnız bilgilendirme (karar beklemez).
    karar_turu        smallint     not null default 0,
    -- SÜRE: adım bu kadar günde karara bağlanmazsa gecikmiş sayılır.
    --   Kimseyi otomatik onaylamaz - sessiz onay, onayın kendisini ortadan
    --   kaldırırdı; yalnız hatırlatma ve gecikme raporu içindir.
    sure_gun          smallint     not null default 0,
    e_imza_zorunlu    smallint     not null default 0,
    aktif             smallint     not null default 1,
    ekleyen           integer      not null default 0,
    ekleme_tarihi     timestamptz  not null default now(),
    degistiren        integer      not null default 0,
    degistirme_tarihi timestamptz
);

create index if not exists ix_onay_akis_adim_akis on public.onay_akis_adim (akis_id, sira);

comment on table public.onay_akis_adim is
  '738: akis basamagi. Esik/bayrak kosulu KURALIN YANINDA durur - satinalmada '
  'bu esikler C# icinde if dallariydi.';

-- ======================================================= YÜRÜYEN ONAY
create table if not exists public.onay (
    id                bigint       primary key generated by default as identity,
    akis_id           integer      references public.onay_akis (id),
    kaynak_tur        integer      not null,
    kaynak_id         bigint       not null,
    sube_id           integer      not null,
    -- KARAR ÖLÇÜSÜ zincir kurulurken DONDURULUR: talep sonradan pahalılaşsa
    --   bile verilmiş imzalar hangi tutara verildiyse o kalır. Zincir
    --   yeniden kurulursa ölçü de tazelenir - ama bu bilinçli bir işlemdir.
    olcu              numeric(18,4) not null default 0,
    bayraklar         varchar(200) not null default '',
    -- 0 yürüyor · 1 onaylandı · 2 reddedildi · 3 iptal.
    durum             smallint     not null default 0,
    baslatan_id       integer      not null default 0,
    baslama           timestamptz  not null default now(),
    bitis             timestamptz,
    ekleyen           integer      not null default 0,
    ekleme_tarihi     timestamptz  not null default now(),
    degistiren        integer      not null default 0,
    degistirme_tarihi timestamptz
);

-- BİR KAYDIN TEK AÇIK ONAYI OLUR: ikinci bir zincir açılsaydı iki ayrı
--   imza dizisi aynı kaydı farklı sonuçlara götürebilirdi.
create unique index if not exists ux_onay_acik
    on public.onay (kaynak_tur, kaynak_id) where durum = 0;
create index if not exists ix_onay_kaynak on public.onay (kaynak_tur, kaynak_id);

comment on table public.onay is
  '738: bir kaydin yuruyen onay zinciri. kaynak_tur = islem_log.tablo_id.';

create table if not exists public.onay_adim (
    id                bigint       primary key generated by default as identity,
    onay_id           bigint       not null references public.onay (id) on delete cascade,
    sira              smallint     not null default 1,
    ad                varchar(60)  not null default '',
    sahip_turu        smallint     not null default 1,
    rol               smallint     not null default 0,
    atanan_kullanici_id integer,
    -- 0 bekliyor · 1 onaylandı · 2 reddedildi · 3 bilgi istendi
    --   · 4 sözlü onay · 5 atlandı.
    --
    --   BİLGİ İSTENDİ ZİNCİRİ DURDURUR AMA BİTİRMEZ (satınalmadan gelen
    --   kural): basamak hâlâ bekleyendir.
    --   SÖZLÜ ONAY yazılı tamamlama süresi taşır - acil işte imza beklemek
    --   ameliyatı geciktirir, ama sözlü onay kalıcı kayıt değildir.
    durum             smallint     not null default 0,
    karar_veren_id    integer,
    karar_zamani      timestamptz,
    gerekce           varchar(400) not null default '',
    yazili_son        timestamptz,
    -- SÜRE AŞIMI: adım açıldığında hesaplanır (akış adımının `sure_gun`i).
    termin            timestamptz,
    ekleyen           integer      not null default 0,
    ekleme_tarihi     timestamptz  not null default now(),
    degistiren        integer      not null default 0,
    degistirme_tarihi timestamptz
);

create unique index if not exists ux_onay_adim_sira on public.onay_adim (onay_id, sira);
create index if not exists ix_onay_adim_bekleyen
    on public.onay_adim (durum, rol) where durum in (0, 3);

comment on table public.onay_adim is
  '738: yuruyen zincirin basamagi. durum 3 (bilgi istendi) zinciri DURDURUR '
  'ama bitirmez - basamak hala bekleyendir.';

-- ============================================================= VEKÂLET
-- İZİNDEKİ ÂMİRİN KUTUSUNDA TALEP BEKLEMESİN. Vekâlet olmadan onay zinciri
--   kişinin izniyle birlikte duruyor; kurum da çareyi "şifresini ver" ile
--   buluyor - imzanın kime ait olduğu o noktada kaybolur.
create table if not exists public.onay_vekalet (
    id                integer      primary key generated by default as identity,
    devreden_id       integer      not null,
    devralan_id       integer      not null,
    baslangic         date         not null,
    bitis             date         not null,
    -- Boşsa TÜM akışlar; doluysa yalnız o akış.
    akis_id           integer      references public.onay_akis (id),
    aciklama          varchar(200) not null default '',
    aktif             smallint     not null default 1,
    sube_id           integer,
    ekleyen           integer      not null default 0,
    ekleme_tarihi     timestamptz  not null default now(),
    degistiren        integer      not null default 0,
    degistirme_tarihi timestamptz
);

create index if not exists ix_onay_vekalet_devralan
    on public.onay_vekalet (devralan_id, aktif);

comment on table public.onay_vekalet is
  '738: onay yetkisinin gecici devri. Devredilen imza DEVRALANIN adiyla '
  'atilir - kimin imzaladigi kaybolmaz.';

-- ===================================================== GELEN KUTUSU GÖRÜNÜMÜ
-- TEK KUTU: kullanıcı "onayımda ne var" sorusunu tür tür ekran gezerek
--   yanıtlamasın. Satınalma onayı bugün yalnız Talepler listesinden
--   görünüyor; izin gelince ikinci bir yere bakmak gerekirdi.
create or replace view public.v_onay_bekleyen as
select a.id                                   as adim_id,
       o.id                                   as onay_id,
       o.kaynak_tur,
       o.kaynak_id,
       o.sube_id,
       o.olcu,
       o.baslatan_id,
       o.baslama,
       k.kod                                  as akis_kod,
       k.ad                                   as akis_ad,
       k.olcu_adi,
       a.sira,
       a.ad                                   as adim_ad,
       a.sahip_turu,
       a.rol,
       a.atanan_kullanici_id,
       a.durum,
       a.gerekce,
       a.termin,
       -- GECİKME GÜN: termin geçmişse kaç gün. Sessiz onay yok; bu sayı
       --   yalnız hatırlatma ve rapor içindir.
       case when a.termin is not null and a.termin < now()
            then (date_part('day', now() - a.termin))::int else 0 end as gecikme_gun
  from public.onay_adim a
  join public.onay o     on o.id = a.onay_id
  left join public.onay_akis k on k.id = o.akis_id
 where o.durum = 0 and a.durum in (0, 3);

comment on view public.v_onay_bekleyen is
  '738: butun modullerin bekleyen onay basamaklari - tek gelen kutusu.';

-- ================================================ SATINALMA AKIŞ TOHUMU
-- 729'da C# içinde duran zincir (birim → satınalma → mali → üst yönetim)
--   artık veri. Eşikler `referans` ayarlarından TAŞINMADI, çünkü ayar
--   tek bir sayıdır; burada eşik ADIMIN kendi özelliğidir ve ikinci bir
--   akış (or. "acil satınalma") farklı eşiklerle tanımlanabilir.
insert into public.onay_akis (kod, ad, kaynak_tur, olcu_adi, aktif, aciklama, ekleyen)
select 'satinalma.talep', 'Satınalma Talebi Onayı', 1241, 'Tutar (TL)', 1,
       '724/729 zinciri: birim sorumlusu her talepte; tutar esigine gore '
       'satinalma ve mali isler; ust sinir ya da butce asiminda ust yonetim.', 0
 where not exists (select 1 from public.onay_akis where kod = 'satinalma.talep');

insert into public.onay_akis_adim
       (akis_id, sira, ad, sahip_turu, rol, esik_alt, bayrak, sure_gun, ekleyen)
select k.id, x.sira, x.ad, 1, x.rol, x.esik, x.bayrak, x.sure, 0
  from public.onay_akis k
  cross join (values
        -- BİRİM SORUMLUSU HER TALEPTE: talebi açanın âmiri, talebin
        --   gerçekten o birimin işi olduğunu söyleyen tek kişidir.
        (1::smallint, 'Birim Sorumlusu', 1::smallint, null::numeric, '',        3::smallint),
        (2::smallint, 'Satınalma',       2::smallint, 0::numeric,    '',        3::smallint),
        (3::smallint, 'Mali İşler',      4::smallint, 50000::numeric, '',       3::smallint),
        -- BÜTÇESİ OLMAYAN/AŞAN HARCAMA mali işlere ayrıca sorulur.
        (4::smallint, 'Mali İşler (bütçe)', 4::smallint, null::numeric, 'butce', 3::smallint),
        (5::smallint, 'Üst Yönetim',     5::smallint, 250000::numeric, '',      5::smallint),
        (6::smallint, 'Üst Yönetim (bütçe aşımı)', 5::smallint, null::numeric, 'butce_asildi', 5::smallint)
      ) as x(sira, ad, rol, esik, bayrak, sure)
 where k.kod = 'satinalma.talep'
   and not exists (select 1 from public.onay_akis_adim a where a.akis_id = k.id);

-- ======================================== ESKİ ZİNCİRLER OMURGAYA TAŞINIR
-- `satinalma_onay` SİLİNMİYOR: göç geri alınamaz değildir ve müşteride
--   yürüyen onay olabilir. Veriyi kopyalıyoruz, eski tablo yerinde duruyor;
--   okuma/yazma yeni omurgaya geçtikten sonra bir dahaki sürümde düşer.
insert into public.onay (akis_id, kaynak_tur, kaynak_id, sube_id, olcu, durum,
                         baslatan_id, baslama, bitis, ekleyen, ekleme_tarihi)
select (select id from public.onay_akis where kod = 'satinalma.talep'),
       1241, t.id, t.sube_id, coalesce(t.tahmini_tutar, 0),
       case when t.durum = 3 then 1        -- onaylandı
            when t.durum = 4 then 2        -- reddedildi
            else 0 end,
       t.ekleyen, min(o.ekleme_tarihi),
       case when t.durum in (3, 4) then max(o.karar_zamani) end,
       0, min(o.ekleme_tarihi)
  from public.satinalma_talep t
  join public.satinalma_onay o on o.talep_id = t.id
 where not exists (select 1 from public.onay n
                    where n.kaynak_tur = 1241 and n.kaynak_id = t.id)
 group by t.id, t.sube_id, t.tahmini_tutar, t.durum, t.ekleyen;

insert into public.onay_adim (onay_id, sira, ad, sahip_turu, rol, durum,
                              karar_veren_id, karar_zamani, gerekce, yazili_son,
                              ekleyen, ekleme_tarihi)
select n.id, o.basamak,
       case o.rol when 1 then 'Birim Sorumlusu' when 2 then 'Satınalma'
                  when 4 then 'Mali İşler' else 'Üst Yönetim' end,
       1, o.rol, o.durum, o.onaylayan_id, o.karar_zamani, o.gerekce, o.yazili_son,
       o.ekleyen, o.ekleme_tarihi
  from public.satinalma_onay o
  join public.onay n on n.kaynak_tur = 1241 and n.kaynak_id = o.talep_id
 where not exists (select 1 from public.onay_adim a
                    where a.onay_id = n.id and a.sira = o.basamak);

comment on table public.satinalma_onay is
  '724: ESKI onay zinciri - 738 omurgasina tasindi (onay / onay_adim). '
  'Veri korunuyor; yeni yazma buraya YAPILMAZ.';
