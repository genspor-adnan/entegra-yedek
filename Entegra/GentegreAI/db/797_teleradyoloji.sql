    aylik_adet_siniri  integer     not null default 0,
    acil_ek_oran       numeric(5,2) not null default 0,
    oncelikli_ek_oran  numeric(5,2) not null default 0,
    -- SLA DAKIKA: oncelige gore ayri. Isteğe kopyalanir (asagidaki tetik) -
    --   sozlesme sonradan degisince GECMIS istegin sozu degismesin.
