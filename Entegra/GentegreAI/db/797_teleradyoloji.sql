-- ---------------------------------------------------------------- kurum ----
create table if not exists public.telerad_kurum (
    id                integer generated by default as identity primary key,
    -- CARIYE BAGLI: fatura, tahsilat ve bakiye zaten orada. Teleradyoloji
    --   kurumu ayri bir "musteri" degil, carinin bir OZELLIGIDIR.
    taraf_id          integer      not null references public.taraf(id),
    yon               smallint     not null default 1,   -- 1 gelen · 2 giden · 3 iki yon
    tesis_kodu        varchar(10)  not null default '',
    dicom_ae_title    varchar(16)  not null default '',
    dicom_host        varchar(120) not null default '',
    dicom_port        integer      not null default 0,
    hl7_adres         varchar(120) not null default '',
    hl7_tur           smallint     not null default 0,   -- 0 portal · 1 ORU MLLP · 2 REST · 3 FHIR
    rapor_sablon_id   integer      references public.radyoloji_sablon(id),
    gece_nobet        smallint     not null default 0,
    varsayilan_oncelik smallint    not null default 1,
    onam_zorunlu      smallint     not null default 0,
    aktif             smallint     not null default 1,
    sube_id           integer      references public.sube(id),
    ekleyen           integer      not null default 0,
    ekleme_tarihi     timestamptz  not null default now(),
    degistiren        integer      not null default 0,
    degistirme_tarihi timestamptz,
    constraint ck_telerad_kurum_yon check (yon between 1 and 3),
    constraint ux_telerad_kurum_taraf unique (taraf_id)
);

