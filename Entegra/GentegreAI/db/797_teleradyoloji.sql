-- -------------------------------------------------- istek numarasi ---------
-- TR-yyyy/nnnnn · yil basinda 1'e doner (numara_sablonu deseni yerine burada
--   dogrudan: telerad kendi serisini kullanir, belge numarasiyla karismaz).
create or replace function public.fn_telerad_istek_no(p_tarih date default current_date)
returns varchar
language plpgsql
as $function$
declare
    v_yil  integer := extract(year from p_tarih)::int;
    v_son  integer;
begin
    select coalesce(max(nullif(split_part(istek_no, '/', 2), '')::int), 0)
      into v_son
      from public.telerad_istek
     where istek_no like 'TR-' || v_yil || '/%';
    return 'TR-' || v_yil || '/' || lpad((v_son + 1)::text, 5, '0');
end $function$;

-- ------------------------------------------------- istek kurallari ---------
create or replace function public.tg_telerad_istek()
returns trigger
language plpgsql
as $function$
declare
    v_sla integer;
begin
    if tg_op = 'INSERT' then
        if coalesce(new.istek_no, '') = '' then
            new.istek_no := public.fn_telerad_istek_no(coalesce(new.cekim_zamani::date, current_date));
        end if;
        -- SOZLESME: verilmediyse kurumun O TARIHTE aktif sozlesmesi.
        if new.sozlesme_id is null then
            select s.id into new.sozlesme_id
              from public.telerad_sozlesme s
             where s.kurum_id = new.kurum_id and s.durum = 1
               and s.baslangic <= coalesce(new.cekim_zamani::date, current_date)
               and (s.bitis is null or s.bitis >= coalesce(new.cekim_zamani::date, current_date))
             order by s.baslangic desc limit 1;
        end if;
    end if;

    -- SLA SOZLESMEDEN KOPYALANIR (tetkik anindaki soz gecerlidir) ve
    --   GORUNTU GELDIGI AN baslar - istek acildigi an degil.
    if new.sla_dk = 0 and new.sozlesme_id is not null then
        select case new.oncelik when 3 then s.sla_acil_dk
                                when 2 then s.sla_oncelikli_dk
                                else s.sla_rutin_dk end
          into v_sla
          from public.telerad_sozlesme s where s.id = new.sozlesme_id;
        new.sla_dk := coalesce(v_sla, 0);
    end if;

    if new.gelis_zamani is not null and new.sla_dk > 0 then
        new.sla_bitis := new.gelis_zamani + make_interval(mins => new.sla_dk);
    end if;

    -- GORUNTU GELDI -> SIRADA. Durumu elle geriye almak serbest (ek goruntu
    --   istendi gibi); burada yalniz "bekliyordu, geldi" gecisi yazilir.
    if new.goruntu_durum = 1 and new.durum = 1 then new.durum := 2; end if;

    -- ATAMA -> durum en az "atandi"; atama kalkinca sıraya döner.
    if new.atanan_radyolog_id is not null and new.durum = 2 then new.durum := 3; end if;
    if new.atanan_radyolog_id is null and new.durum = 3 then new.durum := 2; end if;

    -- ONAY: zaman damgasi + SLA asimi KARARI burada verilir (tek yer).
    if new.durum >= 6 and new.onay_zamani is null then
        new.onay_zamani := now()::timestamp;
    end if;
    if new.onay_zamani is not null and new.sla_bitis is not null then
        new.sla_asildi := case when new.onay_zamani > new.sla_bitis then 1 else 0 end;
    end if;

    if tg_op = 'UPDATE' then new.degistirme_tarihi := now(); end if;
    return new;
end $function$;

comment on function public.tg_telerad_istek() is
  '797: istek numarasi, sozlesme cozumu, SLA kopyasi ve durum gecisleri TEK '
  'yerde - ekran, API ve ice aktarim ayni kurala carpsin.';

drop trigger if exists tg_telerad_istek on public.telerad_istek;
create trigger tg_telerad_istek
    before insert or update on public.telerad_istek
    for each row execute function public.tg_telerad_istek();

-- ---------------------------------------------- atama gecmisi tetigi -------
create or replace function public.tg_telerad_atama_izi()
returns trigger
language plpgsql
as $function$
begin
    if new.atanan_radyolog_id is distinct from old.atanan_radyolog_id then
        -- Onceki atamayi kapat.
        update public.telerad_atama
           set birakma_zamani = now()
         where istek_id = new.id and birakma_zamani is null;

        if new.atanan_radyolog_id is not null then
            insert into public.telerad_atama (istek_id, radyolog_id, atayan_id, neden)
            values (new.id, new.atanan_radyolog_id, nullif(new.degistiren, 0),
                    case when old.atanan_radyolog_id is null then 2 else 3 end);
        end if;
    end if;
    return new;
end $function$;

comment on function public.tg_telerad_atama_izi() is
  '797: atama degisince gecmis KENDILIGINDEN yazilir - "kim atamis" sorusu '
  'ekranin hatirlamasina birakilmaz.';

drop trigger if exists tg_telerad_atama_izi on public.telerad_istek;
create trigger tg_telerad_atama_izi
    after update of atanan_radyolog_id on public.telerad_istek
    for each row execute function public.tg_telerad_atama_izi();

-- ------------------------------------------------------- calisma listesi ---
create or replace view public.v_telerad_istek as
select i.id, i.istek_no, i.kurum_id, k.taraf_id as kurum_taraf_id,
       coalesce(kt.unvan, '')                as kurum_adi,
       i.yon, i.oncelik,
       coalesce(h.unvan, i.dis_hasta_kimlik) as hasta_adi,
       i.dis_hasta_kimlik, i.dis_erisim_no, i.modalite,
       coalesce(hz.ad, '')                   as tetkik_adi,
       i.klinik_bilgi, i.cekim_zamani, i.gelis_zamani, i.sla_dk, i.sla_bitis,
       -- KALAN DAKIKA: eksi deger gecikmeyi anlatir. Ekran bunu hesaplamasin -
       --   iki ekran iki farkli "simdi" kullanirsa liste kendi icinde celisir.
       case when i.sla_bitis is null or i.durum >= 6 then null
            else floor(extract(epoch from (i.sla_bitis - now())) / 60)::int end as kalan_dk,
       case when i.durum < 6 and i.sla_bitis is not null and now() > i.sla_bitis
            then 1 else 0 end::smallint as sla_riskli,
       i.sla_asildi, i.goruntu_sayisi, i.seri_sayisi, i.goruntu_durum,
       i.durum, i.atanan_radyolog_id,
       coalesce(r.unvan, '')                 as radyolog_adi,
       i.okuma_bas, i.onay_zamani, i.teslim_zamani, i.teslim_durum,
       i.ucret, i.radyoloji_istem_id, i.rapor_id, i.sube_id, i.fatura_belge_id
  from public.telerad_istek i
  join public.telerad_kurum k  on k.id = i.kurum_id
  left join public.taraf kt    on kt.id = k.taraf_id
  left join public.taraf h     on h.id = i.hasta_id
  left join public.taraf r     on r.id = i.atanan_radyolog_id
  left join public.hizmet hz   on hz.id = i.tetkik_hizmet_id;

comment on view public.v_telerad_istek is
  '797: teleradyoloji calisma listesi - kalan SLA dakikasi ve risk isareti '
  'SUNUCUDA hesaplanir (iki ekran iki farkli "simdi" kullanmasin).';

-- --------------------------------------------- yetki dagitimi -------------
-- YENI YETKI KIMSEDE YOKSA EKRAN DA YOK: yonetici dahil hicbir rol yeni
--   yetkiyi kendiliginden almaz (her goc kendi dagitimini yapar). Bu blok
--   olmadan menude teleradyoloji hic gorunmuyordu - modul acik olsa bile.
insert into public.rol_yetki (rol_id, yetki_id, gor, ekle, degistir, sil, deger)
select r.id, y.id, 1,
       -- SALT OKUMA ROLLERI YAZMAZ (788): yonetim goruntuleyici ve ust yonetim
       --   her seyi gorur, hicbir seyi degistirmez - ekle/degistir 0.
       case when y.tur = 0 and r.kod not in ('rapor_goruntuleyici', 'ust_yonetim')
            then 1 else 0 end,
       case when y.tur = 0 and r.kod not in ('rapor_goruntuleyici', 'ust_yonetim')
            then 1 else 0 end,
       case when y.tur = 0 and r.kod = 'yonetici' then 1 else 0 end, ''
  from public.rol r
  join public.yetki y on y.modul = 'teleradyoloji'
 where (r.kod = 'yonetici')
    -- KLINIK TARAF: calisma listesi + atama + teslim.
    or (r.kod in ('radyolog', 'teleradyoloji_hekim')
        and y.kod in ('teleradyoloji', 'telerad.ata', 'telerad.teslim'))
    -- TICARI TARAF: kurum, sozlesme, donem faturasi.
    or (r.kod in ('muhasebe', 'muhasebe_sorumlu')
        and y.kod in ('teleradyoloji.kurum', 'teleradyoloji.sozlesme', 'telerad.faturala'))
    -- SALT OKUMA: yonetim goruntuleyici her seyi gorur, yazmaz.
    or (r.kod in ('rapor_goruntuleyici', 'ust_yonetim') and y.tur = 0)
   and not exists (select 1 from public.rol_yetki ry
                    where ry.rol_id = r.id and ry.yetki_id = y.id)
on conflict (rol_id, yetki_id) do nothing;

do $$
declare v_yetki int;
begin
    select count(*) into v_yetki from public.yetki where modul = 'teleradyoloji';
    raise notice '797 tamam: telerad_kurum/sozlesme/istek/atama kuruldu, % yetki. '
                 'DICOM alimi, HL7 teslimi, otomatik atama ve nobet SONRAKI faz.',
                 v_yetki;
end $$;
