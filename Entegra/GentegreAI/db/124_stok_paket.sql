-- ============================================================================
--  Gentegre AI — PAKET (set) STOK
--  124_stok_paket.sql
--
--  Bazi stoklar tek basina degil, icinde baska stoklar olan bir PAKET olarak
--  satilir (implant seti, kampanya paketi, kit). Bugune kadar boyle bir kavram
--  yoktu: paketi satan kullanici icerigi elle kalem kalem giriyordu.
--
--  stok.paket = 1 -> stok kartinda "Paket" sekmesi acilir, icerik burada
--  tanimlanir. Paket olmayan stokta sekme HIC gorunmez.
--
--  AYRI URUN AGACI TABLOSU DEGIL: uretim recetesi (URETIMRECETE) baska bir sey -
--  o hammaddeden mamul URETIR, stok hareketi yaratir. Paket ise SATIS
--  duzeyinde bir demettir; icerigi burada, tek seviyede tutulur.
--
--  IC ICE PAKET YOK (bilerek): bir paketin icine baska bir paket konulamaz -
--  aksi halde miktar carpimi ve dongusel referans kontrolu gerekirdi; ihtiyac
--  cikarsa ayri bir istir. Tetik bunu engeller.
-- ============================================================================
\set ON_ERROR_STOP on

alter table public.stok add column if not exists paket smallint not null default 0;

comment on column public.stok.paket is
  'Bu stok bir PAKET mi (124). 1 ise kartta Paket sekmesi acilir, icerik stok_paket''te.';

create index if not exists ix_stok_paket on public.stok (paket) where paket = 1;

create table if not exists public.stok_paket (
    id                bigint generated by default as identity primary key,
    paket_stok_id     integer not null references public.stok(id) on delete cascade,
    icerik_stok_id    integer not null references public.stok(id),
    sira              smallint not null default 0,
    birim             smallint not null default 0,
    adet              numeric(19,4) not null default 1,
    ekleyen           integer   not null default 0,
    ekleme_tarihi     timestamp not null default now()::timestamp,
    degistiren        integer   not null default 0,
    degistirme_tarihi timestamp,

    constraint ck_stok_paket_kendisi check (paket_stok_id <> icerik_stok_id),
    constraint ck_stok_paket_adet    check (adet > 0)
);

comment on table public.stok_paket is
  'Paket icerigi (124): hangi pakette hangi stoktan kac adet. Tek seviye - ic ice paket yok.';

create index if not exists ix_stok_paket_ust    on public.stok_paket (paket_stok_id, sira);
create index if not exists ix_stok_paket_icerik on public.stok_paket (icerik_stok_id);
create unique index if not exists ux_stok_paket_satir
    on public.stok_paket (paket_stok_id, icerik_stok_id);

do $$
begin
    if not exists (select 1 from pg_trigger where tgname = 'trg_stok_paket_degistirme') then
        create trigger trg_stok_paket_degistirme before update on public.stok_paket
            for each row execute function public.fn_degistirme_tarihi();
    end if;
end $$;

-- IC ICE PAKET ENGELI: icerige baska bir PAKET eklenemez. Uygulamaya birakilsa
--   ikinci bir ekran unutur ve miktar hesabi sessizce yanlis cikardi.
create or replace function public.fn_stok_paket_kontrol() returns trigger
language plpgsql as $$
begin
    if exists (select 1 from public.stok s where s.id = new.icerik_stok_id and s.paket = 1) then
        raise exception 'Paket icine baska bir paket eklenemez (stok %).', new.icerik_stok_id
              using errcode = 'check_violation';
    end if;
    return new;
end $$;

do $$
begin
    if not exists (select 1 from pg_trigger where tgname = 'trg_stok_paket_kontrol') then
        create trigger trg_stok_paket_kontrol before insert or update on public.stok_paket
            for each row execute function public.fn_stok_paket_kontrol();
    end if;
end $$;

do $$
declare v_paket integer;
begin
    select count(*) into v_paket from public.stok where paket = 1;
    raise notice '124 tamam: stok_paket hazir, % paket stok', v_paket;
end $$;
