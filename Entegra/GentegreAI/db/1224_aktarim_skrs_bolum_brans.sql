-- Yok sayılan yazımlar (bölüm / branş değil): adayı yok, masada "yok say" önerilir.
create or replace function public.fn_skrs_yok_say(p text) returns boolean language sql immutable as $$
  select public.fn_skrs_sade(p) in ('KENDI ISTEGI', 'HEKIM DISI', '') or coalesce(btrim(p), '') = ''
$$;

-- Bölüm adayları: sözlük (1.00) + departman ad benzerliği. kod = departman.id (metin).
create or replace function public.fn_skrs_bolum_adaylari(p text, p_n integer default 3)
returns table (kod varchar, ad varchar, puan numeric, dikkat text) language sql stable as $$
  with s as (select public.fn_skrs_sade(p) as s),
  hep as (
    select d.id::varchar as kod, (d.ad || coalesce(' · ' || nullif(d.kod, ''), ''))::varchar as ad, 1.00::numeric as puan,
           'sözlük'::text as dikkat
      from public.skrs_esanlam e join public.departman d on d.ad = e.hedef_ad, s
     where e.liste = 'bolum' and e.terim = s.s
    union all
    select d.id::varchar, (d.ad || coalesce(' · ' || nullif(d.kod, ''), ''))::varchar,
           similarity(public.fn_skrs_sade(d.ad), s.s)::numeric(4,2), null
      from public.departman d, s
     where coalesce(d.durum, 1) = 1 and public.fn_skrs_sade(d.ad) % s.s)
  select distinct on (kod) kod, ad, puan, case when dikkat = 'sözlük' then null else dikkat end
    from hep order by kod, puan desc
$$;

-- Branş adayları: sözlük + hekim.brans (SKRS) ad benzerliği. kod = SKRS branş kodu.
create or replace function public.fn_skrs_brans_adaylari(p text, p_n integer default 3)
returns table (kod varchar, ad varchar, puan numeric, dikkat text) language sql stable as $$
  with s as (select public.fn_skrs_sade(p) as s),
  b as (select d.deger::varchar as kod, d.ad::varchar as ad from public.kod_deger d join public.kod_liste l on l.id = d.liste_id
         where l.kod = 'hekim.brans' and d.dil = 0),
  hep as (
    select b.kod, b.ad, 1.00::numeric as puan from public.skrs_esanlam e join b on lower(b.ad) = lower(e.hedef_ad), s
     where e.liste = 'brans' and e.terim = s.s
    union all
    select b.kod, b.ad, similarity(public.fn_skrs_sade(b.ad), s.s)::numeric(4,2) from b, s where public.fn_skrs_sade(b.ad) % s.s)
  select distinct on (kod) kod, ad, puan, null::text from hep order by kod, puan desc
$$;

-- --------------------------------------------------------------- doldur ----
create or replace function public.fn_aktarim_esleme_doldur_metin(p_liste varchar) returns integer language plpgsql as $$
declare v_n integer;
begin
  if p_liste = 'bolum' and to_regclass('eski.gelisler') is not null then
    execute $q$
      insert into public.aktarim_esleme (liste, kayit_id, eski_kod, eski_ad, tur, kullanim, durum)
      select 'bolum', null, upper(btrim(coalesce(g.poliklinik, ''))), max(btrim(coalesce(g.poliklinik, ''))), 'BOLUM', count(*), 0
        from eski.gelisler g where coalesce(btrim(g.poliklinik), '') <> ''
       group by upper(btrim(coalesce(g.poliklinik, '')))
      on conflict (liste, eski_kod) where kayit_id is null do update set kullanim = excluded.kullanim
       where public.aktarim_esleme.uygulandi = 0 $q$;
  elsif p_liste = 'brans' and to_regclass('eski.doktorlar') is not null then
    execute $q$
      insert into public.aktarim_esleme (liste, kayit_id, eski_kod, eski_ad, tur, kullanim, durum)
      select 'brans', null, upper(btrim(coalesce(d.uzmanlik, ''))), max(btrim(coalesce(d.uzmanlik, ''))), 'BRANS', count(*), 0
        from eski.doktorlar d where coalesce(btrim(d.uzmanlik), '') <> ''
       group by upper(btrim(coalesce(d.uzmanlik, '')))
      on conflict (liste, eski_kod) where kayit_id is null do update set kullanim = excluded.kullanim
       where public.aktarim_esleme.uygulandi = 0 $q$;
  else
    raise notice 'eski şema yok (eski.gelisler / eski.doktorlar) - % doldurulmadı', p_liste;
  end if;

  update public.aktarim_esleme e
     set adaylar = coalesce((select jsonb_agg(jsonb_build_object('kod', a.kod, 'ad', a.ad, 'puan', a.puan, 'dikkat', a.dikkat)
                                              order by a.puan desc)
                               from (select * from public.fn_skrs_bolum_adaylari(e.eski_ad) where p_liste = 'bolum'
                                     union all
                                     select * from public.fn_skrs_brans_adaylari(e.eski_ad) where p_liste = 'brans'
                                     order by puan desc limit 3) a), '[]'::jsonb)
   where e.liste = p_liste and e.uygulandi = 0 and e.durum in (0, 3);
  -- Bölüm / branş olmayan yazım "yok say" önerisiyle gelir (karar kullanıcının).
  update public.aktarim_esleme set durum = case when jsonb_array_length(adaylar) = 0 then 3 else 0 end,
         notlar = case when public.fn_skrs_yok_say(eski_ad) and notlar = '' then 'Öneri: yok say (bölüm / branş değil)' else notlar end
   where liste = p_liste and uygulandi = 0 and durum in (0, 3);
  select count(*) into v_n from public.aktarim_esleme where liste = p_liste;
  return v_n;
end $$;

-- --------------------------------------------------------------- uygula ----
-- bolum: dış hekimin (aktarım) bölümü = en sık gönderdiği poliklinik, masadaki karara göre (yok say -> sayılmaz).
-- brans: dış hekimin (DOKTORLAR) branşı = UZMANLIK kararı; taraf_personel.brans (SKRS kod) + taraf.gorev_id (görev ağacı).
--   Uzmanlığı olmayan / yok sayılan hekimin branşına dokunulmaz.
create or replace function public.fn_aktarim_esleme_uygula_metin(p_liste varchar, p_kullanici integer) returns jsonb
language plpgsql as $$
declare v_n integer := 0;
begin
  if p_liste = 'bolum' then
    if to_regclass('eski.gelisler') is null then raise exception 'eski.gelisler yok - bölüm kararları uygulanamaz'; end if;
    execute $q$
      with ist as (
        select t2.id as taraf_id, upper(btrim(coalesce(g.poliklinik, ''))) as pol
          from eski.gelisler g
          join public.taraf t2 on t2.aktarim_kaynak = 2
           and ((t2.aktarim_tablo = 'DOKTORLAR' and t2.aktarim_id = g.doktorid)
                or (t2.aktarim_tablo = 'GELISLER.DOKTOR' and g.doktorid is null
                    and upper(btrim(g.doktor)) = upper(btrim(coalesce(t2.ad, '') || ' ' || coalesce(t2.soyad, ''))))))
      , sec as (
        select ist.taraf_id, e.secilen_kod::int as dep, count(*) as n
          from ist join public.aktarim_esleme e on e.liste = 'bolum' and e.eski_kod = ist.pol and e.durum = 1
                                                and e.secilen_kod ~ '^[0-9]+$'
         group by ist.taraf_id, e.secilen_kod)
      , en as (select distinct on (taraf_id) taraf_id, dep from sec order by taraf_id, n desc, dep)
      update public.taraf t set departman = en.dep, degistiren = $1, degistirme_tarihi = now()
        from en where t.id = en.taraf_id and t.departman is distinct from en.dep $q$ using p_kullanici;
    get diagnostics v_n = row_count;
  elsif p_liste = 'brans' then
    if to_regclass('eski.doktorlar') is null then raise exception 'eski.doktorlar yok - branş kararları uygulanamaz'; end if;
    execute $q$
      with k as (
        select t.id, e.secilen_kod as kod,
               (select d.ad from public.kod_deger d join public.kod_liste l on l.id = d.liste_id
                 where l.kod = 'hekim.brans' and d.dil = 0 and d.deger::text = e.secilen_kod limit 1) as ad
          from public.taraf t
          join eski.doktorlar dl on t.aktarim_kaynak = 2 and t.aktarim_tablo = 'DOKTORLAR' and dl.id = t.aktarim_id
          join public.aktarim_esleme e on e.liste = 'brans' and e.eski_kod = upper(btrim(coalesce(dl.uzmanlik, ''))) and e.durum = 1),
      tp as (update public.taraf_personel p set brans = k.kod from k where p.id = k.id and p.brans is distinct from k.kod returning p.id)
      update public.taraf t set gorev_id = (select min(g.id) from public.personel_gorev g where lower(g.ad) = lower(k.ad)),
             degistiren = $1, degistirme_tarihi = now()
        from k where t.id = k.id
         and t.gorev_id is distinct from (select min(g.id) from public.personel_gorev g where lower(g.ad) = lower(k.ad)) $q$
      using p_kullanici;
    get diagnostics v_n = row_count;
  end if;
  update public.aktarim_esleme set uygulandi = 1, uygulama_tarihi = now()
   where liste = p_liste and uygulandi = 0 and durum in (1, 2);
  return jsonb_build_object('guncellenen', v_n);
end $$;

