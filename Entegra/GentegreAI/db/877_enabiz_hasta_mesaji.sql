-- =====================================================================
--  877_enabiz_hasta_mesaji.sql
--  HEKİMDEN HASTANIN e-NABIZ PROFİLİNE DÜZ METİN MESAJ
--  (KTS denetim maddesi H7; D14 ile aynı madde. H1 · D16 · D17 bu
--   altyapının üstüne binen OTOMATİK mesajlardır.)
--
--  NEDEN AYRI TABLO, `bildirim` KUYRUĞU DEĞİL: `bildirim` kurumun kendi
--  SMS/e-posta kanalıdır - alıcısı telefon numarası, göndereni kurum.
--  Buradaki mesajın alıcısı hastanın **e-Nabız profili**, göndereni
--  HEKİMDİR ve gönderim Bakanlık servisine gider. Yanıt kodu, hekim
--  kimliği ve tetikleyen olay (numune reddi / randevu iptali) bu kayda
--  aittir; bildirim kuyruğuna sıkıştırmak iki farklı işi tek tabloda
--  birleştirirdi.
--
--  KUYRUKLU: mesaj önce KAYDEDİLİR (durum 0), gönderimi zamanlı iş yapar.
--  Hekim, Bakanlık servisi yavaşken ekran başında beklemesin; servis
--  cevap vermezse mesaj kaybolmasın, kuyrukta kalsın.
--
--  SERVİS METODU HENÜZ BİLİNMİYOR - KAPI KAPALI KURULUR.
--  Elimizdeki resmî kılavuz (SBYS Entegrasyon Kılavuzu, 05.04.2017)
--  kapsamında "hastalara bilgilendirme mesajlarının gönderilmesi" yazıyor
--  ama TEK metot tanımlıyor: `DoktorEHRErisimi` (hekimin hastanın
--  kayıtlarına erişimi - bizim H6 maddemiz). Mesaj metodunun adı ve
--  alanları kılavuzda yok.
--
--  Bu yüzden `entegrasyon_hesap` satırı **pasif** açılır ve metot adı
--  ayardan gelir (`enabiz.mesaj_metot`). Metot adı boşken kuyruk mesajı
--  GÖNDERMEZ ama HATA DA VERMEZ: satır "kuyrukta" kalır, sebebi
--  `son_hata` alanına yazılır. Kurum metot adını öğrenince tek ayar
--  satırı doldurup hesabı açar; kod değişmez.
-- =====================================================================

-- ------------------------------------------------------- kod listeleri ----
insert into public.kod_liste (kod, ad)
select v.kod, v.ad from (values
    ('enabiz.mesaj_durum',  'e-Nabız Mesaj Durumu'),
    ('enabiz.mesaj_kaynak', 'e-Nabız Mesaj Kaynağı')
  ) as v(kod, ad)
 where not exists (select 1 from public.kod_liste k where k.kod = v.kod);

insert into public.kod_deger (liste_id, deger, ad, sira, aktif, ekleyen)
select l.id, v.deger, v.ad, v.deger * 10, 1, 0
  from public.kod_liste l
  join (values
    ('enabiz.mesaj_durum', 0, 'Kuyrukta'),
    ('enabiz.mesaj_durum', 1, 'Gönderildi'),
    ('enabiz.mesaj_durum', 2, 'Hata'),
    ('enabiz.mesaj_durum', 3, 'Vazgeçildi'),
    -- Kaynak = mesajı DOĞURAN olay. Denetimde sorulan üç otomatik mesaj
    --   (numune reddi, randevu iptali, ameliyat iptali) buradan ayırt edilir.
    ('enabiz.mesaj_kaynak', 1, 'Hekim (elle)'),
    ('enabiz.mesaj_kaynak', 2, 'Numune reddi'),
    ('enabiz.mesaj_kaynak', 3, 'Randevu / işlem iptali'),
    ('enabiz.mesaj_kaynak', 4, 'Sonuç bilgilendirme'),
    ('enabiz.mesaj_kaynak', 9, 'Diğer')
  ) as v(liste, deger, ad) on v.liste = l.kod
 where not exists (select 1 from public.kod_deger d
                    where d.liste_id = l.id and d.deger = v.deger);

-- ------------------------------------------------------------- tablo ----
create table if not exists public.enabiz_mesaj (
  id             bigint generated by default as identity primary key,
  sube_id        integer  not null default 0,
  hasta_id       integer  not null references public.taraf(id),
  -- HEKİM KİMLİĞİ ZORUNLU: mesajı e-Nabız'da gönderen hekimdir, kurum
  --   değil. Kimlik numarası servise gider; hekim silinse de mesajın kimden
  --   gittiği kayıtta kalsın diye numara SATIRA da yazılır.
  hekim_id       integer  references public.taraf(id),
  hekim_kimlik   varchar(11) not null default '',
  hasta_kimlik   varchar(11) not null default '',
  belge_id       integer  references public.belge(id),   -- başvuru (tür 19)
  kaynak         smallint not null default 1,            -- enabiz.mesaj_kaynak
  kaynak_id      integer,                                -- tetikleyen kaydın id'si
  metin          varchar(500) not null,
  durum          smallint not null default 0,            -- enabiz.mesaj_durum
  deneme         smallint not null default 0,
  gonderim_zamani timestamptz,
  yanit_kod      varchar(20)  not null default '',
  yanit_mesaj    varchar(400) not null default '',
  son_hata       varchar(400) not null default '',
  ekleyen        integer  not null default 0,
  ekleme_tarihi  timestamptz not null default now(),
  degistiren     integer  not null default 0,
  degistirme_tarihi timestamptz,
  constraint ck_enabiz_mesaj_durum  check (durum in (0, 1, 2, 3)),
  constraint ck_enabiz_mesaj_metin  check (length(btrim(metin)) > 0)
);

create index if not exists ix_enabiz_mesaj_kuyruk on public.enabiz_mesaj (durum, id)
  where durum = 0;
create index if not exists ix_enabiz_mesaj_hasta on public.enabiz_mesaj (hasta_id, id desc);

comment on table public.enabiz_mesaj is
  '877: hekimden hastanin e-Nabiz profiline duz metin mesaj (KTS H7/D14). '
  'Kuyruklu: kayit aninda durum 0, gonderimi zamanli is (enabiz.mesaj) yapar. '
  'kaynak = mesaji doguran olay; otomatik mesajlar (numune reddi H1/D16, '
  'randevu iptali D17) ayni tabloya kaynak koduyla yazilir.';
comment on column public.enabiz_mesaj.hekim_kimlik is
  'Gonderen hekimin TC kimlik numarasi - servise giden deger, satirda dondurulur.';
comment on column public.enabiz_mesaj.son_hata is
  'Gonderilemediyse sebebi. Metot adi ayarlanmamisken de buraya yazilir; '
  'satir kuyrukta kalir, hata sayilmaz.';

-- ------------------------------------------------------------ görünüm ----
create or replace view public.v_enabiz_mesaj as
select m.id,
       m.sube_id,
       m.hasta_id,
       t.unvan                          as hasta_adi,
       m.hasta_kimlik,
       m.hekim_id,
       coalesce(h.unvan, '')            as hekim_adi,
       m.hekim_kimlik,
       m.belge_id,
       m.kaynak,
       coalesce(kk.ad, '')              as kaynak_adi,
       m.kaynak_id,
       m.metin,
       m.durum,
       coalesce(kd.ad, '')              as durum_adi,
       m.deneme,
       m.gonderim_zamani,
       m.yanit_kod,
       m.yanit_mesaj,
       m.son_hata,
       m.ekleme_tarihi,
       m.ekleyen
  from public.enabiz_mesaj m
  join public.taraf t on t.id = m.hasta_id
  left join public.taraf h on h.id = m.hekim_id
  left join public.kod_liste lk on lk.kod = 'enabiz.mesaj_kaynak'
  left join public.kod_deger kk on kk.liste_id = lk.id and kk.deger = m.kaynak
  left join public.kod_liste ld on ld.kod = 'enabiz.mesaj_durum'
  left join public.kod_deger kd on kd.liste_id = ld.id and kd.deger = m.durum;

comment on view public.v_enabiz_mesaj is
  '877: e-Nabiz hasta mesaji + cozulmus kaynak/durum adlari. Ekran ve rapor '
  'bu gorunumden okur.';

-- ------------------------------------------------- entegrasyon hesabı ----
--  AYRI HESAP: USS paket servisi (`ENABIZ`, SYSSendMessage) ile e-Nabız
--  Portal servisi (`NabizHBYS.svc`) farklı uçlardır ve farklı kullanıcı
--  isteyebilir. Adres kılavuzdan sabit; hesap PASİF açılır.
insert into public.entegrasyon_hesap (kod, ad, url, test_url, kullanici_adi, sifre, test_mi, aktif)
select 'ENABIZ_HBYS', 'e-Nabız Portal (hekim erişimi / hasta mesajı)',
       'https://www.enabiz.gov.tr/NabizHBYS/NabizHBYS.svc', '', '', '', 1, 0
 where not exists (select 1 from public.entegrasyon_hesap where kod = 'ENABIZ_HBYS');

-- ------------------------------------------------------------- ayarlar ----
--  `enabiz.mesaj_metot`: SOAP eyleminin/metodunun adı. BOŞ bırakıldığı
--  sürece kuyruk gönderim denemez. Kılavuzda bu metot tanımlı olmadığı
--  için varsayılanı boş bırakıyoruz - uydurulmuş bir ad, gönderim
--  denemesini her turda hata olarak kaydettirirdi.
--  (Kurum kodu ayrı ayar değil: `entegrasyon_hesap.kurum_kodu` alanında
--   durur - hesabın kendi bilgisidir, hesap değişince o da değişir.)
insert into public.referans (anahtar, deger, tip, kapsam, aciklama)
values ('enabiz.mesaj_metot', '', 'metin', 'firma',
        'NabizHBYS servisindeki hasta mesajı metodunun adı. Boşken mesajlar kuyrukta bekler.')
on conflict (anahtar) do nothing;

insert into public.referans (anahtar, deger, tip, kapsam, aciklama)
values ('enabiz.mesaj_azami_deneme', '8', 'sayi', 'firma',
        'Mesaj kaç denemeden sonra kalıcı hata sayılır (0 = sınırsız)')
on conflict (anahtar) do nothing;

-- -------------------------------------------------------------- yetki ----
--  AKSİYON yetkisi (tur 1): kendi liste ekranı yok, hekim ekranındaki
--  "e-Nabız'a mesaj" düğmesini açar. Ürün modu 2 = HBYS.
insert into public.yetki (kod, ad, grup, tur, sira, aktif, urun_modu, modul)
select 'enabiz.mesaj', 'Hastanın e-Nabız profiline mesaj gönder',
       'Entegrasyon', 1, 20, 1, 2, 'enabiz'
 where not exists (select 1 from public.yetki y where y.kod = 'enabiz.mesaj');

insert into public.rol_yetki (rol_id, yetki_id, gor, ekle, degistir, sil, ekleyen)
select r.id, y.id, 1, 1, 1, 0, 0
  from public.rol r cross join public.yetki y
 where r.kod = 'yonetici' and y.kod = 'enabiz.mesaj'
   and not exists (select 1 from public.rol_yetki ry
                    where ry.rol_id = r.id and ry.yetki_id = y.id);
update public.rol set yetki_surumu = yetki_surumu + 1 where kod = 'yonetici';

-- --------------------------------------------------------- zamanlı iş ----
--  15 dakikada bir: mesaj kullanıcının gözünün önünde yazılır, gönderimi
--  arka planda olur. Kapı kapalıyken (metot adı yok) iş çalışır ve "0
--  gönderildi" der - kuyruk büyümesi böyle görünür kalır.
insert into public.zamanli_is (kod, ad, aktif, periyot, gun, saat, dakika, aciklama)
select 'enabiz.mesaj', 'e-Nabız hasta mesajı kuyruğu', 1, 1, 1, 0, 15,
       'Kuyruktaki hasta mesajlarını e-Nabız Portal servisine gönderir. '
       'Metot adı (referans enabiz.mesaj_metot) boşken gönderim yapılmaz.'
 where not exists (select 1 from public.zamanli_is where kod = 'enabiz.mesaj');

do $$
begin
    raise notice '877 tamam: e-Nabiz hasta mesaji (kuyruk % satir, metot adi: %)',
        (select count(*) from public.enabiz_mesaj),
        coalesce((select nullif(deger, '') from public.referans
                   where anahtar = 'enabiz.mesaj_metot'), '(bos - gonderim kapali)');
end $$;
