--  423 - DOKUMAN EK BAGLANTILARI (mockup dokuman_karti.html · Baglantilar)
--
--  `dokuman.kaynak/kaynak_id` BIRINCIL baglantidir ve oyle kalir; bir dokuman
--  birden cok kayitla ilgili olabiliyor:
--
--     bir sozlesme hem CARI kartinda hem "Sozlesmeler" klasorunde,
--     bir prosedur hem KALITE klasorunde hem lab tetkik ekranindaki "?" ile.
--
--  Ikinci bir kopya yuklemek ayni dosyayi iki yerde ayri ayri surumlemek
--  olurdu; bu yuzden ILISKI tablosu: tek icerik, cok bag.
-- ============================================================================

create table if not exists public.dokuman_iliski (
    id            integer     primary key generated by default as identity,
    dokuman_id    integer     not null references public.dokuman(id) on delete cascade,
    kaynak        varchar(20) not null,
    kaynak_id     integer     not null,
    -- Bagin NE OLDUGU: "ilgili prosedur", "ek", "sozlesme eki" - listede rol
    --   yazmadan bag anlamsiz gorunuyor.
    rol           varchar(60) not null default '',
    ekleyen       integer     not null default 0,
    ekleme_tarihi timestamp   not null default now(),
    constraint ux_dokuman_iliski unique (dokuman_id, kaynak, kaynak_id)
);
create index if not exists ix_dokuman_iliski_kaynak
    on public.dokuman_iliski(kaynak, kaynak_id);

-- BIRINCIL ve EK baglantilar TEK LISTEDE: kartta "bu dokuman nerelere bagli"
--   sorusunun cevabi tek tablodan okunmali. Birincil satir isaretlidir ve
--   kaldirilamaz (dokumanin kendi kaynagi).
create or replace view public.v_dokuman_baglanti as
    select (d.id * 1000000)::bigint as id,      -- birincil satirlar icin sanal kimlik
           d.id as dokuman_id, d.kaynak, d.kaynak_id,
           1::smallint as birincil, 'ana konum'::varchar(60) as rol,
           d.ekleme_tarihi
      from public.dokuman d
     where d.durum <> 0
    union all
    select i.id::bigint, i.dokuman_id, i.kaynak, i.kaynak_id,
           0::smallint, i.rol, i.ekleme_tarihi
      from public.dokuman_iliski i;

comment on view public.v_dokuman_baglanti is
    'Dokumanin TUM baglantilari (423): birincil (dokuman.kaynak) + ek (dokuman_iliski).';
