-- =====================================================================
--  753_avans_modulu.sql
--  PERSONEL AVANSI — talep, onay, ödeme ve mahsup.
--
--  ============= KAPSAM KARARI: BORDRO YOK ============================
--  Avans üç ayaklı bir iştir: (1) talep + onay, (2) ödeme, (3) maaştan
--  mahsup. Bu kurulumda BORDRO MODÜLÜ YOK - ne maaş tutarı ne de bordro
--  satırı var. Üçüncü ayağı "bordroya yazarız" diye kurgulamak, olmayan
--  bir tabloya yaslanan ve ilk maaş döneminde kırılan bir akış üretirdi.
--
--  Bunun yerine mahsup KENDİ PLANINDA izleniyor: onaylanan avans taksit
--  taksit bölünür, her kesinti "kesildi" diye işaretlenir ve kalan düşer.
--  Bordro geldiğinde kesinti satırları oraya bağlanacak - plan zaten
--  dönem bazlı (`donem` yyyy-mm) tutuluyor.
--
--  ============= ÖDEME KASADAN GEÇER, KENDİ TABLOSUNDAN DEĞİL =========
--  Avans ödemesi bir kasa/banka hareketidir; `kasa_islem` zaten var ve
--  `kaynak_tur`/`kaynak_id` taşıyor. İkinci bir ödeme tablosu açsaydık
--  kasa bakiyesi avansı görmez, mutabakat tutmazdı.
--
--  ============= AÇIK AVANS ENGEL DEĞİL, BASAMAK ======================
--  Üstüne avans almak yasak değil (kurum bilir) ama AYRI BİR KARARDIR:
--  açık avansı olan personelin ikinci talebi zincire ek İK basamağı
--  ekler. Engelleseydik kurum sistemin dışında avans verirdi.
-- =====================================================================

-- ==================================================== AYARLAR (EŞİK)
insert into public.referans (anahtar, deger, aciklama)
select x.anahtar, x.deger, x.aciklama
  from (values
    ('ik.avans_esik_mali', '',
     'Mali isler onayi esigi (TL). Bos ise varsayilan 10.000.'),
    ('ik.avans_esik_ust', '',
     'Ust yonetim onayi esigi (TL). Bos ise varsayilan 50.000.'),
    ('ik.avans_azami_taksit', '',
     'Azami kesinti taksiti. Bos ise varsayilan 6.')
  ) as x(anahtar, deger, aciklama)
 where not exists (select 1 from public.referans r where r.anahtar = x.anahtar);

-- ===================================================== YETKİLER
insert into public.yetki (kod, ad, grup, tur, modul, aktif, sira)
select x.kod, x.ad, 'İnsan Kaynakları', x.tur, 'ik', 1, x.sira
  from (values
        ('ik.avans',            'Personel Avansı',           0::smallint, 20::smallint),
        ('ik.avans_onay_amir',  'Avans onayı - âmir',        1::smallint, 21::smallint),
        ('ik.avans_onay_ik',    'Avans onayı - İK',          1::smallint, 22::smallint),
        ('ik.avans_onay_mali',  'Avans onayı - mali işler',  1::smallint, 23::smallint),
        ('ik.avans_onay_ust',   'Avans onayı - üst yönetim', 1::smallint, 24::smallint),
        ('ik.avans_ode',        'Avans ödemesi',             1::smallint, 25::smallint)
       ) as x(kod, ad, tur, sira)
 where not exists (select 1 from public.yetki y where y.kod = x.kod);

insert into public.rol_yetki (rol_id, yetki_id, gor, ekle, degistir, sil, ekleyen)
select r.id, y.id, 1, 1, 1, 1, 0
  from public.rol r cross join public.yetki y
 where r.kod = 'yonetici' and y.kod like 'ik.avans%'
   and not exists (select 1 from public.rol_yetki ry
                    where ry.rol_id = r.id and ry.yetki_id = y.id);

-- ========================================================= AVANS
create table if not exists public.personel_avans (
    id                integer      primary key generated by default as identity,
    avans_no          varchar(30)  not null default '',
    taraf_id          integer      not null,
    talep_tarihi      date         not null default current_date,
    tutar             numeric(18,2) not null default 0,
    -- TEK PARA BİRİMİ (TL): avans maaştan mahsup edilir, maaş da TL'dir.
    --   Dövizli avans kur farkı sorusunu doğurur ve onun yeri burası değil.
    gerekce           varchar(400) not null default '',
    taksit_sayisi     smallint     not null default 1,
    -- İLK KESİNTİ DÖNEMİ: 'yyyy-mm'. Mahsup planı buradan başlar.
    ilk_donem         varchar(7)   not null default '',
    -- 0 taslak · 1 onayda · 2 onaylandı · 3 reddedildi · 4 ödendi
    --   · 5 kapandı (tamamı mahsup edildi) · 8 iptal
    durum             smallint     not null default 0,
    -- ÖDEME KASA İŞLEMİDİR: burada yalnız BAĞ durur (bkz. dosya başlığı).
    odeme_islem_id    bigint,
    odeme_tarihi      date,
    red_neden         varchar(400) not null default '',
    iptal_neden       varchar(400) not null default '',
    aciklama          varchar(300) not null default '',
    sube_id           integer,
    ekleyen           integer      not null default 0,
    ekleme_tarihi     timestamptz  not null default now(),
    degistiren        integer      not null default 0,
    degistirme_tarihi timestamptz
);

create index if not exists ix_personel_avans_taraf
    on public.personel_avans (taraf_id, durum);

comment on table public.personel_avans is
  '753: personel avansi. Odeme kasa_islemde (odeme_islem_id), mahsup '
  'personel_avans_kesintide - bordro modulu yok.';

-- ==================================================== KESİNTİ PLANI
create table if not exists public.personel_avans_kesinti (
    id                integer      primary key generated by default as identity,
    avans_id          integer      not null references public.personel_avans (id)
                                   on delete cascade,
    sira              smallint     not null default 1,
    -- DÖNEM 'yyyy-mm': bordro geldiğinde kesinti satırı o dönemin
    --   bordrosuna bağlanacak. Tarih yerine dönem tutuyoruz çünkü mahsup
    --   bir güne değil bir maaş dönemine aittir.
    donem             varchar(7)   not null,
    tutar             numeric(18,2) not null default 0,
    -- 0 planlandı · 1 kesildi · 2 ertelendi · 3 iptal
    durum             smallint     not null default 0,
    kesinti_tarihi    date,
    aciklama          varchar(200) not null default '',
    ekleyen           integer      not null default 0,
    ekleme_tarihi     timestamptz  not null default now(),
    degistiren        integer      not null default 0,
    degistirme_tarihi timestamptz
);

create unique index if not exists ux_avans_kesinti_sira
    on public.personel_avans_kesinti (avans_id, sira);

comment on table public.personel_avans_kesinti is
  '753: avans mahsup plani. donem yyyy-mm - mahsup bir gune degil bir '
  'maas donemine aittir; bordro gelince satirlar oraya baglanacak.';

-- ================================================= LİSTE GÖRÜNÜMÜ
create or replace view public.v_personel_avans as
select a.id,
       a.avans_no,
       a.taraf_id,
       coalesce(nullif(t.unvan, ''), '')                as personel_ad,
       coalesce(nullif(p.gorev, ''), '')                as gorev_ad,
       coalesce(nullif(am.unvan, ''), '')               as amir_ad,
       a.talep_tarihi,
       a.tutar,
       a.taksit_sayisi,
       a.ilk_donem,
       a.durum,
       a.odeme_islem_id,
       a.odeme_tarihi,
       a.gerekce,
       a.red_neden,
       a.iptal_neden,
       a.sube_id,
       -- KESİLEN / KALAN: avansın asıl sorusu "ne kadarı geri geldi".
       coalesce((select sum(k.tutar) from public.personel_avans_kesinti k
                  where k.avans_id = a.id and k.durum = 1), 0)     as kesilen_tutar,
       a.tutar - coalesce((select sum(k.tutar) from public.personel_avans_kesinti k
                            where k.avans_id = a.id and k.durum = 1), 0)
                                                                   as kalan_tutar,
       (select count(*) from public.personel_avans_kesinti k
         where k.avans_id = a.id and k.durum = 0)                  as bekleyen_taksit,
       -- GECİKEN KESİNTİ: dönemi geçmiş ama kesilmemiş taksit, unutulmuş
       --   bir mahsuptur - avans kapanmadan personel ayrılırsa tahsil
       --   edilemez.
       (select count(*) from public.personel_avans_kesinti k
         where k.avans_id = a.id and k.durum = 0
           and k.donem < to_char(current_date, 'YYYY-MM'))         as geciken_taksit,
       (select v.adim_ad from public.v_onay_bekleyen v
         where v.kaynak_tur = 907 and v.kaynak_id = a.id
         order by v.sira limit 1)                                  as bekleyen_basamak,
       a.ekleme_tarihi,
       a.degistirme_tarihi
  from public.personel_avans a
  join public.taraf t              on t.id = a.taraf_id
  left join public.taraf_personel p on p.id = a.taraf_id
  left join public.taraf am        on am.id = p.yonetici_taraf_id;

comment on view public.v_personel_avans is
  '753: avans listesi - kesilen/kalan, bekleyen ve geciken taksit, '
  'bekleyen onay basamagi.';

