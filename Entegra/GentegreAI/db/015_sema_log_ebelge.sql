-- ------------------------------------------- 2) degistirme_tarihi trigger'i ----
create or replace function public.fn_degistirme_tarihi()
returns trigger language plpgsql as $$
begin
    new.degistirme_tarihi := now()::timestamp;
    return new;
end;
$$;

comment on function public.fn_degistirme_tarihi() is
  'BEFORE UPDATE: degistirme_tarihi alanini sunucu saatiyle doldurur. Uygulama unutsa da alan dogru kalir.';

do $$
declare
    t text;
begin
    for t in
        select c.relname
          from pg_class c
          join pg_namespace n on n.oid = c.relnamespace
         where n.nspname = 'public' and c.relkind = 'r'
           and exists (select 1 from information_schema.columns k
                        where k.table_schema = 'public' and k.table_name = c.relname
                          and k.column_name = 'degistirme_tarihi')
    loop
        execute format('drop trigger if exists trg_%s_degistirme on public.%I', t, t);
        execute format('create trigger trg_%s_degistirme before update on public.%I
                        for each row execute function public.fn_degistirme_tarihi()', t, t);
    end loop;
end $$;

-- ------------------------------------------------------------- 3) islem_log ----
-- Eski GENDEPO.ISLEMLOG. Delphi'de yillik LOG<yyyy> tablolari + kendini onaran
--   ISLEMLOG view'i vardi (ayri veritabani oldugu icin). Burada tek tablo:
--   PG'de tarih bazli BOLUMLEME (partition) ayni isi standart yoldan yapar.
create table if not exists public.islem_log (
    id                bigint generated by default as identity,
    tarih             timestamp not null default now()::timestamp,
    kullanici_id      integer   not null default 0,
    sube_id           smallint  not null default 0,
    ip                varchar(45)  not null default '',
    istasyon          varchar(64)  not null default '',
    islem_tipi        smallint  not null default 0,   -- 0 sil, 1 ekle, 2 degistir
    alt_islem_tipi    smallint  not null default 0,
    ust_tablo_id      integer   not null default 0,   -- modul/tablo kodu (kart)
    ust_kayit_id      bigint    not null default 0,
    tablo_id          integer   not null default 0,   -- degisen tablo kodu
    kayit_id          bigint    not null default 0,
    taraf_id          integer,
    stok_id           integer,
    bilgi             jsonb,                          -- alan bazli eski/yeni deger
    constraint pk_islem_log primary key (id, tarih)
) partition by range (tarih);

-- Yillik bolumler: Delphi'deki GENDEPO.LOG<yyyy> adlandirmasi korunur.
--   Yeni yil icin: create table log_2028 partition of islem_log
--                  for values from ('2028-01-01') to ('2029-01-01');
create table if not exists public.log_2026 partition of public.islem_log
    for values from ('2026-01-01') to ('2027-01-01');
create table if not exists public.log_2027 partition of public.islem_log
    for values from ('2027-01-01') to ('2028-01-01');
-- Aralik disi kayit hata vermesin diye varsayilan bolum
create table if not exists public.log_diger partition of public.islem_log default;

create index if not exists ix_islem_log_kayit    on public.islem_log (tablo_id, kayit_id, tarih desc);
create index if not exists ix_islem_log_ust      on public.islem_log (ust_tablo_id, ust_kayit_id, tarih desc);
create index if not exists ix_islem_log_kullanici on public.islem_log (kullanici_id, tarih desc);
create index if not exists ix_islem_log_taraf    on public.islem_log (taraf_id, tarih desc) where taraf_id is not null;
create index if not exists ix_islem_log_stok     on public.islem_log (stok_id, tarih desc)  where stok_id is not null;

comment on table  public.islem_log       is 'Islem/denetim gunlugu (eski GENDEPO.ISLEMLOG + yillik LOG<yyyy>). Tarihe gore bolumlenmis.';
comment on column public.islem_log.bilgi is 'Alan bazli degisiklik: {"alan": "eski -> yeni"} bicimi. Silme kaydinda satirin tam hali (Geri Al icin).';

-- --------------------------------------------------------------- 4) e_belge ----
-- Eski GENDEPO.EBELGE. Belge ile 1:N (bir belgenin birden cok gonderim denemesi olabilir).
create table if not exists public.e_belge (
    id                   bigint generated by default as identity primary key,
    belge_id             integer,
    taraf_id             integer,
    belge_turu           smallint     not null,            -- e-Fatura / e-Arsiv / e-Irsaliye ...
    yon                  smallint     not null,            -- 1 giden, 2 gelen
    uuid                 varchar(50),
    belge_no             varchar(50)  not null default '',
    gonderici_alias      varchar(500) not null default '',
    alici_alias          varchar(500) not null default '',
    durum                smallint     not null default 0,
    api_json             text         not null default '',
    ubl_xml              text         not null default '',
    ubl_xml_zip          bytea,
    servis_durum_kodu    varchar(100) not null default '',
    servis_durum_adi     varchar(250) not null default '',
    gib_durum_kodu       varchar(50)  not null default '',
    gib_durum_aciklama   varchar(500) not null default '',
    yanit_durum_kodu     varchar(100) not null default '',
    yanit_durum_adi      varchar(250) not null default '',
    ekleyen              integer      not null default 0,
    ekleme_tarihi        timestamp    not null default now()::timestamp,
    degistiren           integer      not null default 0,
    degistirme_tarihi    timestamp,
    constraint fk_e_belge_belge foreign key (belge_id) references public.belge (id) on delete set null,
    constraint fk_e_belge_taraf foreign key (taraf_id) references public.taraf (id)
);

create unique index if not exists ux_e_belge_uuid  on public.e_belge (uuid) where uuid is not null;
create index        if not exists ix_e_belge_belge on public.e_belge (belge_id) where belge_id is not null;
create index        if not exists ix_e_belge_liste on public.e_belge (yon, belge_turu, durum, ekleme_tarihi desc);

comment on table  public.e_belge     is 'e-Belge gonderim/alim kaydi (eski GENDEPO.EBELGE). Belge ile 1:N - her gonderim denemesi ayri satir.';
comment on column public.e_belge.uuid is 'GIB UUID. Tekil (kismi indeks: NULL olanlar disarida).';

-- e_belge trigger'i (yukaridaki dongu bu tablodan once calisti)
drop trigger if exists trg_e_belge_degistirme on public.e_belge;
create trigger trg_e_belge_degistirme before update on public.e_belge
    for each row execute function public.fn_degistirme_tarihi();
