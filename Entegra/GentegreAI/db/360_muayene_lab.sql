-- ================================================================ muayene ==
create table if not exists public.muayene (
    id             integer generated by default as identity primary key,
    -- Hangi BASVURUYA ait (belge tur 19 / tipi 30). Bos olabilir: basvurusuz
    --   (or. kontrol) muayene de kaydedilebilsin.
    belge_id       integer      null references public.belge(id) on delete set null,
    taraf_id       integer      not null references public.taraf(id),   -- hasta
    sube_id        integer      not null default 0,
    bolum_id       integer      null,
    personel_id    integer      null,                                   -- hekim
    muayene_no     varchar(30)  not null default '',
    muayene_tarihi timestamp    not null default now()::timestamp,
    -- 1 ilk muayene · 2 kontrol · 3 konsultasyon
    tur            smallint     not null default 1,
    sikayet        text         not null default '',
    oyku           text         not null default '',
    bulgu          text         not null default '',
    -- ICD kodlari virgullu ("J06.9, R50"); ayri tablo klinik fazda.
    tani_kodlari   varchar(200) not null default '',
    tani           varchar(300) not null default '',
    tedavi         text         not null default '',
    oneri          text         not null default '',
    -- 1 acik (devam) · 2 tamamlandi · 3 iptal
    durum          smallint     not null default 1,
    ekleyen        integer      not null default 0,
    ekleme_tarihi  timestamp    not null default now()::timestamp,
    degistiren     integer      not null default 0,
    degistirme_tarihi timestamp null
);
comment on table public.muayene is
  'Muayene kaydi (360): basvuruya bagli hekim muayenesi - sikayet/oyku/bulgu/tani/tedavi.';

create index if not exists ix_muayene_taraf   on public.muayene (taraf_id, muayene_tarihi desc);
create index if not exists ix_muayene_belge   on public.muayene (belge_id);
create index if not exists ix_muayene_personel on public.muayene (personel_id, muayene_tarihi desc);

-- ============================================================ laboratuvar ==
create table if not exists public.lab_istem (
    id             integer generated by default as identity primary key,
    belge_id       integer      null references public.belge(id) on delete set null,
    taraf_id       integer      not null references public.taraf(id),   -- hasta
    sube_id        integer      not null default 0,
    istem_no       varchar(30)  not null default '',
    istem_tarihi   timestamp    not null default now()::timestamp,
    -- 1 biyokimya · 2 mikrobiyoloji · 3 genetik · 4 patoloji · 9 diger
    bolum          smallint     not null default 1,
    personel_id    integer      null,                                   -- isteyen hekim
    -- 1 istendi · 2 numune alindi · 3 calisiliyor · 4 sonuclandi · 5 onaylandi · 9 iptal
    durum          smallint     not null default 1,
    numune_tarihi  timestamp    null,
    sonuc_tarihi   timestamp    null,
    aciklama       varchar(300) not null default '',
    ekleyen        integer      not null default 0,
    ekleme_tarihi  timestamp    not null default now()::timestamp,
    degistiren     integer      not null default 0,
    degistirme_tarihi timestamp null
);
comment on table public.lab_istem is
  'Laboratuvar istemi (360): hastanin bir bolume verilen test istegi; testler lab_istem_test''te.';

create index if not exists ix_lab_istem_taraf on public.lab_istem (taraf_id, istem_tarihi desc);
create index if not exists ix_lab_istem_durum on public.lab_istem (durum, istem_tarihi desc);

create table if not exists public.lab_istem_test (
    id             integer generated by default as identity primary key,
    istem_id       integer      not null references public.lab_istem(id) on delete cascade,
    -- Test HIZMET kartidir (stok tur 2): ucretlendirme ve fiyat listesi oradan.
    stok_id        integer      null,
    kod            varchar(30)  not null default '',
    ad             varchar(200) not null default '',
    sonuc          varchar(100) not null default '',
    birim          varchar(20)  not null default '',
    referans       varchar(60)  not null default '',
    -- 0 normal · 1 dusuk · 2 yuksek · 3 panik (sonuc degerlendirmesi)
    isaret         smallint     not null default 0,
    durum          smallint     not null default 1,
    sonuc_tarihi   timestamp    null,
    cihaz          varchar(60)  not null default '',
    aciklama       varchar(300) not null default ''
);
comment on table public.lab_istem_test is
  'Istemdeki tek test (360): sonuc, birim, referans araligi ve degerlendirme isareti.';

create index if not exists ix_lab_test_istem on public.lab_istem_test (istem_id);

-- ================================================================= yetki ===
insert into public.yetki (kod, ad, grup, tur, sira)
select v.kod, v.ad, 'belge', 0, v.sira
  from (values ('muayene', 'Muayene', 35), ('lab', 'Laboratuvar', 36)) as v(kod, ad, sira)
 where not exists (select 1 from public.yetki y where y.kod = v.kod);

-- Yeni yetkiyi RADYOLOJI'si olan rollere ac: ayni klinik kullanicilar.
insert into public.rol_yetki (rol_id, yetki_id, gor, ekle, degistir, sil)
select ry.rol_id, y.id, ry.gor, ry.ekle, ry.degistir, ry.sil
  from public.rol_yetki ry
  join public.yetki yr on yr.id = ry.yetki_id and yr.kod = 'radyoloji'
 cross join public.yetki y
 where y.kod in ('muayene', 'lab')
   and not exists (select 1 from public.rol_yetki r2
                    where r2.rol_id = ry.rol_id and r2.yetki_id = y.id);
