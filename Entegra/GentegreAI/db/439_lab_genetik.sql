drop view if exists public.v_lab_gen_lookup;
create view public.v_lab_gen_lookup as
select g.id, g.sembol as kod,
       g.sembol || coalesce(' · ' || nullif(g.hastalik, ''), '') as ad,
       case when g.durum = 0 then 1 else 0 end::smallint as aktif
  from public.lab_gen g;

drop view if exists public.v_lab_genetik_panel_lookup;
create view public.v_lab_genetik_panel_lookup as
select p.id, p.kod, p.kod || ' · ' || p.ad as ad,
       case when p.durum = 0 then 1 else 0 end::smallint as aktif
  from public.lab_genetik_panel p;

drop view if exists public.v_lab_genetik_run_lookup;
create view public.v_lab_genetik_run_lookup as
select r.id, r.kod,
       r.kod || ' · ' || to_char(r.tarih, 'DD.MM.YYYY') as ad,
       case when r.durum in (0, 4) then 0 else 1 end::smallint as aktif
  from public.lab_genetik_run r;

