create view public.v_lab_varyant_yeniden as
select v.id            as varyant_id,
       v.vaka_id,
       g.vaka_no,
       g.hasta_id,
       v.gen_sembol,
       v.hgvs_c,
       v.sinif         as rapor_sinif,
       b.sinif         as guncel_sinif,
       b.surum         as bilgi_surum,
       b.degerlendirme_tarihi,
       g.onay_zamani
  from public.lab_varyant v
  join public.lab_genetik_vaka g on g.id = v.vaka_id
  join public.lab_varyant_bilgi b
       on upper(b.gen_sembol) = upper(v.gen_sembol) and b.hgvs_c = v.hgvs_c
 where g.durum = 7                    -- yalnız raporlanmış vakalar
   and v.raporla = 1
   and b.sinif <> v.sinif;

