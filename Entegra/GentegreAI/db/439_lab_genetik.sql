-- ---------------------------------------------------------------------
--  6) ACMG/AMP 2015 SINIFLAMA KURALLARI
--
--  Kanıt kodları güç ekiyle gelebilir (PP1_Strong, PM2_Supporting):
--  ek varsa GÜCÜ O BELİRLER, yoksa kodun kendi sınıfı. Bu, ClinGen'in
--  kanıt gücü ayarlama pratiğidir; ekleri yok saymak PP1_Strong'u
--  "destekleyici" sayıp patojenik varyantı VUS'a düşürürdü.
-- ---------------------------------------------------------------------
create or replace function public.fn_lab_acmg_sinif(p_kriterler text[])
returns smallint language plpgsql immutable as $$
declare
    v_kod    text;
    v_temel  text;
    v_ek     text;
    v_guc    text;
    v_pvs int := 0; v_ps int := 0; v_pm int := 0; v_pp int := 0;
    v_ba  int := 0; v_bs int := 0; v_bp int := 0;
    v_pat boolean; v_olasi_pat boolean;
    v_ben boolean; v_olasi_ben boolean;
begin
    if p_kriterler is null or cardinality(p_kriterler) = 0 then
        return 3;                      -- kanıt yok = VUS
    end if;

    foreach v_kod in array p_kriterler loop
        v_kod := upper(trim(v_kod));
        if position('_' in v_kod) > 0 then
            v_temel := split_part(v_kod, '_', 1);
            v_ek    := split_part(v_kod, '_', 2);
        else
            v_temel := v_kod;
            v_ek    := '';
        end if;

        -- Güç: ek varsa ek belirler, yoksa kodun kendi ön eki.
        v_guc := case v_ek
                    when 'VERYSTRONG' then 'PVS'
                    when 'STRONG'     then 'PS'
                    when 'MODERATE'   then 'PM'
                    when 'SUPPORTING' then 'PP'
                    when 'STANDALONE' then 'BA'
                    else '' end;

        if v_guc = '' then
            v_guc := case
                        when v_temel like 'PVS%' then 'PVS'
                        when v_temel like 'PS%'  then 'PS'
                        when v_temel like 'PM%'  then 'PM'
                        when v_temel like 'PP%'  then 'PP'
                        when v_temel like 'BA%'  then 'BA'
                        when v_temel like 'BS%'  then 'BS'
                        when v_temel like 'BP%'  then 'BP'
                        else '' end;
        elsif v_temel like 'B%' then
            -- Benign kanıtın gücü ayarlanmışsa benign tarafta kalır.
            v_guc := case v_guc when 'PS' then 'BS' when 'PP' then 'BP'
                                when 'PM' then 'BS' else v_guc end;
        end if;

        case v_guc
            when 'PVS' then v_pvs := v_pvs + 1;
            when 'PS'  then v_ps  := v_ps  + 1;
            when 'PM'  then v_pm  := v_pm  + 1;
            when 'PP'  then v_pp  := v_pp  + 1;
            when 'BA'  then v_ba  := v_ba  + 1;
            when 'BS'  then v_bs  := v_bs  + 1;
            when 'BP'  then v_bp  := v_bp  + 1;
            else null;
        end case;
    end loop;

    -- Patojenik (Richards 2015, Tablo 5)
    v_pat := (v_pvs >= 1 and (v_ps >= 1 or v_pm >= 2 or (v_pm = 1 and v_pp >= 1)
                              or v_pp >= 2))
          or (v_ps >= 2)
          or (v_ps = 1 and (v_pm >= 3 or (v_pm = 2 and v_pp >= 2)
                            or (v_pm = 1 and v_pp >= 4)));

    v_olasi_pat := (v_pvs = 1 and v_pm = 1)
                or (v_ps = 1 and v_pm between 1 and 2)
                or (v_ps = 1 and v_pp >= 2)
                or (v_pm >= 3)
                or (v_pm = 2 and v_pp >= 2)
                or (v_pm = 1 and v_pp >= 4);

    v_ben       := (v_ba >= 1) or (v_bs >= 2);
    v_olasi_ben := (v_bs = 1 and v_bp >= 1) or (v_bp >= 2);

    -- ÇELİŞKİLİ KANIT = VUS: hem patojenik hem benign ölçüt sağlanıyorsa
    --   birini seçmek yerine belirsiz denir (ACMG'nin açık kuralı).
    if (v_pat or v_olasi_pat) and (v_ben or v_olasi_ben) then return 3; end if;

    if v_pat       then return 5; end if;
    if v_olasi_pat then return 4; end if;
    if v_ben       then return 1; end if;
    if v_olasi_ben then return 2; end if;
    return 3;
end $$;

comment on function public.fn_lab_acmg_sinif(text[]) is
    'ACMG/AMP 2015 kanit kodlarindan varyant sinifi (1 benign .. 5 patojenik). '
    'Guc ekleri (PP1_Strong, PM2_Supporting) dikkate alinir; celiskili kanit VUS.';

-- Sınıf, kriterler değişince KENDİLİĞİNDEN güncellenir. Elle ezilen
--   (sinif_elle = 1) satıra dokunulmaz: uzman kararı kuralın üstündedir.
create or replace function public.tg_lab_varyant_sinif()
returns trigger language plpgsql as $$
begin
    if new.sinif_elle = 1 then return new; end if;
    new.sinif := public.fn_lab_acmg_sinif(new.acmg_kriterler);
    -- Raporlama varsayılanı: VUS ve üstü raporlanır, benign raporlanmaz.
    --   Hastanın istemediği ikincil bulgu her hâlükârda kapalı kalır.
    if tg_op = 'INSERT' then
        new.raporla := case when new.ikincil_bulgu = 1 then 0
                            when new.sinif >= 3 then 1 else 0 end;
    end if;
    return new;
end $$;

drop trigger if exists tg_lab_varyant_sinif on public.lab_varyant;
create trigger tg_lab_varyant_sinif
    before insert or update of acmg_kriterler, sinif_elle on public.lab_varyant
    for each row execute function public.tg_lab_varyant_sinif();

-- ---------------------------------------------------------------------
--  7) VAKA SONUÇ ÖZETİ
--
--  Rapor cümlesi TEK YERDE kurulur: ekran, çıktı ve e-Nabız aynı şeyi
--  söylesin. "Pozitif" tanımı da buradadır - patojenik/olası patojenik
--  varyant varsa pozitif, yalnız VUS varsa "belirsiz", hiçbiri yoksa
--  negatif. Üç ayrı yerde yazılsaydı biri VUS'u pozitif sayardı.
-- ---------------------------------------------------------------------
create or replace function public.fn_lab_genetik_ozet(p_vaka_id integer)
returns text language sql stable as $$
    with v as (
        select * from public.lab_varyant
         where vaka_id = p_vaka_id and raporla = 1
    )
    select case
        when exists (select 1 from v where sinif >= 4) then
            'POZİTİF — ' || (select string_agg(
                 gen_sembol || ' ' || hgvs_c
                 || coalesce(' ' || nullif(hgvs_p, ''), '')
                 || ' (' || case sinif when 5 then 'patojenik'
                                       else 'olası patojenik' end || ')',
                 ' · ' order by sinif desc, gen_sembol)
               from v where sinif >= 4)
        when exists (select 1 from v where sinif = 3) then
            'BELİRSİZ (VUS) — ' || (select string_agg(
                 gen_sembol || ' ' || hgvs_c, ' · ' order by gen_sembol)
               from v where sinif = 3)
        else 'NEGATİF — klinik olarak anlamlı varyant saptanmadı'
    end;
$$;

