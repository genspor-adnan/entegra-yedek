-- ============================================================================
--  Gentegre AI — NUMARA SABLONU (belge / tahsilat / odeme numaralandirmasi)
--  152_numara_sablonu.sql
--
--  Kullanici: "Genel Ayarlar'da Numaralama sekmesi; Satis Belgeleri, Alis
--  Belgeleri, Tahsilat Turleri, Odeme Turleri icin Tur + Baslama (tarih) +
--  On Ek + Baslama No. Belge veya odeme/tahsilat islemlerinde bu numaralandirma
--  kullanilacak."
--
--  MODEL
--    Bir sablon = (tur, sube, baslama_tarihi) uclusu. Belge kesilirken BELGE
--    TARIHINE gore YURURLUKTEKI sablon secilir: baslama_tarihi <= belge tarihi
--    olanlarin EN YENISI. Boylece "1 Ocak'tan itibaren A- serisi, 000001'den
--    baslasin" denince eski belgeler eski seriyi korur, yeni belgeler yeniyi
--    alir - kayit gecmisi yeniden yazilmaz.
--
--    BASLAMA NO IKI BILGI TASIR (kullanici karari): "00000100" hem numaranin
--    nereden baslayacagini (100) hem KAC HANE yazilacagini (8) soyler. Iki ayri
--    alan sormak yerine kullanicinin zaten yazdigi ornegi okuyoruz; ikisi de
--    turetilmis kolon, elle girilmez.
--
--  SAYAC
--    Sayac anahtarina sablon kimligi girer (|N<id>). Yeni sablon = YENI SAYAC:
--    on ek ya da baslangic degisince numara eski sayacin kaldigi yerden devam
--    etmez. Sayacin ilk degeri baslangic-1'dir, ilk uretilen numara tam olarak
--    kullanicinin yazdigi "Baslama No" olur.
--
--    BOSLUKSUZLUK ve satir kilidi kurallari degismedi (025 + 087): numara
--    transaction icinde, kaydin en son adiminda, "for update" altinda uretilir.
--
--  GERIYE UYUM: sablon TANIMLANMAMISSA eski davranis aynen surer (belgede
--    seri + hane, kasada makbuz_seri + hane). Sablon opsiyoneldir.
-- ============================================================================
\set ON_ERROR_STOP on

-- ------------------------------------------------------------- tablo --------
create table if not exists public.numara_sablonu (
    id                   integer generated by default as identity primary key,
    -- Belge turu ya da kasa islem turu - ikisi de ayni katalogda (kasa_islem_turu).
    tur                  smallint     not null,
    -- Bu tarihten ITIBAREN gecerli. Ayni tur icin birden fazla sablon olabilir.
    baslama_tarihi       date         not null default current_date,
    -- Numaranin onune eklenir ("A-", "2026/"). Bos birakilabilir.
    on_ek                varchar(20)  not null default '',
    -- Hem baslangic degeri hem HANE sayisi ("00000100" -> 100'den basla, 8 hane).
    baslama_no           varchar(30)  not null default '1',
    -- 0 = tum subeler; sube verilirse o sube icin bu sablon oncelikli.
    sube_id              smallint     not null default 0,
    durum                smallint     not null default 0,   -- 0 aktif, 1 pasif
    aciklama             varchar(200) not null default '',
    ekleyen              integer      not null default 0,
    ekleme_tarihi        timestamp    not null default now()::timestamp,
    degistiren           integer      not null default 0,
    degistirme_tarihi    timestamp    null,
    -- Turetilmis: kullanicinin yazdigi ornekten okunur, elle girilmez.
    hane                 smallint     generated always as
                             (length(btrim(baslama_no))::smallint) stored,
    baslangic            bigint       generated always as
                             (coalesce(nullif(regexp_replace(baslama_no, '\D', '', 'g'), '')::bigint, 1)) stored
);

comment on table public.numara_sablonu is
  'Belge / tahsilat / odeme numaralandirma sablonu (152). Belge tarihine gore yururlukteki satir secilir; on ek ve hane buradan gelir.';
comment on column public.numara_sablonu.baslama_no is
  'Ornek numara: hem baslangic degeri hem hane sayisi ("00000100" = 100''den basla, 8 hane).';
comment on column public.numara_sablonu.baslama_tarihi is
  'Sablon bu tarihten ITIBAREN gecerli; eski belgeler eski sablonu korur.';

-- Ayni tur/sube icin ayni gunde iki sablon anlamsiz - hangisi gecerli belirsiz kalirdi.
create unique index if not exists ux_numara_sablonu_tur_sube_tarih
    on public.numara_sablonu (tur, sube_id, baslama_tarihi);
create index if not exists ix_numara_sablonu_tur
    on public.numara_sablonu (tur, durum);

drop trigger if exists tr_numara_sablonu_degistirme on public.numara_sablonu;
create trigger tr_numara_sablonu_degistirme
    before update on public.numara_sablonu
    for each row execute function public.fn_degistirme_tarihi();

-- --------------------------------------------------- yururlukteki sablon ----
-- Sube-ozel sablon, genel (sube 0) sablondan ONCE gelir; esitlikte en YENI
--   baslama tarihi kazanir.
create or replace function public.fn_numara_sablonu_bul(
        p_tur integer, p_sube_id integer, p_tarih date)
returns public.numara_sablonu
language sql stable as $$
    select s.*
      from public.numara_sablonu s
     where s.tur = p_tur
       and s.durum = 0
       and s.sube_id in (coalesce(p_sube_id, 0), 0)
       and s.baslama_tarihi <= coalesce(p_tarih, current_date)
     order by (s.sube_id = coalesce(p_sube_id, 0)) desc, s.baslama_tarihi desc
     limit 1
$$;

comment on function public.fn_numara_sablonu_bul(integer, integer, date) is
  'Verilen tur/sube/tarih icin YURURLUKTEKI numara sablonu; yoksa bos satir (id null).';

-- --------------------------------------------------- sayactan siradaki no ---
-- Sablonlu ve sablonsuz yollarin ORTAK govdesi: anahtari kilitler, ilk kullanimda
--   baslangic-1'e kurar, artirir ve sifir dolgulu metni doner.
create or replace function public.fn_numara_sirada(
        p_anahtar text, p_tablo text, p_alan text, p_kapsam text,
        p_hane integer, p_baslangic bigint)
returns text
language plpgsql as $$
declare
    v_no    bigint;
    v_metin text;
begin
    insert into public.belge_no_sayac (anahtar, tablo_adi, alan_adi, kapsam, son_no)
    values (p_anahtar, p_tablo, p_alan, p_kapsam, greatest(coalesce(p_baslangic, 1) - 1, 0))
    on conflict (anahtar) do nothing;

    select son_no into v_no
      from public.belge_no_sayac
     where anahtar = p_anahtar
       for update;

    v_no := coalesce(v_no, 0) + 1;

    update public.belge_no_sayac
       set son_no = v_no, guncelleme = now()::timestamp
     where anahtar = p_anahtar;

    -- lpad UZUN metni KESER (087): hane bir ALT sinirdir, ust sinir degil.
    v_metin := v_no::text;
    return case when length(v_metin) >= p_hane then v_metin
                else lpad(v_metin, p_hane, '0') end;
end $$;

comment on function public.fn_numara_sirada(text, text, text, text, integer, bigint) is
  'Sayac anahtarini kilitleyip siradaki numarayi uretir (bosluksuz, sifir dolgulu). Ilk kullanimda sayac baslangic-1 kurulur.';

-- ------------------------------------------------------------- belge no -----
-- Imzaya p_tarih EKLENDI (sonda, varsayilanli): eski cagrilar calismaya devam
--   eder, sablon secimi icin belge tarihi verilir.
create or replace function public.fn_belge_no_uret(p_tur integer, p_seri text,
                                                   p_sube_id integer, p_hane integer default 9,
                                                   p_tarih date default null)
returns text
language plpgsql as $$
declare
    v_sablon public.numara_sablonu;
    v_anahtar text;
    v_kapsam  text;
begin
    v_sablon := public.fn_numara_sablonu_bul(p_tur, p_sube_id, coalesce(p_tarih, current_date));

    if v_sablon.id is not null then
        -- Sablonlu: sayac SABLONA baglidir - on ek/baslangic degisince yeni sayac.
        v_anahtar := 'belge.belge_no|T' || p_tur::text ||
                     '|SUBE' || coalesce(p_sube_id, 0)::text ||
                     '|N' || v_sablon.id::text;
        v_kapsam  := 'sablon ' || v_sablon.id::text || ' / tur ' || p_tur::text ||
                     ' / sube ' || coalesce(p_sube_id, 0)::text;
        return v_sablon.on_ek || public.fn_numara_sirada(
                   v_anahtar, 'belge', 'belge_no', v_kapsam,
                   v_sablon.hane, v_sablon.baslangic);
    end if;

    -- Sablonsuz: 025/087'deki eski davranis (seri bazli kapsam, on ek yok).
    v_anahtar := public.fn_belge_no_anahtar(p_tur, p_seri, p_sube_id);
    v_kapsam  := 'T' || p_tur::text || '|S' || coalesce(nullif(btrim(p_seri), ''), '-') ||
                 '|SUBE' || coalesce(p_sube_id, 0)::text;
    return public.fn_numara_sirada(v_anahtar, 'belge', 'belge_no', v_kapsam, p_hane, 1);
end $$;

comment on function public.fn_belge_no_uret(integer, text, integer, integer, date) is
  'Siradaki belge numarasi. Tarihe uyan numara sablonu varsa on ek + hane oradan gelir (152); yoksa seri bazli eski davranis.';

-- --------------------------------------------------------- kasa islem no ----
create or replace function public.fn_kasa_islem_no_uret(p_tur integer, p_sube_id integer,
                                                        p_yil integer, p_hane integer default 8,
                                                        p_tarih date default null)
returns text
language plpgsql as $$
declare
    v_sablon  public.numara_sablonu;
    v_seri    text;
    v_anahtar text;
begin
    v_sablon := public.fn_numara_sablonu_bul(
                    p_tur, p_sube_id,
                    coalesce(p_tarih, make_date(coalesce(p_yil, extract(year from current_date)::int), 1, 1)));

    if v_sablon.id is not null then
        -- YIL kapsami korunur: makbuz serisi her yil bastan akar.
        v_anahtar := 'kasa_islem.islem_no|SUBE' || coalesce(p_sube_id, 0)::text ||
                     '|Y' || p_yil::text || '|N' || v_sablon.id::text;
        return v_sablon.on_ek || public.fn_numara_sirada(
                   v_anahtar, 'kasa_islem', 'islem_no',
                   'sablon ' || v_sablon.id::text || ' / sube ' || coalesce(p_sube_id, 0)::text
                   || ' / ' || p_yil::text,
                   v_sablon.hane, v_sablon.baslangic);
    end if;

    -- Sablonsuz: katalogdaki makbuz serisi (eski davranis).
    select coalesce(nullif(btrim(t.makbuz_seri), ''), 'K') into v_seri
      from public.kasa_islem_turu t where t.kod = p_tur;
    v_seri := coalesce(v_seri, 'K');

    v_anahtar := 'kasa_islem.islem_no|S' || v_seri
              || '|SUBE' || coalesce(p_sube_id, 0)::text || '|Y' || p_yil::text;
    return v_seri || public.fn_numara_sirada(
               v_anahtar, 'kasa_islem', 'islem_no',
               'seri ' || v_seri || ' / sube ' || coalesce(p_sube_id, 0)::text || ' / ' || p_yil::text,
               p_hane, 1);
end $$;

comment on function public.fn_kasa_islem_no_uret(integer, integer, integer, integer, date) is
  'Siradaki tahsilat/odeme makbuz numarasi. Numara sablonu varsa on ek + hane oradan (152); yoksa katalogdaki makbuz serisi.';

