-- ============================================================================
--  Gentegre AI — stok_uts'e SATIR KIMLIGI
--  120_stok_uts_id.sql
--
--  119'da stok_uts'un birincil anahtari stok_id idi (1:1 uzanti). Kart detay
--  mekanizmasi ise satirlari "id" alanindan tanir: id gelmeyen satir YENI kabul
--  edilir. Sonuc: var olan ÜTS kaydini duzenleyip Kaydet deyince ekleme
--  denenip "Ayni kayit zaten var (stok_uts_pkey)" hatasi aliniyordu.
--
--  Cozum, mekanizmayi degil TABLOYU hizalamak: butun detay tablolarindaki gibi
--  bir "id" kolonu eklenir. 1:1 kurali stok_id'nin BENZERSIZ olmasiyla korunur -
--  bir stokun ikinci ÜTS kaydi yine acilamaz.
-- ============================================================================
\set ON_ERROR_STOP on

alter table public.stok_uts add column if not exists id integer generated by default as identity;

do $$
begin
    -- Birincil anahtar id'ye tasinir; stok_id benzersiz kalarak 1:1'i korur.
    if exists (select 1 from pg_constraint where conname = 'stok_uts_pkey'
                 and conrelid = 'public.stok_uts'::regclass
                 and pg_get_constraintdef(oid) like '%(stok_id)%') then
        alter table public.stok_uts drop constraint stok_uts_pkey;
        alter table public.stok_uts add constraint stok_uts_pkey primary key (id);
    end if;

    if not exists (select 1 from pg_constraint where conname = 'ux_stok_uts_stok') then
        alter table public.stok_uts add constraint ux_stok_uts_stok unique (stok_id);
    end if;
end $$;

comment on column public.stok_uts.id is
  'Satir kimligi (120). Kart detay mekanizmasi satirlari bu alandan tanir; 1:1 kurali stok_id benzersizligiyle korunur.';

do $$
declare v_satir integer;
begin
    select count(*) into v_satir from public.stok_uts;
    raise notice '120 tamam: stok_uts % satir, id kolonu hazir', v_satir;
end $$;
