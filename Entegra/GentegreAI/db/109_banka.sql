-- ------------------------------------------------------------- lookup'lar ---
-- Kart alanlari (KodTablosu) "id, ad, aktif" bekler.
create or replace view public.v_banka_lookup as
select id, ad, aktif from public.banka;

create or replace view public.v_banka_sube_lookup as
select s.id, b.kisa_ad || ' — ' || s.ad as ad, s.aktif
  from public.banka_sube s
  join public.banka b on b.id = s.banka_id;

comment on view public.v_banka_sube_lookup is
  'Sube secimi: bankasiyla birlikte gosterilir (sube adlari bankalar arasi tekrar eder).';

-- --------------------------------------------------- kayitlari baglama ----
-- Cek/senet ve hesap kartlarindaki banka/sube METIN alanlari kaliyor (eski
--   kayitlar icin) ama yeni girisler ID ile baglanir. Gocte doldurulmus banka
--   adi YOK (0 kayit), donusturulecek veri de yok.
alter table public.cek_senet
    add column if not exists banka_id      integer references public.banka(id),
    add column if not exists banka_sube_id integer references public.banka_sube(id);

alter table public.hesap
    add column if not exists banka_id      integer references public.banka(id),
    add column if not exists banka_sube_id integer references public.banka_sube(id);

comment on column public.cek_senet.banka_id is 'Kagidin bankasi (109). Eski banka_adi metni yalniz gocmus kayitlar icin.';
comment on column public.hesap.banka_id is 'Hesabin bankasi (109). Eski banka_adi metni yalniz gocmus kayitlar icin.';

