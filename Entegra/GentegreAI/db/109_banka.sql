--  109_banka.sql
--
--  Cek/senet ve banka hesabi kartlarinda banka ve sube ELLE YAZILIYORDU
--  (varchar). Ayni banka "Ziraat", "T.C. Ziraat Bankasi", "ziraat" diye uc kez
--  yaziliyor, raporda tek banka gorunmuyordu. Iki tablo aciliyor.
--
--  BANKALAR SEED'LI: Turkiye'de faaliyetteki bankalar EFT kodlariyla gelir -
--  liste kisadir (~40) ve degismez, kullaniciya yazdirmanin anlami yok.
--
--  SUBELER BOS BASLAR: binlerce sube var ve guvenilir acik kaynagi yok;
--  kullanici calistigi subeyi bir kez ekler, sonra listeden secer. Uydurma
--  sube listesi koymak, yanlis IBAN/sube eslesmesinden kotudur.
-- ============================================================================
\set ON_ERROR_STOP on

create table if not exists public.banka (
    id                integer generated by default as identity primary key,
    kod               varchar(10)  not null default '',   -- EFT katilimci kodu
    ad                varchar(120) not null,
    kisa_ad           varchar(40)  not null default '',
    swift             varchar(15)  not null default '',
    aktif             smallint     not null default 1,
    sira              smallint     not null default 0,
    ekleyen           integer      not null default 0,
    ekleme_tarihi     timestamp    not null default now()::timestamp,
    degistiren        integer      not null default 0,
    degistirme_tarihi timestamp
);

comment on table public.banka is
  'Banka tanimlari (109). EFT kodu ile seed edilir; hesap ve cek/senet buna baglanir.';

create unique index if not exists ux_banka_ad on public.banka (ad);

create table if not exists public.banka_sube (
    id                integer generated by default as identity primary key,
    banka_id          integer      not null references public.banka(id),
    kod               varchar(10)  not null default '',   -- sube kodu
    ad                varchar(120) not null,
    il                varchar(60)  not null default '',
    ilce              varchar(60)  not null default '',
    telefon           varchar(30)  not null default '',
    aktif             smallint     not null default 1,
    ekleyen           integer      not null default 0,
    ekleme_tarihi     timestamp    not null default now()::timestamp,
    degistiren        integer      not null default 0,
    degistirme_tarihi timestamp
);

comment on table public.banka_sube is
  'Banka subeleri (109). SEED YOK - kullanici calistigi subeyi ekler.';

create index if not exists ix_banka_sube_banka on public.banka_sube (banka_id, aktif);
create unique index if not exists ux_banka_sube on public.banka_sube (banka_id, ad);

do $$
begin
    if not exists (select 1 from pg_trigger where tgname = 'trg_banka_degistirme') then
        create trigger trg_banka_degistirme before update on public.banka
            for each row execute function public.fn_degistirme_tarihi();
    end if;
    if not exists (select 1 from pg_trigger where tgname = 'trg_banka_sube_degistirme') then
        create trigger trg_banka_sube_degistirme before update on public.banka_sube
            for each row execute function public.fn_degistirme_tarihi();
    end if;
end $$;

