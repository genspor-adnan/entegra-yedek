-- ============================================================================
--  406 - ILAC FIYAT TARIHCESI (Faz 0/1)
--
--  Uc ayri fiyat, uc ayri kaynak, tek tablo:
--    * TITCK Detayli Fiyat Listesi -> depocu + perakende (KDV dahil/haric)
--    * SGK Ek-4/A                  -> kamu fiyati + iskonto oranlari
--    * Kurumun ALIS faturasi       -> BURAYA GIRMEZ (stok maliyeti belge
--                                     tarafinda; perakende fiyati maliyet
--                                     sanmak ay sonunda "kar neden yanlis"
--                                     sorusunu dogurur)
--
--  TARIHCE SART: TITCK fiyati her Cuma ilan edilir, takip eden SALI yururluge
--  girer. Tek "guncel fiyat" kolonu tutan sistem, bir ay sonra eski faturayi
--  yeniden hesaplayamaz - hangi tarihte hangi fiyat gecerliydi bilinmeli.
--
--  ilac tablosundaki iki kolon GOLGEDIR (listede/aramada hizli okunsun);
--  dogruluk kaynagi daima tarihcedir.
-- ============================================================================

create table if not exists public.ilac_fiyat (
    id               integer      primary key generated by default as identity,
    barkod           varchar(20)  not null,
    -- 1 TITCK detayli fiyat · 2 SGK Ek-4/A · 9 elle giris
    kaynak           smallint     not null default 1,
    yururluk_bas     date         not null,
    yururluk_bit     date,
    -- TITCK
    depocu_fiyat     numeric(19,4),
    perakende_fiyat  numeric(19,4),
    kdv_oran         numeric(9,4),
    -- SGK Ek-4/A
    kamu_fiyat       numeric(19,4),
    kamu_iskonto     numeric(9,4),
    esdeger_iskonto  numeric(9,4),
    para_birimi      varchar(3)   not null default 'TL',
    kaynak_surum     varchar(40)  not null default '',
    ekleyen          integer      not null default 0,
    ekleme_tarihi    timestamp    not null default now(),
    constraint ux_ilac_fiyat unique (barkod, kaynak, yururluk_bas)
);

comment on table public.ilac_fiyat is
    'Ilac fiyat tarihcesi (406): TITCK detayli fiyat + SGK Ek-4/A. Alis fiyati BURAYA GIRMEZ.';

create index if not exists ix_ilac_fiyat_barkod on public.ilac_fiyat(barkod, yururluk_bas desc);

-- Golge kolonlar: liste/arama hizli okusun (dogruluk kaynagi tarihce).
alter table public.ilac
    add column if not exists guncel_perakende numeric(19,4),
    add column if not exists guncel_kamu      numeric(19,4),
    add column if not exists fiyat_tarihi     date;

-- SKRS e-Recete listesinden gelen ek bilgiler (recete turu ZATEN vardi ama
--   TITCK ruhsat listesinde yok - gercek kaynagi SKRS e-Recete listesi).
alter table public.ilac
    add column if not exists temel_ilac       smallint not null default 0,
    add column if not exists cocuk_temel_ilac smallint not null default 0;

-- Verilen tarihte gecerli fiyat: ekranlar ve belge kesimi bunu okur.
create or replace function public.fn_ilac_fiyat(p_barkod varchar, p_tarih date default current_date)
returns table (perakende numeric, kamu numeric, depocu numeric, kdv numeric, yururluk date)
language sql stable as $$
    select f.perakende_fiyat, f.kamu_fiyat, f.depocu_fiyat, f.kdv_oran, f.yururluk_bas
      from public.ilac_fiyat f
     where f.barkod = p_barkod
       and f.yururluk_bas <= p_tarih
       and (f.yururluk_bit is null or f.yururluk_bit >= p_tarih)
     order by f.yururluk_bas desc, f.kaynak asc
     limit 1;
$$;

-- Golge kolonlari tazele (yukleyiciler cagirir).
create or replace function public.fn_ilac_fiyat_golge_tazele()
returns integer language plpgsql as $$
declare v_sayi integer;
begin
    with son as (
        select distinct on (barkod) barkod, perakende_fiyat, kamu_fiyat, yururluk_bas
          from public.ilac_fiyat
         where yururluk_bas <= current_date
         order by barkod, yururluk_bas desc, kaynak asc
    )
    update public.ilac i
       set guncel_perakende = coalesce(s.perakende_fiyat, i.guncel_perakende),
           guncel_kamu      = coalesce(s.kamu_fiyat, i.guncel_kamu),
           fiyat_tarihi     = s.yururluk_bas
      from son s
     where s.barkod = i.barkod
       and (i.fiyat_tarihi is distinct from s.yururluk_bas
            or i.guncel_perakende is distinct from coalesce(s.perakende_fiyat, i.guncel_perakende));
    get diagnostics v_sayi = row_count;
    return v_sayi;
end $$;

insert into public.katalog_senkron (kod, ad)
select v.kod, v.ad
  from (values ('ilac_fiyat', 'İlaç fiyatları (TİTCK / SGK)'),
               ('ilac_recete', 'SKRS e-Reçete listesi (reçete türü)')) as v(kod, ad)
 where not exists (select 1 from public.katalog_senkron k where k.kod = v.kod);
