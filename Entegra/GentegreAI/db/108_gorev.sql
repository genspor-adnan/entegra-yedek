-- ============================================================================
--  Gentegre AI — GOREV / HATIRLATMA / TAKVIM
--  108_gorev.sql
--
--  Ana sayfa panelinde "Bekleyen Görev" ve "Yaklaşan Takvim" kutulari mockup'ta
--  vardi ama modul YOKTU; uydurma sayi gostermemek icin bos birakilmisti.
--  Bu goc modulu aciyor.
--
--  TEK TABLO: gorev, hatirlatma ve takvim kaydi ayni seydir - degisen yalnizca
--  TUR ve tarih alanlarinin nasil okundugudur. Ayri "takvim" tablosu acmak ayni
--  alanlari (kime, ne zaman, ne hakkinda) ikinci kez tanimlamak olurdu.
--
--    tur     1 Görev · 2 Hatırlatma · 3 Görüşme/Aktivite · 4 Toplantı · 9 Diğer
--    durum   0 Bekliyor · 1 Devam Ediyor · 2 Tamamlandı · 3 İptal
--    oncelik 1 Düşük · 2 Normal · 3 Yüksek · 4 Acil
--
--  ILGILI KAYIT: taraf_id (cari/kisi), proje_id, belge_id - hepsi opsiyonel.
--  Gorev bir cariyle, bir projeyle ya da bir belgeyle iliskili olabilir; ucu de
--  bos olan serbest gorev de gecerlidir.
-- ============================================================================
\set ON_ERROR_STOP on

create table if not exists public.gorev (
    id                bigint generated by default as identity primary key,
    gorev_no          varchar(20)  not null default '',
    konu              varchar(200) not null,
    aciklama          text         not null default '',

    tur               smallint     not null default 1,
    kategori          smallint     not null default 0,
    oncelik           smallint     not null default 2,
    durum             smallint     not null default 0,
    ilerleme          smallint     not null default 0,      -- yuzde 0-100

    -- KIM: sorumlu = isi yapacak personel, acan = kaydi olusturan kullanici.
    sorumlu_id        bigint,
    acan_id           integer      not null default 0,

    -- NE ZAMAN: baslangic takvimde konumu, termin ise "geciken" hesabini verir.
    baslangic         timestamp,
    termin            timestamp,
    hatirlatma        timestamp,
    tamamlanma        timestamp,
    tum_gun           smallint     not null default 0,

    -- NE HAKKINDA (hepsi opsiyonel)
    taraf_id          bigint,
    proje_id          bigint,
    belge_id          bigint,

    sube_id           integer      not null default 0,
    giris_kaynak      smallint     not null default 0,
    ekleyen           integer      not null default 0,
    ekleme_tarihi     timestamp    not null default now()::timestamp,
    degistiren        integer      not null default 0,
    degistirme_tarihi timestamp,

    constraint ck_gorev_durum   check (durum   between 0 and 3),
    constraint ck_gorev_oncelik check (oncelik between 1 and 4),
    constraint ck_gorev_ilerleme check (ilerleme between 0 and 100)
);

comment on table public.gorev is
  'Gorev / hatirlatma / takvim kaydi (108). Panel ve CRM ekranlari bunu okur.';
comment on column public.gorev.tur is
  '1 Görev · 2 Hatırlatma · 3 Görüşme/Aktivite · 4 Toplantı · 9 Diğer';
comment on column public.gorev.durum is
  '0 Bekliyor · 1 Devam Ediyor · 2 Tamamlandı · 3 İptal';
comment on column public.gorev.termin is
  'Bitmesi gereken an. Gecmisse ve durum 0/1 ise gorev GECIKMIS sayilir.';

do $$
begin
    if not exists (select 1 from pg_constraint where conname = 'fk_gorev_sorumlu') then
        alter table public.gorev add constraint fk_gorev_sorumlu
            foreign key (sorumlu_id) references public.taraf(id);
    end if;
    if not exists (select 1 from pg_constraint where conname = 'fk_gorev_taraf') then
        alter table public.gorev add constraint fk_gorev_taraf
            foreign key (taraf_id) references public.taraf(id);
    end if;
end $$;

-- Panelin iki sorgusu: "benim bekleyenlerim" ve "yaklasan takvim".
create index if not exists ix_gorev_sorumlu_durum on public.gorev (sorumlu_id, durum);
create index if not exists ix_gorev_termin        on public.gorev (termin) where durum in (0, 1);
create index if not exists ix_gorev_baslangic     on public.gorev (baslangic) where durum in (0, 1);
create index if not exists ix_gorev_taraf         on public.gorev (taraf_id);

do $$
begin
    if not exists (select 1 from pg_trigger where tgname = 'trg_gorev_degistirme') then
        create trigger trg_gorev_degistirme before update on public.gorev
            for each row execute function public.fn_degistirme_tarihi();
    end if;
end $$;

-- --------------------------------------------------------------- kod listeleri --
insert into public.kod_liste (kod, ad) values
    ('gorev.tur', 'Görev Türü'),
