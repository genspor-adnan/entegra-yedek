insert into public.kod_deger (liste_id, deger, ad, sira, aktif)
select kl.id, d.deger, d.ad, d.sira, 1
  from public.kod_liste kl
  join (values ('gorev.tur', 1, 'Görev', 10),
               ('gorev.tur', 2, 'Hatırlatma', 20),
               ('gorev.tur', 3, 'Görüşme / Aktivite', 30),
               ('gorev.tur', 4, 'Toplantı', 40),
               ('gorev.tur', 9, 'Diğer', 90),
               ('gorev.durum', 0, 'Bekliyor', 10),
               ('gorev.durum', 1, 'Devam Ediyor', 20),
               ('gorev.durum', 2, 'Tamamlandı', 30),
               ('gorev.durum', 3, 'İptal', 40),
               ('gorev.oncelik', 1, 'Düşük', 10),
               ('gorev.oncelik', 2, 'Normal', 20),
               ('gorev.oncelik', 3, 'Yüksek', 30),
               ('gorev.oncelik', 4, 'Acil', 40),
               ('gorev.kategori', 0, 'Genel', 10),
               ('gorev.kategori', 1, 'Satış', 20),
               ('gorev.kategori', 2, 'Muhasebe', 30),
               ('gorev.kategori', 3, 'Depo', 40),
               ('gorev.kategori', 4, 'İK', 50),
               ('gorev.kategori', 5, 'Teknik', 60)
       ) as d(liste, deger, ad, sira) on d.liste = kl.kod
 where not exists (select 1 from public.kod_deger k
                    where k.liste_id = kl.id and k.deger = d.deger);

-- ---------------------------------------------------------------------- yetki --
insert into public.yetki (kod, ad, grup, tur, deger_alir, kapsam_alir, sira, aktif)
values ('gorev', 'Görevler', 'kart', 0, 0, 0, 40, 1)
on conflict (kod) do nothing;

insert into public.rol_yetki (rol_id, yetki_id, gor, ekle, degistir, sil)
select r.id, y.id, 1,
       case when r.id = 1 then 1 else 0 end,
       case when r.id = 1 then 1 else 0 end,
       case when r.id = 1 then 1 else 0 end
  from public.rol r
  join public.yetki y on y.kod = 'gorev'
 where r.id in (1, 2)
   and not exists (select 1 from public.rol_yetki x
                    where x.rol_id = r.id and x.yetki_id = y.id);

