\set ON_ERROR_STOP on

-- ------------------------------------------------------------------ sube ----
create table if not exists public.sube (
    id                   integer generated by default as identity primary key,
    kod                  varchar(20)  not null default '',
    ad                   varchar(60)  not null,                 -- "Merkez", "Ankara Sube"
    unvan                varchar(200) not null default '',      -- resmi unvan (e-Belge gonderici)
    vkno                 varchar(20)  not null default '',
    vd                   varchar(60)  not null default '',
    adres                varchar(300) not null default '',
    ilce                 varchar(60)  not null default '',
    il                   varchar(60)  not null default '',
    ulke                 varchar(60)  not null default 'Turkiye',
    posta_kodu           varchar(10)  not null default '',
    telefon              varchar(30)  not null default '',
    eposta               varchar(120) not null default '',
    web                  varchar(200) not null default '',
    efatura_alias        varchar(500) not null default '',      -- GIB gonderici etiketi
    logo                 bytea,
    varsayilan           smallint     not null default 0,
    aktif                smallint     not null default 1,
    eski_id              integer,                                -- goc izi (REHBER.ID < 0)
    ekleyen              integer      not null default 0,
    ekleme_tarihi        timestamp    not null default now()::timestamp,
    degistiren           integer      not null default 0,
    degistirme_tarihi    timestamp
);

create unique index if not exists ux_sube_varsayilan on public.sube (varsayilan) where varsayilan = 1;
create unique index if not exists ux_sube_eski_id    on public.sube (eski_id)    where eski_id is not null;

comment on table  public.sube          is 'Firmanin kendi subeleri/lokasyonlari (eski REHBER ID<0 kayitlari). e-Belge gonderici bilgisi burada.';
comment on column public.sube.eski_id  is 'GOC IZI: eski REHBER.ID (negatif). Hareketlerdeki SUBEID bu deger uzerinden eslendi.';

-- ------------------------------------------------------- taraf: rol modeli ----
-- Bayraklar birbirini DISLAMAZ: bir kart hem musteri hem tedarikci, ya da hem
--   personel hem hasta olabilir.
alter table public.taraf add column if not exists musteri    smallint not null default 0;
alter table public.taraf add column if not exists tedarikci  smallint not null default 0;
alter table public.taraf add column if not exists personel   smallint not null default 0;
alter table public.taraf add column if not exists kisi       smallint not null default 0;
alter table public.taraf add column if not exists hasta      smallint not null default 0;
-- NOT: Ayri "tc_kimlik" kolonu YOK. Kimlik numarasi tek alanda tutulur:
--   taraf.vkno  -> musteri/tedarikcide VERGI NO, kisi/personel/hastada TC NO
--   taraf.vd    -> musteri/tedarikcide VERGI DAIRESI, personel/hastada DOGUM YERI
--   (eposta_web ile ayni desen: alan tek, anlami rol'e gore.)
--   e-Belge'de gercek kisinin VKN alani zaten TCKN ile doldurulur, bu yuzden
--   ayri kolon tutmak mukerrer veri olurdu.
create index if not exists ix_taraf_rol_musteri   on public.taraf (musteri)   where musteri = 1;
create index if not exists ix_taraf_rol_tedarikci on public.taraf (tedarikci) where tedarikci = 1;
create index if not exists ix_taraf_rol_personel  on public.taraf (personel)  where personel = 1;
create index if not exists ix_taraf_rol_hasta     on public.taraf (hasta)     where hasta = 1;

comment on column public.taraf.vkno is
  'Musteri/tedarikcide vergi numarasi, kisi/personel/hastada TC kimlik numarasi. Ayni kisinin mukerrer kart acilmasi bu alandan denetlenir.';
comment on column public.taraf.vd is
  'Musteri/tedarikcide vergi dairesi, personel/hastada DOGUM YERI.';

-- ------------------------------------------------------- rol uzantilari ----
-- Role OZEL alanlar ana tabloyu sismesin diye 1:1 uzanti tablolarinda.
create table if not exists public.taraf_musteri (
    id                   integer primary key references public.taraf (id) on delete cascade,
    risk_limiti          numeric(19,4) not null default 0,
    vade_gun             smallint      not null default 0,
    fiyat_listesi        smallint      not null default 0,
    temsilci_id          integer,
    iskonto_orani        numeric(9,4)  not null default 0,
    ekleyen              integer   not null default 0,
    ekleme_tarihi        timestamp not null default now()::timestamp,
    degistiren           integer   not null default 0,
    degistirme_tarihi    timestamp
);

create table if not exists public.taraf_tedarikci (
    id                   integer primary key references public.taraf (id) on delete cascade,
    odeme_kosulu         smallint      not null default 0,
    vade_gun             smallint      not null default 0,
    temin_suresi_gun     smallint      not null default 0,
    ekleyen              integer   not null default 0,
    ekleme_tarihi        timestamp not null default now()::timestamp,
    degistiren           integer   not null default 0,
    degistirme_tarihi    timestamp
);

create table if not exists public.taraf_kisi (
    id                   integer primary key references public.taraf (id) on delete cascade,
    ekleyen              integer   not null default 0,
    ekleme_tarihi        timestamp not null default now()::timestamp,
    degistiren           integer   not null default 0,
    degistirme_tarihi    timestamp
);

-- Ozluk: KVKK geregi ayri tablo + ayri yetki.
create table if not exists public.taraf_personel (
    id                   integer primary key references public.taraf (id) on delete cascade,
    sicil_no             varchar(20)  not null default '',
    dogum_tarihi         date,
    cinsiyet             smallint     not null default 0,      -- 0 belirtilmemis, 1 erkek, 2 kadin
    gorev                varchar(100) not null default '',
    departman            smallint     not null default 0,
    ise_giris_tarihi     date,
    isten_cikis_tarihi   date,
    sube_id              integer,
    ekleyen              integer   not null default 0,
    ekleme_tarihi        timestamp not null default now()::timestamp,
    degistiren           integer   not null default 0,
    degistirme_tarihi    timestamp
);

-- Hasta: Ayni kisi hem personel hem hasta olabilir -> ayni taraf kaydi,
--   hasta bilgisi 1:1 uzanti tablosunda tutulur.
create table if not exists public.taraf_hasta (
    id                   integer primary key references public.taraf (id) on delete cascade,
    dogum_tarihi         date,
    dogum_yeri           varchar(60) not null default '',
    cinsiyet             smallint    not null default 0,
    uyruk                varchar(60) not null default 'TC',
    kan_grubu            smallint    not null default 0,
    meslek               varchar(60) not null default '',
    ekleyen              integer     not null default 0,
    ekleme_tarihi        timestamp   not null default now()::timestamp,
    degistiren           integer     not null default 0,
    degistirme_tarihi    timestamp
);

comment on table public.taraf_hasta   is 'Hasta karti 1:1 kimlik/ozluk bilgileri. id = taraf.id.';
comment on table public.taraf_kisi    is 'Kisi rolu 1:1 uzanti tablosu. id = taraf.id.';
comment on table public.taraf_personel is 'Personel ozluk bilgileri. KVKK: ayri yetki; liste sorgulari bu tabloya dokunmaz.';

-- ---------------------------------------------------------------- gorunumler ----
drop view if exists public.cari;
drop view if exists public.personel;

create or replace view public.cari as
    select * from public.taraf where musteri = 1 or tedarikci = 1;

create or replace view public.musteri as
    select * from public.taraf where musteri = 1;

create or replace view public.tedarikci as
    select * from public.taraf where tedarikci = 1;

create or replace view public.personel as
    select * from public.taraf where personel = 1;

create or replace view public.hasta as
    select * from public.taraf where hasta = 1;

comment on view public.cari is 'Musteri + tedarikci (taraf.musteri=1 or taraf.tedarikci=1). Cift rollu kart TEK kayittir.';
comment on view public.hasta is 'Hasta rollu kartlar. Ayrintilar taraf_hasta tablosunda.';


