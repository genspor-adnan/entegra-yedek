--  Gentegre AI — HARCAMA BELGESİ / MASRAF BEYANI ONAYI
--  764_masraf_beyani.sql
--
--  Kullanıcı: "Personelin iş amaçlı yaptığı (taksi, temsil ağırlama, acil
--  malzeme alımı) cepten harcamaların fatura/fiş karşılığında geri ödenmesi
--  talebi."
--
--  ============ BEYAN BAŞLIK + SATIR =====================================
--  Bir beyan birden çok harcamayı taşır: bir günlük saha ziyaretinde taksi,
--  otopark ve yemek ayrı fişlerdir ama tek onaya gider. Her fiş ayrı beyan
--  olsaydı âmir günde on kez aynı kararı verirdi.
--
--  Satır, gider kalemini `masraf` KATALOĞUNDAN seçer (282 kayıt, muhasebe
--  kodu ve KDV oranı orada). İkinci bir "harcama türü" listesi açmak, aynı
--  kalemi iki yerde tanımlamak olurdu.
--
--  ============ BELGE NUMARASI ZORUNLU ===================================
--  "Fatura/fiş karşılığında" ifadesi kuralın kendisi: belgesiz satır
--  yazılamaz (`belge_no` boş olamaz). Beyan bir harcama İDDİASI değil,
--  belgeye dayanan bir taleptir; belgesiz kabul edilirse geri ödeme
--  denetlenemez hâle gelir.
--
--  Fişin GÖRSELİ ayrı bir kolon değil: doküman modülü kaynak + kaynak_id ile
--  her kayda ek bağlayabiliyor, üçüncü bir dosya alanı açmak o modülü
--  yok saymak olurdu.
--
--  ============ ÖDEME BU MODÜLDE DEĞİL ===================================
--  Kullanıcı kararı (17.09.2026): zincir "onaylandı" ile biter, ödemeyi
--  muhasebe kendi akışında yapar. Bu yüzden avanstaki gibi `kasa_islem`
--  bağı ve "Öde" aksiyonu YOK - olmayan bir ödeme izini varmış gibi
--  göstermektense hiç göstermemek doğru.
-- ============================================================================
\set ON_ERROR_STOP on

-- ---------------------------------------------------------------------- 1
insert into public.referans (anahtar, deger, aciklama)
select x.anahtar, x.deger, x.aciklama
  from (values
    ('ik.masraf_esik_mali', '',
     'Masraf beyaninda mali isler onayi esigi (TL). Bos ise varsayilan 2.500.'),
    ('ik.masraf_esik_ust', '',
     'Masraf beyaninda ust yonetim onayi esigi (TL). Bos ise varsayilan 10.000.')
  ) as x(anahtar, deger, aciklama)
 where not exists (select 1 from public.referans r where r.anahtar = x.anahtar);

-- ---------------------------------------------------------------------- 2
insert into public.yetki (kod, ad, grup, tur, modul, aktif, sira)
select x.kod, x.ad, 'İnsan Kaynakları', x.tur, 'ik', 1, x.sira
  from (values
        ('ik.masraf',            'Masraf Beyanı',              0::smallint, 30::smallint),
        ('ik.masraf_onay_amir',  'Masraf onayı - âmir',        1::smallint, 31::smallint),
        ('ik.masraf_onay_mali',  'Masraf onayı - mali işler',  1::smallint, 32::smallint),
        ('ik.masraf_onay_ust',   'Masraf onayı - üst yönetim', 1::smallint, 33::smallint)
  ) as x(kod, ad, tur, sira)
 where not exists (select 1 from public.yetki y where y.kod = x.kod);

-- TANIMLI AMA VERİLMEMİŞ YETKİ = ekranı ilk açanda 403 (747/752/753'te aynı
--   hata iki kez yapıldı). Aksiyon yetkisinde yalnız `gor` anlamlı.
insert into public.rol_yetki (rol_id, yetki_id, gor, ekle, degistir, sil)
select r.id, y.id, 1,
       case when y.tur = 1 then 0 else 1 end,
       case when y.tur = 1 then 0 else 1 end, 0
  from public.rol r cross join public.yetki y
 where r.kod in ('yonetici', 'ik')
   and y.kod in ('ik.masraf', 'ik.masraf_onay_amir', 'ik.masraf_onay_mali',
                 'ik.masraf_onay_ust')
   and not exists (select 1 from public.rol_yetki ry
                    where ry.rol_id = r.id and ry.yetki_id = y.id);

-- ---------------------------------------------------------------------- 3
--  BEYAN BAŞLIĞI
--  `toplam_tutar` satırlardan TÜRETİLİR ama kolonda durur: onay ölçüsü odur
--  ve karar anındaki tutarın sonradan değişmemesi gerekir. Satır eklenince
--  başlık yeniden hesaplanır - ama yalnız TASLAK beyanda (aşağıdaki tetik).
create table if not exists public.personel_masraf (
    id                integer      primary key generated by default as identity,
    beyan_no          varchar(30)  not null default '',
    taraf_id          integer      not null references public.taraf_personel (id),
    sube_id           integer      not null,
    beyan_tarihi      date         not null default current_date,
    aciklama          varchar(300) not null default '',
    toplam_tutar      numeric(18,4) not null default 0,
    -- 0 taslak · 1 onayda · 2 onaylandı · 3 reddedildi · 8 iptal
    --   ÖDENDİ DURUMU YOK: ödeme bu modülde değil (bkz. başlık).
    durum             smallint     not null default 0,
    red_neden         varchar(300) not null default '',
    iptal_neden       varchar(300) not null default '',
    ekleyen           integer      not null default 0,
    ekleme_tarihi     timestamptz  not null default now(),
    degistiren        integer      not null default 0,
    degistirme_tarihi timestamptz
);
create index if not exists ix_personel_masraf_taraf
    on public.personel_masraf (taraf_id, beyan_tarihi desc);
create index if not exists ix_personel_masraf_durum
    on public.personel_masraf (durum) where durum in (0, 1);

comment on table public.personel_masraf is
  '764: personelin cepten yaptigi is harcamalarinin geri odeme beyani. '
  'Odeme bu modulde DEGIL - zincir onayla biter, muhasebe disarida oder.';

-- ---------------------------------------------------------------------- 4
--  BEYAN SATIRI
create table if not exists public.personel_masraf_satir (
    id                integer      primary key generated by default as identity,
    beyan_id          integer      not null
                      references public.personel_masraf (id) on delete cascade,
    sira              smallint     not null default 1,
    masraf_id         integer      references public.masraf (id),
    harcama_tarihi    date         not null default current_date,
    -- 1 fatura · 2 fiş / perakende satış belgesi · 3 e-arşiv · 4 bilet
    -- 5 gider pusulası · 9 diğer
    belge_turu        smallint     not null default 2,
    belge_no          varchar(60)  not null,
    tutar             numeric(18,4) not null default 0,
    kdv_tutar         numeric(18,4) not null default 0,
    aciklama          varchar(300) not null default '',
    ekleyen           integer      not null default 0,
    ekleme_tarihi     timestamptz  not null default now(),
    -- BELGESİZ SATIR YAZILAMAZ: beyan bir iddia değil, belgeye dayanan
    --   bir taleptir.
    constraint ck_masraf_satir_belge check (btrim(belge_no) <> ''),
    constraint ck_masraf_satir_tutar check (tutar > 0)
);
create index if not exists ix_personel_masraf_satir
    on public.personel_masraf_satir (beyan_id, sira);

comment on column public.personel_masraf_satir.belge_no is
  '764: fatura/fis numarasi - ZORUNLU. Belgesiz harcama beyan edilemez.';
comment on column public.personel_masraf_satir.masraf_id is
  '764: gider kalemi `masraf` katalogundan (muhasebe kodu ve KDV orani orada).';

-- ---------------------------------------------------------------------- 5
--  TOPLAM: satır değişince başlık yeniden hesaplanır - YALNIZ TASLAKTA.
--  Onaya gönderilmiş beyanın tutarı değişirse, imza başka bir rakama
--  verilmiş olur; iskonto kilidiyle aynı gerekçe (662).
create or replace function public.tg_masraf_toplam()
returns trigger language plpgsql as $$
declare v_beyan int;
begin
    v_beyan := coalesce(new.beyan_id, old.beyan_id);

    if exists (select 1 from public.personel_masraf
                where id = v_beyan and durum <> 0) then
        raise exception 'Taslak olmayan masraf beyanının satırları değiştirilemez.'
              using errcode = 'GK422';
    end if;

    update public.personel_masraf m
       set toplam_tutar = coalesce((select sum(s.tutar)
                                      from public.personel_masraf_satir s
                                     where s.beyan_id = v_beyan), 0),
           degistirme_tarihi = now()
     where m.id = v_beyan;

    return null;
end $$;

drop trigger if exists tr_masraf_toplam on public.personel_masraf_satir;
create trigger tr_masraf_toplam
  after insert or update or delete on public.personel_masraf_satir
  for each row execute function public.tg_masraf_toplam();

-- ---------------------------------------------------------------------- 6
--  LİSTE GÖRÜNÜMÜ
create or replace view public.v_personel_masraf as
select m.id,
       m.beyan_no,
       m.taraf_id,
       m.sube_id,
       coalesce(nullif(t.unvan, ''), '')              as personel_ad,
       coalesce(nullif(p.gorev, ''), '')              as gorev_ad,
       coalesce(nullif(am.unvan, ''), '')             as amir_ad,
       m.beyan_tarihi,
       m.aciklama,
       m.toplam_tutar,
       m.durum,
       m.red_neden,
       (select count(*) from public.personel_masraf_satir s
         where s.beyan_id = m.id)                     as satir_sayisi,
       -- EN ESKİ HARCAMA: geç beyan edilen masraf, unutulmuş masraftır;
       --   listede "kaç gündür bekliyor" sorusunu bu cevaplar.
       (select min(s.harcama_tarihi) from public.personel_masraf_satir s
         where s.beyan_id = m.id)                     as ilk_harcama,
       (select v.adim_ad from public.v_onay_bekleyen v
         where v.kaynak_tur = 1312 and v.kaynak_id = m.id
         order by v.sira limit 1)                     as bekleyen_basamak,
       m.ekleme_tarihi,
       m.degistirme_tarihi
  from public.personel_masraf m
  join public.taraf t               on t.id = m.taraf_id
  left join public.taraf_personel p on p.id = m.taraf_id
  left join public.taraf am         on am.id = p.yonetici_taraf_id;

comment on view public.v_personel_masraf is
  '764: masraf beyani listesi - satir sayisi, ilk harcama ve bekleyen basamak.';

-- ---------------------------------------------------------------------- 7
--  ONAY AKIŞI
--  Ölçü = beyanın toplam tutarı. Birim âmiri HER beyanda: harcamanın
--  gerçekten iş amaçlı olduğunu söyleyebilecek tek kişi odur; mali işler
--  tutara bakar, işin niteliğine değil.
insert into public.onay_akis (kod, ad, kaynak_tur, olcu_adi, aktif, aciklama, ekleyen)
select 'personel.masraf', 'Masraf Beyanı Onayı', 1312, 'Tutar (TL)', 1,
       '764: birim amiri her beyanda; esik ustu mali isler ve ust yonetim. '
       'Odeme bu akista YOK - zincir onayla biter.', 0
 where not exists (select 1 from public.onay_akis where kod = 'personel.masraf');

insert into public.onay_akis_adim
       (akis_id, sira, ad, sahip_turu, rol, esik_alt, bayrak, sure_gun, ekleyen)
select k.id, x.sira, x.ad, x.sahip, x.rol, x.esik, '', x.sure, 0
  from public.onay_akis k
  cross join (values
        -- 3 = ÂMİR: harcamayı yapanın yöneticisi (taraf_personel.yonetici_taraf_id)
        (1::smallint, 'Birim Âmiri', 3::smallint, 0::smallint, null::numeric, 2::smallint),
        (2::smallint, 'Mali İşler',  1::smallint, 4::smallint, 2500::numeric, 3::smallint),
        (3::smallint, 'Üst Yönetim', 1::smallint, 5::smallint, 10000::numeric, 3::smallint)
      ) as x(sira, ad, sahip, rol, esik, sure)
 where k.kod = 'personel.masraf'
   and not exists (select 1 from public.onay_akis_adim a where a.akis_id = k.id);

-- ---------------------------------------------------------------------- 8
--  GELEN KUTUSU MASRAFI DA TANISIN
create or replace view public.v_onay_kutusu as
select v.adim_id                                as id,
       v.onay_id, v.kaynak_tur, v.kaynak_id, v.sube_id,
       v.akis_kod, v.akis_ad, v.olcu, v.olcu_adi, v.sira, v.adim_ad, v.rol,
       v.atanan_kullanici_id, v.durum, v.gerekce, v.baslama, v.termin,
       v.gecikme_gun,
       case v.kaynak_tur
            when 1241 then coalesce(nullif(t.talep_no, ''), '#' || v.kaynak_id::text)
            when 904  then coalesce(nullif(z.izin_no, ''), 'İzin #' || v.kaynak_id::text)
            when 1224 then coalesce(nullif(w.is_emri_no, ''),
                                    'İş emri #' || v.kaynak_id::text)
            when 1257 then coalesce(nullif(av.avans_no, ''),
                                    'Avans #' || v.kaynak_id::text)
            when 1256 then coalesce(nullif(ib.belge_no, ''),
                                    'Başvuru #' || coalesce(isk.belge_id, 0)::text)
            when 976  then coalesce(nullif(dk.kod, ''), 'DOK-' || dk.id::text)
                           || ' v' || ds.surum_no::text
            when 1312 then coalesce(nullif(ms.beyan_no, ''),
                                    'Masraf #' || v.kaynak_id::text)
            else '#' || v.kaynak_id::text
       end                                      as kayit_no,
       case v.kaynak_tur
            when 1241 then coalesce(nullif(t.gerekce, ''), 'Satınalma talebi')
            when 904  then case z.tur when 1 then 'Yıllık izin'
                                      when 2 then 'Mazeret izni'
                                      when 3 then 'Rapor'
                                      when 4 then 'Ücretsiz izin'
                                      else 'İzin' end
                           || ' · ' || to_char(z.baslangic_tarihi, 'DD.MM')
                           || '-' || to_char(z.bitis_tarihi, 'DD.MM.YYYY')
            when 1224 then coalesce(nullif(dm.ad, ''), 'Cihaz')
                           || ' · ' || coalesce(nullif(w.ariza_metni, ''), 'onarım')
            when 1257 then coalesce(nullif(av.gerekce, ''), 'Avans')
                           || ' · ' || av.taksit_sayisi::text || ' taksit'
            when 1256 then coalesce(nullif(isk.gerekce, ''), 'İskonto talebi')
                           || ' · ' || (select count(*)::text
                                          from public.iskonto_talep_satir ts
                                         where ts.talep_id = isk.id) || ' kalem'
            when 976  then coalesce(nullif(dk.ad, ''), 'Doküman')
                           || coalesce(' · ' || nullif(ds.degisiklik_notu, ''), '')
            -- MASRAFTA KONU = AÇIKLAMA + KAÇ BELGE: onaylayanın sorusu
            --   "ne kadar" değil yalnız; "ne için ve kaç fiş".
            when 1312 then coalesce(nullif(ms.aciklama, ''), 'Masraf beyanı')
                           || ' · ' || (select count(*)::text
                                          from public.personel_masraf_satir mss
                                         where mss.beyan_id = ms.id) || ' belge'
            else ''
       end                                      as konu,
       case v.kaynak_tur
            when 1241 then coalesce(d.ad, '')
            when 904  then coalesce(nullif(zp.gorev, ''), '')
            when 1224 then coalesce(wd.ad, '')
            when 1257 then coalesce(nullif(ap.gorev, ''), '')
            when 1256 then coalesce(ih.unvan, '')
            when 976  then coalesce(dkat.ad, '')
            when 1312 then coalesce(nullif(mp.gorev, ''), '')
            else ''
       end                                      as birim,
       case v.kaynak_tur
            when 1241 then coalesce(p.unvan, '')
            when 904  then coalesce(zt.unvan, '')
            when 1224 then coalesce(wb.unvan, '')
            when 1257 then coalesce(at.unvan, '')
            when 1256 then coalesce(ii.unvan, '')
            when 976  then coalesce(dy.unvan, '')
            when 1312 then coalesce(mt.unvan, '')
            else ''
       end                                      as talep_eden
  from public.v_onay_bekleyen v
  left join public.satinalma_talep t on v.kaynak_tur = 1241 and t.id = v.kaynak_id
  left join public.departman d on d.id = t.departman_id
  left join public.taraf p     on p.id = t.isteyen_id
  left join public.personel_izin z on v.kaynak_tur = 904 and z.id = v.kaynak_id
  left join public.taraf zt          on zt.id = z.taraf_id
  left join public.taraf_personel zp on zp.id = z.taraf_id
  left join public.demirbas_is_emri w on v.kaynak_tur = 1224 and w.id = v.kaynak_id
  left join public.demirbas dm  on dm.id = w.demirbas_id
  left join public.departman wd on wd.id = w.departman_id
  left join public.taraf wb     on wb.id = w.bildiren_id
  left join public.personel_avans av on v.kaynak_tur = 1257 and av.id = v.kaynak_id
  left join public.taraf at          on at.id = av.taraf_id
  left join public.taraf_personel ap on ap.id = av.taraf_id
  left join public.iskonto_talep isk on v.kaynak_tur = 1256 and isk.id = v.kaynak_id
  left join public.belge ib on ib.id = isk.belge_id
  left join public.taraf ih on ih.id = ib.taraf_id
  left join public.taraf ii on ii.id = isk.isteyen_id
  left join public.dokuman_surum ds on v.kaynak_tur = 976 and ds.id = v.kaynak_id
  left join public.dokuman dk        on dk.id = ds.dokuman_id
  left join public.dokuman_kategori dkat on dkat.id = dk.kategori_id
  left join public.taraf dy          on dy.id = ds.yukleyen_id
  left join public.personel_masraf ms on v.kaynak_tur = 1312 and ms.id = v.kaynak_id
  left join public.taraf mt          on mt.id = ms.taraf_id
  left join public.taraf_personel mp on mp.id = ms.taraf_id;

