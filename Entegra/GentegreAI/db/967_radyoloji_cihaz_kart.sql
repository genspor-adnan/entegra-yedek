create table if not exists public.radyoloji_cihaz_qa (
    id          integer generated by default as identity primary key,
    cihaz_id    integer not null references public.radyoloji_cihaz(id) on delete cascade,
    sira        smallint not null default 0,
    ad          varchar(100) not null,
    periyot_gun integer,                     -- 1 günlük · 7 haftalık · 365 yıllık · null tek sefer
    son_tarih   date,
    sonuc       smallint,                    -- 1 uygun · 2 uygun değil
    notu        varchar(200) not null default '',
    ekleyen integer, ekleme_tarihi timestamptz default now(), degistiren integer, degistirme_tarihi timestamptz
);
create index if not exists ix_rad_cihaz_qa on public.radyoloji_cihaz_qa (cihaz_id, sira);

insert into public.kod_liste (kod, ad)
select 'rad.qa_sonuc', 'Cihaz Kalite Kontrol Sonucu'
 where not exists (select 1 from public.kod_liste where kod = 'rad.qa_sonuc');
insert into public.kod_deger (liste_id, deger, ad, dil, sira, aktif, ekleyen)
select l.id, v.deger, v.ad, 0, v.deger, 1, 0
  from (values (1, 'Uygun'), (2, 'Uygun değil')) v(deger, ad)
  join public.kod_liste l on l.kod = 'rad.qa_sonuc'
 where not exists (select 1 from public.kod_deger x where x.liste_id = l.id and x.deger = v.deger and x.dil = 0);

-- Cihaz seçimi için protokol arama görünümü (cihaz kartı "Protokoller" sekmesi).
create or replace view public.v_rad_protokol_lookup as
select p.id, coalesce(h.ad, '') as ad, p.durum as aktif
  from public.radyoloji_protokol p join public.hizmet h on h.id = p.hizmet_id;

-- ANLIK DURUM + BUGÜN + HAFTA + QA (liste ve gösterge aynı tanım).
drop view if exists public.v_radyoloji_cihaz_durum;
create view public.v_radyoloji_cihaz_durum as
with simdi as (select now() as an, (now() at time zone 'Europe/Istanbul')::date as gun)
select c.id as cihaz_id,
       case when c.durum <> 1 then 0
            when k.neden_tur = 2 then 3                 -- arızada
            when k.id is not null then 2                -- bakım / kapalı
            else 1 end::smallint as su_an_kod,
       case when c.durum <> 1 then 'Pasif'
            when k.neden_tur = 2 then 'Arızada'
            when k.neden_tur = 1 then 'Bakımda'
            when k.id is not null then 'Kapalı'
            else 'Çalışıyor' end::varchar(20) as su_an,
       k.bitis as kapali_bitis,
       (select count(*) from public.radyoloji_istem i
         where i.cihaz_id = c.id and (i.cekim_tarihi at time zone 'Europe/Istanbul')::date = s.gun)::int as bugun_cekim,
       (select count(*) from public.randevu r
         where r.cihaz_id = c.id and r.durum <> 4 and (r.baslangic at time zone 'Europe/Istanbul')::date = s.gun)::int as bugun_randevu,
       (select count(*) from public.radyoloji_istem i
         where i.cihaz_id = c.id and i.durum = 1 and (i.ekleme_tarihi at time zone 'Europe/Istanbul')::date = s.gun)::int as sirada,
       (select count(*) from public.randevu r
         where r.cihaz_id = c.id and r.durum <> 4
           and r.baslangic >= date_trunc('week', s.an) and r.baslangic < date_trunc('week', s.an) + interval '7 days')::int as hafta_randevu,
       -- HAFTALIK KAPASİTE: (mesai - öğle) / slot x eşzaman x çalışma günü. Randevusuz cihazda null.
       case when c.randevu_verilir = 1 and coalesce(c.slot_dk, 0) > 0
                 and c.baslangic_saat ~ '^\d{1,2}:\d{2}$' and c.bitis_saat ~ '^\d{1,2}:\d{2}$' then
            (greatest(0, extract(epoch from (c.bitis_saat::time - c.baslangic_saat::time)) / 60
                       - case when c.ogle_baslangic ~ '^\d{1,2}:\d{2}$' and c.ogle_bitis ~ '^\d{1,2}:\d{2}$'
                              then extract(epoch from (c.ogle_bitis::time - c.ogle_baslangic::time)) / 60 else 0 end)
             / c.slot_dk)::int * greatest(coalesce(c.eszaman, 1), 1)
             * greatest(cardinality(string_to_array(nullif(c.calisma_gunleri, ''), ',')), 0)
       end::int as hafta_kapasite,
       (select count(*) from public.radyoloji_protokol_cihaz pc where pc.cihaz_id = c.id)::int as protokol_sayisi,
       (select count(*) from public.radyoloji_istem i
         where i.cihaz_id = c.id and i.durum >= 2 and coalesce(i.study_uid, '') = ''
           and i.cekim_tarihi > s.an - interval '2 days')::int as goruntu_eksik,
       (select count(*) from public.radyoloji_cihaz_qa q
         where q.cihaz_id = c.id and q.periyot_gun is not null
           and (q.son_tarih is null or q.son_tarih + q.periyot_gun < s.gun))::int as qa_geciken,
       (select count(*) from public.radyoloji_cihaz_qa q
         where q.cihaz_id = c.id and q.periyot_gun is not null and q.son_tarih is not null
           and q.son_tarih + q.periyot_gun between s.gun and s.gun + 30)::int as qa_yaklasan,
       (select string_agg(q.ad, ', ' order by q.sira) from public.radyoloji_cihaz_qa q
         where q.cihaz_id = c.id and q.periyot_gun is not null
           and (q.son_tarih is null or q.son_tarih + q.periyot_gun < s.gun)) as qa_geciken_ad
  from public.radyoloji_cihaz c
  cross join simdi s
  left join lateral (
       select x.id, x.neden_tur, x.bitis from public.radyoloji_cihaz_kapatma x
        where x.cihaz_id = c.id and s.an between x.baslangic and x.bitis
        order by x.neden_tur = 2 desc, x.bitis desc limit 1) k on true;
