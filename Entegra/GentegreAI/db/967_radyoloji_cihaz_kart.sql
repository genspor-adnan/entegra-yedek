alter table public.radyoloji_cihaz add column if not exists marka           varchar(60)  not null default '';
alter table public.radyoloji_cihaz add column if not exists model           varchar(80)  not null default '';
alter table public.radyoloji_cihaz add column if not exists seri_no         varchar(60)  not null default '';
alter table public.radyoloji_cihaz add column if not exists uretim_yili     smallint;
