--  MEVCUT ALTYAPI KORUNUR: `dokuman` (polimorfik kaynak+kaynak_id) ve
--  `dokuman_icerik` (hash-dedup) oldugu gibi kalir; kart galerileri ayni
--  tabloyu gormeye devam eder. Ustune YONETIM KATMANI eklenir: klasor, tur,
--  surum, onay, gizlilik, gunluk.
--
--  Neden ayri tablo degil de ayni tablo: bir personelin is sozlesmesi hem
--  kart galerisinde hem kurumsal klasorde gorunmeli. Ikinci bir "kurumsal
--  dokuman" tablosu acmak, ayni dosyanin iki kopyasini ve iki farkli izin
--  modelini dogururdu.
--
--  SURUM AYRI TABLODA: `dokuman.hash` YAYINDAKI surumu gosterir, tarihce
--  `dokuman_surum`dedir. Tek satirda tutmak "gecen yilki prosedur neydi"
--  sorusunu cevapsiz birakirdi - kalite denetiminin ilk sordugu sey budur.
--
--  SURUMSUZ TURLER (urun resmi, tetkik sonucu) akisa girmez: yukleme =
--  yayinda. Her dosyayi onaydan gecirmek, galeriye resim ekleyeni onay
--  beklemeye mahkum ederdi.
-- ============================================================================

-- ----------------------------------------------------------- belge turu ----
create table if not exists public.dokuman_turu (
    id            integer     primary key generated by default as identity,
    ad            varchar(80) not null,
    kisaltma      varchar(10) not null default '',
    -- Surum takibi acik mi: resimde kapali, prosedurde acik.
    surumlu       smallint    not null default 0,
    akis_id       integer,
    gozden_gecirme_ay smallint not null default 0,
    -- 1 herkese acik · 2 kurum ici · 3 gizli · 4 ozel nitelikli (KVKK)
    gizlilik      smallint    not null default 2,
    -- Hangi kartlarda secilebilir; bos = hepsi.
    kaynaklar     varchar(20)[] not null default '{}',
    aktif         smallint    not null default 1,
    sira          smallint    not null default 0,
    ekleyen       integer     not null default 0,
    ekleme_tarihi timestamp   not null default now(),
    degistiren    integer     not null default 0,
    degistirme_tarihi timestamp,
    constraint ux_dokuman_turu_ad unique (ad)
);

-- --------------------------------------------------------------- klasor ----
--  Kurumsal klasor agaci. KAYNAK KLASORLERI SANALDIR: bir personelin
--  dokumanlari kaynak+kaynak_id'den turer, klasor kaydi gerektirmez - yoksa
--  her yeni personel icin klasor acmak gerekirdi.
create table if not exists public.dokuman_klasor (
    id            integer      primary key generated by default as identity,
    ust_id        integer,
    ad            varchar(120) not null,
    -- Yol denormalize: agacta yukari yurumeden arama/gosterim yapilabilsin.
    yol           varchar(400) not null default '',
    varsayilan_tur_id integer,
    varsayilan_gizlilik smallint not null default 2,
    kod_sablonu   varchar(60)  not null default '',
    sira          smallint     not null default 0,
    aktif         smallint     not null default 1,
    ekleyen       integer      not null default 0,
    ekleme_tarihi timestamp    not null default now(),
    degistiren    integer      not null default 0,
    degistirme_tarihi timestamp
);
create index if not exists ix_dokuman_klasor_ust on public.dokuman_klasor(ust_id);

-- ---------------------------------------------------------- onay akisi -----
create table if not exists public.dokuman_akis (
    id            integer     primary key generated by default as identity,
    ad            varchar(80) not null,
    aktif         smallint    not null default 1,
    ekleyen       integer     not null default 0,
    ekleme_tarihi timestamp   not null default now(),
    degistiren    integer     not null default 0,
    degistirme_tarihi timestamp
);

create table if not exists public.dokuman_akis_adim (
    id            integer     primary key generated by default as identity,
    akis_id       integer     not null references public.dokuman_akis(id) on delete cascade,
    sira          smallint    not null default 1,
    ad            varchar(60) not null default '',
    rol_id        integer,
    kullanici_id  integer,
    -- Dinamik atama: 1 sahip · 2 klasor sorumlusu · 3 bolum sorumlusu
    dinamik       smallint    not null default 0,
    -- 1 inceleme (uygun/duzelt) · 2 onay (onay/ret)
    karar_turu    smallint    not null default 2,
    sure_gun      smallint    not null default 3,
    e_imza_zorunlu smallint   not null default 0,
    constraint ux_dokuman_akis_adim unique (akis_id, sira)
);

create table if not exists public.dokuman_onay (
    id            integer   primary key generated by default as identity,
    dokuman_id    integer   not null references public.dokuman(id) on delete cascade,
    surum_id      integer,
    akis_id       integer   not null,
    baslatan_id   integer   not null default 0,
    baslama       timestamp not null default now(),
    guncel_adim   smallint  not null default 1,
    -- 1 suruyor · 2 tamamlandi · 3 reddedildi · 4 geri cekildi
    durum         smallint  not null default 1,
    bitis         timestamp
);
create index if not exists ix_dokuman_onay_dokuman on public.dokuman_onay(dokuman_id);

create table if not exists public.dokuman_onay_adim (
    id            integer     primary key generated by default as identity,
    onay_id       integer     not null references public.dokuman_onay(id) on delete cascade,
    sira          smallint    not null default 1,
    ad            varchar(60) not null default '',
    atanan_rol_id integer,
    atanan_kullanici_id integer,
    -- 0 bekliyor · 1 uygun/onay · 2 duzelt/ret · 3 geri gonder
    karar         smallint    not null default 0,
    karar_veren_id integer,
    karar_zamani  timestamp,
    not_metni     varchar(400) not null default '',
    constraint ux_dokuman_onay_adim unique (onay_id, sira)
);

-- ---------------------------------------------------------------- surum ----
create table if not exists public.dokuman_surum (
    id            integer     primary key generated by default as identity,
    dokuman_id    integer     not null references public.dokuman(id) on delete cascade,
    surum_no      smallint    not null,
    hash          varchar(64) not null default '',
    content_type  varchar(100) not null default '',
    boyut         integer     not null default 0,
    degisiklik_notu varchar(400) not null default '',
    yukleyen_id   integer     not null default 0,
    yukleme       timestamp   not null default now(),
    -- 1 taslak · 2 onayda · 3 yayinda · 4 arsiv · 5 reddedildi
    durum         smallint    not null default 1,
    yayin_tarihi  timestamp,
    arsiv_tarihi  timestamp,
    onay_id       integer,
    constraint ux_dokuman_surum unique (dokuman_id, surum_no)
);
-- YAYINDA EN FAZLA BIR SURUM: iki yayin, "hangisi gecerli" sorusunu
--   cevapsiz birakir ve kalite denetiminde bulunan ilk hatadir.
create unique index if not exists ux_dokuman_surum_yayin
    on public.dokuman_surum(dokuman_id) where durum = 3;

-- --------------------------------------------------------------- gunluk ----
--  KVKK erisim kaydi: SILINMEZ. Ozel nitelikli dokumanda gerekce zorunlu.
create table if not exists public.dokuman_olay (
    id           bigint    primary key generated by default as identity,
    dokuman_id   integer   not null,
    surum_id     integer,
    zaman        timestamp not null default now(),
    kullanici_id integer,
    -- 1 yukleme · 2 goruntuleme · 3 indirme · 4 duzenleme · 5 yeni surum
    -- 6 onaya gonderme · 7 onay · 8 ret · 9 yayin · 10 arsiv · 11 paylasim
    -- 12 link acilma · 13 imha · 14 erisim reddi
    olay         smallint  not null,
    gerekce      varchar(200) not null default '',
    ip           varchar(45) not null default '',
    -- 1 uygulama · 2 portal · 3 link · 4 API
    kanal        smallint  not null default 1
);
create index if not exists ix_dokuman_olay_dokuman on public.dokuman_olay(dokuman_id, zaman desc);
create index if not exists ix_dokuman_olay_kullanici on public.dokuman_olay(kullanici_id, zaman desc);

