-- ------------------------------------------------------------- seed --------
insert into public.dokuman_akis (ad)
select 'İnceleme + Onay'
 where not exists (select 1 from public.dokuman_akis a where a.ad = 'İnceleme + Onay');

-- IKI ADIM: v1 kapsaminda "basit 2 adimli onay". Inceleme uygunluk bakar,
--   onay yayina izin verir; ikisini tek adima indirmek, yazani kendi isini
--   onaylayan tek kisi yapardi.
insert into public.dokuman_akis_adim (akis_id, sira, ad, karar_turu, dinamik, sure_gun)
select a.id, v.sira, v.ad, v.karar, v.dinamik, v.sure
  from public.dokuman_akis a,
       (values (1::smallint, 'İnceleme', 1::smallint, 2::smallint, 3::smallint),
               (2::smallint, 'Onay',     2::smallint, 0::smallint, 3::smallint))
         as v(sira, ad, karar, dinamik, sure)
 where a.ad = 'İnceleme + Onay'
   and not exists (select 1 from public.dokuman_akis_adim d
                    where d.akis_id = a.id and d.sira = v.sira);

insert into public.dokuman_turu (ad, kisaltma, surumlu, gizlilik, kaynaklar, sira, akis_id)
select v.ad, v.kis, v.surumlu, v.gizlilik, v.kaynaklar::varchar(20)[], v.sira,
       case when v.surumlu = 1
            then (select id from public.dokuman_akis where ad = 'İnceleme + Onay') end
  from (values
      ('Prosedür',        'PR', 1::smallint, 2::smallint, '{}',                10::smallint),
      ('Talimat',         'TL', 1::smallint, 2::smallint, '{}',                20::smallint),
      ('Sözleşme',        'SZ', 1::smallint, 3::smallint, '{taraf}',           30::smallint),
      ('İş Sözleşmesi',   'IS', 1::smallint, 4::smallint, '{taraf}',           40::smallint),
      ('Ürün Resmi',      'UR', 0::smallint, 1::smallint, '{stok}',            50::smallint),
      ('Tetkik Sonucu',   'TS', 0::smallint, 4::smallint, '{hasta,radyoloji-istem}', 60::smallint),
      ('e-Belge Şablonu', 'XS', 0::smallint, 2::smallint, '{ebelge-xslt}',     70::smallint),
      ('Diğer',           'DG', 0::smallint, 2::smallint, '{}',                90::smallint)
  ) as v(ad, kis, surumlu, gizlilik, kaynaklar, sira)
 where not exists (select 1 from public.dokuman_turu t where t.ad = v.ad);

insert into public.dokuman_klasor (ad, yol, sira)
select v.ad, v.ad, v.sira
  from (values ('Kurumsal', 10::smallint), ('Kalite', 20::smallint),
               ('İnsan Kaynakları', 30::smallint), ('Sözleşmeler', 40::smallint))
         as v(ad, sira)
 where not exists (select 1 from public.dokuman_klasor k where k.ad = v.ad);

-- ------------------------------------------------------------- gecis -------
--  Mevcut satirlar: serbest `belge_turu` metni -> katalog turu, surum 1
--  yayinda. Veri kaybi yok, eski kolon gorunum icin kalir.
update public.dokuman d
   set belge_turu_id = t.id,
       -- GIZLILIK IKI KAYNAKTAN, EN YUKSEGI GECERLI: kaynak (hasta/personel
       --   otomatik ozel nitelikli - KVKK sinifini kullaniciya sormak,
       --   unutuldugunda sizinti demekti) ve TUR (is sozlesmesi cari kartinda
       --   dursa bile ozel niteliklidir). Yalniz kaynaga bakmak, turun
       --   getirdigi ust siniri dusururdu.
       gizlilik = greatest(
           case when d.kaynak in ('hasta', 'personel') then 4
                when d.kaynak = 'taraf' then 3
                when d.kaynak = 'stok' then 1
                else 2 end,
           coalesce(t.gizlilik, 2)),
       surumlu = coalesce(t.surumlu, 0),
       akis_id = t.akis_id,
       surum_no = 1,
       durum = case when d.durum = 1 then 3 else d.durum end
  from (select dd.id as dokuman_id,
               coalesce(
                 (select x.id from public.dokuman_turu x
                   where lower(x.ad) = lower(nullif(btrim(dd.belge_turu), ''))),
                 (select x.id from public.dokuman_turu x
                   where x.ad = case when dd.kaynak = 'stok' then 'Ürün Resmi'
                                     when dd.kaynak = 'ebelge-xslt' then 'e-Belge Şablonu'
                                     when dd.kaynak in ('radyoloji-istem', 'hasta')
                                          then 'Tetkik Sonucu'
                                     else 'Diğer' end)) as tur_id
          from public.dokuman dd) as e
  join public.dokuman_turu t on t.id = e.tur_id
 where d.id = e.dokuman_id and d.belge_turu_id is null;

insert into public.dokuman_surum (dokuman_id, surum_no, hash, content_type, boyut,
                                  yukleyen_id, yukleme, durum, yayin_tarihi)
select d.id, 1, d.hash, d.content_type, d.boyut, d.ekleyen, d.ekleme_tarihi, 3, d.ekleme_tarihi
  from public.dokuman d
 where not exists (select 1 from public.dokuman_surum s where s.dokuman_id = d.id);

-- ------------------------------------------------------------- yetki -------
--  Dokuman YONETIMI icin ayri yetki: bugune kadar dokuman erisimi KAYNAK
--  KARTIN yetkisinden geliyordu (personeli goren dokumanini gorur) ve bu
--  kart galerisi icin dogru. Kurumsal klasorde kaynak YOK - prosedurun
--  sahibi bir kart degil; o yuzden kendi yetkisi gerekiyor.
insert into public.yetki (kod, ad, grup, tur, sira)
select v.kod, v.ad, 'Doküman', 0, v.sira
  from (values ('dokuman',        'Doküman yönetimi',        410::smallint),
               ('dokuman.onayla', 'Doküman onaylama',        411::smallint),
               ('dokuman.ozel_nitelikli',
                                  'Özel nitelikli doküman erişimi', 412::smallint))
         as v(kod, ad, sira)
 where not exists (select 1 from public.yetki y where y.kod = v.kod);

-- Yoneticiye tam yetki: yeni yetki hicbir role bagli olmadan gelirse ekran
--   herkese kapali acilir ve sebebi gorunmez.
insert into public.rol_yetki (rol_id, yetki_id, gor, ekle, degistir, sil)
select r.id, y.id, 1, 1, 1, 1
  from public.rol r, public.yetki y
 where r.ad in ('Yönetici', 'Yonetici')
   and y.kod in ('dokuman', 'dokuman.onayla', 'dokuman.ozel_nitelikli')
   and not exists (select 1 from public.rol_yetki x
                    where x.rol_id = r.id and x.yetki_id = y.id);
