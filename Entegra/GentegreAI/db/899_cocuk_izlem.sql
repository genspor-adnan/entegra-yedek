-- --------------------------------------------------------- persentil ----
--  LMS tablosu: kaynak (WHO / Bakanlık), cinsiyet, yaş ayı, ölçüt ve L/M/S.
--  BOŞ KURULUR - eğri verisi yüklenmeden persentil hesaplanmaz.
create table if not exists public.cocuk_buyume_lms (
  id       integer generated by default as identity primary key,
  kaynak   varchar(40) not null default 'WHO',
  -- 1 erkek · 2 kız (taraf_hasta.cinsiyet ile aynı kod uzayı)
  cinsiyet smallint    not null,
  -- 1 kilo (kg) · 2 boy (cm) · 3 baş çevresi (cm)
  olcut    smallint    not null,
  ay       smallint    not null,
  l        numeric(12,6) not null,
  m        numeric(12,6) not null,
  s        numeric(12,6) not null,
  constraint ck_cocuk_lms_olcut check (olcut in (1, 2, 3))
);

create unique index if not exists ux_cocuk_buyume_lms
  on public.cocuk_buyume_lms (kaynak, cinsiyet, olcut, ay);

comment on table public.cocuk_buyume_lms is
  '899: buyume egrisi LMS tablosu (WHO/Bakanlik). BOS KURULUR - egri verisi '
  'uydurulmaz; yuklenmeden persentil hesaplanmaz.';

/**
 * PERSENTİL (LMS yöntemi).
 *
 * z = ((X/M)^L − 1) / (L·S)   (L ≠ 0);  L = 0 ise z = ln(X/M) / S
 * persentil = Φ(z) · 100
 *
 * Normal dağılım kümülatifi için <c>erf</c> yaklaşımı kullanılır (Abramowitz
 * & Stegun 7.1.26) - PostgreSQL'de hazır Φ yok. Eğri satırı yoksa NULL
 * döner: "hesaplayamadım" ile "sıfırıncı persentil" farklı şeylerdir.
 */
create or replace function public.fn_cocuk_persentil(p_cinsiyet smallint,
                                                     p_olcut    smallint,
                                                     p_ay       integer,
                                                     p_deger    numeric,
                                                     p_kaynak   varchar default 'WHO')
returns numeric language plpgsql immutable as $fn$
declare
    r record;
    z double precision;
    x double precision;
    t double precision;
    y double precision;
begin
    if p_deger is null or p_deger <= 0 or p_ay is null then return null; end if;

    select l, m, s into r from public.cocuk_buyume_lms
     where kaynak = p_kaynak and cinsiyet = p_cinsiyet and olcut = p_olcut
       and ay = p_ay
     limit 1;
    if r.m is null then return null; end if;

    if r.l = 0 then
        z := ln(p_deger::double precision / r.m::double precision)
             / r.s::double precision;
    else
        z := (power(p_deger::double precision / r.m::double precision,
                    r.l::double precision) - 1)
             / (r.l::double precision * r.s::double precision);
    end if;

    -- Φ(z): erf yaklaşımı. Hata payı ~1e-7 - persentil için fazlasıyla yeterli.
    x := abs(z) / sqrt(2);
    t := 1 / (1 + 0.3275911 * x);
    y := 1 - (((((1.061405429 * t - 1.453152027) * t) + 1.421413741) * t
              - 0.284496736) * t + 0.254829592) * t * exp(-x * x);
    if z < 0 then y := -y; end if;

    return round((0.5 * (1 + y) * 100)::numeric, 1);
end $fn$;

comment on function public.fn_cocuk_persentil(smallint, smallint, integer, numeric, varchar) is
  '899: LMS persentili. Egri satiri yoksa NULL doner - "hesaplayamadim" ile '
  '"sifirinci persentil" farkli seylerdir.';

-- -------------------------------------------------------------- döküm ----
create or replace view public.v_cocuk_izlem as
select i.id, i.taraf_id, i.belge_id, i.muayene_id,
       coalesce(nullif(trim(h.ad || ' ' || h.soyad), ''), h.unvan) as cocuk,
       hh.dogum_tarihi, hh.cinsiyet,
       -- YAŞ AYI izlem tarihine göre: persentil eğrisi aya bakar.
       case when hh.dogum_tarihi is null then null
            else (extract(year from age(i.izlem_tarihi::date, hh.dogum_tarihi::date)) * 12
                  + extract(month from age(i.izlem_tarihi::date, hh.dogum_tarihi::date)))::int
       end as yas_ay,
       i.kacinci_izlem, i.islem_turu, i.izlem_tarihi,
       i.boy_cm, i.kilo_kg, i.bas_cevresi_cm, i.dogum_agirligi_g,
       i.hemoglobin, i.hematokrit,
       i.beslenme, i.d_vitamini, i.demir, i.gkd, i.gorme, i.dkh,
       i.dkh_yapilmama, i.ntp, i.oneri, i.aciklama,
       i.durum, i.iptal_neden, i.enabiz_durum, i.sube_id,
       public.fn_cocuk_persentil(hh.cinsiyet, 1::smallint,
            case when hh.dogum_tarihi is null then null
                 else (extract(year from age(i.izlem_tarihi::date, hh.dogum_tarihi::date)) * 12
                       + extract(month from age(i.izlem_tarihi::date, hh.dogum_tarihi::date)))::int
            end, i.kilo_kg) as kilo_persentil,
       public.fn_cocuk_persentil(hh.cinsiyet, 2::smallint,
            case when hh.dogum_tarihi is null then null
                 else (extract(year from age(i.izlem_tarihi::date, hh.dogum_tarihi::date)) * 12
                       + extract(month from age(i.izlem_tarihi::date, hh.dogum_tarihi::date)))::int
            end, i.boy_cm) as boy_persentil,
       public.fn_cocuk_persentil(hh.cinsiyet, 3::smallint,
            case when hh.dogum_tarihi is null then null
                 else (extract(year from age(i.izlem_tarihi::date, hh.dogum_tarihi::date)) * 12
                       + extract(month from age(i.izlem_tarihi::date, hh.dogum_tarihi::date)))::int
            end, i.bas_cevresi_cm) as bas_persentil
  from public.cocuk_izlem i
  left join public.taraf h on h.id = i.taraf_id
  left join public.taraf_hasta hh on hh.id = i.taraf_id;

comment on view public.v_cocuk_izlem is
  '899: cocuk izlemleri - olcumler, yas ayi ve (egri verisi varsa) persentiller.';

