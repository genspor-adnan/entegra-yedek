-- ------------------------------------------------------------- izlem ----
create table if not exists public.cocuk_izlem (
  id            integer generated by default as identity primary key,
  taraf_id      integer not null references public.taraf(id),
  belge_id      integer references public.belge(id),
  muayene_id    integer,
  -- SKRS "kaçıncı izlem" kodu (paket zorunlu ögesi). Ayrıca yaş ayı
  --   hesaplanır ve persentilde kullanılır.
  kacinci_izlem smallint     not null,
  islem_turu    smallint,
  izlem_tarihi  timestamptz  not null default now(),
  -- ÖLÇÜMLER EKRANDAKİ BİRİMLERLE: boy cm, kilo KG, baş çevresi cm.
  --   Pakette kilo grama çevrilir (tek yerde).
  boy_cm        numeric(6,2),
  kilo_kg       numeric(6,3),
  bas_cevresi_cm numeric(6,2),
  dogum_agirligi_g integer,
  hemoglobin    numeric(6,2),
  hematokrit    numeric(6,2),
  beslenme      smallint,
  d_vitamini    smallint,
  demir         smallint,
  gkd           smallint,
  gorme         smallint,
  dkh           smallint,
  dkh_yapilmama smallint,
  ntp           smallint,
  oneri         varchar(400) not null default '',
  aciklama      varchar(400) not null default '',
  durum         smallint     not null default 1,   -- 1 geçerli · 0 iptal
  iptal_neden   varchar(200) not null default '',
  enabiz_durum  smallint     not null default 0,
  sube_id       integer      not null default 0,
  ekleyen       integer      not null default 0,
  ekleme_tarihi timestamptz  not null default now(),
  degistiren    integer      not null default 0,
  degistirme_tarihi timestamptz,
