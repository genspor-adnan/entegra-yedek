--  Kullanıcı: "bana gelenleri duyuru (zil)'e aktar.. bir de duyuru girişi /
--  yayınlama için mockup yap" → "mockup uygun, uygula"
--  (Ekranlar/Duyuru/duyuru.html).
--
--  duyuru          başlık, metin (sınırlı HTML - sunucuda temizlenir), önem
--                  (1 bilgi · 2 önemli · 3 kritik), yayın aralığı, okuma onayı,
--                  sabit, e-posta / SMS, sürüm (yayındayken düzenlenince +1).
--  duyuru_hedef    kime: 1 şube · 2 bölüm · 3 rol · 4 kişi (BİRLEŞİM);
--                  `herkes` = 1 ise hedef satırı yok sayılır.
--  duyuru_okuma    kim gördü / kim "okudum" dedi, hangi sürümü.
--
--  YETKİ: `duyuru` (yönetim listesi + yayınlama), `duyuru.genel` (herkese ve
--  SMS). Okumak yetki istemez - hedefteki herkes görür.
--  Yalnız dev docker'a uygulanır.
-- ============================================================================

create table if not exists public.duyuru (
    id              integer      primary key generated by default as identity,
    baslik          varchar(200) not null,
    metin           text         not null default '',
    onem            smallint     not null default 1,
    herkes          smallint     not null default 0,
    yayin_bas       timestamptz,
    yayin_bit       timestamptz,
    okuma_onayi     smallint     not null default 0,
    sabit           smallint     not null default 0,
    yorum_acik      smallint     not null default 0,
    eposta          smallint     not null default 0,
    sms             smallint     not null default 0,
    -- 0 taslak · 1 yayın (zamanı gelince görünür) · 9 yayından kaldırıldı
    durum           smallint     not null default 0,
    surum           smallint     not null default 1,
    guncelleme      timestamptz,
    gonderim        timestamptz,
    yayinlayan      integer      not null default 0,
    adina           varchar(120) not null default '',
    sube_id         integer,
    ekleyen         integer      not null default 0,
    ekleme_tarihi   timestamptz  not null default now(),
    degistiren      integer      not null default 0,
    degistirme_tarihi timestamptz,
    constraint ck_duyuru_onem check (onem in (1, 2, 3)),
    constraint ck_duyuru_durum check (durum in (0, 1, 9)),
    constraint ck_duyuru_aralik check (yayin_bit is null or yayin_bas is null or yayin_bit > yayin_bas),
    constraint ck_duyuru_sms check (sms = 0 or onem = 3)
);
create index if not exists ix_duyuru_yayin on public.duyuru (durum, yayin_bas, yayin_bit);

create table if not exists public.duyuru_hedef (
    duyuru_id integer  not null references public.duyuru (id) on delete cascade,
    tur       smallint not null,
    hedef_id  integer  not null,
    primary key (duyuru_id, tur, hedef_id),
    constraint ck_duyuru_hedef_tur check (tur in (1, 2, 3, 4))
);

create table if not exists public.duyuru_okuma (
    duyuru_id    integer     not null references public.duyuru (id) on delete cascade,
    kullanici_id integer     not null,
    gordu        timestamptz,
    gordu_surum  smallint    not null default 0,
    okudu        timestamptz,
    okudu_surum  smallint    not null default 0,
    primary key (duyuru_id, kullanici_id)
);
create index if not exists ix_duyuru_okuma_kullanici on public.duyuru_okuma (kullanici_id);

-- ------------------------------------------------------ kullanıcının bölümleri
--  Görevdeki personel hareketinin bölümü + aktif çalışma şablonu bölümleri.
create or replace function public.fn_kullanici_bolumleri(p_kullanici integer)
returns setof integer language sql stable as $fn$
    select h.departman_id from public.personel_hareket h
     where h.taraf_id = p_kullanici and h.departman_id is not null
       and h.yururluk <= current_date and (h.bitis is null or h.bitis >= current_date)
    union
    select s.departman_id from public.hekim_calisma_sablon s
     where s.hekim_id = p_kullanici and s.aktif = 1 and s.departman_id is not null
$fn$;

-- ------------------------------------------------------ kim görür
create or replace function public.fn_duyuru_gorur(p_duyuru integer, p_kullanici integer)
returns boolean language sql stable as $fn$
    select exists (
        select 1 from public.duyuru d
         where d.id = p_duyuru
           and (d.herkes = 1
                or d.yayinlayan = p_kullanici
                or exists (select 1 from public.duyuru_hedef h where h.duyuru_id = d.id and (
                       (h.tur = 4 and h.hedef_id = p_kullanici)
                    or (h.tur = 3 and (h.hedef_id = (select k.rol_id from public.taraf_kullanici k where k.id = p_kullanici)
                                       or h.hedef_id in (select kr.rol_id from public.kullanici_rol kr where kr.kullanici_id = p_kullanici)))
                    or (h.tur = 1 and h.hedef_id in (select ks.sube_id from public.kullanici_sube ks where ks.taraf_id = p_kullanici))
                    or (h.tur = 2 and h.hedef_id in (select public.fn_kullanici_bolumleri(p_kullanici)))))))
$fn$;

-- ------------------------------------------------------ alıcı listesi
create or replace function public.fn_duyuru_alicilari(p_duyuru integer)
returns setof integer language sql stable as $fn$
    select k.id from public.taraf_kullanici k
     where k.aktif = 1 and coalesce(k.portal_taraf_id, 0) = 0
       and public.fn_duyuru_gorur(p_duyuru, k.id)
$fn$;

-- ------------------------------------------------------ yetki
insert into public.yetki (kod, ad, grup, tur, sira, aktif, urun_modu, modul)
select v.kod, v.ad, 'Yönetim', 0, v.sira, 1, 0, ''
  from (values ('duyuru', 'Duyurular (yayınla / yönet)', 90),
               ('duyuru.genel', 'Duyuru: herkese ve SMS ile', 91)) v(kod, ad, sira)
 where not exists (select 1 from public.yetki y where y.kod = v.kod);

insert into public.rol_yetki (rol_id, yetki_id, gor, ekle, degistir, sil, ekleyen)
select r.id, y.id, 1, 1, 1, 1, 0
  from public.rol r cross join public.yetki y
 where r.kod = 'yonetici' and y.kod in ('duyuru', 'duyuru.genel')
   and not exists (select 1 from public.rol_yetki x where x.rol_id = r.id and x.yetki_id = y.id);
update public.rol set yetki_surumu = yetki_surumu + 1;

-- ------------------------------------------------------ bildirim şablonları
insert into public.bildirim_sablon (kod, ad, kanal, konu, govde, degiskenler, durum, aciklama, ekleyen)
select v.kod, v.ad, v.kanal, v.konu, v.govde, v.degiskenler::json, 1, v.aciklama, 0 from (values
    ('duyuru.sms', 'Duyuru: kritik (SMS)', 1, '',
     '{{adina}}: {{baslik}} - ayrıntı GenoTIP AI zilinde.',
     '{"adina":"Yayınlayan","baslik":"Başlık"}', 'Kritik duyuru SMS ile'),
    ('duyuru.eposta', 'Duyuru (e-posta)', 2, '{{adina}} duyurusu: {{baslik}}',
     E'Sayın {{alici}},\n\n{{baslik}}\n\n{{metin}}\n\n{{adina}}',
     '{"alici":"Alıcı","adina":"Yayınlayan","baslik":"Başlık","metin":"Metin (düz)"}', 'Duyuru e-posta ile')
) as v(kod, ad, kanal, konu, govde, degiskenler, aciklama)
where not exists (select 1 from public.bildirim_sablon s where s.kod = v.kod);

