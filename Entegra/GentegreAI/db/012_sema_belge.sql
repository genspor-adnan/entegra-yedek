--        yazili (281 belgenin 229'unda kart unvanindan farkli; bir kismi ise
--        gelen e-faturadan gelen gercek tedarikci bilgisi).
--      Bu yuzden goc alanlari OLDUGU GIBI tasir, yorumlamaz; taraf.fatura_unvan
--      onerisi ise YALNIZ satis belgelerinden uretilir.
