\set ON_ERROR_STOP on

-- ----------------------------------------------------------------- belge ----
create table if not exists public.belge (
    id                     integer generated by default as identity primary key,
    tur                    smallint     not null,               -- islem turu (satis fat., alis irs., ...)
    tipi                   smallint     not null default 0,     -- 0 normal, 2 iade ...
    -- taraf: bag + belge anindaki snapshot
    taraf_id               integer,
    taraf_adres_id         integer,
    taraf_unvan            varchar(200) not null default '',
    taraf_vkno         varchar(20)  not null default '',
    taraf_vd    varchar(60)  not null default '',
    taraf_adres            varchar(300) not null default '',
    taraf_ilce             varchar(60)  not null default '',
    taraf_il               varchar(60)  not null default '',
    -- belge kimligi
    belge_seri             varchar(5)   not null default '',
    belge_no               varchar(20)  not null default '',
    kocan_no               integer      not null default 0,
    belge_tarihi           timestamp    not null,
    kayit_tarihi           timestamp    not null default now()::timestamp,
    irsaliye_no            varchar(50)  not null default '',
    irsaliye_tarihi        timestamp,
    -- depo / sube / proje
    giris_depo_id          integer,
    cikis_depo_id          integer,
    sube_id                smallint     not null default 0,
    merkez_id              integer      not null default 0,
    proje_id               integer,
    servis_id              integer,
    aktivite_id            integer,
    -- tutarlar (hepsi belge dovizinde degil, TL karsiligi ile birlikte saklanir)
    matrah                 numeric(19,4) not null default 0,
    kdv_tutari             numeric(19,4) not null default 0,
    ek_vergi               numeric(19,4) not null default 0,
    genel_toplam           numeric(19,4) not null default 0,
    stok_iskonto           numeric(9,4)  not null default 0,
    kdv_durum              varchar(5)   not null default '',
    -- doviz
    belge_dovizi           varchar(5)   not null default '',
    doviz_cinsi            varchar(6)   not null default '',
    doviz_tutari           numeric(19,4) not null default 0,
    doviz_kuru             numeric(19,6) not null default 0,   -- belge anindaki kur DEGERI
    rapor_dovizi           varchar(5)   not null default '',
    kur                    varchar(5)   not null default '',
    -- odeme / durum
    vade_gun               smallint     not null default 0,
    acik_kapali            smallint     not null default 0,
    durum                  smallint     not null default 0,
    fiyat_listesi          smallint     not null default 0,
    masraf_id              integer,                              -- belge geneli masraf dagitimi
    satici_id              integer      not null default 0,
    ekstrede_kullan        smallint     not null default 1,
    -- e-Belge
    efatura_durum          smallint     not null default 0,
    efatura_sonuc          smallint     not null default 0,
    senaryo                smallint     not null default 0,
    zarf_id                integer      not null default 0,
    yazdirildi             smallint     not null default 0,
    -- donusum zinciri (kaynak belge/satir bagi)
    kaynak_tur             smallint     not null default 0,    -- eski YERI
    kaynak_id              integer      not null default 0,    -- eski YERID
    ana_kayit_id           integer      not null default 0,
    -- diger
    aciklama               varchar(300) not null default '',
    ozel_kod               varchar(20)  not null default '',
    ozel_kod2              varchar(20)  not null default '',
    detay_bolumu           varchar(20)  not null default '',
    dil                    smallint     not null default 0,
    sayfa                  smallint     not null default 0,
    sayfa_sayisi           smallint     not null default 0,
    maliyet_ort            numeric(19,4) not null default 0,
    giris_kaynak           smallint     not null default 0,
    -- kayit izleri
    ekleyen                integer      not null default 0,
    ekleme_tarihi          timestamp    not null default now()::timestamp,
    degistiren             integer      not null default 0,
    degistirme_tarihi      timestamp,
    constraint fk_belge_taraf       foreign key (taraf_id)       references public.taraf (id),
    constraint fk_belge_masraf      foreign key (masraf_id)      references public.masraf (id),
    constraint fk_belge_taraf_adres foreign key (taraf_adres_id) references public.taraf_adres (id),
    constraint fk_belge_giris_depo  foreign key (giris_depo_id)  references public.depo (id),
    constraint fk_belge_cikis_depo  foreign key (cikis_depo_id)  references public.depo (id)
);

-- Belge numarasi: TEKIL INDEKS KONULMADI. Gerekce olculdu - mevcut veride ayni
--   (tur, seri, no) uclusu tekrar ediyor (or. tur=11 no='000001' uc kayit;
--   tur=15 no='2025000000704' iki kayit) ve 99 belgede numara '0'. Tekillik yeni
--   kayitlarda belge_no_sayac + uygulama kontrolu ile saglanir; gecmis veriyi
--   reddeden bir kisit gocu imkansiz kilardi.
create index if not exists ix_belge_no
    on public.belge (tur, belge_seri, belge_no) where belge_no <> '';
create index if not exists ix_belge_taraf   on public.belge (taraf_id, belge_tarihi desc);
create index if not exists ix_belge_tarih   on public.belge (belge_tarihi desc);
create index if not exists ix_belge_tur     on public.belge (tur, durum);
create index if not exists ix_belge_kaynak  on public.belge (kaynak_tur, kaynak_id) where kaynak_id > 0;

comment on table  public.belge                is 'Belge basligi (eski FATBASLIK): fatura, irsaliye, fis, konsinye, transfer, uretim fisi.';
comment on column public.belge.taraf_adres_id is 'Secilen adres. FK RESTRICT: bir belgede kullanilan adres SILINEMEZ; kart ekraninda pasife alinir (taraf_adres.aktif=0).';
comment on column public.belge.taraf_unvan    is 'Belge anindaki unvan. taraf.fatura_unvan bos ise taraf.unvan kopyalanir; kullanici belge uzerinde degistirebilir.';
comment on column public.belge.doviz_kuru     is 'Belge anindaki kur DEGERI. doviz_kur tablosu sonradan degisse de belge etkilenmez.';

-- ------------------------------------------------------------ belge_satir ----
create table if not exists public.belge_satir (
    id                     integer generated by default as identity primary key,
    belge_id               integer      not null,
    sira                   integer      not null default 0,
    tur                    smallint     not null default 1,    -- 1 stok, 2 hizmet, 3 masraf
    stok_id                integer,
    hizmet_id              integer,                              -- satilan hizmet kalemi
    masraf_id              integer,                              -- gider kalemi
    aciklama               text         not null default '',
    -- miktar / fiyat
    miktar                 numeric(24,6) not null default 0,
    adet                   numeric(24,6) not null default 0,   -- ana birime cevrilmis miktar
    birim                  smallint     not null default 0,
    birim_fiyat            numeric(24,6) not null default 0,
    iskonto                numeric(9,4)  not null default 0,
    iskontolu_birim_fiyat  numeric(24,6) not null default 0,
    kdv                    smallint     not null default 0,
    kdv_dahil_birim_fiyat  numeric(24,6) not null default 0,
    otv_yuzde              smallint     not null default 0,
    tutar                  numeric(24,2) not null default 0,
    ek_maliyet             numeric(19,4) not null default 0,
    -- doviz
    doviz_cinsi            varchar(5)   not null default '',
    doviz_birim_fiyat      numeric(24,6) not null default 0,
    doviz_tutari           numeric(24,2) not null default 0,
    doviz_kuru             numeric(19,6) not null default 0,
    -- depo / izleme
    giris_depo_id          integer,
    cikis_depo_id          integer,
    izleme                 smallint     not null default 0,
    izleme_kodu            varchar(40)  not null default '',
    stok_durum_degis       smallint     not null default 1,    -- 0 ise stok durumunu etkilemez
    ekipman_id             integer      not null default 0,
    -- donusum zinciri (kaynak satir bagi)
    kaynak_tur             integer      not null default 0,    -- eski YERI
    kaynak_id              integer      not null default 0,    -- eski YERID
    -- diger
    proje_id               integer,
    taraf_id               integer,                            -- satir bazli cari (masraf dagitimi)
    satici_id              integer      not null default 0,
    vade_gun               smallint     not null default 0,
    ozel_kod               varchar(20)  not null default '',
    ozel_kod2              varchar(20)  not null default '',
    muh_kodu               varchar(25)  not null default '',
    sube_id                smallint     not null default 0,
    merkez_id              integer      not null default 0,
    giris_kaynak           smallint     not null default 0,
    -- kayit izleri
    ekleyen                integer      not null default 0,
    ekleme_tarihi          timestamp    not null default now()::timestamp,
    degistiren             integer      not null default 0,
    degistirme_tarihi      timestamp,
    constraint fk_belge_satir_belge      foreign key (belge_id)      references public.belge (id) on delete cascade,
    constraint fk_belge_satir_stok       foreign key (stok_id)       references public.stok (id),
    constraint fk_belge_satir_hizmet     foreign key (hizmet_id)     references public.hizmet (id),
    constraint fk_belge_satir_masraf     foreign key (masraf_id)     references public.masraf (id),
    -- Satir ya stok, ya hizmet, ya masraf: en fazla BIRI dolu olabilir.
    constraint ck_belge_satir_urun check (
        (case when stok_id   is not null then 1 else 0 end) +
        (case when hizmet_id is not null then 1 else 0 end) +
        (case when masraf_id is not null then 1 else 0 end) <= 1),
    constraint fk_belge_satir_giris_depo foreign key (giris_depo_id) references public.depo (id),
    constraint fk_belge_satir_cikis_depo foreign key (cikis_depo_id) references public.depo (id)
);

create index if not exists ix_belge_satir_belge  on public.belge_satir (belge_id, sira);
create index if not exists ix_belge_satir_stok   on public.belge_satir (stok_id)  where stok_id is not null;
create index if not exists ix_belge_satir_hizmet on public.belge_satir (hizmet_id) where hizmet_id is not null;
create index if not exists ix_belge_satir_masraf on public.belge_satir (masraf_id) where masraf_id is not null;
create index if not exists ix_belge_satir_kaynak on public.belge_satir (kaynak_tur, kaynak_id) where kaynak_id > 0;

comment on table public.belge_satir is
  'Belge satirlari (eski FATURA - ad yaniltici oldugu icin degistirildi).';

-- ---------------------------------------------------------- mali_hareket ----
-- Cari + kasa + banka + POS + kredi karti hareketlerinin TAMAMI (eski KASA).
--   hesap_turu: K kasa, B banka, P POS, V kredi karti, C cari  (kaynak koda gore)
create table if not exists public.mali_hareket (
    id                     integer generated by default as identity primary key,
    tur                    smallint     not null default 0,
    hesap_turu             varchar(1)   not null default '',
    hesap_id               integer      not null default 0,
    taraf_id               integer,
    belge_id               integer,
    belge_no               varchar(30)  not null default '',
    islem_tarihi           timestamp    not null,
    plan_tarihi            timestamp,
    borc                   numeric(19,4) not null default 0,
    alacak                 numeric(19,4) not null default 0,
    doviz_cinsi            varchar(6)   not null default '',
    doviz_tutari           numeric(19,4) not null default 0,
    doviz_kuru             numeric(19,6) not null default 0,
    kur                    varchar(6)   not null default '',
    durum                  smallint     not null default 0,
    kasa_id                integer      not null default 0,
    masraf_id              integer,                              -- gider kalemi (eski MASRAFID)
    hizmet_id              integer,                              -- gelir/hizmet kalemi
    ceksenet_id            integer      not null default 0,
    geridonus_id           integer      not null default 0,
    kredi_id               integer      not null default 0,
    aciklama               varchar(100) not null default '',
    kaynak_tur             integer      not null default 0,   -- eski YERI
    kaynak_id              bigint       not null default 0,   -- eski YERID
    ekstrede_kullan        smallint     not null default 1,
    sube_id                smallint     not null default 0,
    merkez_id              integer      not null default 0,
    giris_kaynak           smallint     not null default 0,
    ekleyen                integer      not null default 0,
    ekleme_tarihi          timestamp    not null default now()::timestamp,
    degistiren             integer      not null default 0,
    degistirme_tarihi      timestamp,
    constraint fk_mali_hareket_taraf foreign key (taraf_id) references public.taraf (id),
    constraint fk_mali_hareket_masraf foreign key (masraf_id) references public.masraf (id),
    constraint fk_mali_hareket_hizmet foreign key (hizmet_id) references public.hizmet (id),
    constraint ck_mali_hareket_kalem check (masraf_id is null or hizmet_id is null),
    constraint fk_mali_hareket_belge foreign key (belge_id) references public.belge (id)
);

create index if not exists ix_mali_hareket_taraf on public.mali_hareket (taraf_id, islem_tarihi)
    where taraf_id is not null;
create index if not exists ix_mali_hareket_belge on public.mali_hareket (belge_id)
    where belge_id is not null;
create index if not exists ix_mali_hareket_hesap on public.mali_hareket (hesap_turu, hesap_id, islem_tarihi);

comment on table public.mali_hareket is
  'Cari, kasa, banka, POS ve kredi karti hareketleri (eski KASA). hesap_turu ile ayrisir; cari ekstresi taraf_id uzerinden okunur.';

