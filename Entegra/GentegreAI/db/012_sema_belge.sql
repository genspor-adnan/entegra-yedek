--    26'si, FATURA'nin 65 kolonundan 16'si bu veritabaninda tamamen bos ve
--    Faz 2'de degerlendirilecek (lot_no, kdv_muafiyeti, odeme_plani, onaylayan,
--    irsaliye_tipi, iade_fatura_id, kampanya_id, uretim_plan_id ...).
--
