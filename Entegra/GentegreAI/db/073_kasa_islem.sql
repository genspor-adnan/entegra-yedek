-- ----------------------------------------------------- islem no ureteci ----
-- fn_belge_no_uret (025) ile AYNI desen: sayac satiri "for update" ile kilitlenir,
--   BOSLUKSUZ artar. Cagiran ZATEN transaction icinde olmali; numara en son alinir
--   ki rollback numarayi bosluga dusurmesin.
create or replace function public.fn_kasa_islem_no_uret(
    p_tur     integer,
    p_sube_id integer,
    p_yil     integer,
    p_hane    integer default 8
) returns text
language plpgsql
as $$
declare
    v_seri    text;
    v_anahtar text;
    v_no      bigint;
begin
    select coalesce(nullif(btrim(t.makbuz_seri), ''), 'K') into v_seri
      from public.kasa_islem_turu t where t.kod = p_tur;

    v_anahtar := 'kasa_islem.islem_no|S' || coalesce(v_seri, 'K')
              || '|SUBE' || coalesce(p_sube_id, 0) || '|Y' || p_yil;

    insert into public.belge_no_sayac (anahtar, tablo_adi, alan_adi, kapsam, son_no)
    values (v_anahtar, 'kasa_islem', 'islem_no',
            'seri ' || coalesce(v_seri, 'K') || ' / sube ' || coalesce(p_sube_id, 0) || ' / ' || p_yil, 0)
    on conflict (anahtar) do nothing;

    select son_no into v_no from public.belge_no_sayac where anahtar = v_anahtar for update;
    v_no := coalesce(v_no, 0) + 1;
    update public.belge_no_sayac set son_no = v_no, guncelleme = now()::timestamp where anahtar = v_anahtar;

    return coalesce(v_seri, 'K') || lpad(v_no::text, p_hane, '0');
end $$;

comment on function public.fn_kasa_islem_no_uret(integer, integer, integer, integer) is
  'Makbuz/islem numarasi ureteci. Seri kasa_islem_turu.makbuz_seri, kapsam sube+yil. Bosluksuz (for update) - fn_belge_no_uret ile ayni desen.';

