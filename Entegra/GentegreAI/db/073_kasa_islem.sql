-- ------------------------------------------------------- kasa_islem_turu ----
create table if not exists public.kasa_islem_turu (
    kod                  smallint     primary key,      -- legacy TUR kodu korunur
    ad                   varchar(100) not null,
    grup                 varchar(12)  not null,         -- belge|tahsilat|odeme|virman|doviz|ceksenet|kredi|plan|acilis|kurfarki|kupon
    yon                  smallint     not null default 0,  -- +1 para girisi, -1 cikis, 0 notr (virman)
    ana_hesap_turu       varchar(1)   not null default '', -- baslik hesap_id'sinin beklenen turu
    karsi_hesap_turu     varchar(1)   not null default '',
    cari_zorunlu         smallint     not null default 0,  -- 1 zorunlu, 0 opsiyonel, -1 yasak
    kalem_turu           smallint     not null default 0,  -- 0 yok, 1 masraf, 2 hizmet, 3 ikisi de olabilir
    plan_mi              smallint     not null default 0,
    cari_ekstre          smallint     not null default 1,
    hesap_ekstre         smallint     not null default 1,
    bakiye_dahil         smallint     not null default 1,  -- 0: plan - yuruyen bakiyeye girmez
    fis_mi               smallint     not null default 1,
    fis_turu             smallint     not null default 1,  -- 1 mahsup, 2 tahsil, 3 tediye
    sablon               jsonb        not null default '[]'::jsonb,
    makbuz_basligi       varchar(40)  not null default '',
    makbuz_seri          varchar(6)   not null default 'K',
    sira                 smallint     not null default 0,
    aktif                smallint     not null default 1
);

