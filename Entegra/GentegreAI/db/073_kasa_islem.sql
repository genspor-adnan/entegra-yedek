    karsi_tutar          numeric(19,4) not null default 0,
    karsi_kur            numeric(19,6) not null default 0,
    -- ek bacak (banka masrafi / POS komisyonu / kredi faizi)
    masraf_tutar         numeric(19,4) not null default 0,
    -- boyutlar
    masraf_id            integer,
    hizmet_id            integer,
    proje_id             integer,
    merkez_id            integer,
    cek_senet_id         integer,
    kredi_taksit_id      integer,
    kupon_turu_id        integer,
    belge_id             integer,
    -- plan / iptal baglari
    plan_islem_id        integer,                           -- gerceklesen -> plani
    gerceklesen_tutar    numeric(19,4) not null default 0,  -- planda birikir
    iptal_islem_id       integer,                           -- ters kayit bagi
