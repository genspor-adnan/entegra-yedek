-- ------------------- mali_hareket.tur -> katalog FK (seed'den SONRA) -------
-- Once eksik tur var mi diye bakilir; varsa FK kurulmaz ve uyari verilir
--   (sessizce yarim kalmis sema birakmamak icin acikca raise edilir).
do $$
declare v_eksik text;
begin
    select string_agg(distinct m.tur::text, ', ') into v_eksik
      from public.mali_hareket m
     where not exists (select 1 from public.kasa_islem_turu t where t.kod = m.tur);

    if v_eksik is not null then
        raise exception '073: mali_hareket icinde katalogda olmayan tur kodlari var: %', v_eksik;
    end if;
end $$;

alter table public.mali_hareket drop constraint if exists fk_mali_hareket_tur;
alter table public.mali_hareket add  constraint fk_mali_hareket_tur
      foreign key (tur) references public.kasa_islem_turu (kod);

-- ------------------------------------------------------------- dogrulama ----
do $$
declare v_tur integer; v_kolon integer;
begin
    select count(*) into v_tur from public.kasa_islem_turu;
    select count(*) into v_kolon from information_schema.columns
     where table_name = 'mali_hareket'
       and column_name in ('kasa_islem_id','sira','proje_id','yerel_borc','yerel_alacak','cek_senet_id');
    raise notice '073 tamam: % islem turu seed edildi, mali_hareket % / 6 yeni kolon', v_tur, v_kolon;
end $$;
