    plan_tarihi          date,
    durum                smallint     not null default 0,   -- 0 taslak, 1 planli, 2 gerceklesti, 3 iptal, 4 plan kapandi
    -- taraflar
    taraf_id             integer,
    karsi_taraf_id       integer,                           -- cari virman (49) hedefi
    taraf_unvan          varchar(200) not null default '',  -- SNAPSHOT (belge deseni)
    -- hesaplar
    hesap_id             integer,
    karsi_hesap_id       integer,
    -- tutarlar (islem dovizinde + TL karsiligi)
    doviz_cinsi          varchar(6)   not null default 'TL',
    tutar                numeric(19,4) not null default 0,
    doviz_kuru           numeric(19,6) not null default 1,
    yerel_tutar          numeric(19,4) not null default 0,
