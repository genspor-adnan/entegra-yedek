    kaynak_id            bigint       not null default 0,
    aciklama             varchar(200) not null default '',
    sube_id              integer      not null default 0,
    giris_kaynak         smallint     not null default 1,
    ekleyen              integer      not null default 0,
    ekleme_tarihi        timestamp    not null default now()::timestamp,
    degistiren           integer      not null default 0,
    degistirme_tarihi    timestamp,
    constraint ck_kasa_islem_kur   check (doviz_kuru > 0),
    constraint ck_kasa_islem_kalem check (masraf_id is null or hizmet_id is null),
    constraint ck_kasa_islem_durum check (durum in (0,1,2,3,4)),
    constraint fk_kasa_islem_tur         foreign key (tur)             references public.kasa_islem_turu (kod),
    constraint fk_kasa_islem_taraf       foreign key (taraf_id)        references public.taraf (id),
    constraint fk_kasa_islem_karsi_taraf foreign key (karsi_taraf_id)  references public.taraf (id),
    constraint fk_kasa_islem_hesap       foreign key (hesap_id)        references public.hesap (id),
    constraint fk_kasa_islem_karsi_hesap foreign key (karsi_hesap_id)  references public.hesap (id),
    constraint fk_kasa_islem_masraf      foreign key (masraf_id)       references public.masraf (id),
    constraint fk_kasa_islem_hizmet      foreign key (hizmet_id)       references public.hizmet (id),
    constraint fk_kasa_islem_proje       foreign key (proje_id)        references public.proje (id),
    constraint fk_kasa_islem_merkez      foreign key (merkez_id)       references public.masraf_merkezi (id),
