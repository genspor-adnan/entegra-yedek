-- ------------------------------------------------------------- kasa_islem ----
create table if not exists public.kasa_islem (
    id                   integer generated by default as identity primary key,
    tur                  smallint     not null,
    islem_no             varchar(30)  not null default '',  -- makbuz/fis no - kesinlestirmede EN SON uretilir
