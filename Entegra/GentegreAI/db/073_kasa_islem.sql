--                         mali_hareket ALTER, fn_kasa_islem_no_uret
--
--  KARAR (model): BASLIK + BACAK. Bir mali islem tek bir kasa_islem satiri ve
--    ona bagli 2+ mali_hareket "bacagi"dir. Legacy'de transfer 2 ayri KASA
--    satiriydi ve birbirine GERIDONUSID ile baglaniyordu; kredi odemesi 4
--    satirlik bir HALKA idi. Artik bag tek yonlu ve acik: kasa_islem_id.
--
--  KARAR K5: durum=2 (gerceklesti) olan her baslikta
--    sum(yerel_borc) = sum(yerel_alacak)  --  tek kural tum turleri dogrular
--    ve muhasebe fisi otomatik dengeli cikar.
--
--  KARAR (TUR kod uzayi VERIDE): legacy'de TUR sabitleri Pascal kodunda
--    (Utablo.pas) ve GENINI'de dagilmisti; "hangi tur cari ekstresine girer"
--    bilgisi ise SQL'lere gomulu "TUR NOT BETWEEN 40 AND 79" gibi sihirli
--    araliklardaydi. Burada tur bir TABLO: bayraklar (cari_ekstre, bakiye_dahil,
--    fis_mi ...) ve bacak sablonu veriyle tasinir, kod sorgu yazmaz.
-- ============================================================================
