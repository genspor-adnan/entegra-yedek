--  mockuplarını ekle" + "daha sade olabilir mi?". Mockup Ekranlar/Kalite/
--  kalite_dof.html / kalite_dof_karti.html - SADELEŞTİRİLMİŞ hali: tek liste,
--  generic kart (KartKatalogu "kys-dof") + faaliyetler detay tablosu.
--  Aşama şeridi, 5 Neden / balık kılçığı, tekrar DÖF otomasyonu YOK.
--
--  DURUM (basit seçim): 1 Açık · 3 Faaliyette · 4 Doğrulamada · 5 Kapandı · 9 İptal.
--    Numaralar 1048 sözleşmesiyle uyumlu: açık = durum < 5, kapandı = 5.
--  KAYNAK BAĞI (1048 sözleşmesi): kaynak_tur 1 iç denetim · 2 olay bildirimi ·
--    3 görüş/şikâyet · 4 risk · 5 dış denetim · 6 YGG/toplantı · 7 gösterge ·
--    8 tedarikçi · 9 diğer; kaynak_id o tablonun kimliği (FK YOK), kaynak_no
--    ekranda görünen numara. Yeni kart `/kys-dof/yeni?kaynakTur&kaynakId&
--    kaynakNo&birimId&tanim` ile kaynaktan dolu açılır.
--  NUMARA: 'DÖF-2026-001' - kolon varsayılanı fn_kalite_no (1048).
--  İdempotent.
-- =============================================================================

begin;

create table if not exists public.kalite_dof (
    id                 integer generated by default as identity primary key,
    no                 varchar(20)   not null default public.fn_kalite_no('DÖF', 3),
    tur                smallint      not null default 1,      -- 1 düzeltici · 2 önleyici
    kaynak_tur         smallint      not null default 9,
    kaynak_id          integer,
    kaynak_no          varchar(40)   not null default '',
    departman_id       integer       references public.departman(id),
    sorumlu_id         integer       references public.taraf(id),
    termin             date,
    tanim              varchar(4000) not null default '',
    kok_neden          varchar(2000) not null default '',
    dogrulama_tarihi   date,
    dogrulama_sonuc    smallint,                               -- 1 etkin · 2 kısmen etkin · 3 etkin değil
    durum              smallint      not null default 1,
    sube_id            integer       not null default 0,
    ekleyen            integer       not null default 0,
    ekleme_tarihi      timestamptz   not null default now(),
    degistiren         integer       not null default 0,
    degistirme_tarihi  timestamptz
);
comment on table public.kalite_dof is
  'Kurumsal Kalite (1050): DÖF. durum 1 açık · 3 faaliyette · 4 doğrulamada · 5 kapandı · 9 iptal; kaynak_tur 1048 sözleşmesi.';
create index if not exists ix_kalite_dof_kaynak on public.kalite_dof (kaynak_tur, kaynak_id);
create unique index if not exists uq_kalite_dof_no on public.kalite_dof (no);

create table if not exists public.kalite_dof_faaliyet (
    id                 integer generated by default as identity primary key,
    dof_id             integer       not null references public.kalite_dof(id) on delete cascade,
    faaliyet           varchar(1000) not null,
    sorumlu_id         integer       references public.taraf(id),
    termin             date,
    durum              smallint      not null default 0,      -- 0 başlamadı · 1 sürüyor · 2 tamamlandı
    sube_id            integer       not null default 0,      -- generic kart detay yazımı damgalar
    ekleyen            integer       not null default 0,
    ekleme_tarihi      timestamptz   not null default now(),
    degistiren         integer       not null default 0,
    degistirme_tarihi  timestamptz
);
alter table public.kalite_dof_faaliyet add column if not exists sube_id integer not null default 0;
create index if not exists ix_kalite_dof_faaliyet_dof on public.kalite_dof_faaliyet (dof_id);

-- ---------------------------------------------------------------- liste --
--  Vadesi geçen = açık (durum < 5) ve termin < bugün.
create or replace view public.v_kalite_dof as
select d.id, d.no, d.tur,
       case d.tur when 2 then 'Önleyici' else 'Düzeltici' end::varchar(20) as tur_adi,
       d.kaynak_tur,
       case d.kaynak_tur when 1 then 'İç denetim' when 2 then 'Olay bildirimi' when 3 then 'Şikâyet / görüş'
                         when 4 then 'Risk' when 5 then 'Dış denetim' when 6 then 'YGG / toplantı'
                         when 7 then 'Gösterge' when 8 then 'Tedarikçi' else 'Diğer' end::varchar(30) as kaynak_adi,
       d.kaynak_id, d.kaynak_no,
       left(d.tanim, 300)::varchar(300) as tanim,
       d.departman_id, coalesce(dp.ad, '')::varchar(100) as birim_adi,
       d.sorumlu_id, coalesce(public.fn_taraf_ad(ts.unvan, ts.ad, ts.soyad), '')::varchar(120) as sorumlu_adi,
       d.ekleme_tarihi::date as acilis, d.termin, d.dogrulama_tarihi, d.dogrulama_sonuc,
       d.durum,
       case when d.durum < 5 and d.termin < current_date then 'GECİKTİ · ' || (current_date - d.termin) || ' gün'
            else case d.durum when 1 then 'Açık' when 3 then 'Faaliyette' when 4 then 'Doğrulamada'
                              when 5 then 'Kapandı' when 9 then 'İptal' else '?' end
       end::varchar(40) as durum_adi,
       case when d.durum < 5 then 1 else 0 end::smallint as acik,
       case when d.durum < 5 and d.termin < current_date then 1 else 0 end::smallint as vadesi_gecti,
       d.sube_id, d.ekleme_tarihi
  from public.kalite_dof d
  left join public.departman dp on dp.id = d.departman_id
  left join public.taraf ts on ts.id = d.sorumlu_id;

-- ----------------------------------------------------------- yardım kataloğu --
insert into public.ai_rehber_ekran (kaynak, rota, baslik, yol, menu_grup, menu_ad, yetki_kodu, urun_modu, modul,
                                    kart_yolu, anahtar, aciklama, aksiyon_ekrani)
select 'kys-dof', '/kys-dof', 'DÖF — Düzeltici / Önleyici Faaliyetler', 'Kalite › DÖF', 'Kalite', 'DÖF', 'kys.dof', 0, 'kys', '/kys-dof',
       'döf düzeltici önleyici faaliyet uygunsuzluk kök neden aksiyon termin doğrulama iso 9001 10.2',
       'Kurumun DÖF kayıtları: açık / vadesi geçen / kapalı. Kart: kaynak (denetim, olay, şikâyet, risk...), birim, sorumlu, termin, '
       || 'tanım, kök neden, doğrulama sonucu ve durum; altında faaliyetler (faaliyet, sorumlu, termin, durum).',
       'kys-dof-liste'
 where not exists (select 1 from public.ai_rehber_ekran e where e.kaynak = 'kys-dof');

commit;
