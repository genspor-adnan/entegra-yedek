-- ------------------------------------------------------------ kod listeleri --
insert into public.kod_liste (kod, ad)
select v.kod, v.ad from (values ('rad.bolge', 'Radyoloji Bölgesi'), ('rad.kontrol_kaynak', 'Çekim Öncesi Kontrol Kaynağı'),
                             ('rad.alan_tip', 'Yapılandırılmış Alan Tipi')) v(kod, ad)
 where not exists (select 1 from public.kod_liste l where l.kod = v.kod);

insert into public.kod_deger (liste_id, deger, ad, dil, sira, aktif, ekleyen)
select l.id, v.deger, v.ad, 0, v.deger, 1, 0
  from (values ('rad.bolge', 1, 'Baş - Boyun'), ('rad.bolge', 2, 'Toraks'), ('rad.bolge', 3, 'Abdomen - Pelvis'),
               ('rad.bolge', 4, 'Kas - İskelet'), ('rad.bolge', 5, 'Omurga'), ('rad.bolge', 6, 'Meme'),
               ('rad.bolge', 7, 'Vasküler'), ('rad.bolge', 9, 'Diğer'),
               ('rad.kontrol_kaynak', 1, 'Lab sonucu'), ('rad.kontrol_kaynak', 2, 'Alerji kaydı'),
               ('rad.kontrol_kaynak', 3, 'İlaç listesi'), ('rad.kontrol_kaynak', 4, 'Hasta beyanı'),
               ('rad.kontrol_kaynak', 9, 'Diğer'),
               ('rad.alan_tip', 1, 'Seçim'), ('rad.alan_tip', 2, 'Sayı'), ('rad.alan_tip', 3, 'Skor'),
               ('rad.alan_tip', 4, 'Evet / hayır'), ('rad.alan_tip', 5, 'Metin')) v(kod, deger, ad)
  join public.kod_liste l on l.kod = v.kod
 where not exists (select 1 from public.kod_deger x where x.liste_id = l.id and x.deger = v.deger and x.dil = 0);

