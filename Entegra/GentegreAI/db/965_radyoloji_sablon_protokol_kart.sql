do $$
declare t text;
begin
    foreach t in array array['radyoloji_sablon_bolum', 'radyoloji_sablon_alan', 'radyoloji_sablon_makro'] loop
        execute format('alter table public.%I add column if not exists ekleyen integer', t);
        execute format('alter table public.%I add column if not exists ekleme_tarihi timestamptz default now()', t);
        execute format('alter table public.%I add column if not exists degistiren integer', t);
        execute format('alter table public.%I add column if not exists degistirme_tarihi timestamptz', t);
    end loop;
end $$;

