create table if not exists public.radyoloji_sablon_hizmet (
    id         integer generated by default as identity primary key,
    sablon_id  integer not null references public.radyoloji_sablon(id) on delete cascade,
    hizmet_id  integer not null references public.hizmet(id),
    ekleyen    integer, ekleme_tarihi timestamptz default now(),
    degistiren integer, degistirme_tarihi timestamptz,
    unique (sablon_id, hizmet_id)
);

