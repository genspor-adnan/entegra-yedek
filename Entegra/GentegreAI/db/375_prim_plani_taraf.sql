-- ============================================================================
--  375 - PRIM PLANI: TEK HEKIM YERINE KISI LISTESI
--
--  Kullanici: "dış hekimlerin bazısı MR için %20 alacak bazısı %25 alacak,
--  gönderen olarak" + "hekim listesi demeyelim, teknisyen vb olabilir".
--
--  ESKI HALI: plan tek bir kisiye baglanabiliyordu (`prim_plani.hekim_id`).
--  Ayni orani alan 30 kisi = 30 AYRI PLAN; oran degisince otuz kaydi tek tek
--  duzeltmek gerekiyordu. Ustelik ad yaniltiyordu: prim rolleri yalniz hekim
--  degil - Teknisyen, Asistan, Raporlayan, Anestezi de prim alir.
--
--  YENI HALI: plan bir KISI LISTESI tasir (`prim_plani_taraf`).
--      liste BOS  -> plan o roldeki HERKESE uyar (eski hekim_id null davranisi)
--      liste DOLU -> yalnizca listedekilere
--  Boylece iki plan yeter: "MR — Gönderen %20" + kisileri, "%25" + kisileri.
--
--  ESLESMEDE ONCELIK KORUNUYOR: listesi dolu plan, listesi bos olana gore
--  DAHA OZELDIR ve onu ezer - `hekim_id`nin dolu olmasinin yaptigi is buydu.
--
--  hekim_id KOLONU KALDIRILIYOR: iki yerden ayni soruya cevap vermek (kolon +
--  liste) "hangisi gecerli" belirsizligi uretir. Varsa degeri once listeye
--  tasinir - hicbir plan davranisini kaybetmez.
-- ============================================================================

-- ============================================================== liste ========
create table if not exists public.prim_plani_taraf (
    id             integer generated by default as identity primary key,
    plan_id        integer      not null references public.prim_plani(id) on delete cascade,
    taraf_id       integer      not null references public.taraf(id),
    aciklama       varchar(200) not null default '',
    ekleyen        integer      not null default 0,
    ekleme_tarihi  timestamp    not null default now()::timestamp,
    degistiren     integer      not null default 0,
    degistirme_tarihi timestamp,
    constraint ux_prim_plani_taraf unique (plan_id, taraf_id)
);

create index if not exists ix_prim_plani_taraf_taraf
    on public.prim_plani_taraf (taraf_id);

comment on table public.prim_plani_taraf is
  'Planin kapsadigi KISILER (375). BOS = plan o roldeki herkese uyar; DOLU = '
  'yalnizca listedekilere. "Hekim" degil "kisi": Teknisyen / Asistan / '
  'Raporlayan rolleri de prim alir. Eski prim_plani.hekim_id bu tabloya '
  'tasindi ve kaldirildi.';

-- ============================================================== gocurme =====
-- Var olan tek-hekim planlari listeye tasinir (kolon dusmeden ONCE).
do $$
begin
    if exists (select 1 from information_schema.columns
                where table_schema = 'public' and table_name = 'prim_plani'
                  and column_name = 'hekim_id') then
        insert into public.prim_plani_taraf (plan_id, taraf_id, aciklama)
        select p.id, p.hekim_id, '375 gocu: eski hekim_id'
          from public.prim_plani p
         where p.hekim_id is not null
        on conflict (plan_id, taraf_id) do nothing;
    end if;
end $$;

-- ============================================================== lookup ======
-- Kart, kisileri PRIM ROLU ISARETLI olanlar arasindan sectirir: rolu olmayan
--   birini plana yazmak hicbir hakedis uretmez ve bu ancak ay sonunda fark
--   edilirdi.
create or replace view public.v_prim_taraf_lookup as
select distinct a.id, a.ad, 1 as aktif
  from public.v_prim_rol_aday a
 where coalesce(a.durum, 1) = 1;

comment on view public.v_prim_taraf_lookup is
  'Prim planina eklenebilecek kisiler (375): prim rolu ISARETLI olanlar. '
  'Rolsuz birini plana yazmak hicbir hakedis uretmez.';

-- ============================================================== eslestirme ==
-- fn_prim_plan_satiri: hekim_id kosulu KISI LISTESI kosuluna cevrilir.
--   Ozgulluk puani da ayni sekilde tasinir - listesi dolu plan, listesi bos
--   olani ezmeye devam eder.
create or replace function public.fn_prim_plan_satiri(
    p_rol smallint, p_taraf_id integer, p_hizmet_id integer, p_stok_id integer,
    p_belge_tur smallint, p_pay smallint, p_kurum_id integer, p_sube_id integer,
    p_tarih date, p_tahsilat_turu smallint default 0)
returns table(plan_id integer, satir_id integer, oran_tipi smallint,
              deger numeric, alt_sinir numeric, ust_sinir numeric,
              baz smallint, prim_zamani smallint)
language sql
stable
as $function$
    select p.id, s.id, s.oran_tipi, s.deger, s.alt_sinir, s.ust_sinir, p.baz,
           coalesce(p.prim_zamani, 1)
      from public.prim_plani p
      join public.prim_plani_satir s on s.plan_id = p.id
     where coalesce(p.durum, 1) = 1
       and p.baslangic <= p_tarih
       and (p.bitis is null or p.bitis >= p_tarih)
       and s.rol = p_rol
       -- KISI LISTESI (375): bos = herkes, dolu = yalnizca listedekiler.
       and (not exists (select 1 from public.prim_plani_taraf t
                         where t.plan_id = p.id)
            or exists (select 1 from public.prim_plani_taraf t
                        where t.plan_id = p.id and t.taraf_id = p_taraf_id))
       and (coalesce(p.odeyen_kurum_id, 0) = 0 or p.odeyen_kurum_id = p_kurum_id)
       and (coalesce(p.sube_id, 0) = 0 or p.sube_id = p_sube_id)
       and (s.tip = 1
            or (s.tip = 2 and (
                   (coalesce(s.kalem_turu, 0) in (0, 2)
                    and s.hedef_id = (select h.kategori from public.hizmet h
                                       where h.id = p_hizmet_id))
                or (coalesce(s.kalem_turu, 0) in (0, 1)
                    and s.hedef_id = (select st.kategori from public.stok st
                                       where st.id = p_stok_id))))
            or (s.tip = 3 and (
                   (coalesce(s.kalem_turu, 0) in (0, 2) and s.hedef_id = p_hizmet_id)
                or (coalesce(s.kalem_turu, 0) in (0, 1) and s.hedef_id = p_stok_id))))
       and (s.belge_turleri = ''
            or p_belge_tur is null
            or p_belge_tur::text = any(string_to_array(s.belge_turleri, ',')))
       -- Tahsilat turu kriteri YALNIZ tahsilat zamanli planda anlamlidir:
       --   faturalama priminde henuz odeme araci bilinmez.
       and (coalesce(s.tahsilat_turu, 0) = 0
            or coalesce(p.prim_zamani, 1) = 2
            or s.tahsilat_turu = p_tahsilat_turu)
       and (s.pay = 0 or s.pay = p_pay)
     order by
       (case s.tip when 3 then 3 when 2 then 1 else 0 end)
       + (case when coalesce(s.kalem_turu, 0) <> 0 then 1 else 0 end)
       + (case when s.belge_turleri <> '' then 1 else 0 end)
       + (case when coalesce(s.tahsilat_turu, 0) <> 0 then 1 else 0 end)
       + (case when s.pay <> 0 then 1 else 0 end)
       + (case when exists (select 1 from public.prim_plani_taraf t
                             where t.plan_id = p.id) then 1 else 0 end)
       + (case when coalesce(p.odeyen_kurum_id, 0) <> 0 then 1 else 0 end) desc,
       p.oncelik desc, s.sira, s.id
     limit 1;
$function$;

-- ============================================================== kolon =======
-- Degeri listeye tasindi; iki kaynak birakmak "hangisi gecerli" belirsizligi.
alter table public.prim_plani drop column if exists hekim_id;
