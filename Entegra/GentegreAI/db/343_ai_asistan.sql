-- 343: YAPAY ZEKA ASİSTANI ŞEMASI (İletişim & AI › Yapay Zeka).
--
-- Mockup: `Ekranlar/ai_asistan.html` (Delphi krokisinde AISOHBET / AIMESAJ /
-- AIARAC / AIARACLOG / AITASLAK / AILOG / AIAYAR). 341'de menü ve yetki
-- açılmıştı; bu göç veriyi ve kuralı kurar.
--
-- MOCKUP'IN ANA KURALI ŞEMAYA GEÇİYOR:
--   "Model veritabanına doğrudan bağlanmaz. Yalnızca İZİNLİ FONKSİYONLAR
--    üzerinden veri okur; YAZAN her işlem TASLAK üretir ve kullanıcı onayı
--    olmadan kaydedilmez."
-- Bu yüzden:
--   * `ai_arac` = izinli fonksiyon kataloğu (yazan fonksiyon yok; `yazar`
--     bayrağı taslak üretenleri işaretler),
--   * `ai_taslak` = onay bekleyen çıktı (görev / e-posta / teklif metni);
--     onaylanınca hedef kayıt oluşur ve `hedef_id` yazılır,
--   * `ai_arac_log` = hangi fonksiyon hangi parametreyle çağrıldı, kaç kayıt
--     döndü, kaç ms sürdü - denetim izi model cevabından bağımsız durur.
--
-- MODEL BAĞLANTISI bu göçün konusu DEĞİL: model kimliği `entegrasyon_hesap`
-- (336) üzerinden yapılandırılır (kod = 'AI'). Model tanımlı değilken de
-- ekran çalışır: izinli fonksiyonlar doğrudan çağrılabilir (mockup'taki
-- "hazır komutlar"), yalnız serbest metin yanıtı üretilmez.
\set ON_ERROR_STOP on

-- --------------------------------------------------------------- sohbet ---
create table if not exists public.ai_sohbet (
    id            integer generated by default as identity primary key,
    kullanici_id  integer      not null references public.taraf_kullanici(id),
    baslik        varchar(160) not null default 'Yeni sohbet',
    -- Ekran bağlamı (mockup sağ panel "Açık ekran / Seçili kayıt"): asistanın
    --   neyin üzerinde konuştuğu. Serbest jsonb - her ekran kendi özetini yazar.
    baglam        jsonb        not null default '{}'::jsonb,
    model         varchar(60)  not null default '',
    token_toplam  integer      not null default 0,
    ekleme_tarihi timestamp    not null default (now())::timestamp,
    son_tarih     timestamp    not null default (now())::timestamp,
    durum         smallint     not null default 1   -- 1 açık, 2 arşiv
);

create index if not exists ix_ai_sohbet_kullanici
    on public.ai_sohbet (kullanici_id, son_tarih desc);

-- ---------------------------------------------------------------- mesaj ---
create table if not exists public.ai_mesaj (
    id         integer generated by default as identity primary key,
    sohbet_id  integer   not null references public.ai_sohbet(id) on delete cascade,
    -- 1 kullanıcı, 2 asistan, 3 sistem/araç özeti.
    rol        smallint  not null default 1,
    metin      text      not null default '',
    -- Araç çağrısının SONUCU (tablo) mesajla birlikte saklanır: model cevabı
    --   yeniden üretilse de kullanıcının o an gördüğü veri kayıtta kalır.
    veri       jsonb,
    token      integer   not null default 0,
    model      varchar(60) not null default '',
    tarih      timestamp not null default (now())::timestamp,
    -- Kullanıcı geri bildirimi (mockup 👍/👎): 0 yok, 1 olumlu, 2 olumsuz.
    geribildirim smallint not null default 0
);

create index if not exists ix_ai_mesaj_sohbet on public.ai_mesaj (sohbet_id, tarih);

-- ------------------------------------------------- izinli fonksiyonlar ----
-- Katalog VERİDEDİR: yeni fonksiyon eklemek için kod değişikliği gerekir ama
--   hangi rolün hangisini çağırabildiği burada yönetilir (mockup: "İzinli
--   Fonksiyonlar" paneli).
create table if not exists public.ai_arac (
    kod        varchar(60)  primary key,
    ad         varchar(160) not null,
    aciklama   varchar(400) not null default '',
    -- Çağırabilmek için gereken uygulama yetkisi (yetki.kod) - asistan
    --   kullanıcının GÖREMEDİĞİ veriyi okuyamaz.
    yetki_kodu varchar(40)  not null default '',
    -- 1 ise çıktısı TASLAK üretir (yazan işlem); 0 salt okuma.
    yazar      smallint     not null default 0,
    parametre  jsonb        not null default '[]'::jsonb,
    aktif      smallint     not null default 1,
    sira       smallint     not null default 0
);

create table if not exists public.ai_arac_log (
    id         integer generated by default as identity primary key,
    sohbet_id  integer   references public.ai_sohbet(id) on delete set null,
    mesaj_id   integer   references public.ai_mesaj(id) on delete set null,
    kullanici_id integer not null,
    arac_kod   varchar(60) not null,
    parametre  jsonb     not null default '{}'::jsonb,
    kayit_sayisi integer not null default 0,
    sure_ms    integer   not null default 0,
    hata       varchar(400) not null default '',
    tarih      timestamp not null default (now())::timestamp
);

create index if not exists ix_ai_arac_log_sohbet on public.ai_arac_log (sohbet_id, tarih desc);

-- --------------------------------------------------------------- taslak ---
-- YAZAN İŞLEM YOK, TASLAK VAR: asistan görev/e-posta/teklif metnini hazırlar,
--   kayıt ancak kullanıcı onaylayınca oluşur (mockup: "✔ Onayla ve Taslak
--   Oluştur"). Onay kimin verdiği ve ne zaman verdiği burada durur.
create table if not exists public.ai_taslak (
    id          integer generated by default as identity primary key,
    sohbet_id   integer   not null references public.ai_sohbet(id) on delete cascade,
    mesaj_id    integer   references public.ai_mesaj(id) on delete set null,
    -- 1 görev, 2 e-posta metni, 3 not/özet, 4 teklif metni.
    tip         smallint  not null default 1,
    baslik      varchar(200) not null default '',
    icerik      text      not null default '',
    -- Hedef kayıt (onaylanınca): 'gorev' + id.
    hedef_modul varchar(40) not null default '',
    hedef_id    integer,
    -- 1 bekliyor, 2 onaylandı, 3 iptal.
    durum       smallint  not null default 1,
    taraf_id    integer,
    onaylayan   integer,
    onay_tarihi timestamp,
    ekleme_tarihi timestamp not null default (now())::timestamp
);

create index if not exists ix_ai_taslak_sohbet on public.ai_taslak (sohbet_id, durum);

-- ------------------------------------------------------- araç kataloğu ----
-- İlk üç fonksiyon GERÇEKTEN çalışır (uygulama tarafında SQL karşılıkları
--   var); listeyi büyütmek kod + bu tabloya satır işidir.
insert into public.ai_arac (kod, ad, aciklama, yetki_kodu, yazar, sira) values
    ('cari_vadesi_gecen', 'Vadesi geçen cariler',
     'Vadesi geçmiş bakiyesi olan carileri tutara göre sıralar.', 'kasa_islem', 0, 10),
    ('stok_kritik', 'Kritik stok listesi',
     'Minimum stok seviyesinin altına düşen ürünler.', 'stok', 0, 20),
    ('bugun_ozet', 'Bugünün özeti',
     'Bugünkü belge, tahsilat ve açık görev sayıları.', 'belge', 0, 30),
    ('gorev_taslagi', 'Görev taslağı hazırla',
     'Konu ve termin ile GÖREV taslağı üretir - kayıt onayla oluşur.', 'gorev', 1, 40)
on conflict (kod) do update
   set ad = excluded.ad, aciklama = excluded.aciklama,
       yetki_kodu = excluded.yetki_kodu, yazar = excluded.yazar, sira = excluded.sira;

do $$
begin
    raise notice '343 tamam: ai_sohbet / ai_mesaj / ai_arac (+log) / ai_taslak · % arac.',
        (select count(*) from public.ai_arac);
end $$;
