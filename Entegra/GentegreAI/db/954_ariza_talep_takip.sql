     '{"talepNo":"Talep no","kategori":"Kategori","konum":"Konum","aciklama":"Açıklama","talepEden":"Bildiren","telefon":"Ulaşılacak telefon"}',
     'Acil öncelikli arıza açılınca ekibe'),
    ('ariza.acil.eposta', 'Arıza: ACİL bildirim (e-posta)', 2, 'ACİL arıza {{talepNo}} - {{kategori}}',
     E'Sayın {{alici}},\n\nAcil öncelikli bir arıza bildirildi.\n\nNo: {{talepNo}}\nKategori: {{kategori}}\nKonum: {{konum}}\nBildiren: {{talepEden}} {{telefon}}\n\n{{aciklama}}',
     '{"alici":"Alıcı","talepNo":"Talep no","kategori":"Kategori","konum":"Konum","aciklama":"Açıklama","talepEden":"Bildiren","telefon":"Ulaşılacak telefon"}',
     'Acil öncelikli arıza açılınca ekibe')
