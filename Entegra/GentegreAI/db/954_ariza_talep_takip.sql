--
--  1. ariza_talep: telefon (ulaşılacak numara), cozum_tarihi (çözüldü anı -
--     talep edenin onayı bundan sayılır).
--  2. ariza_talep_hareket: AKIŞ. Kim, ne zaman, ne yaptı - durum ve sorumlu
--     değişimi tetikle yazılır (uç unutsa da iz kalır), notlar uçtan.
--  3. ariza_talep_takipci: "Ben de bildiriyorum" - aynı arıza için ikinci
--     kayıt açılmaz, kişi mevcut kayda takipçi olarak eklenir.
--  4. fn_ariza_talep_ac: telefon parametresi.
--  5. ÇÖZÜLDÜ → ONAY: teknisyen "çözüldü" der, talep eden "kapat" ya da
--     "yeniden aç" der. 3 gün yanıt yoksa zamanlı iş kapatır (degistiren 0).
--  6. Acil bildirim şablonları (SMS + e-posta).
--  Yalnız dev docker'a uygulanır.
-- ============================================================================

-- ---------------------------------------------------------------------- 1
alter table public.ariza_talep add column if not exists telefon      varchar(40) not null default '';
alter table public.ariza_talep add column if not exists cozum_tarihi timestamptz;

-- Eski çözülmüşlerin çözüm anı: son değişiklik (onay sayacı bundan başlar).
update public.ariza_talep
   set cozum_tarihi = coalesce(degistirme_tarihi, ekleme_tarihi)
 where durum = 4 and cozum_tarihi is null;

-- ---------------------------------------------------------------------- 2
--  tur: 1 bildirildi · 2 ekibe iletildi · 3 atandı · 4 işleme alındı
--       5 çözüldü · 6 kapandı (talep eden onayladı / ekip kapattı)
--       7 yeniden açıldı · 8 iptal · 9 not · 10 ben de bildiriyorum
--       11 kendiliğinden kapandı (onay gelmedi)
create table if not exists public.ariza_talep_hareket (
    id         bigint       primary key generated by default as identity,
    talep_id   integer      not null references public.ariza_talep (id) on delete cascade,
    tur        smallint     not null,
    metin      varchar(1000) not null default '',
    yazan      integer      not null default 0,
    tarih      timestamptz  not null default now()
);
create index if not exists ix_ariza_hareket_talep on public.ariza_talep_hareket (talep_id, id);

-- ---------------------------------------------------------------------- 3
create table if not exists public.ariza_talep_takipci (
    talep_id      integer     not null references public.ariza_talep (id) on delete cascade,
    taraf_id      integer     not null,
    ekleme_tarihi timestamptz not null default now(),
    primary key (talep_id, taraf_id)
);
create index if not exists ix_ariza_takipci_taraf on public.ariza_talep_takipci (taraf_id);

-- ------------------------------------------------- çözüm anı (BEFORE) ----
create or replace function public.tg_ariza_talep_cozum()
returns trigger language plpgsql as $fn$
begin
    if new.durum = 4 and (tg_op = 'INSERT' or old.durum is distinct from 4) then
        new.cozum_tarihi := now();
    elsif new.durum <> 4 and tg_op = 'UPDATE' and old.durum = 4 and new.durum <> 5 then
        new.cozum_tarihi := null;      -- yeniden açıldı: sayaç sıfır
    end if;
    return new;
end $fn$;

drop trigger if exists tg_ariza_talep_cozum on public.ariza_talep;
create trigger tg_ariza_talep_cozum before insert or update of durum on public.ariza_talep
    for each row execute function public.tg_ariza_talep_cozum();

-- ------------------------------------------------- akış (AFTER) ----------
create or replace function public.tg_ariza_talep_hareket()
returns trigger language plpgsql as $fn$
declare
    v_kim integer := coalesce(new.degistiren, 0);
    v_ad  varchar;
begin
    if tg_op = 'INSERT' then
        insert into public.ariza_talep_hareket (talep_id, tur, metin, yazan, tarih)
        values (new.id, 1, '', new.talep_eden, new.ekleme_tarihi);
        select d.ad into v_ad from public.kod_deger d join public.kod_liste l on l.id = d.liste_id
         where l.kod = 'ariza.ekip' and d.deger = new.ekip and d.dil = 0;
        insert into public.ariza_talep_hareket (talep_id, tur, metin, yazan, tarih)
        values (new.id, 2, coalesce(v_ad, ''), 0, new.ekleme_tarihi);
        return new;
    end if;

    if new.sorumlu_id is distinct from old.sorumlu_id and new.sorumlu_id is not null then
        insert into public.ariza_talep_hareket (talep_id, tur, metin, yazan)
        values (new.id, 3, coalesce((select public.fn_taraf_ad(t.unvan, t.ad, t.soyad)::varchar(120)
                                       from public.taraf t where t.id = new.sorumlu_id), ''), v_kim);
    end if;

    if new.durum is distinct from old.durum then
        insert into public.ariza_talep_hareket (talep_id, tur, metin, yazan)
        values (new.id,
                case when new.durum = 3 and old.durum in (1, 2) then 4
                     when new.durum = 4 then 5
                     when new.durum = 5 and v_kim = 0 then 11
                     when new.durum = 5 then 6
                     when new.durum = 0 then 8
                     when old.durum in (4, 5) then 7
                     else 4 end,
                case when new.durum = 4 then coalesce(new.cozum_notu, '') else '' end,
                v_kim);
    end if;
    return new;
end $fn$;

drop trigger if exists tg_ariza_talep_hareket on public.ariza_talep;
create trigger tg_ariza_talep_hareket after insert or update of durum, sorumlu_id on public.ariza_talep
    for each row execute function public.tg_ariza_talep_hareket();

-- Var olan kayıtlara başlangıç akışı (yalnız hiç hareketi olmayanlar).
insert into public.ariza_talep_hareket (talep_id, tur, metin, yazan, tarih)
select t.id, 1, '', t.talep_eden, t.ekleme_tarihi
  from public.ariza_talep t
 where not exists (select 1 from public.ariza_talep_hareket h where h.talep_id = t.id);

-- ---------------------------------------------------------------------- 4
drop function if exists public.fn_ariza_talep_ac(smallint, varchar, varchar, smallint, integer, integer, integer);

create or replace function public.fn_ariza_talep_ac(
    p_kategori    smallint,
    p_aciklama    varchar,
    p_konum       varchar default '',
    p_oncelik     smallint default 2,
    p_demirbas_id integer default null,
    p_talep_eden  integer default 0,
    p_sube_id     integer default 0,
    p_telefon     varchar default '')
returns integer language plpgsql as $fn$
declare
    v_ekip smallint;
    v_id   integer;
    v_no   bigint;
begin
    select ekip into v_ekip from public.ariza_kategori_ekip where kategori = p_kategori;
    v_ekip := coalesce(v_ekip, 4);            -- eşleşme yoksa İdari
    v_no := nextval('public.ariza_talep_no_seq');

    insert into public.ariza_talep
           (talep_no, kategori, ekip, konum, aciklama, oncelik, demirbas_id,
            talep_eden, durum, sube_id, ekleyen, telefon)
    values ('AT-' || lpad(v_no::text, 6, '0'), p_kategori, v_ekip,
            coalesce(p_konum,''), p_aciklama, coalesce(p_oncelik,2), p_demirbas_id,
            p_talep_eden, 1, coalesce(p_sube_id,0), p_talep_eden, left(coalesce(p_telefon,''), 40))
    returning id into v_id;
    return v_id;
end $fn$;

-- ---------------------------------------------------------------------- 5
--  Talep eden 3 gün yanıt vermezse çözülmüş talep kapanır (degistiren 0 =
--  sistem; akışa "kendiliğinden kapandı" yazılır).
create or replace function public.fn_ariza_otomatik_kapat(p_gun integer default 3)
returns integer language plpgsql as $fn$
declare v_n integer;
begin
    update public.ariza_talep
       set durum = 5, kapanis_tarihi = now(), degistiren = 0, degistirme_tarihi = now()
     where durum = 4 and cozum_tarihi < now() - make_interval(days => p_gun);
    get diagnostics v_n = row_count;
    return v_n;
end $fn$;

insert into public.zamanli_is (kod, ad, aktif, periyot, gun, saat, dakika)
select 'ariza.otomatik_kapat', 'Onaylanmayan çözülmüş arızayı kapat (3 gün)', 1, 1, 1, 5, 20
 where not exists (select 1 from public.zamanli_is where kod = 'ariza.otomatik_kapat');

-- ---------------------------------------------------------------------- 6
insert into public.bildirim_sablon (kod, ad, kanal, konu, govde, degiskenler, durum, aciklama, ekleyen)
select v.kod, v.ad, v.kanal, v.konu, v.govde, v.degiskenler::json, 1, v.aciklama, 0 from (values
    ('ariza.acil', 'Arıza: ACİL bildirim (SMS)', 1, '',
