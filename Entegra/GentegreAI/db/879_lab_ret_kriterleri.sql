-- =====================================================================
--  879_lab_ret_kriterleri.sql
--  NUMUNE RET KRİTERLERİ TANIMLANABİLİR OLDU + RET → e-NABIZ MESAJI
--  (KTS denetim maddeleri L6 "Ret kriterleri tanımlanabiliyor mu?" ve
--   H1 / D16 "Numune reddi olması durumunda hastanın e-Nabız profiline
--   otomatik mesaj gönderiliyor mu?")
--
--  BUGÜNKÜ DURUM: ret AKIŞI var (433) - numune reddedilir, tetkikler
--  "tekrar numune bekliyor"a düşer, hareket kaydı yazılır. Eksik olan,
--  ret NEDENLERİNİN koda gömülü olması: sekiz sabit kod hem sunucuda hem
--  ekranda ayrı ayrı yazılıydı. Denetimin sorduğu "tanımlanabiliyor mu"
--  tam olarak budur: laboratuvar kendi ret kriterlerini (kurumun kalite
--  el kitabındakileri) girebilmeli.
--
--  ESKİ KOD UZAYI KORUNUR. `lab_numune.ret_neden` ve `kalite` aynı kod
--  uzayını kullanıyor (1 Uygun · 2 Hemolizli · …) ve GEÇMİŞ KAYITLAR o
--  kodlarla duruyor. Tanım tablosu aynı kodlarla tohumlanır; kurum yeni
--  kriter eklerse 20'den devam eder. Kodları yeniden numaralandırmak,
--  geçmiş numunelerin ret sebebini sessizce değiştirirdi.
--
--  İKİ BAYRAK, İKİ AYRI SORUYA CEVAP:
--   * `kabulde_secilebilir`: bu gözlem numuneyi REDDETTİRMEDEN de
--     işaretlenebilir mi ("hafif lipemik ama çalışıldı"). "Diğer" için 0.
--   * `hasta_bilgilendir`: bu nedenle reddedilince hastanın e-Nabız
--     profiline mesaj gider mi. Varsayılan olarak yalnız hastanın yeniden
--     numune vermesi gereken nedenlerde 1 - "etiketsiz tüp" kurumun kendi
--     hatasıdır, hastaya mesaj atmak onu gereksiz yere endişelendirir ve
--     bize hiçbir şey kazandırmaz. Kurum ekrandan değiştirebilir.
--
--  MESAJ ŞABLONU NEDENİN KENDİSİNDE: "numune reddedildi" demek yetmez,
--  hastanın ne yapacağını bilmesi gerekir. Şablon boşsa genel metin
--  kullanılır (`referans.lab.ret_mesaj_sablonu`).
-- =====================================================================

create table if not exists public.lab_ret_nedeni (
  id                  integer generated by default as identity primary key,
  -- KOD = eski kod uzayı (lab_numune.ret_neden / kalite). Benzersiz.
  kod                 smallint     not null,
  ad                  varchar(80)  not null,
  aciklama            varchar(300) not null default '',
  kabulde_secilebilir smallint     not null default 1,
  hasta_bilgilendir   smallint     not null default 0,
  mesaj_sablonu       varchar(300) not null default '',
  sira                smallint     not null default 0,
  aktif               smallint     not null default 1,
  ekleyen             integer      not null default 0,
  ekleme_tarihi       timestamptz  not null default now(),
  degistiren          integer      not null default 0,
  degistirme_tarihi   timestamptz,
  constraint ux_lab_ret_nedeni_kod unique (kod)
);

comment on table public.lab_ret_nedeni is
  '879: numune ret kriterleri (KTS L6). Kod uzayi 433 ile AYNI - gecmis '
  'numunelerin ret_neden/kalite degerleri bu tabloya baglanir. '
  'hasta_bilgilendir = 1 ise ret, hastanin e-Nabiz profiline mesaj dogurur (H1).';
comment on column public.lab_ret_nedeni.kabulde_secilebilir is
  'Numuneyi reddetmeden kalite notu olarak secilebilir mi ("hafif lipemik ama calisildi").';
comment on column public.lab_ret_nedeni.mesaj_sablonu is
  'e-Nabiz mesaj metni. Bos ise referans lab.ret_mesaj_sablonu kullanilir.';

-- ------------------------------------------------------------ tohum ----
--  1-9: 433'teki kod uzayı, birebir (ekranlarda yıllardır bu adlar).
--  10-15: kalite el kitaplarında standart olan ama kodda hiç olmayan
--         preanalitik ret kriterleri. Kurum istemediğini pasife alır.
insert into public.lab_ret_nedeni
       (kod, ad, aciklama, kabulde_secilebilir, hasta_bilgilendir, mesaj_sablonu, sira)
select v.kod, v.ad, v.aciklama, v.kabul, v.bilgilendir, v.sablon, v.kod * 10
  from (values
    (1::smallint, 'Uygun', 'Numune kabul ölçütlerini karşılıyor.', 1, 0, ''),
    (2::smallint, 'Hemolizli', 'Serum/plazma hemolizi sonucu etkiliyor.', 1, 1,
     'Laboratuvar numuneniz teknik nedenle çalışılamadı. Yeniden numune vermeniz için kurumumuzla iletişime geçiniz.'),
    (3::smallint, 'Lipemik', 'Lipemi ölçümü bozuyor; açlık numunesi gerekebilir.', 1, 1,
     'Laboratuvar numuneniz teknik nedenle çalışılamadı. 12 saat açlık sonrası yeniden numune vermeniz gerekmektedir.'),
    (4::smallint, 'İkterik', 'Bilirubin girişimi.', 1, 0, ''),
    (5::smallint, 'Yetersiz miktar', 'Tüp hacmi çalışma için yeterli değil.', 1, 1,
     'Laboratuvar numuneniz yeterli miktarda olmadığı için çalışılamadı. Yeniden numune vermeniz gerekmektedir.'),
    (6::smallint, 'Pıhtılı', 'Antikoagülanlı tüpte pıhtı.', 1, 1,
     'Laboratuvar numuneniz teknik nedenle çalışılamadı. Yeniden numune vermeniz için kurumumuzla iletişime geçiniz.'),
    (7::smallint, 'Yanlış tüp', 'Tetkik için uygun olmayan tüp kullanılmış.', 1, 1,
     'Laboratuvar numuneniz uygun tüple alınmadığı için çalışılamadı. Yeniden numune vermeniz gerekmektedir.'),
    (8::smallint, 'Etiketsiz', 'Etiketsiz ya da okunamayan etiket - kimlik güvenliği.', 0, 0, ''),
    (9::smallint, 'Diğer', 'Açıklamada belirtilir.', 0, 0, ''),
    (10::smallint, 'Etiket - hasta uyuşmazlığı', 'Tüp etiketi ile istem/hasta bilgisi uyuşmuyor.', 0, 0, ''),
    (11::smallint, 'Uygunsuz taşıma / sıcaklık', 'Soğuk zincir ya da taşıma koşulu bozulmuş.', 0, 1,
     'Laboratuvar numuneniz taşıma koşulları nedeniyle çalışılamadı. Yeniden numune vermeniz gerekmektedir.'),
    (12::smallint, 'Süre aşımı', 'Numune, tetkikin kabul süresi içinde laboratuvara ulaşmamış.', 0, 1,
     'Laboratuvar numuneniz süresi içinde çalışılamadı. Yeniden numune vermeniz gerekmektedir.'),
    (13::smallint, 'Kırık / dökülmüş tüp', 'Numune taşıma sırasında kaybolmuş.', 0, 1,
     'Laboratuvar numuneniz ulaşmadığı için çalışılamadı. Yeniden numune vermeniz gerekmektedir.'),
    (14::smallint, 'İstem bilgisi eksik', 'Tetkik ya da klinik bilgi eksik; çalışma yapılamaz.', 0, 0, ''),
    (15::smallint, 'Mükerrer numune', 'Aynı istem için ikinci kez gelen numune.', 0, 0, '')
  ) as v(kod, ad, aciklama, kabul, bilgilendir, sablon)
 where not exists (select 1 from public.lab_ret_nedeni r where r.kod = v.kod);

-- ------------------------------------------------------------ görünüm ----
create or replace view public.v_lab_ret_nedeni as
select r.id, r.kod, r.ad, r.aciklama, r.kabulde_secilebilir, r.hasta_bilgilendir,
       r.mesaj_sablonu, r.sira, r.aktif
  from public.lab_ret_nedeni r;

comment on view public.v_lab_ret_nedeni is
  '879: ret kriterleri - ret penceresi, kabul kalite listesi ve ayar ekrani '
  'bu gorunumden okur (kod uzayi tek yerde).';

-- ------------------------------------------------------------- ayarlar ----
insert into public.referans (anahtar, deger, tip, kapsam, aciklama)
values ('lab.ret_mesaj_sablonu',
        'Laboratuvar numuneniz çalışılamadı. Yeniden numune vermeniz için kurumumuzla iletişime geçiniz.',
        'metin', 'firma',
        'Ret nedeninin kendi şablonu boşsa e-Nabız mesajında kullanılacak genel metin.')
on conflict (anahtar) do nothing;

insert into public.referans (anahtar, deger, tip, kapsam, aciklama)
values ('lab.ret_enabiz_bildir', '1', 'bool', 'firma',
        'Numune reddinde hastanın e-Nabız profiline otomatik mesaj yazılsın mı (KTS H1). '
        'Hangi ret nedenlerinde mesaj gideceği nedenin kendi ayarındadır.')
on conflict (anahtar) do nothing;

-- -------------------------------------------------------------- yetki ----
--  Kriter tanımı laboratuvar sorumlusunun işi - ayrı KAYNAK yetkisi
--  (kendi liste/kart ekranı var).
insert into public.yetki (kod, ad, grup, tur, sira, aktif, urun_modu, modul)
select 'lab.ret_nedeni', 'Numune ret kriterleri (tanım)', 'Laboratuvar', 0, 45, 1, 2, 'lab'
 where not exists (select 1 from public.yetki y where y.kod = 'lab.ret_nedeni');

insert into public.rol_yetki (rol_id, yetki_id, gor, ekle, degistir, sil, ekleyen)
select r.id, y.id, 1, 1, 1, 1, 0
  from public.rol r cross join public.yetki y
 where r.kod = 'yonetici' and y.kod = 'lab.ret_nedeni'
   and not exists (select 1 from public.rol_yetki ry
                    where ry.rol_id = r.id and ry.yetki_id = y.id);
update public.rol set yetki_surumu = yetki_surumu + 1 where kod = 'yonetici';

do $$
begin
    raise notice '879 tamam: % ret kriteri (% tanesi hastaya mesaj dogurur)',
        (select count(*) from public.lab_ret_nedeni),
        (select count(*) from public.lab_ret_nedeni where hasta_bilgilendir = 1);
end $$;
