-- =====================================================================
--  892_lab_grafik_sonuc.sql
--  GRAFİK TİPLİ SONUÇ: CİHAZDAN ALMA VE RAPORDA GÖSTERME
--  (KTS denetim maddesi L10: "Cihazlardan grafik tipli sonuç alınabiliyor
--   ve raporda gösterilebiliyor mu?")
--
--  BUGÜN NE VAR: ORU/ASTM çözümleyici OBX kalemlerini SAYISAL ya da METİN
--  olarak alıyor (`cihaz_mesaj_kalem.deger` varchar(200)). Elektroforez
--  eğrisi, kromatogram, jel görüntüsü gibi GRAFİK sonuçlar hiç alınmıyor;
--  alınsa saklanacak yer de yok, rapora da girmiyor.
--
--  İKİ AYRI GRAFİK BİÇİMİ VARDIR, İKİSİ DE DESTEKLENİR:
--
--    1. GÖMÜLÜ GÖRÜNTÜ (HL7 OBX-2 = "ED", encapsulated data): cihaz eğriyi
--       PNG/PDF olarak base64 gönderir. İçerik `dokuman` deposuna yazılır -
--       hash ile tekilleştirme, paylaşım, KVKK erişim günlüğü orada zaten
--       var; ikinci bir blob deposu açmak aynı işi iki yerde yapmak olurdu.
--
--    2. SAYISAL SERİ (OBX-2 = "NA", numeric array): cihaz noktaları dizi
--       olarak gönderir. Bunu görüntüye çevirip saklamak veriyi KAYBETMEK
--       olurdu - seri `jsonb` olarak durur, ekran ve rapor kendisi çizer;
--       ölçek değişse eski sonuç yeniden çizilebilir.
--
--  RAPORDA GÖSTERİM AYRI BİR KARARDIR (`raporda`): her eğri hastanın
--  raporuna basılmaz (ham kalibrasyon eğrisi laboratuvarın iç kaydıdır),
--  ama bazıları raporun ayrılmaz parçasıdır (protein elektroforezi).
--  Varsayılan "basılır" - cihazın gönderdiği bulguyu gizlemek, göstermekten
--  daha büyük karar.
-- =====================================================================

-- ---------------------------------------------- cihaz mesaj kalemi ----
--  `deger` varchar(200): base64 bir eğri oraya SIĞMAZ. Gömülü içerik ve
--  seri ayrı kolonlarda durur; ham mesaj yine `cihaz_mesaj.icerik`te.
alter table public.cihaz_mesaj_kalem
  add column if not exists deger_tipi varchar(10)  not null default '',
  add column if not exists gomulu     bytea,
  add column if not exists gomulu_tip varchar(100) not null default '',
  add column if not exists seri       jsonb;

comment on column public.cihaz_mesaj_kalem.deger_tipi is
  '892: HL7 OBX-2 deger tipi (NM sayisal, ST metin, ED gomulu veri, NA sayi '
  'dizisi). Bos = eski kayitlar.';
comment on column public.cihaz_mesaj_kalem.gomulu is
  '892: OBX-2 = ED ise cozulmus ikili icerik (PNG/PDF); tipi gomulu_tip.';
comment on column public.cihaz_mesaj_kalem.seri is
  '892: OBX-2 = NA ise sayi dizisi {"y":[...]} - goruntuye cevirmek veriyi '
  'kaybetmek olurdu.';

-- ------------------------------------------------------ grafik sonuç ----
create table if not exists public.lab_sonuc_grafik (
  id             integer generated by default as identity primary key,
  sonuc_id       bigint  references public.lab_sonuc(id) on delete cascade,
  istem_satir_id integer not null references public.lab_istem_satir(id) on delete cascade,
  -- 1 elektroforez · 2 kromatogram · 3 jel / blot · 4 kalibrasyon eğrisi ·
  -- 5 reaksiyon (kinetik) eğrisi · 9 diğer
  tur            smallint     not null default 9,
  baslik         varchar(120) not null default '',
  -- GÖRÜNTÜ: dokuman deposunda (hash-dedup, erişim günlüğü orada).
  dokuman_id     integer references public.dokuman(id) on delete set null,
  -- SERİ: {"x":[...], "y":[...], "isaret":[{"ad":"Albümin","bas":10,"son":25}]}
  seri           jsonb,
  birim_x        varchar(20)  not null default '',
  birim_y        varchar(20)  not null default '',
  -- 1 cihazdan geldi · 2 elle yüklendi
  kaynak         smallint     not null default 1,
  cihaz_id       integer references public.cihaz(id),
  cihaz_mesaj_id bigint,
  -- Hastanın raporuna basılsın mı: ham kalibrasyon eğrisi laboratuvarın iç
  --   kaydıdır, protein elektroforezi ise raporun parçasıdır.
  raporda        smallint     not null default 1,
  sira           smallint     not null default 0,
  aciklama       varchar(300) not null default '',
  sube_id        integer      not null default 0,
  ekleyen        integer      not null default 0,
  ekleme_tarihi  timestamptz  not null default now(),
  -- BOŞ GRAFİK OLMAZ: ya görüntü ya seri.
  constraint ck_lab_grafik_icerik check (dokuman_id is not null or seri is not null),
  constraint ck_lab_grafik_tur    check (tur in (1, 2, 3, 4, 5, 9))
);

create index if not exists ix_lab_sonuc_grafik_satir
  on public.lab_sonuc_grafik (istem_satir_id, sira);
create index if not exists ix_lab_sonuc_grafik_sonuc
  on public.lab_sonuc_grafik (sonuc_id);

comment on table public.lab_sonuc_grafik is
  '892: grafik tipli sonuc (KTS L10). Goruntu dokuman deposunda, sayisal '
  'seri jsonb; raporda bayragi hastanin raporuna basilip basilmayacagini '
  'soyler.';

-- ------------------------------------------------------------- döküm ----
create or replace view public.v_lab_sonuc_grafik as
select g.id, g.istem_satir_id as satir_id, s.istem_id, i.istem_no,
       s.tetkik_id, s.kod, s.ad as tetkik,
       i.taraf_id as hasta_id, g.sonuc_id,
       g.tur, g.baslik, g.dokuman_id, d.content_type, d.boyut,
       (g.seri is not null) as seri_var, g.seri,
       g.birim_x, g.birim_y, g.kaynak, g.cihaz_id, coalesce(c.ad, '') as cihaz,
       g.raporda, g.sira, g.aciklama, g.ekleme_tarihi, g.ekleyen, g.sube_id
  from public.lab_sonuc_grafik g
  join public.lab_istem_satir s on s.id = g.istem_satir_id
  join public.lab_istem i on i.id = s.istem_id
  left join public.dokuman d on d.id = g.dokuman_id
  left join public.cihaz c on c.id = g.cihaz_id;

comment on view public.v_lab_sonuc_grafik is
  '892: grafik sonuclar - tetkik, istem, icerik tipi ve raporda bayragi.';

-- -------------------------------------------------------------- yetki ----
--  Grafik, sonucun parçasıdır: ayrı GÖRME yetkisi açmıyoruz (`lab.sonuc`
--  yeter; test bazlı kısıt 889 zaten sonucun kendisinde uygulanıyor).
--  Ayrı olan tek şey ELLE YÜKLEME: cihazdan gelmeyen bir eğriyi hasta
--  dosyasına koymak bilinçli bir işlemdir.
insert into public.yetki (kod, ad, grup, tur, sira, aktif, urun_modu, modul)
select 'lab.grafik.yukle', 'Grafik sonuç yükleme', 'Laboratuvar', 1, 54, 1, 2, 'lab'
 where not exists (select 1 from public.yetki y where y.kod = 'lab.grafik.yukle');

insert into public.rol_yetki (rol_id, yetki_id, gor, ekle, degistir, sil, ekleyen)
select r.id, y.id, 1, 1, 1, 1, 0
  from public.rol r cross join public.yetki y
 where r.kod = 'yonetici' and y.kod = 'lab.grafik.yukle'
   and not exists (select 1 from public.rol_yetki ry
                    where ry.rol_id = r.id and ry.yetki_id = y.id);
update public.rol set yetki_surumu = yetki_surumu + 1 where kod = 'yonetici';

