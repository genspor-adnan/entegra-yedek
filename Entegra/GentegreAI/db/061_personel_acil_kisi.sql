\set ON_ERROR_STOP on

create table if not exists public.personel_acil_kisi (
    id                  integer generated by default as identity primary key,
    taraf_id            integer not null references public.taraf(id) on delete cascade,
    varsayilan          smallint not null default 0,
    ad_soyad            character varying(120) not null default '',
    yakinlik            character varying(60) not null default '',
    telefon             character varying(30) not null default '',
    sira                smallint not null default 0,
    ekleyen             integer not null default 0,
    ekleme_tarihi       timestamp not null default now()::timestamp,
    degistiren          integer not null default 0,
    degistirme_tarihi   timestamp
);

create index if not exists ix_personel_acil_kisi_taraf
    on public.personel_acil_kisi (taraf_id, sira, id);

create unique index if not exists ux_personel_acil_kisi_varsayilan
    on public.personel_acil_kisi (taraf_id) where varsayilan = 1;

comment on table public.personel_acil_kisi is
  'Personel karti Iletisim sekmesi - acil durumda aranacak kisiler (Ad Soyad/Yakinlik/Telefon, 1:N).';
