-- =========================================================== kurallar ==
-- KALİBRASYON SONUCU CİHAZA İŞLENİR. İki yerde tutulup elle eşitlenseydi
--   "cihaz listesi uygun diyor, kayıt uygun değil diyor" durumu doğardı.
--   Uygunsuz sonuç cihazı KULLANIM DIŞI yapar (durum 3).
create or replace function public.fn_demirbas_kalibrasyon_isle()
returns trigger language plpgsql as $tg$
begin
    if new.tur <> 1 or new.sonuc = 0 then
        return new;
    end if;

    update public.demirbas d
       set son_kalibrasyon = new.tarih,
           kalibrasyon_gecerlilik = case when new.sonuc in (1, 3) then new.gecerlilik end,
           -- 3 = kullanim disi. Uygun sonucta cihaz kendiliginden "aktif"e
           --   DONMEZ: arizasi da olabilir - yalniz kalibrasyon yuzunden
           --   kapatilmissa acilir.
           durum = case when new.sonuc = 2 then 3
                        when d.durum = 3 then 1
                        else d.durum end
     where d.id = new.demirbas_id;
    return new;
end;
$tg$;

drop trigger if exists tg_demirbas_kalibrasyon_isle on public.demirbas_kalibrasyon;
create trigger tg_demirbas_kalibrasyon_isle
  after insert or update of sonuc, gecerlilik on public.demirbas_kalibrasyon
  for each row execute function public.fn_demirbas_kalibrasyon_isle();

-- Ölçüm noktası sınır dışıysa işaretle: iki yerde (ekran + sunucu)
--   hesaplanırsa "uygun" diyen ekranla "sınır dışı" diyen kayıt yan yana gelir.
create or replace function public.fn_demirbas_olcum_sonuc()
returns trigger language plpgsql as $tg$
begin
    if new.olculen is null then
        new.sonuc := 0;
    elsif (new.alt_sinir is not null and new.olculen < new.alt_sinir)
       or (new.ust_sinir is not null and new.olculen > new.ust_sinir) then
        new.sonuc := 2;
    elsif new.alt_sinir is null and new.ust_sinir is null then
        new.sonuc := coalesce(new.sonuc, 0);   -- sinir metinle verilmis
    else
        new.sonuc := 1;
    end if;
    return new;
end;
$tg$;

drop trigger if exists tg_demirbas_olcum_sonuc on public.demirbas_kalibrasyon_olcum;
create trigger tg_demirbas_olcum_sonuc
  before insert or update of olculen, alt_sinir, ust_sinir
  on public.demirbas_kalibrasyon_olcum
  for each row execute function public.fn_demirbas_olcum_sonuc();

-- =========================================================== görünüm ==
-- "HAZIR" = ARIZASIZ **VE** KALİBRASYONU GEÇERLİ. Çalışan ama kalibrasyonu
--   geçmiş cihaz sayıya girmez: ölçtüğü değere güvenilmiyor. Kullanılabilirlik
--   raporu ve pano aynı tanımı okusun diye tek görünüm.
create or replace view public.v_demirbas_durum as
select d.id, d.kod, d.ad, d.sube_id, d.departman_id, d.risk_sinifi,
       d.durum, d.yedek_havuz,
       d.kalibrasyon_gecerlilik, d.sonraki_bakim,
       (d.kalibrasyon_periyot_ay > 0
        and (d.kalibrasyon_gecerlilik is null
             or d.kalibrasyon_gecerlilik < current_date)) as kalibrasyon_gecmis,
       (d.bakim_periyot_ay > 0
        and (d.sonraki_bakim is null or d.sonraki_bakim < current_date)) as bakim_gecmis,
       exists (select 1 from public.demirbas_is_emri e
                where e.demirbas_id = d.id and e.tur = 2
                  and e.durum between 0 and 4) as arizali,
       (d.durum = 1
        and not exists (select 1 from public.demirbas_is_emri e
                         where e.demirbas_id = d.id and e.tur = 2
                           and e.durum between 0 and 4)
        and (d.kalibrasyon_periyot_ay = 0
             or (d.kalibrasyon_gecerlilik is not null
                 and d.kalibrasyon_gecerlilik >= current_date))) as hazir
  from public.demirbas d;

comment on view public.v_demirbas_durum is
  '723: "hazir" = arizasiz VE kalibrasyonu gecerli. Calisan ama kalibrasyonu '
  'gecmis cihaz kullanilabilirlik sayisina GIRMEZ.';

