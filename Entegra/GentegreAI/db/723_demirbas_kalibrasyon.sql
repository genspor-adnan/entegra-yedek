-- ============================================ kalibrasyon / güvenlik ==
create table if not exists public.demirbas_kalibrasyon (
  id            bigint generated by default as identity primary key,
  sube_id       integer not null default 0,
  demirbas_id   integer not null references public.demirbas(id) on delete cascade,
  kayit_no      varchar(30) not null default '',
  -- 1 kalibrasyon · 2 elektriksel güvenlik testi (IEC 62353) · 3 doğrulama
  tur           smallint not null default 1,
  tarih         date not null default current_date,
  -- AYAR ÖNCESİ / SONRASI: cihaz bozuksa NE KADAR SÜREDİR bozuk olduğunu
  --   ancak as-found ölçüm gösterir. Ayar yapıldıysa ikinci bir kayıt açılır
  --   ve `ayar_oncesi_id` ile buna bağlanır.
  ayar_sonrasi  smallint not null default 0,
  ayar_oncesi_id bigint references public.demirbas_kalibrasyon(id),
  -- 0 açık · 1 uygun · 2 uygun değil · 3 şartlı uygun
  sonuc         smallint not null default 0,
  gecerlilik    date,
  -- İÇ EKİP mi DIŞ FİRMA mı: ikisinin de yetki belgesi izlenir.
  yapan_id      integer references public.taraf(id),
  firma_id      integer references public.taraf(id),
  -- İZLENEBİLİRLİK: ölçen cihazın kendi kalibrasyonu geçerli olmalı, yoksa
  --   ölçüm bir sayıdır, delil değildir. Zincir ulusal standarda kadar gider.
  referans_cihaz varchar(120) not null default '',
  referans_seri  varchar(60) not null default '',
  referans_sertifika varchar(60) not null default '',
  referans_gecerlilik date,
  belirsizlik   numeric(12,4),
  belirsizlik_birim varchar(20) not null default '',
  ortam_sicaklik numeric(5,1),
  ortam_nem     numeric(5,1),
  -- UYGUNSUZ SONUÇTA ZORUNLU: cihaz ne zamandır sapıyordu, o sürede kaç
  --   hastada kullanıldı. Sistem yanıtı bilmez, sorunun sorulduğunu bilir.
  geriye_donuk_deger varchar(400) not null default '',
  aciklama      varchar(400) not null default '',
  ekleyen       integer not null default 0,
  ekleme_tarihi timestamptz not null default now(),
  degistiren    integer not null default 0,
  degistirme_tarihi timestamptz
);
create index if not exists ix_demirbas_kalib_cihaz
