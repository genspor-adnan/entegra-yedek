-- =====================================================================
--  723_demirbas_kalibrasyon.sql
--  BİYOMEDİKAL — cihaz künyesi, kalibrasyon, elektriksel güvenlik testi,
--  periyodik bakım, arıza iş emri, zimmet hareketi ve belgeler.
--
--  Mockup'lar: `Ekranlar/Demirbas/*.html`.
--
--  TEMEL KARAR — YENİ CİHAZ TABLOSU AÇILMADI. `demirbas` zaten var (kod, ad,
--    marka/model/seri, lokasyon, zimmet, alış, garanti). Eksik olan KLİNİK
--    MÜHENDİSLİK katmanıydı: risk sınıfı, periyotlar, kalibrasyon ve iş
--    emirleri. `demirbas` genişletiliyor, ikinci bir envanter açılmıyor -
--    iki envanter demek, sayımda hangisinin doğru olduğunu bilememek demek.
--
--  TEMEL KARAR — `cihaz` İLE KARIŞTIRILMADI. `cihaz` (432) bir ENTEGRASYON
--    ucudur: HL7/DICOM adresi, sürücüsü, portu olan bağlantı tanımı.
--    Biyomedikalin izlediği şey ise FİZİKSEL VARLIKTIR. Aynı analizör iki
--    kayıtta görünebilir; bağ `demirbas.cihaz_id` ile kurulur, tablolar
--    birleştirilmez.
--
--  TEMEL KARAR — BAKIM ve ARIZA TEK TABLO (`demirbas_is_emri`). İkisi de
--    "cihazda yapılan iş"tir: aynı duruş, aynı parça, aynı maliyet, aynı
--    geçmiş. Ayırsaydık cihazın hikâyesi ikiye bölünür ve "bu cihaz ne
--    sıklıkla bozuluyor" sorusu iki tablodan toplanırdı. Tür alanı ayırır.
--
--  TEMEL KARAR — KALİBRASYON ve EST AYNI TABLODA, AYRI TÜR. İkisi de
--    "ölçüm noktası + sınır + sonuç" yapısındadır; ayrı tablo iki kez aynı
--    ölçüm şemasını yazmak olurdu. Ama ayrı SORULARI yanıtlarlar: biri
--    "doğru ölçüyor mu", öteki "hastayı çarpar mı".
-- =====================================================================

