-- =====================================================================
--  882_bzbh_bildirim.sql
--  BİLDİRİMİ ZORUNLU BULAŞICI HASTALIK (BZBH) İŞ AKIŞI + 214 PAKETİ
--  (KTS denetim maddesi H5: "Bildirimi Zorunlu Bulaşıcı Hastalık (BZBH)
--   iş akışı doğru işliyor mu?" — eski denetimde **Hatalı**)
--
--  AKIŞ: hekim tanıyı koyar → tanı BZBH listesindeyse **bildirim taslağı**
--  kendiliğinden açılır → sorumlu hekim/enfeksiyon birimi vaka tipini ve
--  klinik belirti başlangıcını girip bildirimi tamamlar → **214 Bulaşıcı
--  Hastalık Bildirim** paketi üretilir ve USS kuyruğuna girer.
--
--  TASLAK KENDİLİĞİNDEN AÇILIR AMA KENDİLİĞİNDEN GÖNDERİLMEZ. 214'ün iki
--  zorunlu alanı (VAKA_TIPI ve KLINIK_BELIRTILERIN_BASLADIGI_TARIH) tanıdan
--  çıkarılamaz - şüpheli mi kesin mi olduğunu, belirtilerin ne zaman
--  başladığını hekim söyler. Otomatik gönderim, "kesin vaka" diye bildirilen
--  şüpheli vakalar üretirdi; bildirimi hiç açmamak ise denetimin tam da
--  bulduğu boşluktu. Ortası: kayıt açılır, ekranda bekler, süresi işler.
--
--  HASTALIK LİSTESİ KURUM TARAFINDAN DÜZENLENEBİLİR. Bakanlığın BZBH
--  tebliği (Grup A-D) zaman zaman değişiyor; listeyi koda gömmek her
--  değişiklikte yeni sürüm demekti. Tohum liste **çekirdek Grup A**
--  hastalıklarıdır ve `dogrulandi = 0` ile gelir: enfeksiyon kontrol
--  komitesi listeyi tebliğe göre gözden geçirip işaretler.
--
--  EŞLEŞME ICD ÖNEKİYLE: tek satır "A00" bütün kolera alt kodlarını
--  (A00.0, A00.1, A00.9) yakalar. Tam kod da yazılabilir; en UZUN eşleşen
--  önek kazanır - "A15" tüberküloz genel, "A15.0" akciğer tüberkülozu ayrı
--  bir satır olabilsin.
-- =====================================================================

