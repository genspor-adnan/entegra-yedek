-- ------------------------------------------------- eşleşme fonksiyonu ----
--  EN UZUN ÖNEK KAZANIR: "A15.0" satırı varsa akciğer tüberkülozu onun
--  kuralına, yoksa "A15"e düşer. Nokta ve büyük/küçük harf yok sayılır -
--  ICD kodu bazı kaynaklarda "A15.0", bazılarında "A150" yazılıyor.
create or replace function public.fn_bzbh_hastalik(p_icd varchar)
returns public.bzbh_hastalik language sql stable as $$
    select h.*
      from public.bzbh_hastalik h
     where h.aktif = 1
       and replace(upper(coalesce(p_icd, '')), '.', '')
           like replace(upper(h.icd_onek), '.', '') || '%'
     order by length(replace(h.icd_onek, '.', '')) desc
     limit 1;
$$;

comment on function public.fn_bzbh_hastalik(varchar) is
  '882: ICD kodundan BZBH hastaligini bulur (en uzun onek kazanir). '
  'Eslesme yoksa NULL - tani bildirimi zorunlu degil demektir.';

-- ------------------------------------------------------------ bildirim ----
create table if not exists public.bzbh_bildirim (
  id              bigint generated by default as identity primary key,
  sube_id         integer not null default 0,
  hasta_id        integer not null references public.taraf(id),
  muayene_id      integer references public.muayene(id),
  belge_id        integer references public.belge(id),
  hastalik_id     integer references public.bzbh_hastalik(id),
  icd_kod         varchar(10)  not null default '',
  hekim_id        integer references public.taraf(id),
  tani_zamani     timestamptz,
  -- 214'ÜN İKİ ZORUNLU ALANI: tanıdan çıkarılamaz, hekim girer.
  vaka_tipi       smallint,                        -- bzbh.vaka_tipi (SKRS)
  belirti_tarihi  date,
  durum           smallint not null default 0,     -- bzbh.durum
  bildirim_zamani timestamptz,
  paket_id        bigint,
  not_metin       varchar(400) not null default '',
  ekleyen         integer not null default 0,
  ekleme_tarihi   timestamptz not null default now(),
  degistiren      integer not null default 0,
  degistirme_tarihi timestamptz,
  constraint ck_bzbh_durum check (durum in (0, 1, 2)),
  -- AYNI MUAYENE + AYNI TANI ICIN TEK BILDIRIM: hekim muayeneyi iki kez
  --   tamamlarsa ikinci bir taslak acilmasin.
  constraint ux_bzbh_muayene_icd unique (muayene_id, icd_kod)
);

create index if not exists ix_bzbh_bildirim_durum on public.bzbh_bildirim (durum, id)
  where durum = 0;
create index if not exists ix_bzbh_bildirim_hasta on public.bzbh_bildirim (hasta_id, id desc);

comment on table public.bzbh_bildirim is
  '882: BZBH vaka bildirimi (KTS H5). Tani konunca TASLAK acilir (durum 0); '
  'vaka tipi ve belirti tarihi girilince 214 paketi uretilir.';

-- ------------------------------------------------------------ görünüm ----
create or replace view public.v_bzbh_bildirim as
select b.id,
       b.sube_id,
       b.hasta_id,
       t.unvan                            as hasta_adi,
       coalesce(t.vkno, '')               as hasta_kimlik,
       b.muayene_id,
       b.belge_id,
       b.hastalik_id,
       coalesce(h.ad, '')                 as hastalik_adi,
       coalesce(h.grup, 0)                as grup,
       coalesce(kg.ad, '')                as grup_adi,
       coalesce(h.sure_saat, 24)          as sure_saat,
       b.icd_kod,
       coalesce(i.ad, '')                 as icd_adi,
       b.hekim_id,
       coalesce(hk.unvan, '')             as hekim_adi,
       b.tani_zamani,
       b.vaka_tipi,
       coalesce(kv.ad, '')                as vaka_tipi_adi,
       b.belirti_tarihi,
       b.durum,
       coalesce(kd.ad, '')                as durum_adi,
       b.bildirim_zamani,
       b.paket_id,
       coalesce(p.paket_no, '')           as paket_no,
       b.not_metin,
       b.ekleme_tarihi,
       -- GECIKTI MI: Grup A'da 24 saat. Bildirilmis kayitta gecikme
       --   BILDIRIM ANINA gore, bekleyende SIMDIYE gore olculur.
       case when b.durum <> 0 then 0
            when b.tani_zamani is null then 0
            when now() > b.tani_zamani + make_interval(hours => coalesce(h.sure_saat, 24))
                 then 1 else 0 end::smallint as gecikti
  from public.bzbh_bildirim b
  join public.taraf t on t.id = b.hasta_id
  left join public.bzbh_hastalik h on h.id = b.hastalik_id
  left join public.icd i on i.kod = b.icd_kod
  left join public.taraf hk on hk.id = b.hekim_id
  left join public.enabiz_paket p on p.id = b.paket_id
  left join public.kod_liste lg on lg.kod = 'bzbh.grup'
  left join public.kod_deger kg on kg.liste_id = lg.id and kg.deger = coalesce(h.grup, 0)
  left join public.kod_liste lv on lv.kod = 'bzbh.vaka_tipi'
  left join public.kod_deger kv on kv.liste_id = lv.id and kv.deger = b.vaka_tipi
  left join public.kod_liste ld on ld.kod = 'bzbh.durum'
  left join public.kod_deger kd on kd.liste_id = ld.id and kd.deger = b.durum;

comment on view public.v_bzbh_bildirim is
  '882: BZBH bildirimi + hastalik/grup/vaka tipi adlari ve GECIKME bayragi.';

