                    where d.liste_id = l.id and d.deger = v.deger);

-- ------------------------------------------------- hastalık tanım listesi ----
create table if not exists public.bzbh_hastalik (
  id            integer generated by default as identity primary key,
  ad            varchar(120) not null,
  -- ICD ÖNEKİ: "A00" tüm alt kodları, "A15.0" tek kodu yakalar.
  icd_onek      varchar(10)  not null,
  grup          smallint     not null default 1,      -- bzbh.grup
  -- BİLDİRİM SÜRESİ: Grup A ivedi (24 saat), ötekiler haftalık/aylık.
  --   Ekran gecikeni bu süreden hesaplar.
  sure_saat     smallint     not null default 24,
  -- KURUM DOĞRULADI MI: tohum liste tebliğe göre gözden geçirilsin.
  dogrulandi    smallint     not null default 0,
  aciklama      varchar(300) not null default '',
  aktif         smallint     not null default 1,
  ekleyen       integer      not null default 0,
  ekleme_tarihi timestamptz  not null default now(),
  degistiren    integer      not null default 0,
  degistirme_tarihi timestamptz,
  constraint ux_bzbh_hastalik_onek unique (icd_onek)
);

