-- 700: YATAK / REFAKAT ÜCRETİ GÜN SONU TAHAKKUKU.
--
-- TEMEL KARAR — TAHAKKUK AYRI BİR KAYITTIR, fatura satırı değil.
--   Yatak ücreti hasta yatarken GÜN GÜN doğar; fatura ise çıkışta (ya da
--   dönem sonunda) kesilir. Doğrudan belge satırı yazsaydık, açık bir belgeyi
--   her gece büyütmemiz ve fatura kesildikten sonra doğan günü nereye
--   yazacağımızı bilememiz gerekirdi. Tahakkuk kaydı "bu gün şu ücreti
--   doğurdu" der; faturalama onu okur ve `belge_satir_id` ile işaretler.
--
-- TEMEL KARAR — ÜCRET YATAK HAREKETİNDEN ÇIKAR (`yatis_yatak`), yatışın
--   güncel yatağından değil: altı günlük yatışta üç farklı oda olabiliyor ve
--   her odanın ücret sınıfı farklı. Güncel yataktan hesaplasaydık, yoğun
--   bakımda geçen iki gün de son odanın fiyatından faturalanırdı.
--
-- TEMEL KARAR — GÜN BÖLÜNMEZ: hareket saatinden itibaren yeni tarife işler ve
--   o gün hangi yatakta DAHA UZUN kalındıysa o günün ücreti odur. Saat
--   bazında bölmek, SUT'un gün üzerinden çalışan yatak ücretiyle
--   uyuşmuyor ve iki kurum arasında uzlaşılamayan kuruşlar üretiyor.
--
-- TEMEL KARAR — AYNI GÜN İKİ KEZ TAHAKKUK ETMEZ: (yatış, tarih, kaynak)
--   benzersiz. Gece işi iki kez çalışsa da ücret bir kez doğar; "mükerrer
--   yatak ücreti" yatan hasta faturasının en sık hatasıdır.

create table if not exists public.yatis_tahakkuk (
  id            bigint generated by default as identity primary key,
  sube_id       integer not null default 0,
  yatis_id      integer not null references public.yatis(id) on delete cascade,
  tarih         date not null,
  -- 1 yatak · 2 refakatçi (ileride: 3 paket farkı ...).
  kaynak        smallint not null default 1,
  yatak_id      integer references public.yatak(id),
  hizmet_id     integer references public.hizmet(id),
  aciklama      varchar(200) not null default '',
  adet          numeric(10,2) not null default 1,
  birim_fiyat   numeric(14,4) not null default 0,
  tutar         numeric(14,2) not null default 0,
  -- Faturalanınca dolar: tahakkuk SİLİNMEZ, işaretlenir. Silinseydi "bu gün
  --   neden faturalandı" sorusunun dayanağı kaybolurdu.
  belge_satir_id bigint,
  ekleyen       integer not null default 0,
  ekleme_tarihi timestamptz not null default now(),
  degistiren    integer not null default 0,
  degistirme_tarihi timestamptz
);

create unique index if not exists ux_yatis_tahakkuk_gun
  on public.yatis_tahakkuk (yatis_id, tarih, kaynak);
create index if not exists ix_yatis_tahakkuk_fatura
  on public.yatis_tahakkuk (yatis_id) where belge_satir_id is null;

comment on table public.yatis_tahakkuk is
  'Gün sonu yatak/refakat tahakkuku (700). Fatura satırı DEĞİL: ücret gün gün '
  'doğar, fatura çıkışta kesilir. Faturalanınca belge_satir_id ile işaretlenir.';

-- ====================================================== gün sonu işi ==
-- O GÜN HANGİ YATAKTA DAHA UZUN KALINDIYSA o yatağın ücreti yazılır (gün
--   bölünmez). Ücret odanın `ucret_hizmet_id` hizmetinden ve hastanın fiyat
--   kuralından gelir - fiyat listesi zinciri tek yerde (fn_belge_kalem_fiyati),
--   ikinci bir fiyat yolu açmak iki farklı tutar üretmenin en kısa yoludur.
create or replace function public.fn_yatak_ucreti_tahakkuk(
    p_tarih date default null
) returns table (yazilan integer, tutar numeric, aciklama text)
language plpgsql
as $$
declare
    v_gun   date := coalesce(p_tarih, (current_date - 1));
    v_yaz   integer := 0;
    v_top   numeric(14,2) := 0;
    r       record;
    v_fiyat numeric(14,4);
begin
    for r in
        -- O GÜN İÇİN yatakta geçen süreyi yatak bazında topla; en uzun kalınan
        --   yatak o günün ücretini belirler.
        select y.id            as yatis_id,
               y.sube_id,
               y.hasta_id,
               y.refakatci_ad,
               yy.yatak_id,
               o.ucret_hizmet_id,
               o.refakatci_alir,
               coalesce(o.kod, '') || '/' || coalesce(yk.kod, '') as yatak_ad,
               sum(least(coalesce(yy.bitis, now()), (v_gun + 1)::timestamptz)
                   - greatest(yy.baslangic, v_gun::timestamptz))   as sure,
               row_number() over (
                   partition by y.id
                   order by sum(least(coalesce(yy.bitis, now()), (v_gun + 1)::timestamptz)
                                - greatest(yy.baslangic, v_gun::timestamptz)) desc) as sira
          from public.yatis y
          join public.yatis_yatak yy on yy.yatis_id = y.id
          join public.yatak yk on yk.id = yy.yatak_id
          join public.oda o on o.id = yk.oda_id
         where yy.baslangic < (v_gun + 1)::timestamptz
           and coalesce(yy.bitis, now()) > v_gun::timestamptz
           -- İPTAL EDİLEN YATIŞ ÜCRET DOĞURMAZ.
           and y.durum <> 0
         group by y.id, y.sube_id, y.hasta_id, y.refakatci_ad, yy.yatak_id,
                  o.ucret_hizmet_id, o.refakatci_alir, o.kod, yk.kod
    loop
        if r.sira <> 1 then continue; end if;

        -- ÜCRET HİZMETİ TANIMSIZSA TAHAKKUK YAZILMAZ: sıfır tutarlı satır,
        --   "ücretlendirildi" izlenimi verip farkı gizlerdi. Kurum odanın
        --   hizmetini tanımlayana kadar eksik GÖRÜNMELİ.
        if r.ucret_hizmet_id is null then continue; end if;

        select f.fiyat into v_fiyat
          from public.fn_belge_kalem_fiyati(
                   r.hasta_id, 2::smallint, null, r.ucret_hizmet_id, v_gun) f
         limit 1;
        v_fiyat := coalesce(v_fiyat, 0);

        insert into public.yatis_tahakkuk
            (sube_id, yatis_id, tarih, kaynak, yatak_id, hizmet_id, aciklama,
             adet, birim_fiyat, tutar, ekleyen)
        values (r.sube_id, r.yatis_id, v_gun, 1, r.yatak_id, r.ucret_hizmet_id,
                'Yatak ücreti · ' || r.yatak_ad, 1, v_fiyat, v_fiyat, 0)
        on conflict (yatis_id, tarih, kaynak) do nothing;

        if found then
            v_yaz := v_yaz + 1;
            v_top := v_top + v_fiyat;
        end if;

        -- REFAKATÇİ ÜCRETİ AYRI SATIR: çoğu kurumda kapsam dışıdır ve hasta
        --   payına girer; yatak ücretiyle birleştirilseydi hastaya "oda
        --   farkı" diye anlatılamazdı.
        if coalesce(r.refakatci_alir, 0) = 1 and coalesce(r.refakatci_ad, '') <> '' then
            insert into public.yatis_tahakkuk
                (sube_id, yatis_id, tarih, kaynak, yatak_id, hizmet_id, aciklama,
                 adet, birim_fiyat, tutar, ekleyen)
            values (r.sube_id, r.yatis_id, v_gun, 2, r.yatak_id, null,
                    'Refakatçi · ' || r.refakatci_ad, 1, 0, 0, 0)
            on conflict (yatis_id, tarih, kaynak) do nothing;
        end if;
    end loop;

    yazilan  := v_yaz;
    tutar    := v_top;
    aciklama := v_gun::text || ': ' || v_yaz || ' yatak tahakkuku, toplam ' || v_top || ' TL.';
    return next;
end $$;

comment on function public.fn_yatak_ucreti_tahakkuk(date) is
  'Gün sonu yatak/refakat tahakkuku (700). O gün EN UZUN kalınan yatağın '
  'ücretini yazar; aynı gün ikinci kez tahakkuk etmez.';

