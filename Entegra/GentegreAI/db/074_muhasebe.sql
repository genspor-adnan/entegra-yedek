create index if not exists ix_muhasebe_fis_satir_fis   on public.muhasebe_fis_satir (fis_id, sira);
create index if not exists ix_muhasebe_fis_satir_hesap on public.muhasebe_fis_satir (hesap_plani_id, fis_id);
create index if not exists ix_muhasebe_fis_satir_taraf on public.muhasebe_fis_satir (taraf_id) where taraf_id is not null;

comment on table public.muhasebe_fis_satir is
  'Fis satiri. borc/alacak TL, doviz_* satirin kendi dovizinde - dovizli fis aktarimi (Logo/Mikro) icin ikisi de tasinir.';

-- ------------------------------------------------------ muhasebe_eslestirme ----
-- Bacak -> hesap plani cozumu icin KURAL tablosu (eski MUHASEBEKOD'un genellenmis
--   hali). Once dogrudan kolon (hesap.muh_hesap_id, masraf.muh_hesap_id ...)
--   denenir; cozulemezse bu kurallar oncelik sirasiyla uygulanir.
create table if not exists public.muhasebe_eslestirme (
    id                   integer generated by default as identity primary key,
    kural_turu           varchar(20)  not null,          -- hesap_turu | cari | cek_senet | kalem_varsayilan | tur | belge
    hesap_turu           varchar(1)   not null default '',
    yon                  smallint     not null default 0, -- cek_senet: 1 alinan 2 verilen | cari: 1 alici 2 satici 3 personel
    doviz_mi             smallint     not null default 0, -- 0 hepsi, 1 yalniz doviz, 2 yalniz TL
    kasa_islem_tur       smallint,
    rol                  varchar(12)  not null default '', -- sablondaki bacak rolu / belge rolu
    hesap_plani_id       integer      not null,
    oncelik              smallint     not null default 100,
    aktif                smallint     not null default 1,
    constraint fk_muhasebe_eslestirme_hesap foreign key (hesap_plani_id) references public.hesap_plani (id),
    constraint fk_muhasebe_eslestirme_tur   foreign key (kasa_islem_tur) references public.kasa_islem_turu (kod)
);

create index if not exists ix_muhasebe_eslestirme_arama
    on public.muhasebe_eslestirme (kural_turu, hesap_turu, yon, oncelik) where aktif = 1;

comment on table public.muhasebe_eslestirme is
  'Bacak -> hesap plani esleme kurallari (eski MUHASEBEKOD). Cozum sirasi: dogrudan kolon > cari > hesap_turu > tur+rol.';

