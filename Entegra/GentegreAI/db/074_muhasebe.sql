-- ust_id agacini koddan tureterek bagla (100 -> 10 -> 1)
update public.hesap_plani h
   set ust_id = u.id
  from public.hesap_plani u
 where h.ust_id is null
   and u.kod = case when position('.' in h.kod) > 0 then split_part(h.kod, '.', 1)
                    when length(h.kod) > 1 then left(h.kod, length(h.kod) - 1) end
   and u.id <> h.id;

