    merkez_id            integer,
    masraf_id            integer,
    hizmet_id            integer,
    mali_hareket_id      integer,                            -- bacak geri bagi
    aciklama             varchar(200) not null default '',
    constraint ck_muhasebe_fis_satir_yon check (borc = 0 or alacak = 0),
    constraint fk_muhasebe_fis_satir_fis    foreign key (fis_id)         references public.muhasebe_fis (id) on delete cascade,
    constraint fk_muhasebe_fis_satir_hesap  foreign key (hesap_plani_id) references public.hesap_plani (id),
    constraint fk_muhasebe_fis_satir_taraf  foreign key (taraf_id)       references public.taraf (id),
    constraint fk_muhasebe_fis_satir_proje  foreign key (proje_id)       references public.proje (id),
    constraint fk_muhasebe_fis_satir_merkez foreign key (merkez_id)      references public.masraf_merkezi (id),
    constraint fk_muhasebe_fis_satir_hareket foreign key (mali_hareket_id) references public.mali_hareket (id) on delete set null
