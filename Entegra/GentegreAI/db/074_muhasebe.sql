    id                   integer generated by default as identity primary key,
    fis_id               integer      not null,
    sira                 smallint     not null default 1,
    hesap_plani_id       integer      not null,
    borc                 numeric(19,4) not null default 0,   -- TL (yerel)
    alacak               numeric(19,4) not null default 0,
    doviz_cinsi          varchar(6)   not null default 'TL',
    doviz_borc           numeric(19,4) not null default 0,
    doviz_alacak         numeric(19,4) not null default 0,
