--  074_muhasebe.sql  —  hesap_plani (+seed), muhasebe_donem, muhasebe_fis,
--                       muhasebe_fis_satir, muhasebe_eslestirme (+seed),
--                       muh_hesap_id kolonlari
--
--  Eski sistemde muhasebe FISI HIC YOKTU: yalnizca bir hesap plani (HESAPPLANI),
--    kart bazli kod eslesmesi (MUHASEBEKOD) ve hicbir zaman yazilmayan bir
--    MUHAKTAR bayragi vardi; fis uretimi harici bir programa (G2LKS -> Logo/
--    Orka/Mikro) birakilmisti ve o kod bu depoda yok. Burada fis DAHILI uretilir;
--    disa aktarim (muhasebe_fis.disa_aktarim_*) bu tablodan beslenecek bir kanca.
--
--  KARAR K9: baslik basina TEK fis, kesinlestirmede, idempotent
--    (unique kaynak_tur+kaynak_id). Iptal = TERS FIS (silme yok) - donem kilidi
--    ve dis aktarim ters kayit ister.
-- ============================================================================
\set ON_ERROR_STOP on

-- ------------------------------------------------------------- hesap_plani ----
create table if not exists public.hesap_plani (
    id                   integer generated by default as identity primary key,
    kod                  varchar(20)  not null,
    ad                   varchar(150) not null,
    ust_id               integer,
    seviye               smallint     not null default 1,
    sinif                smallint     not null default 0,  -- 1 aktif, 2 pasif, 3 gelir, 4 gider, 5 maliyet, 6 nazim
    doviz_cinsi          varchar(6)   not null default 'TL',
    calisir_mi           smallint     not null default 0,  -- 1 = yaprak, fis satiri alabilir
    cari_alt_hesap       smallint     not null default 0,  -- 1 = taraf bazli alt hesap otomatik acilir (120/320)
    durum                smallint     not null default 1,
    ekleyen              integer      not null default 0,
    ekleme_tarihi        timestamp    not null default now()::timestamp,
    degistiren           integer      not null default 0,
    degistirme_tarihi    timestamp,
    constraint ux_hesap_plani_kod unique (kod),
    constraint fk_hesap_plani_ust foreign key (ust_id) references public.hesap_plani (id)
);

create index if not exists ix_hesap_plani_ust on public.hesap_plani (ust_id) where ust_id is not null;

comment on table public.hesap_plani is
  'Tek duzen hesap plani (eski HESAPPLANI). calisir_mi=1 olan YAPRAK hesaplar fis satiri alabilir; ara hesaplara kayit yasak.';
comment on column public.hesap_plani.cari_alt_hesap is
  '1 ise cari bazli alt hesap otomatik acilir: 120 -> 120.<taraf_id>. Tek duzen pratigi.';

-- ---------------------------------------------------------- muhasebe_donem ----
create table if not exists public.muhasebe_donem (
    id                   integer generated by default as identity primary key,
    yil                  smallint     not null,
    ay                   smallint     not null,
    baslangic            date         not null,
    bitis                date         not null,
    kilitli              smallint     not null default 0,
    kilitleyen           integer      not null default 0,
    kilit_tarihi         timestamp,
    constraint ux_muhasebe_donem unique (yil, ay)
);

comment on table public.muhasebe_donem is
  'Muhasebe donemleri. kilitli=1 olan doneme fis yazilamaz (fn_muhasebe_donem_kontrol).';

-- ------------------------------------------------------------ muhasebe_fis ----
create table if not exists public.muhasebe_fis (
    id                   integer generated by default as identity primary key,
    fis_no               varchar(30)  not null default '',
    fis_tarihi           date         not null,
    tur                  smallint     not null default 1,  -- 1 mahsup, 2 tahsil, 3 tediye, 4 acilis, 5 kapanis
    durum                smallint     not null default 1,  -- 1 kayitli, 2 ters fisle iptal edildi, 3 ters fis
    kaynak_tur           smallint     not null default 0,  -- 1 kasa_islem, 2 belge, 3 manuel, 4 degerleme, 5 kapatma
    kaynak_id            bigint       not null default 0,
    ters_fis_id          integer,
    donem_id             integer,
    toplam_borc          numeric(19,4) not null default 0,
    toplam_alacak        numeric(19,4) not null default 0,
    disa_aktarim_durum   smallint     not null default 0,  -- 0 aktarilmadi, 1 aktarildi, 2 hata
    disa_aktarim_ref     varchar(60)  not null default '',
    disa_aktarim_tarihi  timestamp,
    aciklama             varchar(200) not null default '',
    sube_id              integer      not null default 0,
    ekleyen              integer      not null default 0,
    ekleme_tarihi        timestamp    not null default now()::timestamp,
    degistiren           integer      not null default 0,
    degistirme_tarihi    timestamp,
    constraint fk_muhasebe_fis_ters  foreign key (ters_fis_id) references public.muhasebe_fis (id),
    constraint fk_muhasebe_fis_donem foreign key (donem_id)    references public.muhasebe_donem (id),
    constraint fk_muhasebe_fis_sube  foreign key (sube_id)     references public.sube (id)
);

-- IDEMPOTENCY: ayni kaynaktan (kasa_islem / belge) ikinci bir GECERLI fis olamaz.
create unique index if not exists ux_muhasebe_fis_kaynak
    on public.muhasebe_fis (kaynak_tur, kaynak_id)
    where durum = 1 and kaynak_tur in (1, 2, 5);
create unique index if not exists ux_muhasebe_fis_no
    on public.muhasebe_fis (fis_no) where fis_no <> '';
create index if not exists ix_muhasebe_fis_tarih on public.muhasebe_fis (fis_tarihi desc, id desc);

comment on table public.muhasebe_fis is
  'Muhasebe fisi basligi. kaynak_tur/kaynak_id ile uretildigi isleme baglidir; ayni kaynaktan ikinci gecerli fis unique index ile engellenir (idempotent fisleme).';

-- ------------------------------------------------------ muhasebe_fis_satir ----
