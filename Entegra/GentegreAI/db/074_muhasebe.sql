alter table public.taraf  add column if not exists muh_hesap_id integer;
alter table public.kasa_islem add column if not exists muhasebe_fis_id integer;

do $$
declare r record;
begin
    for r in select unnest(array['hesap','masraf','hizmet','taraf']) as t loop
        execute format('alter table public.%1$s drop constraint if exists fk_%1$s_muh_hesap', r.t);
        execute format('alter table public.%1$s add  constraint fk_%1$s_muh_hesap
                        foreign key (muh_hesap_id) references public.hesap_plani (id)', r.t);
    end loop;
end $$;

alter table public.kasa_islem drop constraint if exists fk_kasa_islem_fis;
alter table public.kasa_islem add  constraint fk_kasa_islem_fis
      foreign key (muhasebe_fis_id) references public.muhasebe_fis (id);

do $$
declare t text;
begin
    foreach t in array array['hesap_plani','muhasebe_fis'] loop
        execute format('drop trigger if exists trg_%1$s_degistirme on public.%1$s', t);
        execute format('create trigger trg_%1$s_degistirme before update on public.%1$s
                        for each row execute function public.fn_degistirme_tarihi()', t);
    end loop;
end $$;

-- --------------------------------------------------------- fis no ureteci ----
-- KARAR (kullanici): YILLIK TEK yevmiye sirasi - sube ayrimi yok, ay sifirlamasi yok.
create or replace function public.fn_muhasebe_fis_no_uret(p_yil integer, p_hane integer default 6)
returns text
language plpgsql
as $$
declare
    v_anahtar text := 'muhasebe_fis.fis_no|Y' || p_yil;
    v_no      bigint;
begin
    insert into public.belge_no_sayac (anahtar, tablo_adi, alan_adi, kapsam, son_no)
    values (v_anahtar, 'muhasebe_fis', 'fis_no', 'yevmiye ' || p_yil, 0)
    on conflict (anahtar) do nothing;

    select son_no into v_no from public.belge_no_sayac where anahtar = v_anahtar for update;
    v_no := coalesce(v_no, 0) + 1;
    update public.belge_no_sayac set son_no = v_no, guncelleme = now()::timestamp where anahtar = v_anahtar;

    return p_yil::text || '-' || lpad(v_no::text, p_hane, '0');
end $$;

comment on function public.fn_muhasebe_fis_no_uret(integer, integer) is
  'Yevmiye numarasi: yillik TEK seri (2026-000001). Bosluksuz - fn_belge_no_uret deseni.';

-- --------------------------------------------------- donem kilidi kontrolu ----
create or replace function public.fn_muhasebe_donem_kontrol(p_tarih date)
returns void
language plpgsql
as $$
declare v_kilitli smallint;
begin
    select d.kilitli into v_kilitli from public.muhasebe_donem d
     where d.yil = extract(year from p_tarih)::smallint
       and d.ay  = extract(month from p_tarih)::smallint;

    if coalesce(v_kilitli, 0) = 1 then
        raise exception 'Muhasebe donemi kilitli: % - bu tarihe fis yazilamaz.',
              to_char(p_tarih, 'MM.YYYY') using errcode = 'P0001';
    end if;
end $$;

