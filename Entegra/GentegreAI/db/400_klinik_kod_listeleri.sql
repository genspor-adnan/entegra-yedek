-- ---------------------------------------------------------------- ICD-10
-- Kendi tablosu: ~20 bin satır, ağaç (üst kod), ARAMA ile kullanılır.
create table if not exists public.icd (
    kod           varchar(12)  primary key,       -- 'A09', 'A09.0'
    ad            varchar(300) not null,
    ust_kod       varchar(12),                    -- 'A09' -> 'A00-A09' bloğu
    seviye        smallint     not null default 3, -- 1 bölüm · 2 blok · 3 tanı · 4 alt tanı
    -- Kullanım kısıtları (SKRS): cinsiyet/yaş kısıtı olan tanılar var.
    cinsiyet      smallint     not null default 0, -- 0 farketmez · 1 erkek · 2 kadın
    yas_alt       smallint,
    yas_ust       smallint,
    -- Kronik / bildirimi zorunlu / e-Nabız zorunlu gibi işaretler.
    bayraklar     jsonb        not null default '{}',
    aktif         smallint     not null default 1,
    kaynak_surum  varchar(20)  not null default '',
    guncelleme    timestamp    not null default now()
);

comment on table public.icd is
    'ICD-10 tanı kataloğu (400). SKRS senkronundan beslenir; kod_deger''e konmaz (20 bin satır).';

create index if not exists ix_icd_ad on public.icd(lower(ad));
create index if not exists ix_icd_ust on public.icd(ust_kod);

-- ---------------------------------------------------------------- ilaç
-- Barkod BİRİNCİL: reçete ve sarf barkoddan okunur.
create table if not exists public.ilac (
    id            integer      primary key generated by default as identity,
    barkod        varchar(20)  not null unique,
    atc_kod       varchar(20)  not null default '',
    ad            varchar(300) not null,
    etken_madde   varchar(300) not null default '',
    firma         varchar(200) not null default '',
    -- Reçete türü (SKRS): normal / kırmızı / yeşil / mor / turuncu
    recete_turu   smallint     not null default 0,
    -- Ödeme ve kullanım bilgileri
    aktif         smallint     not null default 1,
    esdeger_grup  varchar(20)  not null default '',
    birim         varchar(20)  not null default '',
    ambalaj       varchar(60)  not null default '',
    -- Stok kartıyla eşleşme (kurum kendi kartını açtıysa) - zorunlu değil.
    stok_id       integer      references public.stok(id),
    kaynak_surum  varchar(20)  not null default '',
    guncelleme    timestamp    not null default now()
);

comment on table public.ilac is
    'İlaç kataloğu (400): barkod birincil, ATC + etken madde + reçete türü. e-Reçete ve sarf bunu okur.';

create index if not exists ix_ilac_ad  on public.ilac(lower(ad));
create index if not exists ix_ilac_atc on public.ilac(atc_kod);
create index if not exists ix_ilac_etken on public.ilac(lower(etken_madde));

insert into public.kod_liste (kod, ad)
select 'ilac.recete_turu', 'Reçete Türü (SKRS)'
 where not exists (select 1 from public.kod_liste where kod = 'ilac.recete_turu');

insert into public.kod_deger (liste_id, deger, ad, sira)
select l.id, v.deger, v.ad, v.sira
  from public.kod_liste l,
       (values (0,'Normal',0), (1,'Kırmızı',1), (2,'Yeşil',2),
               (3,'Mor',3), (4,'Turuncu',4)) as v(deger, ad, sira)
 where l.kod = 'ilac.recete_turu'
   and not exists (select 1 from public.kod_deger d where d.liste_id = l.id and d.deger = v.deger);

-- ------------------------------------------------------- senkron izleme kaydı
-- Hangi katalog ne zaman, kaç satırla güncellendi: "ICD listesi eski mi"
-- sorusu tek yerden cevaplansın (SKRS senkronu bu satırı yazar).
create table if not exists public.katalog_senkron (
    kod           varchar(40) primary key,   -- 'icd' · 'ilac' · 'klinik' · 'brans'
    ad            varchar(120) not null default '',
    son_calisma   timestamp,
    son_surum     varchar(20)  not null default '',
    satir_sayisi  integer      not null default 0,
    sonuc         varchar(300) not null default '',
    basarili      smallint     not null default 0
);

insert into public.katalog_senkron (kod, ad)
select v.kod, v.ad
  from (values ('icd','ICD-10 Tanı'), ('ilac','İlaç (barkod)'),
               ('klinik','Klinik (SKRS)'), ('brans','Branş (SKRS)')) as v(kod, ad)
 where not exists (select 1 from public.katalog_senkron k where k.kod = v.kod);
