-- ============================================================================
--  400 - KLINIK KOD LISTELERI + ICD-10 / ILAC KATALOGU (Faz 0, ortak platform)
--
--  Yol haritası Faz 0: "Kod listeleri: ICD-10, ilaç (barkod), klinik,
--  muayene/vaka/kabul/çıkış türleri → SKRS senkronuna ekle (tablo hedefli)".
--
--  IKI FARKLI SEY, IKI FARKLI YER:
--    * KÜÇÜK kümeler (muayene türü, vaka türü, kabul/çıkış şekli) mevcut
--      kod_liste/kod_deger'e girer - combo malzemesi, on-yirmi satır.
--    * BÜYÜK kataloglar (ICD-10 ~ 20 bin, ilaç ~ 30 bin barkod) KENDI
--      TABLOSUNA girer. kod_deger'e doldurmak arama/indeks/senkron ihtiyacını
--      karşılamaz ve her combo çağrısını ağırlaştırır.
--
--  Her ikisi de SKRS'den beslenecek (mevcut entegrasyon kod senkronu);
--  bu göç yalnız HEDEFI açar, veriyi senkron doldurur.
-- ============================================================================

-- ------------------------------------------------------ küçük kümeler (combo)
insert into public.kod_liste (kod, ad)
select v.kod, v.ad
  from (values
    ('muayene.turu',      'Muayene Türü (SKRS)'),
    ('muayene.vaka_turu', 'Vaka Türü (SKRS)'),
    ('kabul.sekli',       'Hasta Kabul Şekli (SKRS)'),
    ('cikis.sekli',       'Çıkış Şekli (SKRS)'),
    ('klinik.kod',        'Klinik (SKRS)')
  ) as v(kod, ad)
 where not exists (select 1 from public.kod_liste l where l.kod = v.kod);

-- Başlangıç değerleri: SKRS senkronu gelene kadar ekranlar boş combo görmesin.
--   (Senkron aynı kodları getirince ad güncellenir, deger DEĞİŞMEZ.)
insert into public.kod_deger (liste_id, deger, ad, sira)
select l.id, v.deger, v.ad, v.sira
  from public.kod_liste l,
       (values (1,'İlk Muayene',1), (2,'Kontrol',2), (3,'Konsültasyon',3),
               (4,'Acil',4), (5,'Ön Değerlendirme',5)) as v(deger, ad, sira)
 where l.kod = 'muayene.turu'
   and not exists (select 1 from public.kod_deger d where d.liste_id = l.id and d.deger = v.deger);

insert into public.kod_deger (liste_id, deger, ad, sira)
