-- MÜKERRER AYIKLAMA: aynı kontrol numarası ikinci kez yazılamaz. Boş
--   kontrol numarası (çözümlenemeyen mesaj) bu kuralın dışında - onları
--   ayıklamak kontrol numarasıyla mümkün değil.
create unique index if not exists ux_telerad_gelen_kontrol
    on public.telerad_gelen (kontrol_no)
 where kontrol_no <> '';
create index if not exists ix_telerad_gelen_acc
    on public.telerad_gelen (accession_no) where accession_no <> '';
create index if not exists ix_telerad_gelen_durum
    on public.telerad_gelen (geldi_zamani desc) where durum in (0, 1, 4);

-- --------------------------------------------------------- eşleştirme ----
-- TEK KURAL (kılavuz § 5.2 mantığı): accession ZORUNLU, kimlik doğrulayıcı.
--   * accession + gönderen kurumun SKRS kodu eşleşiyorsa o istek,
--   * SKRS gelmediyse accession + hasta TCKN,
--   * yalnız accession eşleşiyorsa ve TEK aday varsa o istek.
--   Birden çok aday varsa HİÇBİRİ seçilmez: yanlış hastanın raporunu
--   yazmaktansa "eşleşmedi" demek yeğdir.
create or replace function public.fn_telerad_gelen_istek(
    p_accession text, p_skrs text, p_tckn text)
returns integer
language plpgsql stable as $$
declare v_id integer; v_sayi integer;
begin
    if btrim(coalesce(p_accession, '')) = '' then return null; end if;

    if coalesce(p_skrs, '') <> '' then
        select i.id into v_id
          from public.telerad_istek i
          join public.telerad_kurum k on k.id = i.kurum_id
         where i.dis_erisim_no = p_accession
           and (k.skrs_kodu = p_skrs or k.tesis_kodu = p_skrs)
         limit 1;
        if v_id is not null then return v_id; end if;
    end if;

    if coalesce(p_tckn, '') <> '' then
        select i.id into v_id
          from public.telerad_istek i
         where i.dis_erisim_no = p_accession
           and i.dis_hasta_kimlik = p_tckn
         limit 1;
        if v_id is not null then return v_id; end if;
    end if;

    select count(*), min(i.id) into v_sayi, v_id
      from public.telerad_istek i
     where i.dis_erisim_no = p_accession;
    return case when v_sayi = 1 then v_id else null end;
end $$;

comment on function public.fn_telerad_gelen_istek(text, text, text) is
  '817: gelen raporu isteğe bağlar - accession zorunlu, SKRS/TCKN doğrulayıcı. '
  'Birden çok aday varsa NULL (yanlış hastaya rapor yazmaktansa eşleşmesin).';

-- ------------------------------------------------------------- görünüm ----
create or replace view public.v_telerad_gelen as
select g.id,
       g.geldi_zamani,
       g.kontrol_no,
       g.accession_no,
       g.hasta_tckn,
       coalesce(i.istek_no, '')                       as istek_no,
       coalesce(tk.unvan, '')                         as kurum_adi,
       g.gonderen_skrs,
       case g.kaynak_tur when 1 then 'Bakanlık' when 2 then 'Kurum'
                         else 'Bilinmiyor' end        as kaynak_adi,
       g.kaynak_tur,
       g.radyolog_ad,
       g.radyolog_tckn,
       g.onay_zamani,
       g.durum,
       case g.durum when 0 then 'Çözümlenemedi' when 1 then 'Eşleşmedi'
                    when 2 then 'İşlendi'       when 3 then 'Mükerrer'
                    else 'Hata' end                   as durum_adi,
       g.hata_metni,
       g.kaynak_ip,
       g.istek_id,
       g.rapor_id,
       g.sube_id,
       -- Eşleşmeyen rapor KRİTİKTİR: karşı taraf raporu gönderdiğini sanıyor,
       --   bizde hiçbir işe oturmadı.
       case when g.durum in (0, 1, 4) then 'kritik'
            when g.durum = 3          then 'pasif'
            else '' end                                as satir_rengi
  from public.telerad_gelen g
  left join public.telerad_istek i on i.id = g.istek_id
  left join public.telerad_kurum k on k.id = i.kurum_id
  left join public.taraf tk on tk.id = k.taraf_id;

comment on view public.v_telerad_gelen is
  '817: gelen rapor listesi - eşleşmeyenler kırmızı.';

