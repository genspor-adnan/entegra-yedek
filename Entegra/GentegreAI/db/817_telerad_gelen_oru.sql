-- --------------------------------------------------------------- tablo ----
create table if not exists public.telerad_gelen (
    id              bigint      primary key generated by default as identity,
    -- MSH-10. Mükerrer gönderimin tek ayıklama yolu.
    kontrol_no      varchar(40) not null default '',
    geldi_zamani    timestamp   not null default now()::timestamp,
    kaynak_ip       varchar(45) not null default '',
    -- 1 Bakanlık · 2 karşı kurum · 0 bilinmiyor (SKRS kodu eşleşmedi)
    kaynak_tur      smallint    not null default 0,
    gonderen_skrs   varchar(10) not null default '',
    accession_no    varchar(40) not null default '',
    hasta_tckn      varchar(11) not null default '',
    radyolog_tckn   varchar(11) not null default '',
    radyolog_ad     varchar(120) not null default '',
    onay_zamani     timestamp,
    -- 0 çözümlenemedi · 1 eşleşmedi · 2 işlendi · 3 mükerrer · 4 hata
    durum           smallint    not null default 1,
    istek_id        integer     references public.telerad_istek(id) on delete set null,
    rapor_id        integer     references public.radyoloji_rapor(id) on delete set null,
    hata_metni      varchar(400) not null default '',
    ack_kodu        varchar(2)  not null default '',
    ham             text        not null default '',
    sube_id         integer     references public.sube(id),
    ekleme_tarihi   timestamptz not null default now(),
    islenme_zamani  timestamp,
    constraint ck_telerad_gelen_durum check (durum between 0 and 4)
);

