--  Rapor bize iki yönden gelebilir:
--    * BAKANLIK Teleradyoloji Sistemi - havuzdaki radyolog okudu (kılavuz
--      3.46 § 3.1.4.1: "Teleradyoloji üzerinden yazılan raporlar ORU^R01
--      mesajları ile hastanedeki HBYS'ye iletilir").
--    * KARŞI KURUM - bizim gönderdiğimiz işi (yon = 2) onlar raporladı.
--  Mesaj ikisinde de ORU^R01, eşleştirme ikisinde de accession. Bu yüzden
