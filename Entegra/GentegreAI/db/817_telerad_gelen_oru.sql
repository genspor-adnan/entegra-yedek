--  başarısızsa insan bakar, kayıt kaybolmaz - karşı taraf raporu bir kez
--  gönderir.
--
--  ============ MÜKERRER GÖNDERİM =====================================
--  Karşı sistem ACK'i alamadığını sanıp aynı raporu tekrar gönderiyor.
--  `kontrol_no` (MSH-10) benzersiz: ikinci mesaj "zaten alındı" diye geçilir
--  ve AA döner - yoksa aynı rapor iki kez yazılırdı.
-- ============================================================================
