-- =====================================================================
--  898_asi_modulu.sql
--  AŞI MODÜLÜ + USS 207 AŞI VERİ SETİ
--  (KTS denetim maddesi H10'un birinci parçası)
--
--  H10 altı USS paketi istiyor; 409 Radyoloji Sonuç 883'te yapılmıştı çünkü
--  kaynağı vardı (onaylı rapor). Kalan beşinin ortak sorunu paket değil,
--  KAYNAK VERİ: bizde aşı kaydı hiç yoktu (`isg_asi` yalnız işyeri
--  hekimliğinin tarama listesi - hasta bazlı uygulama kaydı değil).
--
--  BU DOSYA AŞI UYGULAMASINI KAYIT ALTINA ALIR ve 207 paketini bağlar.
--
--  ŞEMA REHBERDEN OKUNDU (rehber.enabiz.gov.tr → 207 → YAPI):
--    HASTA_TAKIP_BILGISI/SYSTakipNo (zorunlu)
--    ASI_VERI_SETI/ASI_BILGISI (tekrarlı grup)
--      IZLEMIN_YAPILDIGI_YER  zorunlu  SKRS c3eade04-4f91-5dab-e043-14031b0ac9f9
--      ASI                    zorunlu  SKRS c3dbbb53-3b59-06e1-e043-14031b0a9fe6
--      ASI_DOZU               zorunlu  SKRS da92a50e-b1a8-4e6a-be8c-2b6ca2c0a58b
--      ASI_BARKODU, ASI_SORGU_NUMARASI, ISLEM_YAPAN (TCKN),
--      ASININ_UYGULAMA_SEKLI  SKRS f20210e0-d780-4961-87eb-3323000b7dbb
--      ASININ_UYGULAMA_YERI   SKRS eb66330f-2b96-40a7-931e-fc9aed2b9409
--      ASI_ISLEM_TURU         SKRS 5fff8778-89a4-4045-b33e-a7ffe0de0179
--      ASI_OZEL_DURUM_NEDENI  SKRS 0a8f681f-4ed0-4830-9dc9-a0295686398b
--      BILGI_ALINAN_KISI_ADI_SOYADI, BILGI_ALINAN_KISI_TEL,
--      ASI_YAPILMA_ZAMANI
--
--  SKRS KOD LİSTELERİ TOHUMLANMAZ, GUID'LERİ TANIMLANIR. Aşı adlarını ve
--  kodlarını elle yazmak, Bakanlığın listesiyle bir gün uyuşmayan ikinci
--  bir liste üretirdi; listeler `skrs-ham` yoluyla çekilir. Bu dosya
--  listelerin KİMLİĞİNİ (guid) kurar, içeriğini değil.
--
--  PAKET, UYGULAMA KAYDEDİLİNCE DOĞAR ama gönderim kuyruğu 101/105 ile aynı
--  kuralı izler: SYSTakipNo yoksa paket üretilmez, bekler (877'de öğrenilen
--  ders - takip numarası içerik hash'ine girmediği için erken üretilen paket
--  hiç tamamlanmıyordu).
-- =====================================================================

-- --------------------------------------------------- SKRS kod listeleri ----
--  Yalnız KİMLİK: guid ve ad. Değerler SKRS'den çekilir.
insert into public.kod_liste (kod, ad, skrs_liste)
select v.kod, v.ad, v.guid
  from (values
    ('asi.asi',            'SKRS Aşı',                    'c3dbbb53-3b59-06e1-e043-14031b0a9fe6'),
    ('asi.doz',            'SKRS Aşı Dozu',               'da92a50e-b1a8-4e6a-be8c-2b6ca2c0a58b'),
    ('asi.uygulama_sekli', 'SKRS Aşı Uygulama Şekli',     'f20210e0-d780-4961-87eb-3323000b7dbb'),
    ('asi.uygulama_yeri',  'SKRS Aşı Uygulama Yeri',      'eb66330f-2b96-40a7-931e-fc9aed2b9409'),
    ('asi.islem_turu',     'SKRS Aşı İşlem Türü',         '5fff8778-89a4-4045-b33e-a7ffe0de0179'),
    ('asi.ozel_durum',     'SKRS Aşı Özel Durum Nedeni',  '0a8f681f-4ed0-4830-9dc9-a0295686398b'),
    ('asi.izlem_yeri',     'SKRS İzlemin Yapıldığı Yer',  'c3eade04-4f91-5dab-e043-14031b0ac9f9')
  ) as v(kod, ad, guid)
 where not exists (select 1 from public.kod_liste l where l.kod = v.kod);

-- ------------------------------------------------------------ katalog ----
create table if not exists public.asi (
  id            integer generated by default as identity primary key,
  kod           varchar(20)  not null,
  ad            varchar(160) not null,
  -- SKRS aşı kodu: paket bunu gönderir. Boşsa aşı e-Nabız'a GİDEMEZ ve
  --   uygulama ekranı bunu söyler - sessizce eksik paket üretmek yerine.
  skrs_kod      varchar(20)  not null default '',
  -- Şemadaki toplam doz sayısı (kızamık 2, hepatit B 3 ...). 0 = tek doz
  --   ya da şemasız (seyahat aşısı, kuduz profilaksisi kendi akışında).
  doz_sayisi    smallint     not null default 1,
  -- Varsayılan uygulama şekli / yeri (SKRS kodları) - kayıt ekranı bunlarla
  --   açılır, kullanıcı değiştirebilir.
  uygulama_sekli smallint,
  uygulama_yeri  smallint,
  -- Stok bağı: lot ve karekod buradan gelir (İTS bildirimleri stok tarafında).
  stok_id       integer references public.stok(id),
  aciklama      varchar(300) not null default '',
  aktif         smallint     not null default 1,
  sira          smallint     not null default 0,
  ekleyen       integer      not null default 0,
  ekleme_tarihi timestamptz  not null default now(),
  degistiren    integer      not null default 0,
  degistirme_tarihi timestamptz
);

create unique index if not exists ux_asi_kod on public.asi (upper(kod));

comment on table public.asi is
  '898: asi katalogu (KTS H10 / USS 207). skrs_kod bos ise asi e-Nabiz''a '
  'gonderilemez - ekran bunu soyler.';

-- -------------------------------------------------------- uygulama ----
create table if not exists public.asi_uygulama (
  id            integer generated by default as identity primary key,
  taraf_id      integer not null references public.taraf(id),
  belge_id      integer references public.belge(id),
  muayene_id    integer,
  asi_id        integer not null references public.asi(id),
  -- Kaçıncı doz: 207'de ASI_DOZU zorunlu ve SKRS kodludur.
  doz_no        smallint     not null default 1,
  lot           varchar(40)  not null default '',
  -- ASI_BARKODU: karekod/barkod - İTS ile aynı numara.
  barkod        varchar(60)  not null default '',
  uygulama_sekli smallint,
  uygulama_yeri  smallint,
  islem_turu     smallint,
  ozel_durum     smallint,
  izlem_yeri     smallint,
  uygulayan_id  integer,
  uygulama_zamani timestamptz not null default now(),
  -- Bilgi alınan kişi (çocukta veli): pakette ayrı iki öge.
  bilgi_alinan_ad  varchar(120) not null default '',
  bilgi_alinan_tel varchar(20)  not null default '',
  -- ASI_SORGU_NUMARASI: Bakanlık sorgu numarası (varsa).
  sorgu_no      varchar(40)  not null default '',
  aciklama      varchar(300) not null default '',
  -- 1 uygulandı · 0 iptal (kayıt SİLİNMEZ: uygulanmış aşı geri alınamaz,
  --   yanlış kayıt gerekçesiyle iptal edilir).
  durum         smallint     not null default 1,
  iptal_neden   varchar(200) not null default '',
  enabiz_durum  smallint     not null default 0,
  sube_id       integer      not null default 0,
  ekleyen       integer      not null default 0,
  ekleme_tarihi timestamptz  not null default now(),
  degistiren    integer      not null default 0,
  degistirme_tarihi timestamptz,
  constraint ck_asi_uygulama_doz check (doz_no > 0)
);

create index if not exists ix_asi_uygulama_hasta
  on public.asi_uygulama (taraf_id, uygulama_zamani desc);
create index if not exists ix_asi_uygulama_belge on public.asi_uygulama (belge_id);
-- AYNI DOZ İKİ KEZ YAZILMASIN: aynı hastaya aynı aşının aynı dozu tek kayıt.
--   İptal edilen kayıt sayılmaz - hatalı kayıt düzeltilebilmeli.
create unique index if not exists ux_asi_uygulama_doz
  on public.asi_uygulama (taraf_id, asi_id, doz_no) where durum = 1;

comment on table public.asi_uygulama is
  '898: hastaya uygulanan asi kaydi (KTS H10 / USS 207). Iptal kayit SILMEZ; '
  'ayni hastaya ayni asinin ayni dozu bir kez yazilir.';

-- -------------------------------------------------------------- döküm ----
create or replace view public.v_asi_uygulama as
select u.id, u.taraf_id, u.belge_id, u.muayene_id,
       coalesce(nullif(trim(h.ad || ' ' || h.soyad), ''), h.unvan) as hasta,
       h.vkno as kimlik_no,
       u.asi_id, a.kod as asi_kod, a.ad as asi, a.skrs_kod, a.doz_sayisi,
       u.doz_no, u.lot, u.barkod, u.uygulama_sekli, u.uygulama_yeri,
       u.islem_turu, u.ozel_durum, u.izlem_yeri,
       u.uygulayan_id, coalesce(p.unvan, '') as uygulayan, p.vkno as uygulayan_tckn,
       u.uygulama_zamani, u.bilgi_alinan_ad, u.bilgi_alinan_tel, u.sorgu_no,
       u.aciklama, u.durum, u.iptal_neden, u.enabiz_durum, u.sube_id,
       -- Şemaya göre kalan doz: "3 dozluk aşının 2. dozu" bilgisi ekranda
       --   ve hatırlatmada kullanılır.
       greatest(a.doz_sayisi - u.doz_no, 0) as kalan_doz
  from public.asi_uygulama u
  join public.asi a on a.id = u.asi_id
  left join public.taraf h on h.id = u.taraf_id
  left join public.taraf p on p.id = u.uygulayan_id;

comment on view public.v_asi_uygulama is
  '898: asi uygulamalari - hasta, asi, doz, lot ve SKRS kodlari (USS 207).';

-- SKRS KODU OLMAYAN AŞILAR: denetimde "neden gönderilmedi" sorusunun cevabı.
create or replace view public.v_asi_skrs_eksik as
select a.id, a.kod, a.ad,
       (select count(*) from public.asi_uygulama u
         where u.asi_id = a.id and u.durum = 1) as uygulama
  from public.asi a
 where a.aktif = 1 and coalesce(nullif(trim(a.skrs_kod), ''), '') = '';

comment on view public.v_asi_skrs_eksik is
  '898: SKRS kodu girilmemis asilar - bu asilarin uygulamalari USS 207 ile '
  'GONDERILEMEZ.';

-- --------------------------------------------------------- 207 paketi ----
insert into public.enabiz_paket_turu (kod, uss_paket_kodu, ad, zorunlu_alanlar, aktif)
select 'ASI', 207, 'Aşı Veri Seti',
       -- Rehberdeki zorunlu ögeler: takip no + izlem yeri + aşı + doz.
       '["SYSTakipNo","ASI_VERI_SETI/ASI_BILGISI[1]/IZLEMIN_YAPILDIGI_YER",
         "ASI_VERI_SETI/ASI_BILGISI[1]/ASI",
         "ASI_VERI_SETI/ASI_BILGISI[1]/ASI_DOZU"]'::jsonb,
       1
 where not exists (select 1 from public.enabiz_paket_turu t where t.kod = 'ASI');

-- -------------------------------------------------------------- yetki ----
insert into public.yetki (kod, ad, grup, tur, sira, aktif, urun_modu, modul)
select v.kod, v.ad, 'Klinik', v.tur, v.sira, 1, 2, 'asi'
  from (values
    ('asi',          'Aşı Uygulamaları', 0::smallint, 70::smallint),
    ('asi.katalog',  'Aşı kataloğu (tanım)', 0::smallint, 71::smallint),
    ('asi.iptal',    'Aşı kaydı iptali', 1::smallint, 72::smallint)
  ) as v(kod, ad, tur, sira)
 where not exists (select 1 from public.yetki y where y.kod = v.kod);

insert into public.rol_yetki (rol_id, yetki_id, gor, ekle, degistir, sil, ekleyen)
select r.id, y.id, 1, 1, 1, 1, 0
  from public.rol r cross join public.yetki y
 where r.kod = 'yonetici' and y.kod in ('asi', 'asi.katalog', 'asi.iptal')
   and not exists (select 1 from public.rol_yetki ry
                    where ry.rol_id = r.id and ry.yetki_id = y.id);
update public.rol set yetki_surumu = yetki_surumu + 1 where kod = 'yonetici';

do $$
