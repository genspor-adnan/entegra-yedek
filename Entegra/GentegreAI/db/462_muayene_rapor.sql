-- =====================================================================
-- 462 - MUAYENE RAPORU (istirahat / durum / ilaç kullanım)
--
-- Mockup `Ekranlar/Muayene/muayene_karti.html` "Rapor" sekmesinin karşılığı.
-- Rapor muayenenin ÇIKTISIDIR: hekimin verdiği istirahat, sağlık durumu ya da
-- ilaç kullanım raporu; e-Nabız'a ve SGK'ya giden ayrı bir kayıttır.
--
-- NEDEN AYRI TABLO: raporun kendi numarası, tarih ARALIĞI, onay/iptal durumu
-- ve e-Nabız gönderim izi var. Muayene kartına alan olarak eklenseydi bir
-- muayenede iki rapor (istirahat + ilaç kullanım) yazılamazdı; iptal edilen
-- raporun izi de kalmazdı.
--
-- İŞ GÜNÜ HESABI YOK: "kaç gün" hekimin yazdığıdır; hafta sonu/tatil kuralı
-- kuruma göre değişir ve burada varsayılan uydurmak yanlış rapor üretirdi.
-- =====================================================================

create table if not exists public.muayene_rapor (
    id            integer generated by default as identity primary key,
    muayene_id    integer     not null references public.muayene(id),
    hasta_id      integer     not null,
    hekim_id      integer,
    rapor_no      varchar(20) not null default '',
    -- 1 istirahat · 2 sağlık durumu · 3 ilaç kullanım · 4 iş göremezlik
    tur           smallint    not null default 1,
    baslangic     date,
    bitis         date,
    gun           smallint    not null default 0,
    aciklama      varchar(500) not null default '',
    icd_kod       varchar(10) not null default '',
    -- 0 iptal · 1 taslak · 2 onaylı
    durum         smallint    not null default 1,
    enabiz_durum  smallint    not null default 0,
    sube_id       integer     not null default 0,
    ekleyen       integer     not null default 0,
    ekleme_tarihi timestamp   not null default now(),
    degistiren    integer     not null default 0,
    degistirme_tarihi timestamp
);

create index if not exists ix_muayene_rapor_muayene
    on public.muayene_rapor (muayene_id);
create index if not exists ix_muayene_rapor_hasta
    on public.muayene_rapor (hasta_id, baslangic desc);

comment on table public.muayene_rapor is
    'Muayeneden cikan rapor: istirahat / durum / ilac kullanim (462).';

-- ---------------------------------------------------------------------
-- HASTA MUAYENEDEN GELİR: rapor hastaya bağlıdır ama hangi hasta olduğu
-- muayeneden bellidir - ekranda sorulacak bir şey değil, kullanıcı yanlış
-- hastayı seçebilirdi. Boş gelirse tetik doldurur.
-- ---------------------------------------------------------------------
create or replace function public.tg_muayene_rapor_hasta()
returns trigger language plpgsql as $$
begin
    if coalesce(new.hasta_id, 0) = 0 then
        select m.taraf_id into new.hasta_id
          from public.muayene m where m.id = new.muayene_id;
    end if;
    if coalesce(new.hekim_id, 0) = 0 then
        select m.personel_id into new.hekim_id
          from public.muayene m where m.id = new.muayene_id;
    end if;
    if coalesce(new.sube_id, 0) = 0 then
        select m.sube_id into new.sube_id
          from public.muayene m where m.id = new.muayene_id;
    end if;
    return new;
end $$;

drop trigger if exists tg_muayene_rapor_hasta on public.muayene_rapor;
create trigger tg_muayene_rapor_hasta
    before insert on public.muayene_rapor
    for each row execute function public.tg_muayene_rapor_hasta();

alter table public.muayene_rapor alter column hasta_id set default 0;
