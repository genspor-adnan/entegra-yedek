               ('ik.belge_takip.liste', 'Belge Takibi Listesi')) as v(kod, ad)
 where not exists (select 1 from public.yetki y where y.kod = v.kod);

insert into public.rol_yetki (rol_id, yetki_id, gor, ekle, degistir, sil, ekleyen)
select r.id, y.id, 1, case when y.kod like '%.liste' then 0 else 1 end,
       case when y.kod like '%.liste' then 0 else 1 end, case when y.kod like '%.liste' then 0 else 1 end, 0
  from public.rol r cross join public.yetki y
 where r.kod = 'yonetici' and y.kod in ('ik.belge_takip', 'ik.belge_takip.liste')
   and not exists (select 1 from public.rol_yetki ry where ry.rol_id = r.id and ry.yetki_id = y.id);
update public.rol set yetki_surumu = yetki_surumu + 1 where kod = 'yonetici';

-- ------------------------------------------------------------- tablolar --
create table if not exists public.personel_belge_turu (
    id                 integer generated by default as identity primary key,
    ad                 varchar(150) not null,
    grup               smallint     not null default 5,   -- 1 Kimlik / işe giriş · 2 Mesleki · 3 Sağlık / İSG · 4 İdari · 5 Diğer
    gecerlilik_ay      smallint,                          -- boş = süresiz
    hatirlat_gun       smallint     not null default 60,
    sira               smallint     not null default 0,
    aktif              smallint     not null default 1,
    aciklama           varchar(400) not null default '',
    sube_id            integer      not null default 0,   -- 0 = kurum geneli
    ekleyen            integer      not null default 0,
    ekleme_tarihi      timestamptz  not null default now(),
    degistiren         integer      not null default 0,
    degistirme_tarihi  timestamptz
);
comment on table public.personel_belge_turu is
  'Personel belge takibi (1135): özlük belge türü. gecerlilik_ay null = süresiz; hatirlat_gun = kaç gün önce "yaklaşıyor".';

create table if not exists public.personel_belge_kapsam (
    id                 integer generated by default as identity primary key,
    belge_turu_id      integer      not null references public.personel_belge_turu(id) on delete cascade,
    departman_id       integer      references public.departman(id),
    gorev_id           integer      references public.personel_gorev(id),
    ekleyen            integer      not null default 0,
    ekleme_tarihi      timestamptz  not null default now(),
    degistiren         integer      not null default 0,
    degistirme_tarihi  timestamptz
);
create index if not exists ix_personel_belge_kapsam_tur on public.personel_belge_kapsam (belge_turu_id);
comment on table public.personel_belge_kapsam is
  'Personel belge takibi (1135): türün zorunlu olduğu birim / görev. İkisi boş = tüm personel; türün satırı yoksa isteğe bağlı.';

create table if not exists public.personel_belge (
    id                 integer generated by default as identity primary key,
    taraf_id           integer      not null references public.taraf(id) on delete cascade,
    belge_turu_id      integer      not null references public.personel_belge_turu(id),
    belge_no           varchar(60)  not null default '',
    belge_tarihi       date,
    gecerlilik_tarihi  date,
    aciklama           varchar(400) not null default '',
    sube_id            integer      not null references public.sube(id),
    ekleyen            integer      not null default 0,
    ekleme_tarihi      timestamptz  not null default now(),
    degistiren         integer      not null default 0,
    degistirme_tarihi  timestamptz
);
create index if not exists ix_personel_belge_taraf on public.personel_belge (taraf_id, belge_turu_id);
comment on table public.personel_belge is
  'Personel belge takibi (1135): personelin elindeki belge. gecerlilik_tarihi boşsa belge_tarihi + tür geçerlilik ayı (tetik).';

do $$ begin
  if not exists (select 1 from pg_trigger where tgname = 'trg_personel_belge_turu_degistirme') then
    create trigger trg_personel_belge_turu_degistirme before update on public.personel_belge_turu
      for each row execute function public.fn_degistirme_tarihi();
  end if;
  if not exists (select 1 from pg_trigger where tgname = 'trg_personel_belge_degistirme') then
    create trigger trg_personel_belge_degistirme before update on public.personel_belge
      for each row execute function public.fn_degistirme_tarihi();
  end if;
end $$;

-- Geçerlilik tarihi boşsa türün süresinden hesaplanır (elle yazılan korunur).
create or replace function public.fn_personel_belge_gecerlilik()
returns trigger language plpgsql as $$
declare v_ay smallint;
begin
  if new.gecerlilik_tarihi is null and new.belge_tarihi is not null then
    select gecerlilik_ay into v_ay from public.personel_belge_turu where id = new.belge_turu_id;
    if v_ay is not null then
      new.gecerlilik_tarihi := (new.belge_tarihi + make_interval(months => v_ay))::date;
    end if;
  end if;
  return new;
end $$;
do $$ begin
  if not exists (select 1 from pg_trigger where tgname = 'trg_personel_belge_gecerlilik') then
    create trigger trg_personel_belge_gecerlilik before insert or update on public.personel_belge
      for each row execute function public.fn_personel_belge_gecerlilik();
  end if;
end $$;

-- ------------------------------------------------------------ görünümler --
create or replace view public.v_personel_belge_turu_lookup as
select id, ad, aktif from public.personel_belge_turu;

create or replace view public.v_personel_belge_durum as
with zorunlu as (
  select distinct t.id as personel_id, bt.id as belge_turu_id, 1::smallint as zorunlu
    from public.taraf t
    join public.personel_belge_kapsam k
      on (k.departman_id is null or k.departman_id = t.departman)
     and (k.gorev_id is null or k.gorev_id = t.gorev_id)
    join public.personel_belge_turu bt on bt.id = k.belge_turu_id and bt.aktif = 1
   where t.personel = 1 and t.durum = 1
), girilen as (
  select distinct b.taraf_id as personel_id, b.belge_turu_id, 0::smallint as zorunlu
    from public.personel_belge b
    join public.taraf t on t.id = b.taraf_id and t.personel = 1 and t.durum = 1
), hepsi as (
  select personel_id, belge_turu_id, max(zorunlu)::smallint as zorunlu
    from (select * from zorunlu union all select * from girilen) u
   group by personel_id, belge_turu_id
)
select row_number() over (order by h.personel_id, bt.grup, bt.sira, bt.ad)::integer as id,
       h.personel_id,
       public.fn_taraf_ad(t.unvan, t.ad, t.soyad)::varchar(120) as ad,
       t.departman::integer                                      as departman_id,
       coalesce(d.ad, '')::varchar(150)                          as birim,
       coalesce(g.ad, '')::varchar(150)                          as gorev,
       bt.id                                                     as belge_turu_id,
       bt.ad                                                     as belge,
       bt.grup,
       case bt.grup when 1 then 'Kimlik / işe giriş' when 2 then 'Mesleki' when 3 then 'Sağlık / İSG'
                    when 4 then 'İdari' else 'Diğer' end         as grup_adi,
       h.zorunlu,
       s.belge_tarihi,
       s.gecerlilik_tarihi,
       case when s.gecerlilik_tarihi is not null then (s.gecerlilik_tarihi - current_date) end as kalan_gun,
       x.durum::smallint                                         as durum,
       case x.durum when 1 then 'Eksik' when 2 then 'Süresi doldu' when 3 then 'Yaklaşıyor' else 'Tamam' end as durum_adi,
       t.sube_id
  from hepsi h
  join public.taraf t on t.id = h.personel_id
  join public.personel_belge_turu bt on bt.id = h.belge_turu_id
  left join public.departman d on d.id = t.departman
  left join public.personel_gorev g on g.id = t.gorev_id
  left join lateral (
        select b.belge_tarihi, b.gecerlilik_tarihi
          from public.personel_belge b
         where b.taraf_id = h.personel_id and b.belge_turu_id = h.belge_turu_id
         order by coalesce(b.gecerlilik_tarihi, 'infinity'::date) desc, b.belge_tarihi desc nulls last, b.id desc
         limit 1) s on true
  cross join lateral (
        select case when s.belge_tarihi is null and s.gecerlilik_tarihi is null then 1
                    when s.gecerlilik_tarihi is not null and s.gecerlilik_tarihi < current_date then 2
                    when s.gecerlilik_tarihi is not null and s.gecerlilik_tarihi < current_date + bt.hatirlat_gun then 3
                    else 4 end as durum) x;

-- İK takip listesi: personel başına tek satır (id = personel id -> çift tık personel kartı).
create or replace view public.v_personel_belge_ozet as
select x.personel_id                                              as id,
       max(x.ad)                                                  as ad,
       max(x.birim)                                               as birim,
       max(x.gorev)                                               as gorev,
       max(x.departman_id)                                        as departman_id,
       count(*) filter (where x.zorunlu = 1)::integer             as zorunlu,
       count(*) filter (where x.zorunlu = 1 and x.durum in (3, 4))::integer as tamam,
       count(*) filter (where x.zorunlu = 1 and x.durum = 1)::integer as eksik,
       count(*) filter (where x.durum = 2)::integer               as doldu,
       count(*) filter (where x.durum = 3)::integer               as yaklasan,
       case when count(*) filter (where x.zorunlu = 1) = 0 then 100
            else round(100.0 * count(*) filter (where x.zorunlu = 1 and x.durum in (3, 4))
                       / count(*) filter (where x.zorunlu = 1)) end::integer as tamamlanma,
       (array_agg(x.belge || ' - ' || x.durum_adi
                  || case when x.kalan_gun is not null and x.durum in (2, 3) then ' (' || x.kalan_gun || ' gün)' else '' end
                  order by x.durum, x.kalan_gun nulls first)
          filter (where x.durum in (1, 2, 3) and (x.zorunlu = 1 or x.durum in (2, 3))))[1]::varchar(250) as en_acil,
       max(x.sube_id)                                             as sube_id
  from public.v_personel_belge_durum x
 group by x.personel_id;

-- Tanım listesi: kapsam özeti + eksik sayısı.
create or replace view public.v_personel_belge_turu as
select bt.id, bt.ad, bt.grup,
       case bt.grup when 1 then 'Kimlik / işe giriş' when 2 then 'Mesleki' when 3 then 'Sağlık / İSG'
                    when 4 then 'İdari' else 'Diğer' end as grup_adi,
       bt.gecerlilik_ay,
       case when bt.gecerlilik_ay is null then 'Süresiz' else bt.gecerlilik_ay || ' ay' end as gecerlilik_adi,
       bt.hatirlat_gun, bt.sira, bt.aktif,
       case when bt.aktif = 1 then 'Aktif' else 'Pasif' end as aktif_adi,
       coalesce((select string_agg(case when k.departman_id is null and k.gorev_id is null then 'Tüm personel'
                                        else concat_ws(' / ', d.ad, g.ad) end, ', ')
                   from public.personel_belge_kapsam k
                   left join public.departman d on d.id = k.departman_id
                   left join public.personel_gorev g on g.id = k.gorev_id
                  where k.belge_turu_id = bt.id), 'İsteğe bağlı')::varchar(400) as kapsam,
       (select count(*) from public.v_personel_belge_durum x where x.belge_turu_id = bt.id and x.zorunlu = 1 and x.durum in (1, 2))::integer as eksik,
       bt.aciklama, bt.sube_id
  from public.personel_belge_turu bt;

