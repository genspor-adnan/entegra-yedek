--  1135  PERSONEL BELGE TAKİBİ (özlük dosyası: eksik / süresi dolan belge)
--
--  Kullanıcı (19.10.2026): "personel kartında eksik belgeleri ... takip etmek",
--  mockup Ekranlar/IK/personel_belge_takibi.html -> "personele belge takibini ekle".
--  Bu göç 1. aşama: özlük belgeleri. Vize başvurusu ayrı aşama.
--
--  TANIM: personel_belge_turu - belge adı, grup, geçerlilik (ay; boş = süresiz),
--    kaç gün önce uyarılacağı (hatirlat_gun). Kime ZORUNLU olduğu ayrı tabloda
--    (personel_belge_kapsam): satırda birim ve/veya görev; ikisi boş satır = tüm
--    personel. Kapsam satırı yoksa belge isteğe bağlıdır (kartta girilebilir,
--    eksik sayılmaz).
--  KAYIT: personel_belge - personel kartının "Belgeler" sekmesi. Geçerlilik
--    tarihi boş bırakılırsa belge tarihi + türün geçerlilik ayı (tetik).
--  DURUM: v_personel_belge_durum - aktif personel × kendisine zorunlu tür
--    (+ isteğe bağlı girilmiş belgeler); türün EN SON belgesi esas:
--      1 Eksik · 2 Süresi doldu · 3 Yaklaşıyor (hatirlat_gun içinde) · 4 Tamam.
--  Yetki ik.belge_takip (tanım kartı) + ik.belge_takip.liste (liste ekranı,
--    yalnız Gör - 1128 deseni). Personel kartındaki sekme personel yetkisinde.
--  Log: 1600 belge türü · 1601 kapsam · 1602 personel belgesi.
--  İdempotent.
-- =============================================================================

