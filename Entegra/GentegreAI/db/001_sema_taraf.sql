\set ON_ERROR_STOP on

-- ----------------------------------------------------------------- taraf ----
create table if not exists public.taraf (
    id                  integer generated by default as identity primary key,
    kod                 varchar(20),
    eski_tip            smallint     not null default 1,   -- GOC IZI: eski tek degerli tip (1 musteri 2 tedarikci 3 personel 4 kisi 9 diger)
    -- ROLLER 017_sema_sube_rol.sql'de eklenir: musteri / tedarikci / personel / kisi / hasta
    --   Bayraklar birbirini DISLAMAZ; olculdu: kartlarin ~%14'u hem musteri hem tedarikci.
    unvan               varchar(120) not null,             -- gorunen ad / kisa unvan
    fatura_unvan        varchar(200),                      -- belgeye yazilacak resmi unvan (bos ise unvan kullanilir)
    ad                  varchar(50),                       -- gercek kisi
    soyad               varchar(60),                       -- gercek kisi
    -- siniflandirma
    statu               smallint,
    grup                smallint,
    kategori            smallint,
    sinif               integer,
    durum               smallint     not null default 1,   -- 1 AKTIF, 0 pasif (GENINI -2708/-2201)
    sektor              smallint,
    alt_sektor          integer,
    bolge               smallint,
    alt_bolge           smallint,
    temsilci            integer,
    bag_id              integer,                           -- kisi/sube -> bagli oldugu taraf
    -- iletisim (eski REHBERBILGI YERI=1, varsayilan lokasyondan)
    telefon             varchar(30),
    cep_tel             varchar(30),
    eposta              varchar(120),
    eposta_web          varchar(200),   -- musteri/tedarikci: web adresi | kisi/personel: 2. e-posta
    -- mali kimlik (eski REHBERBILGI YERI=2)
    vkno                varchar(20),   -- musteri/tedarikci: vergi no | kisi/personel/hasta: TC no
    vd                  varchar(60),   -- musteri/tedarikci: vergi dairesi | personel/hasta: dogum yeri
    efatura             smallint     not null default 0,
    -- izin bayraklari (eski POSTA / EPOSTA bit kolonlari)
    posta_izin          smallint     not null default 0,
    eposta_izin         smallint     not null default 0,
    -- diger
    notlar              varchar(1000),
    ozel_kod            varchar(20),
    ozel                varchar(20),
    yetki_kodu          varchar(10),
    muh_kodu            varchar(20),
    muh_aktar           smallint,
    konum               varchar(50),
    peryot              smallint,
    giris_kaynak        smallint,
    d_tarih             timestamp,
    resim               bytea,
    -- kayit izleri
    sube_id             smallint,
    ekleyen             integer,
    ekleme_tarihi       timestamp    not null default now()::timestamp,
    degistiren          integer,
    degistirme_tarihi   timestamp,
    constraint fk_taraf_bag  foreign key (bag_id) references public.taraf (id)
);

create index if not exists ix_taraf_unvan_lower on public.taraf (lower(unvan));
create index if not exists ix_taraf_kod         on public.taraf (kod);
create index if not exists ix_taraf_vkno        on public.taraf (vkno)      where vkno is not null;
create index if not exists ix_taraf_bag         on public.taraf (bag_id)        where bag_id is not null;
create index if not exists ix_taraf_eposta      on public.taraf (lower(eposta)) where eposta is not null;

comment on table  public.taraf              is 'Musteri, tedarikci, personel ve kisi ana verisi (eski REHBER). UBL Party karsiligi.';
comment on column public.taraf.unvan        is 'Gorunen ad / kisa unvan. Listelerde ve arama sonucunda bu gosterilir.';
comment on column public.taraf.fatura_unvan is 'Belgeye yazilacak resmi unvan. Bos ise unvan kullanilir; belge yazilirken belge.taraf_unvan alanina KOPYALANIR.';
comment on column public.taraf.eposta_web   is 'Role gore iki anlamli: musteri/tedarikcide web adresi, kisi/personelde ikinci e-posta.';
comment on column public.taraf.vkno         is 'Role gore iki anlamli: musteri/tedarikcide VERGI NO, kisi/personel/hastada TC KIMLIK NO.';
comment on column public.taraf.vd           is 'Role gore iki anlamli: musteri/tedarikcide VERGI DAIRESI, personel/hastada DOGUM YERI.';
comment on column public.taraf.bag_id       is 'Ilgili kisi / sube kaydinin bagli oldugu taraf (eski REHBERILETISIM.REHBERID).';

-- ------------------------------------------------------------ taraf_adres ----
-- Bir kartin birden cok adresi olur: fatura, teslimat, merkez, sube/depo.
-- e-Belge alanlari (PartyAddress / DeliveryAddress) dogrudan buradan uretilir.
create table if not exists public.taraf_adres (
    id                  integer generated by default as identity primary key,
    taraf_id            integer     not null,
    tur                 smallint    not null,        -- 1 fatura 2 teslimat 3 merkez 4 sube/depo 9 diger
    baslik              varchar(60),
    adres               varchar(300),
    ilce                varchar(60),
    il                  varchar(60),
    ulke                varchar(60) not null default 'Turkiye',
    posta_kodu          varchar(10),
    yetkili             varchar(60),
    telefon             varchar(30),
    eposta              varchar(120),
    varsayilan          smallint    not null default 0,
    aktif               smallint    not null default 1,
    sube_id             smallint,
    ekleyen             integer,
    ekleme_tarihi       timestamp   not null default now()::timestamp,
    degistiren          integer,
    degistirme_tarihi   timestamp,
    constraint fk_taraf_adres_taraf foreign key (taraf_id)
        references public.taraf (id) on delete cascade,
    constraint ck_taraf_adres_tur check (tur in (1,2,3,4,9))
);

create index if not exists ix_taraf_adres_taraf on public.taraf_adres (taraf_id, tur);

-- Tur basina TEK varsayilan adres.
create unique index if not exists ux_taraf_adres_varsayilan
    on public.taraf_adres (taraf_id, tur) where varsayilan = 1;

comment on table public.taraf_adres is
  'Taraf adresleri. tur: 1 Fatura, 2 Teslimat/Sevk, 3 Merkez, 4 Sube/Depo, 9 Diger.';

