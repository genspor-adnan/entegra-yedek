-- ============================================================================
--  Gentegre AI — İSKONTO ONAYI
--  662_iskonto_onay.sql
--
--  Kullanıcı: "başvuruda ücret sekmesine 'İskonto Onayı' butonu ekle, basınca
--  işaretli işlemler için onay istesin, onaylayacak kişiye zil ikonu içinde
--  gelsin, onay/ret yapsın, onay olunca o iskonto oranı uygulansın ve satırlar
--  değişemesin."
--
--  AKIŞ:
--    kayıt kabul satırları seçer → talep (durum 0, bekliyor)
--    → yetkilinin zilinde görünür → onay / ret
--    → onayda oran satırlara YAZILIR ve satırlar KİLİTLENİR.
--
--  NEDEN AYRI TABLO: iskonto zaten `belge_satir.iskonto`da duruyor ama orada
--  yalnız SONUÇ var - kimin istediği, kimin onayladığı, ne kadarının
--  istenip ne kadarının verildiği yok. Para kararının izi tutulmadan onay
--  mekanizması kurmak, onayı bir tıklık formaliteye çevirirdi.
--
--  KISMİ ONAY BİRİNCİ SINIF: yetkili talebi DÜŞÜREREK onaylar (%20 istendi,
--  %10 verildi). Yalnız onay/ret bırakmak yetkiliyi "ya hep ya hiç"e zorlar;
--  gerçekte karar pazarlıktır (bkz. Ekranlar/Kayıt Kabul/iskonto_onay.html).
-- ============================================================================
\set ON_ERROR_STOP on

-- ---------------------------------------------------------------------------
--  1) TALEP BAŞLIĞI
-- ---------------------------------------------------------------------------
create table if not exists public.iskonto_talep (
    id                integer generated by default as identity primary key,
    belge_id          integer      not null,
    sube_id           integer,
    -- Talep edilen oran; satırların HEPSİNE aynı oran istenir (ekranda tek
    --   kutu). Kalem kalem farklı oran gerekirse ayrı talep açılır.
    oran              numeric(9,4) not null default 0,
    gerekce           varchar(300) not null default '',
    -- 0 bekliyor · 1 onaylandı · 2 reddedildi · 3 geri çekildi
    durum             smallint     not null default 0,
    isteyen_id        integer      not null,
    istek_ts          timestamp    not null default now()::timestamp,
    onay_id           integer,
    onay_ts           timestamp,
    -- Kısmi onayda talepten KÜÇÜK olabilir; ret ve bekleyende 0.
    onaylanan_oran    numeric(9,4) not null default 0,
    karar_notu        varchar(300) not null default '',
    ekleyen           integer      not null default 0,
    ekleme_tarihi     timestamp    not null default now()::timestamp,
    degistiren        integer      not null default 0,
    degistirme_tarihi timestamp,
    constraint fk_iskonto_talep_belge foreign key (belge_id)
        references public.belge (id) on delete cascade
);
create index if not exists ix_iskonto_talep_belge on public.iskonto_talep (belge_id);
-- BEKLEYENLER SORGUSU zilin her açılışında koşar: kısmi indeks dar kalsın.
create index if not exists ix_iskonto_talep_bekleyen
    on public.iskonto_talep (sube_id, istek_ts) where durum = 0;

comment on table public.iskonto_talep is
  'Basvuruda iskonto onay talebi (662): kim ne kadar istedi, kim ne kadar verdi.';

-- ---------------------------------------------------------------------------
--  2) TALEBİN SATIRLARI
--     Fiyat ve tutar TALEP ANINDAKİ haliyle saklanır: onay ertesi gün gelirse
--     yetkilinin gördüğü rakam, kararını verdiği rakam olmalı.
-- ---------------------------------------------------------------------------
create table if not exists public.iskonto_talep_satir (
    id                integer generated by default as identity primary key,
    talep_id          integer      not null,
    belge_satir_id    integer      not null,
    birim_fiyat       numeric(24,6) not null default 0,
    onceki_iskonto    numeric(9,4) not null default 0,
    constraint fk_iskonto_talep_satir_talep foreign key (talep_id)
        references public.iskonto_talep (id) on delete cascade,
    constraint fk_iskonto_talep_satir_satir foreign key (belge_satir_id)
        references public.belge_satir (id) on delete cascade
);
create unique index if not exists ux_iskonto_talep_satir
    on public.iskonto_talep_satir (talep_id, belge_satir_id);

-- ---------------------------------------------------------------------------
--  3) SATIR KİLİDİ
--     Onaylanan iskonto satırda DEĞİŞTİRİLEMEZ: onay o rakama verildi. Kilit
--     bir kolon, kural bir tetik - istemciye bırakılırsa ikinci bir ekran
--     (ya da API çağrısı) onayı sessizce ezerdi.
-- ---------------------------------------------------------------------------
alter table public.belge_satir
    add column if not exists iskonto_kilit smallint not null default 0;

comment on column public.belge_satir.iskonto_kilit is
  'Onaylanmis iskonto (662): 1 ise iskonto/birim fiyat degistirilemez.';

create or replace function public.tg_belge_satir_iskonto_kilit()
returns trigger language plpgsql as $$
begin
    if coalesce(old.iskonto_kilit, 0) = 1
       and coalesce(new.iskonto_kilit, 0) = 1
       and (coalesce(new.iskonto, 0)     is distinct from coalesce(old.iskonto, 0)
         or coalesce(new.iskonto2, 0)    is distinct from coalesce(old.iskonto2, 0)
         or coalesce(new.birim_fiyat, 0) is distinct from coalesce(old.birim_fiyat, 0))
    then
        raise exception 'Bu satırın iskontosu onaylanmıştır, değiştirilemez. '
                        'Değişiklik için yeni bir iskonto onayı alın.'
              using errcode = 'GK422';
    end if;
    return new;
end $$;

-- YALNIZ bu üç kolon korunur: miktar, KDV, açıklama serbest kalır - onay
--   iskontoya verildi, satırın tamamı dondurulmadı. Kilidi KALDIRMAK da
--   serbest (yeni talep ya da yetkili düzeltmesi), o yüzden koşul iki
--   tarafta da kilit = 1 arar.
drop trigger if exists tr_belge_satir_iskonto_kilit on public.belge_satir;
create trigger tr_belge_satir_iskonto_kilit
  before update on public.belge_satir
  for each row execute function public.tg_belge_satir_iskonto_kilit();

-- ---------------------------------------------------------------------------
--  4) KARAR: onay oranı satırlara işlenir ve satırlar kilitlenir.
--     Tek fonksiyon, çünkü "oranı yaz" ile "kilitle" ayrılamaz: biri olup
--     öteki olmazsa ya onaysız indirim ya kilitli yanlış rakam kalır.
-- ---------------------------------------------------------------------------
create or replace function public.fn_iskonto_talep_karar(
    p_talep_id integer,
    p_onay     smallint,          -- 1 onay · 2 ret
    p_oran     numeric,           -- onaylanan oran (kısmi onay); ret'te yok sayılır
    p_not      varchar,
    p_kullanici integer)
returns void language plpgsql as $$
declare
  v_durum smallint;
  v_oran  numeric(9,4);
begin
    select durum into v_durum from public.iskonto_talep where id = p_talep_id;
    if v_durum is null then
        raise exception 'İskonto talebi bulunamadı: %', p_talep_id using errcode = 'GK404';
    end if;
    if v_durum <> 0 then
        raise exception 'Talep zaten sonuçlanmış (durum %).', v_durum using errcode = 'GK422';
    end if;

    if p_onay = 2 then
        update public.iskonto_talep
           set durum = 2, onay_id = p_kullanici, onay_ts = now()::timestamp,
               onaylanan_oran = 0, karar_notu = coalesce(p_not, ''),
               degistiren = p_kullanici, degistirme_tarihi = now()::timestamp
         where id = p_talep_id;
        return;
    end if;

    -- ONAYLANAN ORAN talepten büyük OLAMAZ: yetkili indirimi artırmak
    --   isterse kendi talebini açar - istenmeyen bir indirimi "onay" diye
    --   yazmak, talebi belge olmaktan çıkarırdı.
    select least(coalesce(p_oran, 0), oran) into v_oran
      from public.iskonto_talep where id = p_talep_id;
    if not (v_oran > 0) then
        raise exception 'Onaylanan oran sıfırdan büyük olmalı.' using errcode = 'GK422';
    end if;

    -- Kilit ÖNCE kaldırılır: satır daha önce onaylıysa tetik yeni oranı
    --   reddederdi. Aynı deyimde iki kez update, çünkü tetik satır satır bakar.
    update public.belge_satir s
       set iskonto_kilit = 0
      from public.iskonto_talep_satir ts
     where ts.talep_id = p_talep_id and s.id = ts.belge_satir_id;

    update public.belge_satir s
       set iskonto = v_oran, iskonto2 = 0, iskonto_kilit = 1
      from public.iskonto_talep_satir ts
     where ts.talep_id = p_talep_id and s.id = ts.belge_satir_id;

    update public.iskonto_talep
       set durum = 1, onay_id = p_kullanici, onay_ts = now()::timestamp,
           onaylanan_oran = v_oran, karar_notu = coalesce(p_not, ''),
           degistiren = p_kullanici, degistirme_tarihi = now()::timestamp
     where id = p_talep_id;
end $$;

comment on function public.fn_iskonto_talep_karar is
  'Iskonto talebini onaylar (orani satirlara yazip kilitler) ya da reddeder (662).';

do $$
begin
    raise notice '662 tamam: iskonto_talep tablolari ve satir kilidi kuruldu.';
end $$;
