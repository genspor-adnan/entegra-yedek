-- ------------------------------------------------------------------ sayaç --
create table if not exists public.sevk_sayac (
    yil     smallint not null primary key,
    son_no  integer  not null default 0
);

-- fn_sevk_no() -> 'SV-2026-0001'
create or replace function public.fn_sevk_no()
returns varchar language plpgsql as $$
declare v_yil smallint := extract(year from current_date)::smallint; v_no integer;
begin
  insert into public.sevk_sayac (yil, son_no) values (v_yil, 1)
  on conflict (yil) do update set son_no = public.sevk_sayac.son_no + 1
  returning son_no into v_no;
  return 'SV-' || v_yil || '-' || lpad(v_no::text, 4, '0');
end $$;

-- ------------------------------------------------------------------ sevk --
create table if not exists public.sevk (
    id                 integer generated by default as identity primary key,
    no                 varchar(20)  not null default '',
    sube_id            integer      not null default 0,
    belge_id           integer      references public.belge(id),
    taraf_id           integer      not null references public.taraf(id),
    muayene_id         integer      references public.muayene(id),
    hekim_id           integer      references public.taraf(id),
    bolum_id           integer      references public.departman(id),
    sevk_zamani        timestamptz  not null default now(),
    tur                smallint     not null default 1,
    tesis_kodu         varchar(20)  not null default '',
    tesis_ad           varchar(160) not null default '',
    klinik_id          integer,
    hedef_bolum_id     integer      references public.departman(id),
    neden              smallint     not null default 1,
    ulasim             smallint     not null default 1,
    notu               varchar(500) not null default '',
    durum              smallint     not null default 1,
    imza_zamani        timestamptz,
    medula_sevk_no     varchar(30)  not null default '',
    sonuc_zamani       timestamptz,
    iptal_gerekce      varchar(400) not null default '',
    ekleyen            integer      not null default 0,
    ekleme_tarihi      timestamptz  not null default now(),
    degistiren         integer      not null default 0,
    degistirme_tarihi  timestamptz
);
create index if not exists ix_sevk_hekim   on public.sevk (hekim_id, durum);
create index if not exists ix_sevk_hedef   on public.sevk (hedef_bolum_id, durum) where hedef_bolum_id is not null;
create index if not exists ix_sevk_muayene on public.sevk (muayene_id);
comment on table public.sevk is
  '1110: sevk kaydı (kurum dışı / kurum içi / yatış). Muayenenin sevk kolonları gönderimde senkron yazılır.';

-- Numara + kart kapısı: kart yalnız taslağı yazar, durum geçişleri uçlarda.
create or replace function public.tg_sevk_kayit() returns trigger language plpgsql as $$
begin
  if tg_op = 'INSERT' and coalesce(new.no, '') = '' then
    new.no := public.fn_sevk_no();
  end if;
  if coalesce(current_setting('sevk.uc', true), '') <> '1' then
    if tg_op = 'INSERT' and new.durum <> 1 then
      raise exception 'Sevk taslak olarak açılır (gönder ucu kullanın).' using errcode = 'P0001';
    end if;
    if tg_op = 'UPDATE' and old.durum <> 1 then
      raise exception 'Gönderilmiş sevk değiştirilemez (iptal edip yeniden sevk edin).' using errcode = 'P0001';
    end if;
    if tg_op = 'UPDATE' and new.durum is distinct from old.durum then
      raise exception 'Sevk durumu bu ekrandan değiştirilemez (gönder / iptal kullanın).' using errcode = 'P0001';
    end if;
  end if;
  if tg_op = 'UPDATE' then new.degistirme_tarihi := now(); end if;
  return new;
end $$;
drop trigger if exists trg_sevk_kayit on public.sevk;
create trigger trg_sevk_kayit before insert or update on public.sevk
  for each row execute function public.tg_sevk_kayit();

-- --------------------------------------------------- eski sevkler (geriye dönük) --
--  1110 öncesi muayenede yazılmış sevk (yonlendirme 1/2/3): gönderilmiş sevk kaydı.
--  yonlendirme 1 kurum içi -> tur 2 · 2 kurum dışı -> tur 1 · 3 yatış önerisi -> tur 3.
--  ambulans 1 (112) -> ulasim 3 · 2 (kurum ambulansı) -> 2 · diğer -> 1 (kendi).
--  Tekrar çalışırsa çift satır açmaz.
do $$
declare v_n integer;
begin
  perform set_config('sevk.uc', '1', true);
  insert into public.sevk (sube_id, belge_id, taraf_id, muayene_id, hekim_id, bolum_id, sevk_zamani,
                           tur, tesis_kodu, klinik_id, neden, ulasim, notu, durum, imza_zamani, ekleyen)
  select m.sube_id, m.belge_id, m.taraf_id, m.id, m.personel_id, m.bolum_id, coalesce(m.tamamlanma, m.muayene_tarihi),
         case m.yonlendirme when 1 then 2 when 2 then 1 else 3 end,
         coalesce(m.sevk_tesis_kodu, ''),
         (select d.deger from public.kod_deger d join public.kod_liste l on l.id = d.liste_id
           where l.kod = 'klinik.kod' and d.dil = 0 and d.skrs_kod = m.sevk_klinik_kod and coalesce(m.sevk_klinik_kod, '') <> '' limit 1),
         case when coalesce(m.sevk_neden, 0) = 0 then 9 else m.sevk_neden end,
         case m.ambulans when 1 then 3 when 2 then 2 else 1 end,
         left(coalesce(m.sevk_notu, ''), 500), 2, coalesce(m.tamamlanma, m.muayene_tarihi), 0
    from public.muayene m
   where m.yonlendirme in (1, 2, 3)
     and not exists (select 1 from public.sevk s where s.muayene_id = m.id);
  get diagnostics v_n = row_count;
  raise notice '1110: geriye dönük % sevk kaydı', v_n;
end $$;

-- ---------------------------------------------------------------- yetki --
--  Menü kodu = yetki matrisi kodu (Muayene › Sevk Listesi). Muayene hakkı olan her
--  role aynı hak (sevk muayenenin parçası).
insert into public.yetki (kod, ad, grup, tur, sira, aktif, modul, urun_modu)
select 'muayene.sevk', 'Sevkler (Muayene)', 'Muayene', 0, 255, 1, 'muayene', 2
 where not exists (select 1 from public.yetki where kod = 'muayene.sevk');
insert into public.rol_yetki (rol_id, yetki_id, gor, ekle, degistir, sil, ekleyen)
select ry.rol_id, y.id, ry.gor, ry.ekle, ry.degistir, 0, 0
  from public.rol_yetki ry
  join public.yetki e on e.id = ry.yetki_id and e.kod = 'muayene'
  cross join public.yetki y
 where y.kod = 'muayene.sevk'
   and not exists (select 1 from public.rol_yetki x where x.rol_id = ry.rol_id and x.yetki_id = y.id);
update public.rol r set yetki_surumu = yetki_surumu + 1
 where exists (select 1 from public.rol_yetki ry join public.yetki y on y.id = ry.yetki_id
                where ry.rol_id = r.id and y.kod = 'muayene.sevk');

-- Kontrol
select (select count(*) from public.sevk) as sevk,
       (select count(*) from public.rol_yetki ry join public.yetki y on y.id = ry.yetki_id
         where y.kod = 'muayene.sevk') as rol_hakki;
