--
--  MUAYENEDEN BAGIMSIZ, KUMULATIF: tibbi gecmis hastanindir, tek bir
--  muayenenin degil. Muayene notlarindan okumaya calismak (ozgecmis_notu
--  serbest metin) "bu hastanin kronik tanilari neler" sorusunu her seferinde
--  yeniden okumak demekti - ve etkilesim/alerji kontrolu bunu yapamaz.
--
--  KRONIK TANI TETIKLE DUSER: muayenede "kronik" isaretlenen tani hastanin
--  ozetine kendiliginden islenir. Hekime "bir de tibbi ozete ekle" dedirtmek,
--  unutuldugunda bir sonraki hekimin eksik bilgiyle karar vermesi demekti.
