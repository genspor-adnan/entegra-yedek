create table if not exists public.hasta_kronik_tani (
    id             integer     primary key generated by default as identity,
    hasta_id       integer     not null references public.taraf(id) on delete cascade,
    icd_kod        varchar(10) not null,
    -- Ad KOPYA: katalog guncellenirse ozetteki metin degismesin.
    tani_ad        varchar(300) not null default '',
    baslangic      date,
    bitis          date,
    takip_hekim_id integer,
    -- 1 hekim (muayeneden) · 2 hasta beyani · 3 e-Nabiz · 4 dis kurum
    kaynak         smallint    not null default 1,
    kayit_muayene_id integer,
    -- 1 aktif · 2 kontrol altinda · 3 gecmis (remisyon)
    durum          smallint    not null default 1,
    not_metni      varchar(300) not null default '',
    ekleyen        integer     not null default 0,
    ekleme_tarihi  timestamp   not null default now(),
    degistiren     integer     not null default 0,
    degistirme_tarihi timestamp
);
create index if not exists ix_hasta_kronik_hasta
    on public.hasta_kronik_tani(hasta_id) where durum <> 3;
-- AYNI ICD IKI KEZ AKTIF OLMAZ: her muayenede tekrar isaretlenen kronik tani
--   ozeti coklardi ("Tip 2 DM" on kez).
create unique index if not exists ux_hasta_kronik_aktif
    on public.hasta_kronik_tani(hasta_id, icd_kod) where durum <> 3;

create table if not exists public.hasta_gecmis_olay (
    id            integer     primary key generated by default as identity,
    hasta_id      integer     not null references public.taraf(id) on delete cascade,
    -- 1 ameliyat · 2 girisim · 3 yatis · 4 asi · 5 travma · 6 transfuzyon
    tur           smallint    not null default 1,
    ad            varchar(200) not null default '',
    kod           varchar(20) not null default '',
    tarih         date,
    kurum         varchar(120) not null default '',
    not_metni     varchar(400) not null default '',
    kaynak        smallint    not null default 2,
    kayit_muayene_id integer,
    ekleyen       integer     not null default 0,
    ekleme_tarihi timestamp   not null default now(),
    degistiren    integer     not null default 0,
    degistirme_tarihi timestamp
);
create index if not exists ix_hasta_gecmis_olay_hasta
    on public.hasta_gecmis_olay(hasta_id, tarih desc);

create table if not exists public.hasta_aile_oykusu (
    id            integer     primary key generated by default as identity,
    hasta_id      integer     not null references public.taraf(id) on delete cascade,
    -- 1 anne · 2 baba · 3 kardes · 4 cocuk · 5 buyukanne/baba · 9 diger
    yakinlik      smallint    not null default 9,
    icd_kod       varchar(10) not null default '',
    hastalik      varchar(200) not null default '',
    baslangic_yas smallint,
    -- Vefat ve yasi: aile oykusunde "kac yasinda" risk hesabinin girdisidir.
    vefat         smallint    not null default 0,
    vefat_yas     smallint,
    not_metni     varchar(300) not null default '',
    kaynak        smallint    not null default 2,
    ekleyen       integer     not null default 0,
    ekleme_tarihi timestamp   not null default now(),
    degistiren    integer     not null default 0,
    degistirme_tarihi timestamp
);
create index if not exists ix_hasta_aile_hasta on public.hasta_aile_oykusu(hasta_id);

create table if not exists public.hasta_aliskanlik (
    id            integer     primary key generated by default as identity,
    hasta_id      integer     not null references public.taraf(id) on delete cascade,
    -- 1 sigara · 2 alkol · 3 madde · 4 egzersiz · 5 beslenme · 9 diger
    tur           smallint    not null default 1,
    -- 0 yok/hic · 1 kullaniyor · 2 birakmis
    durum         smallint    not null default 0,
    -- Sigarada paket-yil, alkolde haftalik birim, egzersizde haftalik dakika.
    miktar        numeric(9,2),
    birim         varchar(20) not null default '',
    baslangic_yil smallint,
    birakma_yil   smallint,
    not_metni     varchar(300) not null default '',
    kaynak        smallint    not null default 2,
    ekleyen       integer     not null default 0,
    ekleme_tarihi timestamp   not null default now(),
    degistiren    integer     not null default 0,
    degistirme_tarihi timestamp,
    -- Bir hastanin her aliskanlik turunden TEK kaydi olur; ikincisi
    --   "sigara iciyor mu" sorusunu iki cevapli yapardi.
    constraint ux_hasta_aliskanlik unique (hasta_id, tur)
);

-- ---------------------------------------------------------------------------
--  KRONİK TANI YANSIMASI
--
--  Muayenede "kronik" isaretlenen tani hastanin ozetine duser. Var olan kayit
--  GUNCELLENIR (baslangic tarihi korunur): hasta 2018'den beri diyabetliyse,
--  2026'daki muayene onu 2026 baslangicli yapmamali.
-- ---------------------------------------------------------------------------
create or replace function public.tg_tani_kronik_yansit()
returns trigger language plpgsql as $$
declare v_hasta integer; v_hekim integer; v_ad varchar(300);
begin
    if new.kronik <> 1 then return new; end if;

    select m.taraf_id, m.personel_id into v_hasta, v_hekim
      from public.muayene m where m.id = new.muayene_id;
    if v_hasta is null then return new; end if;

    select i.ad into v_ad from public.icd i where i.kod = new.icd_kod;

    insert into public.hasta_kronik_tani
           (hasta_id, icd_kod, tani_ad, baslangic, takip_hekim_id, kaynak,
            kayit_muayene_id, durum, ekleyen)
    values (v_hasta, new.icd_kod, coalesce(v_ad, ''),
            coalesce(new.baslangic_tarihi, current_date), v_hekim, 1,
            new.muayene_id, 1, new.ekleyen)
    on conflict (hasta_id, icd_kod) where durum <> 3
    do update set takip_hekim_id = coalesce(excluded.takip_hekim_id,
                                            public.hasta_kronik_tani.takip_hekim_id),
                  -- BASLANGIC KORUNUR: en eski tarih gecerli.
                  baslangic = least(public.hasta_kronik_tani.baslangic, excluded.baslangic),
                  degistirme_tarihi = now();
    return new;
end $$;

drop trigger if exists trg_tani_kronik_yansit on public.tani;
create trigger trg_tani_kronik_yansit
    after insert or update of kronik on public.tani
    for each row execute function public.tg_tani_kronik_yansit();

-- ---------------------------------------------------------------------------
--  TIBBİ ÖZET
--
--  Tek cagriyla ozet: muayene kartinin ust seridi ve Tibbi Ozet ekrani ayni
--  kaynagi okumali - iki ayri sorgu, iki farkli "aktif ilac" tanimi uretirdi.
-- ---------------------------------------------------------------------------
create or replace view public.v_hasta_tibbi_ozet as
    select t.id as hasta_id,
           (select count(*) from public.hasta_alerji a
             where a.hasta_id = t.id and a.aktif = 1) as alerji_sayisi,
           (select count(*) from public.hasta_alerji a
             where a.hasta_id = t.id and a.aktif = 1 and a.siddet >= 3) as agir_alerji,
           (select count(*) from public.hasta_kronik_tani k
             where k.hasta_id = t.id and k.durum <> 3) as kronik_sayisi,
           (select count(*) from public.hasta_ilac i
             where i.hasta_id = t.id and i.aktif = 1) as aktif_ilac,
           (select count(*) from public.hasta_gecmis_olay o
             where o.hasta_id = t.id) as gecmis_olay,
           (select string_agg(a.etken, ' · ' order by a.siddet desc, a.id)
              from public.hasta_alerji a
             where a.hasta_id = t.id and a.aktif = 1) as alerjiler,
           (select string_agg(coalesce(nullif(k.tani_ad, ''), k.icd_kod), ' · '
                              order by k.baslangic nulls last)
              from public.hasta_kronik_tani k
             where k.hasta_id = t.id and k.durum <> 3) as kronik_tanilar,
           (select max(m.muayene_tarihi) from public.muayene m
             where m.taraf_id = t.id) as son_muayene
      from public.taraf t
     where t.hasta = 1;

comment on view public.v_hasta_tibbi_ozet is
    'Hasta tibbi ozeti (420): muayene kartinin ust seridi ve Tibbi Ozet ekrani AYNI kaynagi okur.';
