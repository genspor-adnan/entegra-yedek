-- -------------------------------------------------------- gebelik dosyası ----
create table if not exists public.gebelik (
  id            integer generated by default as identity primary key,
  taraf_id      integer not null references public.taraf(id),
  -- Son adet tarihi: beklenen doğum ve gebelik haftası bundan hesaplanır.
  sat           date,
  -- SAT bilinmiyorsa (düzensiz adet, USG ile tarihlendirme) doğrudan
  --   beklenen doğum girilir - ikisinden biri olmadan hafta hesaplanamaz.
  beklenen_dogum date,
  gebelik_no    smallint     not null default 1,
  risk_durumu   smallint     not null default 0,   -- 0 normal · 1 riskli
  aciklama      varchar(400) not null default '',
  -- 1 devam ediyor · 2 sonuçlandı (224 ile kapanacak) · 0 iptal
  durum         smallint     not null default 1,
  sonuc_tarihi  date,
  sube_id       integer      not null default 0,
  ekleyen       integer      not null default 0,
  ekleme_tarihi timestamptz  not null default now(),
  degistiren    integer      not null default 0,
  degistirme_tarihi timestamptz,
  constraint ck_gebelik_tarih check (sat is not null or beklenen_dogum is not null)
);

create index if not exists ix_gebelik_taraf on public.gebelik (taraf_id, durum);
-- AYNI ANDA TEK AÇIK GEBELİK: iki açık dosya, izlemlerin hangisine ait
--   olduğunu belirsiz bırakırdı.
create unique index if not exists ux_gebelik_acik
  on public.gebelik (taraf_id) where durum = 1;

comment on table public.gebelik is
  '900: gebelik dosyasi (KTS H10). Izlem buna baglanir; 223/224 paketleri '
  'ayni dosya uzerine kurulacak. Ayni anda tek acik gebelik.';

/**
 * GEBELİK HAFTASI. SAT varsa ondan, yoksa beklenen doğumdan geriye sayarak
 * (280 gün / Naegele). İkisi de yoksa NULL - uydurma hafta, izlem takvimini
 * yanlış kurardı.
 */
create or replace function public.fn_gebelik_hafta(p_sat date,
                                                   p_beklenen date,
                                                   p_tarih date default current_date)
returns integer language sql immutable as $$
    select case
             when p_sat is not null then greatest(((p_tarih - p_sat) / 7)::int, 0)
             when p_beklenen is not null
                  then greatest((40 - ((p_beklenen - p_tarih) / 7))::int, 0)
             else null
           end;
$$;

comment on function public.fn_gebelik_hafta(date, date, date) is
  '900: gebelik haftasi - SAT varsa ondan, yoksa beklenen dogumdan (280 gun). '
  'Ikisi de yoksa NULL.';

-- ------------------------------------------------------------- izlem ----
create table if not exists public.gebe_izlem (
  id            integer generated by default as identity primary key,
  gebelik_id    integer not null references public.gebelik(id) on delete cascade,
  taraf_id      integer not null references public.taraf(id),
  belge_id      integer references public.belge(id),
  muayene_id    integer,
  kacinci_izlem smallint     not null,
  islem_turu    smallint,
  izlem_tarihi  timestamptz  not null default now(),
  -- 221'de KILO KİLOGRAM (209'daki gram tuzağı burada yok).
  boy_cm        numeric(6,2),
  kilo_kg       numeric(6,2),
  sistolik      smallint,
  diastolik     smallint,
  fetus_kalp_sesi smallint,
  hemoglobin    numeric(6,2),
  idrar_protein smallint,
  gdm           smallint,
  demir         smallint,
  d_vitamini    smallint,
  anomali       smallint,
  oneri         varchar(400) not null default '',
  aciklama      varchar(400) not null default '',
  durum         smallint     not null default 1,   -- 1 geçerli · 0 iptal
  iptal_neden   varchar(200) not null default '',
  enabiz_durum  smallint     not null default 0,
  sube_id       integer      not null default 0,
  ekleyen       integer      not null default 0,
  ekleme_tarihi timestamptz  not null default now(),
  degistiren    integer      not null default 0,
  degistirme_tarihi timestamptz,
  constraint ck_gebe_izlem_sira check (kacinci_izlem > 0)
);

create index if not exists ix_gebe_izlem_gebelik
  on public.gebe_izlem (gebelik_id, izlem_tarihi desc);
create unique index if not exists ux_gebe_izlem_sira
  on public.gebe_izlem (gebelik_id, kacinci_izlem) where durum = 1;

comment on table public.gebe_izlem is
  '900: gebe izlem kaydi (USS 221). KILO KILOGRAM - 209''daki gram cevrimi '
  'BURADA YOK.';

-- RİSK FAKTÖRLERİ TEKRARLI GRUPTUR: bir izlemde birden çok risk olabilir.
create table if not exists public.gebe_izlem_risk (
  id        integer generated by default as identity primary key,
  izlem_id  integer  not null references public.gebe_izlem(id) on delete cascade,
  risk      smallint not null,
  sira      smallint not null default 0
);

create unique index if not exists ux_gebe_izlem_risk
  on public.gebe_izlem_risk (izlem_id, risk);

comment on table public.gebe_izlem_risk is
  '900: izlemdeki risk faktorleri (221 tekrarli grubu). Bir izlemde ayni '
  'risk bir kez.';

-- -------------------------------------------------------------- döküm ----
create or replace view public.v_gebe_izlem as
select i.id, i.gebelik_id, i.taraf_id, i.belge_id, i.muayene_id,
       coalesce(nullif(trim(h.ad || ' ' || h.soyad), ''), h.unvan) as gebe,
       g.sat, g.beklenen_dogum, g.gebelik_no, g.risk_durumu,
       public.fn_gebelik_hafta(g.sat, g.beklenen_dogum, i.izlem_tarihi::date) as hafta,
       i.kacinci_izlem, i.islem_turu, i.izlem_tarihi,
       i.boy_cm, i.kilo_kg, i.sistolik, i.diastolik, i.fetus_kalp_sesi,
       i.hemoglobin, i.idrar_protein, i.gdm, i.demir, i.d_vitamini, i.anomali,
       i.oneri, i.aciklama, i.durum, i.iptal_neden, i.enabiz_durum, i.sube_id,
       (select count(*) from public.gebe_izlem_risk r where r.izlem_id = i.id) as risk_sayisi
  from public.gebe_izlem i
  join public.gebelik g on g.id = i.gebelik_id
  left join public.taraf h on h.id = i.taraf_id;

comment on view public.v_gebe_izlem is
  '900: gebe izlemleri - olcumler, gebelik haftasi ve risk sayisi.';

create or replace view public.v_gebelik as
select g.id, g.taraf_id,
       coalesce(nullif(trim(h.ad || ' ' || h.soyad), ''), h.unvan) as gebe,
       g.sat, g.beklenen_dogum,
       coalesce(g.beklenen_dogum, g.sat + 280) as tahmini_dogum,
       public.fn_gebelik_hafta(g.sat, g.beklenen_dogum) as hafta,
       g.gebelik_no, g.risk_durumu, g.durum, g.sonuc_tarihi, g.aciklama, g.sube_id,
       (select count(*) from public.gebe_izlem i
         where i.gebelik_id = g.id and i.durum = 1) as izlem_sayisi
  from public.gebelik g
  left join public.taraf h on h.id = g.taraf_id;

comment on view public.v_gebelik is
  '900: gebelik dosyalari - hafta, tahmini dogum ve izlem sayisi.';

