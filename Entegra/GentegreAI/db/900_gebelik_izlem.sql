--      IDRARDA_PROTEIN                 SKRS f3d218b5-1a31-4e67-a5f2-72f2d412a802
--      KONJENITAL_ANOMALI_VARLIGI      SKRS 484b2fc2-d1a2-4675-872e-c2c56e72d921
--      HEMOGLOBIN (decimal)
--      FETUS_KALP_SESI_BILGISI/FETUS_KALP_SESI (integer)
--      TANSIYON_BILGISI/SISTOLIK · DIASTOLIK (integer)
--      GEBELIKTE_RISK_FAKTORLERI_BILGISI[n]/GEBELIKTE_RISK_FAKTORLERI
--                                      TEKRARLI  SKRS ad9ae051-f75d-4180-b57f-38f45132a1b0
--      BOY_KILO_BILGILERI/BOY (cm) · KILO (decimal)
--
--  DİKKAT — 221'DE GEBELİK HAFTASI YOK. İzlem paketi yalnız izlemin
--  kendisini taşıyor; son adet tarihi ve beklenen doğum 223 Gebelik
--  Bildirim paketinin işi. Buna rağmen GEBELİK DOSYASI burada açılıyor:
--  izlem bir gebeliğe bağlı olmadan "kaçıncı izlem" sayılamaz, iki ayrı
--  gebeliğin izlemleri birbirine karışırdı. 223 ve 224 paketleri bu
--  dosyanın üzerine sonra bağlanacak.
--
--  KİLO BİRİMİ: 221'de KILO **decimal** (kilogram) - 209'daki gram tuzağı
