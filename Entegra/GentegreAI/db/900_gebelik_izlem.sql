--      IZLEM_ISLEM_TURU     zorunlu  SKRS 5fff8778-89a4-4045-b33e-a7ffe0de0179
--      DEMIR_LOJISTIGI_VE_DESTEGI      zorunlu SKRS 83c966d5-...
