begin;

create table if not exists public.kasa_gun_kapanis (
  id              integer generated by default as identity primary key,
  sube_id         integer      not null default 0,
  tarih           date         not null,
  -- 1 kapalı · 0 yeniden açıldı (satır silinmez: kim kapattı / kim açtı izi kalır)
  durum           smallint     not null default 1,
  kapatan_id      integer      not null default 0,
  kapanis_zamani  timestamptz  not null default now(),
  ozet            jsonb,
  acan_id         integer,
  acilis_zamani   timestamptz,
  acilis_gerekce  varchar(400) not null default '',
  constraint uq_kasa_gun_kapanis unique (sube_id, tarih),
  constraint ck_kasa_gun_kapanis_durum check (durum in (0, 1))
);
comment on table public.kasa_gun_kapanis is
  'Kasa gün sonu kilidi (1030): kapalı güne kasa_islem yazılamaz (fn_kasa_gun_kilidi).';

create table if not exists public.kasa_gun_sayim (
  id           integer generated by default as identity primary key,
  sube_id      integer       not null default 0,
  tarih        date          not null,
  hesap_id     integer       not null references public.hesap(id),
  sayilan      numeric(14,2) not null,
  aciklama     varchar(400)  not null default '',
  sayan_id     integer       not null default 0,
  sayim_zamani timestamptz   not null default now(),
  constraint uq_kasa_gun_sayim unique (sube_id, tarih, hesap_id)
);

create table if not exists public.pos_gun_sonu (
  id           integer generated by default as identity primary key,
  sube_id      integer       not null default 0,
  tarih        date          not null,
  hesap_id     integer       not null references public.hesap(id),
  adet         integer       not null default 0,
  tutar        numeric(14,2) not null,
  giren_id     integer       not null default 0,
  giris_zamani timestamptz   not null default now(),
  constraint uq_pos_gun_sonu unique (sube_id, tarih, hesap_id)
);

create table if not exists public.banka_gun_mutabakat (
  id           integer generated by default as identity primary key,
  sube_id      integer       not null default 0,
  tarih        date          not null,
  hesap_id     integer       not null references public.hesap(id),
  yatis        numeric(14,2),
  havale       numeric(14,2),
  giren_id     integer       not null default 0,
  giris_zamani timestamptz   not null default now(),
  constraint uq_banka_gun_mutabakat unique (sube_id, tarih, hesap_id)
);

create table if not exists public.kasa_gun_fark (
  id           integer generated by default as identity primary key,
  sube_id      integer       not null default 0,
  tarih        date          not null,
  -- kalem: 'kasa:<hesap>' · 'pos:<hesap>' · 'banka:<hesap>'
  kalem        varchar(40)   not null,
  fark         numeric(14,2) not null default 0,
  -- 1 para üstü · 2 sayım hatası · 3 tutar hatası · 4 mükerrer işlem ·
  -- 5 makbuz kesilmemiş · 6 provizyon iptali · 7 valör / zamanlama · 9 diğer
  neden        smallint      not null,
  aciklama     varchar(400)  not null default '',
  giren_id     integer       not null default 0,
  giris_zamani timestamptz   not null default now(),
  constraint uq_kasa_gun_fark unique (sube_id, tarih, kalem)
);

-- --------------------------------------------------------------- gün kilidi --
create or replace function public.fn_kasa_gun_kapali(p_sube integer, p_ts timestamptz)
returns boolean language sql stable as $f$
  select exists (select 1 from public.kasa_gun_kapanis k
                  where k.durum = 1
                    and k.tarih = (p_ts at time zone 'Europe/Istanbul')::date
                    and (k.sube_id = coalesce(p_sube, 0) or k.sube_id = 0));
$f$;

create or replace function public.fn_kasa_gun_kilidi() returns trigger language plpgsql as $f$
begin
  if tg_op in ('UPDATE', 'DELETE') and public.fn_kasa_gun_kapali(old.sube_id, old.islem_tarihi) then
    raise exception 'Kasa günü kapalı (%): bu güne ait kasa işlemi değiştirilemez. Gün Sonu ekranından yetkili kişi günü açmalı.',
      to_char((old.islem_tarihi at time zone 'Europe/Istanbul')::date, 'DD.MM.YYYY');
  end if;
  if tg_op in ('INSERT', 'UPDATE') and public.fn_kasa_gun_kapali(new.sube_id, new.islem_tarihi) then
    raise exception 'Kasa günü kapalı (%): bu güne kasa işlemi yazılamaz. Gün Sonu ekranından yetkili kişi günü açmalı.',
      to_char((new.islem_tarihi at time zone 'Europe/Istanbul')::date, 'DD.MM.YYYY');
  end if;
  return coalesce(new, old);
end $f$;

drop trigger if exists trg_kasa_gun_kilidi on public.kasa_islem;
create trigger trg_kasa_gun_kilidi before insert or update or delete on public.kasa_islem
  for each row execute function public.fn_kasa_gun_kilidi();

create temp table _bolme (yeni varchar(60), eski varchar(60), ad varchar(120),
                          grup varchar(40))
  on commit drop;

insert into _bolme values
  ('kasa.gun_sonu', 'kasa.finans', 'Kasa / Gün Sonu (Finans)', 'Finans');

do $$
declare n int;
begin
  select count(*) into n from _bolme b where not exists (select 1 from public.yetki y where y.kod = b.eski);
  if n > 0 then raise exception '1030: % satırın eski kodu yetki tablosunda yok', n; end if;
end $$;

insert into public.yetki (kod, ad, grup, tur, sira, urun_modu, modul)
select b.yeni, b.ad, b.grup, 0, ye.sira, ye.urun_modu, ye.modul
  from _bolme b
  join public.yetki ye on ye.kod = b.eski
on conflict (kod) do update
   set ad = excluded.ad, grup = excluded.grup, tur = 0, aktif = 1;

insert into public.rol_yetki (rol_id, yetki_id, gor, ekle, degistir, sil, deger, kapsam, ekleyen)
select ry.rol_id, yn.id, ry.gor, ry.ekle, ry.degistir, ry.sil, ry.deger, ry.kapsam, 0
  from _bolme b
  join public.yetki ye     on ye.kod = b.eski
  join public.yetki yn     on yn.kod = b.yeni
  join public.rol_yetki ry on ry.yetki_id = ye.id
on conflict (rol_id, yetki_id) do nothing;

update public.rol r set yetki_surumu = yetki_surumu + 1
 where exists (select 1 from public.rol_yetki ry
                 join public.yetki y on y.id = ry.yetki_id
                 join _bolme b on b.yeni = y.kod
                where ry.rol_id = r.id);

