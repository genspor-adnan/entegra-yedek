--  885_enabiz_ay_sonu.sql
--  408 AY SONU VERİ SETİ (KTS maddeleri H13 / D24'ün ikinci ayağı)
--
--  407 gün sonu TESİS TOPLAMINI gönderiyor; 408 ay sonu aynı ölçütleri
--  **KLİNİK (branş) KIRILIMIYLA** istiyor. Şema (rehber, 20.09.2026):
--
--    AY_SONU_VERI_SETI (zorunlu)
--      KAYIT_YERI            SKRS c3eade04-…            zorunlu
--      KALITE_YIL            integer                    zorunlu
--      KALITE_AY             integer                    zorunlu
--      KLINIK_KODU_KALITE_BILGISI (Grup, tekrarlı)
--        KLINIK_KODU         SKRS c04bee57-…            (branş kodu)
--        KLINIK_KALITE_BILGISI (Grup, ZORUNLU, tekrarlı)
--          KLINIK_KALITE_TANIM  SKRS 4fa9b630-…  (407 ile AYNI liste)
--          KLINIK_KALITE_SAYI   integer
--
--  ÖLÇÜT LİSTESİ 407 İLE ORTAK. Aynı tanım tablosu (`enabiz_gun_sonu_olcut`)
--  kullanılıyor - kurum bir ölçütü kapattığında hem günlük hem aylık
--  özetten düşsün. İki ayrı liste tutmak, birinde açık ötekinde kapalı
--  ölçütler bırakırdı.
--
--  KLİNİK KODU `departman.kod`'tan. 619/622 ile SKRS klinik kodları
--  departmanlara yazıldı; kodu OLMAYAN bölümün işi pakete GİRMEZ (kodsuz
--  gönderim USS'de "geçersiz klinik" ile döner). Kaç işin dışarıda kaldığı
--  ekranda görünür - eksikliğin sessiz kalması, ay sonu sayılarını sessizce
--  düşürürdü.
--
--  BRANŞ KIRILIMI OLMAYAN ÖLÇÜT AY SONUNDA GÖNDERİLMEZ. Radyoloji istemi
--  bizde bölüme bağlı değil (`radyoloji_istem`de bölüm kolonu yok); o
--  ölçütler 407'de tesis toplamı olarak gidiyor, 408'de uydurma bir branşa
--  yazılmıyor.
-- =====================================================================

create table if not exists public.enabiz_ay_sonu (
  id           bigint generated by default as identity primary key,
  sube_id      integer  not null default 0,
  yil          smallint not null,
  ay           smallint not null,
  durum        smallint not null default 0,     -- 0 hesaplandı · 1 paket üretildi
  paket_id     bigint,
  hesap_zamani timestamptz not null default now(),
  ekleyen      integer  not null default 0,
  degistiren   integer  not null default 0,
  degistirme_tarihi timestamptz,
  constraint ux_enabiz_ay_sonu unique (sube_id, yil, ay),
  constraint ck_enabiz_ay_sonu_ay check (ay between 1 and 12)
);

create table if not exists public.enabiz_ay_sonu_satir (
  id          bigint generated by default as identity primary key,
  ay_sonu_id  bigint      not null references public.enabiz_ay_sonu(id) on delete cascade,
  klinik_kodu varchar(20) not null,
  skrs_kod    smallint    not null,
  sayi        integer     not null default 0,
  constraint ux_enabiz_ay_sonu_satir unique (ay_sonu_id, klinik_kodu, skrs_kod)
);

comment on table public.enabiz_ay_sonu is
  '885: aylik ozet (408). Ayni sube+yil+ay icin tek satir; yeniden '
  'hesaplanirsa satirlari guncellenir.';
comment on column public.enabiz_ay_sonu_satir.klinik_kodu is
  'SKRS klinik (brans) kodu - departman.kod. Kodsuz bolumun isi pakete girmez.';

-- ------------------------------------------------------- sayım motoru ----
--  407'nin ölçütleri, KLİNİK kırılımıyla. Branş boyutu olmayan ölçütler
--  (radyoloji) burada üretilmez - uydurma branşa yazmak yerine hiç
--  gönderilmiyor.
create or replace function public.fn_enabiz_ay_sonu_sayilar(p_yil integer, p_ay integer,
                                                            p_sube integer default 0)
returns table(klinik_kodu varchar, skrs_kod smallint, ad varchar, sayi integer)
language sql stable as $$
    with bas as (select make_date(p_yil, p_ay, 1) as ilk,
                        (make_date(p_yil, p_ay, 1) + interval '1 month')::date as son),
    sayimlar as (
      -- 15 · 20: başvuru ve ayaktan hasta (başvurunun bölümü)
      select d.kod as klinik, 15::smallint as skrs, count(distinct b.id)::int as sayi
        from public.belge b
        join public.belge_basvuru bb on bb.id = b.id
        join public.departman d on d.id = bb.bolum_id
        cross join bas
       where b.tur = 19 and b.belge_tarihi >= bas.ilk and b.belge_tarihi < bas.son
         and (p_sube = 0 or b.sube_id = p_sube) and coalesce(d.kod, '') <> ''
       group by d.kod
      union all
      select d.kod, 20::smallint, count(distinct b.id)::int
        from public.belge b
        join public.belge_basvuru bb on bb.id = b.id
        join public.departman d on d.id = bb.bolum_id
        cross join bas
       where b.tur = 19 and b.belge_tarihi >= bas.ilk and b.belge_tarihi < bas.son
         and (p_sube = 0 or b.sube_id = p_sube) and coalesce(d.kod, '') <> ''
         and not exists (select 1 from public.yatis y where y.belge_id = b.id)
       group by d.kod
      union all
      -- 16: tanı bilgisi olan başvuru (muayenenin bölümü)
      select d.kod, 16::smallint, count(distinct m.belge_id)::int
        from public.muayene m
        join public.departman d on d.id = m.bolum_id
        join public.tani t on t.muayene_id = m.id
        cross join bas
       where coalesce(m.muayene_tarihi, m.baslangic) >= bas.ilk
         and coalesce(m.muayene_tarihi, m.baslangic) < bas.son
         and coalesce(t.icd_kod, '') <> '' and coalesce(d.kod, '') <> ''
         and (p_sube = 0 or m.sube_id = p_sube)
       group by d.kod
      union all
      -- 18 · 21: yatış ve taburcu (yatışın departmanı)
      select d.kod, 18::smallint, count(*)::int
        from public.yatis y
        join public.departman d on d.id = y.departman_id
        cross join bas
       where y.giris_tarihi >= bas.ilk and y.giris_tarihi < bas.son
         and (p_sube = 0 or y.sube_id = p_sube) and coalesce(d.kod, '') <> ''
       group by d.kod
      union all
      select d.kod, 21::smallint, count(*)::int
        from public.yatis y
        join public.departman d on d.id = y.departman_id
        cross join bas
       where y.cikis_tarihi >= bas.ilk and y.cikis_tarihi < bas.son
         and (p_sube = 0 or y.sube_id = p_sube) and coalesce(d.kod, '') <> ''
       group by d.kod
      union all
      -- 37 · 38 · 39: muayene türleri (muayenenin bölümü)
      select d.kod, 37::smallint, count(distinct m.id)::int
        from public.muayene m
        join public.departman d on d.id = m.bolum_id
        cross join bas
       where coalesce(m.muayene_tarihi, m.baslangic) >= bas.ilk
         and coalesce(m.muayene_tarihi, m.baslangic) < bas.son
         and (p_sube = 0 or m.sube_id = p_sube) and coalesce(d.kod, '') <> ''
         and upper(d.ad) not like '%ACİL%'
         and not exists (select 1 from public.dis_muayene dm where dm.muayene_id = m.id)
       group by d.kod
      union all
      select d.kod, 38::smallint, count(distinct m.id)::int
        from public.muayene m
        join public.departman d on d.id = m.bolum_id
        cross join bas
       where coalesce(m.muayene_tarihi, m.baslangic) >= bas.ilk
         and coalesce(m.muayene_tarihi, m.baslangic) < bas.son
         and (p_sube = 0 or m.sube_id = p_sube) and coalesce(d.kod, '') <> ''
         and upper(d.ad) like '%ACİL%'
       group by d.kod
      union all
      select d.kod, 39::smallint, count(distinct dm.muayene_id)::int
        from public.dis_muayene dm
        join public.muayene m on m.id = dm.muayene_id
        join public.departman d on d.id = m.bolum_id
        cross join bas
       where coalesce(m.muayene_tarihi, m.baslangic) >= bas.ilk
         and coalesce(m.muayene_tarihi, m.baslangic) < bas.son
         and (p_sube = 0 or m.sube_id = p_sube) and coalesce(d.kod, '') <> ''
       group by d.kod
    )
    select s.klinik::varchar, s.skrs, o.ad, s.sayi
      from sayimlar s
      join public.enabiz_gun_sonu_olcut o on o.skrs_kod = s.skrs and o.aktif = 1
     where s.sayi > 0
     order by s.klinik, s.skrs;
$$;

comment on function public.fn_enabiz_ay_sonu_sayilar(integer, integer, integer) is
  '885: 408 ay sonu sayilari - olcut x KLINIK (departman.kod). Brans boyutu '
  'olmayan olcutler (radyoloji) uretilmez; sifir satir da yazilmaz (aylikta '
  '"o brans o ay hic is yapmadi" satirini gondermek listeyi sisirir).';

-- ---------------------------------------------- klinik kodu eksik raporu ----
create or replace view public.v_enabiz_klinik_kodsuz as
select d.id, d.ad, count(m.id)::int as muayene_sayisi
  from public.departman d
  left join public.muayene m on m.bolum_id = d.id
 where coalesce(d.kod, '') = ''
 group by d.id, d.ad
having count(m.id) > 0;

comment on view public.v_enabiz_klinik_kodsuz is
  '885: SKRS klinik kodu olmayan ama muayenesi olan bolumler. Bunlarin isi '
  '408 ay sonu paketine GIRMEZ - eksiklik sessiz kalmasin.';

