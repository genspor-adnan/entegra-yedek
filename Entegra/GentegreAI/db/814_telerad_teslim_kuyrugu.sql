-- -------------------------------------------------------------- yetki ----
insert into public.yetki (kod, ad, grup, tur, sira, aktif, urun_modu, modul)
select 'telerad.teslim_kuyruk', 'Teslim kuyruğunu yönet (yeniden dene / iptal)',
       'Teleradyoloji', 1, 70, 1, 2, 'teleradyoloji'
 where not exists (select 1 from public.yetki y where y.kod = 'telerad.teslim_kuyruk');

-- Raporu teslim edebilen (telerad.teslim) kuyruğu da yönetebilir: aynı işin
--   iki adımı, ayrı rol istemek kimsenin işine yaramaz.
insert into public.rol_yetki (rol_id, yetki_id, gor, ekle, degistir, sil)
select ry.rol_id, y2.id, 1, 1, 1, 0
  from public.rol_yetki ry
  join public.yetki y1 on y1.id = ry.yetki_id and y1.kod = 'telerad.teslim'
  join public.yetki y2 on y2.kod = 'telerad.teslim_kuyruk'
 where not exists (select 1 from public.rol_yetki x
                    where x.rol_id = ry.rol_id and x.yetki_id = y2.id);

-- --------------------------------------------------------------- kuyruk ----
create table if not exists public.telerad_teslim (
    id               bigint      primary key generated by default as identity,
    istek_id         integer     not null references public.telerad_istek(id) on delete cascade,
    hedef            smallint    not null default 1,   -- 1 kurum HBYS · 2 Bakanlık
    kanal            smallint    not null default 1,   -- 1 ORU MLLP · 2 REST · 3 FHIR
    -- 0 iptal · 1 bekliyor · 2 gönderiliyor · 3 başarılı · 4 kalıcı hata
    durum            smallint    not null default 1,
    deneme_no        smallint    not null default 0,
    ilk_kuyruk       timestamp   not null default now()::timestamp,
    son_deneme       timestamp,
    -- SIRADAKİ DENEME ZAMANI SATIRDA: kuyruğu okuyan servis "kim hazır"
    --   sorusunu tek koşulla sorsun, geri çekilme mantığını yeniden
    --   hesaplamasın.
    sonraki_deneme   timestamp   not null default now()::timestamp,
    ack_kodu         varchar(2)  not null default '',
    hata_metni       varchar(400) not null default '',
    -- MSH-10: ACK'i hangi mesaja ait olduğunu bununla eşleştiriyoruz.
    mesaj_kontrol_no varchar(20) not null default '',
    sube_id          integer     references public.sube(id),
    ekleyen          integer     not null default 0,
    ekleme_tarihi    timestamptz not null default now(),
    degistiren       integer     not null default 0,
    degistirme_tarihi timestamptz,
    constraint ck_telerad_teslim_hedef check (hedef in (1, 2)),
    constraint ck_telerad_teslim_durum check (durum between 0 and 4),
    -- AYNI İŞ + AYNI HEDEF İÇİN TEK KUYRUK SATIRI: ikinci satır açılsaydı
    --   aynı rapor iki kez gider ve karşı HBYS'de mükerrer rapor doğardı.
    constraint ux_telerad_teslim unique (istek_id, hedef)
);

comment on table public.telerad_teslim is
  '814: teleradyoloji rapor teslim kuyruğu - istek + hedef başına tek satır. '
  'hedef: 1 kurum HBYS · 2 Bakanlık Teleradyoloji.';

create index if not exists ix_telerad_teslim_sira
    on public.telerad_teslim (sonraki_deneme)
 where durum = 1;
create index if not exists ix_telerad_teslim_istek
    on public.telerad_teslim (istek_id);

