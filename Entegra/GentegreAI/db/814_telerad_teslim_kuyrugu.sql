--  ============ NEDEN KUYRUK ==========================================
--  Rapor onaylandığı anda karşı sistem kapalı olabilir. Gönderimi onay
--  işleminin İÇİNDE yapmak iki kötülük doğurur: onay, karşı tarafın ağı
--  yüzünden başarısız olur; ya da gönderim sessizce düşer ve "rapor gitti mi"
--  sorusunun cevabı hiçbir yerde durmaz. Kuyruk ikisini de çözer.
--
--  ============ İKİ TABLO, İKİ SORU ===================================
--    `telerad_teslim`     -> "ŞU AN ne durumda" (istek + hedef başına TEK satır)
