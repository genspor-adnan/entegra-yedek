create index if not exists ix_telerad_teslim_iz on public.telerad_teslim_iz (teslim_id, id desc);

-- ------------------------------------------------------- geri çekilme ----
-- ARTAN ARALIK: 1 dk · 5 dk · 15 dk · 1 sa · 4 sa, sonra günde bir. Sabit
--   aralıkla denemek, karşı sistem kapalıyken günde binlerce boş bağlantı
--   demekti (kapsam belgesi § 4.2).
create or replace function public.fn_telerad_teslim_sonraki(p_deneme smallint)
returns interval
language sql immutable as $$
  select case
           when p_deneme <= 1 then interval '1 minute'
           when p_deneme = 2  then interval '5 minutes'
           when p_deneme = 3  then interval '15 minutes'
           when p_deneme = 4  then interval '1 hour'
           when p_deneme = 5  then interval '4 hours'
           else interval '1 day'
         end;
$$;

comment on function public.fn_telerad_teslim_sonraki(smallint) is
  '814: teslim denemeleri arasındaki artan bekleme.';

-- --------------------------------------------------------- kuyruğa alma ----
-- TEK YAZICI: uç da, tetik de, servis de buradan geçer. Hedefin açık olup
--   olmadığına (kanal, bakanlik_gonderim) burada karar verilir - üç ayrı
--   yerde üç farklı "gönderilmeli mi" kuralı olmasın.
create or replace function public.fn_telerad_teslim_kuyrukla(
    p_istek_id integer, p_hedef smallint, p_kullanici integer default 0)
returns bigint
language plpgsql
as $$
declare
    r      record;
    v_id   bigint;
begin
    select i.id, i.sube_id, i.rapor_id, i.durum,
           coalesce(k.hl7_tur, 0)           as kanal,
           coalesce(k.bakanlik_gonderim, 0) as bakanlik
      into r
      from public.telerad_istek i
      join public.telerad_kurum k on k.id = i.kurum_id
     where i.id = p_istek_id;

    if not found then
        raise exception 'Teleradyoloji isteği bulunamadı (%).', p_istek_id
              using errcode = 'GK404';
    end if;

    -- ONAYLI RAPOR YOKSA GÖNDERİLECEK BİR ŞEY YOK: boş gövdeli ORU, karşı
    --   tarafta "rapor geldi" sayılır ve hasta raporsuz kalır.
    if r.rapor_id is null then
        raise exception 'Raporu onaylanmamış iş teslim kuyruğuna alınamaz.'
              using errcode = 'GK422';
    end if;

    if p_hedef = 1 and r.kanal <> 1 then
        raise exception 'Kurumun teslim kanalı HL7 ORU değil; kuyruk kullanılmaz.'
              using errcode = 'GK422';
    end if;
    if p_hedef = 2 and r.bakanlik <> 1 then
        raise exception 'Kurumda Bakanlık bildirimi kapalı.'
              using errcode = 'GK422';
    end if;

    -- BAŞARILI TESLİM TEKRAR KUYRUĞA GİRMEZ: düzeltme ek rapor (addendum)
    --   olarak ayrıca gönderilir.
    insert into public.telerad_teslim (istek_id, hedef, kanal, durum, sube_id, ekleyen)
    values (p_istek_id, p_hedef, 1, 1, r.sube_id, p_kullanici)
    on conflict (istek_id, hedef) do update
       set durum = case when public.telerad_teslim.durum = 3 then 3 else 1 end,
           sonraki_deneme = now()::timestamp,
           degistiren = p_kullanici, degistirme_tarihi = now()
    returning id into v_id;

    return v_id;
end $$;

comment on function public.fn_telerad_teslim_kuyrukla(integer, smallint, integer) is
  '814: teslimi kuyruğa alır (hedef 1 kurum · 2 Bakanlık). Hedefin açık olup '
  'olmadığına burada karar verilir.';

-- ----------------------------------------------------- onayda otomatik ----
-- AYAR KAPALIYKEN HİÇBİR ŞEY DEĞİŞMEZ: bugünkü akış "Teslim Et" düğmesidir.
create or replace function public.tg_telerad_teslim_otomatik()
returns trigger
language plpgsql
as $$
declare v_acik text;
begin
    if coalesce(new.durum, 0) < 6 or coalesce(old.durum, 0) >= 6 then
        return new;
    end if;

    select deger into v_acik from public.referans
     where anahtar = 'telerad.teslim_otomatik';
    if coalesce(v_acik, '0') <> '1' then return new; end if;

    -- HATA YUTULMAZ AMA ONAYI DA DÜŞÜRMEZ: kuyruğa alınamayan iş (kanal
    --   kapalı, rapor yok) uyarı olarak günlüğe düşer; rapor onayı durmaz.
    begin
        perform public.fn_telerad_teslim_kuyrukla(new.id, 1::smallint, new.degistiren);
    exception when others then
        raise notice 'Teslim kuyruğu (kurum) atlandı: %', sqlerrm;
    end;
    begin
        perform public.fn_telerad_teslim_kuyrukla(new.id, 2::smallint, new.degistiren);
    exception when others then
        raise notice 'Teslim kuyruğu (Bakanlık) atlandı: %', sqlerrm;
    end;
    return new;
end $$;

-- ADI "tg_telerad_z_...": 797'deki damga tetiğinden SONRA çalışsın - onay
--   zamanı yazılmadan kuyruğa almak, mesajda OBR-7'yi boş bırakırdı.
drop trigger if exists tg_telerad_z_teslim on public.telerad_istek;
create trigger tg_telerad_z_teslim
    after update of durum on public.telerad_istek
    for each row execute function public.tg_telerad_teslim_otomatik();

-- ------------------------------------------------------------- görünüm ----
create or replace view public.v_telerad_teslim as
select t.id,
       t.istek_id,
       i.istek_no,
       coalesce(tk.unvan, '')                        as kurum_adi,
       t.hedef,
       case t.hedef when 2 then 'Bakanlık' else 'Kurum' end as hedef_adi,
       t.durum,
       case t.durum when 0 then 'İptal'    when 1 then 'Bekliyor'
                    when 2 then 'Gönderiliyor' when 3 then 'Teslim edildi'
                    else 'Hata' end                  as durum_adi,
       t.deneme_no,
       t.son_deneme,
       t.sonraki_deneme,
       t.ack_kodu,
       t.hata_metni,
       t.mesaj_kontrol_no,
       t.sube_id,
       -- Kalıcı hata KRİTİK, bekleyen tekrar UYARI: kuyruğun uzaması sessiz
       --   kalmasın.
       case when t.durum = 4 then 'kritik'
            when t.durum = 1 and t.deneme_no > 0 then 'uyari'
            when t.durum = 0 then 'pasif'
            else '' end                              as satir_rengi
  from public.telerad_teslim t
  join public.telerad_istek i on i.id = t.istek_id
  join public.telerad_kurum k on k.id = i.kurum_id
  join public.taraf tk        on tk.id = k.taraf_id;

comment on view public.v_telerad_teslim is
  '814: teslim kuyruğu ekranı - hangi iş, hangi hedefe, kaçıncı denemede.';

