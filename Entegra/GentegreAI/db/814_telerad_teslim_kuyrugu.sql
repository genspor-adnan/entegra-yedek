    zaman         timestamp   not null default now()::timestamp,
    -- 1 başarılı · 2 uygulama hatası (AE) · 3 ret (AR) · 4 ulaşmadı
    sonuc         smallint    not null default 4,
    ack_kodu      varchar(2)  not null default '',
    hata_metni    varchar(400) not null default '',
    sure_ms       integer     not null default 0,
    istek_govde   text        not null default '',
    yanit_govde   text        not null default ''
