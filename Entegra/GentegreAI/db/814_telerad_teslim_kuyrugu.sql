--  bulmak için her seferinde en büyük id aranırdı.
--
--  ============ GÖVDELER SAKLANIR =====================================
--  "Ne gönderdik, ne aldık" sorusu aylar sonra sorulur - e-Belge tarafındaki
--  dersin aynısı. Ham ORU ve ham ACK izde durur.
--
--  ============ HEDEF İKİ TANE =======================================
--  1 KURUM: raporu isteyen kurumun HBYS'si (kurum-kuruma teleradyoloji).
--  2 BAKANLIK: Teletıp/Teleradyoloji Sistemi (809-813 profili). Aynı işin
--  iki hedefi olabilir ve biri başarısızken öteki gitmiş olabilir - bu yüzden
--  hedef satırın ANAHTARININ parçası.
