alter table public.radyoloji_rapor_gonderim add column if not exists kaynak smallint not null default 1;
alter table public.radyoloji_rapor_gonderim add column if not exists belge_id integer references public.belge(id) on delete cascade;
alter table public.radyoloji_rapor_gonderim add column if not exists lab_bolum smallint;
alter table public.radyoloji_rapor_gonderim alter column rapor_id drop not null;
alter table public.radyoloji_rapor_gonderim alter column istem_id drop not null;

do $$
begin
  if not exists (select 1 from pg_constraint where conname = 'ck_rrg_kaynak') then
    alter table public.radyoloji_rapor_gonderim add constraint ck_rrg_kaynak check (
        (kaynak = 1 and rapor_id is not null and istem_id is not null) or
        (kaynak = 2 and belge_id is not null and lab_bolum is not null));
  end if;
end $$;
create unique index if not exists ux_rrg_lab on public.radyoloji_rapor_gonderim (belge_id, lab_bolum, alici_tur) where kaynak = 2;
create index if not exists ix_rrg_belge on public.radyoloji_rapor_gonderim (belge_id) where kaynak = 2;

comment on column public.radyoloji_rapor_gonderim.kaynak is '1 radyoloji raporu (rapor_id) · 2 başvurunun lab bölümü (belge_id + lab_bolum) (1394).';

alter table public.radyoloji_rapor_gonderim_ayar add column if not exists lab_panik_dakika integer not null default 0;
comment on column public.radyoloji_rapor_gonderim_ayar.lab_panik_dakika is
  'Laboratuvar panik değerli sonuçta gönderim süresi (dk); 0 = otomatik gitmez. Radyoloji kritik bulgu süresi kritik_dakika (1394).';

alter table public.lab_tetkik add column if not exists baglantida_gizle smallint not null default 0;
comment on column public.lab_tetkik.baglantida_gizle is
  'Hasta rapor bağlantısında gösterilmez (1394): sonuç yerine "kuruma başvurun" notu. Gönderen dış doktor görür.';

create table if not exists public.lab_sonuc_teslim (
    id             integer     primary key generated by default as identity,
    belge_id       integer     not null references public.belge(id) on delete cascade,
    bolum          smallint    not null,
    tur            smallint    not null default 2,          -- rad.teslim_turu: 1 portal / bağlantı · 2 basılı rapor · 5 e-posta
    teslim_zamani  timestamp   not null default now()::timestamp,
    teslim_eden_id integer     references public.taraf(id),
    alan_ad        varchar(120) not null default '',
    alan_yakinlik  varchar(60)  not null default '',
    aciklama       varchar(300) not null default '',
    dijital        smallint    not null default 0,
    ekleyen        integer     not null default 0,
    ekleme_tarihi  timestamp   not null default now()::timestamp
);
create index if not exists ix_lab_sonuc_teslim_belge on public.lab_sonuc_teslim (belge_id, bolum);
comment on table public.lab_sonuc_teslim is
  'Laboratuvar sonucunun hastaya teslimi (1394): elden ya da dijital (rapor bağlantısı açıldı). Satır başvuru + lab bölümü.';

