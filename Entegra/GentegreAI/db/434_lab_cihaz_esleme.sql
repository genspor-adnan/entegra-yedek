-- =====================================================================
-- 434 - LABORATUVAR CIHAZ ESLEME VE CALISMA LISTESI (Lab v1)
--
-- 432'deki cihaz ara katmani ham sonucu ALIR ve SAKLAR; bu betik o ham
-- sonucu LAB TETKIGINE baglar.
--
-- ESLEME KAYDI ZORUNLU DEGIL: cihaz test kodu ile tetkik kodu ayniysa
--   (WBC, HGB, GLU...) kod uzerinden otomatik bulunur. Tablo yalnizca
--   cihazin FARKLI kod kullandigi (ornegin "GLUC-2", "0031") ya da birim
--   cevrimi gereken durumlar icin. Her cihaz icin 200 satir eslemeyi elle
--   girdirmek, kurulumu haftalara yayardi.
--
-- CARPAN/OFSET: cihaz mg/dL verip laboratuvar mmol/L raporluyorsa cevrim
--   burada yapilir - sonuc tablosunda hem HAM deger hem cevrilmis deger
--   durur, boylece cevrim yanlissa geriye donuk duzeltilebilir.
-- =====================================================================

create table if not exists public.lab_cihaz_test_esleme (
    id                integer generated by default as identity primary key,
    cihaz_id          integer not null references public.cihaz(id) on delete cascade,
    cihaz_test_kodu   varchar(30) not null,
    tetkik_id         integer not null references public.lab_tetkik(id),
    -- Cihazin kendi birimi; rapor birimi tetkikten gelir.
    cihaz_birim       varchar(20)  not null default '',
    carpan            numeric(19,6) not null default 1,
    ofset             numeric(19,6) not null default 0,
    -- Cihaz bir kodda birden cok sonuc veriyorsa (ornegin diferansiyel)
    --   sirayla ayirt edilir.
    alt_kod           varchar(20)  not null default '',
    aciklama          varchar(200) not null default '',
    durum             smallint     not null default 0,   -- 0 aktif / 1 pasif
    sube_id           integer      not null default 0,
    ekleyen           integer      not null default 0,
    ekleme_tarihi     timestamp    not null default now(),
    degistiren        integer      not null default 0,
    degistirme_tarihi timestamp
);

-- Ayni cihazda ayni kod iki tetkige bakamaz: hangisine yazilacagi
--   belirsiz kalir ve sonuc sessizce yanlis hastanin tetkigine gider.
create unique index if not exists ux_lab_cihaz_esleme
    on public.lab_cihaz_test_esleme (cihaz_id, upper(cihaz_test_kodu), alt_kod);

create index if not exists ix_lab_cihaz_esleme_tetkik
    on public.lab_cihaz_test_esleme (tetkik_id);

-- =====================================================================
-- CIHAZ TEST KODU -> TETKIK COZUMU
--
-- Once esleme tablosu, sonra tetkik kodu. Bulunamazsa NULL doner ve
-- cagiran mesaji "eslesmeyen test" olarak isaretler - sessizce atmak,
-- sonucu kaybolmus gosterirdi.
-- =====================================================================
create or replace function public.fn_lab_cihaz_tetkik(
    p_cihaz_id integer,
    p_test_kodu text,
    p_alt_kod text default ''
) returns table (tetkik_id integer, carpan numeric, ofset numeric)
language sql stable as $$
    select e.tetkik_id, e.carpan, e.ofset
      from public.lab_cihaz_test_esleme e
     where e.cihaz_id = p_cihaz_id
       and upper(e.cihaz_test_kodu) = upper(coalesce(p_test_kodu, ''))
       and e.alt_kod = coalesce(p_alt_kod, '')
       and e.durum = 0
     union all
    select t.id, 1::numeric, 0::numeric
      from public.lab_tetkik t
     where t.durum = 0
       and upper(t.kod) = upper(coalesce(p_test_kodu, ''))
       and not exists (select 1 from public.lab_cihaz_test_esleme e2
                        where e2.cihaz_id = p_cihaz_id
                          and upper(e2.cihaz_test_kodu) = upper(coalesce(p_test_kodu, ''))
                          and e2.durum = 0)
     limit 1;
$$;

-- =====================================================================
-- HOST QUERY (cift yon) - cihaz "bu barkodda ne calisacagim" diye sorar.
--
-- Cihaza calisma listesini SUNUCU verir; teknisyenin cihaz basinda testi
-- elle secmesi hem yavas hem hatali (yanlis test, eksik test). Yalniz
-- KABUL EDILMIS numunenin testleri donder: reddedilmis tupu calistirmak
-- yanlis sonuc uretir.
-- =====================================================================
create or replace function public.fn_lab_cihaz_calisma_listesi(
    p_cihaz_id integer,
    p_barkod text
) returns table (
    istem_satir_id integer,
    barkod         varchar,
    tetkik_id      integer,
    tetkik_kodu    varchar,
    cihaz_kodu     varchar,
    tetkik_adi     varchar,
    hasta_no       integer,
    hasta_adi      text,
    oncelik        smallint
)
language sql stable as $$
    select s.id, n.barkod, t.id, t.kod,
           coalesce((select e.cihaz_test_kodu
                       from public.lab_cihaz_test_esleme e
                      where e.cihaz_id = p_cihaz_id and e.tetkik_id = t.id
                        and e.durum = 0
                      order by e.id limit 1), t.kod)::varchar,
           t.ad, n.hasta_id,
           coalesce(nullif(trim(h.ad || ' ' || h.soyad), ''), h.unvan),
           i.oncelik
      from public.lab_numune n
      join public.lab_istem_satir s on s.numune_id = n.id
      join public.lab_istem i on i.id = s.istem_id
      join public.lab_tetkik t on t.id = s.tetkik_id
      join public.taraf h on h.id = n.hasta_id
     where n.barkod = p_barkod
       and n.durum = 3            -- yalniz KABUL EDILMIS numune
       and s.durum in (1, 2, 6)   -- bekleyen / calisiliyor / tekrar
     order by s.sira, s.id;
$$;

-- =====================================================================
-- LOOKUP - cihaz esleme kartinda tetkik secimi zaten v_lab_tetkik_lookup
-- ile yapiliyor; burada yalniz esleme listesi gorunumu.
-- =====================================================================
drop view if exists public.v_lab_cihaz_esleme;
create view public.v_lab_cihaz_esleme as
select e.id, e.cihaz_id, c.kod as cihaz_kod, c.ad as cihaz_ad,
       e.cihaz_test_kodu, e.alt_kod, e.tetkik_id, t.kod as tetkik_kod,
       t.ad as tetkik_ad, e.cihaz_birim, t.birim as tetkik_birim,
       e.carpan, e.ofset, e.durum, e.aciklama, e.sube_id
  from public.lab_cihaz_test_esleme e
  join public.cihaz c on c.id = e.cihaz_id
  join public.lab_tetkik t on t.id = e.tetkik_id;

