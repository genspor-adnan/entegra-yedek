-- =====================================================================
-- KURAL MOTORU DUZELTMELERI (433'un iki bosluğu)
--
-- 1) REFERANSSIZ TETKIK 'N' DEMEMELI. 433'teki fn_lab_bayrak, alt ve ust
--    sinir yokken 'Normal' donuyordu: referans araligi girilmemis bir
--    tetkigin her sonucu hekime "normal" gorunurdu. Bos bayrak, ekranda
--    "degerlendirilmedi" olarak durur - uydurma normalden iyidir.
--
-- 2) DOGUM TARIHI BILINMEYEN HASTA YENIDOGAN SAYILIYORDU. Yas gunu
--    coalesce(..., 0) ile sifirlaniyordu ve 0-28 gunluk aralik esleşiyordu;
--    dogum tarihi bos bir eriskin, yenidogan referansiyla degerlendirilirdi.
--    Bilinmiyorsa ERISKIN (18 yas) varsayilir: nufusun cogunlugu odur ve
--    yanlis alarm yerine "genis aralik" tarafinda hata yapilir.
-- =====================================================================
create or replace function public.fn_lab_bayrak(p_deger numeric,
                                                p_alt numeric, p_ust numeric,
                                                p_panik_alt numeric,
                                                p_panik_ust numeric)
returns text language sql immutable as $$
    select case
        when p_deger is null then ''
        when p_panik_alt is not null and p_deger <= p_panik_alt then 'LL'
        when p_panik_ust is not null and p_deger >= p_panik_ust then 'HH'
        when p_alt is not null and p_deger < p_alt then 'L'
        when p_ust is not null and p_deger > p_ust then 'H'
        -- Hicbir sinir yoksa DEGERLENDIRME YOK.
        when p_alt is null and p_ust is null
             and p_panik_alt is null and p_panik_ust is null then ''
        else 'N'
    end;
$$;

create or replace function public.fn_lab_referans(p_tetkik_id integer,
                                                  p_hasta_id integer,
                                                  p_tarih date default null)
returns public.lab_tetkik_referans language sql stable as $$
    select r.*
      from public.lab_tetkik_referans r
      left join public.taraf_hasta h on h.id = p_hasta_id
     where r.tetkik_id = p_tetkik_id
       and (r.cinsiyet = 0 or r.cinsiyet = coalesce(h.cinsiyet, 0))
       and (r.gecerli_bas is null or r.gecerli_bas <= coalesce(p_tarih, current_date))
       and coalesce(
             (coalesce(p_tarih, current_date) - h.dogum_tarihi::date),
             6570)                                  -- dogum tarihi yoksa eriskin
           between r.yas_alt_gun and r.yas_ust_gun
     order by (r.yas_ust_gun - r.yas_alt_gun) asc,   -- en dar aralik
              r.cinsiyet desc,                        -- cinsiyete ozel once
              r.sira asc, r.id asc
     limit 1;
$$;

