--  identity id'si + ayri UstKolon FK. taraf_adres/taraf_gecmis'teki desene uydurmak icin
--  synthetic id eklendi (Kisi'nin TekAdres.tsx'i gibi TEK SATIR gosterilecek - "TekOzluk").
