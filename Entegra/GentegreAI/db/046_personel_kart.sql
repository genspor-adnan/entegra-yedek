\set ON_ERROR_STOP on

alter table public.personel_ozluk add column if not exists id integer generated by default as identity;

do $$
begin
    if not exists (
        select 1 from pg_constraint where conname = 'personel_ozluk_pkey_id'
    ) then
        alter table public.personel_ozluk drop constraint personel_ozluk_pkey;
        alter table public.personel_ozluk add constraint personel_ozluk_pkey_id primary key (id);
        alter table public.personel_ozluk add constraint ux_personel_ozluk_taraf unique (taraf_id);
    end if;
end $$;
