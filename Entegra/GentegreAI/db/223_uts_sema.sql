\set ON_ERROR_STOP on

-- ------------------------------------------------------------- uts_hesap ---
-- ÜTS hesabı ŞUBE BAZLI (kullanıcı: "e-fatura gibi hem merkez hem şubeye
-- özel"): şubenin aktif kaydı varsa o, yoksa varsayılan şubenin (merkez)
-- kaydı kullanılır (fn_uts_hesap). Token e-imza ile ÜTS arayüzünden üretilir
-- ve buraya KULLANICI tarafından yapıştırılır - koda/migration'a asla girmez.
create table if not exists public.uts_hesap (
    sube_id           integer      primary key
                                   references public.sube(id) on delete cascade,
    aktif             smallint     not null default 0,
    kurum_no          varchar(30)  not null default '',  -- ÜTS kurum/firma no (KUN)
    token             text         not null default '',  -- canlı sistem token'ı
    -- Yeni kurulum TESTTE başlar: yanlışlıkla canlıya bildirim gitmesin.
    test_ortami       smallint     not null default 1,
    test_kurum_no     varchar(30)  not null default '',
    test_token        text         not null default '',
    ekleyen           integer      not null default 0,
    ekleme_tarihi     timestamp    not null default now()::timestamp,
    degistiren        integer      not null default 0,
    degistirme_tarihi timestamp
);

comment on table public.uts_hesap is
  'Şubenin ÜTS hesabı (223): token + kurum no, test/canlı. Şube kaydı yoksa '
  'varsayılan şubenin (merkez) hesabı kullanılır - fn_uts_hesap.';

-- ---------------------------------------------------------- fn_uts_hesap ---
-- Şube -> merkez düşüşlü hesap çözümü (fn_ebelge_hesap 171 deseninin düz
-- hali). URL: referans uts.test_url / uts.uretim_url (elle değiştirilebilir),
-- boşsa resmi sabitler.
create or replace function public.fn_uts_hesap(p_sube_id integer default null)
returns table (kurum_no varchar, token text, test_mi boolean, url varchar)
language sql stable as $$
    with h as (
        -- Önce İSTENEN şubenin kaydı, yoksa varsayılan şubenin kaydı.
        -- "ÜTS Hesabı Aktif" ile "Test Ortamı" ekranda KARŞILIKLI DIŞLANAN
        -- seçimdir (kullanıcı): test işaretliyken aktif kalkıktır - hesap
        -- ikisinden biri işaretliyse kullanılabilir sayılır.
        select x.* from public.uts_hesap x
         where (x.aktif = 1 or x.test_ortami = 1)
           and x.sube_id = coalesce(p_sube_id,
                 (select id from public.sube
                   where varsayilan = 1 and aktif = 1 order by id limit 1))
        union all
        select x.* from public.uts_hesap x
         where (x.aktif = 1 or x.test_ortami = 1)
           and x.sube_id = (select id from public.sube
                             where varsayilan = 1 and aktif = 1 order by id limit 1)
        limit 1
    )
    select case when h.test_ortami = 1 then h.test_kurum_no else h.kurum_no end::varchar,
           case when h.test_ortami = 1 then h.test_token    else h.token    end,
           h.test_ortami = 1,
           coalesce(
             nullif(btrim((select r.deger from public.referans r
                            where r.anahtar = case when h.test_ortami = 1
                                                   then 'uts.test_url'
                                                   else 'uts.uretim_url' end)), ''),
             case when h.test_ortami = 1
                  then 'https://utstest.saglik.gov.tr'
                  else 'https://utsuygulama.saglik.gov.tr' end)::varchar
      from h
$$;

comment on function public.fn_uts_hesap(integer) is
  'Şubenin ÜTS hesabı: kurum no + token (test ya da canlı) + taban URL (223). '
  'Şubenin aktif kaydı yoksa varsayılan şubenin kaydına düşer.';

-- ---------------------------------------------------------- uts_bildirim ---
-- Bildirim başlığı. DURUM: 0 Bekliyor (HTTP öncesi iz - süreç ölse bile ne
-- gönderilmeye çalışıldığı bellidir), 1 Başarılı, 2 Hata, 3 İptal.
create table if not exists public.uts_bildirim (
    id                  integer generated by default as identity primary key,
    tur                 smallint     not null,             -- kod_liste uts.bildirim_tur
    durum               smallint     not null default 0,   -- kod_liste uts.bildirim_durum
    sube_id             integer      not null references public.sube(id),
    test_mi             smallint     not null default 0,   -- hangi ortama gitti
    stok_id             integer      references public.stok(id),
    seri_lot_id         integer      references public.stok_seri_lot(id),
    belge_id            integer      references public.belge(id),
    belge_satir_id      integer      references public.belge_satir(id),
    adet                numeric(24,6) not null default 0,
    gercek_islem_tarihi date,                              -- GIT
    -- ÜTS'nin döndürdüğü bildirim kimliği (SNC): GUID METİNDİR, sayı değil.
    --   İptal (BID) ve almanın VBI bağı bunu kullanır.
    uts_bildirim_id     varchar(36)  not null default '',
    ekleyen             integer      not null default 0,
    ekleme_tarihi       timestamp    not null default now()::timestamp,
    degistiren          integer      not null default 0,
    degistirme_tarihi   timestamp
);

create index if not exists ix_uts_bildirim_durum on public.uts_bildirim (durum);
create index if not exists ix_uts_bildirim_stok  on public.uts_bildirim (stok_id)
    where stok_id is not null;
create index if not exists ix_uts_bildirim_belge on public.uts_bildirim (belge_id)
    where belge_id is not null;
create index if not exists ix_uts_bildirim_uid   on public.uts_bildirim (uts_bildirim_id)
    where uts_bildirim_id <> '';
-- Çift gönderim kilidi: aynı belge satırı + tür için bekleyen/başarılı TEK
--   bildirim olabilir (hatalı/iptal kayıt yenisini engellemez).
create unique index if not exists ux_uts_bildirim_satir
    on public.uts_bildirim (belge_satir_id, tur)
 where belge_satir_id is not null and durum in (0, 1);

comment on table public.uts_bildirim is
  'ÜTS bildirim başlığı (223): tur 1 Alma / 2 Verme / 3 Kullanım; durum '
  '0 Bekliyor / 1 Başarılı / 2 Hata / 3 İptal. uts_bildirim_id = SNC (GUID).';

-- ---------------------------------------------------- uts_bildirim_mesaj ---
-- 1:1 ham istek/cevap. TOKEN BURAYA ASLA GİRMEZ (HTTP başlığında taşınır).
create table if not exists public.uts_bildirim_mesaj (
    bildirim_id  integer      primary key
                              references public.uts_bildirim(id) on delete cascade,
    kurum_no     varchar(30)  not null default '',  -- karşı kurum (KUN)
    belge_no     varchar(50)  not null default '',  -- BNO
    urun_no      varchar(23)  not null default '',  -- UNO
    lot_no       varchar(20)  not null default '',  -- LNO
    seri_no      varchar(20)  not null default '',  -- SNO
    urt          date,
    skt          date,
    istek_json   jsonb,                             -- gönderilen gövde
    cevap_json   jsonb,                             -- ÜTS cevabı (SNC + MSJ) ham
    http_kodu    smallint     not null default 0,
    sonuc_kodu   varchar(20)  not null default '',  -- ilk HATA mesajının KOD'u
    sonuc_mesaji varchar(500) not null default ''   -- ilk HATA/UYARI MET'i
);

comment on table public.uts_bildirim_mesaj is
  'ÜTS bildiriminin ham istek/cevap JSON''u ve özet sonucu (223, 1:1).';

-- ---------------------------------------------------------- uts_envanter ---
-- Karşı kurumların bize VERDİĞİ (askıdaki) tekil ürünler - askıdakiler
-- senkronuyla dolar (verme/askidakiler). verme_bildirim_id = BID: alma
-- bildiriminin VBI bağı ve upsert anahtarı.
create table if not exists public.uts_envanter (
    id                 integer generated by default as identity primary key,
    sube_id            integer      not null references public.sube(id),
    verme_bildirim_id  varchar(36)  not null,             -- BID (GUID)
    kurum_no           varchar(30)  not null default '',  -- gönderen KUN
    kurum_unvan        varchar(200) not null default '',  -- AKU
    urun_no            varchar(23)  not null default '',
    lot_no             varchar(20)  not null default '',
    seri_no            varchar(20)  not null default '',
    belge_no           varchar(50)  not null default '',  -- BNO
    bildirim_tipi      varchar(30)  not null default '',  -- BTI (VERME / GECICI_VERME ...)
    bildirim_zamani    timestamp,                          -- BZA
    marka_model        varchar(300) not null default '',  -- MME
    gelen_adet         numeric(24,6) not null default 0,
    aski_adet          numeric(24,6) not null default 0,   -- alma yapıldıkça düşer
    gelen_urt          date,
    gelen_skt          date,
    stok_id            integer      references public.stok(id), -- GTIN 13/14 eşleşmesi
    durum              smallint     not null default 1,    -- 1 askıda / 2 alındı / 0 kayboldu
    guncelleme         timestamp    not null default now()::timestamp
);

create unique index if not exists ux_uts_envanter_bid
    on public.uts_envanter (sube_id, verme_bildirim_id);
create index if not exists ix_uts_envanter_durum on public.uts_envanter (durum);

comment on table public.uts_envanter is
  'ÜTS askıdaki/gelen tekil ürünler (223): verme_bildirim_id = ÜTS BID (GUID), '
  'alma bildirimi VBI ile buna bağlanır. durum 1 askıda / 2 alındı / 0 kayboldu.';

-- ----------------------------------------------------------- kod listesi ---
insert into public.kod_liste (kod, ad)
select v.kod, v.ad
  from (values ('uts.bildirim_tur',   'ÜTS Bildirim Türü'),
               ('uts.bildirim_durum', 'ÜTS Bildirim Durumu')) v(kod, ad)
 where not exists (select 1 from public.kod_liste k where k.kod = v.kod);

insert into public.kod_deger (liste_id, deger, ad, sira, aktif)
select l.id, v.deger, v.ad, v.deger * 10, 1
  from (values (1, 'Alma'), (2, 'Verme'), (3, 'Kullanım')) v(deger, ad)
  join public.kod_liste l on l.kod = 'uts.bildirim_tur'
 where not exists (select 1 from public.kod_deger d
                    where d.liste_id = l.id and d.deger = v.deger);

insert into public.kod_deger (liste_id, deger, ad, sira, aktif)
select l.id, v.deger, v.ad, v.deger * 10 + 10, 1
  from (values (0, 'Bekliyor'), (1, 'Başarılı'), (2, 'Hata'), (3, 'İptal')) v(deger, ad)
  join public.kod_liste l on l.kod = 'uts.bildirim_durum'
 where not exists (select 1 from public.kod_deger d
                    where d.liste_id = l.id and d.deger = v.deger);

-- -------------------------------------------------------- referans tohumu ---
-- URL'ler elle değiştirilebilir (Genel Ayarlar); boş bırakılırsa fn_uts_hesap
-- resmi sabitlere düşer.
insert into public.referans (anahtar, deger, tip, kapsam, aciklama)
select v.anahtar, v.deger, 'metin', 'firma', v.aciklama
  from (values
        ('uts.test_url',   'https://utstest.saglik.gov.tr',
         'ÜTS test ortamı taban adresi'),
        ('uts.uretim_url', 'https://utsuygulama.saglik.gov.tr',
         'ÜTS canlı ortam taban adresi')) v(anahtar, deger, aciklama)
 where not exists (select 1 from public.referans r where r.anahtar = v.anahtar);

do $$ begin
    raise notice '223 tamam: uts_hesap + fn_uts_hesap + uts_bildirim(+mesaj) + uts_envanter.';
end $$;
