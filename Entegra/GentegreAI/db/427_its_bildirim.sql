-- ============================================================================
--  427 - İTS (İLAÇ TAKİP SİSTEMİ) BİLDİRİMLERİ — v1 (Faz 1 · HBYS)
--
--  Kaynak: its.gov.tr REST API servis adres listesi (05.07.2022).
--
--  ÜTS ile KARIŞTIRILMAMALI: ÜTS tıbbi cihaz/malzeme, İTS İLAÇ içindir.
--  İkisi ayrı kurum, ayrı servis, ayrı bildirim türleri - tek tabloya
--  toplamak, bir gün birinin alanı değişince ötekini de kırardı.
--
--  v1 KAPSAMI: karekod okuma (GTIN + seri + SKT + parti), ürün doğrulama ve
--  MAL ALIM (kabul) bildirimi. Tüketim, iade, deaktivasyon Faz 2 - ama tür
--  kodları şimdiden ayrılmıştır ki kuyruk deseni sonradan değişmesin.
--
--  KAREKOD TEKİLDİR: aynı GTIN+seri ikinci kez kabul edilemez (ilaç kutusu
--  tek). Benzersiz indeks bunu koruyor; olmazsa aynı kutu iki kez bildirilir
--  ve İTS envanteri gerçekle tutmaz.
-- ============================================================================

create table if not exists public.its_bildirim (
    id             integer  primary key generated by default as identity,
    -- 1 mal alim (kabul) · 2 tuketim · 3 iade · 4 deaktivasyon · 5 transfer
    tur            smallint not null default 1,
    -- 0 hazirlaniyor · 1 bekliyor · 2 gonderiliyor · 3 gonderildi
    -- 4 hatali · 5 iptal
    durum          smallint not null default 0,
    sube_id        integer  not null default 0,
    test_mi        smallint not null default 1,
    -- Kaynak belge: alis irsaliyesi / faturasi (mal alim), muayene (tuketim).
    belge_id       integer,
    belge_satir_id integer,
    muayene_id     integer,
    -- Karsi taraf GLN'i: mal alimda GONDEREN (depo/ecza deposu).
    karsi_gln      varchar(13) not null default '',
    islem_tarihi   date,
    -- ITS'nin dondurdugu bildirim kimligi (sorgu ve iptal bununla).
    its_bildirim_no varchar(64) not null default '',
    deneme         smallint not null default 0,
    son_deneme     timestamp,
    planlanan      timestamp not null default now(),
    hata_kodu      varchar(20) not null default '',
    hata_mesaj     varchar(400) not null default '',
    -- 1 veri (kullanici duzeltir) · 2 servis (otomatik tekrar) · 3 yetki
    hata_sinifi    smallint not null default 0,
    ham_istek      text     not null default '',
    ham_yanit      text     not null default '',
    ekleyen        integer  not null default 0,
    ekleme_tarihi  timestamp not null default now(),
    degistiren     integer  not null default 0,
    degistirme_tarihi timestamp
);
create index if not exists ix_its_bildirim_kuyruk
    on public.its_bildirim(durum, planlanan) where durum in (1, 4);
create index if not exists ix_its_bildirim_belge
    on public.its_bildirim(belge_id) where belge_id is not null;

create table if not exists public.its_bildirim_satir (
    id            integer  primary key generated by default as identity,
    bildirim_id   integer  not null references public.its_bildirim(id) on delete cascade,
    -- Karekodun ham hali: ITS'ye giden ve sorun cikinca bakilacak olan budur.
    karekod       varchar(200) not null default '',
    gtin          varchar(14)  not null,
    seri_no       varchar(20)  not null default '',
    parti_no      varchar(20)  not null default '',
    son_kullanma  date,
    -- Katalog eslesmesi: ilac bulunamazsa bildirim yine gider (ITS kendi
    --   katalogunu kullanir) ama stok hareketi kurulamaz.
    ilac_barkod   varchar(20)  not null default '',
    stok_id       integer,
    seri_lot_id   integer,
    -- 0 dogrulanmadi · 1 dogrulandi (ITS) · 2 ITS'de bulunamadi · 3 uyumsuz
    dogrulama     smallint not null default 0,
    dogrulama_not varchar(200) not null default '',
    ekleyen       integer  not null default 0,
    ekleme_tarihi timestamp not null default now()
);
create index if not exists ix_its_satir_bildirim on public.its_bildirim_satir(bildirim_id);

-- AYNI KUTU IKI KEZ BILDIRILEMEZ: ilac kutusu tekil (GTIN + seri). Iptal
--   edilmis bildirim (durum 5) sayilmaz - hatali bildirim iptal edilip
--   yeniden gonderilebilmeli.
create unique index if not exists ux_its_karekod_tekil
    on public.its_bildirim_satir(gtin, seri_no)
 where seri_no <> '';

comment on table public.its_bildirim is
    'ITS ilac bildirimleri (427). UTS ile KARISTIRILMAZ: UTS cihaz, ITS ilac.';

-- ---------------------------------------------------------------------------
--  KUYRUKTAN ALMA - 399/415 deseninin aynisi (for update skip locked).
-- ---------------------------------------------------------------------------
create or replace function public.fn_its_siradakiler(p_adet integer default 20)
returns setof public.its_bildirim language sql as $$
    update public.its_bildirim b
       set durum = 2, deneme = b.deneme + 1, son_deneme = now()
     where b.id in (
         select x.id from public.its_bildirim x
          where x.durum in (1, 4)
            and x.planlanan <= now()
            and x.deneme < 5
          order by x.planlanan asc, x.id asc
          limit p_adet
          for update skip locked
     )
    returning b.*;
$$;

