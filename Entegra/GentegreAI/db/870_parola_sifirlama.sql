-- 870: PAROLAMI UNUTTUM (kullanıcı: "parolamı unuttum seçeneği ekle login e").
--
-- NUMARA DEGISTI (843 -> 870): 843 ayni anda iki dosyada kullanilmisti.
-- (869 hedeflenmisti, o sirada baska bir calisma 869u aldi.)
-- Tasinan bu dosya oldu; digeri (843_kadro_ana_rol.sql) 845 ve 847nin
-- kullandigi kolonu/fonksiyonu olusturuyor, numarasi buyuse kur.ps1
-- sirali uygulamada onlardan SONRA calisir ve kurulum kirilirdi.
-- Bu dosya bagimsiz: tek tablo + indeks, sonraki dosya atif yapmiyor.
--
-- Akış (oturumsuz, /api/kimlik/parola-unuttum):
--   1. kullanıcı kodu → hesabın kayıtlı cep telefonuna (yoksa e-postasına)
--      6 haneli tek kullanımlık kod gider (bildirim kuyruğu, şablon
--      kimlik.parola_sifirlama / .eposta). Kod BCRYPT ile saklanır; düz kod
--      yalnız mesajda.
--   2. kod + yeni parola → parola yazılır, açık oturumlar kapanır.
-- Kural: 10 dk geçerli, 5 yanlış denemede iptal, 15 dk'da en çok 3 istek.
-- Hesabın telefonu/e-postası yoksa kod gönderilemez; yöneticinin "parola
-- sıfırla"sı (KullaniciYonetimUclari) ve ilk-parola akışı geçerli kalır.

create table if not exists public.parola_sifirlama (
    id            bigint generated by default as identity primary key,
    kullanici_id  integer not null references public.taraf_kullanici (id) on delete cascade,
    kod_hash      varchar(200) not null,
    kanal         smallint not null,                -- 1 sms · 2 e-posta
    hedef         varchar(120) not null default '',  -- gönderilen numara / adres
    bitis         timestamptz not null,
    deneme        smallint not null default 0,
    kullanildi    timestamptz,
    ip            varchar(45) not null default '',
    ekleme_tarihi timestamptz not null default now()
);
comment on table public.parola_sifirlama is 'Parolamı unuttum: tek kullanımlık doğrulama kodları (843)';
create index if not exists ix_parola_sifirlama_kullanici on public.parola_sifirlama (kullanici_id, ekleme_tarihi desc);

insert into public.bildirim_sablon (kod, ad, kanal, konu, govde, degiskenler, durum, aciklama, ekleyen)
select v.kod, v.ad, v.kanal, v.konu, v.govde, v.degiskenler::json, 1, v.aciklama, 0 from (values
    ('kimlik.parola_sifirlama', 'Kimlik: parola sıfırlama kodu (SMS)', 1, '',
     '{{kurum}}: parola sıfırlama kodunuz {{kod}}. {{dakika}} dk geçerlidir. Siz istemediyseniz dikkate almayın.',
     '{"kurum":"Kurum adı","kod":"Doğrulama kodu","dakika":"Geçerlilik (dk)"}', 'Parolamı unuttum - cep telefonuna kod'),
    ('kimlik.parola_sifirlama.eposta', 'Kimlik: parola sıfırlama kodu (e-posta)', 2, '{{kurum}} - parola sıfırlama',
     E'Sayın {{kisi}},\n\nParola sıfırlama kodunuz: {{kod}}\nKod {{dakika}} dakika geçerlidir ve bir kez kullanılır.\n\nBu isteği siz yapmadıysanız bu iletiyi dikkate almayın.',
     '{"kisi":"Kişi adı","kurum":"Kurum adı","kod":"Doğrulama kodu","dakika":"Geçerlilik (dk)"}', 'Parolamı unuttum - e-postaya kod')
) as v(kod, ad, kanal, konu, govde, degiskenler, aciklama)
where not exists (select 1 from public.bildirim_sablon s where s.kod = v.kod);
