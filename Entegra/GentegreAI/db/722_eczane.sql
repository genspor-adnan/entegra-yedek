-- ============================================= kontrollü ilaç defteri ==
-- KASA STOKTAN AYRIDIR ama ayrı bir stok tablosu açmıyoruz: kasa bir `depo`
--   kaydıdır, hareketler yine belge/stok hattından geçer. Buradaki tablo
--   DEFTERDİR: numaralı, çift imzalı, silinmeyen kayıt. Mevzuat defteri
--   istiyor; stok hareketi defterin yerine geçmez.
create table if not exists public.kontrollu_defter (
  id            bigint generated by default as identity primary key,
  sube_id       integer not null default 0,
  defter_no     varchar(30) not null,
  zaman         timestamptz not null default now(),
  -- 1 giriş (mal kabul) · 2 çıkış (reçete/order) · 3 iade · 4 artık imha
  -- 5 devir · 6 sayım
  hareket       smallint not null default 2,
  stok_id       integer references public.stok(id),
  seri_lot_id   integer references public.stok_seri_lot(id),
  ad            varchar(200) not null default '',
  miktar        numeric(12,3) not null default 0,
  -- 1 kırmızı reçete (narkotik) · 2 yeşil reçete (psikotrop)
  recete_renk   smallint not null default 1,
  recete_no     varchar(40) not null default '',
  hasta_id      integer references public.taraf(id),
  departman_id  integer references public.departman(id),
  -- ÇİFT İMZA: teslim eden ve alan ayrı kişilerdir. Artık imhasında ayrıca
  --   TANIK istenir - yarım ampul "kayboldu" olamaz.
  teslim_eden_id integer references public.taraf(id),
  teslim_alan_id integer references public.taraf(id),
  tanik_id      integer references public.taraf(id),
  belge_id      integer references public.belge(id),
  aciklama      varchar(300) not null default '',
  -- DÜZELTME SATIRI: yanlış kayıt SİLİNMEZ, düzeltme satırıyla kapatılır.
  duzeltilen_id bigint references public.kontrollu_defter(id),
  ekleyen       integer not null default 0,
  ekleme_tarihi timestamptz not null default now()
);
create unique index if not exists ux_kontrollu_defter_no
  on public.kontrollu_defter (sube_id, defter_no);
