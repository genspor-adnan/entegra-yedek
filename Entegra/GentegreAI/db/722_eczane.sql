create index if not exists ix_kontrollu_sayim_satir on public.kontrollu_sayim_satir (sayim_id);

-- İKİ SAYIM BİRBİRİNİ GÖRMEDEN yapılır; uyumu tetik hesaplar - ekranda ve
--   sunucuda iki kez hesaplanırsa "tamam" diyen ekranla "fark var" diyen
--   kayıt yan yana gelir.
create or replace function public.fn_kontrollu_sayim_uyum()
returns trigger language plpgsql as $tg$
begin
    if new.sayan1 is null or new.sayan2 is null then
        new.uyumlu := null;
    else
        new.uyumlu := case when new.sayan1 = new.sayan2 and new.sayan1 = new.defter
                           then 1 else 0 end;
    end if;
    return new;
end;
$tg$;

drop trigger if exists tg_kontrollu_sayim_uyum on public.kontrollu_sayim_satir;
create trigger tg_kontrollu_sayim_uyum
  before insert or update of defter, sayan1, sayan2 on public.kontrollu_sayim_satir
  for each row execute function public.fn_kontrollu_sayim_uyum();

-- =========================================================== görünüm ==
-- MİAD + TÜKETİM TEK YERDE. Öneri yalnız tarihe değil tüketim hızına bakar:
--   günlük 6 giden kalem 14 gün kala iade edilmez, tüketilir. İki ekran
--   (eczane panosu, stok & miad) aynı hesabı okusun.
create or replace view public.v_eczane_miad as
select sd.stok_id, sd.depo_id, sl.id as seri_lot_id,
       s.ad, s.kod, sl.lot_no, sl.son_kullanma_tarihi as skt,
       (sl.son_kullanma_tarihi::date - current_date) as kalan_gun,
       ld.kalan as miktar,
       -- Son 90 günün günlük ortalama çıkışı. AYRI BİR HAREKET TABLOSU YOK:
       --   stok hareketi belge satırıdır (`belge_satir`), çıkış yönü belgenin
       --   türünden gelir. İkinci bir hareket defteri tutsaydık belge ile
       --   arasındaki fark ilk düzeltmede ortaya çıkardı.
       coalesce((select round(sum(bs.miktar) / 90.0, 2)
                   from public.belge_satir bs
                   join public.belge b on b.id = bs.belge_id
                  where bs.stok_id = ld.stok_id
                    and coalesce(bs.cikis_depo_id, b.cikis_depo_id) = ld.depo_id
                    and b.durum <> 0                    -- taslak sayılmaz
                    and b.belge_tarihi >= current_date - 90), 0) as gunluk_tuketim
  from public.stok_lot_durum ld
  join public.stok_durum sd on sd.stok_id = ld.stok_id and sd.depo_id = ld.depo_id
  join public.stok_seri_lot sl on sl.id = ld.seri_lot_id
  join public.stok s on s.id = ld.stok_id
 where ld.kalan > 0 and sl.son_kullanma_tarihi is not null;

comment on view public.v_eczane_miad is
