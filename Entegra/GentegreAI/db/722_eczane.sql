-- =====================================================================
--  722_eczane.sql
--  HASTANE ECZANESİ — eczacı kontrolü, ünite doz, hazırlama, iade/imha,
--  kontrollü ilaç defteri.
--
--  Mockup'lar: `Ekranlar/Eczane/*.html`.
--
--  TEMEL KARAR — ORDER TABLOSU AÇILMADI. Yatan hasta orderı `yatis_order`,
--    uygulamaları `order_uygulama` (695). Eczane bunları OKUR; kendi order
--    kopyasını açsaydı hastanın ilaç geçmişi ikiye bölünür, "bu hastaya ne
--    verildi" sorusu iki yerden toplanmak zorunda kalırdı. Bu dosya eczanenin
--    KENDİ kavramlarını ekliyor: eczacı kontrolü, ünite doz hazırlığı,
--    hazırlama (aseptik), iade, imha, kontrollü ilaç defteri.
--
--  TEMEL KARAR — STOK TABLOSU DA AÇILMADI. Miad, lot, depo ve bakiye
--    `stok_durum` / `stok_lot_durum` / `stok_seri_lot`'ta duruyor; eczane
--    deposu bir `depo` kaydıdır. Eczaneye ayrı stok yazsaydık FEFO iki yerde
--    hesaplanır ve ikisi zamanla ayrışırdı.
--
--  TEMEL KARAR — ECZACI KONTROLÜ DOZDAN ÖNCE, AYRI SATIR. Order satırına
--    "eczacı onayladı" bayrağı koymak yetmezdi: bir order satırı için BİRDEN
--    ÇOK uyarı çıkabilir (alerji + etkileşim + böbrek dozu) ve her birinin
--    kendi kararı, gerekçesi ve hekim bildirimi olur. Önlenen ilaç hatası
--    kalite göstergesidir - tek bayrakla sayılamaz.
--
--  TEMEL KARAR — HAZIRLANMIŞ DOZ STOĞA DÖNMEZ. İade kaydı "kabul" derse
--    stoğa girer, "ret" derse imhaya gider; kararı sistem değil eczacı verir
--    ama SEBEBİ kayda geçer (açıldı / sulandırıldı / soğuk zincir bozuldu).
-- =====================================================================

-- ==================================================== eczacı kontrolü ==
-- Bir order satırına birden çok uyarı düşebilir; her biri ayrı satır.
create table if not exists public.eczane_kontrol (
  id            bigint generated by default as identity primary key,
  sube_id       integer not null default 0,
  order_id      integer not null references public.yatis_order(id) on delete cascade,
  -- 1 alerji · 2 etkileşim · 3 doz (böbrek/karaciğer/yaş) · 4 tekrar/mükerrer
  -- 5 yüksek riskli ilaç · 6 uygulama yolu · 7 antibiyotik kısıtlama
  -- 8 sözel order · 9 kontrollü ilaç · 99 diğer
  tur           smallint not null default 99,
  -- 1 bilgi · 2 uyarı · 3 yüksek (geçilemez)
  duzey         smallint not null default 2,
  bulgu         varchar(400) not null default '',
  -- Uyarının DAYANAĞI: hangi kayıt tetikledi (alerji kaydı, KrKl değeri...).
  kaynak        varchar(200) not null default '',
  -- 0 bekliyor · 1 uygun (onaylandı) · 2 öneri yapıldı · 3 durduruldu
  karar         smallint not null default 0,
  oneri         varchar(400) not null default '',
  eczaci_id     integer references public.taraf(id),
  karar_zamani  timestamptz,
  -- HEKİME BİLDİRİM izlenir: eczacı önerisi hekimi bağlamaz, karar hekimin -
  --   ama önerinin iletildiği ve okunduğu kayda geçmeli.
  hekim_id      integer references public.taraf(id),
  bildirim_zamani timestamptz,
  okundu_zamani timestamptz,
  hekim_yaniti  varchar(400) not null default '',
  -- ÖNLENEN HATA (SKS göstergesi): karar 3 ise ve hasta etkilenmediyse 1.
  onlenen_hata  smallint not null default 0,
  ekleyen       integer not null default 0,
  ekleme_tarihi timestamptz not null default now(),
  degistiren    integer not null default 0,
  degistirme_tarihi timestamptz
);
create index if not exists ix_eczane_kontrol_order on public.eczane_kontrol (order_id);
create index if not exists ix_eczane_kontrol_bekleyen
  on public.eczane_kontrol (sube_id, ekleme_tarihi) where karar = 0;

comment on table public.eczane_kontrol is
  'Eczaci kontrolu (722): order satirina dusen uyarilar ve kararlari. Bir satira '
  'birden cok uyari dusebilir - her biri ayri kayit.';

-- ======================================================== ünite doz ==
-- Hazırlanan doz, `order_uygulama` satırına bağlanır: plan orada, hazırlık
--   burada. Ayrı tablo, çünkü bir uygulama HAZIRLANMADAN da geçilebilir
--   (servis stoğundan) ve hazırlanmış doz İADE edilebilir.
create table if not exists public.eczane_doz (
  id            bigint generated by default as identity primary key,
  sube_id       integer not null default 0,
  uygulama_id   integer not null references public.order_uygulama(id) on delete cascade,
  -- DOZ BARKODU: hasta bilekliğiyle eşleşen kimlik. Boş olabilir (numara
  --   şablonu tanımsızsa) ama varsa benzersizdir.
  doz_barkod    varchar(40) not null default '',
  stok_id       integer references public.stok(id),
  seri_lot_id   integer references public.stok_seri_lot(id),
  miktar        numeric(12,3) not null default 0,
  -- 0 bekliyor · 1 hazırlandı · 2 kontrol edildi · 3 teslim edildi
  -- 4 uygulandı · 8 iade · 9 imha
  durum         smallint not null default 0,
  hazirlayan_id integer references public.taraf(id),
  hazirlama_zamani timestamptz,
  -- ÇİFT KONTROL yüksek riskli ilaçta zorunlu; kimin kontrol ettiği ayrı alan.
  kontrol_eden_id integer references public.taraf(id),
  kontrol_zamani  timestamptz,
  teslim_zamani timestamptz,
  teslim_alan_id integer references public.taraf(id),
  aciklama      varchar(300) not null default '',
  ekleyen       integer not null default 0,
  ekleme_tarihi timestamptz not null default now()
);
create index if not exists ix_eczane_doz_uygulama on public.eczane_doz (uygulama_id);
create unique index if not exists ux_eczane_doz_barkod
  on public.eczane_doz (doz_barkod) where doz_barkod <> '';
create index if not exists ix_eczane_doz_bekleyen
  on public.eczane_doz (sube_id, durum) where durum in (0, 1, 2);

comment on table public.eczane_doz is
  'Unite doz hazirligi (722). Tek hasta, tek saat; lot/SKT dozla birlikte '
  'kaydedilir - geri cagirmada aranan budur.';

-- ============================================== aseptik hazırlama ==
-- Kemoterapi / TPN / sürekli infüzyon. Ayrı tablo çünkü ünite dozdan farklı:
--   protokole ve hastanın VYA/AUC değerine göre DOZ HESAPLANIR, iki eczacı
--   bağımsız doğrular, kabin koşulları kaydedilir ve ürünün ömrü saatlerledir.
create table if not exists public.eczane_hazirlama (
  id            bigint generated by default as identity primary key,
  sube_id       integer not null default 0,
  hazirlama_no  varchar(30) not null default '',
  -- 1 kemoterapi · 2 TPN · 3 sürekli infüzyon · 9 diğer
  tur           smallint not null default 1,
  hasta_id      integer not null references public.taraf(id),
  yatis_id      integer references public.yatis(id),
  belge_id      integer references public.belge(id),
  protokol      varchar(200) not null default '',
  kur_no        smallint not null default 0,
  kur_toplam    smallint not null default 0,
  -- DOZ HESABININ GİRDİLERİ kayda geçer: aynı hastanın boyu/kilosu kürler
  --   arasında değişir, doz onunla değişir. Sonradan "bu doz nasıl çıktı"
  --   sorusu ancak girdilerle yanıtlanır.
  boy_cm        numeric(5,1),
  kilo_kg       numeric(6,2),
  vya_m2        numeric(5,3),
  krkl          numeric(6,2),
  planlanan     timestamptz,
  -- 0 sırada · 1 ön koşul bekliyor · 2 doz onayı bekliyor · 3 hazırlanıyor
  -- 4 hazır · 5 teslim edildi · 8 iptal
  durum         smallint not null default 0,
  iptal_neden   varchar(200) not null default '',
  -- HASTA GELMEDEN HAZIRLANMAZ: hazırlanıp iptal edilen ürün çöpe gider.
  hasta_geldi_zamani timestamptz,
  hazirlayan_id integer references public.taraf(id),
  hazirlama_zamani timestamptz,
  -- İKİNCİ ECZACI doğrulaması (çift kontrol) - kemoterapide yanlış doz geri alınamaz.
  dogrulayan_id integer references public.taraf(id),
  dogrulama_zamani timestamptz,
  kabin_kod     varchar(30) not null default '',
  -- SON KULLANIM HAZIRLAMA ANINDAN sayılır, ilacın kutu miadından değil.
  son_kullanim  timestamptz,
  saklama       varchar(80) not null default '',
  teslim_zamani timestamptz,
  teslim_alan_id integer references public.taraf(id),
  ekleyen       integer not null default 0,
  ekleme_tarihi timestamptz not null default now(),
  degistiren    integer not null default 0,
  degistirme_tarihi timestamptz
);
create index if not exists ix_eczane_hazirlama_gun
  on public.eczane_hazirlama (sube_id, planlanan);
create index if not exists ix_eczane_hazirlama_hasta on public.eczane_hazirlama (hasta_id);

comment on table public.eczane_hazirlama is
