-- Defter satırı silinemez - mevzuat defteridir.
create or replace function public.fn_kontrollu_defter_silinmez()
returns trigger language plpgsql as $tg$
begin
    raise exception 'Kontrollü ilaç defteri satırı silinemez; düzeltme satırı ekleyin.'
          using errcode = 'restrict_violation';
end;
$tg$;

drop trigger if exists tg_kontrollu_defter_silinmez on public.kontrollu_defter;
create trigger tg_kontrollu_defter_silinmez
  before delete on public.kontrollu_defter
  for each row execute function public.fn_kontrollu_defter_silinmez();

