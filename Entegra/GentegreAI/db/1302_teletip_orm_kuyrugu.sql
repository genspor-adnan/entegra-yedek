-- 1302 - Teletıp ORM kuyruğu: radyoloji istemi -> HL7 ORM^O01 (NW / XO / CA) -> Mirth K1 -> Teletıp
--
-- Kullanıcı 11.11.2026: "ORM'yi kuyruğa ve akışa bağla". Üretici C#'ta (Gentegre.Cekirdek OrmUretici, kılavuz 3.43
-- birebir); burada: (1) ayarlar, (2) gönderim tablosu, (3) mesaj verisini TEK YERDEN toplayan fn_teletip_orm_verisi,
-- (4) radyoloji_istem tetiği - hangi olayda hangi emir kuyruğa girer.
--
-- Kurallar:
--   * Teletıp kapalıysa (teletip.aktif <> '1') hiçbir şey kuyruğa girmez - özel merkez etkilenmez.
--   * NW: istem "hazır" olunca (iptal değil, accession dolu, sevkli accession beklemiyor) BİR KEZ.
--   * XO: NW gönderildikten (AA) sonra mesajı etkileyen alan değişirse; bekleyen XO varsa yenisi açılmaz (mesaj
--     gönderim anında güncel veriden kurulur). NW henüz gitmediyse XO gereksiz - NW zaten güncel veriyle gider;
--     NW "gidemez" (eksik) durumundaysa veri değişince tekrar denemeye alınır.
--   * CA: istem iptal edilir ya da silinirse ve NW gönderilmişse. Veri o an anlık görüntü (veri jsonb) olarak
--     saklanır - silinen istemin mesajı sonradan kurulamaz. NW hiç gitmediyse bekleyenler "atlandı" olur, CA yok.
--   * Accession değişirse (gönderildikten sonra): eski numarayla CA + yeni numarayla NW (Bakanlık istemi
--     accession ile tanır).
--
-- Tekrar çalıştırılabilir.
\set ON_ERROR_STOP on
begin;

-- ------------------------------------------------------------------ 1) ayarlar
insert into public.referans (anahtar, deger, tip, kapsam, aciklama) values
  ('teletip.aktif', '0', 'sayi', 'firma',
   'Teletıp (Bakanlık Teleradyoloji) gönderimi: 1 = radyoloji istemleri HL7 ORM ile kuyruğa girer. Özel merkezde 0.'),
  ('teletip.hl7_adres', '', 'metin', 'firma',
   'Teletıp HL7 hedefi host:port - Mirth K1 (TELETIP_HL7) dinleyicisi, ör. 10.0.0.12:6661. Boşsa kuyruk bekler.'),
  ('teletip.firma_kodu', '', 'metin', 'firma',
   'MSH-3 firma uygulama kodu - e-Nabız sisteminde kayıtlı olduğu gibi (yanlışsa Bakanlık 0275 döner).'),
  ('teletip.encoding', 'UTF8', 'metin', 'firma',
   'MSH-18: UTF8 ya da Windows1254 (Windows1254 Bakanlık''a önceden bildirilir).'),
  ('teletip.sube_no', '1', 'metin', 'firma',
   'ORC-21 şube numarası (Kurum^^SKRS\S\şube\S\MEDULA tesis).')
on conflict (anahtar) do nothing;

-- ------------------------------------------------------------------ 2) gönderim tablosu
create table if not exists public.teletip_gonderim (
  id               bigint generated by default as identity primary key,
  istem_id         integer references public.radyoloji_istem(id) on delete set null,
  accession_no     varchar(40)  not null default '',      -- istem silinse de iz kalsın
  kanal            smallint     not null default 1,       -- 1 HL7 ORM · 2 KOS · 3 HL7 ORU · 4 doz
  emir             smallint     not null default 1,       -- ORM: 1 NW · 2 XO · 3 CA
  durum            smallint     not null default 0,       -- 0 bekliyor · 1 gönderildi (AA) · 2 reddedildi (AE)
                                                          -- 3 gidemez (eksik) · 4 atlandı · 5 ulaşmadı (tekrar)
  deneme_no        integer      not null default 0,
  sonraki_deneme   timestamptz  not null default now(),
  son_deneme       timestamptz,
  ack_kodu         varchar(4)   not null default '',
  hata_metni       varchar(2000) not null default '',
  kontrol_no       varchar(40)  not null default '',
  mesaj            text         not null default '',      -- son gönderilen ham HL7 (kart: mesaj izi)
  yanit            text         not null default '',      -- son ACK
  veri             jsonb,                                  -- CA için anlık görüntü (istem silinmiş olabilir)
  sube_id          integer      not null default 0,
  ekleyen          integer      not null default 0,
  ekleme_tarihi    timestamptz  not null default now(),
  constraint ck_teletip_gonderim_durum check (durum between 0 and 5),
  constraint ck_teletip_gonderim_emir check (emir between 1 and 3)
);
comment on table public.teletip_gonderim is
  '1302: Teletıp gönderim kuyruğu ve izi (ORM NW/XO/CA; ileride KOS/ORU/doz). Gönderen TeletipOrmServisi (Mirth K1).';
create index if not exists ix_teletip_gonderim_bekleyen on public.teletip_gonderim (sonraki_deneme, id)
  where durum in (0, 5);
create index if not exists ix_teletip_gonderim_istem on public.teletip_gonderim (istem_id, id);
create index if not exists ix_teletip_gonderim_acc on public.teletip_gonderim (accession_no);

-- ------------------------------------------------------------------ 3) mesaj verisi (tek kaynak)
-- Anahtarlar C# OrmVerisi özellik adlarıyla AYNI (System.Text.Json doğrudan okur). Zamanlar şube yerel saati,
-- dilimsiz ("YYYY-MM-DDTHH:MI:SS") - HL7 yerel saat ister.
create or replace function public.fn_teletip_orm_verisi(p_istem_id integer)
returns jsonb language sql stable as $$
  with i as (
    select r.*, public.fn_sube_zaman_dilimi(r.sube_id) as tz
      from public.radyoloji_istem r where r.id = p_istem_id
  )
  select jsonb_build_object(
    'HbysAdi',          coalesce(nullif(sb.unvan, ''), sb.ad, ''),
    'Zaman',            to_char(now() at time zone i.tz, 'YYYY-MM-DD"T"HH24:MI:SS'),
    'HastaDosyaNo',     coalesce(h.kod, ''),
    'HastaTckn',        case when coalesce(h.vkno, '') ~ '^[1-9][0-9]{10}$' then h.vkno else '' end,
    'PasaportNo',       case when coalesce(h.vkno, '') ~ '^[1-9][0-9]{10}$' then '' else coalesce(th.pasaport_no, '') end,
    'UlkeKodu',         coalesce(u.skrs_kod::text, ''),
    'HastaSoyad',       upper(coalesce(nullif(h.soyad, ''), h.unvan, '')),
    'HastaAd',          upper(coalesce(h.ad, '')),
    'DogumTarihi',      to_char(th.dogum_tarihi, 'YYYY-MM-DD"T00:00:00"'),
    'Cinsiyet',         case th.cinsiyet when 1 then 'M' when 2 then 'F' else 'U' end,
    'EvTelefonu',       coalesce(nullif(h.cep_tel, ''), h.telefon, ''),
    'Eposta',           coalesce(h.eposta, ''),
    'AnneTckn',         coalesce(th.anne_tckn, ''),
    'DogumYeri',        coalesce(th.dogum_yeri::text, ''),
    'HastaSinifi',      case bb.basvuru_turu when 2 then 'E' when 3 then 'I' else 'O' end,
    'BirimId',          coalesce(bb.bolum_id::text, ''),
    'BirimAdi',         coalesce(dp.ad, ''),
    'BasvuruReferansi', coalesce(nullif(ref.hastane_referans, ''), ''),
    'Sgk',              coalesce(bp.sgk_takip_no, '') <> '',
    'MedulaTakipNo',    coalesce(bp.sgk_takip_no, ''),
    'KabulZamani',      to_char(coalesce(i.kabul_tarihi, i.ekleme_tarihi) at time zone i.tz, 'YYYY-MM-DD"T"HH24:MI:SS'),
    'AccessionNo',      i.accession_no,
    'IstemZamani',      to_char(i.ekleme_tarihi at time zone i.tz, 'YYYY-MM-DD"T"HH24:MI:SS'),
    'PlanlananZaman',   to_char(coalesce(rv.baslangic, i.kabul_tarihi, i.ekleme_tarihi) at time zone i.tz, 'YYYY-MM-DD"T"HH24:MI:SS'),
    'Giren',            jsonb_build_object('Kimlik', coalesce(i.ekleyen::text, ''), 'Soyad', upper(coalesce(gt.soyad, '')),
                                           'Ad', upper(coalesce(gt.ad, ''))),
    'IsteyenHekim',     jsonb_build_object(
                          'Kimlik', case when coalesce(hk.vkno, '') ~ '^[1-9][0-9]{10}$' then hk.vkno
                                         else coalesce(nullif(i.dis_hekim_tckn, ''), '') end,
                          'Soyad', upper(coalesce(nullif(hk.soyad, ''), split_part(coalesce(i.dis_hekim_ad, ''), ' ', 2))),
                          'Ad',    upper(coalesce(nullif(hk.ad, ''), split_part(coalesce(i.dis_hekim_ad, ''), ' ', 1))),
                          'Onek',  coalesce(hk.unvan, '')),
    'KurumAdi',         coalesce(nullif(sb.unvan, ''), sb.ad, ''),
    'KurumKisaAdi',     coalesce(sb.ad, ''),
    'KurumSkrs',        coalesce((select r.deger from public.referans r where r.anahtar = 'kurum.skrs_kodu'), ''),
    'SubeNo',           coalesce((select r.deger from public.referans r where r.anahtar = 'teletip.sube_no'), '1'),
    'MedulaTesisKodu',  coalesce(nullif((select kp.tesis_kodu from public.kurum_profil kp
                                          where kp.sube_id in (i.sube_id, 0) and coalesce(kp.tesis_kodu, '') <> ''
                                          order by (kp.sube_id = i.sube_id) desc limit 1), ''),
                                 bp.sgk_tesis_kodu, ''),
    'SutKodu',          coalesce(s.sut_kodu, ''),
    'SutAdi',           coalesce(s.ad, '') || public.fn_radyoloji_yon_ek(i.yon),
    'Loinc',            case when coalesce(s.loinc, '') = '' then '[]'::jsonb
                             else jsonb_build_array(jsonb_build_object('Kod', s.loinc, 'Ad', coalesce(nullif(s.kisa_ad, ''), s.ad, ''))) end,
    'KlinikBilgi',      coalesce(i.klinik_bilgi, ''),
    'SysTakipNo',       coalesce(nullif(ref.sys_takip_no, ''), bb.sys_takip_no, ''),
    'HastaneReferansi', coalesce(nullif(ref.hastane_referans, ''), ''),
    'Modalite',         public.fn_radyoloji_dicom_modalite(i.modalite),
    'Teknisyen',        case when i.tekniker_id is null then jsonb_build_object()
                             else jsonb_build_object('Kimlik', i.tekniker_id::text, 'Soyad', upper(coalesce(tk.soyad, '')),
                                                     'Ad', upper(coalesce(tk.ad, ''))) end,
    'Tanilar',          coalesce(tn.liste, '[]'::jsonb)
  )
    from i
    join public.taraf h on h.id = i.hasta_id
    left join public.taraf_hasta th on th.id = h.id
    left join public.ulke u on u.id = th.uyruk
    left join public.sube sb on sb.id = i.sube_id
    left join public.belge_basvuru bb on bb.id = i.belge_id
    left join public.departman dp on dp.id = bb.bolum_id
    left join public.belge_provizyon bp on bp.id = i.belge_id
    left join public.randevu rv on rv.id = i.randevu_id
    left join public.hizmet s on s.id = i.hizmet_id
    left join public.taraf hk on hk.id = i.istek_hekim_id
    left join public.taraf tk on tk.id = i.tekniker_id
    left join public.taraf gt on gt.id = i.ekleyen          -- kullanıcı = taraf (taraf_kullanici)
    left join lateral (select * from public.fn_enabiz_basvuru_referans(i.belge_id)) ref on i.belge_id is not null
    left join lateral (
      -- Başvurunun muayene tanıları (kesin = F, diğerleri A); yoksa istemin ön tanısındaki ICD kodu.
      select jsonb_agg(jsonb_build_object('Icd', x.icd, 'Ad', x.ad, 'Tur', x.tur) order by x.sira) as liste
        from (
          select t.icd_kod as icd, coalesce(ic.ad, '') as ad, case when t.kesinlik = 1 then 'F' else 'A' end as tur,
                 t.sira * 1000 + t.id as sira
            from public.muayene m
            join public.tani t on t.muayene_id = m.id
            left join public.icd ic on ic.kod = t.icd_kod
           where i.belge_id is not null and m.belge_id = i.belge_id
          union all
          select substring(i.on_tani from '^([A-Z][0-9]{2}(?:\.[0-9A-Z]{1,4})?)'), coalesce(ic.ad, ''), 'A', 1
            from (select 1) z
            left join public.icd ic on ic.kod = substring(i.on_tani from '^([A-Z][0-9]{2}(?:\.[0-9A-Z]{1,4})?)')
           where substring(coalesce(i.on_tani, '') from '^([A-Z][0-9]{2}(?:\.[0-9A-Z]{1,4})?)') is not null
             and not exists (select 1 from public.muayene m join public.tani t on t.muayene_id = m.id
                              where i.belge_id is not null and m.belge_id = i.belge_id)
        ) x
    ) tn on true
$$;
comment on function public.fn_teletip_orm_verisi(integer) is
  '1302: Teletıp ORM mesaj verisi (jsonb, anahtarlar = C# OrmVerisi). Tek kaynak: kuyruk gönderimi ve CA anlık görüntüsü.';

-- ------------------------------------------------------------------ 4) kuyruğa alma + tetik
create or replace function public.fn_teletip_aktif()
returns boolean language sql stable as $$
  select coalesce((select deger from public.referans where anahtar = 'teletip.aktif'), '0') = '1'
$$;

create or replace function public.fn_teletip_orm_kuyrukla(p_istem_id integer, p_accession varchar, p_emir smallint,
                                                          p_sube_id integer, p_kullanici integer, p_veri jsonb default null)
returns bigint language sql as $$
  insert into public.teletip_gonderim (istem_id, accession_no, kanal, emir, durum, veri, sube_id, ekleyen)
  values (p_istem_id, coalesce(p_accession, ''), 1, p_emir, 0, p_veri, coalesce(p_sube_id, 0), coalesce(p_kullanici, 0))
  returning id
$$;

create or replace function public.tg_radyoloji_istem_teletip()
returns trigger language plpgsql as $$
declare
  v_kul int;
  v_nw_gitti boolean;
  v_nw_var boolean;
  v_veri jsonb;
begin
  if not public.fn_teletip_aktif() then
    return case when tg_op = 'DELETE' then old else new end;
  end if;

  if tg_op = 'DELETE' then
    if exists (select 1 from public.teletip_gonderim g where g.istem_id = old.id and g.kanal = 1 and g.emir = 1 and g.durum = 1) then
      perform public.fn_teletip_orm_kuyrukla(old.id, old.accession_no, 3::smallint, old.sube_id,
                                             coalesce(old.degistiren, old.ekleyen), public.fn_teletip_orm_verisi(old.id));
    end if;
    update public.teletip_gonderim set durum = 4, hata_metni = 'İstem silindi.'
     where istem_id = old.id and kanal = 1 and durum in (0, 3, 5) and emir <> 3;
    return old;
  end if;

  v_kul := coalesce(new.degistiren, new.ekleyen, 0);
  select coalesce(bool_or(g.emir = 1 and g.durum = 1), false), coalesce(bool_or(g.emir = 1 and g.durum <> 4), false)
    into v_nw_gitti, v_nw_var
    from public.teletip_gonderim g where g.istem_id = new.id and g.kanal = 1;

  -- İPTAL
  if new.durum = 0 then
    if tg_op = 'UPDATE' and old.durum <> 0 then
      update public.teletip_gonderim set durum = 4, hata_metni = 'İstem iptal edildi.'
       where istem_id = new.id and kanal = 1 and durum in (0, 3, 5) and emir <> 3;
      if v_nw_gitti then
        perform public.fn_teletip_orm_kuyrukla(new.id, new.accession_no, 3::smallint, new.sube_id, v_kul,
                                               public.fn_teletip_orm_verisi(new.id));
      end if;
    end if;
    return new;
  end if;

  -- HAZIR DEĞİL: accession yok / sevkli accession bekliyor
  if coalesce(new.accession_no, '') = '' or coalesce(new.accession_bekliyor, 0) = 1 then
    return new;
  end if;

  -- ACCESSION DEĞİŞTİ (gönderildikten sonra): eski numarayla CA, yeni numarayla NW
  if tg_op = 'UPDATE' and v_nw_gitti and coalesce(old.accession_no, '') <> '' and old.accession_no <> new.accession_no then
    v_veri := jsonb_set(public.fn_teletip_orm_verisi(new.id), '{AccessionNo}', to_jsonb(old.accession_no));
    perform public.fn_teletip_orm_kuyrukla(new.id, old.accession_no, 3::smallint, new.sube_id, v_kul, v_veri);
    update public.teletip_gonderim set durum = 4, hata_metni = 'Accession değişti.'
     where istem_id = new.id and kanal = 1 and durum in (0, 3, 5) and emir = 2;
    perform public.fn_teletip_orm_kuyrukla(new.id, new.accession_no, 1::smallint, new.sube_id, v_kul);
    return new;
  end if;

  -- YENİ (NW): bir kez
  if not v_nw_var then
    perform public.fn_teletip_orm_kuyrukla(new.id, new.accession_no, 1::smallint, new.sube_id, v_kul);
    return new;
  end if;

  -- GÜNCELLEME: mesajı etkileyen alan değiştiyse
  if tg_op = 'UPDATE' and (
       old.hizmet_id is distinct from new.hizmet_id or old.modalite is distinct from new.modalite
    or old.randevu_id is distinct from new.randevu_id or old.istek_hekim_id is distinct from new.istek_hekim_id
    or old.on_tani is distinct from new.on_tani or old.klinik_bilgi is distinct from new.klinik_bilgi
    or old.yon is distinct from new.yon or old.kabul_tarihi is distinct from new.kabul_tarihi
    or old.tekniker_id is distinct from new.tekniker_id or old.dis_hekim_tckn is distinct from new.dis_hekim_tckn) then
    -- Eksik yüzünden duran NW / XO veri değişince yeniden denenir.
    update public.teletip_gonderim set durum = 0, sonraki_deneme = now(), hata_metni = ''
     where istem_id = new.id and kanal = 1 and durum = 3;
    if v_nw_gitti and not exists (select 1 from public.teletip_gonderim g
                                   where g.istem_id = new.id and g.kanal = 1 and g.emir = 2 and g.durum in (0, 3, 5)) then
      perform public.fn_teletip_orm_kuyrukla(new.id, new.accession_no, 2::smallint, new.sube_id, v_kul);
    end if;
  end if;
  return new;
end $$;

drop trigger if exists tg_radyoloji_istem_teletip on public.radyoloji_istem;
create trigger tg_radyoloji_istem_teletip
  after insert or update on public.radyoloji_istem
  for each row execute function public.tg_radyoloji_istem_teletip();
drop trigger if exists tg_radyoloji_istem_teletip_sil on public.radyoloji_istem;
create trigger tg_radyoloji_istem_teletip_sil
  before delete on public.radyoloji_istem
  for each row execute function public.tg_radyoloji_istem_teletip();

commit;

do $$ begin
  raise notice '1302 tamam: Teletıp ORM kuyruğu. teletip.aktif = % (1 olmadan kuyruğa bir şey girmez), teletip.hl7_adres = "%"',
    (select deger from public.referans where anahtar = 'teletip.aktif'),
    (select deger from public.referans where anahtar = 'teletip.hl7_adres');
end $$;
