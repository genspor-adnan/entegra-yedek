--
--  Kullanıcı (24.10.2026): "kasa liste ve kartı koda dök" (mockup
--  Ekranlar/kasa_listesi_ver3.html + kasa_karti_ver3.html).
--
--  · hesap: kasa limit ve sayım kuralları (Limitler & Kurallar sekmesi).
--  · hesap_yetki: kasaya işleyebilen kullanıcı / rol (Yetkiler sekmesi) -
--    rol yetkisinin ÜSTÜNE daraltma; şimdilik tanım (uygulama kapısı ayrı iş).
--  · v_kasa_ozet: liste kolonları ve KPI - bugün giriş / çıkış, son sayım ve
--    farkı, bugün sayıldı mı, son 7 gün net eğrisi, açık banko oturumu.
--    Günler oturum dilimi yerine Europe/Istanbul (KasaGunSonu ile aynı).
--  İdempotent.
-- =============================================================================

begin;

alter table public.hesap
    add column if not exists guvenlik_limiti     numeric(14,2) not null default 0,   -- azami nakit (0 = yok)
    add column if not exists gunluk_odeme_limiti numeric(14,2) not null default 0,
    add column if not exists tek_islem_limiti    numeric(14,2) not null default 0,   -- üstü onaylı
    add column if not exists eksi_bakiye_yasak   smallint      not null default 0,
    add column if not exists sayim_zorunlu       smallint      not null default 0,   -- her gün gün sonu sayımı
    add column if not exists sayim_saati         varchar(5)    not null default '',
    add column if not exists fark_toleransi      numeric(14,2) not null default 0,
    add column if not exists kupur_zorunlu       smallint      not null default 0;

comment on column public.hesap.guvenlik_limiti is 'Kasada tutulabilecek azami nakit; asinca liste sari, 1,25 katinda kirmizi (1161).';
comment on column public.hesap.sayim_zorunlu   is '1: her gun gun sonu sayimi beklenir - KPI "sayim bekleyen" bunu sayar (1161).';

create table if not exists public.hesap_yetki (
    id                integer generated by default as identity primary key,
    hesap_id          integer  not null references public.hesap (id) on delete cascade,
    kullanici_id      integer,                               -- taraf_kullanici.id (biri dolu)
    rol_id            integer,                               -- rol.id
    gor               smallint not null default 1,
    tahsilat          smallint not null default 0,
    odeme             smallint not null default 0,
    virman            smallint not null default 0,
    sayim             smallint not null default 0,
    limit_onay        smallint not null default 0,
    sube_id           integer  not null default 0,
    ekleyen           integer  not null default 0,
    ekleme_tarihi     timestamp not null default now()::timestamp,
    degistiren        integer  not null default 0,
    degistirme_tarihi timestamp
);
create index if not exists ix_hesap_yetki_hesap on public.hesap_yetki (hesap_id);
comment on table public.hesap_yetki is 'Kasaya isleyebilen kullanici / rol ve islem turleri (mockup kasa_karti_ver3 Yetkiler). Rol yetkisinin ustune daraltma.';

create or replace view public.v_kasa_ozet as
with yp as (
    select (now() at time zone 'Europe/Istanbul')::date as bugun
),
h as (
    select m.hesap_id, (m.islem_tarihi at time zone 'Europe/Istanbul')::date as gun, m.borc, m.alacak, m.tur_grup
      from public.v_mali_hareket_ek m
      join public.hesap hs on hs.id = m.hesap_id and hs.tur = 'K'
     where m.hesap_ekstre = 1 and m.islem_durum = 2
),
gun as (
    select h.hesap_id,
           sum(h.borc)   filter (where h.gun = yp.bugun) as bugun_giris,
           sum(h.alacak) filter (where h.gun = yp.bugun) as bugun_cikis,
           count(*)      filter (where h.gun = yp.bugun) as bugun_adet,
           sum(h.borc - h.alacak) filter (where h.gun >= date_trunc('month', yp.bugun)::date) as ay_net,
           max(h.gun)    filter (where h.tur_grup = 'virman' and h.alacak > 0) as son_yatirma
      from h, yp
     group by h.hesap_id
),
egri as (
    select k.hesap_id, string_agg(round(coalesce(x.t, 0))::text, ',' order by g.gun) as son7
      from (select distinct hesap_id from h) k
     cross join (select (yp.bugun - i) as gun from yp, generate_series(6, 0, -1) i) g
      left join (select hesap_id, gun, sum(borc - alacak) as t from h group by 1, 2) x
             on x.hesap_id = k.hesap_id and x.gun = g.gun
     group by k.hesap_id
),
sayim as (
    select distinct on (s.hesap_id) s.hesap_id, s.tarih, s.sayilan, s.sayim_zamani, s.sayan_id, s.aciklama
      from public.kasa_gun_sayim s
     order by s.hesap_id, s.tarih desc, s.sayim_zamani desc
),
oturum as (
    select bk.hesap_id, count(*) as n,
           string_agg(coalesce(public.fn_taraf_ad(t.unvan, t.ad, t.soyad)::text, ''), ', ') as kisiler
      from public.banko_oturum o
      join public.banko bk on bk.id = o.banko_id
      left join public.taraf t on t.id = o.kullanici_id
     where o.durum = 2 and bk.hesap_id is not null
     group by bk.hesap_id
)
select hs.id as hesap_id,
       coalesce(g.bugun_giris, 0) as bugun_giris, coalesce(g.bugun_cikis, 0) as bugun_cikis, coalesce(g.bugun_adet, 0) as bugun_adet,
       coalesce(g.ay_net, 0) as ay_net, g.son_yatirma,
       coalesce(e.son7, '') as son7,
       s.tarih as son_sayim_tarih, s.sayim_zamani as son_sayim_zaman, s.sayilan as son_sayilan, s.sayan_id as son_sayan_id,
       case when s.tarih is null then null
            else s.sayilan - (select coalesce(sum(h2.borc - h2.alacak), 0) from h h2 where h2.hesap_id = hs.id and h2.gun <= s.tarih) end as son_fark,
       coalesce(s.aciklama, '') as son_fark_aciklama,
       case when s.tarih = yp.bugun then 1 else 0 end as bugun_sayildi,
       coalesce(o.n, 0) as acik_oturum, coalesce(o.kisiler, '') as oturum_kisiler
  from public.hesap hs
 cross join yp
  left join gun g on g.hesap_id = hs.id
  left join egri e on e.hesap_id = hs.id
  left join sayim s on s.hesap_id = hs.id
  left join oturum o on o.hesap_id = hs.id
 where hs.tur = 'K';

comment on view public.v_kasa_ozet is 'Kasa listesi V3 kolonlari ve KPI (1161): bugun giris / cikis, son sayim + fark, bugun sayildi mi, son 7 gun net, acik banko oturumu.';

commit;
