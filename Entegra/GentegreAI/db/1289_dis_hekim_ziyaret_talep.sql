-- Ziyaret: temsilci boşsa şube temsilcisi; yapılan ziyaretin sonraki tarihi temsilciye hatırlatma açar.
create or replace function public.tg_dis_hekim_ziyaret_hazirla()
returns trigger language plpgsql as $$
declare
    v_hekim_ad text;
    v_hid      integer;
begin
    if new.temsilci_id is null then
        new.temsilci_id := public.fn_dis_hekim_temsilci(new.hekim_id, new.sube_id, new.tarih::date);
    end if;
    if new.sure_dk = 0 and new.bas_zamani is not null and new.bit_zamani is not null and new.bit_zamani > new.bas_zamani then
        new.sure_dk := extract(epoch from (new.bit_zamani - new.bas_zamani))::integer / 60;
    end if;
    -- SONRAKİ ZİYARET HATIRLATMASI: yalnız yapılmış ziyarette, temsilci belliyken, bir kez.
    if new.durum = 1 and new.sonraki_tarih is not null and coalesce(new.hatirlat, 0) = 1
       and new.hatirlatma_id is null and new.temsilci_id is not null then
        select public.fn_taraf_ad(t.unvan, t.ad, t.soyad)::text into v_hekim_ad from public.taraf t where t.id = new.hekim_id;
        insert into public.hatirlatma (sahip_id, baslik, notu, zaman, uyar_dk, oncelik, kaynak, kaynak_id, kaynak_ad, sube_id, ekleyen)
        values (new.temsilci_id, left('Ziyaret: ' || coalesce(v_hekim_ad, ''), 120), left(coalesce(new.notu, ''), 500),
                (new.sonraki_tarih + time '09:00')::timestamptz, 1440, 2, 'dis_hekim_ziyaret', new.id,
                left(coalesce(v_hekim_ad, ''), 120), new.sube_id, new.temsilci_id)
        returning id into v_hid;
        new.hatirlatma_id := v_hid;
    end if;
    return new;
end $$;
drop trigger if exists tr_dis_hekim_ziyaret_hazirla on public.dis_hekim_ziyaret;
create trigger tr_dis_hekim_ziyaret_hazirla before insert or update on public.dis_hekim_ziyaret
    for each row execute function public.tg_dis_hekim_ziyaret_hazirla();

-- Talep: ziyaretten doğuyorsa hekim / şube ziyaretten; kapanınca damga.
create or replace function public.tg_dis_hekim_talep_hazirla()
returns trigger language plpgsql as $$
begin
    if new.ziyaret_id is not null and (new.hekim_id is null or coalesce(new.sube_id, 0) = 0) then
        select coalesce(new.hekim_id, z.hekim_id), case when coalesce(new.sube_id, 0) = 0 then z.sube_id else new.sube_id end
          into new.hekim_id, new.sube_id
          from public.dis_hekim_ziyaret z where z.id = new.ziyaret_id;
    end if;
    if new.hekim_id is null then
        raise exception 'Talebin doktoru belirtilmeli.' using errcode = 'GK422';
    end if;
    if new.durum in (3, 4) and new.kapanma is null then new.kapanma := now(); end if;
    if new.durum in (1, 2) then new.kapanma := null; end if;
    return new;
end $$;
drop trigger if exists tr_dis_hekim_talep_hazirla on public.dis_hekim_talep;
create trigger tr_dis_hekim_talep_hazirla before insert or update on public.dis_hekim_talep
    for each row execute function public.tg_dis_hekim_talep_hazirla();

