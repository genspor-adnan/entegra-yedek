-- --- kurulum kullanicisi ----------------------------------------------------
-- Sistem yoneticisi personel rollu bir taraf kaydidir. Gercek kullanicilar
--   021_goc_kimlik.sql ile eski KULLANICI tablosundan gelir.
do $$
declare
    v_taraf integer;
    v_rol   integer;
    v_sube  integer;
begin
    select id into v_rol from public.rol where kod = 'yonetici';

    if to_regclass('public.sube') is not null then
        select id into v_sube from public.sube where varsayilan = 1 limit 1;
    end if;

    select id into v_taraf from public.taraf_kullanici where kod = 'admin';

    if v_taraf is null then
        select t.id into v_taraf
          from public.taraf t
         where t.unvan = 'Sistem Yoneticisi'
         limit 1;

        if v_taraf is null then
            insert into public.taraf (kod, unvan, eski_tip, sube_id)
            values ('ADMIN', 'Sistem Yoneticisi', 3, v_sube)
            returning id into v_taraf;
        end if;

        -- personel bayragi 017'de eklenir; sadece-sema kurulumunda henuz olmayabilir
        begin
            execute 'update public.taraf set personel = 1 where id = $1' using v_taraf;
        exception when undefined_column then
            null;
        end;

        insert into public.taraf_kullanici (id, kod, rol_id, parola_degismeli)
        values (v_taraf, 'admin', v_rol, 1);

        -- ilk parola: kurulumdan sonra DEGISTIRILMEK ZORUNDA (parola_degismeli = 1)
        perform public.fn_parola_ata(v_taraf, 'Gentegre!2026', 1::smallint);
    end if;

    if v_sube is not null and to_regclass('public.kullanici_sube') is not null then
        insert into public.kullanici_sube (taraf_id, sube_id, varsayilan)
        values (v_taraf, v_sube, 1)
        on conflict (taraf_id, sube_id) do nothing;
    end if;
end $$;

