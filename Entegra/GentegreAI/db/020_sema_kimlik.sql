-- ------------------------------------------- degistirme_tarihi tetikleyici ----
-- 015'teki dongu bu tablolardan once calistigi icin burada tekrarlanir.
do $$
declare t text;
begin
    for t in
        select c.relname from pg_class c
          join pg_namespace n on n.oid = c.relnamespace
         where n.nspname = 'public' and c.relkind = 'r'
           and c.relname in ('rol', 'rol_yetki', 'kullanici')
    loop
        execute format('drop trigger if exists trg_%s_degistirme on public.%I', t, t);
        execute format('create trigger trg_%s_degistirme before update on public.%I
                        for each row execute function public.fn_degistirme_tarihi()', t, t);
    end loop;
end $$;

-- ----------------------------------------------- yetki surumu tetikleyici ----
-- Rolun yetkisi degisince rol.yetki_surumu artar; elinde eski surumlu token olan
--   kullanicinin yetkisi bir sonraki istekte yeniden cozulur.
create or replace function public.fn_yetki_surumu_artir() returns trigger
language plpgsql as $$
declare v_rol integer;
begin
    v_rol := coalesce(new.rol_id, old.rol_id);
    update public.rol set yetki_surumu = yetki_surumu + 1 where id = v_rol;
    return null;
end $$;

drop trigger if exists trg_rol_yetki_surum on public.rol_yetki;
create trigger trg_rol_yetki_surum after insert or update or delete on public.rol_yetki
    for each row execute function public.fn_yetki_surumu_artir();

drop trigger if exists trg_rol_alan_yetki_surum on public.rol_alan_yetki;
create trigger trg_rol_alan_yetki_surum after insert or update or delete on public.rol_alan_yetki
    for each row execute function public.fn_yetki_surumu_artir();

-- ------------------------------------------------------------ fonksiyonlar ----
-- Kullanicinin cozulmus yetki listesi. Sunucu her istekte bunu cagirir
--   (yetki listesi token'a GOMULMEZ - API §1.1).
create or replace function public.fn_kullanici_yetkileri(p_kullanici_id integer)
returns table (yetki_kod varchar, tur smallint, gor smallint, ekle smallint, degistir smallint, sil smallint)
language sql stable as $$
    select y.kod, y.tur, ry.gor, ry.ekle, ry.degistir, ry.sil
      from public.taraf_kullanici k
      join public.rol_yetki ry on ry.rol_id = k.rol_id
      join public.yetki y      on y.id = ry.yetki_id and y.aktif = 1
     where k.id = p_kullanici_id
       and k.aktif = 1
       and (ry.gor = 1 or ry.ekle = 1 or ry.degistir = 1 or ry.sil = 1)
$$;

comment on function public.fn_kullanici_yetkileri(integer) is 'Kullanicinin rolunden cozulmus yetki listesi. Yetkisiz kaynak / aksiyon HIC DONMEZ.';

-- Parola dogrulama (bcrypt). Kilit / deneme sayaci uygulamada yonetilir.
create or replace function public.fn_parola_dogru(p_kod varchar, p_parola text)
returns boolean
language sql stable as $$
    select coalesce(max(case when k.parola_hash <> ''
                              and k.parola_hash = crypt(p_parola, k.parola_hash)
                             then 1 else 0 end), 0) = 1
      from public.taraf_kullanici k
     where k.kod = lower(p_kod collate "C")
       and k.aktif = 1
$$;

-- Parola atama / degistirme - hash disaridan gelmesin diye tek kapi.
create or replace function public.fn_parola_ata(p_kullanici_id integer, p_parola text,
                                                p_degismeli smallint default 0)
returns void
language sql as $$
    update public.taraf_kullanici
       set parola_hash      = crypt(p_parola, gen_salt('bf', 12)),
           parola_algo      = 'bcrypt',
           parola_tarihi    = now()::timestamp,
           parola_degismeli = p_degismeli,
           hatali_giris     = 0,
           kilit_bitis      = null
     where id = p_kullanici_id
$$;

