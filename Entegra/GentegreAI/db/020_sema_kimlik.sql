-- ---------------------------------------------------------------- 1) rol ----
create table if not exists public.rol (
    id                integer generated by default as identity primary key,
    kod               varchar(40)  not null,               -- 'yonetici', 'muhasebe' (ascii kucuk harf)
    ad                varchar(100) not null,
    ust_rol_id        integer,                             -- eski ROLLER.USTID
    departman_id      integer,                             -- eski ROLLER.DEPARTMAN (kod_liste degeri)
    gorev_id          integer,                             -- eski ROLLER.GOREVID
    sistem            smallint     not null default 0,     -- 1 ise silinemez / yeniden adlandirilamaz
    aktif             smallint     not null default 1,
    yetki_surumu      bigint       not null default 1,     -- JWT'deki yetkiSurumu; yetki degisince artar
    eski_id           integer,                             -- GOC IZI: ROLLER.ID
    ekleyen           integer      not null default 0,
    ekleme_tarihi     timestamp    not null default now()::timestamp,
    degistiren        integer      not null default 0,
    degistirme_tarihi timestamp,
    constraint ck_rol_kod check (kod ~ '^[a-z0-9._-]+$'),
    constraint fk_rol_ust foreign key (ust_rol_id) references public.rol (id)
);
create unique index if not exists ux_rol_kod     on public.rol (kod);
create unique index if not exists ux_rol_eski_id on public.rol (eski_id) where eski_id is not null;

comment on table  public.rol              is 'Yetki rolu (eski ROLLER). Kullanici TEK role baglidir - JWT icindeki rolId.';
comment on column public.rol.yetki_surumu is 'Rolun yetkileri her degistiginde artar. Token icindeki deger eskiyse sunucu yetkiyi yeniden cozer.';
comment on column public.rol.kod          is 'ASCII kucuk harf. Turkce buyuk/kucuk donusumu (I/i) tuzagina dusmemek icin kolon kucuk harf saklanir.';

-- --------------------------------------------------- 2) yetki (aksiyon) ----
-- Iki tur:
--   tur = 0  KAYNAK yetkisi  -> gor / ekle / degistir / sil bayraklari anlamli
--   tur = 1  AKSIYON yetkisi -> yalniz "gor" anlamli (= calistirma izni)
-- Aksiyon katalogu ucu (API §7) bu tablodan beslenir.
--
-- Eski MODUL.TUR'daki iki ozel dal korunur (UKullaniciYetki.pas:530-531):
--   deger_alir  = eski TUR 5..9   -> yetki bir DEGER tasir (or. izin verilen iskonto orani)
--   kapsam_alir = eski TUR 15..19 -> gorme kapsami secilir (herkes / yalniz kendi kayitlari)
create table if not exists public.yetki (
    id                integer generated by default as identity primary key,
    kod               varchar(60)  not null,               -- 'cari', 'belge', 'ebelge.gonder'
    ad                varchar(120) not null,
    grup              varchar(40)  not null default '',    -- menu / ekran gruplamasi
    tur               smallint     not null default 0,     -- 0 kaynak, 1 aksiyon
    deger_alir        smallint     not null default 0,     -- 1 ise rol_yetki.deger anlamli
    kapsam_alir       smallint     not null default 0,     -- 1 ise rol_yetki.kapsam anlamli
    sira              smallint     not null default 0,
    aktif             smallint     not null default 1,
    eski_modul_id     bigint,                              -- GOC IZI: MODUL.MODULID
    eski_tur          smallint,                            -- GOC IZI: MODUL.TUR
    constraint ck_yetki_kod check (kod ~ '^[a-z0-9._-]+$')
);
create unique index if not exists ux_yetki_kod  on public.yetki (kod);
create        index if not exists ix_yetki_eski on public.yetki (eski_modul_id) where eski_modul_id is not null;

comment on table  public.yetki     is 'Yetki / aksiyon katalogu (eski MODUL). Kaynak yetkileri liste-kart uclarini, aksiyon yetkileri arac cubugu / sag tus komutlarini kapsar.';
comment on column public.yetki.tur is '0 kaynak (gor/ekle/degistir/sil), 1 aksiyon (yalniz gor = calistirma izni).';

-- ----------------------------------------------------------- 3) rol_yetki ----
-- Eski YETKI tablosunda her (ROLID, MODULID, TUR) ayri satirdi - TUR 1..4 =
--   gorsun / eklesin / degistirsin / silsin (UKullaniciYetki.pas:204). Burada
--   tek satir + 4 bayrak. Satir YOKSA yetki yok (varsayilan kapali) - ayri
--   "yasakla" satiri tutulmaz.
create table if not exists public.rol_yetki (
    rol_id            integer   not null,
    yetki_id          integer   not null,
    gor               smallint  not null default 0,
    ekle              smallint  not null default 0,
    degistir          smallint  not null default 0,
    sil               smallint  not null default 0,
    deger             varchar(50) not null default '',     -- yetki.deger_alir = 1 ise (eski YETKI/YETKIEK.BILGI)
    kapsam            smallint  not null default 0,        -- yetki.kapsam_alir = 1 ise: 0 herkes, 1 yalniz kendi kayitlari
    ekleyen           integer   not null default 0,
    ekleme_tarihi     timestamp not null default now()::timestamp,
    degistiren        integer   not null default 0,
    degistirme_tarihi timestamp,
    constraint pk_rol_yetki       primary key (rol_id, yetki_id),
    constraint fk_rol_yetki_rol   foreign key (rol_id)   references public.rol (id)   on delete cascade,
    constraint fk_rol_yetki_yetki foreign key (yetki_id) references public.yetki (id) on delete cascade
);

comment on table public.rol_yetki is 'Rolun kaynak / aksiyon yetkileri. Satir yoksa yetki YOKTUR.';

