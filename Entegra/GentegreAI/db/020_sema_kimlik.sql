-- ----------------------------------------------------------- 5) kullanici ----
-- PK = id: uygulamanin kullanicisi personel rollu bir taraf kaydidir
--   (eski KULLANICI.REHBERID). kullanici_sube (019) ve islem_log.kullanici_id
--   ayni kimligi tasir - araya ikinci bir numara girmez.
create table if not exists public.taraf_kullanici (
    id                integer      not null primary key references public.taraf (id),
    kod               varchar(30)  not null,              -- giris adi, ascii kucuk harf
    parola_hash       varchar(200) not null default '',   -- bcrypt; bos = parola atanmamis
    parola_algo       varchar(20)  not null default 'bcrypt',
    parola_tarihi     timestamp,
    parola_degismeli  smallint     not null default 0,    -- 1 ise ilk giriste degistirmek zorunda
    rol_id            integer      not null,
    eposta            varchar(120) not null default '',
    cep_tel           varchar(30)  not null default '',
    dil               smallint     not null default 0,
    aktif             smallint     not null default 1,
    hatali_giris      smallint     not null default 0,
    kilit_bitis       timestamp,                          -- dolu ve gelecekteyse giris kapali
    son_giris_tarihi  timestamp,
    son_giris_ip      varchar(45)  not null default '',
    totp_gizli        varchar(64)  not null default '',   -- iki asamali dogrulama (henuz kullanilmiyor)
    totp_aktif        smallint     not null default 0,
    mobil             smallint     not null default 0,    -- eski KULLANICI.MOBIL
    eski_id           integer,                            -- GOC IZI: KULLANICI.ID
    ekleyen           integer      not null default 0,
    ekleme_tarihi     timestamp    not null default now()::timestamp,
    degistiren        integer      not null default 0,
    degistirme_tarihi timestamp,
    constraint ck_taraf_kullanici_kod check (kod ~ '^[a-z0-9._@-]+$'),
    constraint fk_taraf_kullanici_rol foreign key (rol_id) references public.rol (id)
);
create unique index if not exists ux_taraf_kullanici_kod     on public.taraf_kullanici (kod);
create unique index if not exists ux_taraf_kullanici_eski_id on public.taraf_kullanici (eski_id) where eski_id is not null;
create        index if not exists ix_taraf_kullanici_rol     on public.taraf_kullanici (rol_id);

comment on table  public.taraf_kullanici     is 'Uygulama kullanicisi. id = personel rollu taraf kaydi (eski KULLANICI.REHBERID). Kullanici TEK role baglidir.';
comment on column public.taraf_kullanici.kod is 'Giris adi. ASCII kucuk harf saklanir - Turkce I/i donusumu yuzunden buyuk-kucuk esitligi DB collation''ina birakilmaz.';
