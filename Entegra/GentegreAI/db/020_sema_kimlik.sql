--  KARAR (19.08.2026): JWT = 30 dk access token + DB'de tutulan refresh token.
--    Kisa access token yetki degisimini en gec 30 dk icinde etkili kilar;
--    refresh token iptal edilebilir (cikis, calinti, kullanici pasiflenmesi).
--    Refresh token DONER (rotation): her yenilemede yenisi verilir, eskisi
--    iptal olur. Iptal edilmis bir token tekrar kullanilirsa AILE komple
--    iptal edilir (token calinmis demektir).
--
--  ESKI MODEL (MSSQL) -> YENI
--    KULLANICI (ID, REHBERID, SIFRE, KOD, ROLID)  -> kullanici (taraf_id PK)
--    ROLLER    (ID, ROL, USTID, DEPARTMAN)        -> rol
--    MODUL     (MODULID, MODULADI, TUR) 312 satir -> yetki (aksiyon katalogu)
--    YETKI     (ROLID, MODULID, TUR, HAK)         -> rol_yetki (4 bayrak)
--    YETKIEK   (ROLID, MODULID, BILGI)            -> rol_yetki (tur = 1 aksiyon)
--    YETKIALANI(SAHIPREHBERID, REHBERID)          -> kullanici_kapsam
--    Sube yetkisi 019'daki kullanici_sube'de; burada TEKRAR EDILMEZ.
--
--  Parola: bcrypt (pgcrypto). .NET tarafi BCrypt.Net ile ayni $2a$ bicimini
--    uretir; dogrulama iki tarafta da yapilabilir. Eski SIFRE kolonu Delphi'nin
--    kendi sifrelemesi - TASINMAZ, gocte parola_degismeli = 1 birakilir.
-- ============================================================================
\set ON_ERROR_STOP on

