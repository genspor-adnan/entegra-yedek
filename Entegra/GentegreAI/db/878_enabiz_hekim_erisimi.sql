--  HEKİMİN HASTANIN e-NABIZ KAYITLARINA ERİŞİMİ
--  (KTS denetim maddesi H6 / D15: "hekim ekranlarından hastanın e-Nabız
--   profilindeki sağlık bilgilerine erişim süreçleri başarılı şekilde
--   tamamlanıyor mu? (SMS onayı, sisteme giriş)")
--
--  AKIŞ (SBYS Entegrasyon Kılavuzu, 05.04.2017 — 877'deki servisin aynısı):
--    1. HBYS, `DoktorEHRErisimi` metodunu çağırır: KURUM_KODU +
--       HEKIM_KIMLIK_NUMARASI + HASTA_KIMLIK_NUMARASI.
--    2. Servis geçici bir `AccessKey` döner.
--    3. HBYS, `…/nabizpaylasim/HastaBilgisiKontrol.aspx?keyH={AccessKey}`
--       adresini TARAYICIDA açar; hekim e-Devlet ile girer. Hasta verisini
--       gizlemişse aynı ekrandan SMS onayı istenir.
--
--  ERİŞİM KAYIT ALTINA ALINIR - ASIL SEBEBİ DENETİM DEĞİL, KVKK.
--  "Hangi hekim, hangi hastanın kayıtlarına, ne zaman erişmek istedi"
--  sorusunun cevabı kurumda durmalı; Bakanlık tarafındaki kayıt bize
--  sorulduğunda karşılığını gösteremezdik.
--
--  ANAHTARIN KENDİSİ SAKLANMAZ. `AccessKey` geçici bir erişim
--  kimlik bilgisidir (parola gibi); tabloya yazmak, veritabanını okuyan
--  herkese o hastanın kayıtlarına açılan bir kapı bırakmak olurdu.
--  Yalnız ilk 8 karakteri iz sürmek için tutulur.
--
--  HESAP 877 İLE ORTAK (`ENABIZ_HBYS`): aynı servis, aynı kimlik. Kurum
--  hesabı bir kez tanımlar, iki özellik birden açılır. Bu maddenin kendi
--  kapısı yok - metot adı kılavuzda tanımlı (`DoktorEHRErisimi`), yani
--  hesap açıldığı anda çalışır.
-- =====================================================================

-- ------------------------------------------------------- kod listesi ----
insert into public.kod_liste (kod, ad)
select 'enabiz.erisim_sonuc', 'e-Nabız Erişim Sonucu'
 where not exists (select 1 from public.kod_liste k where k.kod = 'enabiz.erisim_sonuc');

insert into public.kod_deger (liste_id, deger, ad, sira, aktif, ekleyen)
select l.id, v.deger, v.ad, v.deger * 10, 1, 0
  from public.kod_liste l
  join (values
    ('enabiz.erisim_sonuc', 0, 'İstendi'),
    ('enabiz.erisim_sonuc', 1, 'Anahtar alındı'),
    ('enabiz.erisim_sonuc', 2, 'Servis reddetti'),
    ('enabiz.erisim_sonuc', 3, 'Hata')
  ) as v(liste, deger, ad) on v.liste = l.kod
 where not exists (select 1 from public.kod_deger d
                    where d.liste_id = l.id and d.deger = v.deger);

-- ------------------------------------------------------------- tablo ----
create table if not exists public.enabiz_erisim (
  id             bigint generated by default as identity primary key,
  sube_id        integer  not null default 0,
  hasta_id       integer  not null references public.taraf(id),
  hekim_id       integer  references public.taraf(id),
  hasta_kimlik   varchar(11) not null default '',
  hekim_kimlik   varchar(11) not null default '',
  muayene_id     integer  references public.muayene(id),
  belge_id       integer  references public.belge(id),
  zaman          timestamptz not null default now(),
  sonuc          smallint not null default 0,          -- enabiz.erisim_sonuc
  -- ANAHTARIN İLK 8 KARAKTERİ: Bakanlık tarafındaki kayıtla eşleştirmeye
  --   yeter, kapıyı açmaya yetmez.
  anahtar_onek   varchar(8)   not null default '',
  servis_mesaji  varchar(400) not null default '',
  ip             varchar(45)  not null default '',
  ekleyen        integer  not null default 0,
  ekleme_tarihi  timestamptz not null default now(),
  constraint ck_enabiz_erisim_sonuc check (sonuc in (0, 1, 2, 3))
);

create index if not exists ix_enabiz_erisim_hasta on public.enabiz_erisim (hasta_id, zaman desc);
create index if not exists ix_enabiz_erisim_hekim on public.enabiz_erisim (hekim_id, zaman desc);

comment on table public.enabiz_erisim is
  '878: hekimin hastanin e-Nabiz kayitlarina erisim istegi (KTS H6/D15). '
  'AccessKey SAKLANMAZ - gecici erisim kimligidir; yalniz ilk 8 karakteri '
  'iz surmek icin tutulur.';
comment on column public.enabiz_erisim.anahtar_onek is
  'AccessKey ilk 8 karakteri - Bakanlik tarafindaki kayitla eslestirmek icin.';

-- ------------------------------------------------------------ görünüm ----
create or replace view public.v_enabiz_erisim as
select e.id,
       e.sube_id,
       e.hasta_id,
       t.unvan                      as hasta_adi,
       e.hasta_kimlik,
       e.hekim_id,
       coalesce(h.unvan, '')        as hekim_adi,
       e.hekim_kimlik,
       e.muayene_id,
       e.belge_id,
       e.zaman,
       e.sonuc,
       coalesce(ks.ad, '')          as sonuc_adi,
       e.anahtar_onek,
       e.servis_mesaji,
       e.ip
  from public.enabiz_erisim e
  join public.taraf t on t.id = e.hasta_id
  left join public.taraf h on h.id = e.hekim_id
  left join public.kod_liste lk on lk.kod = 'enabiz.erisim_sonuc'
  left join public.kod_deger ks on ks.liste_id = lk.id and ks.deger = e.sonuc;

comment on view public.v_enabiz_erisim is
  '878: e-Nabiz erisim gecmisi + cozulmus sonuc adi (KVKK izi).';

-- ------------------------------------------------------------- ayarlar ----
--  Paylaşım ekranının adresi kılavuzdan sabit ama AYARDAN gelir: Bakanlık
--  adresi değiştirirse yeni sürüm beklemek gerekmesin.
insert into public.referans (anahtar, deger, tip, kapsam, aciklama)
values ('enabiz.paylasim_adresi',
        'https://www.enabiz.gov.tr/nabizpaylasim/HastaBilgisiKontrol.aspx?keyH=',
        'metin', 'firma',
        'e-Nabız hasta paylaşım ekranının adresi; alınan AccessKey sonuna eklenir.')
on conflict (anahtar) do nothing;

-- -------------------------------------------------------------- yetki ----
--  AKSİYON yetkisi (tur 1): hekim ekranındaki düğmeyi açar. Mesaj
--  yetkisinden AYRI - hastanın kayıtlarını GÖRMEK ile ona mesaj YAZMAK
--  farklı iki haktır; kurum birini verip ötekini vermeyebilmeli.
insert into public.yetki (kod, ad, grup, tur, sira, aktif, urun_modu, modul)
select 'enabiz.erisim', 'Hastanın e-Nabız kayıtlarına eriş (hekim)',
       'Entegrasyon', 1, 21, 1, 2, 'enabiz'
 where not exists (select 1 from public.yetki y where y.kod = 'enabiz.erisim');

insert into public.rol_yetki (rol_id, yetki_id, gor, ekle, degistir, sil, ekleyen)
select r.id, y.id, 1, 1, 1, 0, 0
  from public.rol r cross join public.yetki y
 where r.kod = 'yonetici' and y.kod = 'enabiz.erisim'
   and not exists (select 1 from public.rol_yetki ry
                    where ry.rol_id = r.id and ry.yetki_id = y.id);
update public.rol set yetki_surumu = yetki_surumu + 1 where kod = 'yonetici';

