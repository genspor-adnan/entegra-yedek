--
--   * goz_kaynak: ODA / CİHAZ TANIMI. Bugüne kadar akış satırındaki `oda` serbest metindi;
--     "OCT-1" ile "OCT1" iki ayrı kaynak sayılıyordu ve pano doluluğu ikiye bölünüyordu.
--     Tanım tablosu ayrıca BOŞ kaynağı da gösterebilmeyi sağlıyor: mockup'ın "Oda 2 ·
--     boş · hekim vizitte" satırı, yalnız dolu odalardan çıkan bir sorguda hiç görünmez.
--   * goz_ziyaret_istasyon.kaynak_id: atama artık tanıma bağlanıyor; `oda` metni ekranda
--     okunabilirlik için KALIYOR (geçmiş satırlar ve tanımsız kurulum bu metinle çalışıyor).
--   * v_goz_kaynak_doluluk: tanımlı kaynaklar + akışta geçen tanımsız oda metinleri.
--   * v_goz_unite_akis: kanban kartının mockup'taki ayrıntıları (çağrıldı mı, işlemde mi,
--     acil / çocuk, ön tetkik tamamlanması, GİB ve otoref değerleri, randevu gecikmesi).
--   * v_goz_bekleme_ekrani: bekleme salonu TV ekranı - ad MASKELİ (panoya tam ad yazılmaz).

-- ----------------------------------------------------------------- kaynak tanımı --
create table if not exists public.goz_kaynak (
    id                integer generated by default as identity primary key,
    sube_id           integer      not null default 0,
    kod               varchar(20)  not null,
    ad                varchar(60)  not null,
    -- 1 muayene odası · 2 cihaz · 3 işlem / enjeksiyon odası · 4 ön tetkik masası
    tur               smallint     not null default 1,
    -- Kaynağın bağlı olduğu istasyon (0 = hepsi): ön tetkik masası muayene
    --   odasıyla aynı listede görünmesin diye.
    istasyon          smallint     not null default 0,
    -- Görüntüleme cihazıysa tanımın kendisi goz_cihaz'da: ikinci bir cihaz
    --   tanımı üretmek, ölçüm eşlemesini iki yere bölerdi.
    cihaz_id          integer      references public.goz_cihaz(id),
    -- Sabit sahibi varsa (hekimin odası, teknikerin masası).
    personel_id       integer      references public.taraf(id),
    sira              smallint     not null default 0,
    aktif             smallint     not null default 1,
    not_metin         varchar(200) not null default '',
    ekleyen           integer      not null default 0,
    ekleme_tarihi     timestamptz  not null default now(),
    degistiren        integer      not null default 0,
    degistirme_tarihi timestamptz
);

create unique index if not exists ux_goz_kaynak_kod on public.goz_kaynak (kod);
create index if not exists ix_goz_kaynak_aktif on public.goz_kaynak (aktif, sira) where aktif = 1;

insert into public.kod_liste (kod, ad)
select v.kod, v.ad from (values ('goz.kaynak_tur', 'Göz Ünitesi Kaynak Türü')) v(kod, ad)
 where not exists (select 1 from public.kod_liste where kod = v.kod);

insert into public.kod_deger (liste_id, deger, ad, dil, sira, aktif, ekleyen)
select l.id, v.deger, v.ad, 0, v.deger, 1, 0
  from (values ('goz.kaynak_tur', 1, 'Muayene odası'), ('goz.kaynak_tur', 2, 'Cihaz'),
               ('goz.kaynak_tur', 3, 'İşlem / enjeksiyon odası'),
               ('goz.kaynak_tur', 4, 'Ön tetkik masası')) v(liste, deger, ad)
  join public.kod_liste l on l.kod = v.liste
 where not exists (select 1 from public.kod_deger x where x.liste_id = l.id and x.deger = v.deger and x.dil = 0);

alter table public.goz_ziyaret_istasyon
    add column if not exists kaynak_id integer references public.goz_kaynak(id);

-- GEÇMİŞ ODA METİNLERİ TANIMA ÇEVRİLİR: kurulumda hiç tanım yapılmamış olsa
--   bile pano ilk açılışta dolu görünsün. Yalnız akışta GERÇEKTEN kullanılmış
--   metinler alınır; uydurma kaynak üretilmez.
insert into public.goz_kaynak (sube_id, kod, ad, tur, istasyon, sira, not_metin)
select min(i.sube_id), left(i.oda, 20), left(i.oda, 60),
       -- Cihaz adı gibi görünenler (OCT, HFA, biyometri...) cihaz sayılır.
       case when i.oda ~* '(oct|hfa|görme alanı|biyometri|topograf|pakimetri|fundus|lens|otoref|tono)'
            then 2
            when i.oda ~* '(ön tetkik|on tetkik|tetkik)' then 4
            when i.oda ~* '(enjeksiyon|işlem|islem|lazer)' then 3
            else 1 end,
       0, 900, 'akış kayıtlarından üretildi (976)'
  from public.goz_ziyaret_istasyon i
 where coalesce(i.oda, '') <> ''
   and not exists (select 1 from public.goz_kaynak k
                    where k.kod = left(i.oda, 20) or k.ad = left(i.oda, 60))
 group by i.oda;

update public.goz_ziyaret_istasyon i
   set kaynak_id = k.id
  from public.goz_kaynak k
 where i.kaynak_id is null and coalesce(i.oda, '') <> ''
   and (k.ad = i.oda or k.kod = i.oda);

-- ------------------------------------------------------------ kaynak doluluğu --
-- Pano HASTAYI değil KAYNAĞI sayar: bekleme çoğu zaman hekimden değil tek
--   cihazdan doğuyor. BOŞ kaynak da satır üretir - "HFA sırası 4 kişiyken
--   muayene odası boş duruyor" cümlesi ancak boş oda da görünürse kurulur.
create or replace view public.v_goz_kaynak_doluluk as
with acik as (
    select i.id, i.sube_id, i.kaynak_id, i.oda, i.istasyon, i.giris, i.personel_id,
           public.fn_taraf_ad(t.unvan, t.ad, t.soyad)::varchar(120) as hasta_adi
      from public.goz_ziyaret_istasyon i
      join public.taraf t on t.id = i.hasta_id
     where i.cikis is null
),
kaynak as (
    select k.id as kaynak_id, k.sube_id, k.kod, k.ad, k.tur, k.istasyon as kaynak_istasyon,
           k.personel_id, k.sira, 1::smallint as tanimli
      from public.goz_kaynak k
     where k.aktif = 1
    union all
    -- Tanımsız ama akışta kullanılan oda metni: tanım yapılmamış kurulumda
    --   pano boş kalmasın.
    select null::integer, min(a.sube_id), left(a.oda, 20), left(a.oda, 60),
           0::smallint, 0::smallint, null::integer, 900::smallint, 0::smallint
      from acik a
     where coalesce(a.oda, '') <> '' and a.kaynak_id is null
       and not exists (select 1 from public.goz_kaynak k
                        where k.aktif = 1 and (k.ad = a.oda or k.kod = a.oda))
     group by left(a.oda, 20), left(a.oda, 60)
)
select k.kaynak_id, k.sube_id, k.kod, k.ad, k.tur,
       case k.tur when 1 then 'Muayene odası' when 2 then 'Cihaz'
                  when 3 then 'İşlem odası' when 4 then 'Ön tetkik' else '' end::varchar(20) as tur_adi,
       k.kaynak_istasyon, k.sira, k.tanimli,
       coalesce(public.fn_taraf_ad(p.unvan, p.ad, p.soyad)::varchar(120), '')::varchar(120) as sahip_adi,
       coalesce(d.sayi, 0)                             as sayi,
       coalesce(d.hasta, '')::varchar(120)             as hasta,
       coalesce(d.istasyon, 0)::smallint               as istasyon,
       coalesce(d.sure_dk, 0)                          as sure_dk,
       coalesce(d.en_uzun_dk, 0)                       as en_uzun_dk,
       case when coalesce(d.sayi, 0) = 0 then 1 else 0 end::smallint as bos
  from kaynak k
  left join public.taraf p on p.id = k.personel_id
  left join lateral (
      select count(*)::int                                                               as sayi,
             -- KAYNAĞI KULLANAN: en son giren hasta masada, ötekiler sırada.
             (array_agg(a.hasta_adi order by a.giris desc))[1]                           as hasta,
             (array_agg(a.istasyon  order by a.giris desc))[1]                           as istasyon,
             (array_agg((extract(epoch from (now() - a.giris)) / 60)::int
                        order by a.giris desc))[1]                                       as sure_dk,
             max((extract(epoch from (now() - a.giris)) / 60)::int)                      as en_uzun_dk
        from acik a
       where (k.kaynak_id is not null and a.kaynak_id = k.kaynak_id)
          or (a.kaynak_id is null and coalesce(a.oda, '') <> '' and (a.oda = k.ad or a.oda = k.kod))
  ) d on true;

-- --------------------------------------------------------------- akış görünümü --
-- Kanban kartının mockup'taki ayrıntıları buraya eklendi: grid ve kanban AYNI
--   satırı okuyor, hesap iki yerde yapılmamalı.
--
--   Muayene bağı LATERAL: bir başvurunun birden çok muayenesi olabiliyor ve
--   düz join o hastayı panoda iki kez gösterirdi. Göz uzantısı olan muayene
--   öncelikli - pano göz muayenesini arıyor.
-- Kolon sırası değiştiği için REPLACE yetmez (PG kolon adı değiştirmeye izin vermez);
--   görünümü başka hiçbir nesne okumuyor, bırakıp yeniden kuruluyor.
drop view if exists public.v_goz_unite_akis;
create view public.v_goz_unite_akis as
select b.id                                                          as belge_id,
       b.sube_id,
       b.taraf_id                                                    as hasta_id,
       public.fn_taraf_ad(t.unvan, t.ad, t.soyad)::varchar(120)       as hasta_adi,
       i.id                                                          as istasyon_id,
       i.istasyon,
       i.giris                                                       as istasyon_giris,
       i.oda,
       i.kaynak_id,
       coalesce(k.ad, i.oda)::varchar(60)                             as kaynak_adi,
       i.sira_no,
       i.personel_id,
       i.dilatasyon_zamani,
       i.dilatasyon_ilac,
       case when i.dilatasyon_zamani is null then null::integer
            when i.dilatasyon_zamani + interval '20 minutes' <= now() then 1
            else 0 end                                               as dilatasyon_hazir,
       case when i.dilatasyon_zamani is null then 0 else 1 end::smallint as dilatasyonda,
       (extract(epoch from (now() - i.giris)) / 60)::integer          as bekleme_dk,
       -- ÇAĞRI: "çağrıldı ama gelmedi" ile "kimse çağırmadı" aynı görünürse
       --   sıra kimsede kalmaz (702).
       i.cagri_zamani,
       case when i.cagri_zamani is null then 0 else 1 end::smallint   as cagrildi,
       -- İŞLEMDE: çağrılmış ve kaynağı atanmış satır "şu an masada" -
       --   mockup'ta bu kart vurgulu çiziliyor.
       case when i.cagri_zamani is not null and (i.kaynak_id is not null or coalesce(i.oda, '') <> '')
            then 1 else 0 end::smallint                               as islemde,
       -- GECİKEN: yarım saati geçen bekleme. Eşik panoda tek yerde.
       case when (extract(epoch from (now() - i.giris)) / 60)::integer >= 30
            then 1 else 0 end::smallint                               as gecikti,
       mu.goz_muayene_id,
       mu.muayene_turu,
       case when mu.muayene_turu = 4 then 1 else 0 end::smallint      as acil,
       case when th.dogum_tarihi is null then null::integer
            else extract(year from age(th.dogum_tarihi))::integer end  as yas,
       th.cinsiyet,
       case when th.dogum_tarihi is not null
             and th.dogum_tarihi > (current_date - interval '16 years') then 1
            else 0 end::smallint                                      as cocuk,
       -- ÖN TETKİK TAMAMLANMASI: mockup kartta "Otoref ✔ · Tonometri —"
       --   yazıyor; hastayı hekime almadan önce bakılan tek şey bu.
       coalesce(rf.otoref, 0)::smallint                               as otoref_var,
       coalesce(tn.tono, 0)::smallint                                 as tono_var,
       rf.ref_od_sph, rf.ref_os_sph,
       tn.gib_od, tn.gib_os,
       r.baslangic                                                    as randevu_saat,
       case when r.baslangic is null then null::integer
            else greatest(0, (extract(epoch from (now() - r.baslangic)) / 60)::int)
       end                                                            as randevu_gecikme_dk,
       mu.hekim_id,
       mu.hekim_adi
  from public.goz_ziyaret_istasyon i
  join public.belge b on b.id = i.belge_id
  join public.taraf t on t.id = i.hasta_id
  left join public.taraf_hasta th on th.id = i.hasta_id
  left join public.goz_kaynak k on k.id = i.kaynak_id
  left join lateral (
      select m.id as muayene_id, m.personel_id as hekim_id,
             public.fn_taraf_ad(h.unvan, h.ad, h.soyad)::varchar(120) as hekim_adi,
             gm.id as goz_muayene_id, gm.muayene_turu
        from public.muayene m
        left join public.goz_muayene gm on gm.muayene_id = m.id
        left join public.taraf h on h.id = m.personel_id
       where m.belge_id = b.id
       order by (gm.id is not null) desc, m.id desc
       limit 1
  ) mu on true
  left join lateral (
      select max(case when x.tur = 1 then 1 else 0 end)                as otoref,
             max(x.sph) filter (where x.goz = 1 and x.tur = 1)         as ref_od_sph,
             max(x.sph) filter (where x.goz = 2 and x.tur = 1)         as ref_os_sph
        from public.goz_refraksiyon x
       where x.goz_muayene_id = mu.goz_muayene_id
  ) rf on true
  left join lateral (
      select case when count(*) > 0 then 1 else 0 end                  as tono,
             max(x.gib) filter (where x.goz = 1)                       as gib_od,
             max(x.gib) filter (where x.goz = 2)                       as gib_os
        from public.goz_tonometri x
       where x.goz_muayene_id = mu.goz_muayene_id
  ) tn on true
  left join lateral (
      select rr.baslangic
        from public.randevu rr
       where rr.belge_id = b.id
       order by rr.baslangic
       limit 1
  ) r on true
 where i.cikis is null;

-- --------------------------------------------------------------- bekleme ekranı --
-- Bekleme salonu TV'si: hasta adı MASKELİ (salonda herkes okuyor), çağrılan
--   kişi ve kaynağı büyük yazılır. Ekran kayıt yazmaz, yalnız okur.
create or replace view public.v_goz_bekleme_ekrani as
select i.id                                                           as istasyon_id,
       i.sube_id,
       i.istasyon,
       i.sira_no,
       -- MASKE TAM ADDAN: ad / soyad kolonları boş olup adın tamamı unvanda
       --   duran kayıtlar var (eski göç, kurum kaydı); kolonlardan maskelemek
       --   o hastayı TV'de adsız bir kutu yapardı.
       case when position(' ' in ta.tam) = 0 then ta.tam
            else split_part(ta.tam, ' ', 1) || ' '
                 || upper(left(split_part(ta.tam, ' ', 2), 1)) || '***' end::varchar(60) as maskeli_ad,
       coalesce(nullif(coalesce(k.ad, i.oda), ''), '')::varchar(60)    as kaynak_adi,
       i.cagri_zamani,
       (extract(epoch from (now() - i.giris)) / 60)::int               as bekleme_dk,
       case when i.cagri_zamani is null then null::integer
            else (extract(epoch from (now() - i.cagri_zamani)) / 60)::int end as cagri_dk,
       coalesce(mu.hekim_adi, '')::varchar(120)                        as hekim_adi,
       case when i.dilatasyon_zamani is null then 0
            when i.dilatasyon_zamani + interval '20 minutes' <= now() then 1
            else 2 end::smallint                                       as dilatasyon_durum
  from public.goz_ziyaret_istasyon i
  join public.taraf t on t.id = i.hasta_id
  cross join lateral (select trim(public.fn_taraf_ad(t.unvan, t.ad, t.soyad))::varchar(120) as tam) ta
  left join public.goz_kaynak k on k.id = i.kaynak_id
  left join lateral (
      select public.fn_taraf_ad(h.unvan, h.ad, h.soyad)::varchar(120) as hekim_adi
        from public.muayene m
        left join public.taraf h on h.id = m.personel_id
       where m.belge_id = i.belge_id
       order by m.id desc
       limit 1
  ) mu on true
 where i.cikis is null;

