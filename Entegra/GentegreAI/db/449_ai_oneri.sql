-- =====================================================================
-- 449 - AI KONTROLLÜ ÖNERİ (Faz 3)
--
-- Faz 1-2 "nerede / nasıl" diyordu; Faz 3 **açık kaydın** bir sonraki adımını
-- engelleyecek eksikleri söyler: "bu caride VKN yok, e-Fatura GİB'de
-- reddedilir".
--
-- SINIR AYNI: asistan OKUR ve İŞARET EDER, yazmaz. Alan doldurmaz,
-- kaydetmez, göndermez, onaylamaz.
--
-- KURAL AI'YA YAZDIRILMAZ. Her öneri buradaki bir SATIRA bağlıdır; koşul
-- kurumun kendi verisinde çalışan bir SQL'dir (parametre: kayıt id). Model
-- bağlandığında yalnız METNİ güzelleştirir, KARARI değil - "bence şu daha
-- iyi" diyen bir asistan, denetimde savunulamaz.
--
-- SEVIYE: 1 bilgi · 2 uyarı · 3 engel. Engel = bir sonraki adım (gönderim,
-- faturalama, provizyon) bu eksik giderilmeden yapılamaz.
-- =====================================================================

create table if not exists public.ai_oneri_kural (
    id         integer generated by default as identity primary key,
    kod        varchar(60)  not null,
    -- Hangi ekranın kaydı: 'cari' · 'belge' · 'basvuru' (ai_rehber_ekran.kaynak).
    kaynak     varchar(60)  not null,
    seviye     smallint     not null default 2,
    baslik     varchar(160) not null,
    aciklama   varchar(600) not null default '',
    -- Eksik olan ALAN (kart üzerinde işaret etmek için) ve gidilecek ekran.
    alan       varchar(60)  not null default '',
    ekran      varchar(60)  not null default '',
    -- Kuralı görebilmek için gereken yetki; boşsa kaynağın yetkisi yeter.
    yetki_kodu varchar(60)  not null default '',
    -- `select exists(...)` döndürür; @p0 = kayıt id. TRUE ise öneri çıkar.
    kosul      text         not null,
    sira       smallint     not null default 100,
    durum      smallint     not null default 0,
    ekleme_tarihi timestamp not null default now(),
    degistirme_tarihi timestamp
);

create unique index if not exists ux_ai_oneri_kural on public.ai_oneri_kural (kod);
create index if not exists ix_ai_oneri_kural_kaynak
    on public.ai_oneri_kural (kaynak, durum, sira);

