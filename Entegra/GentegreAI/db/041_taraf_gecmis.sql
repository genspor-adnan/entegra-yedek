--  041_taraf_gecmis.sql
--
--  Kullanici: "taraf.geçmiş diye bir tablo oluştursak, ayrıldığı zaman buraya alsak
--  tarihiyle beraber - cari kart kişi gridinde her zaman ayrıldı olarak görsem, kişi
--  kartına girince bağlı caride görmesem ama geçmiş sekmesinde eski kurumunu görsem
--  Başlama/Bitiş/Cari". Her "bagla" (KisiDeposu.BaglaAsync) ACIK bir donem satiri
--  (bitis_tarihi=null) acar; her "kopar" (KoparAsync) o acik donemi kapatir
--  (bitis_tarihi=bugun) - acik donem yoksa (eski/legacy baglanti) bitis-only satir.
-- ============================================================================
\set ON_ERROR_STOP on

create table if not exists public.taraf_gecmis (
    id                  integer generated by default as identity primary key,
    kisi_id             integer not null references public.taraf(id) on delete cascade,
    cari_id             integer not null references public.taraf(id) on delete cascade,
    baslama_tarihi      date,
    bitis_tarihi        date,
    ekleyen             integer not null default 0,
    ekleme_tarihi       timestamp not null default now()::timestamp,
    degistiren          integer not null default 0,
    degistirme_tarihi   timestamp
);

create index if not exists ix_taraf_gecmis_kisi on public.taraf_gecmis (kisi_id);
create index if not exists ix_taraf_gecmis_cari on public.taraf_gecmis (cari_id);
-- Bir kisi bir caride AYNI ANDA sadece TEK acik donem tutabilir.
create unique index if not exists ux_taraf_gecmis_acik
    on public.taraf_gecmis (kisi_id, cari_id) where bitis_tarihi is null;

comment on table public.taraf_gecmis is
  'Kisi-cari baglanti gecmisi (baslama/bitis) - kisi kartinin "Geçmiş" sekmesi, salt-okunur (BaglaAsync/KoparAsync yonetir).';
