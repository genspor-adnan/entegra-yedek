-- ============================================================================
--  425 - DOKUMAN ERISIM IZINLERI (mockup dokuman_karti.html · Erisim)
--
--  Bugune kadar erisim KAYNAK KARTIN yetkisinden geliyordu: personeli goren
--  onun dokumanini gorur. Kart galerisi icin dogru ama KURUMSAL KLASORDE
--  kaynak yok - bir prosedurun sahibi bir kart degil.
--
--  Izin UC KATMANDAN gelir ve kartta hepsi birlikte gorunmeli:
--     * KLASOR izni  - alt klasorlere devralinir (hedef_tur 1)
--     * DOKUMAN izni - klasorden farkli istisna (hedef_tur 2)
--     * SAHIP        - dokumani yukleyen/sahibi her zaman tam yetkili
--
--  Bunlari tek tabloda saklamak "bu izin nereden geliyor" sorusunu cevapsiz
--  birakirdi; gorunumde KAYNAK kolonu tam olarak onu soyluyor.
--
--  GIZLILIK SINIFI izinden BAGIMSIZ UST KISITTIR: ozel nitelikli dokumanda
--  izin verilmis olsa bile gerekce zorunlu ve erisim gunluge yazilir. Bu
--  yuzden sinif burada saklanmaz, dokumanin kendisinde durur.
-- ============================================================================

create table if not exists public.dokuman_erisim (
    id            integer  primary key generated by default as identity,
    -- 1 klasor · 2 dokuman
    hedef_tur     smallint not null,
    hedef_id      integer  not null,
    rol_id        integer,
    kullanici_id  integer,
    oku           smallint not null default 1,
    indir         smallint not null default 1,
    duzenle       smallint not null default 0,
    paylas        smallint not null default 0,
    sil           smallint not null default 0,
    onayla        smallint not null default 0,
    -- Klasor izni alt klasorlere gecsin mi.
    devral        smallint not null default 1,
    gecerli_bit   date,
    ekleyen       integer  not null default 0,
    ekleme_tarihi timestamp not null default now(),
    degistiren    integer  not null default 0,
    degistirme_tarihi timestamp,
    -- Rol ya da kullanici: biri dolu olmali, ikisi birden degil.
    constraint ck_dokuman_erisim_kim
        check ((rol_id is null) <> (kullanici_id is null))
);
create unique index if not exists ux_dokuman_erisim
    on public.dokuman_erisim(hedef_tur, hedef_id,
                             coalesce(rol_id, 0), coalesce(kullanici_id, 0));
create index if not exists ix_dokuman_erisim_hedef
    on public.dokuman_erisim(hedef_tur, hedef_id);

-- Kartin Erisim sekmesi: uc katman TEK LISTEDE, kaynagi yazili.
create or replace view public.v_dokuman_erisim as
    -- 1) Dokumana ozel izin
    select (e.id * 10 + 2)::bigint as id, e.hedef_id as dokuman_id,
           e.rol_id, e.kullanici_id,
           e.oku, e.indir, e.duzenle, e.paylas, e.sil, e.onayla,
           'doküman'::varchar(20) as kaynak, e.gecerli_bit
      from public.dokuman_erisim e
     where e.hedef_tur = 2
    union all
    -- 2) Klasorden devralinan izin
    select (e.id * 10 + 1)::bigint, d.id,
           e.rol_id, e.kullanici_id,
           e.oku, e.indir, e.duzenle, e.paylas, e.sil, e.onayla,
           'klasör'::varchar(20), e.gecerli_bit
      from public.dokuman_erisim e
      join public.dokuman d on d.klasor_id = e.hedef_id
     where e.hedef_tur = 1 and e.devral = 1
    union all
    -- 3) SAHIP: her zaman tam yetkili. Tabloya satir yazmak, sahip degisince
    --    eski satiri temizlemeyi unutmak demekti.
    select (d.id * 10)::bigint, d.id, null::integer, d.sahip_id,
           1::smallint, 1::smallint, 1::smallint, 1::smallint, 1::smallint, 1::smallint,
           'sahip'::varchar(20), null::date
      from public.dokuman d
     where d.sahip_id is not null;

comment on view public.v_dokuman_erisim is
    'Dokuman erisimi (425): klasor izni + dokuman izni + sahip, kaynagiyla birlikte.';

-- Rol secici: Erisim sekmesi rol adini gostersin (kart kod tablosu).
create or replace view public.v_rol_lookup as
    select r.id, r.ad, 1::smallint as aktif from public.rol r;
