-- İKİSİ DE AYNI SORUNUN İKİ UCU: göz muayenesinde hekimin elleri
-- biyomikroskopta, gözü okülerdedir. Bulgu ya konumdur ("saat 11'de kanama")
-- ya cümledir ("kornea saydam") - ikisini de klavyeyle almak muayeneyi böler.
--
-- ÇİZİM ÖLÇÜM DEĞİLDİR. C/D oranı, GİB, görme yine kendi tablolarına yazılır;
-- şema onların yerini almaz, yerini GÖSTERİR. Bu yüzden çizim ayrı tabloda
-- durur ve ölçüm tablolarına dokunmaz.
