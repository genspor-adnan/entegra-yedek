-- Çizim ve dikte AYRI YETKİ DEĞİL: ikisi de muayene bulgusu yazmanın başka
--   bir yoludur. "goz.muayene" değiştirme yetkisi olan çizer ve dikte eder;
--   olmayan ikisini de yapamaz. Ayrı yetki açmak, yetki matrisinde aynı
--   eylemin iki kapısını açık bırakma riski taşırdı.
-- Sözlük yönetimi ise ayrı: kurum sözlüğünü değiştirmek herkesin diktesini
--   etkiler.
-- TUR 0 = KAYNAK YETKİSİ (ekran/kayıt): sözlük bir ekranı olan veridir, bu
--   yüzden 691'deki göz yetkileriyle aynı türde. Tur 1 (özel yetki) yazılırsa
--   kullanıcıya çözülen KAYNAK listesine girmez; menü ve rota sessizce yok
--   olur - "yetkiyi ekledim ama ekran açılmıyor"un sebebi budur.
insert into public.yetki (kod, ad, grup, tur, sira, aktif)
select 'goz.dikte_sozluk', 'Dikte sözlüğü yönetimi', 'Göz', 0, 10, 1
 where not exists (select 1 from public.yetki y where y.kod = 'goz.dikte_sozluk');

-- Betik daha önce tur=1 ile uygulanmış olabilir (geliştirme sırası): düzelt.
update public.yetki set tur = 0, grup = 'Göz'
 where kod = 'goz.dikte_sozluk' and (tur <> 0 or grup <> 'Göz');

-- YENİ YETKİ KİMSEDE YOKSA EKRAN DA YOKTUR: yetki eklemek, onu bir role
--   vermeden yarım kalır - menü görünmez, rota açılmaz ve "ekran çalışmıyor"
--   diye aranır. 691'deki göz yetkileriyle aynı davranış: yönetici rolü alır,
--   ötekiler yetki matrisinden verilir.
insert into public.rol_yetki (rol_id, yetki_id, gor, ekle, degistir, sil, ekleyen)
select r.id, y.id, 1, 1, 1, 1, 0
  from public.rol r cross join public.yetki y
 where r.kod = 'yonetici' and y.kod = 'goz.dikte_sozluk'
   and not exists (select 1 from public.rol_yetki ry
                    where ry.rol_id = r.id and ry.yetki_id = y.id);
