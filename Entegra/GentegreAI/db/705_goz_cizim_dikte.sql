-- SVG sunumdur; aranabilir olan işaret satırlarıdır.
--
-- DİKTE SÖZLÜĞÜ VERİDİR, KOD DEĞİL. "see de → C/D" eşlemesi hekimden hekime
-- değişir; kuruma ve kullanıcıya ait satır olmalı ki yeni bir terim için
-- sürüm çıkmak gerekmesin.

