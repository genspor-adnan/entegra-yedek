-- =========================================================== çizim ==

create table if not exists public.goz_cizim (
  id                bigint primary key generated by default as identity,
  goz_muayene_id    integer     not null references public.goz_muayene(id) on delete cascade,
  goz               smallint    not null,           -- kod_liste goz.taraf (1 OD · 2 OS)
  sema_turu         smallint    not null,           -- kod_liste goz.cizim_sema
  surum             integer     not null default 1,
  kilitli           smallint    not null default 0,
  -- Sunum katmanı: serbest çizgiler ve damgaların yerleşimi. Kayıt burada
  --   DEĞİL işaret satırlarındadır; bu alan yalnız ekranın yeniden çizmesi
  --   ve yazdırma içindir.
  svg               text        not null default '',
  -- Çizimden üretilen cümle. Bulgu alanına YAZILMIŞ hâli değil, ÖNERİ:
  --   hekim onaylayana kadar goz_fundus/goz_on_segment'e geçmez.
  uretilen_metin    text        not null default '',
  aciklama          text        not null default '',
  sube_id           integer     not null default 0,
  ekleyen           integer     not null default 0,
  ekleme_tarihi     timestamptz not null default now(),
  degistiren        integer     not null default 0,
  degistirme_tarihi timestamptz
);

comment on table public.goz_cizim is
  'Göz şeması çizimi (705). Bir muayenenin bir gözü ve bir şema türü için bir '
  'sürüm. Tamamlanmış muayenenin çizimi kilitlenir; düzeltme yeni sürümle yapılır.';
comment on column public.goz_cizim.kilitli is
  'Muayene tamamlanınca 1 olur (705). Kilitli çizim değiştirilmez - ona '
  'dayanan rapor/epikrizle tutarsızlığa düşmesin diye.';

create unique index if not exists ux_goz_cizim_surum
  on public.goz_cizim (goz_muayene_id, goz, sema_turu, surum);
-- Kart açılınca "bu muayenenin çizimleri" sorgusu her seferinde çalışır.
create index if not exists ix_goz_cizim_muayene
  on public.goz_cizim (goz_muayene_id);

create table if not exists public.goz_cizim_isaret (
  id                bigint primary key generated by default as identity,
  cizim_id          bigint      not null references public.goz_cizim(id) on delete cascade,
  sekil             smallint    not null default 1,   -- kod_liste goz.cizim_sekil
  tur               smallint    not null default 0,   -- kod_liste goz.cizim_isaret
  -- NORMALİZE KONUM (0-1): şemanın piksel boyu ekrana göre değişir, kayıt
  --   değişmemeli. Yazdırmada da aynı oran kullanılır.
  x                 numeric(6,4),
  y                 numeric(6,4),
  -- Saat kadranı ve disk çapı: hekimin konuştuğu ölçü birimleri. Konumdan
  --   HESAPLANIR ama satırda durur - sorgu "saat 6 yırtığı" diye arar.
  saat              smallint,
  boyut_dd          numeric(5,2),
  renk              varchar(9)  not null default '',
  -- Serbest çizim yolu (SVG path "d"). Damgada boş.
  yol               text        not null default '',
  aciklama          text        not null default '',
  sira              integer     not null default 0,
  ekleyen           integer     not null default 0,
  ekleme_tarihi     timestamptz not null default now()
);

comment on table public.goz_cizim_isaret is
  'Şema üzerindeki tek tek işaretler (705). SVG sunumdur; ARANABİLİR olan '
  'bu satırlardır: "saat 6 yırtığı olan hastalar" sorusu resimden değil '
  'buradan cevaplanır.';

create index if not exists ix_goz_cizim_isaret_cizim
  on public.goz_cizim_isaret (cizim_id, sira);
create index if not exists ix_goz_cizim_isaret_tur
  on public.goz_cizim_isaret (tur) where tur > 0;

-- =========================================================== dikte ==

create table if not exists public.dikte_terim (
  id                integer primary key generated by default as identity,
  kapsam            smallint    not null default 1,   -- kod_liste dikte.kapsam
  -- Kişisel terim: yalnız o kullanıcının diktesinde uygulanır. Kurum terimi
  --   herkeste geçerli - "gib → GİB" gibi kurumsal yazım kararları.
