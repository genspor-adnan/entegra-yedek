alter table public.acil_yatak
    add column if not exists monitor      smallint not null default 0,
    add column if not exists ventilator   smallint not null default 0,
    add column if not exists defibrilator smallint not null default 0,
    add column if not exists oksijen      smallint not null default 0,
    add column if not exists aspirator    smallint not null default 0,
    add column if not exists infuzyon     smallint not null default 0,
    add column if not exists izolasyon    smallint not null default 0,
    add column if not exists pediatrik    smallint not null default 0;

create table if not exists public.acil_yatak_olay (
    id           bigint generated by default as identity primary key,
    yatak_id     integer not null references public.acil_yatak(id) on delete cascade,
    tur          smallint not null,
    basvuru_id   bigint,
    zaman        timestamptz not null default now(),
    kullanici_id integer not null default 0,
    not_metni    varchar(200) not null default ''
);
create index if not exists ix_acil_yatak_olay_yatak on public.acil_yatak_olay (yatak_id, zaman desc);

comment on table public.acil_yatak_olay is
  '1118: acil yatak olay gunlugu - 1 yerlesti, 2 cikti/tasindi, 3 temizlige alindi, 4 temizlik bitti, '
  '5 kullanim disi, 6 kullanima acildi. Tetikler yazar.';

-- Başvuru yatağa girer / yataktan çıkar (taşıma = eski yatakta 2, yenide 1; çıkış = 2).
create or replace function public.tg_acil_basvuru_yatak_olay() returns trigger language plpgsql as $$
declare
    v_kul integer := coalesce(new.degistiren, new.ekleyen, 0);
begin
    if tg_op = 'INSERT' then
        if new.yatak_id is not null then
            insert into public.acil_yatak_olay (yatak_id, tur, basvuru_id, kullanici_id)
            values (new.yatak_id, 1, new.id, v_kul);
        end if;
        return new;
    end if;
    if new.yatak_id is distinct from old.yatak_id then
        if old.yatak_id is not null then
            insert into public.acil_yatak_olay (yatak_id, tur, basvuru_id, kullanici_id)
            values (old.yatak_id, 2, new.id, v_kul);
        end if;
        if new.yatak_id is not null then
            insert into public.acil_yatak_olay (yatak_id, tur, basvuru_id, kullanici_id)
            values (new.yatak_id, 1, new.id, v_kul);
        end if;
    elsif new.yatak_id is not null and old.cikis_zamani is null and new.cikis_zamani is not null then
        insert into public.acil_yatak_olay (yatak_id, tur, basvuru_id, kullanici_id, zaman)
        values (new.yatak_id, 2, new.id, v_kul, new.cikis_zamani);
    end if;
    return new;
end $$;

drop trigger if exists tg_acil_basvuru_yatak_olay on public.acil_basvuru;
create trigger tg_acil_basvuru_yatak_olay after insert or update of yatak_id, cikis_zamani on public.acil_basvuru
    for each row execute function public.tg_acil_basvuru_yatak_olay();

-- Yatak durumu: temizlik ve kullanım dışı olayları (dolu / boş hasta olaylarından gelir).
create or replace function public.tg_acil_yatak_durum_olay() returns trigger language plpgsql as $$
declare
    v_tur smallint;
begin
    if new.durum is not distinct from old.durum then return new; end if;
    v_tur := case
        when new.durum = 2 then 3
        when new.durum = 3 then 5
        when new.durum = 0 and old.durum = 2 then 4
        when new.durum = 0 and old.durum = 3 then 6
        else null end;
    if v_tur is not null then
        insert into public.acil_yatak_olay (yatak_id, tur, kullanici_id)
        values (new.id, v_tur, coalesce(new.degistiren, 0));
    end if;
    return new;
end $$;

drop trigger if exists tg_acil_yatak_durum_olay on public.acil_yatak;
create trigger tg_acil_yatak_durum_olay after update of durum on public.acil_yatak
    for each row execute function public.tg_acil_yatak_durum_olay();
