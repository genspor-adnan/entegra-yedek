\set ON_ERROR_STOP on

create table if not exists public.ceviri (
    kapsam            varchar(20)  not null,
    anahtar           varchar(200) not null,
    dil               smallint     not null,
    metin             varchar(300) not null,
    ekleyen           integer   not null default 0,
    ekleme_tarihi     timestamp not null default now()::timestamp,
    degistiren        integer   not null default 0,
    degistirme_tarihi timestamp,
    constraint pk_ceviri primary key (kapsam, anahtar, dil)
);

comment on table public.ceviri is
  'Arayuz cevirileri (194). Anahtar TURKCE metnin kendisidir; ceviri yoksa Turkce gosterilir.';

-- Tek metin: yoksa Türkçe (anahtarın kendisi) döner.
create or replace function public.fn_ceviri(p_kapsam varchar, p_anahtar varchar,
                                            p_dil smallint)
returns varchar language sql stable as $$
    select coalesce((select c.metin from public.ceviri c
                      where c.kapsam = p_kapsam and c.anahtar = p_anahtar
                        and c.dil = p_dil), p_anahtar)
$$;

comment on function public.fn_ceviri(varchar, varchar, smallint) is
  'Ceviri metni; kayit yoksa anahtarin kendisi (Turkce) doner (194).';

-- Bir dilin TAMAMI: arayuz girişte tek çağrıda indirir, sunucu önbelleğe alır.
create or replace function public.fn_ceviri_sozluk(p_dil smallint)
returns table (kapsam varchar, anahtar varchar, metin varchar)
language sql stable as $$
    select c.kapsam, c.anahtar, c.metin
      from public.ceviri c where c.dil = p_dil
     order by c.kapsam, c.anahtar
$$;

