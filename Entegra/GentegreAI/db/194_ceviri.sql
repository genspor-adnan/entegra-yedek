--  Dil seçimi vardı (taraf_kullanici.dil · TR/EN/DE bayrakları) ama ekranda
--  hiçbir metin değişmiyordu: menü, kart sekmeleri ve kolon başlıkları koda
--  Türkçe gömülüydü.
--
--  TASARIM — ANAHTAR TÜRKÇE METNİN KENDİSİDİR:
--    ceviri(kapsam='menu', anahtar='Satış Faturaları', dil=1) -> 'Sales Invoices'
--  Ayrı anahtar sözlüğü tutulmaz; yeni ekran eklendiğinde çeviri yoksa Türkçe
--  görünür (kademeli doldurulabilir). Aynı kelimenin bağlama göre farklı
--  karşılığı olabildiği için KAPSAM ayrımı var ('menu' · 'etiket').
--
--  TEK KAYNAK: sözlüğü hem sunucu (katalog başlıkları) hem arayüz (menü, sabit
--  metinler) aynı tablodan okur - iki ayrı sözlük zamanla ayrışırdı.
--
--  dil kodları: 0 Türkçe (kaynak metin) · 1 English · 2 Deutsch
