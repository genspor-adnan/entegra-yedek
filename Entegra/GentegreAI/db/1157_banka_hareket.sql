-- ------------------------------------------------------------- hareketler --
create table if not exists public.banka_hareket (
    id              bigint generated by default as identity primary key,
    hesap_id        integer      not null references public.hesap(id),
    sube_id         integer      not null references public.sube(id),
    kaynak          smallint     not null default 1,         -- 1 API · 2 dosya · 3 benzetim
    banka_islem_no  varchar(80)  not null,
    islem_tarihi    timestamptz  not null,
    valor_tarihi    date,
    tutar           numeric(18, 2) not null,                 -- + gelen · − giden
    doviz_cinsi     varchar(3)   not null default 'TL',
    bakiye          numeric(18, 2),
    aciklama        varchar(500) not null default '',
    karsi_ad        varchar(200) not null default '',
    karsi_iban      varchar(34)  not null default '',
    karsi_vkn       varchar(11)  not null default '',
    fatura_metni    varchar(200) not null default '',
    sinif           varchar(60)  not null default '',
    ham             jsonb,
    -- 0 bekliyor · 1 öneri hazır · 2 işlendi · 3 yoksayıldı · 4 seçim bekliyor
    durum           smallint     not null default 0,
    oneri           jsonb,
    kasa_islem_id   integer references public.kasa_islem(id) on delete set null,
    isleyen         integer,
    isleme_zamani   timestamptz,
    ekleme_tarihi   timestamptz  not null default now(),
    constraint ux_banka_hareket unique (hesap_id, banka_islem_no)
);
create index if not exists ix_banka_hareket_hesap on public.banka_hareket (hesap_id, islem_tarihi desc);
create index if not exists ix_banka_hareket_durum on public.banka_hareket (durum) where durum in (0, 1, 4);
comment on table public.banka_hareket is 'Bankadan çekilen hesap hareketleri (1157) - öneri, işleme (kasa işlemi bağı).';

-- ---------------------------------------------------------------- kurallar --
create table if not exists public.banka_kural (
    id              integer generated by default as identity primary key,
    sira            smallint     not null default 100,
    ad              varchar(120) not null,
    -- iban · vkn · fatura · kendi_hesap · aciklama
    kosul_tur       varchar(20)  not null,
    kosul_metin     varchar(120) not null default '',
    yon             smallint     not null default 0,          -- 1 gelen · -1 giden · 0 ikisi
    -- tahsilat_tediye · virman · pos · masraf · yoksay · cari
    sonuc           varchar(20)  not null,
    hedef_hesap_id  integer references public.hesap(id),
    hedef_masraf_id integer references public.masraf(id),
    hedef_taraf_id  integer references public.taraf(id),
    hesap_id        integer references public.hesap(id),      -- boş = bütün banka hesapları
    sistem          smallint     not null default 0,
    aktif           smallint     not null default 1,
    ekleyen         integer      not null default 0,
    ekleme_tarihi   timestamptz  not null default now(),
    degistiren      integer,
    degistirme_tarihi timestamptz,
    constraint ck_banka_kural_kosul check (kosul_tur in ('iban', 'vkn', 'fatura', 'kendi_hesap', 'aciklama')),
    constraint ck_banka_kural_sonuc check (sonuc in ('tahsilat_tediye', 'virman', 'pos', 'masraf', 'yoksay', 'cari'))
);
comment on table public.banka_kural is 'Banka hareketi öneri kuralları (1157) - sıra ile; sistem kuralları silinmez, kapatılır.';

insert into public.banka_kural (sira, ad, kosul_tur, yon, sonuc, sistem)
select v.sira, v.ad, v.kt, 0, v.sonuc, 1
  from (values (10::smallint, 'Karşı IBAN carinin Banka / IBAN listesinde', 'iban', 'tahsilat_tediye'),
               (20::smallint, 'Karşı VKN / TCKN cari kaydında', 'vkn', 'tahsilat_tediye'),
               (30::smallint, 'Açıklamada açık fatura no geçiyor', 'fatura', 'tahsilat_tediye'),
               (40::smallint, 'Karşı IBAN kurumun kendi hesabı', 'kendi_hesap', 'virman')) v(sira, ad, kt, sonuc)
 where not exists (select 1 from public.banka_kural k where k.sistem = 1 and k.kosul_tur = v.kt);

-- ----------------------------------------------------------------- öneri --
create or replace function public.fn_banka_iban(p text)
returns text language sql immutable as $$ select upper(regexp_replace(coalesce(p, ''), '\s', '', 'g')) $$;

-- Hareket için ÖNERİ: kuralları sırayla dener, ilk tutanı yazar. Döner: yeni durum.
create or replace function public.fn_banka_oneri(p_hareket bigint)
returns smallint language plpgsql as $$
declare
    h public.banka_hareket; k record; v_oneri jsonb; v_taraf integer; v_belge integer; v_adet int;
    v_hesap integer; v_iban text; v_yon smallint; v_durum smallint := 0;
begin
    select * into h from public.banka_hareket where id = p_hareket for update;
    if not found or h.durum in (2, 3) then return h.durum; end if;
    v_iban := public.fn_banka_iban(h.karsi_iban);
    v_yon := case when h.tutar >= 0 then 1 else -1 end;

    for k in select * from public.banka_kural
              where aktif = 1 and (hesap_id is null or hesap_id = h.hesap_id) and (yon = 0 or yon = v_yon)
              order by sira, id
    loop
        v_oneri := null; v_taraf := null; v_belge := null;
        if k.kosul_tur = 'iban' and v_iban <> '' then
            select min(b.taraf_id), count(distinct b.taraf_id) into v_taraf, v_adet
              from public.taraf_banka b where b.aktif = 1 and public.fn_banka_iban(b.iban) = v_iban;
            if v_adet = 1 then v_oneri := jsonb_build_object('guven', 96, 'neden', 'Karşı IBAN carinin Banka / IBAN listesinde');
            elsif v_adet > 1 then v_oneri := jsonb_build_object('guven', 50, 'neden', 'IBAN ' || v_adet || ' caride kayıtlı', 'secim', true);
            end if;
        elsif k.kosul_tur = 'vkn' and h.karsi_vkn <> '' then
            select min(t.id), count(*) into v_taraf, v_adet from public.taraf t
             where t.vkno = h.karsi_vkn and (t.musteri = 1 or t.tedarikci = 1 or t.kurum = 1);
            if v_adet = 1 then v_oneri := jsonb_build_object('guven', 85, 'neden', 'Karşı VKN / TCKN cari kaydında');
            elsif v_adet > 1 then v_oneri := jsonb_build_object('guven', 50, 'neden', 'VKN ' || v_adet || ' caride kayıtlı', 'secim', true);
            end if;
        elsif k.kosul_tur = 'fatura' and h.tutar > 0 then
            -- Açıklamada geçen açık satış faturası (numara en az 6 karakter).
            select b.id, b.taraf_id into v_belge, v_taraf from public.belge b
             where b.durum = 0 and length(coalesce(b.belge_no, '')) >= 6
               and position(upper(b.belge_no) in upper(h.aciklama || ' ' || h.fatura_metni)) > 0
             order by b.belge_tarihi desc limit 1;
            if v_belge is not null then v_oneri := jsonb_build_object('guven', 90, 'neden', 'Açıklamada fatura no geçiyor'); end if;
        elsif k.kosul_tur = 'kendi_hesap' and v_iban <> '' then
            select x.id into v_hesap from public.hesap x
             where x.id <> h.hesap_id and public.fn_banka_iban(x.iban) = v_iban limit 1;
            if v_hesap is not null then
                v_oneri := jsonb_build_object('tur', 'virman', 'hedefHesapId', v_hesap, 'guven', 99,
                                              'neden', 'Karşı IBAN kurumun kendi hesabı');
            end if;
        elsif k.kosul_tur = 'aciklama' and k.kosul_metin <> ''
              and upper(h.aciklama || ' ' || h.karsi_ad) like '%' || upper(k.kosul_metin) || '%' then
            v_oneri := jsonb_build_object('guven', 88, 'neden', 'Kural: "' || k.kosul_metin || '"');
            v_taraf := k.hedef_taraf_id;
        end if;

        continue when v_oneri is null;
        -- Sonuç türü ve hedefler.
        if not v_oneri ? 'tur' then
            v_oneri := v_oneri || jsonb_build_object('tur',
                case k.sonuc when 'tahsilat_tediye' then case when h.tutar >= 0 then 'tahsilat' else 'tediye' end
                             when 'cari' then case when h.tutar >= 0 then 'tahsilat' else 'tediye' end
                             else k.sonuc end);
        end if;
        if v_taraf is not null then
            v_oneri := v_oneri || jsonb_build_object('tarafId', v_taraf,
                'tarafAd', (select coalesce(nullif(t.unvan, ''), t.ad || ' ' || coalesce(t.soyad, '')) from public.taraf t where t.id = v_taraf));
            -- Faturası henüz bulunmadıysa: carinin tutarı TAM tutan açık faturası.
            if v_belge is null and h.tutar > 0 then
                select b.id into v_belge from public.belge b
                 where b.taraf_id = v_taraf and b.durum = 0 and abs(b.genel_toplam - h.tutar) < 0.01
                 order by b.belge_tarihi desc limit 1;
            end if;
        end if;
        if v_belge is not null then
            v_oneri := v_oneri || jsonb_build_object('belgeId', v_belge,
                'belgeNo', (select belge_no from public.belge where id = v_belge));
        end if;
        if k.hedef_hesap_id is not null and not v_oneri ? 'hedefHesapId' then
            v_oneri := v_oneri || jsonb_build_object('hedefHesapId', k.hedef_hesap_id);
        end if;
        if k.hedef_masraf_id is not null then v_oneri := v_oneri || jsonb_build_object('masrafId', k.hedef_masraf_id); end if;
        if v_oneri ? 'hedefHesapId' then
            v_oneri := v_oneri || jsonb_build_object('hedefHesapAd',
                (select ad from public.hesap where id = (v_oneri ->> 'hedefHesapId')::int));
        end if;
        v_oneri := v_oneri || jsonb_build_object('kuralId', k.id);
        -- Hedefi eksik öneri (cari yok, masraf kalemi yok...) seçim ister.
        v_durum := case when coalesce((v_oneri ->> 'secim')::boolean, false) then 4
                        when (v_oneri ->> 'tur') in ('tahsilat', 'tediye') and not v_oneri ? 'tarafId' then 4
                        when (v_oneri ->> 'tur') in ('virman', 'pos') and not v_oneri ? 'hedefHesapId' then 4
                        when (v_oneri ->> 'tur') = 'masraf' and not v_oneri ? 'masrafId' then 4
                        else 1 end;
        update public.banka_hareket set oneri = v_oneri, durum = v_durum where id = p_hareket;
        return v_durum;
    end loop;
    update public.banka_hareket set oneri = null, durum = 0 where id = p_hareket;
    return 0;
end $$;

-- Hesabın işlenmemiş hareketleri için öneriyi yeniden üretir (kural değişince / yeni IBAN).
create or replace function public.fn_banka_oneri_yenile(p_hesap integer)
returns integer language plpgsql as $$
declare r record; v_n int := 0;
begin
    for r in select id from public.banka_hareket where (p_hesap is null or hesap_id = p_hesap) and durum in (0, 1, 4) loop
        perform public.fn_banka_oneri(r.id); v_n := v_n + 1;
    end loop;
    return v_n;
end $$;

-- Kasa işlemi iptal edilince / silinince bağlı hareket yeniden "bekliyor" ve önerisi tazelenir.
--   Silmede BEFORE: banka_hareket.kasa_islem_id FK'si ON DELETE SET NULL - AFTER tetik çalıştığında
--   bağ çoktan boşalmış olur ve hareket "işlendi" kalırdı.
create or replace function public.fn_banka_hareket_kasa_iptal()
returns trigger language plpgsql as $$
declare v_id bigint;
begin
    if (tg_op = 'UPDATE' and new.durum = 3 and old.durum <> 3) or tg_op = 'DELETE' then
        for v_id in
            update public.banka_hareket set durum = 0, kasa_islem_id = null, isleyen = null, isleme_zamani = null
             where kasa_islem_id = old.id returning id
        loop
            perform public.fn_banka_oneri(v_id);
        end loop;
    end if;
    return coalesce(new, old);
end $$;
drop trigger if exists trg_banka_hareket_kasa_iptal on public.kasa_islem;
drop trigger if exists trg_banka_hareket_kasa_sil on public.kasa_islem;
create trigger trg_banka_hareket_kasa_iptal after update of durum on public.kasa_islem
    for each row execute function public.fn_banka_hareket_kasa_iptal();
create trigger trg_banka_hareket_kasa_sil before delete on public.kasa_islem
    for each row execute function public.fn_banka_hareket_kasa_iptal();

-- ----------------------------------------------------------------- görünüm --
create or replace view public.v_banka_hareket as
select h.id, h.hesap_id, x.ad as hesap_ad, x.doviz_cinsi as hesap_doviz, h.sube_id, h.kaynak,
       h.banka_islem_no, h.islem_tarihi, h.valor_tarihi, h.tutar, h.doviz_cinsi, h.bakiye,
       h.aciklama, h.karsi_ad, h.karsi_iban, h.karsi_vkn, h.fatura_metni, h.sinif,
       h.durum, h.oneri,
       coalesce((h.oneri ->> 'tur'), '') as oneri_tur,
       coalesce((h.oneri ->> 'tarafAd'), (h.oneri ->> 'hedefHesapAd'), '') as oneri_hedef,
       coalesce((h.oneri ->> 'neden'), '') as oneri_neden,
       coalesce((h.oneri ->> 'guven')::int, 0) as oneri_guven,
       h.kasa_islem_id, ki.islem_no as kasa_islem_no, h.isleme_zamani,
       case when h.tutar > 0 then h.tutar else 0 end as gelen,
       case when h.tutar < 0 then -h.tutar else 0 end as giden
  from public.banka_hareket h
  join public.hesap x on x.id = h.hesap_id
  left join public.kasa_islem ki on ki.id = h.kasa_islem_id;

-- Banka hesabı listesinin yeni kolonları: bekleyen hareket ve banka - sistem farkı.
create or replace view public.v_banka_hesap_durum as
select x.id as hesap_id,
       (select count(*) from public.banka_hareket b where b.hesap_id = x.id and b.durum in (0, 1, 4)) as bekleyen,
       (select count(*) from public.banka_hareket b where b.hesap_id = x.id and b.durum = 1) as oneri_hazir,
       x.banka_bakiye, x.banka_son_cekim, x.banka_son_sonuc, x.banka_kaynak, x.banka_onay_bitis
  from public.hesap x;

-- -------------------------------------------------------------------- yetki --
insert into public.yetki (kod, ad, grup, tur, sira, urun_modu, modul)
select 'banka.hareket', 'Banka Hareketleri', 'Finans', 0, y.sira, y.urun_modu, y.modul
  from public.yetki y where y.kod = 'hesap.tanim.banka.liste'
on conflict (kod) do update set ad = excluded.ad, grup = excluded.grup, aktif = 1;

-- Gör: Banka Hesabı Listesi'ni gören rol. Çek / işle (ekle, değiştir): o rol KASA İŞLEMİ
--   yazabiliyorsa - işlemek kasa işlemi üretir. Liste yetkisi tek başına yalnız "gör" verir.
insert into public.rol_yetki (rol_id, yetki_id, gor, ekle, degistir, sil, deger, kapsam, ekleyen)
select ry.rol_id, yn.id, ry.gor, coalesce(ki.ekle, 0), coalesce(ki.ekle, 0), 0, ry.deger, ry.kapsam, 0
  from public.rol_yetki ry
  join public.yetki ye on ye.id = ry.yetki_id and ye.kod = 'hesap.tanim.banka.liste'
  join public.yetki yn on yn.kod = 'banka.hareket'
  left join lateral (select max(k.ekle) as ekle from public.rol_yetki k join public.yetki yk on yk.id = k.yetki_id
                      where k.rol_id = ry.rol_id and yk.kod = 'kasa_islem') ki on true
 where not exists (select 1 from public.rol_yetki x where x.rol_id = ry.rol_id and x.yetki_id = yn.id);

-- Eşleştirme kuralları ayrı ekran (Yönetim › Entegrasyonlar): hakları Entegrasyon kartından.
insert into public.yetki (kod, ad, grup, tur, sira, urun_modu, modul)
select 'banka.kural', 'Banka Eşleştirme Kuralları', 'Finans', 0, y.sira, y.urun_modu, y.modul
  from public.yetki y where y.kod = 'banka.hareket'
on conflict (kod) do update set ad = excluded.ad, grup = excluded.grup, aktif = 1;

insert into public.rol_yetki (rol_id, yetki_id, gor, ekle, degistir, sil, deger, kapsam, ekleyen)
select ry.rol_id, yn.id, ry.gor, ry.ekle, ry.degistir, ry.sil, ry.deger, ry.kapsam, 0
  from public.rol_yetki ry
  join public.yetki ye on ye.id = ry.yetki_id and ye.kod = 'entegrasyon'
  join public.yetki yn on yn.kod = 'banka.kural'
 where not exists (select 1 from public.rol_yetki x where x.rol_id = ry.rol_id and x.yetki_id = yn.id);

-- Bu betiğin önceki hali yalnız "gör" yazmıştı: elle dokunulmamış (degistiren = 0) satırları düzelt.
update public.rol_yetki r
   set ekle = 1, degistir = 1
  from public.yetki yn
 where yn.id = r.yetki_id and yn.kod = 'banka.hareket'
   and r.degistiren = 0 and r.ekle = 0 and r.degistir = 0 and r.gor = 1
   and exists (select 1 from public.rol_yetki k join public.yetki yk on yk.id = k.yetki_id
                where k.rol_id = r.rol_id and yk.kod = 'kasa_islem' and k.ekle = 1);

-- Garanti BBVA entegrasyon satırı (anahtarsız - kullanıcı girer). Test ortamında anahtar
