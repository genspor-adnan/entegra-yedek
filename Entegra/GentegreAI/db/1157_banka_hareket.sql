select 'GARANTI', 'Garanti BBVA API', 1, 1, 'https://apis.garantibbva.com.tr', 'https://apis.garantibbva.com.tr',
       '{"scope": "oob"}'::jsonb, 'Hesap hareketleri (Elektronik Hesap Özeti) - 1157', 0
 where not exists (select 1 from public.entegrasyon_hesap where kod = 'GARANTI');

