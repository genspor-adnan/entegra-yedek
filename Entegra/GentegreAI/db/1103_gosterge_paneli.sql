-- ------------------------------------------------------------ YETKİ --
--  Her panel matriste bir satır (grup "Gösterge Panelleri"). Yeni panel eklenince
--  tanım ekranı aynı satırı açar.
insert into public.yetki (kod, ad, grup, tur, sira, urun_modu, modul, aktif)
select 'gosterge.' || p.kod, p.ad, 'Gösterge Panelleri', 0, 9200 + p.sira, 0, '', 1
  from public.gosterge_paneli p
 where not exists (select 1 from public.yetki y where y.kod = 'gosterge.' || p.kod);

-- Varsayılan: YALNIZ yönetici rolleri (rol yetkisinde Gör) bütün panelleri, "genel"i
--   Ana Sayfa'yı (panel) gören roller. Gerisini kullanıcı matristen belirler.
insert into public.rol_yetki (rol_id, yetki_id, gor, ekleyen)
select distinct ry.rol_id, yp.id, 1, 0
  from public.rol_yetki ry
  join public.yetki yk on yk.id = ry.yetki_id and ry.gor = 1
  join public.yetki yp on yp.kod like 'gosterge.%'
 where yk.kod = 'rol' or (yk.kod = 'panel' and yp.kod = 'gosterge.genel')
on conflict (rol_id, yetki_id) do nothing;

update public.rol r set yetki_surumu = yetki_surumu + 1
 where exists (select 1 from public.rol_yetki ry join public.yetki y on y.id = ry.yetki_id
                where y.kod like 'gosterge.%' and ry.rol_id = r.id);

commit;
