-- ----------------------------------------------------------- organizma --
alter table public.lab_organizma
    add column if not exists ureme_esigi     numeric(12,0),
    add column if not exists esik_birimi     varchar(20) not null default '',
    add column if not exists panel_notu      varchar(300) not null default '';

comment on column public.lab_organizma.ureme_esigi is
    'Anlamlı üreme eşiği (idrar için CFU/mL) - altındaki üreme "anlamlı değil" (509).';

create table if not exists public.lab_organizma_direnc (
    id             integer generated by default as identity primary key,
    organizma_id   integer not null references public.lab_organizma(id) on delete cascade,
    antibiyotik_id integer not null references public.lab_antibiyotik(id),
    sebep          varchar(200) not null default '',
    ekleyen        integer not null default 0,
    ekleme_tarihi  timestamp not null default now()
);
create unique index if not exists ux_lab_organizma_direnc
    on public.lab_organizma_direnc (organizma_id, antibiyotik_id);
comment on table public.lab_organizma_direnc is
    'Doğal (intrinsik) direnç - bu antibiyotik bu organizmada RAPORLANMAZ (509).';

create table if not exists public.lab_organizma_panel (
    id             integer generated by default as identity primary key,
    organizma_id   integer not null references public.lab_organizma(id) on delete cascade,
    antibiyotik_id integer not null references public.lab_antibiyotik(id),
    sira           smallint not null default 0,
    basamak        smallint not null default 1,   -- lab_antibiyotik.basamak ile aynı kodlar
    not_metni      varchar(200) not null default '',
    ekleyen        integer not null default 0,
    ekleme_tarihi  timestamp not null default now()
);
create unique index if not exists ux_lab_organizma_panel
    on public.lab_organizma_panel (organizma_id, antibiyotik_id);
create index if not exists ix_lab_organizma_panel_sira
    on public.lab_organizma_panel (organizma_id, sira);
comment on table public.lab_organizma_panel is
    'Organizmaya özel antibiyogram paneli - genel basamağı ezer (509).';

/**
 * ANTİBİYOGRAMDA SORULACAK ANTİBİYOTİKLER: doğal direnç ÇIKARILIR, organizmaya
 * özel panel varsa o, yoksa genel katalog kullanılır. Antibiyogram ekranı ve
 * otomatik panel üretimi tek yerden okur.
 */
create or replace function public.fn_lab_antibiyogram_paneli(p_organizma integer)
returns table(antibiyotik_id integer, kod varchar, ad varchar, basamak smallint,
              sira smallint, yalniz_uriner smallint)
language sql stable as $$
    select a.id, a.kod, a.ad,
           coalesce(p.basamak, a.basamak)::smallint,
           coalesce(p.sira, 100)::smallint,
           a.yalniz_uriner
      from public.lab_antibiyotik a
      left join public.lab_organizma_panel p
             on p.organizma_id = p_organizma and p.antibiyotik_id = a.id
     where a.durum = 0
       and not exists (select 1 from public.lab_organizma_direnc d
                        where d.organizma_id = p_organizma and d.antibiyotik_id = a.id)
       -- Organizmaya özel panel TANIMLIYSA yalnız o panel geçerlidir.
       and (p.id is not null
            or not exists (select 1 from public.lab_organizma_panel x
                            where x.organizma_id = p_organizma))
     order by coalesce(p.sira, 100), coalesce(p.basamak, a.basamak), a.ad;
$$;

-- ------------------------------------------------------------ besiyeri --
alter table public.lab_besiyeri
    add column if not exists stok_id        integer references public.stok(id),
    add column if not exists ekim_hacmi_ul  numeric(9,3) not null default 0,
    add column if not exists sayim_carpani  integer not null default 0,
    add column if not exists kk_susu        varchar(120) not null default '',
    add column if not exists kk_periyot     smallint not null default 1;

comment on column public.lab_besiyeri.ekim_hacmi_ul is
    'Kalibre öze hacmi (µL) - koloni sayımı bununla CFU/mL''ye çevrilir (509).';
comment on column public.lab_besiyeri.sayim_carpani is
    'Koloni x çarpan = CFU/mL. 0 ise ekim hacminden hesaplanır (1000/hacim).';
comment on column public.lab_besiyeri.kk_periyot is
    '1 her yeni lot · 2 haftalık · 3 aylık - KK suşunun çalışılma sıklığı.';

create table if not exists public.lab_besiyeri_numune (
    id           integer generated by default as identity primary key,
    besiyeri_id  integer not null references public.lab_besiyeri(id) on delete cascade,
    numune_tipi  smallint not null,
    ekim_sekli   varchar(60) not null default '',
    amac         varchar(200) not null default ''
);
create unique index if not exists ux_lab_besiyeri_numune
    on public.lab_besiyeri_numune (besiyeri_id, numune_tipi);
comment on table public.lab_besiyeri_numune is
    'Bu besiyeri hangi numune tipinde ekilir - kültür açılışındaki varsayılan set (509).';

/** Koloni sayısını CFU/mL''ye çevirir: çarpan yoksa ekim hacminden türetilir. */
create or replace function public.fn_lab_cfu(p_besiyeri integer, p_koloni numeric)
returns numeric language sql stable as $$
    select case
             when b.sayim_carpani > 0 then p_koloni * b.sayim_carpani
             when b.ekim_hacmi_ul > 0 then round(p_koloni * (1000.0 / b.ekim_hacmi_ul))
             else null            -- çarpan tanımsız: sayım raporlanamaz
           end
      from public.lab_besiyeri b where b.id = p_besiyeri;
$$;
