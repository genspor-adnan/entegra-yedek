--      antibiyotiği hiç sormaz.
--    * PANEL: hangi antibiyotik hangi basamakta çalışılır (rutin → alternatif
--      → kısıtlı). `lab_antibiyotik.basamak` genel kuraldır; organizmaya özel
--      panel onu ezer.
--    * ÜREME EŞİĞİ: idrar kültüründe 10^5 CFU/mL altı "anlamlı değil" diye
--      raporlanır. Eşik kartta durur, teknisyenin ezberinde değil.
--
--  BESİYERİ - okuma planı vardı ama iki şey eksikti:
--    * EKİM HACMİ / SAYIM ÇARPANI: 1 µL kalibre öze ile sayılan koloni
--      ×1000 ile CFU/mL'ye çevrilir. Çarpan kartta olmadan koloni sayımı
--      raporlanamaz.
--    * STOK BAĞI: besiyeri bir sarftır; lot ve miat stoktan okunur. Miadı
--      geçmiş lotla çalışılan kültür geçersizdir.
--    * NUMUNE TİPİ: hangi örnekte hangi besiyeri ekilir - kültür açılırken
