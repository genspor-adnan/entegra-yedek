-- ============================================================================
--  Gentegre AI — AMBALAJ BIRIMLERI (1 kutu = 12 adet)
--  143_stok_birim.sql
--
--  Kullanici: "hem adet ana birim hem de ambalaj 1 kutu = 12 adet tanimlayip,
--  belgeye KUTU girisi yapip ADET cikisi yapabilmeliyim."
--
--  KURAL: STOK BAKIYESI HER ZAMAN ANA BIRIMDE (kullanici karari). Ambalaj
--  yalnizca GIRIS BICIMIDIR - kullanici "2 kutu" yazar, sistem 24 adet dusurur.
--  Boylece kismi acilan kutu sorunu olusmaz ve tum raporlar tek birimde toplar.
--
--  Belge satirinda ayrim:
--      adet         - kullanicinin GIRDIGI miktar (2)
--      birim        - girilen birim (56 = Kutu)
--      birim_carpan - o birimin ana birim karsiligi (12)
--      miktar       - ANA BIRIM miktari = adet x carpan (24)  <- stok bunu okur
--
--  Fiyat GIRILEN BIRIME aittir (1 kutu = 120 TL): tutar = adet x birim_fiyat,
--  yani carpanla oynanmaz - kullanicinin gordugu fiyat kutunun fiyatidir.
-- ============================================================================
\set ON_ERROR_STOP on

create table if not exists public.stok_birim (
    id                integer generated by default as identity primary key,
    stok_id           integer      not null,
    -- kod_liste 'stok.ana_birim' degeri (51 Adet, 56 Kutu, 53 Koli...).
    birim             smallint     not null,
    -- 1 <birim> kac ANA BIRIM eder. Ana birimin kendisi 1'dir.
    carpan            numeric(19,6) not null default 1,
    barkod            varchar(30)  not null default '',
    -- Belge acilinca hangi birim ON SECILI gelsin (alis kutu, satis adet gibi).
    varsayilan_alis   smallint     not null default 0,
    varsayilan_satis  smallint     not null default 0,
    durum             smallint     not null default 1,
    aciklama          varchar(100) not null default '',
    ekleyen           integer      not null default 0,
    ekleme_tarihi     timestamp    not null default now()::timestamp,
    degistiren        integer      not null default 0,
    degistirme_tarihi timestamp,
    constraint fk_stok_birim_stok foreign key (stok_id)
        references public.stok (id) on delete cascade,
    constraint ck_stok_birim_carpan check (carpan > 0)
);

-- Ayni stokta ayni birim iki kez tanimlanamaz: "1 kutu = 12" ve "1 kutu = 24"
--   ayni anda dogru olamaz.
create unique index if not exists ux_stok_birim on public.stok_birim (stok_id, birim);
create index if not exists ix_stok_birim_barkod on public.stok_birim (barkod)
    where barkod <> '';

comment on table public.stok_birim is
  'Stogun ambalaj birimleri ve ana birim carpani (143). Bakiye ANA BIRIMDE tutulur.';
comment on column public.stok_birim.carpan is
  '1 bu birim kac ana birim eder (1 kutu = 12 adet -> 12).';

-- Belge satirinda GIRILEN birimin carpani saklanir: stok kartindaki tanim
--   sonradan degisse bile eski belge kendi carpaniyla okunur (tarihsel dogruluk).
alter table public.belge_satir
    add column if not exists birim_carpan numeric(19,6) not null default 1;

comment on column public.belge_satir.birim_carpan is
  'Girilen birimin ana birim carpani (143). miktar = adet x birim_carpan.';

alter table public.stok_birim
    add constraint ck_stok_birim_durum check (durum in (0, 1)) not valid;

do $$
declare v_adet integer;
begin
    select count(*) into v_adet from public.stok_birim;
    raise notice '143 tamam: stok_birim (% kayit) + belge_satir.birim_carpan', v_adet;
end $$;
