-- ------------------------------------------------------- sayım motoru ----
--  HER ÖLÇÜT BİR DAL. Serbest SQL yerine CASE: ölçüt tanımı ekrandan
--  açılıp kapanabilir ama SORGUYU kullanıcı yazamaz.
create or replace function public.fn_enabiz_gun_sonu_sayilar(p_tarih date,
                                                             p_sube integer default 0)
returns table(skrs_kod smallint, hesap_kodu varchar, ad varchar, sayi integer)
language sql stable as $$
    select o.skrs_kod, o.hesap_kodu, o.ad,
           case o.hesap_kodu
             when 'basvuru' then (
               select count(distinct b.id)::int from public.belge b
                where b.tur = 19 and b.belge_tarihi::date = p_tarih
                  and (p_sube = 0 or b.sube_id = p_sube))
             when 'tanili_basvuru' then (
               select count(distinct m.belge_id)::int
                 from public.muayene m
                 join public.tani t on t.muayene_id = m.id
                where coalesce(m.muayene_tarihi, m.baslangic)::date = p_tarih
                  and coalesce(t.icd_kod, '') <> ''
                  and (p_sube = 0 or m.sube_id = p_sube))
             when 'yatis' then (
               select count(*)::int from public.yatis y
                where y.giris_tarihi::date = p_tarih
                  and (p_sube = 0 or y.sube_id = p_sube))
             when 'ayaktan' then (
               select count(distinct b.id)::int from public.belge b
                where b.tur = 19 and b.belge_tarihi::date = p_tarih
                  and (p_sube = 0 or b.sube_id = p_sube)
                  and not exists (select 1 from public.yatis y where y.belge_id = b.id))
             when 'taburcu' then (
               select count(*)::int from public.yatis y
                where y.cikis_tarihi::date = p_tarih
                  and (p_sube = 0 or y.sube_id = p_sube))
             when 'muayene_normal' then (
               select count(distinct m.id)::int from public.muayene m
                where coalesce(m.muayene_tarihi, m.baslangic)::date = p_tarih
                  and (p_sube = 0 or m.sube_id = p_sube)
                  and not exists (select 1 from public.dis_muayene dm where dm.muayene_id = m.id))
             when 'muayene_acil' then (
               select count(distinct m.id)::int from public.muayene m
                 join public.departman d on d.id = m.bolum_id
                where coalesce(m.muayene_tarihi, m.baslangic)::date = p_tarih
                  and (p_sube = 0 or m.sube_id = p_sube)
                  and upper(d.ad) like '%ACİL%')
             when 'muayene_dis' then (
               select count(distinct dm.muayene_id)::int from public.dis_muayene dm
                 join public.muayene m on m.id = dm.muayene_id
                where coalesce(m.muayene_tarihi, m.baslangic)::date = p_tarih
                  and (p_sube = 0 or m.sube_id = p_sube))
             when 'goruntuleme_rontgen' then (
               select count(*)::int from public.radyoloji_istem i
                where i.cekim_tarihi::date = p_tarih
                  and (p_sube = 0 or i.sube_id = p_sube)
                  and i.modalite in (1, 2, 3))
             when 'goruntuleme_usg' then (
               select count(*)::int from public.radyoloji_istem i
                where i.cekim_tarihi::date = p_tarih
                  and (p_sube = 0 or i.sube_id = p_sube)
                  and i.modalite = 4)
             else 0
           end as sayi
      from public.enabiz_gun_sonu_olcut o
     where o.aktif = 1
     order by o.sira, o.skrs_kod;
$$;

comment on function public.fn_enabiz_gun_sonu_sayilar(date, integer) is
  '884: 407 gun sonu olcutlerinin o gunku sayilari. Modalite kodlari '
  'kurum katalogundan gelir - rontgen/USG dallari kurulumda dogrulanmali.';

-- -------------------------------------------------- gönderim oranı ----
--  DENETİMİN SORDUĞU ORAN: o gün ÜRETİLEN paketlerin kaçı GÖNDERİLDİ.
--  %95-103 aralığı Bakanlığın kendi ölçüsü; burada kurumun kendi
--  tarafındaki oran hesaplanır - Bakanlık tarafındaki sayı geri bildirim
--  raporundan gelir ve ikisi karşılaştırılır.
create or replace view public.v_enabiz_gonderim_orani as
select p.olay_tarihi::date              as tarih,
       t.uss_paket_kodu,
       count(*)::int                    as uretilen,
       count(*) filter (where p.durum = 3)::int as gonderilen,
       count(*) filter (where p.durum in (0, 1, 2))::int as bekleyen,
       count(*) filter (where p.durum = 4)::int as hatali,
       round(100.0 * count(*) filter (where p.durum = 3) / nullif(count(*), 0), 1) as oran
  from public.enabiz_paket p
  join public.enabiz_paket_turu t on t.id = p.paket_turu_id
 where p.durum <> 5
 group by p.olay_tarihi::date, t.uss_paket_kodu;

comment on view public.v_enabiz_gonderim_orani is
  '884: gun ve paket turu bazinda uretilen/gonderilen orani (KTS H13). '
  'Bakanligin bekledigi aralik %95-103; iptal (durum 5) sayilmaz.';

