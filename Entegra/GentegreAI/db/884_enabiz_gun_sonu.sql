--  Şema (rehber.enabiz.gov.tr, 19.09.2026):
--    GUN_SONU_VERI_SETI (zorunlu)
--      KAYIT_YERI (SKRS c3eade04-…)                      zorunlu
--      GUN_SONU_BILGISI (Grup, tekrarlı)
--        GUN_SONU_TARIH                                  datetime
