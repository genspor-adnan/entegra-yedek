--  (anjiyo alt kırılımları, protez, onkoloji göstergeleri…). Hepsini
--  "0 gönder" diye doldurmak, yapmadığımız işi sıfırla bildirmek olurdu -
--  Bakanlık tarafında bu, veri gönderen ama iş yapmayan tesis görüntüsü
--  üretir. Bu yüzden ölçütler TANIM TABLOSUNDA duruyor: kurum kendi
--  yaptığı işlerin ölçütlerini açar. Tohum liste, HBYS verisinden
--  DOĞRUDAN sayılabilen on ölçüttür.
--
--  SAYIM HESABI SQL'DE, TANIMDA DEĞİL. Ölçüt satırı bir `hesap_kodu`
--  taşır; sayımı `fn_enabiz_gun_sonu_sayilar` yapar. Tanım tablosuna
