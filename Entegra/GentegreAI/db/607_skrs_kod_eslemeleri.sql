--  ÜLKE/UYRUK listesi ALINMADI: SKRS sayfasında "RESMİ ÜLKELER" listesinin
--  içeriği satır içinde verilmiyor (yalnız başlık var). 101'deki uyruk GUID'i
--  de farklı bir liste (d650777a-...) - ayrıca çözülmeli.
-- =====================================================================

