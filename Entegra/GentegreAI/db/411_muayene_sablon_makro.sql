-- ============================================================================
--  411 - MUAYENE SABLON KAPSAMI ve METIN MAKROLARI (Faz 1 · Muayene v1)
--
--  Kaynak: Ekranlar/Muayene/muayene_sablonlari.html
--
--  KAPSAM: bir sablon kurumun, bir bransin ya da TEK HEKIMIN olabilir
--  ("Dr. A. Koc - DM kontrol"). Kisisel sablonu kurum sablonu gibi tutmak,
--  bir hekimin alistigi duzeni herkese dayatmak olurdu; ayri tabloya koymak
--  ise ayni sablon motorunu iki kez yazdirirdi. Tek tablo + kapsam alanlari.
--
--  MAKRO: hekimin en cok yazdigi metinleri kisayolla cagirmasi (".fmn" ->
--  "Genel durum iyi, bilinc acik..."). Sablonun yerine gecmez: sablon ALAN
--  tanimlar, makro METIN uretir - biri yapiyi, oteki hizi cozer.
-- ============================================================================

alter table public.muayene_sablon
    -- Hekim dolu = KISISEL sablon. Bos + bolum dolu = brans. Ikisi de bos =
    --   kurum genelinde.
    add column if not exists hekim_id integer;

create index if not exists ix_muayene_sablon_kapsam
    on public.muayene_sablon(hekim_id, bolum_id) where durum = 1;

comment on column public.muayene_sablon.hekim_id is
    'Dolu ise KISISEL sablon (411): yalniz o hekimin listesinde cikar.';

-- ---------------------------------------------------------------------------
--  METIN MAKROLARI
--
--  Kisayol ALAN BAZLIDIR: ayni ".ktr" karar alaninda baska, hikayede baska
--  metin uretebilsin. Alan bos ise her alanda gecerli.
-- ---------------------------------------------------------------------------
create table if not exists public.metin_makro (
    id            integer primary key generated by default as identity,
    kisayol       varchar(20)  not null,
    -- Hangi alanda gecerli: 'sikayet' · 'hikaye' · 'bulguOzet' · 'karar' · ''
    alan          varchar(30)  not null default '',
    metin         text         not null default '',
    aciklama      varchar(200) not null default '',
    -- Kapsam sablonla AYNI kural: hekim > bolum > kurum.
    hekim_id      integer,
    bolum_id      integer,
    durum         smallint     not null default 1,
    kullanim      integer      not null default 0,
    sube_id       integer      not null default 0,
    ekleyen       integer      not null default 0,
    ekleme_tarihi timestamp    not null default now(),
    degistiren    integer      not null default 0,
    degistirme_tarihi timestamp
);

-- Ayni kisayol ayni alanda ayni kapsamda TEK olmali; farkli hekimler ayni
--   kisayolu kendi metinleriyle kullanabilir.
create unique index if not exists ux_metin_makro
    on public.metin_makro(kisayol, alan, coalesce(hekim_id, 0), coalesce(bolum_id, 0));

comment on table public.metin_makro is
    'Metin makrolari (411): kisayol -> hazir metin. Sablon yapiyi, makro hizi cozer.';

-- Kurulum bos gelmesin: en cok yazilan uc metin.
insert into public.metin_makro (kisayol, alan, metin, aciklama)
select v.kisayol, v.alan, v.metin, v.aciklama
  from (values
      ('.fmn', 'bulguOzet',
       'Genel durum iyi, bilinç açık, koopere, oryante. Sistem muayeneleri doğal.',
       'Fizik muayene - normal'),
      ('.ktr', 'karar',
       '3 ay sonra kontrol, tetkikler ile.',
       'Kontrol önerisi'),
      ('.rut', 'hikaye',
       'Rutin kontrol için başvurdu. Yeni şikayet tarif etmiyor, ilaç uyumu iyi.',
       'Rutin kontrol hikayesi')
  ) as v(kisayol, alan, metin, aciklama)
 where not exists (select 1 from public.metin_makro m
                    where m.kisayol = v.kisayol and m.alan = v.alan
                      and m.hekim_id is null and m.bolum_id is null);

-- Sablon secicisi kapsami da gostersin (kisisel / brans / kurum).
--   DROP gerekli: kolon tipi varchar(120)'den text'e degisiyor, PostgreSQL
--   "create or replace view" ile tip degistirtmiyor.
drop view if exists public.v_muayene_sablon_lookup;
create view public.v_muayene_sablon_lookup as
    select s.id,
           s.ad || case when s.hekim_id is not null then ' (kişisel)'
                        when s.bolum_id is not null then ' (branş)'
                        else '' end as ad,
           s.durum as aktif
      from public.muayene_sablon s;
