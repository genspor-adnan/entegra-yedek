--
--  Sayım = sayılan miktarların listesi + fark hesabı + "Farkları Fişle ve
--  Kapat". Delphi'de elle yapılan düzeltmenin otomatik hali: farklar MEVCUT
--  fiş türleriyle yazılır - Giriş Fişi (tür 3) tipi 2 "Sayım Fazlası", Çıkış
--  Fişi (tür 4) tipi 5 "Sayım Eksiği" (101). Yeni hareket türü YOK.
--
--  SİSTEM MİKTARI = sayım açıldığı andaki bakiye (kesit). Sayım tarihi açılış
--  anıdır, değiştirilmez: geçmiş tarihli kesit için bakiyeyi geriye sarmak
--  gerekirdi (lot defteri aktarımla tohumlanmış, sıfırdan toplanamaz).
--  Fark = Sayılan - Sistem; fişler sayım tarihiyle kesilir, sonradan girilen
--  hareketler olduğu gibi kalır.
--
--  LOT: izlemli stokta her lot ayrı satır (stok_lot_durum'da kalanı olan lot).
--  Depo bakiyesi lot toplamını tutmuyorsa aradaki miktar "lotsuz" satırdır; o satırda
--  fark varsa kapanış durur (lotsuz fiş kesilemez - önce lot bilgisi düzeltilir).
--  Sayılmayan satıra DOKUNULMAZ (fark yazılmaz) - rafta hiç olmayan kalem için
--  sayılan 0 girilir.
--
--  Log: 1620 sayım · 1621 sayım satırı. İdempotent.
-- =============================================================================
\set ON_ERROR_STOP on

begin;

-- ------------------------------------------------------------- tablolar --
create table if not exists public.stok_sayim (
    id                 integer generated by default as identity primary key,
    sayim_no           varchar(20)  not null default '',
    sube_id            integer      not null,
    depo_id            integer      not null references public.depo (id),
    sayim_tarihi       timestamptz  not null default now(),
    -- 0 tüm depo · 1 kategori (alt ağacıyla) · 2 seçili stoklar (boş açılır, okutarak / ekleyerek dolar)
    kapsam             smallint     not null default 0 check (kapsam in (0, 1, 2)),
    kategori_id        integer,
    aciklama           varchar(250) not null default '',
    -- 0 açık · 1 kapandı
    durum              smallint     not null default 0 check (durum in (0, 1)),
    giris_belge_id     integer      references public.belge (id),
    cikis_belge_id     integer      references public.belge (id),
    kapanis_tarihi     timestamptz,
    kapatan            integer      not null default 0,
    ekleyen            integer      not null default 0,
    ekleme_tarihi      timestamptz  not null default now(),
    degistiren         integer      not null default 0,
    degistirme_tarihi  timestamptz
);
create index if not exists ix_stok_sayim_depo on public.stok_sayim (depo_id, durum);

create table if not exists public.stok_sayim_satir (
    id                 integer generated by default as identity primary key,
    sayim_id           integer      not null references public.stok_sayim (id) on delete cascade,
    stok_id            integer      not null references public.stok (id),
    seri_lot_id        integer      references public.stok_seri_lot (id),
    sistem             numeric(24,6) not null default 0,
    -- NULL = sayılmadı (fark yazılmaz); 0 = sayıldı, yok
    sayilan            numeric(24,6),
    birim_maliyet      numeric(19,6) not null default 0,
    sayan              integer      not null default 0,
    sayim_zamani       timestamptz,
    ekleyen            integer      not null default 0,
    ekleme_tarihi      timestamptz  not null default now()
);
create unique index if not exists ux_stok_sayim_satir
    on public.stok_sayim_satir (sayim_id, stok_id, coalesce(seri_lot_id, 0));

-- Açık sayım tek: aynı depoda iki açık sayım farkları iki kez fişlerdi.
create unique index if not exists ux_stok_sayim_acik
    on public.stok_sayim (depo_id) where durum = 0;

-- Kapanan sayım değişmez (satırı da).
create or replace function public.tg_stok_sayim_satir_kilit()
returns trigger language plpgsql as $$
begin
    if exists (select 1 from public.stok_sayim s
                where s.id = coalesce(new.sayim_id, old.sayim_id) and s.durum = 1) then
        raise exception 'Kapanmış sayımın satırı değiştirilemez.' using errcode = 'P0001';
    end if;
    return coalesce(new, old);
end $$;
drop trigger if exists tg_stok_sayim_satir_kilit on public.stok_sayim_satir;
create trigger tg_stok_sayim_satir_kilit before insert or update or delete on public.stok_sayim_satir
    for each row execute function public.tg_stok_sayim_satir_kilit();

-- ------------------------------------------------------ satır üretimi --
-- Kapsamdaki stoklar için satırları BUGÜNKÜ bakiyeden üretir (kesit = açılış).
--   İzlemsiz stok: depo bakiyesi (stok_durum), bakiye yoksa 0 - "stoğu 0 olanlar
--   dahil" (rafta bulunursa fazla çıkar). İzlemli stok: kalanı olan her lot.
create or replace function public.fn_stok_sayim_satir_uret(p_sayim_id integer, p_kullanici integer)
returns integer language plpgsql as $$
declare
    v public.stok_sayim%rowtype;
    v_sayi integer;
begin
    select * into v from public.stok_sayim where id = p_sayim_id;
    if not found or v.kapsam = 2 then return 0; end if;

    with recursive dal as (
        select k.id from public.kategori k where v.kapsam = 1 and k.id = v.kategori_id
        union all
        select k.id from public.kategori k join dal on k.ust_id = dal.id
    ), kapsam as (
        select s.id, s.izleme
          from public.stok s
         where s.durum = 1          -- stok.durum 1 = AKTİF (028)
           and (v.kapsam = 0 or s.kategori in (select id from dal))
    ), satir as (
        select k.id as stok_id, null::integer as seri_lot_id, coalesce(sd.kalan, 0) as sistem
          from kapsam k
          left join public.stok_durum sd on sd.stok_id = k.id and sd.depo_id = v.depo_id
         where k.izleme = 0
        union all
        select k.id, ld.seri_lot_id, ld.kalan
          from kapsam k
          join public.stok_lot_durum ld on ld.stok_id = k.id and ld.depo_id = v.depo_id and ld.kalan <> 0
         where k.izleme <> 0
        union all
        -- LOTSUZ BAKİYE: izlemli stokta depo bakiyesi lot toplamını tutmuyorsa (aktarılmış
        --   ya da lotsuz girilmiş mal) aradaki miktar AYRI satır - yoksa sayımda hiç görünmezdi.
        select k.id, null, coalesce(sd.kalan, 0) - coalesce(l.toplam, 0)
          from kapsam k
          left join public.stok_durum sd on sd.stok_id = k.id and sd.depo_id = v.depo_id
          left join lateral (select sum(ld.kalan) as toplam from public.stok_lot_durum ld
                              where ld.stok_id = k.id and ld.depo_id = v.depo_id) l on true
         where k.izleme <> 0 and coalesce(sd.kalan, 0) - coalesce(l.toplam, 0) <> 0
    )
    insert into public.stok_sayim_satir (sayim_id, stok_id, seri_lot_id, sistem, birim_maliyet, ekleyen)
    select p_sayim_id, s.stok_id, s.seri_lot_id, s.sistem,
           coalesce(public.fn_uretim_stok_maliyeti(s.stok_id), 0), p_kullanici
      from satir s
    on conflict do nothing;

    get diagnostics v_sayi = row_count;
    return v_sayi;
end $$;

comment on function public.fn_stok_sayim_satir_uret(integer, integer) is
  '1169: stok sayiminin satirlarini acilis anindaki bakiyeden uretir (izlemsiz stok depo '
  'bakiyesi, izlemli stok kalani olan her lot). Kapsam 2 (secili stoklar) bos acilir.';

-- --------------------------------------------------------------- yetki --
insert into public.yetki (kod, ad, grup, tur, sira, aktif)
select v.kod, v.ad, 'Stok & Hizmet', 0, 230, 1
  from (values ('stok.sayim', 'Stok Sayımı Kartı'),
               ('stok.sayim.liste', 'Stok Sayımları (Stok & Hizmet)')) as v(kod, ad)
 where not exists (select 1 from public.yetki y where y.kod = v.kod);

insert into public.rol_yetki (rol_id, yetki_id, gor, ekle, degistir, sil, ekleyen)
select r.id, y.id, 1, case when y.kod like '%.liste' then 0 else 1 end,
       case when y.kod like '%.liste' then 0 else 1 end, case when y.kod like '%.liste' then 0 else 1 end, 0
  from public.rol r cross join public.yetki y
 where r.kod = 'yonetici' and y.kod in ('stok.sayim', 'stok.sayim.liste')
   and not exists (select 1 from public.rol_yetki ry where ry.rol_id = r.id and ry.yetki_id = y.id);
update public.rol set yetki_surumu = yetki_surumu + 1 where kod = 'yonetici';

commit;
