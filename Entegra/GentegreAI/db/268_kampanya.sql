-- 268: KAMPANYA (kullanıcı: "kampanya tablo oluştur: kod, ad, başlama ve bitiş
-- tarihi, fiyat listesi id, durum; bir de kampanyaya bağlı kampanya_satir:
-- tip (liste/kategori/ürün), stok/hizmet seçimi, iskonto_yeri_id, iskonto_tipi
-- (yüzde/tutar), iskonto, durum... kurumda sözleşme kısmında fiyat listesi
-- yerine kampanya seçilecek").
--
-- Kampanya = bir FİYAT LİSTESİ üzerine işleyen indirim kuralları demeti.
-- Satır düzeyleri:
--   tip 1 LİSTE    -> iskonto_yeri_id = 0, indirim listenin tamamına
--   tip 2 KATEGORİ -> iskonto_yeri_id = kategori id
--   tip 3 ÜRÜN     -> iskonto_yeri_id = stok ya da hizmet id
-- Ürün/kategori hangi tarafta (stok mu hizmet mi) `kalem_turu` ile ayrılır -
-- stok id 5 ile hizmet id 5 farklı kayıtlardır, tek id kolonu bunu bilemez.

create table if not exists public.kampanya (
  id                integer generated by default as identity primary key,
  kod               varchar(20)  not null default '',
  ad                varchar(150) not null,
  baslangic         date,
  bitis             date,
  fiyat_listesi_id  integer references public.fiyat_listesi(id),
  durum             smallint not null default 1,      -- 1 Aktif / 0 Pasif
  aciklama          varchar(300) not null default '',
  ekleyen           integer  not null default 0,
  ekleme_tarihi     timestamp not null default now()::timestamp,
  degistiren        integer  not null default 0,
  degistirme_tarihi timestamp
);

comment on table public.kampanya is
  'Kampanya (268): bir fiyat listesi üzerine işleyen indirim kuralları.';

create unique index if not exists ux_kampanya_kod on public.kampanya (lower(kod))
  where kod <> '';
create index if not exists ix_kampanya_durum on public.kampanya (durum);

create table if not exists public.kampanya_satir (
  id                integer generated by default as identity primary key,
  kampanya_id       integer  not null references public.kampanya(id) on delete cascade,
  tip               smallint not null default 1,      -- 1 Liste / 2 Kategori / 3 Ürün
  -- 0 Farketmez (liste) / 1 Stok / 2 Hizmet
  kalem_turu        smallint not null default 0,
  -- Liste: 0, Kategori: kategori id, Ürün: stok/hizmet id
  iskonto_yeri_id   integer  not null default 0,
  iskonto_tipi      smallint not null default 1,      -- 1 Yüzde / 2 Tutar
  -- Yüzde ise 0-100 (20 ya da 25.35), tutar ise doğrudan fiyat (150).
  iskonto           numeric(24,6) not null default 0,
  doviz_cinsi       varchar(10) not null default '',  -- tutar tipinde anlamlı
  durum             smallint not null default 1,      -- 1 Aktif / 0 Pasif
  aciklama          varchar(300) not null default '',
  ekleyen           integer  not null default 0,
  ekleme_tarihi     timestamp not null default now()::timestamp,
  degistiren        integer  not null default 0,
  degistirme_tarihi timestamp,
  -- Yüzde 0-100 dışına çıkamaz: "iskonto 150" yüzde satırında sessizce fiyatı
  --   eksiye düşürürdü.
  constraint ck_kampanya_satir_yuzde
    check (iskonto_tipi <> 1 or (iskonto >= 0 and iskonto <= 100))
);

comment on table public.kampanya_satir is
  'Kampanya indirim satırı (268): liste/kategori/ürün düzeyinde yüzde ya da tutar.';

create index if not exists ix_kampanya_satir_kampanya
  on public.kampanya_satir (kampanya_id, durum);

-- ------------------------------------------------------------------ lookup --
create or replace view public.v_kampanya_lookup as
select k.id,
       (case when k.kod = '' then k.ad else k.kod || ' - ' || k.ad end)::varchar(200) as ad,
       k.durum as aktif
  from public.kampanya k;

-- ------------------------------------------------- kurum sözleşmesi: kampanya
-- Kurumun anlaşma koşulu artık bir FİYAT LİSTESİ değil KAMPANYA (kullanıcı):
-- kampanyanın kendi listesi ve indirim satırları var, ikisini ayrı ayrı
-- seçtirmek aynı bilgiyi iki yere yazmak olurdu.
alter table public.taraf_kurum add column if not exists kampanya_id integer
  references public.kampanya(id);
alter table public.taraf_kurum drop column if exists fiyat_listesi_id;

comment on column public.taraf_kurum.kampanya_id is
  'Kurumla yapılan anlaşmanın fiyat/indirim kuralları (268).';

-- -------------------------------------------------------------- kod listeleri
insert into public.kod_liste (kod, ad)
select 'kampanya.satir_tip', 'Kampanya Satır Tipi'
 where not exists (select 1 from public.kod_liste where kod = 'kampanya.satir_tip');

insert into public.kod_deger (liste_id, deger, ad, sira, aktif, ekleyen)
select l.id, v.deger, v.ad, v.deger * 10, 1, 0
  from public.kod_liste l
  cross join (values (1, 'Liste'), (2, 'Kategori'), (3, 'Ürün')) as v(deger, ad)
 where l.kod = 'kampanya.satir_tip'
   and not exists (select 1 from public.kod_deger d where d.liste_id = l.id);

insert into public.kod_liste (kod, ad)
select 'kampanya.iskonto_tipi', 'İskonto Tipi'
 where not exists (select 1 from public.kod_liste where kod = 'kampanya.iskonto_tipi');

insert into public.kod_deger (liste_id, deger, ad, sira, aktif, ekleyen)
select l.id, v.deger, v.ad, v.deger * 10, 1, 0
  from public.kod_liste l
  cross join (values (1, 'Yüzde'), (2, 'Tutar')) as v(deger, ad)
 where l.kod = 'kampanya.iskonto_tipi'
   and not exists (select 1 from public.kod_deger d where d.liste_id = l.id);

insert into public.kod_liste (kod, ad)
select 'kampanya.kalem_turu', 'Kalem Türü'
 where not exists (select 1 from public.kod_liste where kod = 'kampanya.kalem_turu');

insert into public.kod_deger (liste_id, deger, ad, sira, aktif, ekleyen)
select l.id, v.deger, v.ad, v.deger * 10, 1, 0
  from public.kod_liste l
  cross join (values (0, 'Farketmez'), (1, 'Stok'), (2, 'Hizmet')) as v(deger, ad)
 where l.kod = 'kampanya.kalem_turu'
   and not exists (select 1 from public.kod_deger d where d.liste_id = l.id);
