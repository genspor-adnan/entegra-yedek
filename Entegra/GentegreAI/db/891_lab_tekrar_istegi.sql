-- =====================================================================
--  891_lab_tekrar_istegi.sql
--  TEST TEKRARININ ELEKTRONİK OLARAK İSTENMESİ
--  (KTS denetim maddesi L8: "Test tekrarı elektronik olarak istenebiliyor
--   mu?")
--
--  BUGÜN NE VAR: `lab_sonuc.tekrar_no` (kaçıncı çalışma), düzeltme yolu
--  (`DuzeltAsync` eski satırı iptal edip yenisini açıyor) ve numune reddi /
--  serum indeksi retinde satırın "tekrar numune bekliyor" (6) durumuna
--  alınması. Yani tekrar ÇALIŞILDIĞINDA iz kalıyor.
--
--  EKSİK OLAN TALEBİN KENDİSİ: uzman ya da klinisyen "bu tetkiki tekrar
--  çalışın" diyemiyor. Bugün bu iş telefonla söyleniyor; laboratuvarda
--  kuyruğa düşmüyor, gerekçesi kayıtta durmuyor, karşılanıp
--  karşılanmadığı görünmüyor. Denetimin sorduğu tam olarak budur:
--  tekrar ELEKTRONİK olarak istenebiliyor mu.
--
--  TASARIM KARARLARI:
--
--  1. İKİ TÜR TEKRAR AYRIDIR. "Aynı tüpten tekrar çalış" (1) ile "yeni
--     numune alınsın" (2) laboratuvar için bambaşka iki iştir: birincisinde
--     tüp aranır (gerekirse arşivden çıkarılır, 890), ikincisinde hastadan
--     yeniden kan alınır. Tek bayrakla anlatılamaz.
--
--  2. AYNI SATIRDA TEK AÇIK TALEP. Kısmi benzersiz index ile; ikinci bir
--     talep, laboratuvara aynı işi iki kez yaptırırdı.
--
--  3. GEREKÇE ZORUNLU ve kod listesinden. "Neden tekrar" sorusunun cevabı
--     kalite kayıtlarının parçasıdır - serbest metin, sayılamaz.
--
--  4. TALEBİ SİSTEM KAPATIR. Aynı satıra yeni sonuç yazıldığında açık talep
--     "karşılandı" olur ve karşılayan sonuç kaydedilir. Elle kapatmaya
--     bırakmak, çalışılmış ama kuyrukta duran talepler biriktirirdi.
-- =====================================================================

create table if not exists public.lab_tekrar_istegi (
  id              integer generated by default as identity primary key,
  istem_satir_id  integer not null references public.lab_istem_satir(id) on delete cascade,
  -- Talebi doğuran sonuç (delta uyarısı, panik değer...). Talep sonuçsuz da
  --   açılabilir: numune pıhtılı gelmiş olabilir, ortada sonuç yoktur.
  sonuc_id        bigint references public.lab_sonuc(id) on delete set null,
  -- 1 aynı numuneden tekrar çalışma · 2 yeni numune istenmesi
  tur             smallint     not null default 1,
  gerekce_kod     smallint     not null default 0,
  gerekce         varchar(200) not null default '',
  isteyen_id      integer      not null default 0,
  istek_zamani    timestamptz  not null default now(),
  -- 1 bekliyor · 2 karşılandı · 3 iptal
  durum           smallint     not null default 1,
  karsilayan_sonuc_id bigint references public.lab_sonuc(id) on delete set null,
  kapanma_zamani  timestamptz,
  kapatan_id      integer,
  iptal_neden     varchar(200) not null default '',
  sube_id         integer      not null default 0,
  constraint ck_lab_tekrar_tur   check (tur in (1, 2)),
  constraint ck_lab_tekrar_durum check (durum in (1, 2, 3))
);

create unique index if not exists ux_lab_tekrar_acik
  on public.lab_tekrar_istegi (istem_satir_id) where durum = 1;
create index if not exists ix_lab_tekrar_bekleyen
  on public.lab_tekrar_istegi (durum, istek_zamani);

comment on table public.lab_tekrar_istegi is
  '891: test tekrari TALEBI (KTS L8). tur 1 ayni numuneden tekrar calisma, '
  '2 yeni numune. Ayni satirda tek acik talep; talebi sistem kapatir (yeni '
  'sonuc yazilinca).';

-- ------------------------------------------------------------ gerekçe ----
--  Kod listesi kurumundur (SKRS karşılığı yok); sayılabilir olsun diye
--  serbest metin değil koddur - "neden tekrar ettik" kalite göstergesidir.
insert into public.kod_liste (kod, ad)
select 'lab.tekrar_gerekce', 'Test tekrar gerekçesi'
 where not exists (select 1 from public.kod_liste l where l.kod = 'lab.tekrar_gerekce');

insert into public.kod_deger (liste_id, deger, ad, sira, dil, aktif)
select l.id, v.deger, v.ad, v.sira, 0, 1
  from public.kod_liste l
  cross join (values
    (1, 'Delta kontrolü uyarısı', 10),
    (2, 'Panik değer teyidi', 20),
    (3, 'Cihaz / yöntem hatası şüphesi', 30),
    (4, 'Numune kalitesi (hemoliz, lipemi, pıhtı)', 40),
    (5, 'Klinik tablo ile uyumsuz', 50),
    (6, 'Hekim talebi', 60),
    (7, 'İç kalite kontrol ihlali', 70),
    (9, 'Diğer', 90)
  ) as v(deger, ad, sira)
 where l.kod = 'lab.tekrar_gerekce'
   and not exists (select 1 from public.kod_deger d
                    where d.liste_id = l.id and d.deger = v.deger and d.dil = 0);

-- ------------------------------------------------------------- talep ----
/**
 * TEKRAR TALEBİ AÇ.
 *
 * Satırın durumu talebin TÜRÜNE göre değişir: yeni numune isteniyorsa satır
 * "tekrar numune bekliyor" (6) olur - numune kabul ekranı bunu zaten
 * gösteriyor; aynı tüpten tekrar çalışma isteniyorsa satır "çalışılıyor"a
 * (2) döner, çünkü laboratuvarın elinde iş vardır.
 *
 * ONAYLI SONUÇ İPTAL EDİLMEZ: tekrar istemek, verilmiş sonucu geçersiz
 * kılmaz - yeni sonuç gelince düzeltme/karşılaştırma yapılır. Sonucu burada
 * iptal etmek, hekimin elindeki raporu sessizce boşaltırdı.
 */
create or replace function public.fn_lab_tekrar_iste(p_satir_id integer,
                                                     p_tur     smallint,
                                                     p_gerekce_kod smallint,
                                                     p_gerekce varchar,
                                                     p_kullanici integer default 0,
                                                     p_sonuc_id bigint default null)
returns integer language plpgsql as $$
declare
    v_id   integer;
    v_sube integer;
begin
    if p_tur not in (1, 2) then
        raise exception 'Tekrar türü geçersiz (1 aynı numune · 2 yeni numune).';
    end if;
    if coalesce(p_gerekce_kod, 0) = 0 then
        raise exception 'Tekrar gerekçesi seçilmeli.';
    end if;
    if not exists (select 1 from public.lab_istem_satir s
                    where s.id = p_satir_id and s.durum <> 0) then
        raise exception 'İstem satırı bulunamadı ya da iptal edilmiş.';
    end if;
    if exists (select 1 from public.lab_tekrar_istegi t
                where t.istem_satir_id = p_satir_id and t.durum = 1) then
        raise exception 'Bu tetkik için zaten açık bir tekrar talebi var.';
    end if;

    select coalesce(i.sube_id, 0) into v_sube
      from public.lab_istem_satir s
      join public.lab_istem i on i.id = s.istem_id
     where s.id = p_satir_id;

    insert into public.lab_tekrar_istegi
           (istem_satir_id, sonuc_id, tur, gerekce_kod, gerekce, isteyen_id, sube_id)
    values (p_satir_id, p_sonuc_id, p_tur, p_gerekce_kod,
            left(coalesce(p_gerekce, ''), 200), p_kullanici, v_sube)
    returning id into v_id;

    update public.lab_istem_satir
       set durum = case when p_tur = 2 then 6 else 2 end,
           degistiren = p_kullanici, degistirme_tarihi = now()
     where id = p_satir_id;

    return v_id;
end $$;

comment on function public.fn_lab_tekrar_iste(integer, smallint, smallint, varchar, integer, bigint) is
  '891: test tekrari talebi acar (KTS L8). tur 2 ise satir "tekrar numune '
  'bekliyor" (6), tur 1 ise "calisiliyor" (2). Onayli sonuc IPTAL EDILMEZ.';

/**
 * TALEBİ KARŞILA. Yeni sonuç yazıldığında çağrılır; açık talep yoksa hiçbir
 * şey yapmaz (her sonuç bir talebin cevabı değildir).
 */
create or replace function public.fn_lab_tekrar_karsila(p_satir_id integer,
                                                        p_sonuc_id bigint,
                                                        p_kullanici integer default 0)
returns integer language sql as $$
    update public.lab_tekrar_istegi
       set durum = 2, karsilayan_sonuc_id = p_sonuc_id,
           kapanma_zamani = now(), kapatan_id = p_kullanici
     where istem_satir_id = p_satir_id and durum = 1
    returning id;
$$;

/** Talebi iptal et - gerekçe zorunlu, çünkü istenen iş yapılmıyor. */
create or replace function public.fn_lab_tekrar_iptal(p_id integer,
                                                      p_neden varchar,
                                                      p_kullanici integer default 0)
returns integer language plpgsql as $$
declare v_satir integer;
begin
    if coalesce(trim(p_neden), '') = '' then
        raise exception 'İptal nedeni yazılmalı.';
    end if;

    update public.lab_tekrar_istegi
       set durum = 3, iptal_neden = left(p_neden, 200),
           kapanma_zamani = now(), kapatan_id = p_kullanici
     where id = p_id and durum = 1
    returning istem_satir_id into v_satir;

    if v_satir is null then
        raise exception 'Açık tekrar talebi bulunamadı.';
    end if;

    -- SATIR ESKİ HÂLİNE DÖNER: sonucu varsa "sonuçlandı"/"onaylandı",
    --   yoksa "bekliyor". Talep iptal edildiği hâlde satırın "çalışılıyor"
    --   kalması, hiç bitmeyen bir iş gösterirdi.
    update public.lab_istem_satir s
       set durum = case
             when exists (select 1 from public.lab_sonuc r
                           where r.istem_satir_id = s.id and r.durum = 3) then 5
             when exists (select 1 from public.lab_sonuc r
                           where r.istem_satir_id = s.id and r.durum in (1, 2)) then 3
             else 1 end,
           degistiren = p_kullanici, degistirme_tarihi = now()
     where s.id = v_satir;

    return v_satir;
end $$;

-- ------------------------------------------------------------- döküm ----
--  Laboratuvarın kuyruğu. ARŞİV BİLGİSİ DE GELİR (890): "aynı tüpten tekrar"
--  talebinde teknisyenin ilk işi tüpü bulmaktır; konumu burada yazmazsak
--  ekran iki ayrı yerden okunurdu.
create or replace view public.v_lab_tekrar_istegi as
select t.id, t.istem_satir_id as satir_id, s.istem_id, i.istem_no,
       s.tetkik_id, s.kod, s.ad as tetkik,
       i.taraf_id as hasta_id,
       coalesce(nullif(trim(h.ad || ' ' || h.soyad), ''), h.unvan) as hasta,
       t.tur, t.gerekce_kod, t.gerekce,
       coalesce(d.ad, '') as gerekce_adi,
       t.isteyen_id, coalesce(k.ad, '') as isteyen,
       t.istek_zamani, t.durum, t.sonuc_id, t.karsilayan_sonuc_id,
       t.kapanma_zamani, t.iptal_neden, t.sube_id,
       n.barkod,
       -- Tüp arşivdeyse nerede: tekrar çalışma önce tüpü bulmakla başlar.
       (select a.konum || ' · ' || a.goz from public.v_lab_arsiv a
         where a.numune_id = n.id and a.durum = 1 limit 1) as arsiv_yeri
  from public.lab_tekrar_istegi t
  join public.lab_istem_satir s on s.id = t.istem_satir_id
  join public.lab_istem i on i.id = s.istem_id
  left join public.lab_numune n on n.id = s.numune_id
  left join public.taraf h on h.id = i.taraf_id
  left join public.v_kullanici_lookup k on k.id = t.isteyen_id
  left join public.kod_deger d on d.deger = t.gerekce_kod and d.dil = 0
       and d.liste_id = (select l.id from public.kod_liste l
                          where l.kod = 'lab.tekrar_gerekce');

comment on view public.v_lab_tekrar_istegi is
  '891: tekrar talepleri - tetkik, hasta, gerekce adi, isteyen ve (890) '
  'tupun arsiv yeri.';

-- -------------------------------------------------------------- yetki ----
--  TEKRAR İSTEMEK AYRI BİR YETKİ: sonucu görebilen herkesin laboratuvara iş
--  açabilmesi doğru değil; ama yetki hem uzmanda hem klinisyende olabilir -
--  denetimin sorduğu "elektronik olarak istenebiliyor mu" ikisini de kapsar.
insert into public.yetki (kod, ad, grup, tur, sira, aktif, urun_modu, modul)
select v.kod, v.ad, 'Laboratuvar', v.tur, v.sira, 1, 2, 'lab'
  from (values
    ('lab.tekrar', 'Tekrar Talepleri', 0::smallint, 52::smallint),
    ('lab.tekrar.iste', 'Test tekrarı isteme', 1::smallint, 53::smallint)
  ) as v(kod, ad, tur, sira)
 where not exists (select 1 from public.yetki y where y.kod = v.kod);

insert into public.rol_yetki (rol_id, yetki_id, gor, ekle, degistir, sil, ekleyen)
select r.id, y.id, 1, 1, 1, 1, 0
  from public.rol r cross join public.yetki y
 where r.kod = 'yonetici' and y.kod in ('lab.tekrar', 'lab.tekrar.iste')
   and not exists (select 1 from public.rol_yetki ry
                    where ry.rol_id = r.id and ry.yetki_id = y.id);
update public.rol set yetki_surumu = yetki_surumu + 1 where kod = 'yonetici';

do $$
begin
    raise notice '891 tamam: % tekrar gerekcesi, % talep',
        (select count(*) from public.kod_deger d
           join public.kod_liste l on l.id = d.liste_id
          where l.kod = 'lab.tekrar_gerekce'),
        (select count(*) from public.lab_tekrar_istegi);
end $$;
