begin;

create table if not exists public.kalite_denetim (
    id                 integer generated by default as identity primary key,
    no                 varchar(20)  not null default public.fn_kalite_no('DEN', 3),
    departman_id       integer      not null references public.departman(id),
    plan_tarih         date         not null,
    gerceklesen        date,
    bas_denetci_id     integer      references public.taraf(id),
    ekip               varchar(300) not null default '',
    kapsam             varchar(2000) not null default '',
    sonuc_notu         varchar(2000) not null default '',
    durum              smallint     not null default 1,
    sube_id            integer      not null default 0,
    ekleyen            integer      not null default 0,
    ekleme_tarihi      timestamptz  not null default now(),
    degistiren         integer      not null default 0,
    degistirme_tarihi  timestamptz,
    constraint uq_kalite_denetim_no unique (no)
);
comment on table public.kalite_denetim is
  'İç denetim (1051). durum 1 planlı · 2 tamamlandı. no kayıt anında fn_kalite_no(DEN).';

create table if not exists public.kalite_denetim_bulgu (
    id                 integer generated by default as identity primary key,
    denetim_id         integer      not null references public.kalite_denetim(id) on delete cascade,
    sinif              smallint     not null default 2,
    aciklama           varchar(1000) not null,
    madde              varchar(80)  not null default '',
    dof_id             integer,
    sube_id            integer      not null default 0
);
comment on column public.kalite_denetim_bulgu.dof_id is
  'DÖF bağı (FK yok). Asıl bağ kalite_dof.kaynak_tur = 1 + kaynak_id = bulgu id.';
create index if not exists ix_kalite_denetim_bulgu on public.kalite_denetim_bulgu (denetim_id);

create or replace view public.v_kalite_denetim as
select d.id, d.no, d.departman_id, coalesce(dp.ad, '')::varchar(100) as birim_adi,
       d.plan_tarih, d.gerceklesen, coalesce(d.gerceklesen, d.plan_tarih) as tarih,
       d.bas_denetci_id, coalesce(fn_taraf_ad(t.unvan, t.ad, t.soyad), '')::varchar(120) as bas_denetci_adi,
       d.ekip, d.kapsam,
       nullif(concat_ws(' · ',
         (select nullif(count(*), 0) || ' majör' from public.kalite_denetim_bulgu b where b.denetim_id = d.id and b.sinif = 1),
         (select nullif(count(*), 0) || ' minör' from public.kalite_denetim_bulgu b where b.denetim_id = d.id and b.sinif = 2),
         (select nullif(count(*), 0) || ' gözlem' from public.kalite_denetim_bulgu b where b.denetim_id = d.id and b.sinif = 3)), '')::varchar(80) as bulgu_ozet,
       (d.durum = 1 and d.plan_tarih < current_date) as gecikti,
       case when d.durum = 2 then 'Tamamlandı' when d.plan_tarih < current_date then 'Gecikti' else 'Planlı' end::varchar(20) as durum_adi,
       d.durum, d.sube_id
  from public.kalite_denetim d
  left join public.departman dp on dp.id = d.departman_id
  left join public.taraf t on t.id = d.bas_denetci_id;

insert into public.ai_rehber_ekran (kaynak, rota, baslik, yol, menu_grup, menu_ad,
                                    yetki_kodu, urun_modu, modul, anahtar, aciklama, aksiyon_ekrani)
select 'kys-denetim', '/kys-denetim', 'İç Denetimler', 'Kalite › İç Denetimler', 'Kalite', 'İç Denetimler', 'kys.denetim', 0, 'kys',
       'iç denetim denetim no DEN bulgu majör minör gözlem ISO 9001 9.2 SKS DÖF',
       'İç denetim kayıtları: birim, plan / gerçekleşen tarih, baş denetçi, ekip, kapsam, sonuç notu; kartta bulgular (majör / minör / gözlem, ISO / SKS maddesi).',
       'kys-denetim-liste'
 where not exists (select 1 from public.ai_rehber_ekran e where e.kaynak = 'kys-denetim');

commit;
