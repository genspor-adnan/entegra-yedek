--  DURUM: 1 planlı · 2 tamamlandı.
--  BULGU SINIFI: 1 majör · 2 minör · 3 gözlem. Bulgunun DÖF'ü
--    kalite_dof.kaynak_tur = 1 + kaynak_id = bulgu id (DÖF dilimi 1050).
--  NUMARA: kayıt anında DEN-2026-001 (kolon varsayılanı, fn_kalite_no).
--  İdempotent.
