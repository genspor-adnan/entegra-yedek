-- =====================================================================
--  749_resmi_tatil.sql
--  RESMÎ TATİL TAKVİMİ.
--
--  743'te iş günü hesabı yalnız cumartesi-pazarı düşüyordu: 29 Ekim'e
--  denk gelen bir izin, bir gün fazla sayılıyordu. Tatil listesi olmadan
--  "iş günü" demek, yanlış sayıyı doğru sanmaktı - o yüzden fonksiyonun
--  başında açıkça yazılıydı. Liste artık var.
--
--  ============= MİLLÎ TATİLLER ÜRETİLİR, DİNÎ BAYRAMLAR GİRİLİR =======
--  Millî bayramlar mîlâdî takvimde SABİT tarihlidir; `fn_resmi_tatil_uret`
--  bir yılın tamamını tek çağrıda yazar. Dinî bayramlar (Ramazan, Kurban)
--  hicrî takvime bağlıdır ve Diyanet'in ilan ettiği tarihe göre kayar:
--  onları ALGORİTMAYLA ÜRETMİYORUZ. Bir gün kayan bir hesap, izin gününü
--  ve bordroyu yanlış hesaplar; "yaklaşık doğru" bir tatil takvimi,
--  olmayan takvimden daha tehlikelidir - çünkü kimse kontrol etmez.
--  Dinî bayramlar Resmî Tatiller ekranından girilir.
--
--  ============= YARIM GÜN =============================================
--  Arife günleri (Ramazan/Kurban arifesi saat 13:00'ten sonra, 28 Ekim
--  saat 13:00'ten sonra) yarım gündür. İzin hesabında yarım gün 0,5
--  sayılır - tam gün saymak çalışanın yarım gününü yer, hiç saymamak
--  kurumun yarım gününü.
-- =====================================================================

create table if not exists public.resmi_tatil (
    id                integer      primary key generated by default as identity,
    tarih             date         not null,
    ad                varchar(80)  not null,
    -- 1 millî · 2 dinî · 3 idarî (kurumun kendi kararı: kuruluş yıldönümü,
    --   idarî izin). Ayrım rapor içindir: dinî bayramlar her yıl kayar,
    --   millî olanlar üretilir, idarî olanı yalnız kurum bilir.
    tur               smallint     not null default 1,
    -- 0 tam gün · 1 yarım gün (öğleden sonra).
    yarim_gun         smallint     not null default 0,
    -- ÇALIŞMA VAR MI: hastane tatilde de çalışır (acil, yatan, nöbet).
    --   Bu bayrak "bu tatilde poliklinik kapalı" demek için; varsayılan 1
    --   (çalışma sürer) çünkü sağlık kurumunda tatil = kapalı DEĞİLDİR.
    calisma_var       smallint     not null default 1,
    aciklama          varchar(200) not null default '',
    -- ŞUBE BOŞSA KURUM GENELİ. Yerel tatil (kurtuluş günü) tek şubeyi
    --   ilgilendirebilir.
    sube_id           integer,
    aktif             smallint     not null default 1,
    ekleyen           integer      not null default 0,
    ekleme_tarihi     timestamptz  not null default now(),
    degistiren        integer      not null default 0,
    degistirme_tarihi timestamptz
);

-- AYNI GÜN İKİ KEZ YAZILMASIN (şube bazında). Bir gün hem "millî" hem
--   "idarî" olarak girilseydi iş günü hesabı onu iki kez düşerdi.
create unique index if not exists ux_resmi_tatil_gun
    on public.resmi_tatil (tarih, coalesce(sube_id, 0));
create index if not exists ix_resmi_tatil_yil
    on public.resmi_tatil (tarih) where aktif = 1;

comment on table public.resmi_tatil is
  '749: resmi tatil takvimi. Milli tatiller fn_resmi_tatil_uret ile '
  'uretilir; DINI bayramlar elle girilir (hicri takvim algoritmayla '
  'uretilmez - bir gun kayan hesap izni ve bordroyu yanlis hesaplar).';

-- ================================================ MİLLÎ TATİL ÜRETİMİ
create or replace function public.fn_resmi_tatil_uret(
    p_yil integer, p_kullanici integer default 0)
returns integer
language plpgsql as $$
declare
    v_eklenen integer := 0;
begin
    insert into public.resmi_tatil (tarih, ad, tur, yarim_gun, aciklama, ekleyen)
    select x.tarih, x.ad, 1, x.yarim, 'Otomatik üretildi (millî tatil)', p_kullanici
      from (values
        (make_date(p_yil,  1,  1), 'Yılbaşı',                              0::smallint),
        (make_date(p_yil,  4, 23), 'Ulusal Egemenlik ve Çocuk Bayramı',    0::smallint),
        (make_date(p_yil,  5,  1), 'Emek ve Dayanışma Günü',               0::smallint),
        (make_date(p_yil,  5, 19), 'Atatürk''ü Anma, Gençlik ve Spor Bayramı', 0::smallint),
        (make_date(p_yil,  7, 15), 'Demokrasi ve Millî Birlik Günü',       0::smallint),
        (make_date(p_yil,  8, 30), 'Zafer Bayramı',                        0::smallint),
        -- 28 EKİM YARIM GÜN: Cumhuriyet Bayramı arifesi 13:00'ten sonra.
        (make_date(p_yil, 10, 28), 'Cumhuriyet Bayramı arifesi',           1::smallint),
        (make_date(p_yil, 10, 29), 'Cumhuriyet Bayramı',                   0::smallint)
      ) as x(tarih, ad, yarim)
     where not exists (select 1 from public.resmi_tatil t
                        where t.tarih = x.tarih and t.sube_id is null);

    get diagnostics v_eklenen = row_count;
    return v_eklenen;
end $$;

comment on function public.fn_resmi_tatil_uret(integer, integer) is
  '749: bir yilin MILLI tatillerini yazar (sabit tarihli). Dini bayramlar '
  'DAHIL DEGILDIR - hicri takvim elle girilir.';

-- =========================================== GÜN SAYISI TATİLİ DÜŞSÜN
-- 743'ün `fn_izin_gun`u yalnız hafta sonunu düşüyordu. Artık resmî tatil
--   de düşülüyor ve YARIM GÜN 0,5 sayılıyor.
--
--   HAFTA SONUNA DENK GELEN TATİL İKİ KEZ DÜŞMEZ: zaten iş günü değil.
create or replace function public.fn_izin_gun(
    p_bas date, p_bit date, p_is_gunu smallint default 0, p_sube integer default null)
returns numeric
language sql stable as $$
    select case
      when p_bas is null or p_bit is null or p_bit < p_bas then 0
      -- TAKVİM GÜNÜ: iki uç dahil, tatil düşülmez. Yıllık izin kanunda
      --   takvim günüdür; kurum iş günü saymak isterse bayrağı açar.
      when coalesce(p_is_gunu, 0) = 0 then (p_bit - p_bas + 1)::numeric
      else (
        select coalesce(sum(
                 case
                   -- Hafta sonu: sayılmaz.
                   when extract(isodow from g) >= 6 then 0
                   -- Tam gün tatil: sayılmaz. Yarım gün: 0,5.
                   when t.yarim_gun = 1 then 0.5
                   when t.tarih is not null then 0
                   else 1
                 end), 0)
          from generate_series(p_bas, p_bit, interval '1 day') g
          left join public.resmi_tatil t
                 on t.tarih = g::date and t.aktif = 1
                and (t.sube_id is null or p_sube is null or t.sube_id = p_sube))
    end $$;

comment on function public.fn_izin_gun(date, date, smallint, integer) is
  '743/749: izin gun sayisi. is_gunu=1 ise hafta sonu VE resmi tatil '
  'dusulur; arife gunu 0,5 sayilir.';

-- ================================================ TATİL LİSTE GÖRÜNÜMÜ
create or replace view public.v_resmi_tatil as
select t.id,
       t.tarih,
       t.ad,
       t.tur,
       t.yarim_gun,
       t.calisma_var,
       t.aciklama,
       t.sube_id,
       coalesce(s.ad, '')                                   as sube_ad,
       t.aktif,
       extract(year from t.tarih)::int                      as yil,
       -- HAFTA SONUNA DENK GELEN TATİL: kurum için "kayıp" değil, ama
       --   planlamada bilinmeli - köprü tatil tartışması buradan çıkar.
       (extract(isodow from t.tarih) >= 6)::int             as hafta_sonu,
       to_char(t.tarih, 'TMDay')                            as gun_adi,
       t.ekleme_tarihi,
       t.degistirme_tarihi
  from public.resmi_tatil t
  left join public.sube s on s.id = t.sube_id;

comment on view public.v_resmi_tatil is
  '749: resmi tatil listesi - gun adi ve hafta sonuna denk gelme bilgisiyle.';

