insert into public.rol_yetki (rol_id, yetki_id, gor, ekle, degistir, sil, ekleyen)
select r.id, y.id, 1, 1, 1, 1, 0
  from public.rol r cross join public.yetki y
 where r.kod = 'yonetici' and y.kod = 'ik.tatil'
   and not exists (select 1 from public.rol_yetki ry
                    where ry.rol_id = r.id and ry.yetki_id = y.id);

-- ============================================= İÇİNDE BULUNULAN YIL
-- Kurulumda boş bir takvim, "iş günü" hesabını 743'teki hâline döndürür.
--   İçinde bulunulan ve gelecek yılın millî tatilleri yazılır; dinî
--   bayramlar ekrandan girilir.
select public.fn_resmi_tatil_uret(extract(year from current_date)::int, 0);
