--  Gentegre AI — e-BELGE SERI KURALLARI
--  156_ebelge_seri.sql
--
--  Kullanici: "e-Belge ayarlarda e-Fatura sekmesi soluna Delphi'deki 'Seri
--  Bilgileri' sekmesini ac ve oradaki gridi kopyala."
--
--  KAYNAK: Delphi `UOpsiyonFatura` > TabSeri gridi. Orada satirlar GENINI'de
--    BOLUM = -24130 (e-Fatura) / -24131 (e-Arsiv) / -24133 (e-Irsaliye),
--    ANAHTAR = seri, DEGER = senaryo, ayrica KULLANICI ve ONCELIK kolonlari
--    ile tutuluyordu. Burada duzgun bir tablo:
--
--      belge_turu + seri + senaryo + kullanici + sira
--
--  NE ISE YARAR: GIB'e giden belgenin SERISI (3 harfli kod, "GEN" gibi).
--    Ayni firma birden fazla seri kullanabilir: kullaniciya gore ("depo
--    kullanicisi DPO serisini kessin"), senaryoya gore (ticari fatura ayri
--    seri) ya da belge turune gore. Birden fazla kural uyarsa SIRA kucuk olan
--    kazanir.
--
--  BU, BELGE NO SABLONU (152) DEGILDIR: sablon bizim IC numaramizi uretir;
--    burasi e-Belge gonderiminde kullanilan GIB serisidir. e-Belge aciksa ic
--    numara zaten "0" kalir (numarayi entegrator verir).
-- ============================================================================
\set ON_ERROR_STOP on

create table if not exists public.ebelge_seri (
    id                   integer generated by default as identity primary key,
    -- 1 e-Fatura · 2 e-Arsiv · 7 e-Irsaliye (Delphi'deki alan eslestirme kodlari).
    belge_turu           smallint     not null,
    seri                 varchar(10)  not null,
    -- 0 = farketmez; 1 Temel · 2 Ticari · 8 Ilac / Tibbi Cihaz.
    senaryo              smallint     not null default 0,
    -- 0 = tum kullanicilar; doluysa yalniz o kullanicinin kestigi belgede.
    kullanici_id         integer      not null default 0,
    -- Birden fazla kural uyarsa KUCUK sira kazanir.
    sira                 smallint     not null default 0,
    durum                smallint     not null default 1,   -- 1 aktif, 0 pasif
    aciklama             varchar(200) not null default '',
    ekleyen              integer      not null default 0,
    ekleme_tarihi        timestamp    not null default now()::timestamp,
    degistiren           integer      not null default 0,
    degistirme_tarihi    timestamp    null
);

comment on table public.ebelge_seri is
  'e-Belge gonderiminde kullanilan GIB seri kurallari (156). Delphi UOpsiyonFatura > Seri Bilgileri gridinin karsiligi.';
comment on column public.ebelge_seri.seri is
  'GIB serisi - genelde 3 harf ("GEN"). Belgenin IC numarasiyla ilgisi yoktur (o 152 sablonundan gelir).';
comment on column public.ebelge_seri.sira is
  'Birden fazla kural uyarsa KUCUK sira once denenir.';

-- Ayni tur/senaryo/kullanici ucin ayni seri iki kez tanimlanmasin.
create unique index if not exists ux_ebelge_seri_kural
    on public.ebelge_seri (belge_turu, senaryo, kullanici_id, seri);
create index if not exists ix_ebelge_seri_tur
    on public.ebelge_seri (belge_turu, durum, sira);

drop trigger if exists tr_ebelge_seri_degistirme on public.ebelge_seri;
create trigger tr_ebelge_seri_degistirme
    before update on public.ebelge_seri
    for each row execute function public.fn_degistirme_tarihi();

-- --------------------------------------------------------- secim listeleri --
-- Kart secim kutulari "id, ad, aktif" bekler (KartDeposu.KodTablosuSecenekleri).
create or replace view public.v_ebelge_turu_lookup as
    select 1 as id, 'e-Fatura'::varchar as ad, 1 as aktif
    union all select 2, 'e-Arşiv', 1
    union all select 7, 'e-İrsaliye', 1;

comment on view public.v_ebelge_turu_lookup is
  'Seri kurallarinda belge turu secimi (156).';

-- Kullanici secimi: ad `taraf.unvan`dan gelir (taraf_kullanici.id = taraf.id).
create or replace view public.v_kullanici_lookup as
    select k.id,
           coalesce(nullif(t.unvan, ''), k.kod)::varchar as ad,
           k.aktif
      from public.taraf_kullanici k
      left join public.taraf t on t.id = k.id;

comment on view public.v_kullanici_lookup is
  'Kullanici secim listesi (id, ad, aktif) - kart kod tablolari icin (156).';

-- --------------------------------------------------------- yururlukteki seri --
-- Kural secimi: once KULLANICIYA ozel, sonra SENARYOYA ozel, sonra genel;
--   esitlikte kucuk sira. Gonderim kodu tek yerden sorsun diye fonksiyon.
create or replace function public.fn_ebelge_seri_bul(
        p_belge_turu integer, p_senaryo integer, p_kullanici_id integer)
returns varchar
language sql stable as $$
    select s.seri
      from public.ebelge_seri s
     where s.belge_turu = p_belge_turu
       and s.durum = 1
       and s.kullanici_id in (coalesce(p_kullanici_id, 0), 0)
       and s.senaryo in (coalesce(p_senaryo, 0), 0)
     order by (s.kullanici_id = coalesce(p_kullanici_id, 0)) desc,
              (s.senaryo = coalesce(p_senaryo, 0)) desc,
              s.sira, s.id
     limit 1
$$;

comment on function public.fn_ebelge_seri_bul(integer, integer, integer) is
  'Belge turu/senaryo/kullanici icin gecerli GIB serisi; kural yoksa NULL (156).';

