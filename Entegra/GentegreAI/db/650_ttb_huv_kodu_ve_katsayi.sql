-- ------------------------------------------------------- hizmet.huv_kodu
--  SUT kodu ile eşleşen hizmete TTB kodu yazılır. Aynı değer zaten
--  yazılıysa satır güncellenmez (degistirme_tarihi kirlenmesin).
update public.hizmet h
   set huv_kodu = v.huv_kod, degistirme_tarihi = now()
  from gecici_ttbhuv v
 where h.kod = v.sut_kod
   and coalesce(h.huv_kodu, '') is distinct from v.huv_kod;

-- ------------------------------------- TTB/HUV listesinin katsayı/çarpanı
--  Liste `tarife_tipi = 2` (TTB/HUV): fiyat = katsayı (taban_fiyat) ×
--  çarpan. Tarife tipi 2 olmayan listeye dokunulmaz - SUT listesinde
--  fiyat SKRS'den gelir ve tetik elle değişimi zaten reddeder.
update public.fiyat_listesi_satir f
   set taban_fiyat = v.katsayi,
       carpan = v.carpan,
       degistirme_tarihi = now()
  from gecici_ttbhuv v
  join public.hizmet h on h.kod = v.sut_kod
 where f.hizmet_id = h.id
   -- `update ... from` hedef tabloyu (f) join kosulunda goremez; liste
   --   tipi alt sorguyla suzulur.
   and exists (select 1 from public.fiyat_listesi l
                where l.id = f.liste_id and l.tarife_tipi = 2)
   and (f.taban_fiyat is distinct from v.katsayi or f.carpan is distinct from v.carpan);

do $kontrol$
declare
    v_huv int; v_fiyat int;
begin
    select count(*) into v_huv from public.hizmet where coalesce(huv_kodu, '') <> '';
    select count(*) into v_fiyat
      from public.fiyat_listesi_satir f
      join public.fiyat_listesi l on l.id = f.liste_id and l.tarife_tipi = 2
     where coalesce(f.taban_fiyat, 0) > 0 and coalesce(f.carpan, 0) > 0;
    raise notice '650 tamam: huv kodu olan hizmet %, katsayi+carpan dolu TTB/HUV satiri %',
        v_huv, v_fiyat;
end $kontrol$;

