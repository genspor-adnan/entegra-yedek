-- =====================================================================
-- 444 - SERUM İNDEKSİ (HIL) KURALI
--
-- Mockuplar: lab_biyokimya_sonuc_onay.html ("Potasyum: hemoliz indeksi 45
-- → yeni numune"), lab_cihaz_entegrasyonu.html ("SI-H > 30 → K, LDH,
-- AST'yi hemoliz bayrağıyla işaretle"), lab_sonuc_formu_biyokimya.html
-- ("Numune kalitesi: Uygun (hemoliz idx 12 · lipemi 8 · ikter 4)").
--
-- NEDEN: hemolizli numunede POTASYUM YALANCI YÜKSEK çıkar - eritrositin
-- içindeki potasyum serumа karışır. Değer "referans dışı" görünür, kural
-- motoru panik bile diyebilir; oysa hasta normaldir. Tersi de olur:
-- lipemi bazı yöntemlerde yalancı DÜŞÜKLÜK yapar ve gerçek bir anormallik
-- normal görünür. İkisi de tedaviyi yanlış yönlendirir.
--
-- KURAL TEST BAZLIDIR: potasyum hemolizden 20 indekste etkilenir, sodyum
-- 200'de bile etkilenmez. Tek bir "numune hemolizli" bayrağı ile bütün
-- paneli reddetmek, çalışılabilir 20 testi de çöpe atmak olurdu.
--
-- SONUÇ SİLİNMEZ: etkilenen test kaydedilir ama OTO-ONAYA GİRMEZ ve
-- raporda uyarısıyla görünür; ret eşiğinde satır "tekrar numune bekliyor"
-- durumuna alınır. Ölçülmüş bir değeri yok saymak, teknisyenin cihazda
-- gördüğü ile sistemin gösterdiğini ayırırdı.
-- =====================================================================

-- ---------------------------------------------------------------------
--  1) İNDEKS EŞİKLERİ
--
--  tetkik_id null = VARSAYILAN (tüm testler için geçerli üst sınır);
--  teste özel satır varsa o kazanır (Westgard kural setiyle aynı desen).
-- ---------------------------------------------------------------------
create table if not exists public.lab_indeks_esik (
    id          integer generated by default as identity primary key,
    tetkik_id   integer references public.lab_tetkik(id) on delete cascade,
    -- 1 hemoliz (H) · 2 lipemi (L) · 3 ikter (I)
    indeks      smallint not null,
    -- Uyarı eşiği: sonuç raporlanır ama oto-onay kapanır ve rapora not düşer.
    uyari_esik  numeric(9,2),
    -- Ret eşiği: sonuç güvenilmez - satır "tekrar numune bekliyor"a alınır.
    ret_esik    numeric(9,2),
    -- 1 yalancı YÜKSEKLİK · 2 yalancı DÜŞÜKLÜK · 3 yön belirsiz
    etki        smallint not null default 3,
    aciklama    varchar(300) not null default '',
    durum       smallint not null default 0,
    ekleyen       integer   not null default 0,
    ekleme_tarihi timestamp not null default now(),
    degistiren    integer   not null default 0,
    degistirme_tarihi timestamp
);

create unique index if not exists ux_lab_indeks_esik
    on public.lab_indeks_esik (coalesce(tetkik_id, 0), indeks);

comment on table public.lab_indeks_esik is
    'Serum indeksi (HIL) esikleri (444): test bazli, tetkik_id null = varsayilan.';

-- ---------------------------------------------------------------------
--  2) CİHAZ İNDEKS KODLARI
--
--  Cihaz indeksleri normal test sonucu gibi gönderir (SI-H, HIL-H, HI…);
--  kod eşleme tablosunda tetkik karşılığı olmadığı için "eşleşmeyen test"
--  sayılıp atılıyorlardı. Bu tablo o kodları numune kalitesine yönlendirir.
-- ---------------------------------------------------------------------
create table if not exists public.lab_indeks_kod (
    id        integer generated by default as identity primary key,
    cihaz_id  integer references public.cihaz(id) on delete cascade,
    kod       varchar(30) not null,
    indeks    smallint not null,          -- 1 H · 2 L · 3 I
    carpan    numeric(19,6) not null default 1,
    durum     smallint not null default 0,
    ekleyen       integer   not null default 0,
    ekleme_tarihi timestamp not null default now(),
    degistiren    integer   not null default 0,
    degistirme_tarihi timestamp
);

create unique index if not exists ux_lab_indeks_kod
    on public.lab_indeks_kod (coalesce(cihaz_id, 0), upper(kod));

-- ---------------------------------------------------------------------
--  3) SONUÇTA İNDEKS İZİ
--
--  Uyarı metni SONUÇLA saklanır: eşik sonradan değişse rapordaki cümle
--  değişmemeli (bayrak ve referansla aynı gerekçe).
-- ---------------------------------------------------------------------
alter table public.lab_sonuc
    add column if not exists indeks_durum smallint not null default 0,  -- 0 yok · 1 uyarı · 2 ret
    add column if not exists indeks_uyari varchar(300) not null default '';

-- ---------------------------------------------------------------------
--  4) ETKİ HESABI
--
--  Numunenin ölçülmüş indeksleriyle testin eşiklerini karşılaştırır.
--  En AĞIR sonuç kazanır (ret > uyarı) ve gerekçe metni üretilir.
-- ---------------------------------------------------------------------
create or replace function public.fn_lab_indeks_etki(p_tetkik_id integer,
                                                     p_numune_id integer)
returns table (durum smallint, uyari text)
language sql stable as $$
    with olculen as (
        select 1::smallint as indeks, n.hemoliz_idx::numeric as deger, 'Hemoliz' as ad
          from public.lab_numune n where n.id = p_numune_id
        union all
        select 2, n.lipemi_idx, 'Lipemi' from public.lab_numune n where n.id = p_numune_id
        union all
        select 3, n.ikter_idx, 'İkter'  from public.lab_numune n where n.id = p_numune_id
    ),
    esik as (
        select o.indeks, o.deger, o.ad,
               -- Teste özel eşik varsa o, yoksa varsayılan satır.
               (select e.uyari_esik from public.lab_indeks_esik e
                 where e.indeks = o.indeks and e.durum = 0
                   and (e.tetkik_id = p_tetkik_id or e.tetkik_id is null)
                 order by e.tetkik_id nulls last limit 1) as uyari_esik,
               (select e.ret_esik from public.lab_indeks_esik e
                 where e.indeks = o.indeks and e.durum = 0
                   and (e.tetkik_id = p_tetkik_id or e.tetkik_id is null)
                 order by e.tetkik_id nulls last limit 1) as ret_esik,
               (select e.etki from public.lab_indeks_esik e
                 where e.indeks = o.indeks and e.durum = 0
                   and (e.tetkik_id = p_tetkik_id or e.tetkik_id is null)
                 order by e.tetkik_id nulls last limit 1) as etki
          from olculen o
         where o.deger is not null
    ),
    karar as (
        select indeks, deger, ad, etki,
               case when ret_esik is not null and deger >= ret_esik then 2
                    when uyari_esik is not null and deger >= uyari_esik then 1
                    else 0 end as d
          from esik
    )
    select coalesce(max(d), 0)::smallint,
           coalesce(string_agg(
               -- Tam sayıda ondalık ayırıcı basılmasın ("45." çirkin ve
               --   raporda yazım hatası gibi duruyor).
               ad || ' indeksi ' || trim(to_char(deger,
                   case when deger = trunc(deger) then 'FM9999990' else 'FM9999990D9' end))
               || case etki when 1 then ' · yalancı yükseklik'
                            when 2 then ' · yalancı düşüklük'
                            else ' · sonucu etkileyebilir' end
               || case d when 2 then ' (RET eşiği - yeni numune gerekir)'
                         else '' end,
               ' · ' order by d desc, indeks) filter (where d > 0), '')
      from karar;
$$;

comment on function public.fn_lab_indeks_etki(integer, integer) is
    'Numunenin HIL indeksleri testin esikleriyle karsilastirilir: '
    '0 etkilenmez · 1 uyari (oto-onay kapanir) · 2 ret (tekrar numune).';

-- ---------------------------------------------------------------------
--  5) VARSAYILAN EŞİKLER
--
--  Ölçek: cihazların yaygın "indeks" birimi (yaklaşık mg/dL serbest
--  hemoglobin, trigliserit, bilirubin karşılığı). Değerler laboratuvarın
--  kendi doğrulamasıyla güncellenir - buradakiler başlangıç.
-- ---------------------------------------------------------------------
insert into public.lab_indeks_esik (tetkik_id, indeks, uyari_esik, ret_esik, etki, aciklama)
select null, v.indeks, v.uyari, v.ret, v.etki, v.acik
  from (values
      (1::smallint, 60::numeric, 150::numeric, 3::smallint,
       'Varsayılan: belirgin hemolizde sonuç yorumla verilir'),
      (2::smallint, 200::numeric, 600::numeric, 3::smallint,
       'Varsayılan: lipemi türbidite ile ölçümü bozar'),
      (3::smallint, 10::numeric, 25::numeric, 3::smallint,
       'Varsayılan: ikter (bilirubin) girişimi')
  ) as v(indeks, uyari, ret, etki, acik)
 where not exists (select 1 from public.lab_indeks_esik e
                    where e.tetkik_id is null and e.indeks = v.indeks);

-- TESTE ÖZEL EŞİKLER: potasyum hemolizden 20 indekste etkilenir, sodyum
--   200'de bile etkilenmez. Hepsini aynı eşikle yönetmek, çalışılabilir
--   testleri de reddetmek olurdu.
insert into public.lab_indeks_esik (tetkik_id, indeks, uyari_esik, ret_esik, etki, aciklama)
select t.id, v.indeks, v.uyari, v.ret, v.etki, v.acik
  from (values
      ('K',   1::smallint,  20::numeric,  40::numeric, 1::smallint,
       'Eritrosit içi potasyum seruma karışır - yalancı yükseklik'),
      ('AST', 1::smallint,  30::numeric,  80::numeric, 1::smallint,
       'Eritrosit içi AST - yalancı yükseklik'),
      ('ALT', 1::smallint,  60::numeric, 150::numeric, 1::smallint,
       'Hemolizden orta düzeyde etkilenir'),
      ('CRP', 2::smallint, 150::numeric, 400::numeric, 3::smallint,
       'Türbidimetrik yöntem lipemiden etkilenir'),
      ('KRE', 3::smallint,  15::numeric,  35::numeric, 2::smallint,
       'Jaffe yönteminde bilirubin girişimi - yalancı düşüklük'),
      -- SODYUM: hemolizden pratikte etkilenmez; varsayılan eşiği ezmek için
      --   yüksek sınır konur, yoksa panelin tamamı uyarı alırdı.
      ('NA',  1::smallint, 400::numeric, 800::numeric, 3::smallint,
       'Hemolizden pratikte etkilenmez - varsayılan eşik geçersiz kılındı')
  ) as v(kod, indeks, uyari, ret, etki, acik)
  join public.lab_tetkik t on upper(t.kod) = v.kod
 where not exists (select 1 from public.lab_indeks_esik e
                    where e.tetkik_id = t.id and e.indeks = v.indeks);

-- Cihazların yaygın indeks kodları (cihaz bağımsız varsayılan).
insert into public.lab_indeks_kod (cihaz_id, kod, indeks)
select null, v.kod, v.indeks
  from (values ('SI-H', 1::smallint), ('SI-L', 2::smallint), ('SI-I', 3::smallint),
               ('HI',   1::smallint), ('LI',   2::smallint), ('II',   3::smallint),
               ('HIL-H', 1::smallint), ('HIL-L', 2::smallint), ('HIL-I', 3::smallint))
         as v(kod, indeks)
 where not exists (select 1 from public.lab_indeks_kod k
                    where k.cihaz_id is null and upper(k.kod) = upper(v.kod));

do $$
begin
    raise notice '444 tamam: lab_indeks_esik / lab_indeks_kod + fn_lab_indeks_etki';
end $$;
