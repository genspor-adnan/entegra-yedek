-- ------------------------------------------------------- sonuç kaydı ----
create table if not exists public.gebelik_sonuc (
  id            integer generated by default as identity primary key,
  gebelik_id    integer not null references public.gebelik(id) on delete cascade,
  taraf_id      integer not null references public.taraf(id),
  belge_id      integer references public.belge(id),
  -- Zorunlu ikili: ne zaman ve nasıl sonuçlandı.
  sonlanma_tarihi timestamptz not null,
  sonuc         smallint     not null,        -- SKRS gebelik sonucu
  dogum_yontemi smallint,
  dogum_yeri    smallint,
  doguma_yardim smallint,
  canli_bebek   smallint,
  olu_bebek     smallint,
  sezaryan_endikasyon smallint,
  endikasyon_neden    smallint,
  aciklama      varchar(400) not null default '',
  durum         smallint     not null default 1,   -- 1 geçerli · 0 iptal
  iptal_neden   varchar(200) not null default '',
  enabiz_durum  smallint     not null default 0,
  sube_id       integer      not null default 0,
  ekleyen       integer      not null default 0,
  ekleme_tarihi timestamptz  not null default now(),
  degistiren    integer      not null default 0,
  degistirme_tarihi timestamptz,
  -- BEBEK SAYISI NEGATİF OLAMAZ; sıfır olabilir (düşük).
  constraint ck_gebelik_sonuc_bebek
    check (coalesce(canli_bebek, 0) >= 0 and coalesce(olu_bebek, 0) >= 0)
);

-- BİR GEBELİĞİN TEK GEÇERLİ SONUCU OLUR.
create unique index if not exists ux_gebelik_sonuc
  on public.gebelik_sonuc (gebelik_id) where durum = 1;

comment on table public.gebelik_sonuc is
  '902: gebelik sonucu (USS 224) - dogum, dusuk ya da tibbi tahliye. Kayit '
  'dosyayi kapatir ve paketi dogurur.';

/**
 * SONUCU KAYDET VE DOSYAYI KAPAT.
 *
 * İki işi ayırmak, kapanmış ama bildirilmemiş (ya da bildirilmiş ama açık
 * kalmış) gebelikler üretirdi. Dosya zaten kapalıysa kayıt yine de açılır -
 * eski bir gebeliğin sonucu sonradan girilebilir.
 */
create or replace function public.fn_gebelik_sonucla(p_gebelik_id integer,
                                                     p_sonuc      smallint,
                                                     p_tarih      timestamptz,
                                                     p_kullanici  integer default 0)
returns integer language plpgsql as $fn$
declare
    v_id    integer;
    v_taraf integer;
    v_sube  integer;
begin
    select taraf_id, sube_id into v_taraf, v_sube
      from public.gebelik where id = p_gebelik_id;
    if v_taraf is null then
        raise exception 'Gebelik dosyası bulunamadı.';
    end if;

    insert into public.gebelik_sonuc
           (gebelik_id, taraf_id, sonlanma_tarihi, sonuc, sube_id, ekleyen)
    values (p_gebelik_id, v_taraf, coalesce(p_tarih, now()), p_sonuc,
            coalesce(v_sube, 0), p_kullanici)
    returning id into v_id;

    update public.gebelik
       set durum = 2, sonuc_tarihi = coalesce(p_tarih, now())::date,
           degistiren = p_kullanici, degistirme_tarihi = now()
     where id = p_gebelik_id and durum = 1;

    return v_id;
end $fn$;

comment on function public.fn_gebelik_sonucla(integer, smallint, timestamptz, integer) is
  '902: gebelik sonucunu yazar ve dosyayi KAPATIR - iki isi ayirmak, kapanmis '
  'ama bildirilmemis gebelikler uretirdi.';

-- -------------------------------------------------------------- döküm ----
create or replace view public.v_gebelik_sonuc as
select s.id, s.gebelik_id, s.taraf_id, s.belge_id,
       coalesce(nullif(trim(h.ad || ' ' || h.soyad), ''), h.unvan) as gebe,
       g.sat, g.gebelik_no,
       public.fn_gebelik_hafta(g.sat, g.beklenen_dogum, s.sonlanma_tarihi::date)
           as sonlanma_haftasi,
       s.sonlanma_tarihi, s.sonuc, s.dogum_yontemi, s.dogum_yeri, s.doguma_yardim,
       s.canli_bebek, s.olu_bebek, s.sezaryan_endikasyon, s.endikasyon_neden,
       s.aciklama, s.durum, s.iptal_neden, s.enabiz_durum, s.sube_id,
       (select count(*) from public.gebe_izlem i
         where i.gebelik_id = g.id and i.durum = 1) as izlem_sayisi
  from public.gebelik_sonuc s
  join public.gebelik g on g.id = s.gebelik_id
  left join public.taraf h on h.id = s.taraf_id;

comment on view public.v_gebelik_sonuc is
  '902: gebelik sonuclari - sonlanma haftasi, dogum bilgileri ve izlem sayisi.';

-- SONUCU GİRİLMEMİŞ KAPALI DOSYALAR: denetimde "kaç gebelik bildirilmedi".
create or replace view public.v_gebelik_sonucsuz as
select g.id as gebelik_id, g.taraf_id,
       coalesce(nullif(trim(h.ad || ' ' || h.soyad), ''), h.unvan) as gebe,
       g.sat, g.sonuc_tarihi, g.sube_id
  from public.gebelik g
  left join public.taraf h on h.id = g.taraf_id
 where g.durum = 2
   and not exists (select 1 from public.gebelik_sonuc s
                    where s.gebelik_id = g.id and s.durum = 1);

comment on view public.v_gebelik_sonucsuz is
  '902: kapanmis ama SONUC KAYDI olmayan gebelikler - 224 paketi bunlar icin '
  'uretilemez.';

