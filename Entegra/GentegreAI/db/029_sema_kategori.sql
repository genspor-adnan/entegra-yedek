--    seviye gerekirse semaya DOKUNMADAN doldurulur.
--
--  ID = eski KATEGORI.ID (taraf.id = REHBER.ID deseniyle AYNI, 003_goc_taraf.sql).
--    stok.kategori kolonu bu degeri donusturulmeden tasidi (011_sema_stok.sql) -
--    ayri bir eski_id kolonuna gerek yok, id'nin kendisi goc izidir.
