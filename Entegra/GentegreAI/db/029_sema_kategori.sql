\set ON_ERROR_STOP on

create table if not exists public.kategori (
    id                integer      generated by default as identity primary key,
    kod               varchar(30)  not null,
    ad                varchar(120) not null,
    ust_id            integer references public.kategori (id),  -- su an hep null (bkz. yukarida)
    aktif             smallint     not null default 1,
    sube_id           integer,
    ekleyen           integer,
    ekleme_tarihi     timestamp    not null default now(),
    degistiren        integer,
    degistirme_tarihi timestamp
);

create index if not exists ix_kategori_ust on public.kategori (ust_id) where ust_id is not null;

comment on table  public.kategori    is 'Stok kategorisi (eski MSSQL KATEGORI). Su an duz liste; ust_id ileride coklu seviye icin hazir.';
comment on column public.kategori.id is 'Eski KATEGORI.ID KORUNUR (taraf.id=REHBER.ID deseni) - stok.kategori dogrudan bu degeri tasir.';

