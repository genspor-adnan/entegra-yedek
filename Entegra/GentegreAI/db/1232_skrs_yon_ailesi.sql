-- =============================================================================
--  1232  SKRS EŞLEME - YÖN AİLESİ
--
--  Kullanıcı 01.11.2026: "evet, yön ailesi eşlemesini yap". Eski yönsüz hizmet ("Diz MR") SUT'ta tek koda değil
--  bir AİLEYE karşılık gelir: "MRG, DİZ - SAĞ, KONTRASTSIZ" / "- SOL, ..." / "- SAĞ, KONTRASTLI" ... Bu hizmeti tek bir
--  yönlü koda bağlamak her hastayı "sağ" faturalar. Yön ailesi kararıyla hizmet banko için TEK kalem kalır (fiyat,
--  kısa ad, eski ad), Bakanlık kodu istemde seçilen YÖN + KONTRAST ile çözülür (Medula, teleradyoloji).
--
--  hizmet_sut_varyant       hizmetin yön / kontrast varyantları -> SUT kodu (kontrastli -1 = kontrast farketmez).
--  hizmet.standart 3        SUT yön ailesi (kod istemde çözülür; hizmet.sut_kodu boş).
--  aktarim_esleme.aile      masanın aile önerisi {kok, seed, varyant:[{kod, ad, yon, kontrastli}]}; durum 4 = yön ailesi.
--  fn_skrs_yon_ailesi       bir SUT kodunun ailesi ("<kök> - SAĞ|SOL|BİLATERAL[, KONTRASTLI|KONTRASTSIZ]" ya da
--                           "<kök> SAĞ|SOL|MUKAYESELİ" grafi biçimi).
--  fn_hizmet_sut_kodu       hizmet + yön + kontrast -> SUT kodu (varyant yoksa hizmet.sut_kodu).
--  fn_belge_satir_sut_kodu  fatura satırının SUT kodu (bağlı radyoloji isteminin yön / kontrastıyla).
--  fn_hizmet_yonleri        hizmetin varyantı olan yönler ('' = sınır yok) - kabul yalnız bunları sunar.
--  fn_hizmet_birlestir      eski hizmeti asıl hizmete birleştirir (1222 gövdesi; SUT ve aile uygulaması ortak).
-- =============================================================================
\set ON_ERROR_STOP on
begin;

create table if not exists public.hizmet_sut_varyant (
    id          integer generated by default as identity primary key,
    hizmet_id   integer     not null references public.hizmet(id) on delete cascade,
    yon         smallint    not null check (yon between 1 and 3),
    kontrastli  smallint    not null default -1 check (kontrastli between -1 and 1),
    sut_kodu    varchar(30) not null,
    unique (hizmet_id, yon, kontrastli)
);
comment on table public.hizmet_sut_varyant is
  '1232: yön ailesi - hizmetin yön (1 sağ 2 sol 3 bilateral) / kontrast (0 yok 1 var -1 farketmez) SUT kodu.';
comment on column public.hizmet.standart is '1222: 0 incelenmedi · 1 SUT (Bakanlık listesi) · 2 kuruma özel · 3 SUT yön ailesi (1232).';

alter table public.aktarim_esleme add column if not exists aile jsonb;
comment on column public.aktarim_esleme.aile is
  '1232: yön ailesi önerisi {kok, seed, varyant:[{kod, ad, yon, kontrastli}]} - durum 4 bu aileyle uygulanır.';

-- ------------------------------------------------------------------- aile ----
create or replace function public.fn_skrs_yon_ailesi(p_kod varchar)
returns table (kok varchar, kod varchar, ad varchar, yon smallint, kontrastli smallint) language sql stable as $$
  with t as (select s.ad, s.tip,
                    (regexp_match(s.ad, '^(.*) - (SAĞ|SOL|BİLATERAL)(, (KONTRASTLI|KONTRASTSIZ))?$'))[1] as kok_a,
                    (regexp_match(s.ad, '^(.*) (SAĞ|SOL|MUKAYESELİ)$'))[1] as kok_b
               from public.skrs_sut s where s.kod = p_kod),
  a as (
    select t.kok_a::varchar as kok, s.kod, s.ad,
           case m[2] when 'SAĞ' then 1 when 'SOL' then 2 else 3 end::smallint as yon,
           case m[4] when 'KONTRASTLI' then 1 when 'KONTRASTSIZ' then 0 else -1 end::smallint as kontrastli
      from t join public.skrs_sut s on s.tip is not distinct from t.tip and s.ad like t.kok_a || ' - %'
      cross join lateral regexp_match(s.ad, '^(.*) - (SAĞ|SOL|BİLATERAL)(, (KONTRASTLI|KONTRASTSIZ))?$') m
     where t.kok_a is not null and coalesce(s.aktif, 1) = 1 and m[1] = t.kok_a
    union all
    select t.kok_b::varchar, s.kod, s.ad,
           case m[2] when 'SAĞ' then 1 when 'SOL' then 2 else 3 end::smallint, (-1)::smallint
      from t join public.skrs_sut s on s.tip is not distinct from t.tip and s.ad like t.kok_b || ' %'
      cross join lateral regexp_match(s.ad, '^(.*) (SAĞ|SOL|MUKAYESELİ)$') m
     where t.kok_a is null and t.kok_b is not null and coalesce(s.aktif, 1) = 1 and m[1] = t.kok_b)
  select distinct on (a.yon, a.kontrastli) a.kok, a.kod, a.ad, a.yon, a.kontrastli
    from a order by a.yon, a.kontrastli, a.kod
$$;

-- Satırın aile önerisi: eski adı yönsüz, hizmetin sabit yönü yok, adaylardan biri en az iki üyeli bir ailenin üyesi ve
--   (BT / MRG / USG eskide) ailenin kökü aynı modaliteyle başlıyor ("Humerus MR" -> "HUMERUS TEK YÖN" grafi ailesi DEĞİL).
create or replace function public.fn_aktarim_esleme_aile(p_id integer) returns jsonb language plpgsql stable as $$
declare e record; a record; v_onek text; v jsonb;
begin
  select x.*, coalesce(h.yon, 0) as h_yon into e
    from public.aktarim_esleme x join public.hizmet h on h.id = x.kayit_id where x.id = p_id and x.liste = 'hizmet';
  if e.id is null or e.tur <> 'RAD' or e.h_yon <> 0
     or upper(e.eski_ad) ~ '(\mSAĞ\M|\mSOL\M|B[İI]LATERAL|İK[İI]\s+TARAF|HER\s+[İI]K[İI]|MUKAYESEL[İI])' then
    return null;
  end if;
  v_onek := case e.modalite when 1 then 'BT' when 2 then 'MRG' when 3 then 'USG' else '' end;
  for a in select x->>'kod' as kod from jsonb_array_elements(e.adaylar) x loop
    select jsonb_build_object('kok', min(f.kok), 'seed', a.kod,
             'varyant', jsonb_agg(jsonb_build_object('kod', f.kod, 'ad', f.ad, 'yon', f.yon, 'kontrastli', f.kontrastli)
                                  order by f.yon, f.kontrastli))
      into v from public.fn_skrs_yon_ailesi(a.kod) f
     having count(*) >= 2 and (v_onek = '' or public.fn_skrs_sade(min(f.kok)) like v_onek || ' %');
    if v is not null then return v; end if;
  end loop;
  return null;
end $$;

-- ---------------------------------------------------------------- çözümleme ----
create or replace function public.fn_hizmet_sut_kodu(p_hizmet integer, p_yon smallint, p_kontrast smallint)
returns varchar language sql stable as $$
  select coalesce(
    (select v.sut_kodu from public.hizmet_sut_varyant v
      where v.hizmet_id = p_hizmet and v.yon = coalesce(p_yon, 0)
        and v.kontrastli in (case when coalesce(p_kontrast, 0) > 0 then 1 else 0 end, -1)
      order by v.kontrastli = -1 limit 1),
    (select nullif(btrim(h.sut_kodu), '') from public.hizmet h where h.id = p_hizmet))
$$;

create or replace function public.fn_belge_satir_sut_kodu(p_satir integer) returns varchar language sql stable as $$
  select coalesce(
    (select public.fn_hizmet_sut_kodu(i.hizmet_id, i.yon, i.kontrast) from public.radyoloji_istem i
      where i.belge_satir_id = p_satir limit 1),
    (select nullif(btrim(h.sut_kodu), '') from public.belge_satir s join public.hizmet h on h.id = s.hizmet_id where s.id = p_satir))
$$;

create or replace function public.fn_hizmet_yonleri(p_hizmet integer) returns varchar language sql stable as $$
  select coalesce(string_agg(distinct v.yon::text, ',' order by v.yon::text), '')::varchar
    from public.hizmet_sut_varyant v where v.hizmet_id = p_hizmet
$$;

-- --------------------------------------------------------------- birleştir ----
create or replace function public.fn_hizmet_birlestir(p_eski integer, p_ana integer, p_sut varchar, p_kullanici integer, p_eski_ad varchar)
returns void language plpgsql as $$
begin
  perform set_config('gentegre.hizmet_birlestir', '1', true);
  update public.belge_satir set hizmet_id = p_ana where hizmet_id = p_eski;
  update public.radyoloji_istem set hizmet_id = p_ana where hizmet_id = p_eski;
  update public.radyoloji_sablon set hizmet_id = p_ana where hizmet_id = p_eski;
  update public.randevu set hizmet_id = p_ana where hizmet_id = p_eski;
  delete from public.fiyat_listesi_satir f where f.hizmet_id = p_eski
     and exists (select 1 from public.fiyat_listesi_satir g where g.liste_id = f.liste_id and g.hizmet_id = p_ana);
  update public.fiyat_listesi_satir set hizmet_id = p_ana where hizmet_id = p_eski;
  delete from public.radyoloji_sablon_hizmet x where x.hizmet_id = p_eski
     and exists (select 1 from public.radyoloji_sablon_hizmet y where y.sablon_id = x.sablon_id and y.hizmet_id = p_ana);
  update public.radyoloji_sablon_hizmet set hizmet_id = p_ana where hizmet_id = p_eski;
  update public.hizmet set durum = 0, standart = (select h.standart from public.hizmet h where h.id = p_ana),
         sut_kodu = nullif(p_sut, ''),
         aciklama = left('Birleşti -> ' || coalesce(nullif(p_sut, ''), 'yön ailesi') || ' (#' || p_ana || '). ' || coalesce(aciklama, ''), 500),
         degistiren = p_kullanici, degistirme_tarihi = now() where id = p_eski;
  -- 1228: asıl hizmetin kısa adı boşsa birleşen eski adı alır (banko eski adla arar).
  update public.hizmet set kisa_ad = left(btrim(p_eski_ad), 60)
   where id = p_ana and coalesce(btrim(kisa_ad), '') = '' and coalesce(btrim(p_eski_ad), '') <> '';
end $$;

-- ------------------------------------------------------------------- doldur ----
-- 1222 gövdesi + aile önerisi (uygulanmamış her satır için tazelenir).
create or replace function public.fn_aktarim_esleme_doldur() returns integer language plpgsql as $$
declare v_n integer;
begin
  insert into public.aktarim_esleme (liste, kayit_id, eski_kod, eski_ad, tur, modalite, kullanim, adaylar, durum)
  select 'hizmet', h.id, h.kod, h.ad,
         case when h.radyoloji = 1 or coalesce(h.modalite, 0) > 0 then 'RAD'
              when h.aciklama like 'Eski HBYS: LAB%' then 'LAB' else 'DIGER' end,
         nullif(h.modalite, 0),
         (select count(*) from public.belge_satir s where s.hizmet_id = h.id), '[]'::jsonb, 0
    from public.hizmet h
   where h.aktarim_kaynak = 2 and h.standart = 0
  on conflict (liste, kayit_id) do update set kullanim = excluded.kullanim
   where public.aktarim_esleme.uygulandi = 0;

  update public.aktarim_esleme e
     set adaylar = coalesce((select jsonb_agg(jsonb_build_object('kod', a.kod, 'ad', a.ad, 'puan', a.puan, 'dikkat', a.dikkat)
                                              order by a.puan desc)
                               from public.fn_skrs_hizmet_adaylari(e.eski_ad, e.tur, e.modalite, 3) a), '[]'::jsonb)
   where e.liste = 'hizmet' and e.uygulandi = 0 and e.durum in (0, 3);
  update public.aktarim_esleme set durum = case when jsonb_array_length(adaylar) = 0 then 3 else 0 end
   where liste = 'hizmet' and uygulandi = 0 and durum in (0, 3);
  update public.aktarim_esleme e set aile = public.fn_aktarim_esleme_aile(e.id)
   where e.liste = 'hizmet' and e.uygulandi = 0;
  select count(*) into v_n from public.aktarim_esleme where liste = 'hizmet';
  return v_n;
end $$;

-- ------------------------------------------------------------------- uygula ----
-- 1228 gövdesi; birleşme fn_hizmet_birlestir'de; durum 4 = yön ailesi. Dönen: {sut, birlesen, ozel, aile}.
create or replace function public.fn_aktarim_esleme_uygula(p_kullanici integer) returns jsonb language plpgsql as $$
declare
  r record; v_ana integer; v_sut int := 0; v_bir int := 0; v_ozel int := 0; v_aile int := 0; v_ad varchar; v_kok varchar;
begin
  perform set_config('gentegre.hizmet_birlestir', '1', true);
  for r in select e.*, h.kod as h_kod, h.ad as h_ad from public.aktarim_esleme e join public.hizmet h on h.id = e.kayit_id
            where e.liste = 'hizmet' and e.uygulandi = 0 and e.durum in (1, 2, 4) order by e.kullanim desc, e.id
  loop
    v_ana := null;
    if r.durum = 2 then
      update public.hizmet set standart = 2, degistiren = p_kullanici, degistirme_tarihi = now() where id = r.kayit_id;
      insert into public.hizmet_eski_kod (hizmet_id, eski_kod, eski_ad, kaynak)
      values (r.kayit_id, r.eski_kod, r.eski_ad, 'Eski HBYS') on conflict do nothing;
      v_ozel := v_ozel + 1; v_ana := r.kayit_id;
    elsif r.durum = 4 then
      -- YÖN AİLESİ: hizmet tek kalem kalır, Bakanlık kodu istemin yön / kontrastından (hizmet_sut_varyant).
      select min(f.kok) into v_kok from public.fn_skrs_yon_ailesi(r.secilen_kod) f;
      if v_kok is null then raise exception 'SUT yön ailesi bulunamadı: %', r.secilen_kod; end if;
      select h.id into v_ana from public.hizmet h
       where h.standart = 3 and h.id <> r.kayit_id and coalesce(h.durum, 1) = 1
         and exists (select 1 from public.hizmet_sut_varyant v where v.hizmet_id = h.id
                        and v.sut_kodu in (select f.kod from public.fn_skrs_yon_ailesi(r.secilen_kod) f))
       order by h.id limit 1;
      if v_ana is null then
        update public.hizmet set ad = left(v_kok, 200),
               kisa_ad = coalesce(nullif(btrim(kisa_ad), ''), left(btrim(r.eski_ad), 60)),
               sut_kodu = null, standart = 3, yon = 0, yon_zorunlu = 1,
               degistiren = p_kullanici, degistirme_tarihi = now() where id = r.kayit_id;
        insert into public.hizmet_sut_varyant (hizmet_id, yon, kontrastli, sut_kodu)
        select r.kayit_id, f.yon, f.kontrastli, f.kod from public.fn_skrs_yon_ailesi(r.secilen_kod) f
        on conflict (hizmet_id, yon, kontrastli) do update set sut_kodu = excluded.sut_kodu;
        v_ana := r.kayit_id; v_aile := v_aile + 1;
      else
        perform public.fn_hizmet_birlestir(r.kayit_id, v_ana, null, p_kullanici, r.eski_ad);
        v_bir := v_bir + 1;
      end if;
      insert into public.hizmet_eski_kod (hizmet_id, eski_kod, eski_ad, kaynak)
      values (v_ana, r.eski_kod, r.eski_ad, 'Eski HBYS') on conflict do nothing;
    else
      select ad into v_ad from public.skrs_sut where kod = r.secilen_kod;
      if v_ad is null then raise exception 'SUT kodu bulunamadı: %', r.secilen_kod; end if;
      select h.id into v_ana from public.hizmet h
       where h.standart = 1 and h.sut_kodu = r.secilen_kod and h.id <> r.kayit_id and coalesce(h.durum, 1) = 1
       order by h.id limit 1;
      if v_ana is null then
        update public.hizmet set kod = r.secilen_kod, ad = left(v_ad, 200),
               kisa_ad = coalesce(nullif(btrim(kisa_ad), ''), left(btrim(r.eski_ad), 60)), sut_kodu = r.secilen_kod, standart = 1,
               degistiren = p_kullanici, degistirme_tarihi = now() where id = r.kayit_id;
        v_ana := r.kayit_id; v_sut := v_sut + 1;
      else
        perform public.fn_hizmet_birlestir(r.kayit_id, v_ana, r.secilen_kod, p_kullanici, r.eski_ad);
        v_bir := v_bir + 1;
      end if;
      insert into public.hizmet_eski_kod (hizmet_id, eski_kod, eski_ad, kaynak)
      values (v_ana, r.eski_kod, r.eski_ad, 'Eski HBYS') on conflict do nothing;
    end if;
    update public.aktarim_esleme set uygulandi = 1, uygulama_tarihi = now(), hedef_hizmet_id = v_ana where id = r.id;
  end loop;
  return jsonb_build_object('sut', v_sut, 'birlesen', v_bir, 'ozel', v_ozel, 'aile', v_aile);
end $$;

-- Mevcut masa satırlarına aile önerisi.
update public.aktarim_esleme e set aile = public.fn_aktarim_esleme_aile(e.id)
 where e.liste = 'hizmet' and e.uygulandi = 0;

commit;
