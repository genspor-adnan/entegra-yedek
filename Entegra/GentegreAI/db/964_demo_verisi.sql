-- ============================================================================
--  Gentegre AI — DEMO VERİSİ (tanıtım kurulumu)
--  964_demo_verisi.sql
--
--  Kullanıcı: "hastane olarak tanıtım için neler yapılabilir?" → "demo tohum
--  için mockup yap" → "mockup uygun, uygula" (Ekranlar/Ayarlar/demo_tohum.html).
--
--  1. referans `kurulum.demo` (0): 1 olan kurulum DEMO'dur. EKRANDAN AÇILMAZ -
--     yalnız sunucuda SQL ile (canlı kurulum yanlışlıkla demo yapılıp
--     verisi silinmesin). Demo kurulumda bildirim işçisi dış gönderim yapmaz.
--  2. referans `demo.ayar` (json): profil, kurum adı, tohum, ölçek, modüller.
--  3. demo_kayit: üreticinin yazdığı HER satır (tablo + id). Temizlik yalnız
--     buradakilere ve demo kişilere bağlı ziyaretçi kayıtlarına dokunur.
--  4. demo_uretim: çalıştırma geçmişi (adım, özet, hata) - ekran ilerlemeyi
--     buradan okur.
--  5. zamanli_is `demo.yenile` (pasif, 03:00): gece temizle + aynı tohumla üret.
--  Yalnız dev docker.
-- ============================================================================

insert into public.referans (anahtar, deger, aciklama)
select 'kurulum.demo', '0', 'DEMO kurulum (1): tanıtım verisi üretilebilir, dış gönderim (SMS / e-posta) yapılmaz. Ekrandan değiştirilmez.'
 where not exists (select 1 from public.referans where anahtar = 'kurulum.demo');

insert into public.referans (anahtar, deger, aciklama)
select 'demo.ayar',
       '{"profil":"hastane","kurumAdi":"Örnek Şehir Hastanesi","sehir":"İstanbul / Kadıköy","tohum":2611,"olcek":"orta","moduller":["yapi","personel","hasta","randevu","ik","kullanici"]}',
       'Demo verisi üretim ayarı (Yönetim › Demo Verisi)'
 where not exists (select 1 from public.referans where anahtar = 'demo.ayar');

create table if not exists public.demo_kayit (
    id        bigint generated by default as identity primary key,
    tablo     varchar(60) not null,
    kayit_id  bigint not null,
    uretim_id integer,
    ekleme_tarihi timestamptz not null default now()
);
create index if not exists ix_demo_kayit_tablo on public.demo_kayit (tablo, kayit_id);

create table if not exists public.demo_uretim (
    id          integer generated by default as identity primary key,
    tetik       varchar(10) not null default 'elle',   -- elle | gece
    baslangic   timestamptz not null default now(),
    bitis       timestamptz,
    durum       smallint not null default 0,           -- 0 çalışıyor · 1 tamam · 2 hata
    adim        varchar(120) not null default '',
    ozet        jsonb not null default '{}'::jsonb,
    hata        varchar(1000),
    tohum       integer,
    ekleyen     integer
);

insert into public.zamanli_is (kod, ad, aktif, periyot, gun, saat, dakika, aciklama)
select 'demo.yenile', 'Demo verisini yenile', 0, 2, 1, 3, 0,
       'Yalnız DEMO kurulumda: demo verisini temizler, aynı tohumla yeniden üretir (ziyaretçi kayıtları da gider).'
 where not exists (select 1 from public.zamanli_is where kod = 'demo.yenile');
