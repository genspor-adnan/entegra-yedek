-- ------------------------------------------------- taslak kolonlarin tasinmasi
-- Eski `muayene` bir TASLAKTI (kullanici: "daha once az muayene yapilmisti,
--   onu iptal edebilirsin"). Serbest metin alanlari yapisal karsiliklarina
--   TASINIR, sonra dusurulur - ayni bilgiyi iki kolonda tutmak, hangisinin
--   dogru oldugunu bilmemek demektir.
update public.muayene
   set hikaye     = case when hikaye = '' then oyku else hikaye end,
       bulgu_ozet = case when bulgu_ozet = '' then bulgu else bulgu_ozet end,
       karar      = case when karar = '' then btrim(tedavi || E'\n' || oneri, E'\n')
                         else karar end
 where oyku <> '' or bulgu <> '' or tedavi <> '' or oneri <> '';

-- Virgullu ICD metni -> tani satirlari (ilki ANA tani).
insert into public.tani (muayene_id, icd_kod, tur, sira, not_metni)
select m.id, btrim(k.kod), case when k.sira = 1 then 1 else 2 end, k.sira::smallint,
       case when k.sira = 1 then m.tani else '' end
  from public.muayene m
 cross join lateral unnest(string_to_array(m.tani_kodlari, ',')) with ordinality as k(kod, sira)
 where btrim(k.kod) <> ''
   and not exists (select 1 from public.tani t where t.muayene_id = m.id);

alter table public.muayene
    drop column if exists oyku,
    drop column if exists bulgu,
    drop column if exists tedavi,
    drop column if exists oneri,
    drop column if exists tani_kodlari,
    drop column if exists tani;

-- ICD secici (kart alani + arama ekrani) icin lookup.
create or replace view public.v_icd_lookup as
    select i.kod as id, i.kod || ' - ' || i.ad as ad, i.aktif
      from public.icd i;

-- Sablon ve sablon alani secicileri (kart alanlari).
create or replace view public.v_muayene_sablon_lookup as
    select s.id, s.ad, s.durum as aktif from public.muayene_sablon s;

create or replace view public.v_muayene_sablon_alan_lookup as
    select a.id, coalesce(nullif(a.grup, '') || ' - ', '') || a.ad as ad, 1::smallint as aktif
      from public.muayene_sablon_alan a;
