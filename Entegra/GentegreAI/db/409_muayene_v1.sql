create table if not exists public.muayene_istem (
    id            integer primary key generated by default as identity,
    muayene_id    integer not null references public.muayene(id) on delete cascade,
    -- 1 lab · 2 goruntuleme · 3 konsultasyon · 4 islem · 5 dis tetkik
    tur           smallint not null default 1,
    hedef_tablo   varchar(40) not null default '',
    hedef_id      integer,
    aciliyet      smallint not null default 0,
    panel_id      integer,
    istem_zamani  timestamp not null default now(),
    -- 0 bekliyor · 1 kismi · 2 tamam · 3 iptal
    sonuc_durum   smallint not null default 0,
    sonuc_zamani  timestamp,
    -- Hekim sonucu GORDU mu: panik deger teyidi ve "sonuc bekliyor" rozeti
    --   bunun uzerinden yurur.
    hekim_gordu   timestamp,
    ekleyen       integer not null default 0,
    ekleme_tarihi timestamp not null default now(),
    degistiren    integer not null default 0,
    degistirme_tarihi timestamp
);
create index if not exists ix_muayene_istem_muayene
    on public.muayene_istem(muayene_id, tur);
create index if not exists ix_muayene_istem_bekleyen
    on public.muayene_istem(sonuc_durum, istem_zamani) where sonuc_durum in (0, 1);

