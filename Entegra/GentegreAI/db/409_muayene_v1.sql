create table if not exists public.muayene_sablon_alan (
    id            integer primary key generated by default as identity,
    sablon_id     integer not null references public.muayene_sablon(id) on delete cascade,
    -- Sistem/grup basligi ("Solunum Sistemi") - raporda basliklar buradan.
    grup          varchar(60) not null default '',
    kod           varchar(30) not null,
    ad            varchar(120) not null,
    -- 1 metin · 2 sayi · 3 secenek · 4 mantik · 5 vucut semasi
    tip           smallint not null default 1,
    secenekler    jsonb,
    birim         varchar(20) not null default '',
    -- "Normal" isaretlenince rapora yazilacak hazir cumle: hekim her normal
    --   bulgu icin ayni metni yazmasin.
    normal_metni  varchar(200) not null default '',
