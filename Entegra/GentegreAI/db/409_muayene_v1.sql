    zorunlu       smallint not null default 0,
    sira          smallint not null default 0,
    constraint ux_muayene_sablon_alan unique (sablon_id, kod)
);

create table if not exists public.muayene_bulgu (
    id             bigint primary key generated by default as identity,
    muayene_id     integer not null references public.muayene(id) on delete cascade,
    sablon_alan_id integer not null references public.muayene_sablon_alan(id),
    normal         smallint not null default 0,
