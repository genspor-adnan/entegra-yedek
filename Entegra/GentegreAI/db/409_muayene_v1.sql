--  409 - MUAYENE v1 (Faz 1 · HBYS)
--
--  Kaynak: Ekranlar/Muayene/muayene_sureci.html (tasarim notu 03.09.2026).
--
--  Mevcut `muayene` tablosu bir TASLAKTI: serbest metin sikayet/oyku/bulgu ve
--  virgullu ICD metni. Muayene v1 dort yerde yapisallastirir:
--
--    * VITAL olcum ayri tabloda (muayene_vital) - bir muayenede birden cok
--      olcum olur (hemsire girisi, cihazdan gelen, hekimin tekrari) ve USS
--      "son olcum"u ister; tek satirda tutmak olcum tarihcesini yok ederdi.
--    * TANI ayri tabloda - ana/ek/on tani ayrimi, kronik isareti ve ICD
--      kataloguna bag gerekiyor. `tani_kodlari` metni ne dogrulanabiliyor ne
--      de "kronik tanilarim" sorusuna cevap verebiliyordu.
--    * FIZIK MUAYENE sablonla - brans sablonu alan alan tanimlanir
--      (muayene_sablon_alan), degerler muayene_bulgu'ya duser. Serbest metin
--      hekime hizli gelir ama "normal" isaretinden rapor uretilemez ve
--      alan bazli karsilastirma (onceki muayene) yapilamaz.
--    * ISTEM birlesik gorunum (muayene_istem) - asil kayit modul tablosunda
--      (lab_istem, radyoloji_istem, belge_satir) kalir; burasi "Istem &
--      Sonuclar" sekmesinin ve "sonuc geldi" bildiriminin tek adresi.
--
--  Recete, rapor ve konsultasyon SONRAKI adimlar (ayni fazda) - bu goc
--  onlarin bag kolonlarini ACMAZ, tablolari gelince eklenir.
-- ============================================================================

-- ------------------------------------------------------------- muayene ------
