    add column if not exists sevk_tesis_kodu    varchar(20) not null default '',
    add column if not exists sevk_klinik_kod    varchar(20) not null default '',
    add column if not exists sevk_neden         smallint    not null default 0,
    add column if not exists vaka_turu          smallint    not null default 0,
    add column if not exists kontrol_onerisi_gun smallint   not null default 0,
    add column if not exists kontrol_randevu_id integer,
    add column if not exists randevu_id         integer,
    -- Konsultasyon yaniti AYRI muayenedir (tur=3) ve isteyene baglanir.
    add column if not exists ust_muayene_id     integer,
    add column if not exists ai_ozet            text        not null default '',
