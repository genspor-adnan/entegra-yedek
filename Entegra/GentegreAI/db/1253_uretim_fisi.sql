-- Operasyon süresi ve tutarı TETİKTE (429 zaman kaydıyla aynı gerekçe): süre boşsa bitiş - başlama -
--   mola; ücret boşsa iş merkezinin ücreti; tutar = süre × ücret.
create or replace function public.fn_uretim_fisi_operasyon_hesapla()
returns trigger language plpgsql as $$
declare v_ucret numeric;
begin
    if coalesce(new.sure_saat, 0) = 0 and new.bas is not null and new.bit is not null then
        new.sure_saat := round(greatest(0, extract(epoch from (new.bit - new.bas))::numeric / 3600
                                           - coalesce(new.mola_dk, 0) / 60), 3);
    end if;
    if coalesce(new.saat_ucreti, 0) = 0 and new.is_merkezi_id is not null then
        select coalesce(im.saat_ucreti, 0) into v_ucret from public.is_merkezi im where im.id = new.is_merkezi_id;
        new.saat_ucreti := coalesce(v_ucret, 0);
    end if;
    new.tutar := round(coalesce(new.sure_saat, 0) * coalesce(new.saat_ucreti, 0), 4);
    return new;
end $$;
drop trigger if exists trg_uretim_fisi_operasyon_hesapla on public.uretim_fisi_operasyon;
create trigger trg_uretim_fisi_operasyon_hesapla
    before insert or update on public.uretim_fisi_operasyon
    for each row execute function public.fn_uretim_fisi_operasyon_hesapla();

-- Fiş numarası merkezi sayaçtan: UF-2026/000001 (emirle aynı desen, fn_uretim_emri_no).
create or replace function public.fn_uretim_fisi_no(p_sube_id integer default 0, p_tarih date default null)
returns text language plpgsql as $$
declare
    v_tarih date := coalesce(p_tarih, current_date);
    v_yil   text := to_char(v_tarih, 'YYYY');
begin
    return 'UF-' || v_yil || '/' ||
           public.fn_numara_sirada(
               'uretim_fisi.no|SUBE' || coalesce(p_sube_id, 0)::text || '|Y' || v_yil,
               'uretim_fisi', 'no',
               'sube ' || coalesce(p_sube_id, 0)::text || ' / yil ' || v_yil,
               6, 1);
end $$;

-- SON MALİYET (Delphi "Son" kolonu): stoğun en son GİRİŞ hareketinin birim fiyatı. Ortalama için
--   fn_uretim_stok_maliyeti (429). Hiç giriş yoksa alış fiyatı, o da yoksa 0 - uydurma fiyat yok.
create or replace function public.fn_uretim_stok_son_maliyeti(p_stok_id integer)
returns numeric language sql stable as $$
    select coalesce(
      (select case when bs.miktar > 0 then round(bs.tutar / bs.miktar, 4) else null end
         from public.belge_satir bs
         join public.belge b on b.id = bs.belge_id
        where bs.stok_id = p_stok_id and bs.miktar > 0 and b.durum = 0
          and b.tur in (3, 10, 11, 12, 109, 122)
        order by b.belge_tarihi desc, b.id desc, bs.id desc
        limit 1),
      public.fn_uretim_stok_maliyeti(p_stok_id));
$$;

-- EMRİN STOK HAREKETLERİ (429 v_uretim_hareket): emre bağlı fişin belgeleri de (kaynak_tur 61 → fiş.emir_id)
--   emrin "Stok Hareketleri" sekmesinde görünsün; sarf toplamı Malzeme sekmesiyle tutsun.
create or replace view public.v_uretim_hareket as
select b.id,
       case when b.kaynak_tur = 60 then b.kaynak_id else f.emir_id end as emir_id,
       b.tur,
       t.ad                               as tur_adi,
       b.belge_tarihi,
       nullif(btrim(b.belge_seri || ' ' || b.belge_no), '') as belge_no,
       coalesce(gd.ad, cd.ad, '')         as depo_adi,
       (select count(*) from public.belge_satir bs where bs.belge_id = b.id)  as satir_sayisi,
       (select coalesce(sum(bs.miktar), 0) from public.belge_satir bs
         where bs.belge_id = b.id)        as miktar,
       b.genel_toplam                     as tutar,
       b.aciklama
  from public.belge b
  left join public.uretim_fisi f on b.kaynak_tur = 61 and f.id = b.kaynak_id
  left join public.kasa_islem_turu t on t.kod = b.tur
  left join public.depo gd on gd.id = b.giris_depo_id
  left join public.depo cd on cd.id = b.cikis_depo_id
 where b.kaynak_tur = 60 or (b.kaynak_tur = 61 and f.emir_id is not null);

