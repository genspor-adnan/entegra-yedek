-- Üretim fişi kendi kodu (ekran bazlı yetki kuralı): uretim.fis (kart), uretim.fis.liste (liste),
--   uretim.fis.serbest (kalite serbest bırakma / ret - aksiyon). Mevcut "uretim" yetkisi olan roller
--   aynı haklarla alır (1004 / 1129 deseni).
insert into public.yetki (kod, ad, grup, tur, sira, urun_modu, modul)
select v.kod, v.ad, k.grup, v.tur, k.sira + v.art, k.urun_modu, k.modul
  from public.yetki k
  cross join (values ('uretim.fis',         'Üretim Fişi Kartı (Üretim)',             0::smallint, 3),
                     ('uretim.fis.liste',   'Üretim Fişi Listesi',                    0::smallint, 4),
                     ('uretim.fis.serbest', 'Üretim fişi kalite serbest bırakma / ret', 1::smallint, 5))
         as v(kod, ad, tur, art)
 where k.kod = 'uretim'
on conflict (kod) do update set ad = excluded.ad, grup = excluded.grup, aktif = 1;

insert into public.rol_yetki (rol_id, yetki_id, gor, ekle, degistir, sil, deger, kapsam, ekleyen)
select ry.rol_id, yl.id, ry.gor, ry.ekle, ry.degistir, ry.sil, '', ry.kapsam, 0
  from public.yetki yk
  join public.yetki yl on yl.kod in ('uretim.fis', 'uretim.fis.liste', 'uretim.fis.serbest')
  join public.rol_yetki ry on ry.yetki_id = yk.id and ry.gor = 1
 where yk.kod = 'uretim'
on conflict (rol_id, yetki_id) do nothing;

