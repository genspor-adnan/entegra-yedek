--  kullanıcı: "KK girip benden kontör alabilecek müşteri" + "3 değişik plan").
--
--  1) KULLANIM İZİ: ai_kontor_hareket'e özellik (rehber/tani/tetkik/ilac),
--     muayene, süre, başarılı mı, sipariş. Başarısız çağrı 0 tutarla YAZILIR
--     (ücretsiz ama görünür). Eski satırlar açıklamadan sınıflanır.
--  2) KURUM AYARLARI: kullanıcı başına günlük sınır, özellik aç/kapa,
--     otomatik ek paket. Çağrı ücreti SATICININDIR (ekrandan değişmez).
--  3) PLAN / PAKET / ABONELİK / SİPARİŞ. Kart verisi HİÇBİR tabloya girmez:
--     ödeme kuruluşunun formunda alınır, biz yalnız sonucu, işlem
--     referansını ve kartın son 4 hanesini tutarız. Kontör yalnız ödeme
--     kuruluşunun doğrulanmış bildirimiyle (webhook) yüklenir.
--  4) YETKİ: ai.kontor (ekran), ai.kontor_satin_al (aksiyon) - yönetici,
--     başhekim.
--  Fiyatlar ÖRNEK (mockup); satıcı değiştirir.
-- =====================================================================
\set ON_ERROR_STOP on

-- 1) kullanım izi
alter table public.ai_kontor_hareket
  add column if not exists ozellik    varchar(20) not null default '',
  add column if not exists muayene_id integer,
  add column if not exists sure_ms    integer,
  add column if not exists basarili   smallint not null default 1,
  add column if not exists siparis_id bigint;

update public.ai_kontor_hareket
   set ozellik = case
         when aciklama like 'YZ önerisi - tanı%'   then 'tani'
         when aciklama like 'YZ önerisi - tetkik%' then 'tetkik'
         when aciklama like 'YZ önerisi - ilaç%'   then 'ilac'
         when aciklama like 'AI rehber%'           then 'rehber'
         else '' end
 where tur = 2 and ozellik = '';

create index if not exists ix_ai_kontor_hareket_ozellik on public.ai_kontor_hareket (ozellik, tarih desc);

-- 2) kurum ayarları
alter table public.ai_kontor
  add column if not exists kullanici_gunluk_siniri integer  not null default 0,
  add column if not exists oz_rehber               smallint not null default 1,
  add column if not exists oz_tani                 smallint not null default 1,
  add column if not exists oz_tetkik               smallint not null default 1,
  add column if not exists oz_ilac                 smallint not null default 1,
  add column if not exists otomatik_ek_paket       varchar(20) not null default '';

-- 3) plan / paket / abonelik / sipariş
create table if not exists public.ai_plan (
  id            integer generated by default as identity primary key,
  kod           varchar(20) not null unique,
  ad            varchar(60) not null,
  aylik_kontor  integer not null,
  aylik_fiyat   numeric(12,2) not null,
  yillik_fiyat  numeric(12,2) not null,
  devreder      smallint not null default 0,
  one_cikan     smallint not null default 0,
  ozellikler    jsonb not null default '[]'::jsonb,
  sira          smallint not null default 0,
  aktif         smallint not null default 1
);

create table if not exists public.ai_paket (
  id      integer generated by default as identity primary key,
  kod     varchar(20) not null unique,
  kontor  integer not null,
  fiyat   numeric(12,2) not null,
  sira    smallint not null default 0,
  aktif   smallint not null default 1
);

-- Kurumda tek abonelik (ai_kontor gibi tek satır).
create table if not exists public.ai_abonelik (
  id               smallint primary key default 1 check (id = 1),
  plan_id          integer references public.ai_plan(id),
  donem_ay         smallint not null default 1,          -- 1 aylık · 12 yıllık
  donem_baslangic  date,
  sonraki_yenileme date,
  durum            smallint not null default 0,          -- 0 yok · 1 aktif · 2 iptal (dönem sonu biter)
  kart_son4        varchar(4) not null default '',
  kart_marka       varchar(20) not null default '',
  odeme_referans   varchar(120) not null default '',     -- ödeme kuruluşundaki abonelik/kart token REFERANSI
  degistirme_tarihi timestamptz
);
insert into public.ai_abonelik (id) values (1) on conflict (id) do nothing;

create table if not exists public.ai_siparis (
  id              bigint generated by default as identity primary key,
  tur             smallint not null,                     -- 1 plan · 2 ek paket · 3 yenileme
  plan_id         integer references public.ai_plan(id),
  paket_id        integer references public.ai_paket(id),
  donem_ay        smallint not null default 1,
  kontor          integer not null,
  tutar           numeric(12,2) not null,
  kdv             numeric(12,2) not null,
  toplam          numeric(12,2) not null,
  durum           smallint not null default 1,           -- 1 bekliyor · 2 ödendi · 3 reddedildi · 4 iptal
  odeme_saglayici varchar(30) not null default '',
  odeme_referans  varchar(120) not null default '',
  hata            varchar(300) not null default '',
  fatura          jsonb not null default '{}'::jsonb,    -- unvan, vkn, vd, adres, eposta (kart YOK)
  fatura_no       varchar(40) not null default '',
  kullanici_id    integer,
  tarih           timestamptz not null default now(),
  odeme_tarihi    timestamptz
);
create index if not exists ix_ai_siparis_tarih on public.ai_siparis (tarih desc);

insert into public.ai_plan (kod, ad, aylik_kontor, aylik_fiyat, yillik_fiyat, devreder, one_cikan, sira, ozellikler)
values
