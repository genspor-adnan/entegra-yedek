-- 4) yetki
insert into public.yetki (kod, ad, grup, tur, sira, aktif)
select v.kod, v.ad, coalesce((select grup from public.yetki where kod = 'ai'), 'Yapay Zeka'), v.tur, v.sira, 1
  from (values ('ai.kontor', 'YZ Kontör & Kullanım', 0::smallint, 50::smallint),
               ('ai.kontor_satin_al', 'YZ kontör satın al (kredi kartı)', 1::smallint, 51::smallint)) v(kod, ad, tur, sira)
 where not exists (select 1 from public.yetki y where y.kod = v.kod);

insert into public.rol_yetki (rol_id, yetki_id, gor, ekle, degistir, sil, ekleyen)
select r.id, y.id, 1, 1, 1, 1, 0
  from public.rol r
  join public.yetki y on y.kod in ('ai.kontor', 'ai.kontor_satin_al')
 where r.kod in ('yonetici', 'bashekim')
   and not exists (select 1 from public.rol_yetki ry where ry.rol_id = r.id and ry.yetki_id = y.id);

