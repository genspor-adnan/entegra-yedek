--        kullanıcı 10.11.2026: "her şubenin pazarlama / satış temsilcisi aynı doktora temsilci olabilir… aynı işlem
--        farklı şubelerde farklı oranlar", "4'ü de ekle" = temsilci primi)
--
--  1) dis_hekim_temsilci: hekim × şube × temsilci (tarihli). taraf.temsilci VARSAYILAN olarak kalır (şube satırı yoksa).
--     Şube başına tek aktif, tarihleri çakışan satır yazılamaz (tetik, 422). fn_dis_hekim_temsilci(hekim, şube, tarih).
--  2) Başvuruda temsilci otomatik: radyoloji / lab istemine dış hekim yazılınca belgenin satici_id'si boşsa o şubenin
--     temsilcisiyle dolar (kurum adına gelen işte de - temsilci primi plana bağlı). Dolu satici korunur.
--  3) prim.rol 10 "Temsilci": belgenin satici_id'si başvurunun TÜM kalemlerine rol 10 olarak yazılır
--     (belge_satir_rol kaynak 2 - elle girilen korunur; satici değişince eskisi silinir, primler yeniden üretilir).
--     Dış hekime 10 verilemez (361 tetiği zaten yalnız Gönderen'e izin verir). v_prim_rol_lookup listeye alır.
--  4) fn_prim_plan_satiri özgüllüğüne ŞUBE: şubeli plan genel planı ezer.
--  İdempotent.
-- =============================================================================
\set ON_ERROR_STOP on

-- ------------------------------------------------------------------ 1) tablo
create table if not exists public.dis_hekim_temsilci (
    id                 integer generated by default as identity primary key,
    hekim_id           integer     not null references public.taraf (id) on delete cascade,
    sube_id            integer     not null references public.sube (id),
    temsilci_id        integer     not null references public.taraf (id),
    baslangic          date        not null default current_date,
    bitis              date,
    aktif              smallint    not null default 1,
    aciklama           varchar(200) not null default '',
    ekleyen            integer     not null default 0,
    ekleme_tarihi      timestamptz not null default now(),
    degistiren         integer     not null default 0,
    degistirme_tarihi  timestamptz,
    constraint ck_dis_hekim_temsilci_tarih check (bitis is null or bitis >= baslangic)
);
create index if not exists ix_dis_hekim_temsilci_hekim on public.dis_hekim_temsilci (hekim_id, sube_id, aktif);
create index if not exists ix_dis_hekim_temsilci_temsilci on public.dis_hekim_temsilci (temsilci_id, sube_id);
comment on table public.dis_hekim_temsilci is
  '1287: dış doktorun ŞUBE bazlı pazarlama / satış temsilcisi. Şube satırı yoksa taraf.temsilci varsayılandır. '
  'Şube başına tek aktif (tarih çakışması tetikle engellenir). Log tablo 1780.';

create or replace function public.tg_dis_hekim_temsilci_dogrula()
returns trigger language plpgsql as $$
declare
    v_ad text;
begin
    if not exists (select 1 from public.taraf_personel p where p.id = new.hekim_id and coalesce(p.dis_hekim, 0) = 1) then
        raise exception 'Temsilci yalnız dış doktora bağlanır (taraf %).', new.hekim_id using errcode = 'GK422';
    end if;
    if not exists (select 1 from public.taraf t join public.taraf_personel p on p.id = t.id
                    where t.id = new.temsilci_id and t.personel = 1 and coalesce(p.dis_hekim, 0) = 0) then
        raise exception 'Temsilci kurum personeli olmalı (taraf %).', new.temsilci_id using errcode = 'GK422';
    end if;
    if coalesce(new.aktif, 1) = 1 then
        select public.fn_taraf_ad(t.unvan, t.ad, t.soyad)::text into v_ad
          from public.dis_hekim_temsilci d
          join public.taraf t on t.id = d.temsilci_id
         where d.hekim_id = new.hekim_id and d.sube_id = new.sube_id and d.id <> coalesce(new.id, 0)
           and coalesce(d.aktif, 1) = 1
           and d.baslangic <= coalesce(new.bitis, date '9999-12-31')
           and coalesce(d.bitis, date '9999-12-31') >= new.baslangic
         limit 1;
        if v_ad is not null then
            raise exception 'Bu şube için aynı tarihlerde % zaten temsilci; önce onun bitişini yazın.', v_ad
                  using errcode = 'GK422';
        end if;
    end if;
    return new;
end $$;
drop trigger if exists tr_dis_hekim_temsilci_dogrula on public.dis_hekim_temsilci;
create trigger tr_dis_hekim_temsilci_dogrula before insert or update on public.dis_hekim_temsilci
    for each row execute function public.tg_dis_hekim_temsilci_dogrula();

-- ------------------------------------------------------------------ çözümleme
create or replace function public.fn_dis_hekim_temsilci(p_hekim_id integer, p_sube_id integer, p_tarih date default current_date)
returns integer language sql stable as $$
    select coalesce(
        (select d.temsilci_id
           from public.dis_hekim_temsilci d
          where d.hekim_id = p_hekim_id and d.sube_id = p_sube_id and coalesce(d.aktif, 1) = 1
            and d.baslangic <= coalesce(p_tarih, current_date)
            and (d.bitis is null or d.bitis >= coalesce(p_tarih, current_date))
          order by d.baslangic desc limit 1),
        (select nullif(t.temsilci, 0) from public.taraf t where t.id = p_hekim_id));
$$;
comment on function public.fn_dis_hekim_temsilci(integer, integer, date) is
  '1287: hekimin o şubedeki aktif temsilcisi; yoksa taraf.temsilci (varsayılan); o da yoksa null.';

-- ------------------------------------------------------------------ 2) başvuruda satici otomatik
create or replace function public.fn_belge_temsilci_doldur(p_belge_id integer, p_hekim_id integer)
returns integer language plpgsql as $$
declare
    v_temsilci integer;
begin
    if coalesce(p_belge_id, 0) = 0 or coalesce(p_hekim_id, 0) = 0 then return null; end if;
    if not exists (select 1 from public.taraf_personel p where p.id = p_hekim_id and coalesce(p.dis_hekim, 0) = 1) then
        return null;
    end if;
    select public.fn_dis_hekim_temsilci(p_hekim_id, b.sube_id, b.belge_tarihi::date) into v_temsilci
      from public.belge b where b.id = p_belge_id and coalesce(b.satici_id, 0) = 0;
    if v_temsilci is null then return null; end if;
    update public.belge set satici_id = v_temsilci where id = p_belge_id and coalesce(satici_id, 0) = 0;
    return v_temsilci;
end $$;
comment on function public.fn_belge_temsilci_doldur(integer, integer) is
  '1287: dış hekimin şube temsilcisini belgenin satici_id''sine yazar (yalnız boşsa). Kurum adına gelen işte de yazılır.';

create or replace function public.tg_rad_istem_temsilci()
returns trigger language plpgsql as $$
declare v_belge integer;
begin
    if new.istek_hekim_id is null or new.belge_satir_id is null then return null; end if;
    select s.belge_id into v_belge from public.belge_satir s where s.id = new.belge_satir_id;
    perform public.fn_belge_temsilci_doldur(v_belge, new.istek_hekim_id);
    return null;
end $$;
drop trigger if exists tr_rad_istem_temsilci on public.radyoloji_istem;
create trigger tr_rad_istem_temsilci
    after insert or update of istek_hekim_id, belge_satir_id on public.radyoloji_istem
    for each row execute function public.tg_rad_istem_temsilci();

