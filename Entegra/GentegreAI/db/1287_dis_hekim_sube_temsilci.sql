create or replace view public.v_prim_rol_lookup as
with roller(id, ad, sira) as (
    values (1::smallint, 'Gönderen'::varchar, 1), (2, 'İsteyen', 2),
           (3, 'Uygulayan', 3), (4, 'Yapan', 4), (5, 'Raporlayan', 5),
           (6, 'Onaylayan', 6), (7, 'Anestezi', 7), (8, 'Asistan', 8),
           (9, 'Teknisyen', 9), (10, 'Temsilci', 10)
)
select r.id,
       (r.ad || case when public.fn_prim_rol_aday_sayisi(r.id::smallint) = 0
                     then ' — aktif kişi işaretlenmemiş'
                     else ' (' || public.fn_prim_rol_aday_sayisi(r.id::smallint)::text
                          || ' kişi)'
                end)::varchar as ad,
       1::smallint as aktif,
       (case when r.id::smallint = public.fn_basvuru_hekim_rolu(0) then 0 else 1 end) * 100
         + case when public.fn_prim_rol_aday_sayisi(r.id::smallint) > 0 then 0 else 50 end
         + r.sira as sira
  from roller r;

-- Temsilci rolü: belgenin satici_id'si başvurunun / belgenin TÜM kalemlerine rol 10 (otomatik, kaynak 2).
create or replace function public.fn_temsilci_rolu_tazele(p_belge_id integer)
returns integer language plpgsql as $$
declare
    v_satici integer;
    v_sayac  integer := 0;
    r        record;
begin
    if coalesce(p_belge_id, 0) = 0 then return 0; end if;
    select nullif(b.satici_id, 0) into v_satici from public.belge b where b.id = p_belge_id;
    -- Satıcı personel değilse (ya da yoksa) rol yazılmaz; eski otomatik satırlar temizlenir.
    if v_satici is not null and not exists (select 1 from public.taraf t join public.taraf_personel p on p.id = t.id
                                             where t.id = v_satici and t.personel = 1 and coalesce(p.dis_hekim, 0) = 0) then
        v_satici := null;
    end if;

    delete from public.belge_satir_rol bsr
     using public.belge_satir s
     where s.id = bsr.belge_satir_id and s.belge_id = p_belge_id
       and bsr.rol = 10 and bsr.kaynak = 2
       and (v_satici is null or bsr.taraf_id <> v_satici);

    if v_satici is not null then
        insert into public.belge_satir_rol (belge_satir_id, rol, taraf_id, pay_yuzde, kaynak)
        select s.id, 10, v_satici, 100, 2
          from public.belge_satir s
         where s.belge_id = p_belge_id
           and not exists (select 1 from public.belge_satir_rol e
                            where e.belge_satir_id = s.id and e.rol = 10 and e.kaynak = 1)
        on conflict (belge_satir_id, rol, taraf_id) do nothing;
        get diagnostics v_sayac = row_count;
    end if;

    -- Rol değişti: kalemlerin AÇIK primleri yeniden üretilir (326 deseni).
    for r in select s.id from public.belge_satir s where s.belge_id = p_belge_id loop
        perform public.fn_prim_uret_belge(r.id);
    end loop;
    for r in select d.id from public.kasa_islem_dagitim d
              join public.belge_satir s on s.id = d.belge_satir_id where s.belge_id = p_belge_id loop
        perform public.fn_prim_uret(r.id);
    end loop;
    return v_sayac;
end $$;
comment on function public.fn_temsilci_rolu_tazele(integer) is
  '1287: belge.satici_id -> kalemlere prim rolü 10 Temsilci (kaynak 2); elle girilen (kaynak 1) korunur.';

-- Yeni kalem: YALNIZ o kalem (belge başına döngü yok - aktarım / toplu kayıt tüm belgeyi yeniden üretmesin).
create or replace function public.tg_temsilci_rolu_satir()
returns trigger language plpgsql as $$
declare v_satici integer;
begin
    select nullif(b.satici_id, 0) into v_satici from public.belge b where b.id = new.belge_id;
    if v_satici is null then return null; end if;
    if not exists (select 1 from public.taraf t join public.taraf_personel p on p.id = t.id
                    where t.id = v_satici and t.personel = 1 and coalesce(p.dis_hekim, 0) = 0) then
        return null;
    end if;
    insert into public.belge_satir_rol (belge_satir_id, rol, taraf_id, pay_yuzde, kaynak)
    values (new.id, 10, v_satici, 100, 2)
    on conflict (belge_satir_id, rol, taraf_id) do nothing;
    -- Prim tetiği (tr_prim_donusum) alfabetik olarak bundan ÖNCE koştu: bu kalemin primi yeniden üretilir.
    perform public.fn_prim_uret_belge(new.id);
    return null;
end $$;
drop trigger if exists tr_temsilci_rolu_satir on public.belge_satir;
create trigger tr_temsilci_rolu_satir
    after insert on public.belge_satir
    for each row execute function public.tg_temsilci_rolu_satir();

create or replace function public.tg_temsilci_rolu_belge()
returns trigger language plpgsql as $$
begin
    if coalesce(new.satici_id, 0) is distinct from coalesce(old.satici_id, 0) then
        perform public.fn_temsilci_rolu_tazele(new.id);
    end if;
    return null;
end $$;
drop trigger if exists tr_temsilci_rolu_belge on public.belge;
create trigger tr_temsilci_rolu_belge
    after update of satici_id on public.belge
    for each row execute function public.tg_temsilci_rolu_belge();

-- ------------------------------------------------------------------ 4) plan seçiminde şube özgüllüğü
create or replace function public.fn_prim_plan_satiri(
    p_rol smallint, p_taraf_id integer, p_hizmet_id integer, p_stok_id integer,
    p_belge_tur smallint, p_pay smallint, p_kurum_id integer, p_sube_id integer,
    p_tarih date, p_tahsilat_turu smallint default 0)
returns table(plan_id integer, satir_id integer, oran_tipi smallint,
              deger numeric, alt_sinir numeric, ust_sinir numeric,
              baz smallint, prim_zamani smallint)
language sql
stable
as $function$
    select p.id, s.id, s.oran_tipi, s.deger, s.alt_sinir, s.ust_sinir, p.baz,
           coalesce(p.prim_zamani, 1)
      from public.prim_plani p
      join public.prim_plani_satir s on s.plan_id = p.id
     where coalesce(p.durum, 1) = 1
       and p.baslangic <= p_tarih
       and (p.bitis is null or p.bitis >= p_tarih)
       and p.rol = p_rol
       and (not exists (select 1 from public.prim_plani_taraf t
                         where t.plan_id = p.id)
            or exists (select 1 from public.prim_plani_taraf t
                        where t.plan_id = p.id and t.taraf_id = p_taraf_id))
       -- ODEYEN TIPI (380): 0 = tumu. Kurumu olmayan basvuru "Özel (Ücretli)".
       and (coalesce(p.odeyen_tipi, 0) = 0
            or p.odeyen_tipi = coalesce((select k.tur from public.taraf_kurum k
                                          where k.id = p_kurum_id), 1))
       and (coalesce(p.odeyen_kurum_id, 0) = 0 or p.odeyen_kurum_id = p_kurum_id)
       and (coalesce(p.sube_id, 0) = 0 or p.sube_id = p_sube_id)
       -- KAPSAM: Liste = tumu · Kategori (ALT AGAC, 558) · Urun
       and (s.tip = 1
            or (s.tip = 2 and (
                   (coalesce(s.kalem_turu, 0) in (0, 2)
                    and s.hedef_id in (select z.id from public.fn_kategori_ust_zinciri(
                            (select h.kategori from public.hizmet h
                              where h.id = p_hizmet_id)) z))
                or (coalesce(s.kalem_turu, 0) in (0, 1)
                    and s.hedef_id in (select z.id from public.fn_kategori_ust_zinciri(
                            (select st.kategori from public.stok st
                              where st.id = p_stok_id)) z))))
            or (s.tip = 3 and (
                   (coalesce(s.kalem_turu, 0) in (0, 2) and s.hedef_id = p_hizmet_id)
                or (coalesce(s.kalem_turu, 0) in (0, 1) and s.hedef_id = p_stok_id))))
       and (s.belge_turleri = ''
            or p_belge_tur is null
            or p_belge_tur::text = any(string_to_array(s.belge_turleri, ',')))
       and (coalesce(s.tahsilat_turu, 0) = 0
            or coalesce(p.prim_zamani, 1) = 2
            or s.tahsilat_turu = p_tahsilat_turu)
       and (s.pay = 0 or s.pay = p_pay)
     order by
       (case s.tip when 3 then 3 when 2 then 1 else 0 end)
       + (case when coalesce(s.kalem_turu, 0) <> 0 then 1 else 0 end)
       + (case when s.belge_turleri <> '' then 1 else 0 end)
       + (case when coalesce(s.tahsilat_turu, 0) <> 0 then 1 else 0 end)
       + (case when s.pay <> 0 then 1 else 0 end)
       + (case when exists (select 1 from public.prim_plani_taraf t
                             where t.plan_id = p.id) then 1 else 0 end)
       -- Tip kisiti da OZGULLUK: "SGK'da %15" plani, tipsiz genel plani ezer.
       + (case when coalesce(p.odeyen_tipi, 0) <> 0 then 1 else 0 end)
       + (case when coalesce(p.odeyen_kurum_id, 0) <> 0 then 1 else 0 end)
       -- ŞUBE (1287): şubeli plan genel planı EZER - eskiden eşit sayılıp önceliğe düşüyordu
       --   ("aynı işlem Koşuyolu %20 / Kadıköy %15" ancak böyle güvenle kurulur).
       + (case when coalesce(p.sube_id, 0) <> 0 then 1 else 0 end) desc,
       -- KATEGORI DERINLIGI (558): kalemin kendi dalina EN YAKIN kapsam once.
       --   Kategori disindaki tiplerde 0 - eski sira degismez.
       (case when s.tip = 2 then
             coalesce((select min(z.derinlik)
                         from public.fn_kategori_ust_zinciri(
                                coalesce((select h.kategori from public.hizmet h
                                           where h.id = p_hizmet_id),
                                         (select st.kategori from public.stok st
                                           where st.id = p_stok_id))) z
                        where z.id = s.hedef_id), 99)
             else 0 end) asc,
       p.oncelik desc, s.sira, s.id
     limit 1;
$function$;

