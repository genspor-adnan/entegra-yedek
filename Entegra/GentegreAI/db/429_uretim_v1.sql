-- ---------------------------------------------------------------------------
--  EMRİN ÜRETTİĞİ BELGELER - sarf / mamul girişi / fire, hepsi kaynak_tur 60
--  ile emre bağlı. Kart bunu SALT OKUNUR sekmede gösterir: belge kendi
--  ekranından düzenlenir, üretim emrinden değil.
-- ---------------------------------------------------------------------------
create or replace view public.v_uretim_hareket as
select b.id,
       b.kaynak_id                        as emir_id,
       b.tur,
       t.ad                               as tur_adi,
       b.belge_tarihi,
       nullif(btrim(b.belge_seri || ' ' || b.belge_no), '') as belge_no,
       coalesce(gd.ad, cd.ad, '')         as depo_adi,
       (select count(*) from public.belge_satir bs where bs.belge_id = b.id)  as satir_sayisi,
       (select coalesce(sum(bs.miktar), 0) from public.belge_satir bs
         where bs.belge_id = b.id)        as miktar,
       b.genel_toplam                     as tutar,
       b.aciklama
  from public.belge b
  left join public.kasa_islem_turu t on t.kod = b.tur
  left join public.depo gd on gd.id = b.giris_depo_id
  left join public.depo cd on cd.id = b.cikis_depo_id
 where b.kaynak_tur = 60;

-- ---------------------------------------------------------------------------
--  ZAMAN KAYDI TÜREVLERİ - süre, ücret, tutar ve emrin işçilik toplamı.
--
--  Hesap TETİKTE, uçta değil: zaman kaydı hem üretim emri kartından hem (Faz 2)
--  terminalden girilecek. İki yazma yolunda aynı formülü tekrarlamak, birinde
--  düzeltilip ötekinde unutulan bir hata demektir.
--
--  Süre elle girilebilir (bas/bit boş olabilir - "3 saat çalıştım"); doluysa
--  ve süre girilmemişse bas/bit farkından hesaplanır.
-- ---------------------------------------------------------------------------
create or replace function public.fn_uretim_zaman_hesapla()
returns trigger language plpgsql as $$
declare
    v_ucret numeric;
begin
    if coalesce(new.sure_saat, 0) = 0 and new.bas is not null and new.bit is not null then
        new.sure_saat := round(extract(epoch from (new.bit - new.bas))::numeric / 3600, 3);
    end if;

    if coalesce(new.saat_ucreti, 0) = 0 then
        select coalesce(nullif(o.saat_ucreti, 0), im.saat_ucreti, 0)
          into v_ucret
          from public.uretim_operasyon o
          left join public.is_merkezi im on im.id = o.is_merkezi_id
         where o.id = new.operasyon_id;
        new.saat_ucreti := coalesce(v_ucret, 0);
    end if;

    new.tutar := round(coalesce(new.sure_saat, 0) * coalesce(new.saat_ucreti, 0), 4);
    return new;
end $$;

drop trigger if exists trg_uretim_zaman_hesapla on public.uretim_zaman;
create trigger trg_uretim_zaman_hesapla
    before insert or update on public.uretim_zaman
    for each row execute function public.fn_uretim_zaman_hesapla();

-- Emrin işçilik toplamı ve operasyonun gerçek süresi zaman kayıtlarından
--   TÜRETİLİR: iki yerde ayrı ayrı tutulup birbirini tutmaması olmasın.
create or replace function public.fn_uretim_zaman_topla()
returns trigger language plpgsql as $$
declare
    v_emir integer := coalesce(new.emir_id, old.emir_id);
    v_opr  integer := coalesce(new.operasyon_id, old.operasyon_id);
begin
    update public.uretim_emri e
       set gercek_iscilik = coalesce((select sum(z.tutar) from public.uretim_zaman z
                                       where z.emir_id = v_emir), 0),
           gercek_toplam  = e.gercek_malzeme
                          + coalesce((select sum(z.tutar) from public.uretim_zaman z
                                       where z.emir_id = v_emir), 0)
     where e.id = v_emir;

    if v_opr is not null then
        update public.uretim_operasyon o
           set gercek_saat = coalesce((select sum(z.sure_saat) from public.uretim_zaman z
                                        where z.operasyon_id = v_opr and z.tur = 1), 0)
         where o.id = v_opr;
    end if;
    return null;
end $$;

drop trigger if exists trg_uretim_zaman_topla on public.uretim_zaman;
create trigger trg_uretim_zaman_topla
    after insert or update or delete on public.uretim_zaman
    for each row execute function public.fn_uretim_zaman_topla();

-- ---------------------------------------------------------------------------
--  ÜRETİM BELGELERİ OTOMATİK FİŞLENMEZ (v1).
--
--  fn_belge_fis_turu_uygun bilmediği her türü fişlenebilir sayıyor; üretim
--  belgeleri carisiz olduğu için "Cari için muhasebe hesabı çözülemedi"
--  hatasıyla SARFI DA GERİ ALIYORDU (aynı transaction).
--
--  Üretimin muhasebe karşılığı cari değil, yarı mamul / mamul / üretim
--  maliyeti hesap çiftidir; o eşleme Muhasebe entegrasyonu adımında gelecek.
--  O gelene kadar üretim belgeleri stok tarafında çalışır, fiş üretmez -
--  transfer ve irsaliyede olduğu gibi.
-- ---------------------------------------------------------------------------
create or replace function public.fn_belge_fis_turu_uygun(p_tur integer)
returns boolean language sql immutable as $$
    -- Fişlenmeyen (mali sonuç faturada doğan) belgeler:
    --   9/19 sipariş · 18 teklif · 105 talep · 10/14 irsaliye ·
    --   109/119 konsinye · 20 transfer · 13/17 tahakkuk · 30 eski başvuru ·
    --   121/122/123 üretim sarf / mamul girişi / fire (429).
    select coalesce(p_tur, 0)
           not in (9, 10, 13, 14, 17, 18, 19, 20, 30, 105, 109, 119,
                   121, 122, 123);
$$;
