create table if not exists public.is_merkezi (
    id                integer primary key generated by default as identity,
    kod               varchar(25)  not null,
    ad                varchar(100) not null,
    sube_id           integer  not null default 0,
    lokasyon          varchar(100) not null default '',
    gunluk_kapasite_saat numeric(9,2) not null default 8,
    saat_ucreti       numeric(19,4) not null default 0,
    -- Fason iş merkezi: operasyon dışarıda yapılır, taraf tedarikçidir.
    fason             smallint not null default 0,
    fason_taraf_id    integer,
    aciklama          varchar(300) not null default '',
    durum             smallint not null default 0,     -- 0 aktif · 1 pasif
    ekleyen           integer  not null default 0,
    ekleme_tarihi     timestamp not null default now(),
    degistiren        integer  not null default 0,
    degistirme_tarihi timestamp
);
create unique index if not exists ux_is_merkezi_kod on public.is_merkezi(kod);

-- ---------------------------------------------------------------------------
--  ÜRÜN AĞACI (BOM / reçete) - mamulün TARİFİ.
--
--  Aynı mamul için birden çok ağaç olabilir: SÜRÜM (v1/v2/v3 - eskisi
--  pasifleşir) ve ALTERNATİF (fason / farklı hammadde). Emir açılırken
--  varsayilan = 1 olan önerilir.
--
--  cikti_miktar: reçete bir PARTİ için yazılabilir (5 Lt cila). Bileşen
--  miktarları o baza göredir; emirde adet / cikti_miktar oranı uygulanır.
-- ---------------------------------------------------------------------------
create table if not exists public.urun_agaci (
    id             integer primary key generated by default as identity,
    kod            varchar(25)  not null,
    ad             varchar(150) not null,
    -- Üretilen mamul stok kartı. Ağaç mamulsüz olamaz: neyin tarifi olduğu
    --   belirsiz kalırsa maliyetin hangi karta yazılacağı da belirsizdir.
    stok_id        integer  not null references public.stok(id),
    -- 1 mamul · 2 yarı mamul · 3 paket/set
    tur            smallint not null default 1,
    cikti_miktar   numeric(18,6) not null default 1,
    birim          smallint not null default 0,
    surum          smallint not null default 1,
    varsayilan     smallint not null default 0,
    alternatif_ad  varchar(100) not null default '',
    gecerli_bas    date,
    gecerli_bit    date,
    sarf_depo_id   integer references public.depo(id),
    mamul_depo_id  integer references public.depo(id),
    fire_depo_id   integer references public.depo(id),
    tavsiye_satis_katsayi numeric(9,4) not null default 0,
    -- Son maliyet hesabının SONUCU - tarihiyle birlikte saklanır ki
    --   "bu fiyat ne zamanki hammadde fiyatıyla çıktı" sorusu cevaplanabilsin.
