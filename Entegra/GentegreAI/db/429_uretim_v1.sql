-- ---------------------------------------------------------------------------
--  İŞ MERKEZİ - operasyonun yapıldığı yer; işçilik saat ücretinin kaynağı.
--  Delphi tarafında ISMERKEZI yalnız bir KOLONDU (serbest metin), tablosu
