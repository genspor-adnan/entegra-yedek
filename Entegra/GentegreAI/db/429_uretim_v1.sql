-- ---------------------------------------------------------------------------
--  EMİR NUMARASI - merkezi sayaç (fn_numara_sirada) kullanılır ki
--  numaralandırma tek yerde kalsın. Ön ek yıllı: UE-2026/000142.
-- ---------------------------------------------------------------------------
create or replace function public.fn_uretim_emri_no(p_sube_id integer default 0,
                                                    p_tarih date default null)
returns text language plpgsql as $$
declare
    v_tarih date := coalesce(p_tarih, current_date);
    v_yil   text := to_char(v_tarih, 'YYYY');
begin
    return 'UE-' || v_yil || '/' ||
           public.fn_numara_sirada(
               'uretim_emri.no|SUBE' || coalesce(p_sube_id, 0)::text || '|Y' || v_yil,
               'uretim_emri', 'no',
               'sube ' || coalesce(p_sube_id, 0)::text || ' / yil ' || v_yil,
               6, 1);
end $$;

-- ---------------------------------------------------------------------------
--  AĞAÇ MALİYETİ - malzeme + işçilik (+ GÜG yüzdesi).
--
--  Malzeme fiyatı: hammadde/sarf/ambalaj için stok kartının ağırlıklı
--  ortalaması; YARI MAMUL için alt ağacın KENDİ hesaplanmış maliyeti - yoksa
--  yarı mamulün stok ortalaması. Alt ağaç önce hesaplanmalı; v1'de kullanıcı
--  sırayı kendi belirler (özyinelemeli patlatma v2).
--
--  Fire dahildir: net gerekli = miktar × (1 + fire%).
-- ---------------------------------------------------------------------------
create or replace function public.fn_urun_agaci_maliyet(p_agac_id integer,
                                                        p_gug_yuzde numeric default 0)
returns table (malzeme numeric, iscilik numeric, gug numeric, toplam numeric)
language plpgsql as $$
declare
    v_cikti   numeric;
    v_malzeme numeric := 0;
    v_iscilik numeric := 0;
    v_gug     numeric := 0;
begin
    select coalesce(nullif(a.cikti_miktar, 0), 1) into v_cikti
      from public.urun_agaci a where a.id = p_agac_id;
    if v_cikti is null then
        return query select 0::numeric, 0::numeric, 0::numeric, 0::numeric;
        return;
    end if;

    select coalesce(sum(
             s.miktar * (1 + s.fire_yuzde / 100) *
             case
               when s.alt_agac_id is not null then
                    coalesce(nullif((select aa.maliyet_toplam
                                       from public.urun_agaci aa
                                      where aa.id = s.alt_agac_id), 0),
                             public.fn_uretim_stok_maliyeti(s.bilesen_stok_id))
               else public.fn_uretim_stok_maliyeti(s.bilesen_stok_id)
             end), 0)
      into v_malzeme
      from public.urun_agaci_satir s
     where s.agac_id = p_agac_id;

    -- İşçilik: (hazırlık + birim süre × çıktı) dakikası, iş merkezi ücretiyle.
    --   Hazırlık PARTİ başınadır, birim süre adet başına.
    select coalesce(sum(
             ((o.hazirlik_dk + o.birim_sure_dk * v_cikti) / 60)
             * coalesce(nullif(o.saat_ucreti, 0), im.saat_ucreti, 0)), 0)
      into v_iscilik
      from public.urun_agaci_operasyon o
      left join public.is_merkezi im on im.id = o.is_merkezi_id
     where o.agac_id = p_agac_id;

    v_malzeme := round(v_malzeme / v_cikti, 4);
    v_iscilik := round(v_iscilik / v_cikti, 4);
    v_gug     := round((v_malzeme + v_iscilik) * coalesce(p_gug_yuzde, 0) / 100, 4);

    return query select v_malzeme, v_iscilik, v_gug, v_malzeme + v_iscilik + v_gug;
end $$;

-- ---------------------------------------------------------------------------
--  BİLEŞEN BİRİM MALİYETİ - ağırlıklı ortalama (giren tutar ÷ giren miktar).
--
--  Ağırlıklı ortalama GİRİŞ hareketlerinden hesaplanır: satış çıkışları
--  ortalamayı bozmamalı (çıkış fiyatı satış fiyatıdır, maliyet değil).
--  Hiç giriş yoksa stok kartının alış fiyatına düşülür; o da yoksa 0 -
--  0 maliyetli bir bileşen ekranda görünür ve düzeltilir, uydurulmuş bir
--  fiyat görünmez.
-- ---------------------------------------------------------------------------
create or replace function public.fn_uretim_stok_maliyeti(p_stok_id integer)
returns numeric language sql stable as $$
    select coalesce(
      (select case when sum(bs.miktar) > 0
                   then round(sum(bs.tutar) / sum(bs.miktar), 4) else null end
         from public.belge_satir bs
         join public.belge b on b.id = bs.belge_id
        where bs.stok_id = p_stok_id
          and bs.miktar > 0
          and b.tur in (3, 10, 11, 12, 109, 122)),
      (select f.fiyat from public.stok_fiyat f
        where f.stok_id = p_stok_id and f.satis = 0 and f.fiyat > 0
        order by f.id limit 1),
      0);
$$;

-- ---------------------------------------------------------------------------
--  MALZEME HAZIRLIK YÜZDESİ - "emri başlatabilir miyim" sorusunun cevabı.
--  Sarf deposundaki kullanılabilir (kalan - başkasının rezervi) ÷ gerekli.
--  Kendi rezervimiz düşülmez: onu zaten biz tuttuk.
-- ---------------------------------------------------------------------------
create or replace function public.fn_uretim_malzeme_hazirlik(p_emir_id integer)
returns numeric language sql stable as $$
    select case when count(*) = 0 then 100
                else round(avg(least(1,
                     case when s.gerekli <= 0 then 1
                          else greatest(0, coalesce(d.kalan, 0)
                                         - greatest(0, coalesce(d.rezerve, 0) - s.rezerve))
                               / s.gerekli
                     end)) * 100, 0)
           end
      from public.uretim_emri_satir s
      join public.uretim_emri e on e.id = s.emir_id
      left join public.stok_durum d
             on d.stok_id = s.bilesen_stok_id
            and d.depo_id = coalesce(s.depo_id, e.sarf_depo_id)
     where s.emir_id = p_emir_id;
$$;

