-- =====================================================================
--  889_lab_tetkik_yetki.sql
--  TEST SEVİYESİNDE YETKİ KISITLAMASI
--  (KTS denetim maddesi L7: "Test seviyesinde yetki kısıtlaması
--   yapılabiliyor mu?")
--
--  BUGÜN: yetki MODÜL seviyesinde - `lab.numune`, `lab.sonuc`, `lab.kultur`,
--  `lab.onay`. Yani `lab.sonuc` yetkisi olan herkes HER tetkikin sonucunu
--  görür. HIV, adli toksikoloji, genetik, evlilik öncesi tarama gibi
--  testlerde bu yetmez: sonucu görmesi gereken kişi ile laboratuvarın
--  tamamını gören kişi aynı değildir.
--
--  MODEL: tetkik × rol × işlem (iste · gör · onayla).
--
--  BEYAZ LİSTE, AMA YALNIZ KISITLANMIŞ TETKİKTE. Bir tetkik için aktif
--  kısıt satırı YOKSA o tetkik herkese açıktır (bugünkü davranış, hiçbir
--  ekran değişmez). Satır varsa tetkik KAPANIR ve yalnız satırı olan roller
--  o işlemi yapabilir. Tersi - "kısıt tanımlayana kadar her şey kapalı" -
--  kurulu bir sistemi ilk güncellemede durdururdu.
--
--  KISITLAMA ÜÇ AYRI İŞLEM İÇİN: bir rol testi İSTEYEBİLİR ama sonucunu
--  göremeyebilir (istem yazan hekim ile sonucu yorumlayan uzman ayrı), ya da
--  görebilir ama onaylayamaz. Tek bayrakla anlatılamaz.
--
--  NEREDE UYGULANIR (hepsi sunucuda):
--    * istem açma - yetkisiz rol o tetkiği isteyemez,
--    * sonuç listeleri ve istem detayı - yetkisiz satır HİÇ dönmez,
--    * rapor - yetkisiz tetkik basılmaz, raporun altına kaç tanesinin
--      gizlendiği yazılır (sessizce eksik rapor, yanlış rapordur),
--    * onay - yetkisiz rol onaylayamaz.
-- =====================================================================

create table if not exists public.lab_tetkik_kisit (
  id         integer generated by default as identity primary key,
  tetkik_id  integer not null references public.lab_tetkik(id) on delete cascade,
  rol_id     integer not null references public.rol(id) on delete cascade,
  iste       smallint not null default 1,
  gor        smallint not null default 1,
  onayla     smallint not null default 1,
  aciklama   varchar(200) not null default '',
  aktif      smallint not null default 1,
  ekleyen    integer not null default 0,
  ekleme_tarihi timestamptz not null default now(),
  degistiren integer not null default 0,
  degistirme_tarihi timestamptz
);

create unique index if not exists ux_lab_tetkik_kisit
  on public.lab_tetkik_kisit (tetkik_id, rol_id);
create index if not exists ix_lab_tetkik_kisit_tetkik
  on public.lab_tetkik_kisit (tetkik_id) where aktif = 1;

comment on table public.lab_tetkik_kisit is
  '889: tetkik x rol x islem (iste/gor/onayla) kisiti (KTS L7). Bir tetkikte '
  'AKTIF satir yoksa tetkik herkese aciktir; satir varsa yalniz satiri olan '
  'roller o islemi yapabilir.';

/**
 * TEK KARAR NOKTASI: hem SQL süzgeçleri hem uygulama kodu buradan sorar.
 * İki yerde ayrı yazılsaydı liste ile rapor sessizce ayrışırdı.
 *
 * `p_islem`: 'iste' | 'gor' | 'onayla'. Tanınmayan işlem KAPALI sayılır -
 * yazım hatası yüzünden kısıtın açılıp kalması, hata vermesinden kötüdür.
 */
create or replace function public.fn_lab_tetkik_izin(p_tetkik_id integer,
                                                     p_rol_id    integer,
                                                     p_islem     varchar)
returns boolean language sql stable as $$
    select case
             when p_islem not in ('iste', 'gor', 'onayla') then false
             -- Kısıtlanmamış tetkik: herkese açık.
             when not exists (select 1 from public.lab_tetkik_kisit k
                               where k.tetkik_id = p_tetkik_id and k.aktif = 1)
                  then true
             else exists (
                    select 1 from public.lab_tetkik_kisit k
                     where k.tetkik_id = p_tetkik_id and k.aktif = 1
                       and k.rol_id = p_rol_id
                       and case p_islem
                             when 'iste'   then k.iste
                             when 'gor'    then k.gor
                             else               k.onayla
                           end = 1)
           end;
$$;

comment on function public.fn_lab_tetkik_izin(integer, integer, varchar) is
  '889: rol bu tetkikte bu islemi yapabilir mi (iste/gor/onayla). Kisit '
  'satiri olmayan tetkik herkese aciktir; taninmayan islem KAPALI.';

-- Kısıtlı tetkikleri tek yerden görmek için (ekran ve denetim dökümü).
create or replace view public.v_lab_tetkik_kisitli as
select t.id as tetkik_id, t.kod, t.ad,
       count(*) filter (where k.aktif = 1) as kural,
       string_agg(r.ad, ' · ' order by r.ad) filter (where k.aktif = 1) as roller
  from public.lab_tetkik t
  join public.lab_tetkik_kisit k on k.tetkik_id = t.id
  left join public.rol r on r.id = k.rol_id
 group by t.id, t.kod, t.ad
having count(*) filter (where k.aktif = 1) > 0;

comment on view public.v_lab_tetkik_kisitli is
  '889: kisitlanmis tetkikler ve izinli rolleri - denetimde "hangi testler '
  'kisitli" sorusunun tek cevabi.';

-- -------------------------------------------------------------- yetki ----
--  Kısıtı TANIMLAMAK ayrı bir yetkidir: tetkik kataloğunu düzenleyebilen
--  herkes kısıtı kaldırabilseydi kısıt kendini koruyamazdı.
insert into public.yetki (kod, ad, grup, tur, sira, aktif, urun_modu, modul)
select 'lab.tetkik_kisit', 'Test yetki kısıtları (tanım)', 'Laboratuvar',
       0, 47, 1, 2, 'lab'
 where not exists (select 1 from public.yetki y where y.kod = 'lab.tetkik_kisit');

insert into public.rol_yetki (rol_id, yetki_id, gor, ekle, degistir, sil, ekleyen)
select r.id, y.id, 1, 1, 1, 1, 0
  from public.rol r cross join public.yetki y
 where r.kod = 'yonetici' and y.kod = 'lab.tetkik_kisit'
   and not exists (select 1 from public.rol_yetki ry
                    where ry.rol_id = r.id and ry.yetki_id = y.id);
update public.rol set yetki_surumu = yetki_surumu + 1 where kod = 'yonetici';

do $$
begin
    raise notice '889 tamam: % kisit satiri, % tetkik kisitli',
        (select count(*) from public.lab_tetkik_kisit),
        (select count(*) from public.v_lab_tetkik_kisitli);
end $$;
