-- =============================================================================
--  1153  CARİ BANKA / IBAN HESAPLARI - müşteri / tedarikçi kartı "Banka / IBAN" sekmesi
--
--  Kullanıcı 23.10.2026: "banka Iban ekleyemedim" - sekme yer tutucuydu, cariye ait
--  banka hesabını tutan bir tablo yoktu (kasa_hesap.iban KURUMUN kendi hesabıdır).
--  Bir carinin birden çok hesabı olur (TL / döviz, farklı banka); ödeme talimatında
--  varsayılan hesap önerilir (tek varsayılan - kısmi benzersiz indeks).
--  IBAN biçimi (ülke kodu + mod-97) uygulamada denetlenir (KimlikDogrulama.IbanTuru);
--  aktarılacak eski veride bozuk IBAN olabileceği için tabloda CHECK yok.
--  Tekrar çalıştırmak güvenli.
-- =============================================================================

begin;

create table if not exists public.taraf_banka (
    id                integer generated by default as identity primary key,
    taraf_id          integer      not null references public.taraf(id) on delete cascade,
    banka_adi         varchar(80),
    sube_adi          varchar(80),
    hesap_no          varchar(40),
    iban              varchar(34),
    doviz_cinsi       varchar(3),
    hesap_sahibi      varchar(120),
    aciklama          varchar(200),
    varsayilan        smallint     not null default 0,
    aktif             smallint     not null default 1,
    ekleyen           integer,
    ekleme_tarihi     timestamptz  not null default now(),
    degistiren        integer,
    degistirme_tarihi timestamptz,
    aktarim_kaynak    smallint,
    aktarim_tablo     varchar(30),
    aktarim_id        bigint
);

create index if not exists ix_taraf_banka_taraf on public.taraf_banka (taraf_id);
create unique index if not exists ux_taraf_banka_varsayilan on public.taraf_banka (taraf_id) where varsayilan = 1;
create unique index if not exists ux_taraf_banka_aktarim on public.taraf_banka (aktarim_kaynak, aktarim_tablo, aktarim_id)
    where aktarim_kaynak is not null;

comment on table public.taraf_banka is 'Carinin banka hesapları (IBAN) - müşteri / tedarikçi kartı Banka / IBAN sekmesi (1153).';

commit;
