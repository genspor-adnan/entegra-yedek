-- exist"). Biçim canlıdakiyle aynı (timestamptz); aktarım kolonlarını 1080 ekler.
create table if not exists public.stok_barkod (
    id                integer generated by default as identity primary key,
    stok_id           integer     not null,
    barkod            varchar(50) not null,
    barkod_tipi       smallint    not null default 0,
    barkod_birimi     smallint    not null default 0,
    varsayilan        smallint    not null default 0,
    ekleyen           integer     not null default 0,
    ekleme_tarihi     timestamptz not null default now(),
    degistiren        integer     not null default 0,
    degistirme_tarihi timestamptz,
    constraint fk_stok_barkod_stok foreign key (stok_id) references public.stok (id) on delete cascade
);
create unique index if not exists ux_stok_barkod on public.stok_barkod (barkod);
create unique index if not exists ux_stok_barkod_varsayilan on public.stok_barkod (stok_id) where varsayilan = 1;
create index if not exists ix_stok_barkod_stok on public.stok_barkod (stok_id);
drop trigger if exists trg_stok_barkod_degistirme on public.stok_barkod;
create trigger trg_stok_barkod_degistirme before update on public.stok_barkod
    for each row execute function public.fn_degistirme_tarihi();
