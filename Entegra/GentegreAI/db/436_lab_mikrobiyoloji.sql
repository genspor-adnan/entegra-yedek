    -- 1 oral · 2 parenteral · 3 her ikisi
    uygulama      smallint     not null default 3,
    -- Yalnız idrar yolu enfeksiyonunda anlamlı (nitrofurantoin, fosfomisin):
    --   kan izolatında raporlanması tedaviyi yanlış yönlendirir.
    yalniz_uriner smallint     not null default 0,
    durum         smallint     not null default 0,
    ekleyen       integer   not null default 0,
    ekleme_tarihi timestamp not null default now(),
    degistiren    integer   not null default 0,
    degistirme_tarihi timestamp
);

create unique index if not exists ux_lab_antibiyotik_kod
    on public.lab_antibiyotik (upper(kod));

