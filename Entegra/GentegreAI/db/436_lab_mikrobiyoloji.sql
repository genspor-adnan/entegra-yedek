-- =====================================================================
-- 436 - LABORATUVAR: MİKROBİYOLOJİ (kültür · identifikasyon · antibiyogram)
--
-- Mockup: Ekranlar/Lab/lab_mikrobiyoloji.html ve
--         Ekranlar/Lab/lab_sonuc_formu_mikrobiyoloji.html
--
-- NEDEN AYRI TABLOLAR: biyokimya sonucu TEK DEĞERDİR (lab_sonuc), kültür
-- ise bir SÜREÇTİR: ekim → planlı okumalar → üreme (birden çok izolat) →
-- identifikasyon → izolat başına antibiyogram (her antibiyotik bir satır).
-- Bunu lab_sonuc'a sığdırmak, tek metin alanına "E. coli, AMP R, SXT R…"
-- yazmak demekti: ne aranabilir ne de direnç istatistiği çıkarılabilirdi.
--
-- YİNE DE ÖZET lab_sonuc'A DÜŞER: kültür onaylanınca istem satırına bir
-- lab_sonuc satırı yazılır ("Escherichia coli — 100.000 CFU/mL"). Böylece
-- istem durumu, muayene sekmesi, e-Nabız ve panik akışı mikrobiyolojiyi
-- ayrıca tanımak zorunda kalmaz - tek sonuç hattı korunur.
--
-- KADEMELİ BİLDİRİM (Akılcı Antibiyotik Kullanımı): geniş spektrumlu
-- ajanlar RAPORDA GİZLENİR; yalnız alt basamakta duyarlı seçenek yoksa
-- açılır. Hepsini birden basmak, klinisyeni gereksiz yere karbapeneme
-- yönlendirir. Karar sunucuda (fn_lab_antibiyogram_bildirim) - ekranda
-- hesaplanırsa rapor ile ekran ayrışır.
-- =====================================================================

-- ---------------------------------------------------------------------
--  1) KATALOGLAR - besiyeri, organizma, antibiyotik
-- ---------------------------------------------------------------------

create table if not exists public.lab_besiyeri (
    id            integer generated by default as identity primary key,
    kod           varchar(20)  not null,
    ad            varchar(120) not null,
    -- 1 katı (agar) · 2 sıvı (buyyon) · 3 kan kültür şişesi · 9 diğer
    tur           smallint     not null default 1,
    -- Ekim sonrası varsayılan inkübasyon: okuma planı buradan kurulur.
    sicaklik      smallint     not null default 37,
    -- 1 aerob · 2 anaerob · 3 %5 CO2 · 4 mikroaerofil
    atmosfer      smallint     not null default 1,
    ilk_okuma_saat  smallint   not null default 24,
    son_okuma_saat  smallint   not null default 48,
    aciklama      varchar(300) not null default '',
    durum         smallint     not null default 0,   -- 0 aktif · 1 pasif
    ekleyen       integer   not null default 0,
    ekleme_tarihi timestamp not null default now(),
    degistiren    integer   not null default 0,
    degistirme_tarihi timestamp
);

create unique index if not exists ux_lab_besiyeri_kod
    on public.lab_besiyeri (upper(kod));

comment on table public.lab_besiyeri is
    'Besiyeri katalogu (436): ekimde kullanilan agar/buyyon ve varsayilan '
    'inkubasyon kosullari.';

-- ORGANİZMA KATALOĞU: rapor ve direnç istatistiği organizma KİMLİĞİNE
--   bağlı. Serbest metin yazılsaydı "E.coli" / "E. coli" / "Escherichia
--   coli" üç ayrı etken sayılır, sürveyans imkânsız olurdu.
create table if not exists public.lab_organizma (
    id            integer generated by default as identity primary key,
    kod           varchar(20)  not null,
    ad            varchar(160) not null,          -- latin ad
    kisa_ad       varchar(60)  not null default '',
    -- 1 bakteri · 2 mantar · 3 virüs · 4 parazit · 9 diğer/durum
    tur           smallint     not null default 1,
    -- 0 uygulanmaz · 1 gram pozitif · 2 gram negatif
    gram          smallint     not null default 0,
    -- 1 kok · 2 basil · 3 kokobasil · 4 maya · 5 küf · 9 diğer
    morfoloji     smallint     not null default 0,
    snomed        varchar(20)  not null default '',
    skrs_kod      varchar(20)  not null default '',
    -- "Üreme yok" ve "normal flora" da birer SONUÇTUR: izolat satırı
    --   olmadan kültür kapatılamaz, rapor da bunu yazmak zorunda.
    sonuc_satiri  smallint     not null default 0,  -- 1: üreme yok / flora
    -- Bildirimi zorunlu bulaşıcı hastalik etkeni (Sağlık Bakanlığı listesi).
    bildirimi_zorunlu smallint not null default 0,
    durum         smallint     not null default 0,
    ekleyen       integer   not null default 0,
    ekleme_tarihi timestamp not null default now(),
    degistiren    integer   not null default 0,
    degistirme_tarihi timestamp
);

create unique index if not exists ux_lab_organizma_kod
    on public.lab_organizma (upper(kod));

create table if not exists public.lab_antibiyotik (
    id            integer generated by default as identity primary key,
    kod           varchar(20)  not null,
    ad            varchar(120) not null,
    grup          varchar(60)  not null default '',   -- beta-laktam, kinolon…
    atc           varchar(12)  not null default '',
    -- KADEMELİ BİLDİRİM BASAMAĞI: 1 dar spektrum (her zaman raporlanır) ·
    --   2 alternatif · 3 geniş spektrum / kısıtlı (yalnız gerektiğinde).
