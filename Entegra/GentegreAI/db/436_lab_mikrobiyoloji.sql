-- ---------------------------------------------------------------------
--  5) ANTİBİYOGRAM - izolat × antibiyotik
--
--  YORUM STANDARDI VE SÜRÜMÜ SATIRDA SAKLANIR (EUCAST 2026 v16 gibi):
--  kesim noktaları yıllık değişir; sürüm yazılmazsa eski rapor bugünün
--  kuralıyla okunur ve "S" idi sanılan sonuç aslında "R" olurdu.
-- ---------------------------------------------------------------------
create table if not exists public.lab_antibiyogram (
    id             integer generated by default as identity primary key,
    ureme_id       integer not null references public.lab_kultur_ureme(id) on delete cascade,
    antibiyotik_id integer not null references public.lab_antibiyotik(id),
    -- MIC "≥ 32" gibi sınır değerlerle gelir: işaret ayrı kolonda tutulur,
    --   sayısal alan sayısal kalır (istatistik ve karşılaştırma için).
    mic            numeric(19,4),
    mic_isaret     varchar(2) not null default '',   -- '', '<=', '>='
    zon_mm         smallint,
    -- S duyarlı · I artırılmış maruziyette duyarlı · R dirençli
    yorum          varchar(1) not null default '',
    -- 1 cihaz (VITEK) · 2 disk difüzyon · 3 gradyan (E-test) · 4 uzman
    kaynak         smallint not null default 1,
    standart       varchar(20) not null default 'EUCAST',
    standart_surum varchar(20) not null default '',
    -- UZMAN S/I/R'yi DEĞİŞTİREBİLİR ama gerekçesiz değil: cihaz sonucunu
    --   sessizce ezmek, sonradan "bu neden R yazıyordu" sorusunu cevapsız
    --   bırakırdı.
    cihaz_yorum    varchar(1) not null default '',
    degistiren_id  integer,
    degistirme_neden varchar(300) not null default '',
    -- Kademeli bildirimde raporda gösterilecek mi (sunucu hesaplar).
    bildir         smallint not null default 1,
    aciklama       varchar(300) not null default '',
    ekleyen        integer   not null default 0,
    ekleme_tarihi  timestamp not null default now(),
    degistiren     integer   not null default 0,
    degistirme_tarihi timestamp
);

create unique index if not exists ux_lab_antibiyogram
    on public.lab_antibiyogram (ureme_id, antibiyotik_id);

-- ---------------------------------------------------------------------
--  6) KADEMELİ BİLDİRİM
--
--  Kural: 1. basamak HER ZAMAN raporlanır. 2. basamak, 1. basamakta
--  duyarlı (S) seçenek YOKSA açılır. 3. basamak (kısıtlı/geniş spektrum)
--  yalnız 1 ve 2'de duyarlı seçenek yoksa. Üriner-özel ajanlar idrar dışı
--  numunede hiç raporlanmaz.
--
--  Uzmanın elle "bildir" dediği satır ASLA gizlenmez: kural klinik kararın
--  yerine geçmez, yalnız varsayılanı belirler.
-- ---------------------------------------------------------------------
create or replace function public.fn_lab_antibiyogram_bildirim(p_ureme_id integer)
returns integer language plpgsql as $$
declare
    v_uriner   boolean;
    v_s1       integer;
    v_s2       integer;
    v_etkilenen integer;
begin
    -- Numune tipi 4 = idrar (db/433 kod uzayı).
    select coalesce(n.numune_tipi, 0) = 4
      into v_uriner
      from public.lab_kultur_ureme u
      join public.lab_kultur k on k.id = u.kultur_id
      left join public.lab_numune n on n.id = k.numune_id
     where u.id = p_ureme_id;

    select count(*) filter (where a.basamak = 1 and g.yorum = 'S'),
           count(*) filter (where a.basamak = 2 and g.yorum = 'S')
      into v_s1, v_s2
      from public.lab_antibiyogram g
      join public.lab_antibiyotik a on a.id = g.antibiyotik_id
     where g.ureme_id = p_ureme_id;

    update public.lab_antibiyogram g
       set bildir = case
             -- Uzman elle karar verdiyse (kaynak 4) dokunulmaz.
             when g.kaynak = 4 then g.bildir
             when a.yalniz_uriner = 1 and not coalesce(v_uriner, false) then 0
             when a.basamak = 1 then 1
             when a.basamak = 2 then case when coalesce(v_s1, 0) = 0 then 1 else 0 end
             else case when coalesce(v_s1, 0) = 0 and coalesce(v_s2, 0) = 0
                       then 1 else 0 end
           end
      from public.lab_antibiyotik a
     where a.id = g.antibiyotik_id and g.ureme_id = p_ureme_id;

    get diagnostics v_etkilenen = row_count;
    return v_etkilenen;
end $$;

-- ---------------------------------------------------------------------
--  7) KÜLTÜR ÖZETİ - lab_sonuc'a yazılacak metin
--
--  Rapor metnini tek yerde üretiriz: ekran, çıktı ve e-Nabız aynı cümleyi
--  görsün. Üç yerde ayrı kurulsaydı biri "10^5", diğeri "100.000" yazardı.
-- ---------------------------------------------------------------------
create or replace function public.fn_lab_kultur_ozet(p_kultur_id integer)
returns text language sql stable as $$
    select coalesce(
        nullif(string_agg(
            o.ad
            -- SAYI BİÇİMİ: 100000 -> "100.000". to_char'ın grup ayıracı
            --   sunucunun lc_numeric'ine bağlı (konteynerde ','), rapor ise
            --   her kurulumda aynı görünmeli; tam sayıda ondalık basamak da
            --   yazılmamalı ("100.000." gibi bir kuyruk kalıyordu).
            || case when u.koloni_sayisi is null then ''
                    else ' — ' || translate(
                             trim(to_char(u.koloni_sayisi,
                                 case when u.koloni_sayisi = trunc(u.koloni_sayisi)
                                      then 'FM999G999G999G990'
                                      else 'FM999G999G999G990D99' end)),
                             ',', '.')
                         || ' ' || u.koloni_birim end
            || case when u.esbl = 2 then ' · ESBL pozitif' else '' end
            || case when u.karbapenemaz = 2 then ' · karbapenemaz pozitif' else '' end
            || case when u.mrsa = 2 then ' · MRSA' else '' end
            || case when u.vre = 2 then ' · VRE' else '' end,
            ' + ' order by u.izolat_no), ''),
        'Üreme yok')
      from public.lab_kultur_ureme u
      join public.lab_organizma o on o.id = u.organizma_id
     where u.kultur_id = p_kultur_id and u.durum = 1;
$$;

