drop view if exists public.v_lab_besiyeri_lookup;
create view public.v_lab_besiyeri_lookup as
select b.id, b.kod, b.kod || ' · ' || b.ad as ad,
       case when b.durum = 0 then 1 else 0 end::smallint as aktif
  from public.lab_besiyeri b;

