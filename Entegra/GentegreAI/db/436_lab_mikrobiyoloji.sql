create view public.v_lab_antibiyotik_lookup as
select a.id, a.kod, a.ad || ' (' || a.basamak::text || '. basamak)' as ad,
       case when a.durum = 0 then 1 else 0 end::smallint as aktif
  from public.lab_antibiyotik a;

