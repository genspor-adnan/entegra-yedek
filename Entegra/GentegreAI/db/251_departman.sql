-- 251: DEPARTMAN TABLOSU + randevu bölümleri (kullanıcı: "departman tablosu
-- oluştur id, adı, randevu_verilebilir alanı; personel kartında bu departman
-- listesi gelsin; randevu tablosunda bölümde ise randevu_verilebilir bölümler
-- listelensin; randevu ayarlarına Bölümler sekmesi aç, solda departmandan
-- randevu verilen bölümler ve bu departmandaki hekimler, sağında o
-- bölüme/hekime ait randevu ayarları - master detail").
--
-- Departman şimdiye kadar kod_liste 'taraf.departman' idi; bölüm de ayrı bir
-- kod listesiydi ('randevu.bolum'). Artık İKİSİ AYNI ŞEY: hastanenin bölümü
-- de bir departmandır, farkı randevu verilip verilmediğidir. Tek tabloya
-- indirmek "hekim hangi bölümde çalışıyor" sorusunu da çözer - personelin
-- departmanı doğrudan randevu bölümüdür.
--
-- ID KORUNUR: taraf.departman (51..131) ve randevu.bolum (1..8) mevcut sayısal
-- değerleri aynen kalsın diye satırlar KENDİ ID'leriyle taşınır; iki küme
-- çakışmıyor, veri dönüştürmeye gerek yok.

create table if not exists public.departman (
  id                   integer generated by default as identity primary key,
  ad                   varchar(100) not null,
  -- Bu departman bir POLİKLİNİK/BÖLÜM mü: randevu kartındaki "Bölüm" listesi
  --   yalnız bunları gösterir (Muhasebe'ye randevu verilmez).
  randevu_verilebilir  smallint not null default 0,
  aktif                smallint not null default 1,
  sira                 integer  not null default 0,
  ekleyen              integer  not null default 0,
  ekleme_tarihi        timestamp not null default now()::timestamp,
  degistiren           integer  not null default 0,
  degistirme_tarihi    timestamp
);

comment on table public.departman is
  'Departman/bölüm (251). randevu_verilebilir = 1 olanlar randevu bölümüdür.';

create unique index if not exists ux_departman_ad on public.departman (lower(ad));
create index if not exists ix_departman_randevu
  on public.departman (randevu_verilebilir) where randevu_verilebilir = 1;

-- --------------------------------------------------------------- veri göçü --
-- Personel departmanları (kod_liste 'taraf.departman').
-- distinct on: eski kod listesinde AYNI AD iki kez geçiyor ("Kalite Yönetimi"
--   65 ve "KALİTE YÖNETİMİ" 129) - küçük id kazanır, büyüğü aşağıda o id'ye
--   yönlendirilir; personelin departmanı boşa düşmesin.
insert into public.departman (id, ad, randevu_verilebilir, aktif, sira)
select distinct on (lower(d.ad)) d.deger, d.ad, 0, d.aktif, d.sira
  from public.kod_deger d
  join public.kod_liste l on l.id = d.liste_id
 where l.kod = 'taraf.departman'
   and not exists (select 1 from public.departman x where x.id = d.deger)
   and not exists (select 1 from public.departman x where lower(x.ad) = lower(d.ad))
 order by lower(d.ad), d.deger;

-- Taşınmayan yinelenen adların personelleri kazanan id'ye çekilir.
update public.taraf t
   set departman = k.yeni
  from (select d.deger as eski,
               (select min(x.id) from public.departman x where lower(x.ad) = lower(d.ad)) as yeni
          from public.kod_deger d
          join public.kod_liste l on l.id = d.liste_id
         where l.kod = 'taraf.departman') k
 where t.departman = k.eski and k.yeni is not null and k.yeni <> k.eski;

-- Randevu bölümleri (kod_liste 'randevu.bolum') - randevu_verilebilir = 1.
insert into public.departman (id, ad, randevu_verilebilir, aktif, sira)
select distinct on (lower(d.ad)) d.deger, d.ad, 1, d.aktif, d.sira
  from public.kod_deger d
  join public.kod_liste l on l.id = d.liste_id
 where l.kod = 'randevu.bolum'
   and not exists (select 1 from public.departman x where x.id = d.deger)
   and not exists (select 1 from public.departman x where lower(x.ad) = lower(d.ad))
 order by lower(d.ad), d.deger;

-- Ad çakışması olduysa (aynı ad hem departman hem bölüm) bölüm bayrağı açılır.
update public.departman d
   set randevu_verilebilir = 1
 where randevu_verilebilir = 0
   and exists (select 1 from public.kod_deger k
                 join public.kod_liste l on l.id = k.liste_id
                where l.kod = 'randevu.bolum' and lower(k.ad) = lower(d.ad));

-- Identity dizisi elle verilen id'lerin gerisinde kalmasın (yoksa ilk insert
--   "duplicate key" verir - MSSQL'den seed edilen tablolardaki bilinen tuzak).
select setval(pg_get_serial_sequence('public.departman', 'id'),
              coalesce((select max(id) from public.departman), 1));

-- ----------------------------------------------------------------- lookup ---
create or replace view public.v_departman_lookup as
select d.id, d.ad, d.aktif
  from public.departman d;

-- Randevu kartındaki "Bölüm" listesi - yalnız poliklinikler.
create or replace view public.v_randevu_bolum_lookup as
select d.id, d.ad, d.aktif
  from public.departman d
 where d.randevu_verilebilir = 1;

-- ------------------------------------------- bölüm/hekim randevu ayarları ---
-- Master-detail: departman satırı (hekim_id boş) = BÖLÜMÜN geneli, altındaki
-- hekim satırı o hekimin kendi düzeni. Boş bırakılan alan bir üst seviyeden
-- (hekim -> bölüm -> genel ayarlar) miras alınır; her seviyede tüm alanları
-- doldurmaya zorlamak, bir tek öğle arası farkı için her şeyi kopyalatırdı.
create table if not exists public.randevu_bolum_ayar (
  id                integer generated by default as identity primary key,
  departman_id      integer  not null references public.departman(id) on delete cascade,
  hekim_id          integer  references public.taraf(id) on delete cascade,
  baslangic_saat    varchar(5)  not null default '',
  bitis_saat        varchar(5)  not null default '',
  ogle_baslangic    varchar(5)  not null default '',
  ogle_bitis        varchar(5)  not null default '',
  slot_dk           smallint,
  varsayilan_sure   smallint,
  calisma_gunleri   varchar(20) not null default '',   -- "1,2,3,4,5"
  aktif             smallint not null default 1,
  aciklama          varchar(300) not null default '',
  ekleyen           integer  not null default 0,
  ekleme_tarihi     timestamp not null default now()::timestamp,
  degistiren        integer  not null default 0,
  degistirme_tarihi timestamp
);

comment on table public.randevu_bolum_ayar is
  'Bölüm ve hekim bazlı randevu düzeni (251). Boş alan üst seviyeden miras alınır.';

-- Bölüm geneli tek satır; her hekim için de tek satır.
create unique index if not exists ux_randevu_bolum_ayar_bolum
  on public.randevu_bolum_ayar (departman_id) where hekim_id is null;
create unique index if not exists ux_randevu_bolum_ayar_hekim
  on public.randevu_bolum_ayar (departman_id, hekim_id) where hekim_id is not null;
