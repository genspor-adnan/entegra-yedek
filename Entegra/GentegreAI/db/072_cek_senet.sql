--  072_cek_senet.sql  —  cek_senet, cek_senet_hareket
--
--  Eski CEKLER + SENETLER tek tabloda birlesti: yapilari %95 ayni, tek fark
--    "cek mi senet mi" (tur) ve alinan/verilen ayrimi (yon). Legacy'de
--    CEKSENET kolonu 101/103/121/321 ile bu iki boyutu tek sayida kodluyordu;
--    burada iki ayri kolon.
--
--  KARAR K8: cek/senet PORTFOYU sanal hesaptir - mali_hareket bacaginda
--    hesap_turu='E', hesap_id null, cek_senet_id dolu. Her doviz icin fiziksel
--    "portfoy hesabi" actirmamak icin. Muhasebe karsiligi (101/103/121/321)
--    muhasebe_eslestirme kuralindan cozulur (074).
--
--  kasa_islem_id kolonlari 073'te ALTER ile eklenir (dongusel FK'yi kirmak icin).
-- ============================================================================
\set ON_ERROR_STOP on

-- -------------------------------------------------------------- cek_senet ----
create table if not exists public.cek_senet (
    id                   integer generated by default as identity primary key,
    tur                  smallint     not null,             -- 1 cek, 2 senet
    yon                  smallint     not null,             -- 1 alinan (musteri/3.sahis), 2 verilen (kendi)
    durum                smallint     not null default 10,  -- 10 portfoy, 20 ciro, 30 bankada tahsilde,
                                                            -- 40 teminatta, 50 tahsil/odendi, 60 karsiliksiz,
                                                            -- 70 iade, 0 iptal
    taraf_id             integer,                           -- alinan: ceki veren cari | verilen: lehtar
    kesideci             varchar(150) not null default '',  -- 3. sahis cekinde kesideci
    ciro_taraf_id        integer,                           -- ciro edildigi cari
    hesap_id             integer,                           -- tahsile verildigi / odendigi banka
    tarih                date         not null,
    vade                 date         not null,
    tutar                numeric(19,4) not null default 0,
    doviz_cinsi          varchar(6)   not null default 'TL',
    doviz_kuru           numeric(19,6) not null default 1,
    yerel_tutar          numeric(19,4) not null default 0,  -- TL karsiligi
    seri_no              varchar(30)  not null default '',
    banka_adi            varchar(60)  not null default '',
    banka_subesi         varchar(60)  not null default '',
    hesap_no             varchar(30)  not null default '',
    makbuz_no            varchar(30)  not null default '',
    giris_kasa_islem_id  integer,                           -- portfoye giren islem (073'te FK)
    proje_id             integer,
    sube_id              integer      not null default 0,
    aciklama             varchar(200) not null default '',
    ekleyen              integer      not null default 0,
    ekleme_tarihi        timestamp    not null default now()::timestamp,
    degistiren           integer      not null default 0,
    degistirme_tarihi    timestamp,
    constraint ck_cek_senet_tur   check (tur in (1,2)),
    constraint ck_cek_senet_yon   check (yon in (1,2)),
    constraint ck_cek_senet_kur   check (doviz_kuru > 0),
    constraint fk_cek_senet_taraf foreign key (taraf_id)      references public.taraf (id),
    constraint fk_cek_senet_ciro  foreign key (ciro_taraf_id) references public.taraf (id),
    constraint fk_cek_senet_hesap foreign key (hesap_id)      references public.hesap (id),
    constraint fk_cek_senet_proje foreign key (proje_id)      references public.proje (id),
    constraint fk_cek_senet_sube  foreign key (sube_id)       references public.sube (id)
);

create index if not exists ix_cek_senet_taraf on public.cek_senet (taraf_id) where taraf_id is not null;
create index if not exists ix_cek_senet_vade  on public.cek_senet (vade, durum);
create index if not exists ix_cek_senet_hesap on public.cek_senet (hesap_id) where hesap_id is not null;

comment on table public.cek_senet is
  'Cek ve senet portfoyu (eski CEKLER + SENETLER). tur 1 cek / 2 senet, yon 1 alinan / 2 verilen. Bacakta hesap_turu=E ile gorunur (K8).';
comment on column public.cek_senet.durum is
  '10 portfoy, 20 ciro edildi, 30 bankada tahsilde, 40 teminatta, 50 tahsil edildi/odendi, 60 karsiliksiz, 70 iade, 0 iptal.';

-- ------------------------------------------------------ cek_senet_hareket ----
-- Durum degisiminin izi (eski CEKHAREKET). Her satir bir mali isleme baglanabilir.
create table if not exists public.cek_senet_hareket (
    id                   integer generated by default as identity primary key,
    cek_senet_id         integer      not null,
    islem                smallint     not null,   -- 130 portfoye giris, 131 ciro, 132 bankaya tahsile,
                                                  -- 133 tahsil edildi, 134 karsiliksiz, 135 iade,
                                                  -- 136 odendi (verilen), 137 teminata, 138 teminattan donus,
                                                  -- 139 iptal (geri alma)
    tarih                date         not null,
    eski_durum           smallint     not null default 0,
    yeni_durum           smallint     not null default 0,
    taraf_id             integer,
    hesap_id             integer,
    kasa_islem_id        integer,                 -- 073'te FK
    aciklama             varchar(200) not null default '',
    ekleyen              integer      not null default 0,
    ekleme_tarihi        timestamp    not null default now()::timestamp,
    constraint fk_cek_senet_hareket_ana   foreign key (cek_senet_id) references public.cek_senet (id) on delete cascade,
    constraint fk_cek_senet_hareket_taraf foreign key (taraf_id)     references public.taraf (id),
    constraint fk_cek_senet_hareket_hesap foreign key (hesap_id)     references public.hesap (id)
);

create index if not exists ix_cek_senet_hareket_ana on public.cek_senet_hareket (cek_senet_id, id);

comment on table public.cek_senet_hareket is
  'Cek/senet durum degisim defteri (eski CEKHAREKET). Iptal islemi 139 ile onceki duruma donulur.';

-- ------------------------------------------------------- degistirme trigger ----
drop trigger if exists trg_cek_senet_degistirme on public.cek_senet;
create trigger trg_cek_senet_degistirme before update on public.cek_senet
    for each row execute function public.fn_degistirme_tarihi();

-- --------------------------------------------------------------- gorunum ----
create or replace view public.v_cek_senet_portfoy as
    select c.id, c.tur, c.yon, c.durum, c.vade, c.tutar, c.doviz_cinsi, c.yerel_tutar,
           c.seri_no, c.banka_adi, c.taraf_id, t.unvan as taraf_unvan,
           c.hesap_id, h.ad as hesap_adi, c.proje_id, c.sube_id,
           (c.vade - current_date) as kalan_gun
      from public.cek_senet c
      left join public.taraf t on t.id = c.taraf_id
      left join public.hesap h on h.id = c.hesap_id
     where c.durum not in (0, 50, 70);

comment on view public.v_cek_senet_portfoy is
  'Elde duran (tahsil edilmemis / iade olmamis) cek ve senetler; vade takibi icin kalan_gun ile.';

