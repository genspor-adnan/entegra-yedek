-- 321: Tahsilatın BELGE SATIRINA dağıtılması.
--
-- Bugüne kadar tahsilat yalnız BELGEYE bağlanıyordu (kasa_islem.belge_id):
-- "bu başvuruya 500 TL alındı" biliniyor, "hangi tetkiğin parası alındı"
-- bilinmiyordu. belge_satir'daki kurum_kapatilan / hasta_kapatilan ise
-- FATURALANDI demek (289 dönüşüm kapatması), tahsil edildi demek değil.
--
-- Bu ayrım prim için belirleyici: kullanıcı kararı "tahsil edildikçe prim".
-- Prim hakedişi tetkik yapıldığında değil, o tetkiğin parası alındığında
-- doğacak - bu yüzden tahsilatın satır kırılımı gerçek veri olmak zorunda,
-- oransal tahminle hesaplanamaz.

-- ------------------------------------------------------------- dağıtım ----
create table if not exists public.kasa_islem_dagitim (
    id             integer generated by default as identity primary key,
    kasa_islem_id  integer   not null references public.kasa_islem(id) on delete cascade,
    belge_satir_id integer   not null references public.belge_satir(id) on delete cascade,
    -- Payın SAHİBİ (289): 1 = hasta payı, 2 = kurum payı. Aynı satırın iki
    --   payı ayrı ayrı tahsil edilir (hasta katkısını hasta öder, kalanı
    --   kurum icmalle öder) - tek toplamda tutulursa hangisinin ödendiği
    --   kaybolur.
    pay            smallint  not null default 1,
    tutar          numeric(19,4) not null,
    ekleyen        integer   not null default 0,
    ekleme_tarihi  timestamp not null default (now())::timestamp
);

create unique index if not exists ux_kasa_dagitim
    on public.kasa_islem_dagitim (kasa_islem_id, belge_satir_id, pay);
create index if not exists ix_kasa_dagitim_satir
    on public.kasa_islem_dagitim (belge_satir_id);

comment on table public.kasa_islem_dagitim is
  'Tahsilat/ödemenin belge satırına dağılımı (321) - prim ve kısmi ödeme takibi.';

-- ------------------------------------------------- satırın tahsil edileni --
alter table public.belge_satir
  add column if not exists hasta_tahsil numeric(19,4) not null default 0,
  add column if not exists kurum_tahsil numeric(19,4) not null default 0;

comment on column public.belge_satir.hasta_tahsil is
  'Satırın hasta payından TAHSİL EDİLEN tutar (321) - kapatilan (faturalandı) ile karıştırılmamalı.';

-- ------------------------------------------------------------- tazeleme ----
-- Tahsil toplamı yalnız GERÇEKLEŞMİŞ (durum 2) ve iptal edilmemiş işlemlerden
-- toplanır: iptal ters kayıt üretir, dağıtım satırı yerinde kalır ama artık
-- saymaz. Bu yüzden toplam tetikte "arttır/azalt" ile değil, HER SEFERİNDE
-- yeniden hesaplanır - iptal, düzeltme ve silme aynı yoldan geçer.
create or replace function public.fn_belge_satir_tahsil_tazele(p_satir_id integer)
returns void language plpgsql as $$
begin
    if coalesce(p_satir_id, 0) = 0 then return; end if;

    update public.belge_satir s
       set hasta_tahsil = coalesce(x.hasta, 0),
           kurum_tahsil = coalesce(x.kurum, 0)
      from (
        select sum(d.tutar) filter (where d.pay = 1) as hasta,
               sum(d.tutar) filter (where d.pay = 2) as kurum
          from public.kasa_islem_dagitim d
          join public.kasa_islem k on k.id = d.kasa_islem_id
         where d.belge_satir_id = p_satir_id
           and coalesce(k.durum, 0) = 2
           and k.iptal_islem_id is null
      ) x
     where s.id = p_satir_id;
end $$;

create or replace function public.tg_kasa_dagitim_tazele()
returns trigger language plpgsql as $$
begin
    if tg_op in ('INSERT', 'UPDATE') then
        perform public.fn_belge_satir_tahsil_tazele(new.belge_satir_id);
    end if;
    if tg_op in ('UPDATE', 'DELETE') then
        perform public.fn_belge_satir_tahsil_tazele(old.belge_satir_id);
    end if;
    return null;
end $$;

drop trigger if exists tr_kasa_dagitim_tazele on public.kasa_islem_dagitim;
create trigger tr_kasa_dagitim_tazele
  after insert or update or delete on public.kasa_islem_dagitim
  for each row execute function public.tg_kasa_dagitim_tazele();

-- İşlemin DURUMU değişince (taslak → gerçekleşti, ya da iptal) dağıttığı
-- satırların hepsi yeniden hesaplanır: iptal edilen tahsilat satırdan düşer.
create or replace function public.tg_kasa_islem_tahsil_tazele()
returns trigger language plpgsql as $$
declare r record;
begin
    for r in select distinct belge_satir_id from public.kasa_islem_dagitim
              where kasa_islem_id = new.id
    loop
        perform public.fn_belge_satir_tahsil_tazele(r.belge_satir_id);
    end loop;
    return null;
end $$;

drop trigger if exists tr_kasa_islem_tahsil_tazele on public.kasa_islem;
create trigger tr_kasa_islem_tahsil_tazele
  after update of durum, iptal_islem_id on public.kasa_islem
  for each row execute function public.tg_kasa_islem_tahsil_tazele();

-- --------------------------------------------------------- aşım koruması ---
-- İki kural: (1) bir satırın payından, o payın TUTARINDAN fazlası tahsil
-- edilemez; (2) bir işlemden dağıtılan toplam, işlemin tutarını aşamaz.
-- Aşım sessiz kalırsa prim de fazla hesaplanır.
create or replace function public.tg_kasa_dagitim_kontrol()
returns trigger language plpgsql as $$
declare
  v_pay_tutar numeric(19,4);
  v_dagitilan numeric(19,4);
  v_islem     numeric(19,4);
begin
    if new.tutar <= 0 then
        raise exception 'Dağıtılan tutar sıfırdan büyük olmalı.' using errcode = 'GK422';
    end if;

    select case when new.pay = 2 then s.kurum_tutar else s.hasta_tutar end
      into v_pay_tutar
      from public.belge_satir s where s.id = new.belge_satir_id;

    select coalesce(sum(d.tutar), 0) into v_dagitilan
      from public.kasa_islem_dagitim d
      join public.kasa_islem k on k.id = d.kasa_islem_id
     where d.belge_satir_id = new.belge_satir_id and d.pay = new.pay
       and d.id is distinct from new.id
       and coalesce(k.durum, 0) = 2 and k.iptal_islem_id is null;

    if coalesce(v_pay_tutar, 0) > 0 and v_dagitilan + new.tutar > v_pay_tutar + 0.005 then
        raise exception 'Satıra payından fazla tahsilat dağıtılamaz (pay %, dağıtılan %, eklenen %).',
            v_pay_tutar, v_dagitilan, new.tutar using errcode = 'GK422';
    end if;

    select coalesce(k.tutar, 0) into v_islem
      from public.kasa_islem k where k.id = new.kasa_islem_id;

    select coalesce(sum(d.tutar), 0) into v_dagitilan
      from public.kasa_islem_dagitim d
     where d.kasa_islem_id = new.kasa_islem_id and d.id is distinct from new.id;

    if v_dagitilan + new.tutar > v_islem + 0.005 then
        raise exception 'Dağıtım toplamı işlem tutarını aşamaz (işlem %, dağıtılan %).',
            v_islem, v_dagitilan + new.tutar using errcode = 'GK422';
    end if;

    return new;
end $$;

drop trigger if exists tr_kasa_dagitim_kontrol on public.kasa_islem_dagitim;
create trigger tr_kasa_dagitim_kontrol
  before insert or update on public.kasa_islem_dagitim
  for each row execute function public.tg_kasa_dagitim_kontrol();

-- ------------------------------------------------ tahsil edilebilir satır --
-- Tahsilat ekranının listesi: belgenin satırları + payların tahsil edileni ve
-- kalanı. Hizmet/stok adı tek kolonda ("kalem") - ekran ikinci sorgu atmasın.
create or replace view public.v_belge_satir_tahsilat as
select s.id                                   as satir_id,
       s.belge_id,
       s.sira,
       coalesce(nullif(hz.ad, ''), nullif(st.ad, ''), nullif(s.aciklama, ''), '')
                                              as kalem,
       coalesce(nullif(hz.kod, ''), nullif(st.kod, ''), '')
                                              as kalem_kod,
       s.miktar,
       s.tutar,
       s.hasta_tutar,
       s.kurum_tutar,
       s.hasta_tahsil,
       s.kurum_tahsil,
       greatest(s.hasta_tutar - s.hasta_tahsil, 0) as hasta_kalan,
       greatest(s.kurum_tutar - s.kurum_tahsil, 0) as kurum_kalan,
       s.hizmet_id,
       s.stok_id
  from public.belge_satir s
  left join public.hizmet hz on hz.id = s.hizmet_id
  left join public.stok st on st.id = s.stok_id
 order by s.sira, s.id;

comment on view public.v_belge_satir_tahsilat is
  'Tahsilat dağıtım ekranı (321): satır bazında tahsil edilen ve kalan pay.';
