\set ON_ERROR_STOP on

create table if not exists public.personel_izin (
    id                  integer generated by default as identity primary key,
    taraf_id            integer not null references public.taraf(id) on delete cascade,
    tur                 smallint not null default 0,
    baslangic_tarihi    date,
    bitis_tarihi        date,
    gun                 smallint not null default 0,
    aciklama            character varying(300) not null default '',
    durum               smallint not null default 0,
    sube_id             integer not null references public.sube(id),
    ekleyen             integer not null default 0,
    ekleme_tarihi       timestamp not null default now()::timestamp,
    degistiren          integer not null default 0,
    degistirme_tarihi   timestamp
);

create index if not exists ix_personel_izin_taraf on public.personel_izin (taraf_id);

comment on table public.personel_izin is
  'Personel izin geçmişi (ik_karti.html mockup İzinler sekmesi) - tür/başlangıç/bitiş/gün/açıklama/durum.';
