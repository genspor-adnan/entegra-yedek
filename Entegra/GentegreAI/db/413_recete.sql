-- ============================================================================
--  413 - e-RECETE ve HASTA ILAC / ALERJI (Faz 1 · Muayene v1)
--
--  Kaynak: Ekranlar/Muayene/muayene_sureci.html adim 7 + hasta_tibbi_ozet.
--
--  Uc tablo ve ucu de AYRI SORUNUN cevabi:
--
--    * recete / recete_satir - BU MUAYENEDE yazilan ilaclar (belge niteligi:
--      imzalanir, Medula'ya gider, degistirilemez).
--    * hasta_ilac            - hastanin SU ANDA kullandigi ilaclar (kumulatif;
--      recetelerden ve hasta beyanindan beslenir).
--    * hasta_alerji          - etken madde bazli alerji kaydi.
--
--  Ikisini birlestirmek cazip gorunur ("recete satirlari zaten ilac listesi")
--  ama yanlistir: hasta baska kurumdan aldigi ilaci da kullanir, bizim
--  yazdigimizin bir kismini kullanmaz. Etkilesim kontrolu KULLANILAN ilaca
--  bakmali, yazilana degil.
--
--  ALERJI ETKEN MADDE BAZLIDIR, barkod bazli degil: "Augmentin alerjisi"
--  kaydi hastaya baska markali amoksisilin yazilmasini engellemezdi.
--
--  MEDULA KAPISI ACIK DEGIL: recete yerel olarak yazilir ve imzalanir,
--  gonderim kuyruga girer (durum 2 imzali -> 3 Medula kabul). Kapiyi
--  beklemek muayene modulunu recetesiz birakirdi.
-- ============================================================================

create table if not exists public.recete (
    id             integer primary key generated by default as identity,
    muayene_id     integer     not null references public.muayene(id) on delete cascade,
    hasta_id       integer     not null references public.taraf(id),
    hekim_id       integer,
    -- Medula e-recete numarasi; yerel recetede bos kalir.
    recete_no      varchar(20) not null default '',
    -- 0 normal · 1 kirmizi · 2 yesil · 3 mor · 4 turuncu (ilac.recete_turu ile ayni)
    tur            smallint    not null default 0,
    aciklama       varchar(200) not null default '',
    imza_zamani    timestamp,
    imza_hash      varchar(64) not null default '',
    medula_gonderim timestamp,
    medula_sonuc   varchar(200) not null default '',
    -- 1 taslak · 2 imzali · 3 Medula kabul · 4 iptal
    durum          smallint    not null default 1,
    enabiz_durum   smallint    not null default 0,
    sube_id        integer     not null default 0,
    ekleyen        integer     not null default 0,
    ekleme_tarihi  timestamp   not null default now(),
    degistiren     integer     not null default 0,
    degistirme_tarihi timestamp
);
create index if not exists ix_recete_muayene on public.recete(muayene_id);
create index if not exists ix_recete_hasta on public.recete(hasta_id, ekleme_tarihi desc);

create table if not exists public.recete_satir (
    id            integer primary key generated by default as identity,
    recete_id     integer     not null references public.recete(id) on delete cascade,
    ilac_barkod   varchar(20) not null,
    -- Ad KOPYALANIR: katalog guncellenince eski recetenin metni degismemeli
    --   (recete bir belgedir, tarihte donmus olmali).
    ilac_ad       varchar(200) not null default '',
    doz           varchar(20) not null default '',
    periyot       varchar(20) not null default '',
    kullanim_sekli smallint   not null default 0,
    sure_gun      smallint    not null default 0,
    kutu          smallint    not null default 1,
    aciklama      varchar(200) not null default '',
    -- Uyari GECILDIYSE metni burada kalir: hekimin neyi gorup gectigini
    --   sonradan bilmek, uyariyi hic gostermemekten daha onemli.
    etkilesim_uyari varchar(200) not null default '',
    sira          smallint    not null default 0,
    ekleyen       integer     not null default 0,
    ekleme_tarihi timestamp   not null default now(),
    degistiren    integer     not null default 0,
    degistirme_tarihi timestamp
);
create index if not exists ix_recete_satir_recete on public.recete_satir(recete_id, sira);

-- --------------------------------------------------------- hasta alerji ----
create table if not exists public.hasta_alerji (
    id            integer     primary key generated by default as identity,
    hasta_id      integer     not null references public.taraf(id) on delete cascade,
    -- 1 ilac · 2 gida · 3 cevresel · 4 lateks · 5 kontrast
    tur           smallint    not null default 1,
    etken         varchar(200) not null default '',
    -- ETKEN MADDE KODU kontrolun asil anahtari: marka adi uzerinden kontrol,
    --   ayni etkeni tasiyan baska markayi kacirirdi.
    etken_madde   varchar(200) not null default '',
    reaksiyon     varchar(200) not null default '',
    -- 1 hafif · 2 orta · 3 siddetli · 4 anafilaksi
    siddet        smallint    not null default 1,
    -- 1 hasta beyani · 2 hekim · 3 e-Nabiz
    kaynak        smallint    not null default 1,
    dogrulandi    smallint    not null default 0,
    kayit_muayene_id integer,
    aktif         smallint    not null default 1,
    ekleyen       integer     not null default 0,
    ekleme_tarihi timestamp   not null default now(),
    degistiren    integer     not null default 0,
    degistirme_tarihi timestamp
);
create index if not exists ix_hasta_alerji_hasta
    on public.hasta_alerji(hasta_id) where aktif = 1;

-- ----------------------------------------------------------- hasta ilac ----
create table if not exists public.hasta_ilac (
    id             integer     primary key generated by default as identity,
    hasta_id       integer     not null references public.taraf(id) on delete cascade,
    ilac_barkod    varchar(20) not null default '',
    ilac_ad        varchar(200) not null default '',
    etken_madde    varchar(200) not null default '',
    doz            varchar(20) not null default '',
    periyot        varchar(20) not null default '',
    baslangic      date,
    bitis          date,
    recete_satir_id integer,
    -- 1 recete (bizden) · 2 hasta beyani · 3 e-Nabiz · 4 dis kurum
    kaynak         smallint    not null default 1,
    -- 1 duzenli · 2 araliki · 3 birakmis
    uyum           smallint    not null default 1,
    aktif          smallint    not null default 1,
    ekleyen        integer     not null default 0,
    ekleme_tarihi  timestamp   not null default now(),
    degistiren     integer     not null default 0,
    degistirme_tarihi timestamp
);
create index if not exists ix_hasta_ilac_hasta
    on public.hasta_ilac(hasta_id) where aktif = 1;

-- ---------------------------------------------------------------------------
--  ALERJI KONTROLU
--
--  Etken madde metinleri kataloglarda serbest yazilmis olabiliyor ("AMOKSISILIN
--  TRIHIDRAT" / "amoksisilin"); bu yuzden karsilastirma KUCUK HARF + ICEREN
--  seklinde yapilir. Yanlis pozitif (gereksiz uyari) yanlis negatife
--  (kacirilmis alerji) yeglenir - hekim uyariyi okuyup gecebilir.
-- ---------------------------------------------------------------------------
create or replace function public.fn_ilac_alerji_kontrol(p_hasta_id integer,
                                                         p_barkod varchar)
returns table (alerji_id integer, etken varchar, siddet smallint, reaksiyon varchar)
language sql stable as $$
    select a.id, a.etken, a.siddet, a.reaksiyon
      from public.hasta_alerji a
      join public.ilac i on i.barkod = p_barkod
     where a.hasta_id = p_hasta_id
       and a.aktif = 1
       and a.tur = 1
       and i.etken_madde <> ''
       and (
            (a.etken_madde <> '' and lower(i.etken_madde) like '%' || lower(a.etken_madde) || '%')
         or (a.etken_madde <> '' and lower(a.etken_madde) like '%' || lower(i.etken_madde) || '%')
         or (a.etken <> '' and lower(i.ad) like '%' || lower(a.etken) || '%')
       );
$$;

comment on function public.fn_ilac_alerji_kontrol(integer, varchar) is
    'Hastanin alerjileriyle ilacin etken maddesini karsilastirir (413). Yanlis pozitif yeglenir.';
