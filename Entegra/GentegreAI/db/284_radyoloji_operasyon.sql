-- 284: RADYOLOJİ — OPERASYON TABLOLARI (Faz 2).
--
-- Kritik bulgu bildirimi, sonuç teslimi ve yapılandırılmış alan tanımları.
-- Üçü de "raporu yazdık, bitti" varsayımının açıkta bıraktığı yerleri kapatır.

-- ========================================================== kritik bulgu ====
-- Hayatı tehdit eden bulgu (kanama, pnömotoraks, pulmoner emboli…) rapora
-- yazmakla bitmez: isteyen hekime/hastaya HABER VERİLDİĞİ kanıtlanabilir
-- olmalıdır. "Söyledim" iddiası kayıt yoksa savunulamaz.
create table if not exists public.radyoloji_kritik_bulgu (
  id             integer generated by default as identity primary key,
  istem_id       integer not null references public.radyoloji_istem(id) on delete cascade,
  rapor_id       integer references public.radyoloji_rapor(id) on delete set null,
  bulgu          varchar(300) not null default '',
  -- Kime, hangi yolla, ne zaman.
  bildiren_id    integer references public.taraf(id),
  bildirilen_id  integer references public.taraf(id),
  bildirilen_ad  varchar(120) not null default '',      -- kayıtlı olmayan kişi
  yol            smallint not null default 1,           -- 1 telefon · 2 SMS · 3 yüz yüze · 4 e-posta
  bildirim_zamani timestamp not null default now()::timestamp,
  geri_bildirim  varchar(300) not null default '',      -- karşı tarafın yanıtı
  ekleyen        integer not null default 0,
  ekleme_tarihi  timestamp not null default now()::timestamp
);
comment on table public.radyoloji_kritik_bulgu is
  'Kritik bulgu bildirimi (284): kime, hangi yolla, ne zaman haber verildi.';
create index if not exists ix_rad_kritik_istem on public.radyoloji_kritik_bulgu (istem_id);

-- İstemde "kritik bulgu var" bayrağı: rapor onayı buna bakar.
alter table public.radyoloji_istem add column if not exists kritik smallint not null default 0;
comment on column public.radyoloji_istem.kritik is
  'Kritik bulgu var (284). Bildirim kaydı olmadan rapor onaylanamaz.';

create or replace function public.fn_radyoloji_rapor_onaylanabilir(p_rapor_id integer)
returns text
language plpgsql stable as $$
declare
  r       record;
  v_adet  integer;
begin
  select rp.id, rp.durum, rp.kilit, rp.istem_id, i.kritik
    into r
    from public.radyoloji_rapor rp
    join public.radyoloji_istem i on i.id = rp.istem_id
   where rp.id = p_rapor_id;
  if not found then return 'Rapor bulunamadı.'; end if;

  if r.kilit = 1 then
    return 'Rapor onaylanmış ve kilitli; düzeltme ek rapor (addendum) olarak yazılır.';
  end if;

  -- Şablonda ZORUNLU işaretli bölüm boş kalamaz.
  select count(*) into v_adet
    from public.radyoloji_rapor_bolum b
    join public.radyoloji_rapor rp on rp.id = b.rapor_id
    left join public.radyoloji_sablon_bolum sb
           on sb.sablon_id = rp.sablon_id and sb.baslik = b.baslik
   where b.rapor_id = p_rapor_id
     and coalesce(sb.zorunlu, 0) = 1
     and btrim(coalesce(b.metin, '')) = '';
  if v_adet > 0 then
    return 'Zorunlu bölümler boş: rapor onaya gönderilemez.';
  end if;

  -- KRİTİK BULGU: işaretliyse bildirim kaydı ŞART.
  if coalesce(r.kritik, 0) = 1 then
    select count(*) into v_adet
      from public.radyoloji_kritik_bulgu k
     where k.istem_id = r.istem_id;
    if v_adet = 0 then
      return 'Kritik bulgu bildirimi kaydedilmeden rapor onaylanamaz.';
    end if;
  end if;

  return '';                                   -- boş = onaylanabilir
end $$;

comment on function public.fn_radyoloji_rapor_onaylanabilir(integer) is
  'Rapor onay ön koşulları (284): kilit, zorunlu bölümler, kritik bulgu bildirimi.';

-- ============================================================ sonuç teslimi ==
-- Görüntüleme merkezinde vazgeçilmez: raporu/CD'yi kim, ne zaman, hangi
-- kimlikle aldı. Hasta yakınına teslimde yakınlık da kayda geçer.
create table if not exists public.radyoloji_teslim (
  id             integer generated by default as identity primary key,
  istem_id       integer not null references public.radyoloji_istem(id) on delete cascade,
  rapor_id       integer references public.radyoloji_rapor(id) on delete set null,
  tur            smallint not null default 1,           -- rad.teslim_turu
  teslim_zamani  timestamp not null default now()::timestamp,
  teslim_eden_id integer references public.taraf(id),
  alan_ad        varchar(120) not null default '',
  alan_yakinlik  varchar(60)  not null default '',
  kimlik_dogrulandi smallint not null default 0,
  aciklama       varchar(300) not null default '',
  ekleyen        integer not null default 0,
  ekleme_tarihi  timestamp not null default now()::timestamp
);
comment on table public.radyoloji_teslim is
  'Sonuç teslim kaydı (284): kim, ne zaman, hangi ortamda aldı.';
create index if not exists ix_rad_teslim_istem on public.radyoloji_teslim (istem_id);

-- ==================================================== yapılandırılmış alanlar ==
-- BI-RADS / TI-RADS / Pfirrmann gibi skorların TANIMI şablonda, DEĞERİ raporda
-- (radyoloji_rapor_alan). Seçenekler serbest metin bırakılırsa istatistik
-- çıkmaz: "BIRADS 4" ile "Bi-Rads IV" iki ayrı değer olur.
create table if not exists public.radyoloji_sablon_alan (
  id          integer generated by default as identity primary key,
  sablon_id   integer not null references public.radyoloji_sablon(id) on delete cascade,
  sira        smallint not null default 1,
  alan_kod    varchar(40) not null,                     -- birads, tirads, pfirrmann
  alan_ad     varchar(80) not null,
  tip         smallint not null default 1,              -- 1 liste · 2 sayı · 3 metin
  secenekler  varchar(400) not null default '',         -- "0|1|2|3|4A|4B|4C|5|6"
  zorunlu     smallint not null default 0,
  rapora_bas  smallint not null default 1
);
comment on table public.radyoloji_sablon_alan is
  'Şablonun yapılandırılmış alan tanımı (284) - değeri radyoloji_rapor_alan''da.';
create index if not exists ix_rad_sablon_alan on public.radyoloji_sablon_alan (sablon_id, sira);
