create table if not exists public.lab_tetkik (
    id             integer primary key generated by default as identity,
    -- Hizmet kartı 1:1: ücret/SUT/KDV oradan okunur. Boş olabilir - dış lab
    --   ya da henüz ücretlendirilmemiş tetkik de katalogda durabilmeli.
    hizmet_id      integer references public.hizmet(id),
    kod            varchar(20)  not null,
    ad             varchar(200) not null,
    kisa_ad        varchar(60)  not null default '',
    -- 1 biyokimya · 2 hematoloji · 3 hormon/immün · 4 mikrobiyoloji ·
    -- 5 genetik · 6 idrar · 7 koagülasyon · 8 dış lab
    bolum          smallint not null default 1,
    -- 1 sayısal · 2 metin · 3 seçenekli · 4 kültür · 5 genetik · 6 panel
    tur            smallint not null default 1,
    numune_tipi    smallint not null default 0,
    tup_tipi       smallint not null default 0,
    numune_hacim_ml numeric(9,2) not null default 0,
    birim          varchar(20)  not null default '',
    ondalik        smallint not null default 2,
    loinc          varchar(12)  not null default '',
    skrs_tetkik_kod varchar(20) not null default '',
    yontem         varchar(100) not null default '',
    hedef_tat_dk   integer  not null default 0,
    acil_tat_dk    integer  not null default 0,
