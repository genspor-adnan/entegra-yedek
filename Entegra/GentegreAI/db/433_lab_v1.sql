-- ---------------------------------------------------------------------------
--  5) BARKOD - numune kimliği.
--
--  10 hane + kontrol hanesi (Luhn): cihaz ya da okuyucu bir haneyi yanlış
--  okursa kontrol hanesi tutmaz ve numune yanlış hastaya bağlanmaz.
-- ---------------------------------------------------------------------------
create or replace function public.fn_lab_barkod_kontrol(p_govde text)
returns integer language plpgsql immutable as $$
declare
    v_toplam integer := 0;
    v_basamak integer;
    v_cift boolean := true;
    i integer;
begin
    for i in reverse length(p_govde)..1 loop
        v_basamak := substr(p_govde, i, 1)::integer;
        if v_cift then
            v_basamak := v_basamak * 2;
            if v_basamak > 9 then v_basamak := v_basamak - 9; end if;
        end if;
        v_toplam := v_toplam + v_basamak;
        v_cift := not v_cift;
    end loop;
    return (10 - (v_toplam % 10)) % 10;
end $$;

create or replace function public.fn_lab_barkod_uret(p_sube_id integer default 0)
returns text language plpgsql as $$
declare
    v_govde text;
begin
    -- Gövde: yıl(2) + sayaç(8). Sayaç merkezi (fn_numara_sirada) - numara
    --   üretimi tek yerde kalsın.
    v_govde := to_char(current_date, 'YY') ||
               public.fn_numara_sirada(
                   'lab_numune.barkod|Y' || to_char(current_date, 'YYYY'),
                   'lab_numune', 'barkod',
                   'yil ' || to_char(current_date, 'YYYY'), 8, 1);
    return v_govde || public.fn_lab_barkod_kontrol(v_govde)::text;
end $$;

-- ---------------------------------------------------------------------------
--  6) REFERANS ARALIĞI SEÇİMİ ve BAYRAK
--
--  Hastanın yaşı ve cinsiyetine uyan EN DAR aralık seçilir: hem "0-150 yaş"
--  genel satırı hem "0-30 gün" yenidoğan satırı varsa yenidoğanınki kazanır.
-- ---------------------------------------------------------------------------
create or replace function public.fn_lab_referans(p_tetkik_id integer,
                                                  p_hasta_id integer,
                                                  p_tarih date default null)
returns public.lab_tetkik_referans language sql stable as $$
    select r.*
      from public.lab_tetkik_referans r
      left join public.taraf_hasta h on h.id = p_hasta_id
     where r.tetkik_id = p_tetkik_id
       and (r.cinsiyet = 0 or r.cinsiyet = coalesce(h.cinsiyet, 0))
       and (r.gecerli_bas is null or r.gecerli_bas <= coalesce(p_tarih, current_date))
       and coalesce(
             (coalesce(p_tarih, current_date) - h.dogum_tarihi::date), 0)
           between r.yas_alt_gun and r.yas_ust_gun
     order by (r.yas_ust_gun - r.yas_alt_gun) asc,   -- en dar aralik
              r.cinsiyet desc,                        -- cinsiyete ozel once
              r.sira asc, r.id asc
     limit 1;
$$;

/*
 * BAYRAK: L düşük · H yüksek · LL/HH panik. Panik sınırı önce REFERANS
 * satırından (yaşa özel), yoksa tetkik kartından okunur - yenidoğanın panik
 * eşiği erişkininkiyle aynı değildir.
 */
create or replace function public.fn_lab_bayrak(p_deger numeric,
                                                p_alt numeric, p_ust numeric,
                                                p_panik_alt numeric,
                                                p_panik_ust numeric)
returns text language sql immutable as $$
    select case
        when p_deger is null then ''
        when p_panik_alt is not null and p_deger <= p_panik_alt then 'LL'
        when p_panik_ust is not null and p_deger >= p_panik_ust then 'HH'
        when p_alt is not null and p_deger < p_alt then 'L'
        when p_ust is not null and p_deger > p_ust then 'H'
        else 'N'
    end;
$$;

