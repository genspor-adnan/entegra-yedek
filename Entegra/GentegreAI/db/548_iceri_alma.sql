-- =====================================================================
--  548_iceri_alma.sql
--  EXCEL'DEN İÇERİ ALMA: yükleme geçmişi + eşleme kuralları.
--
--  Kullanıcı: "jenerik excelden cari/stok/hizmet/... içe alımları yapay zekâ
--  destekli olacak şekilde önce mockup yap Ayarlar'a, sonra da yaz."
--  Mockup: Ekranlar/Ayarlar/excel_iceri_alma.html
--
--  İKİ TABLO:
--
--  1) `iceri_alma` — her yüklemenin İZİ. Mockup'taki "Geçmiş Yüklemeler"
--     sekmesi budur. Dosya adı, hedef, kullanılan eşleme ve satır sonuçları
--     burada durur; hangi kartların bu yüklemeyle yazıldığı `islem_log`
--     satırlarından okunur (log açıklamasına yükleme numarası yazılır).
--     Geri alma HENÜZ YOK - durum alanında yeri ayrıldı (4 = geri alındı),
--     çünkü geri alma "yükleme sonrası elle değişen kaydı atla" kuralını
--     gerektiriyor ve o ayrı bir iş.
--
--  2) `iceri_alma_kurali` — "bu eşlemeyi sakla" dediğinde doğan kural.
--     Aynı düzendeki dosya bir dahaki sefere kolon eşleme adımını atlar.
--     Tanıma ANAHTARI başlık imzasıdır: dosyadaki başlıkların normalize edilip
--     sıralanmış hâli. Dosya adına bakmak yanıltıcı olurdu (aynı ad, değişmiş
--     düzen); başlık imzası dosyanın gerçek biçimidir.
--
--  Eşleme jsonb: { "<excel başlığı>": "<kart alan adı>" }. Boş/eşlenmeyen
--  kolon YAZILMAZ - "— aktarma —" seçeneği anahtarın hiç olmamasıdır.
-- =====================================================================

create table if not exists public.iceri_alma (
    id            integer primary key generated by default as identity,
    hedef         varchar(40)  not null,          -- cari · stok · hizmet ...
    dosya_adi     varchar(200) not null default '',
    sayfa         varchar(120) not null default '',
    satir_sayisi  integer      not null default 0,
    eklenen       integer      not null default 0,
    guncellenen   integer      not null default 0,
    atlanan       integer      not null default 0,
    -- 1 tamam · 2 kısmi (atlanan var) · 3 hata · 4 geri alındı
    durum         smallint     not null default 1,
    esleme        jsonb        not null default '{}'::jsonb,
    mesaj         varchar(400) not null default '',
    sure_ms       integer      not null default 0,
    kullanici_id  integer      not null default 0,
    sube_id       integer,
    tarih         timestamp    not null default now()::timestamp
);

comment on table public.iceri_alma is
  'Excel içeri alma yüklemelerinin izi (548) - Ayarlar > İçeri Alma > Geçmiş Yüklemeler.';

create index if not exists ix_iceri_alma_tarih on public.iceri_alma (tarih desc);
create index if not exists ix_iceri_alma_hedef on public.iceri_alma (hedef, tarih desc);

create table if not exists public.iceri_alma_kurali (
    id            integer primary key generated by default as identity,
    ad            varchar(120) not null,
    hedef         varchar(40)  not null,
    -- Başlıkların normalize + sıralı hâli: dosyanın biçim parmak izi.
    baslik_imzasi text         not null default '',
    esleme        jsonb        not null default '{}'::jsonb,
    aktif         smallint     not null default 1,
    son_kullanim  timestamp,
    kullanici_id  integer      not null default 0,
    sube_id       integer,
    tarih         timestamp    not null default now()::timestamp
);

comment on table public.iceri_alma_kurali is
  'Kayıtlı kolon eşlemeleri (548): aynı düzendeki dosyada eşleme adımı atlanır.';

-- Aynı hedefte aynı imzadan İKİ kural olursa hangisinin uygulandığı
--   belirsizleşir - imza benzersiz.
create unique index if not exists ux_iceri_alma_kurali_imza
    on public.iceri_alma_kurali (hedef, baslik_imzasi)
 where baslik_imzasi <> '';
