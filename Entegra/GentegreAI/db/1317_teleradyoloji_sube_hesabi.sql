-- 1317 - TeleRadyoloji (Bakanlık) bağlantısı şube başına entegrasyon hesabı · kurum kimliği şube bazlı tek kaynak
--
-- Kullanıcı 12.11.2026: "teletıp ayarlarından da buraya taşınabilecek olan var mı" → mockup
-- Ekranlar/Ayarlar/entegrasyon_teletip.html ("her şube için ayrı teleradyoloji gönderimi olabilir", "teletıp yerine
-- TeleRadyoloji kullanalım") → "mockup uygula".
--
--   1) KURUM KİMLİĞİ ŞUBE BAZLI, TEK KAYNAK: kurum_profil'e skrs_kodu + bakanlik_ad (tesis_kodu zaten vardı).
--      fn_kurum_kimlik(şube): şubenin satırı → kurum geneli (şube 0) → eski yer (referans kurum.skrs_kodu; ad için şube
--      unvanı). TeleRadyoloji, Teleradyoloji teslimi, e-Nabız ve MEDULA buradan okur (C# tarafı).
--      Bugün iki yerde duran kodlar (kurum.skrs_kodu ↔ ENABIZ hesabının kurum_kodu; kurum_profil.tesis_kodu ↔ MEDULA
--      hesabının kurum_kodu) bir kez taşınır: profil boşsa eski değer yazılır; ikisi de dolu ve FARKLIYSA kendiliğinden
--      ezilmez, kurum_kimlik_cakisma tablosuna yazılır (ekranda "çakışma raporu").
--   2) TELERADYOLOJI ENTEGRASYON HESABI: şube başına satır (şube boş = kurum geneli), test / canlı ayrı. Alanlar:
--      uygulama_kodu = firma kodu, url = Mirth K1 HL7 adresi, ayarlar = xdsAdres · dozAdres · encoding · subeNo ·
--      xdsHastaOid · mirthHesapId. teletip.* ayarları varsa kurum geneli satıra taşınır (aktif = teletip.aktif).
--      Eski anahtarlar silinmez - hiç TELERADYOLOJI satırı yokken eski davranış (geri uyum).
--   3) fn_teletip_hesap(şube) → gönderim hesabı (şube satırı → kurum geneli; canlı önce). fn_teletip_hesap_ayar(şube) →
--      C#'ın okuduğu tek jsonb (eski anahtarlara düşer). fn_teletip_aktif() = aktif hesap var mı (satır yoksa eski
--      anahtar). Kuyruk kapısı (tg_teletip_gonderim_dis_is): hesap modeli kullanılıyorsa şubenin hesabı yoksa satır
--      AÇILMAZ ("Ataşehir'de hesap yok → istemleri kuyruğa girmez").
--
-- Tekrar çalıştırılabilir.
\set ON_ERROR_STOP on
begin;

-- ------------------------------------------------------------------ 1) kurum kimliği
alter table public.kurum_profil add column if not exists skrs_kodu   varchar(20)  not null default '';
alter table public.kurum_profil add column if not exists bakanlik_ad varchar(200) not null default '';
comment on column public.kurum_profil.skrs_kodu is '1317: SKRS kurum kodu (Bakanlık) - şube bazlı tek kaynak (TeleRadyoloji ORC-21 / KOS, e-Nabız).';
comment on column public.kurum_profil.bakanlik_ad is '1317: Bakanlık''ta görünen ad (ORC-21 kurum adı, KOS InstitutionName). Boş = şube unvanı.';

create table if not exists public.kurum_kimlik_cakisma (
    id            integer generated by default as identity primary key,
    sube_id       integer      not null default 0,
    alan          varchar(30)  not null,            -- skrs | tesis
    profil_degeri varchar(50)  not null default '',
    eski_kaynak   varchar(60)  not null default '',
    eski_deger    varchar(50)  not null default '',
    cozuldu       smallint     not null default 0,
    ekleme_tarihi timestamptz  not null default now()
);
comment on table public.kurum_kimlik_cakisma is
  '1317: kurum kimliği tek kaynağa taşınırken iki yerde FARKLI bulunan kodlar - kendiliğinden ezilmez, ekranda seçilir.';

create or replace function public.fn_kurum_kimlik(p_sube integer)
returns table (sube_id integer, ad varchar, skrs varchar, tesis varchar)
language sql stable as $$
  select coalesce(p_sube, 0),
         coalesce(nullif(ks.bakanlik_ad, ''), nullif(k0.bakanlik_ad, ''), nullif(sb.unvan, ''), sb.ad,
                  (select coalesce(nullif(s1.unvan, ''), s1.ad) from public.sube s1 where s1.aktif = 1 order by s1.id limit 1), '')::varchar,
         coalesce(nullif(ks.skrs_kodu, ''), nullif(k0.skrs_kodu, ''),
                  (select r.deger from public.referans r where r.anahtar = 'kurum.skrs_kodu'), '')::varchar,
         coalesce(nullif(ks.tesis_kodu, ''), nullif(k0.tesis_kodu, ''), '')::varchar
    from (select 1) z
    left join public.kurum_profil ks on ks.sube_id = coalesce(p_sube, 0) and coalesce(p_sube, 0) <> 0
    left join public.kurum_profil k0 on k0.sube_id = 0
    left join public.sube sb on sb.id = p_sube
$$;
comment on function public.fn_kurum_kimlik(integer) is
  '1317: şubenin Bakanlık kimliği (ad, SKRS, MEDULA tesis) - şube satırı → kurum geneli → eski yer. Tek kaynak.';

-- Taşıma: profil boşsa eski değerler; farklıysa çakışma kaydı.
do $$
declare
  v_skrs_ref varchar := coalesce((select deger from public.referans where anahtar = 'kurum.skrs_kodu'), '');
  r record;
  v_profil varchar;
  v_tasinan int := 0; v_cakisan int := 0;
begin
  if exists (select 1 from public.kurum_profil where sube_id = 0) then
    update public.kurum_profil set skrs_kodu = v_skrs_ref where sube_id = 0 and skrs_kodu = '' and v_skrs_ref <> '';
    get diagnostics v_tasinan = row_count;
  end if;
  -- ENABIZ (SKRS) ve MEDULA (tesis) hesaplarındaki kodlar
  for r in select e.kod, coalesce(e.sube_id, 0) as sube, btrim(e.kurum_kodu) as kod_degeri
             from public.entegrasyon_hesap e
            where e.kod in ('ENABIZ', 'MEDULA') and btrim(coalesce(e.kurum_kodu, '')) <> '' and e.aktif = 1
  loop
    if r.kod = 'ENABIZ' then
      select k.skrs into v_profil from public.fn_kurum_kimlik(r.sube) k;
      if coalesce(v_profil, '') = '' then
        update public.kurum_profil set skrs_kodu = r.kod_degeri where sube_id = r.sube and skrs_kodu = '';
        if found then v_tasinan := v_tasinan + 1; end if;
      elsif v_profil <> r.kod_degeri and not exists (select 1 from public.kurum_kimlik_cakisma c
             where c.sube_id = r.sube and c.alan = 'skrs' and c.eski_deger = r.kod_degeri and c.cozuldu = 0) then
        insert into public.kurum_kimlik_cakisma (sube_id, alan, profil_degeri, eski_kaynak, eski_deger)
        values (r.sube, 'skrs', v_profil, 'Entegrasyon › ENABIZ kurum kodu', r.kod_degeri);
        v_cakisan := v_cakisan + 1;
      end if;
    else
      select k.tesis into v_profil from public.fn_kurum_kimlik(r.sube) k;
      if coalesce(v_profil, '') = '' then
        update public.kurum_profil set tesis_kodu = r.kod_degeri where sube_id = r.sube and coalesce(tesis_kodu, '') = '';
        if found then v_tasinan := v_tasinan + 1; end if;
      elsif v_profil <> r.kod_degeri and not exists (select 1 from public.kurum_kimlik_cakisma c
             where c.sube_id = r.sube and c.alan = 'tesis' and c.eski_deger = r.kod_degeri and c.cozuldu = 0) then
        insert into public.kurum_kimlik_cakisma (sube_id, alan, profil_degeri, eski_kaynak, eski_deger)
        values (r.sube, 'tesis', v_profil, 'Entegrasyon › MEDULA kurum / tesis kodu', r.kod_degeri);
        v_cakisan := v_cakisan + 1;
      end if;
    end if;
  end loop;
  raise notice '1317 kurum kimliği: taşınan %, çakışma %', v_tasinan, v_cakisan;
end $$;

-- ------------------------------------------------------------------ 2) TELERADYOLOJI hesabı (eski ayarlardan)
do $$
declare
  v_aktif varchar := coalesce((select deger from public.referans where anahtar = 'teletip.aktif'), '0');
  v_hl7   varchar := coalesce((select deger from public.referans where anahtar = 'teletip.hl7_adres'), '');
  v_xds   varchar := coalesce((select deger from public.referans where anahtar = 'teletip.xds_adres'), '');
  v_doz   varchar := coalesce((select deger from public.referans where anahtar = 'teletip.doz_adres'), '');
  v_firma varchar := coalesce((select deger from public.referans where anahtar = 'teletip.firma_kodu'), '');
begin
  if not exists (select 1 from public.entegrasyon_hesap where kod = 'TELERADYOLOJI')
     and (v_aktif = '1' or v_hl7 <> '' or v_xds <> '' or v_doz <> '' or v_firma <> '') then
    insert into public.entegrasyon_hesap (kod, ad, sube_id, test_mi, aktif, uygulama_kodu, url, ayarlar, aciklama)
    values ('TELERADYOLOJI', 'TeleRadyoloji - Kurum geneli', null, 0, case when v_aktif = '1' then 1 else 0 end, v_firma, v_hl7,
            jsonb_build_object(
              'xdsAdres', v_xds, 'dozAdres', v_doz,
              'encoding', coalesce((select deger from public.referans where anahtar = 'teletip.encoding'), 'UTF8'),
              'subeNo', coalesce((select deger from public.referans where anahtar = 'teletip.sube_no'), '1'),
              'xdsHastaOid', coalesce((select deger from public.referans where anahtar = 'teletip.xds_hasta_oid'), '1.3.6.1.4.1.21367.13.20.3000')),
            '1317: Teletıp Ayarları''ndan (teletip.*) taşındı.');
    raise notice '1317: TeleRadyoloji kurum geneli hesabı eski ayarlardan açıldı (aktif %).', v_aktif;
  end if;
end $$;

-- ------------------------------------------------------------------ 3) çözüm fonksiyonları
create or replace function public.fn_teletip_hesap(p_sube integer)
returns integer language sql stable as $$
  select e.id from public.entegrasyon_hesap e
   where e.kod = 'TELERADYOLOJI' and e.aktif = 1
     and (e.sube_id is null or (coalesce(p_sube, 0) <> 0 and e.sube_id = p_sube))
   order by (e.sube_id is null), e.test_mi, e.id
   limit 1
$$;
comment on function public.fn_teletip_hesap(integer) is
  '1317: şubenin TeleRadyoloji gönderim hesabı - şubenin aktif satırı → kurum geneli; canlı (test_mi 0) önce.';

create or replace function public.fn_teletip_hesap_modeli()
returns boolean language sql stable as $$
  select exists (select 1 from public.entegrasyon_hesap where kod = 'TELERADYOLOJI')
$$;

-- C#'ın okuduğu tek ayar kümesi: hesap modeli varsa şubenin hesabı (yoksa null), yoksa eski anahtarlar.
create or replace function public.fn_teletip_hesap_ayar(p_sube integer)
returns jsonb language sql stable as $$
  select case
    when public.fn_teletip_hesap_modeli() then (
      select jsonb_build_object(
               'HesapId', e.id, 'HesapAd', e.ad, 'Test', e.test_mi = 1,
               'FirmaKodu', coalesce(e.uygulama_kodu, ''), 'Hl7Adres', coalesce(e.url, ''),
               'XdsAdres', coalesce(e.ayarlar->>'xdsAdres', ''), 'DozAdres', coalesce(e.ayarlar->>'dozAdres', ''),
               'Encoding', coalesce(nullif(e.ayarlar->>'encoding', ''), 'UTF8'),
               'SubeNo', coalesce(nullif(e.ayarlar->>'subeNo', ''), '1'),
               'XdsHastaOid', coalesce(nullif(e.ayarlar->>'xdsHastaOid', ''), '1.3.6.1.4.1.21367.13.20.3000'),
               'MirthHesapId', coalesce(e.ayarlar->>'mirthHesapId', ''))
        from public.entegrasyon_hesap e where e.id = public.fn_teletip_hesap(p_sube))
    else (
      select case when coalesce(max(deger) filter (where anahtar = 'teletip.aktif'), '0') = '1' then
        jsonb_build_object(
          'HesapId', 0, 'HesapAd', 'Teletıp Ayarları (eski)', 'Test', false,
          'FirmaKodu', coalesce(max(deger) filter (where anahtar = 'teletip.firma_kodu'), ''),
          'Hl7Adres', coalesce(max(deger) filter (where anahtar = 'teletip.hl7_adres'), ''),
          'XdsAdres', coalesce(max(deger) filter (where anahtar = 'teletip.xds_adres'), ''),
          'DozAdres', coalesce(max(deger) filter (where anahtar = 'teletip.doz_adres'), ''),
          'Encoding', coalesce(nullif(max(deger) filter (where anahtar = 'teletip.encoding'), ''), 'UTF8'),
          'SubeNo', coalesce(nullif(max(deger) filter (where anahtar = 'teletip.sube_no'), ''), '1'),
          'XdsHastaOid', coalesce(nullif(max(deger) filter (where anahtar = 'teletip.xds_hasta_oid'), ''), '1.3.6.1.4.1.21367.13.20.3000'),
          'MirthHesapId', '') end
        from public.referans where anahtar like 'teletip.%')
  end
$$;
comment on function public.fn_teletip_hesap_ayar(integer) is
  '1317: şubenin TeleRadyoloji ayarı (jsonb) - TELERADYOLOJI hesabından; hesap modeli yoksa eski teletip.* anahtarları. null = şubede kapalı.';

create or replace function public.fn_teletip_aktif()
returns boolean language sql stable as $$
  select case when public.fn_teletip_hesap_modeli()
              then exists (select 1 from public.entegrasyon_hesap where kod = 'TELERADYOLOJI' and aktif = 1)
              else coalesce((select deger from public.referans where anahtar = 'teletip.aktif'), '0') = '1' end
$$;
comment on function public.fn_teletip_aktif() is
  '1317: herhangi bir şubede TeleRadyoloji açık mı (aktif TELERADYOLOJI hesabı; hesap modeli yoksa teletip.aktif). Şube kapısı ayrıca kuyrukta.';

-- Kuyruk kapısı: dış kurum işi (1315) + şubenin hesabı yoksa satır açılmaz (hesap modelinde).
create or replace function public.tg_teletip_gonderim_dis_is()
returns trigger language plpgsql as $$
begin
  if public.fn_teletip_dis_is(new.istem_id) then return null; end if;
  if public.fn_teletip_hesap_modeli() and public.fn_teletip_hesap(new.sube_id) is null then return null; end if;
  return new;
end $$;

