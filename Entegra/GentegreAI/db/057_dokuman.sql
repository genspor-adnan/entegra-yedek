\set ON_ERROR_STOP on

create table if not exists public.dokuman (
    id                  integer generated by default as identity primary key,
    kaynak              character varying(20) not null,   -- 'taraf' | 'stok' (whitelist backend'de)
    kaynak_id           integer not null,
    ad                  character varying(200) not null default '',
    content_type        character varying(100) not null,
    boyut               integer not null default 0,
    hash                character varying(64) not null default '',
    icerik              bytea not null,
    sira                smallint not null default 0,
    varsayilan          smallint not null default 0,       -- sadece image/* satirlarda anlamli
    sube_id             integer not null references public.sube(id),
    ekleyen             integer not null default 0,
    ekleme_tarihi       timestamp not null default now()::timestamp,
    degistiren          integer not null default 0,
    degistirme_tarihi   timestamp
);

create index if not exists ix_dokuman_kaynak on public.dokuman (kaynak, kaynak_id);
-- Bir (kaynak, kaynak_id) icin ayni anda SADECE BIR varsayilan olabilir.
create unique index if not exists ux_dokuman_varsayilan
    on public.dokuman (kaynak, kaynak_id) where varsayilan = 1;

comment on table public.dokuman is
  'Genel resim/doküman deposu (kaynak+kaynak_id polimorfik) - coklu satir + tek varsayilan (eski IMAJ deseni). taraf.resim/stok.resim varsayilanin kucuk kapak-cache''i (VarsayilanResimTazele mantigi).';
