--  Gentegre AI — PORTAL DAVETİ (SMS / e-posta bağlantısı)
--  822_portal_daveti.sql
--
--  Kullanıcı: *"hasta davetini de yap"* (SMS kanalı canlıda doğrulandı).
--
--  ============ NEDEN DAVET ==========================================
--  819'daki "Portal Erişimi" hesabı PAROLASIZ açıyor ve kişi giriş ekranından
--  kendi parolasını koyuyor. Dış hekim ve kurum temsilcisinde bu yeterli:
--  ikisi de kurumla temas hâlinde, kullanıcı kodunu telefonda söyleyebilirsin.
--  HASTADA değil - hastaya "portalımız var, şu kodla gir" demek, kodu da
--  yöntemi de anlatmak demektir; pratikte kimse girmez.
--
--  Davet bunu tersine çevirir: kuruma değil HASTAYA bir bağlantı gider,
--  bağlantı kendi hesabını açar.
--
--  ============ JETON DEPODA DÜZ DURAMAZ =============================
--  Bağlantıdaki jeton, o hesaba giriş hakkıdır. Düz saklanırsa veritabanını
--  okuyan herkes (yedek dosyası dâhil) her hastanın portalına girebilirdi.
--  Saklanan SHA-256 ÖZETİ; gelen jeton özetlenip aranır. Yedekten okunan
--  özetle bağlantı üretilemez.
--
--  ============ ÜÇ SINIR =============================================
--    * SÜRE: varsayılan 48 saat (ayar). Süresiz bağlantı, telefonda sonsuza
--      kadar duran bir anahtardır.
--    * TEK KULLANIM: parola konduğu an davet kapanır.
--    * DENEME SINIRI: kimlik kanıtı (TCKN son 4) beş kez yanlış girilirse
--      davet iptal olur - 10.000 ihtimalli bir sayı sınırsız denenebilseydi
--      bağlantıyı ele geçiren kişi kaba kuvvetle açardı.
-- ============================================================================
