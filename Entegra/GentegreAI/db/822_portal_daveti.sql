-- --------------------------------------------------------------- tablo ----
create table if not exists public.portal_davet (
    id             bigint      primary key generated by default as identity,
    taraf_id       integer     not null references public.taraf(id) on delete cascade,
    -- 1 SMS · 2 e-posta
    kanal          smallint    not null default 1,
    alici          varchar(120) not null default '',
    -- SHA-256 ÖZETİ (hex). Jetonun kendisi YALNIZ gönderilen bağlantıda olur.
    jeton_ozet     varchar(64) not null,
    -- 1 bekliyor · 2 kullanıldı · 3 iptal
    durum          smallint    not null default 1,
    gecerlilik     timestamp   not null,
    deneme         smallint    not null default 0,
    gonderim_id    bigint,
    gonderim_hata  varchar(300) not null default '',
    kullanim_zamani timestamp,
    kullanim_ip    varchar(45) not null default '',
    sube_id        integer     references public.sube(id),
    ekleyen        integer     not null default 0,
    ekleme_tarihi  timestamptz not null default now(),
    constraint ck_portal_davet_durum check (durum between 1 and 3),
    constraint ck_portal_davet_kanal check (kanal in (1, 2))
);

comment on table public.portal_davet is
  '822: portal davet bağlantısı - jeton ÖZETİ saklanır, süre + tek kullanım + '
  'deneme sınırı vardır.';

create unique index if not exists ux_portal_davet_jeton on public.portal_davet (jeton_ozet);
create index if not exists ix_portal_davet_taraf on public.portal_davet (taraf_id, id desc);
-- Zamanı gelen temizlik için: açık ve süresi geçmiş davetler.
create index if not exists ix_portal_davet_acik on public.portal_davet (gecerlilik)
 where durum = 1;

-- ------------------------------------------------------- yeni davet kuralı ----
-- AYNI KİŞİYE İKİNCİ DAVET ESKİSİNİ KAPATIR: iki geçerli bağlantı dolaşması,
--   "hangisi geçerli" sorusunu doğurur ve iptal edilen birinin hâlâ
--   çalışmasına yol açar.
create or replace function public.tg_portal_davet_tekil()
returns trigger
language plpgsql
as $$
begin
    update public.portal_davet
       set durum = 3
     where taraf_id = new.taraf_id and durum = 1 and id <> new.id;
    return new;
end $$;

drop trigger if exists tg_portal_davet_tekil on public.portal_davet;
create trigger tg_portal_davet_tekil
    after insert on public.portal_davet
    for each row execute function public.tg_portal_davet_tekil();

-- --------------------------------------------------------------- görünüm ----
create or replace view public.v_portal_davet as
select d.id,
       d.taraf_id,
       coalesce(t.unvan, '')                        as kisi,
       d.kanal,
       case d.kanal when 2 then 'E-posta' else 'SMS' end as kanal_adi,
       d.alici,
       d.durum,
       case d.durum when 2 then 'Kullanıldı'
                    when 3 then 'İptal'
                    when 1 then case when d.gecerlilik < now()::timestamp
                                     then 'Süresi doldu' else 'Bekliyor' end
       end                                          as durum_adi,
       d.gecerlilik,
       d.deneme,
       d.gonderim_hata,
       d.kullanim_zamani,
       d.ekleme_tarihi,
       d.sube_id,
       case when d.durum = 1 and d.gecerlilik < now()::timestamp then 'uyari'
            when d.durum = 3 then 'pasif'
            when d.gonderim_hata <> '' then 'kritik'
            else '' end                             as satir_rengi
  from public.portal_davet d
  left join public.taraf t on t.id = d.taraf_id;

comment on view public.v_portal_davet is
  '822: gönderilen portal davetleri - durum, kanal, deneme sayısı.';

do $$
declare v_url text;
begin
    select deger into v_url from public.referans where anahtar = 'portal.taban_url';
    if coalesce(v_url, '') = '' then
        raise notice '822 tamam: portal_davet hazir. DIKKAT - portal.taban_url BOS, '
                     'davet gonderilemez (baglanti adresi bilinmiyor).';
    else
        raise notice '822 tamam: portal_davet hazir, taban adres %.', v_url;
    end if;
end $$;

