--  zil paneli, Hatırlatmalarım listesi, hatırlatma kartı (Genel · Tekrar &
--  uyarı · Bağlı kayıt · Paylaşım · Geçmiş), kayıttan hızlı hatırlatma,
--  zamanı gelince açılır uyarı.
--
--  KİŞİYE ÖZEL: satırı sahibi ve paylaştıkları görür (uçlarda süzülür; yetki
--  kodu yok - kendi kaydı). Başkasına iş vermek Görev'dir; hasta notu Kendime
--  Not'tur.
--
--  ZAMAN timestamptz (UTC saklanır, şube diliminde girilir/gösterilir - 1097).
--  UYARI: zaman - uyar_dk geçince HatirlatmaIscisi SMS / e-posta kanallarını
--  bildirim kuyruğuna koyar (kaynak_tur 50) ve uyari_gonderildi'yi damgalar;
--  uygulama içi uyarı aynı kayıttan okunur (zil + açılır uyarı).
--  TEKRAR: tamamlanınca bir sonraki zaman kurulur, satır açık kalır.
--  PAYLAŞIM: 0 yalnız ben · 1 seçtiklerim (hatirlatma_paylasim) · 2 birim.
--  herkes_kapatir = 1: biri tamamlayınca herkes için kapanır; 0: her kişi
--  kendi işaretini koyar (sahip: sahip_tamam, paylaşılan: paylasim.tamamlandi).
--  İdempotent.
-- =============================================================================

begin;

create table if not exists public.hatirlatma (
    id                   integer generated by default as identity primary key,
    sahip_id             integer      not null,
    baslik               varchar(200) not null,
    notu                 varchar(2000) not null default '',
    zaman                timestamptz  not null,
    uyar_dk              integer      not null default 15,   -- kaç dakika önce uyarılsın (0 = zamanında)
    oncelik              smallint     not null default 2,    -- 1 düşük · 2 normal · 3 yüksek
    renk                 smallint     not null default 0,    -- 0 yok · 1 kırmızı · 2 sarı · 3 yeşil · 4 mavi
    etiket               varchar(60)  not null default '',
    -- 0 yok · 1 her gün · 2 haftalık · 3 aylık · 4 yıllık · 5 iş günleri
    tekrar               smallint     not null default 0,
    tekrar_aralik        smallint     not null default 1,    -- her N gün / hafta / ay / yıl
    tekrar_gunler        smallint     not null default 0,    -- haftalıkta gün maskesi: 1 Pt · 2 Sa · 4 Ça ... 64 Pz
    tekrar_bitis         date,
    kanal_uygulama       smallint     not null default 1,
    kanal_sms            smallint     not null default 0,
    kanal_eposta         smallint     not null default 0,
    -- BAĞLI KAYIT: kart rotası (cari, hasta, personel, belge ...) + kayıt id + görünen ad.
    kaynak               varchar(40)  not null default '',
    kaynak_id            integer,
    kaynak_ad            varchar(200) not null default '',
    paylasim             smallint     not null default 0,
    paylasim_departman_id integer,
    herkes_kapatir       smallint     not null default 1,
    paylasilan_duzenler  smallint     not null default 0,
    durum                smallint     not null default 1,    -- 1 açık · 2 tamamlandı
    tamamlanma           timestamptz,
    sahip_tamam          timestamptz,
    uyari_gonderildi     timestamptz,
    ertele_sayisi        smallint     not null default 0,
    sube_id              integer      not null default 0,
    ekleyen              integer      not null default 0,
    ekleme_tarihi        timestamptz  not null default now(),
    degistiren           integer      not null default 0,
    degistirme_tarihi    timestamptz
);
create index if not exists ix_hatirlatma_sahip on public.hatirlatma (sahip_id, durum, zaman);
create index if not exists ix_hatirlatma_uyari on public.hatirlatma (zaman) where durum = 1 and uyari_gonderildi is null;
create index if not exists ix_hatirlatma_kaynak on public.hatirlatma (kaynak, kaynak_id) where kaynak_id is not null;
comment on table public.hatirlatma is
  'Kişisel hatırlatıcı (1139): sahibi ve paylaştıkları görür. zaman UTC; uyar_dk önce uyarı; tekrar tamamlanınca ilerler.';

create table if not exists public.hatirlatma_paylasim (
    id                integer generated by default as identity primary key,
    hatirlatma_id     integer     not null references public.hatirlatma(id) on delete cascade,
    kullanici_id      integer     not null,
    tamamlandi        timestamptz,
    unique (hatirlatma_id, kullanici_id)
);
create index if not exists ix_hatirlatma_paylasim_kul on public.hatirlatma_paylasim (kullanici_id);

create table if not exists public.hatirlatma_hareket (
    id                bigint generated by default as identity primary key,
    hatirlatma_id     integer     not null references public.hatirlatma(id) on delete cascade,
    zaman             timestamptz not null default now(),
    -- 1 oluşturuldu · 2 değiştirildi · 3 ertelendi · 4 uyarı gönderildi · 5 tamamlandı · 6 yeniden açıldı
    olay              smallint    not null,
    ayrinti           varchar(400) not null default '',
    kullanici_id      integer     not null default 0
);
create index if not exists ix_hatirlatma_hareket on public.hatirlatma_hareket (hatirlatma_id, zaman desc);

-- ------------------------------------------------------------ şablonlar --
insert into public.bildirim_sablon (kod, ad, kanal, konu, govde, degiskenler, durum, aciklama, ekleyen)
select v.kod, v.ad, v.kanal, v.konu, v.govde, v.degiskenler::jsonb, 1, v.aciklama, 0 from (values
    ('hatirlatma.kisisel', 'Kişisel hatırlatma (SMS)', 1::smallint, '',
     'Hatırlatma {{zaman}}: {{baslik}}{{kayit}}',
     '{"baslik":"Hatırlatma başlığı","zaman":"Tarih saat","kayit":"Bağlı kayıt (\" - Cari: ...\")","notu":"Not"}',
     'Kullanıcı › Hatırlatmalarım'),
    ('hatirlatma.kisisel.eposta', 'Kişisel hatırlatma (e-posta)', 2::smallint,
     'Hatırlatma: {{baslik}}',
     E'{{zaman}}\n\n{{baslik}}{{kayit}}\n\n{{notu}}',
     '{"baslik":"Hatırlatma başlığı","zaman":"Tarih saat","kayit":"Bağlı kayıt","notu":"Not"}',
     'Kullanıcı › Hatırlatmalarım'))
  as v(kod, ad, kanal, konu, govde, degiskenler, aciklama)
 where not exists (select 1 from public.bildirim_sablon s where s.kod = v.kod);

commit;
