-- 342: MESAJLAŞMA ŞEMASI (İletişim & AI › Mesajlar).
--
-- Mockup: `Ekranlar/umesajlar.html` (Delphi'deki UMESAJ / UMESAJSOHBET /
-- UMESAJUYE / UMESAJEK / UMESAJKAYIT karşılığı). 341'de menü ve yetki açıldı;
-- bu göç veriyi kurar.
--
-- Delphi şemasından farklar (bilinçli):
--   * SABİT / SESSİZ / FAVORİ / ARŞİV bayrakları SOHBETTE değil ÜYEDE:
--     "bu sohbeti ben sabitledim" kişiye özel bir tercihtir; sohbette
--     tutulunca bir kullanıcının sabitlemesi herkesin listesini değiştirirdi.
--   * OKUNDU bilgisi mesaj başına tutulmaz (mockup'ın kendi notu):
--     `mesaj_uye.son_okuma` damgası mesaj tarihinden büyükse mesaj o üye için
--     okunmuştur. Grupta en küçük `son_okuma` herkesin okuduğu sınırdır.
--     Mesaj başına satır, 200 kişilik grupta her mesaj için 200 satır demekti.
--   * MESAJLAR ŞUBELER ARASI: `sube_id` yok. Şube filtresi uygulanırsa
--     merkezdeki kullanıcı şubedeki meslektaşına yazamaz.
--   * Ek dosyalar jenerik doküman deposuna bağlanır (`dokuman`, kaynak =
--     'mesaj'); ayrı bir dosya tablosu açılmadı.
\set ON_ERROR_STOP on

-- --------------------------------------------------------------- sohbet ---
create table if not exists public.mesaj_sohbet (
    id            integer generated by default as identity primary key,
    -- 1 kişi (birebir), 2 grup.
    tip           smallint     not null default 1,
    -- Grup adı; kişi sohbetinde BOŞ - başlık karşı tarafın adıdır ve o ad
    --   değişince (evlilik, düzeltme) sohbet başlığı da kendiliğinden değişsin.
    ad            varchar(120) not null default '',
    aciklama      varchar(300) not null default '',
    olusturan     integer      not null default 0,
    ekleme_tarihi timestamp    not null default (now())::timestamp,
    -- Son mesajın zamanı: liste bu kolona göre sıralanır. Her mesajda
    --   tetikle güncellenir - sıralama için her sohbete alt sorgu atmak
    --   (n+1) listeyi kullanıcı sayısıyla birlikte yavaşlatırdı.
    son_mesaj_tarihi timestamp,
    durum         smallint     not null default 1   -- 1 açık, 2 kapatılmış
);

comment on table public.mesaj_sohbet is
  'Kurum ici sohbet (342): tip 1 kisi / 2 grup. Sube filtresi YOK.';

-- ------------------------------------------------------------------ üye ---
create table if not exists public.mesaj_uye (
    sohbet_id     integer   not null references public.mesaj_sohbet(id) on delete cascade,
    kullanici_id  integer   not null references public.taraf_kullanici(id),
    -- 1 üye, 2 yönetici (grubu düzenleyebilir, üye ekler/çıkarır).
    rol           smallint  not null default 1,
    -- Okundu sınırı: bu damgadan ESKİ mesajlar bu üye için okunmuştur.
    son_okuma     timestamp,
    favori        smallint  not null default 0,
    sabit         smallint  not null default 0,
    sessiz        smallint  not null default 0,
    arsiv         smallint  not null default 0,
    katilma_tarihi timestamp not null default (now())::timestamp,
    ayrilma_tarihi timestamp,
    primary key (sohbet_id, kullanici_id)
);

create index if not exists ix_mesaj_uye_kullanici on public.mesaj_uye (kullanici_id);

comment on column public.mesaj_uye.son_okuma is
  'Okundu SINIRI (342): mesaj basina satir tutulmaz - bu damgadan eski mesaj okunmustur.';

-- ---------------------------------------------------------------- mesaj ---
create table if not exists public.mesaj (
    id           integer generated by default as identity primary key,
    sohbet_id    integer   not null references public.mesaj_sohbet(id) on delete cascade,
    gonderen_id  integer   not null references public.taraf_kullanici(id),
    -- 1 metin, 2 dosya/ek, 3 sistem (üye eklendi, grup adı değişti…).
    tip          smallint  not null default 1,
    metin        text      not null default '',
    -- Yanıtlanan mesaj (mockup'taki alıntı şeridi). Silinirse alıntı düşer.
    yanit_id     integer   references public.mesaj(id) on delete set null,
    tarih        timestamp not null default (now())::timestamp,
    -- 1 normal, 2 silindi (metin gizlenir, satır kalır - sohbet akışında
    --   "bu mesaj silindi" olarak görünür ve okundu hesabı bozulmaz).
    durum        smallint  not null default 1,
    sabit        smallint  not null default 0,
    duzenlendi   timestamp
);

create index if not exists ix_mesaj_sohbet on public.mesaj (sohbet_id, tarih desc);

-- Son mesaj tarihi sohbette taşınır (liste sıralaması).
create or replace function public.tg_mesaj_sohbet_tazele()
returns trigger language plpgsql as $$
begin
    update public.mesaj_sohbet s
       set son_mesaj_tarihi = greatest(coalesce(s.son_mesaj_tarihi, new.tarih), new.tarih)
     where s.id = new.sohbet_id;
    return null;
end $$;

drop trigger if exists tr_mesaj_sohbet_tazele on public.mesaj;
create trigger tr_mesaj_sohbet_tazele after insert on public.mesaj
    for each row execute function public.tg_mesaj_sohbet_tazele();

-- ------------------------------------------------------- ek / iliştirme ---
-- Dosya İÇERİĞİ jenerik doküman deposunda (dokuman.kaynak = 'mesaj'); burada
--   yalnız mesaj ile doküman arasındaki bağ durur.
create table if not exists public.mesaj_ek (
    id         integer generated by default as identity primary key,
    mesaj_id   integer not null references public.mesaj(id) on delete cascade,
    dokuman_id integer not null,
    ad         varchar(200) not null default ''
);

create index if not exists ix_mesaj_ek_mesaj on public.mesaj_ek (mesaj_id);

-- KAYIT İLİŞTİRME (mockup: "Gentegre Kaydı İliştir"): kartın kendisi
--   KOPYALANMAZ, yalnız modül + kayıt kimliği tutulur. "Kartı Aç" ilgili
--   ekranı çalıştırır; yetkisi olmayan kullanıcı özet satırı görür, kartı
--   açamaz - yetki kontrolü kartın kendi ekranında zaten var.
create table if not exists public.mesaj_kayit (
    id        integer generated by default as identity primary key,
    mesaj_id  integer not null references public.mesaj(id) on delete cascade,
    -- Hedef ekranın kaynak adı: 'belge', 'cari', 'stok', 'hasta', 'gorev'…
    modul     varchar(40) not null,
    kayit_id  integer     not null,
    ozet      varchar(200) not null default ''
);

create index if not exists ix_mesaj_kayit_mesaj on public.mesaj_kayit (mesaj_id);

-- ------------------------------------------------------------- görünüm ----
-- Kullanıcının sohbet listesi: karşı taraf adı (kişi sohbetinde), son mesaj,
--   okunmamış sayısı ve kişisel bayraklar tek sorguda.
create or replace view public.v_mesaj_sohbet as
    select s.id,
           u.kullanici_id,
           s.tip,
           case when s.tip = 2 then s.ad
                else coalesce((select coalesce(nullif(btrim(t.unvan), ''), t.kod)
                                 from public.mesaj_uye u2
                                 join public.taraf t on t.id = u2.kullanici_id
                                where u2.sohbet_id = s.id
                                  and u2.kullanici_id <> u.kullanici_id
                                order by u2.kullanici_id limit 1), '(boş sohbet)')
           end                                              as baslik,
           -- Kişi sohbetinde karşı tarafın kimliği: kart/kişi bilgisi buradan.
           case when s.tip = 1 then (select u3.kullanici_id from public.mesaj_uye u3
                                      where u3.sohbet_id = s.id
                                        and u3.kullanici_id <> u.kullanici_id
                                      order by u3.kullanici_id limit 1) end as karsi_id,
           s.son_mesaj_tarihi,
           (select m.metin from public.mesaj m
             where m.sohbet_id = s.id and m.durum = 1
             order by m.tarih desc, m.id desc limit 1)       as son_metin,
           (select m.gonderen_id from public.mesaj m
             where m.sohbet_id = s.id and m.durum = 1
             order by m.tarih desc, m.id desc limit 1)       as son_gonderen_id,
           (select count(*) from public.mesaj m
             where m.sohbet_id = s.id and m.durum = 1
               and m.gonderen_id <> u.kullanici_id
               and (u.son_okuma is null or m.tarih > u.son_okuma))::int as okunmamis,
           (select count(*) from public.mesaj_uye u4
             where u4.sohbet_id = s.id and u4.ayrilma_tarihi is null)::int as uye_sayisi,
           u.favori, u.sabit, u.sessiz, u.arsiv, u.rol, u.son_okuma
      from public.mesaj_sohbet s
      join public.mesaj_uye u on u.sohbet_id = s.id and u.ayrilma_tarihi is null
     where s.durum = 1;

comment on view public.v_mesaj_sohbet is
  'Kullanicinin sohbet listesi (342): baslik, son mesaj, okunmamis sayisi, kisisel bayraklar.';

