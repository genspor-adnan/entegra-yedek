-- 248: taraf_kurum -> taraf_hasta_kurum, 1:1 yerine 1:N (kullanıcı:
-- "taraf_kurum rename et taraf_hasta_kurum, 1:n olsun; hastanın
-- başvurularındaki özellikle poliçe bilgileri girilir; sonuncu aktif
-- diğerleri pasif olur; hastaya bağlıdır").
--
-- Neden 1:N: poliçe hastanın kalıcı bir niteliği değil, ZAMANLA DEĞİŞEN bir
-- kayıt. Her başvuruda güncel poliçe girilir; eskisi tarihçe olarak durur
-- (geçmiş başvuruların hangi poliçeyle karşılandığı sorulabilsin diye).
-- "Sonuncu aktif" kuralı tetikle garanti edilir - hangi yoldan yazılırsa
-- yazılsın (kart, göç, elle SQL) bir hastanın en fazla bir aktif poliçesi olur.

create table if not exists public.taraf_hasta_kurum (
  id                integer generated by default as identity primary key,
  hasta_id          integer  not null references public.taraf(id) on delete cascade,
  tur               smallint not null default 1,      -- 1 Özel / 2 ÖSS / 3 SGK
  kurum_id          integer  references public.taraf(id),   -- ÖSS: sigorta şirketi
  police_no         varchar(40)  not null default '',
  gecerlilik        date,
  kapsam            varchar(200) not null default '',  -- teminat/kapsam notu
  aciklama          varchar(300) not null default '',
  aktif             smallint not null default 1,
  ekleyen           integer  not null default 0,
  ekleme_tarihi     timestamp not null default now()::timestamp,
  degistiren        integer  not null default 0,
  degistirme_tarihi timestamp
);

comment on table public.taraf_hasta_kurum is
  'Hastanın kurum/ödeyen ve poliçe kayıtları (248): Özel (kendi) / ÖSS / SGK. '
  'Sonuncusu aktif, öncekiler tarihçe olarak pasif kalır.';

create index if not exists ix_taraf_hasta_kurum_hasta
  on public.taraf_hasta_kurum (hasta_id, aktif, id desc);
create index if not exists ix_taraf_hasta_kurum_kurum
  on public.taraf_hasta_kurum (kurum_id) where kurum_id is not null;

-- Bir hastanın AYNI ANDA tek aktif poliçesi olur.
create unique index if not exists ux_taraf_hasta_kurum_aktif
  on public.taraf_hasta_kurum (hasta_id) where aktif = 1;

-- ------------------------------------------------------- tek aktif tetiği ---
-- BEFORE: benzersiz indeks satır yazılırken kontrol edilir; eskileri ÖNCE
--   pasife çekmezsek insert "duplicate key ux_taraf_hasta_kurum_aktif" verir.
--   İçerideki update aktif=0 yazdığı için tetik kendini tekrar tetiklemez.
create or replace function public.tg_taraf_hasta_kurum_tek_aktif()
returns trigger language plpgsql as $$
begin
  if new.aktif = 1 then
    update public.taraf_hasta_kurum
       set aktif = 0
     where hasta_id = new.hasta_id
       and aktif = 1
       and id is distinct from new.id;
  end if;
  return new;
end $$;

drop trigger if exists tg_taraf_hasta_kurum_tek_aktif on public.taraf_hasta_kurum;
create trigger tg_taraf_hasta_kurum_tek_aktif
  before insert or update of aktif, hasta_id on public.taraf_hasta_kurum
  for each row execute function public.tg_taraf_hasta_kurum_tek_aktif();

-- ------------------------------------------------------------- veri göçü ----
-- 245'teki 1:1 kayıtlar taşınır (id = taraf.id idi, artık hasta_id).
do $$
begin
  if exists (select 1 from information_schema.tables
              where table_schema = 'public' and table_name = 'taraf_kurum') then
    insert into public.taraf_hasta_kurum
           (hasta_id, tur, kurum_id, police_no, gecerlilik, kapsam, aciklama,
            aktif, ekleyen, ekleme_tarihi, degistiren, degistirme_tarihi)
    select k.id, k.tur, k.kurum_id, k.police_no, k.gecerlilik, k.kapsam,
           k.aciklama, 1, k.ekleyen, k.ekleme_tarihi, k.degistiren,
           k.degistirme_tarihi
      from public.taraf_kurum k
     where not exists (select 1 from public.taraf_hasta_kurum h
                        where h.hasta_id = k.id);
    drop table public.taraf_kurum;
  end if;
end $$;

