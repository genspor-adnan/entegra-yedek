-- Tevkifat orani KOD LISTESINDEN ("... (9/10)"): eski fonksiyon 617'ye kadar
--   sabit yaziliydi, 8xx (tam tevkifat) kodlarini 0 sayiyordu.
create or replace function public.fn_tevkifat_orani(p_kod text)
 returns numeric
 language sql
 stable
as $function$
    select coalesce((
        select (substring(d.ad from '\((\d+)/10\)\s*$'))::numeric * 10
          from public.kod_deger d
          join public.kod_liste l on l.id = d.liste_id
         where l.kod = 'belge.tevkifat' and d.dil = 0
           and d.deger::text = regexp_replace(coalesce(p_kod, ''), '\D', '', 'g')
         limit 1), 0)
$function$;
