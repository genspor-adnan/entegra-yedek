\set ON_ERROR_STOP on

-- ------------------------------------------------------------------ proje ----
create table if not exists public.proje (
    id                   integer generated by default as identity primary key,
    kod                  varchar(40)  not null default '',
    ad                   varchar(150) not null,
    ust_id               integer,                          -- alt proje agaci
    taraf_id             integer,                          -- musteri / isveren
    sorumlu_id           integer,                          -- personel (taraf)
    baslangic            date,
    bitis                date,
    butce_tutar          numeric(19,4) not null default 0,
    butce_dovizi         varchar(6)   not null default 'TL',
    durum                smallint     not null default 1,  -- 1 acik, 2 tamamlandi, 0 iptal
    aciklama             varchar(400) not null default '',
    sube_id              integer      not null default 0,
    ekleyen              integer      not null default 0,
    ekleme_tarihi        timestamp    not null default now()::timestamp,
    degistiren           integer      not null default 0,
    degistirme_tarihi    timestamp,
    constraint fk_proje_ust     foreign key (ust_id)     references public.proje (id),
    constraint fk_proje_taraf   foreign key (taraf_id)   references public.taraf (id),
    constraint fk_proje_sorumlu foreign key (sorumlu_id) references public.taraf (id)
);

create unique index if not exists ux_proje_kod on public.proje (kod) where kod <> '';
create index if not exists ix_proje_durum on public.proje (durum, ad);

comment on table public.proje is
  'Projeler (eski PROJELER). Kasa hareketi, belge ve belge satiri projeye baglanabilir; maliyet v_proje_ekstre ile okunur.';

-- --------------------------------------------------------- masraf_merkezi ----
create table if not exists public.masraf_merkezi (
    id                   integer generated by default as identity primary key,
    kod                  varchar(40)  not null default '',
    ad                   varchar(100) not null,
    ust_id               integer,
    durum                smallint     not null default 1,
    ekleyen              integer      not null default 0,
    ekleme_tarihi        timestamp    not null default now()::timestamp,
    degistiren           integer      not null default 0,
    degistirme_tarihi    timestamp,
    constraint fk_masraf_merkezi_ust foreign key (ust_id) references public.masraf_merkezi (id)
);

create unique index if not exists ux_masraf_merkezi_kod on public.masraf_merkezi (kod) where kod <> '';

comment on table public.masraf_merkezi is
  'Sorumluluk / masraf merkezi (eski SRMMERKEZI). 7xx gider hesaplarinin organizasyonel kirilimi; proje ile AYRI boyut.';

-- ------------------------------------------------------------------ hesap ----
-- tur: K kasa, B banka, P POS, V kredi karti, R kredi, H kupon kasasi
--   Tur-ozel kolonlar nullable/varsayilanli; UI ilgili alt-grubu tura gore gosterir.
create table if not exists public.hesap (
    id                   integer generated by default as identity primary key,
    tur                  varchar(1)   not null,
    kod                  varchar(40)  not null default '',
    ad                   varchar(150) not null,
    doviz_cinsi          varchar(6)   not null default 'TL',  -- hesabin KENDI dovizi (eski KASA.KUR)
    alt_tur              smallint     not null default 0,     -- K: 100 merkez,101 satis,195 is avans,196 maas avans / R: 1 taksitli,2 rotatif,3 spot
    sube_id              integer      not null default 0,     -- K11: her hesap tek subeye ait (sube.id integer)
    sorumlu_id           integer,                             -- kasa sorumlusu personel
    bagli_hesap_id       integer,                             -- P: aktarim bankasi, R: kullandiran banka, V: ekstre odeme bankasi
    -- B (banka)
    banka_adi            varchar(60)  not null default '',
    banka_subesi         varchar(60)  not null default '',
    hesap_no             varchar(30)  not null default '',
    iban                 varchar(34)  not null default '',
    -- P (POS)
    komisyon_orani       numeric(9,4) not null default 0,
    komisyon_masraf_id   integer,
    komisyon_zamani      smallint     not null default 1,     -- 1 aktarimda kesilir, 2 islemde kesilir
    valor_gun            smallint     not null default 0,
    -- V (kredi karti)
    hesap_kesim_gunu     smallint     not null default 0,
    son_odeme_gunu       smallint     not null default 0,
    limit_tutar          numeric(19,4) not null default 0,
    -- acilis
    acilis_bakiye        numeric(19,4) not null default 0,
    acilis_tarihi        date,
    durum                smallint     not null default 1,
    aciklama             varchar(200) not null default '',
    ekleyen              integer      not null default 0,
    ekleme_tarihi        timestamp    not null default now()::timestamp,
    degistiren           integer      not null default 0,
    degistirme_tarihi    timestamp,
    constraint ck_hesap_tur check (tur in ('K','B','P','V','R','H')),
    constraint fk_hesap_sube    foreign key (sube_id)            references public.sube (id),
    constraint fk_hesap_sorumlu foreign key (sorumlu_id)         references public.taraf (id),
    constraint fk_hesap_bagli   foreign key (bagli_hesap_id)     references public.hesap (id),
    constraint fk_hesap_komisyon foreign key (komisyon_masraf_id) references public.masraf (id)
);

create unique index if not exists ux_hesap_kod on public.hesap (tur, kod) where kod <> '';
create index if not exists ix_hesap_tur on public.hesap (tur, sube_id, durum);

comment on table public.hesap is
  'Kasa / banka / POS / kredi karti / kredi / kupon kasasi TEK tabloda (eski KASALAR+BANKAHESAPLAR+POS+KREDIKARTI+KREDILER). tur harfi mali_hareket.hesap_turu ile ayni kod uzayindadir.';
comment on column public.hesap.doviz_cinsi is
  'Hesabin kendi para birimi. Bu hesaba yazilan bacaklarin doviz_cinsi bununla AYNI olmak zorundadir (dogrulama).';
comment on column public.hesap.komisyon_zamani is
  'POS komisyonu ne zaman kesilir: 1 = bankaya aktarimda (eski MASRAFCIKIS=1), 2 = tahsilat aninda POS bakiyesinden (=2).';

-- ------------------------------------------------------------------ kredi ----
-- hesap (tur='R') 1:1 uzantisi - taraf_musteri deseni (017_sema_sube_rol.sql).
create table if not exists public.kredi (
    id                   integer primary key,
    taraf_id             integer,                          -- krediyi veren banka carisi
    proje_id             integer,
    anapara              numeric(19,4) not null default 0,
    faiz_orani           numeric(9,4)  not null default 0, -- yillik %
    kkdf_orani           numeric(9,4)  not null default 0,
    bsmv_orani           numeric(9,4)  not null default 0,
    vade_ay              smallint      not null default 0,
    kullanim_tarihi      date,
    ilk_taksit_tarihi    date,
    faiz_masraf_id       integer,                          -- 780 Finansman giderleri kalemi
    kkdf_masraf_id       integer,                          -- bos ise faiz kalemine katlanir
    bsmv_masraf_id       integer,
    durum                smallint      not null default 1, -- 1 acik, 2 kapandi
    ekleyen              integer       not null default 0,
    ekleme_tarihi        timestamp     not null default now()::timestamp,
    degistiren           integer       not null default 0,
    degistirme_tarihi    timestamp,
    constraint fk_kredi_hesap  foreign key (id)             references public.hesap (id) on delete cascade,
    constraint fk_kredi_taraf  foreign key (taraf_id)       references public.taraf (id),
    constraint fk_kredi_proje  foreign key (proje_id)       references public.proje (id),
    constraint fk_kredi_faiz   foreign key (faiz_masraf_id) references public.masraf (id),
    constraint fk_kredi_kkdf   foreign key (kkdf_masraf_id) references public.masraf (id),
    constraint fk_kredi_bsmv   foreign key (bsmv_masraf_id) references public.masraf (id)
);

comment on table public.kredi is
  'Banka kredisi ayrintisi (eski KREDILER). public.hesap (tur=R) 1:1 uzantisi - taraf_musteri deseni.';

