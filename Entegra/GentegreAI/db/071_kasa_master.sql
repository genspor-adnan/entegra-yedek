-- ------------------------------------------ merkez_id: 0 -> null + FK bagi ----
-- Mevcut kolonlar "0 = yok" sabitiyle acilmisti; FK verebilmek icin null'a cevrilir.
--   SIRA ONEMLI: once not-null kisiti kalkar, sonra 0'lar null'a cevrilir.
alter table public.mali_hareket alter column merkez_id drop not null;
alter table public.mali_hareket alter column merkez_id drop default;
alter table public.belge        alter column merkez_id drop not null;
alter table public.belge        alter column merkez_id drop default;

update public.mali_hareket set merkez_id = null where merkez_id = 0;
update public.belge        set merkez_id = null where merkez_id = 0;

-- Legacy'den gelen ARTIK degerler: masraf_merkezi'nde karsiligi olmayan (goc
--   sirasinda bozulmus, 8-9 haneli rastgele) id'ler null'a cekilir - yoksa FK
--   kurulamaz. Sayi rapor edilir ki sessizce veri kaybi gibi gorunmesin.
do $$
declare v_mh integer; v_b integer;
begin
    select count(*) into v_mh from public.mali_hareket m
     where m.merkez_id is not null
       and not exists (select 1 from public.masraf_merkezi k where k.id = m.merkez_id);
    select count(*) into v_b from public.belge b
     where b.merkez_id is not null
       and not exists (select 1 from public.masraf_merkezi k where k.id = b.merkez_id);

    update public.mali_hareket m set merkez_id = null
     where m.merkez_id is not null
       and not exists (select 1 from public.masraf_merkezi k where k.id = m.merkez_id);
    update public.belge b set merkez_id = null
     where b.merkez_id is not null
       and not exists (select 1 from public.masraf_merkezi k where k.id = b.merkez_id);

    raise notice '071: karsiligi olmayan merkez_id temizlendi -> mali_hareket %, belge %', v_mh, v_b;
end $$;

alter table public.mali_hareket drop constraint if exists fk_mali_hareket_merkez;
alter table public.mali_hareket add  constraint fk_mali_hareket_merkez
      foreign key (merkez_id) references public.masraf_merkezi (id);
alter table public.belge drop constraint if exists fk_belge_merkez;
alter table public.belge add  constraint fk_belge_merkez
      foreign key (merkez_id) references public.masraf_merkezi (id);

-- ------------------------------------------------------- degistirme trigger ----
do $$
declare t text;
begin
    foreach t in array array['proje','masraf_merkezi','hesap','kredi','kredi_taksit','kupon_turu'] loop
        execute format('drop trigger if exists trg_%1$s_degistirme on public.%1$s', t);
        execute format('create trigger trg_%1$s_degistirme before update on public.%1$s
                        for each row execute function public.fn_degistirme_tarihi()', t);
    end loop;
end $$;

-- ------------------------------------------------------- lookup gorunumleri ----
-- KartDeposu.KodTablosu mekanizmasi hedefte "id, ad, aktif" kolonlarini arar
--   (bkz. KartDeposu.cs KodTablosuBeyazListe). hizmet/masraf "durum" kullandigi
--   icin gorunumle uyarlanir; hesapta doviz cinsi ada eklenir ki acilir listede
--   "MERKEZ KASA [USD]" seklinde ayirt edilebilsin.
create or replace view public.v_hesap_lookup as
    select h.id, h.ad || ' [' || h.doviz_cinsi || ']' as ad, h.durum as aktif
      from public.hesap h;

create or replace view public.v_proje_lookup as
    select p.id, p.ad, case when p.durum = 1 then 1 else 0 end as aktif
      from public.proje p;

create or replace view public.v_masraf_lookup as
    select m.id, m.ad, m.durum as aktif from public.masraf m;

create or replace view public.v_hizmet_lookup as
    select h.id, h.ad, h.durum as aktif from public.hizmet h;

create or replace view public.v_masraf_merkezi_lookup as
    select m.id, m.ad, m.durum as aktif from public.masraf_merkezi m;

-- ------------------------------------------------------------- dogrulama ----
do $$
declare v_tablo integer;
begin
    select count(*) into v_tablo from information_schema.tables
     where table_schema = 'public'
       and table_name in ('proje','masraf_merkezi','hesap','kredi','kredi_taksit','kupon_turu');
    raise notice '071 tamam: % / 6 tablo kuruldu', v_tablo;
end $$;
