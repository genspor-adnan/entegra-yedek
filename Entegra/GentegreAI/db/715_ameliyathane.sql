-- 715: AMELİYATHANE — salon, talep, ameliyat, ekip, güvenli cerrahi, sarf, sayım.
--
-- Mockup'lar: `Ekranlar/Ameliyathane/*.html`.
--
-- TEMEL KARAR — TALEP ve AMELİYAT AYRI TABLO. Talep, planlanmadan da yaşayan
--   bir kayıttır ("bu hastaya diz protezi gerekiyor"); ameliyat ise salona ve
--   saate bağlanmış olandır. Tek tabloda tutsaydık, planlanan ameliyat iptal
--   edilince talebin de silinmesi ya da "iptal" damgasıyla listede kalması
--   gerekirdi - ikisi de yanlış: hasta hâlâ ameliyat bekliyor. İptal ameliyatı
--   kapatır, talebi yeniden bekleyene düşürür.
--
-- TEMEL KARAR — ZAMAN DAMGALARI AYRI KOLON. Salona alma · anestezi başlangıcı ·
--   KESİ · kapanış · bitiş · salondan çıkış ayrı ayrı tutulur. Tek
--   "başlangıç-bitiş" saklasaydık masa kullanımı ile cerrahi süre ayırt
--   edilemezdi; ameliyathane verimini bozan şey genelde ikisinin arasındaki
--   boşluktur (devir süresi). Kesi ayrıca klinik kalite için gerekli:
--   profilaktik antibiyotiğin "kesiden önceki 60 dk" içinde verilip
--   verilmediği ancak bu damgayla ölçülür.
--
-- TEMEL KARAR — GÜVENLİ CERRAHİ KONTROL LİSTESİ MADDE MADDE. Tek bir
--   "kontrol_listesi_tamam" bayrağı olsaydı liste ameliyat bittikten sonra
--   toplu işaretlenir ve amacı kalmazdı. Her madde kim/ne zaman ile ayrı satır;
--   aşama (sign in / time out / sign out) ve zorunluluk madde tanımında.
--
-- TEMEL KARAR — TARAF (sağ/sol/bilateral) İŞLEM SATIRINDA. Ameliyat başlığında
--   tutulsaydı iki taraflı ameliyatta hangi işlemin hangi tarafa yapıldığı
--   kaybolurdu; yanlış taraf cerrahisi en ağır olaydır ve kontrol listesinde
--   ikinci kez doğrulanır (bilerek yapılmış tekrar).
--
-- TEMEL KARAR — KOMPLİKASYON ICD-10 KODUYLA. Serbest metin klinik kalite
--   göstergesine dönüşemez: DP.G6 / KP.G1 gibi göstergeler tanı kodundan
--   hesaplanıyor (bkz 713 motoru).

-- ================================================================= salon ==
create table if not exists public.ameliyat_salon (
  id            integer generated by default as identity primary key,
  sube_id       integer not null default 0,
  kod           varchar(20)  not null,
  ad            varchar(100) not null,
  -- Salonun donanımı: laminar akım, mikroskop, robotik… serbest metin, çünkü
  --   kurumdan kuruma değişiyor ve süzme değil bilgilendirme amaçlı.
  ozellik       varchar(200) not null default '',
  departman_id  integer references public.departman(id),
  -- Acile AYRILMIŞ salon: plan dışı vaka önce buraya düşer. Ayrılmasaydı her
  --   acil vaka elektif listeyi baştan kaydırırdı.
  acil_ayrilmis smallint not null default 0,
  sira          smallint not null default 0,
  aktif         smallint not null default 1,
  ekleyen       integer not null default 0,
  ekleme_tarihi timestamptz not null default now(),
  degistiren    integer not null default 0,
  degistirme_tarihi timestamptz
);
create unique index if not exists ux_ameliyat_salon_kod
  on public.ameliyat_salon (sube_id, kod);

comment on table public.ameliyat_salon is 'Ameliyathane salonu / masası (715).';

-- ================================================================= talep ==
create table if not exists public.ameliyat_talep (
  id            bigint generated by default as identity primary key,
  sube_id       integer not null default 0,
  talep_no      varchar(30) not null default '',
  hasta_id      integer not null references public.taraf(id),
  -- İsteyen hekim ile ameliyatı yapacak cerrah aynı olmayabilir (konsültasyon
  --   sonrası istem); ameliyattaki cerrah `ameliyat.cerrah_id`de durur.
  isteyen_id    integer references public.taraf(id),
  hizmet_id     integer references public.hizmet(id),
  -- Taraf: 0 yok/uygulanmaz · 1 sağ · 2 sol · 3 bilateral
  taraf         smallint not null default 0,
  -- Öncelik: 1 normal · 2 tarihli (doğum gibi) · 3 onkolojik · 4 acil
  oncelik       smallint not null default 1,
  tahmini_sure_dk smallint not null default 0,
  -- Anestezi tipi: 1 genel · 2 spinal · 3 epidural · 4 bölgesel · 5 lokal · 6 sedasyon
  anestezi_tipi smallint not null default 0,
  istenen_tarih date,
  aciklama      text not null default '',
  -- ÖN HAZIRLIK ayrı bayraklar, tek "hazır mı" değil: eksik olanın NE olduğu
  --   listede yazmazsa kullanıcı her talebi tek tek açıp aramak zorunda kalır.
  anestezi_onay smallint not null default 0,
  tetkik_tamam  smallint not null default 0,
  kan_hazir     smallint not null default 0,
  onam_alindi   smallint not null default 0,
  -- 0 bekliyor · 1 planlandı · 2 yapıldı · 8 iptal · 9 vazgeçildi
  durum         smallint not null default 0,
  iptal_neden   varchar(200) not null default '',
  ekleyen       integer not null default 0,
  ekleme_tarihi timestamptz not null default now(),
  degistiren    integer not null default 0,
  degistirme_tarihi timestamptz
);
create index if not exists ix_ameliyat_talep_bekleyen
  on public.ameliyat_talep (sube_id, durum, oncelik) where durum = 0;
create index if not exists ix_ameliyat_talep_hasta
  on public.ameliyat_talep (hasta_id);

comment on table public.ameliyat_talep is
  'Ameliyat istemi (715). Planlanmadan da yaşar; ameliyat iptal olursa talep bekleyene döner.';

-- ============================================================== ameliyat ==
create table if not exists public.ameliyat (
  id            bigint generated by default as identity primary key,
  sube_id       integer not null default 0,
  ameliyat_no   varchar(30) not null default '',
  talep_id      bigint references public.ameliyat_talep(id),
  hasta_id      integer not null references public.taraf(id),
  salon_id      integer references public.ameliyat_salon(id),
  -- Yatan hastanın ameliyatı yatışa, ayaktan hastanınki başvuruya bağlanır;
  --   ikisi de boş olabilir (acil, henüz kabul edilmemiş).
  yatis_id      integer references public.yatis(id),
  belge_id      integer references public.belge(id),
  cerrah_id     integer references public.taraf(id),
  anestezi_id   integer references public.taraf(id),
  anestezi_tipi smallint not null default 0,
  -- ASA skoru (1-6) ve Mallampati anestezi riskinin iki temel ölçüsü.
  asa_skoru     smallint not null default 0,
  mallampati    smallint not null default 0,

  plan_baslangic timestamptz,
  plan_sure_dk   smallint not null default 0,
  -- GERÇEK ZAMAN DAMGALARI - her biri ayrı soru yanıtlıyor (bkz başlık).
  salona_alma    timestamptz,
  anestezi_bas   timestamptz,
  kesi_zamani    timestamptz,
  kapanis_bas    timestamptz,
  bitis_zamani   timestamptz,
  salondan_cikis timestamptz,

  -- 0 planlandı · 1 hazırlık · 2 sürüyor · 3 kapanışta · 4 bitti · 8 iptal
  durum          smallint not null default 0,
  -- Plan dışı (acil) eklenen vaka: masa kullanımı raporunda ayrı sayılır,
  --   yoksa "plana uymadık" diye görünür.
  plan_disi      smallint not null default 0,
  iptal_neden    varchar(200) not null default '',
  gecikme_neden  varchar(200) not null default '',
  kanama_ml      integer not null default 0,
  ekleyen        integer not null default 0,
  ekleme_tarihi  timestamptz not null default now(),
  degistiren     integer not null default 0,
  degistirme_tarihi timestamptz
);
create index if not exists ix_ameliyat_gun
  on public.ameliyat (sube_id, plan_baslangic);
create index if not exists ix_ameliyat_salon
  on public.ameliyat (salon_id, plan_baslangic);
create index if not exists ix_ameliyat_hasta on public.ameliyat (hasta_id);

comment on table public.ameliyat is
  'Ameliyat kaydı (715). Zaman damgaları ayrı: masa kullanımı ile cerrahi süre farklı sorular.';

-- =============================================================== işlemler ==
-- Bir ameliyatta birden çok işlem olur (ana + ek). SUT kodu `hizmet` üzerinden
--   gelir ve hem faturaya hem klinik kalite göstergesine kaynaklık eder.
create table if not exists public.ameliyat_islem (
  id           bigint generated by default as identity primary key,
  ameliyat_id  bigint not null references public.ameliyat(id) on delete cascade,
  hizmet_id    integer references public.hizmet(id),
  sira         smallint not null default 0,
  -- 1 ana işlem · 2 ek işlem
  tur          smallint not null default 1,
  -- Taraf İŞLEM satırında (bkz başlık kararı).
  taraf        smallint not null default 0,
  cerrah_id    integer references public.taraf(id),
  aciklama     varchar(300) not null default '',
  belge_satir_id bigint
);
create index if not exists ix_ameliyat_islem_ust on public.ameliyat_islem (ameliyat_id, sira);

-- =================================================================== ekip ==
create table if not exists public.ameliyat_ekip (
  id          bigint generated by default as identity primary key,
  ameliyat_id bigint not null references public.ameliyat(id) on delete cascade,
  personel_id integer not null references public.taraf(id),
  -- 1 cerrah · 2 asistan · 3 anestezi uzmanı · 4 anestezi teknikeri
  -- 5 scrub hemşire · 6 sirküle hemşire · 7 görüntüleme · 9 diğer
  rol         smallint not null default 9,
  -- Giriş/çıkış saati kişi bazında: aynı ameliyatta ekip değişebiliyor ve
  --   "kim oradaydı" sorusu adli olarak da sorulabiliyor.
  giris       timestamptz,
  cikis       timestamptz,
  sorumlu     smallint not null default 0,
  aciklama    varchar(200) not null default ''
);
create index if not exists ix_ameliyat_ekip_ust on public.ameliyat_ekip (ameliyat_id, rol);

-- ================================================== güvenli cerrahi (DSÖ) ==
-- Madde TANIMI ayrı tablo: kurum listeyi genişletebilmeli ama geçmiş
--   ameliyatın işaretleri değişmemeli, o yüzden işaret satırı madde METNİNİ de
--   kopyalar (`madde_metin`). Tanım sonradan düzenlenince eski kayıt ne
--   imzalandıysa onu gösterir.
create table if not exists public.ameliyat_kontrol_madde (
  id       integer generated by default as identity primary key,
  -- 1 sign in (anestezi öncesi) · 2 time out (kesi öncesi) · 3 sign out (çıkış)
  asama    smallint not null default 1,
  sira     smallint not null default 0,
  metin    varchar(300) not null,
  zorunlu  smallint not null default 1,
  aktif    smallint not null default 1
);
create index if not exists ix_ameliyat_kontrol_madde on public.ameliyat_kontrol_madde (asama, sira);

create table if not exists public.ameliyat_kontrol (
  id          bigint generated by default as identity primary key,
  ameliyat_id bigint not null references public.ameliyat(id) on delete cascade,
  madde_id    integer references public.ameliyat_kontrol_madde(id),
  asama       smallint not null default 1,
  sira        smallint not null default 0,
  madde_metin varchar(300) not null default '',
  isaretli    smallint not null default 0,
  isaretleyen integer references public.taraf(id),
  isaret_zamani timestamptz,
  not_metni   varchar(300) not null default ''
);
create unique index if not exists ux_ameliyat_kontrol
  on public.ameliyat_kontrol (ameliyat_id, asama, sira);

comment on table public.ameliyat_kontrol is
  'Güvenli cerrahi kontrol listesi işaretleri (715). Madde metni kopyalanır: tanım değişse de geçmiş kayıt sabit.';

