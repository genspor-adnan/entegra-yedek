-- =============================================================== lookup'lar ==
create or replace view public.v_ameliyat_salon_lookup as
select s.id, (s.kod || ' · ' || s.ad)::varchar(130) as ad, s.sube_id, s.aktif
  from public.ameliyat_salon s where s.aktif = 1;

-- ============================================================= sayım kuralı ==
-- Kapanış girildiğinde uyumu TETİK hesaplar: iki yerde hesaplanırsa (ekran ve
--   sunucu) "sayım tamam" diyen ekranla "uyuşmuyor" diyen kayıt yan yana gelir.
create or replace function public.fn_ameliyat_sayim_uyum()
returns trigger language plpgsql as $tg$
begin
    if new.kapanis is null then
        new.uyumlu := null;
    else
        new.uyumlu := case when new.kapanis = (new.baslangic + new.eklenen) then 1 else 0 end;
    end if;
    return new;
end;
$tg$;

drop trigger if exists tg_ameliyat_sayim_uyum on public.ameliyat_sayim;
create trigger tg_ameliyat_sayim_uyum
  before insert or update of baslangic, eklenen, kapanis on public.ameliyat_sayim
  for each row execute function public.fn_ameliyat_sayim_uyum();

