-- =====================================================================
--  875_dis_ortodonti_icon.sql
--  ORTODONTİ ICON SKORU (KTS denetim maddesi D9: "Ortodonti Icon Scor
--  Formu Ekranı ve Raporları var mı?")
--
--  ICON = Index of Complexity, Outcome and Need (Daniels & Richmond, 2000).
--  Beş bileşenin AĞIRLIKLI toplamıdır:
--
--     estetik (IOTN-AC 1-10)                        × 7
--     üst ark dizilimi / aralık (0-4)               × 5
--     çapraz kapanış (0 yok · 1 var)                × 5
--     dikey ilişki: açık ya da derin kapanış (0-4)  × 4
--     bukkal segment ön-arka ilişki (0-4)           × 3
--
--  AĞIRLIK VE EŞİKLER ŞEMADA DURUR, KODDA DEĞİL: toplam üretilmiş
--  (generated) kolondur, karmaşıklık ve iyileşme birer fonksiyondur. Aynı
--  hesabı ekranda bir daha yazmak, iki yerin sessizce ayrılması demekti -
--  para hesabında öğrenilen ders (BelgeHesap) burada da geçerli.
--
--  ÜÇ SORUYA CEVAP VERİR (indeksin adı da bundan gelir):
--   * İHTİYAÇ (Need): toplam > 43 ise ortodontik tedavi endikasyonu var.
--   * KARMAŞIKLIK (Complexity): <29 kolay · 29-50 hafif · 51-63 orta ·
--     64-77 zor · >77 çok zor.
--   * SONUÇ (Outcome): tedavi SONRASI ölçüm, ÖNCEKİ ölçüme bağlanır ve
--     iyileşme derecesi `önce − 4 × sonra` formülünden çıkar.
--
--  KAYNAK VE SORUMLULUK: ağırlıklar ve eşikler indeksin yayımlanmış
--  tanımındandır; klinik sorumlu kurulumda bir kez doğrulamalıdır. Bileşen
--  puanı HEKİMİN verdiği puandır - sistem fotoğraftan puan üretmez.
--
--  ÖNCE/SONRA AYNI TABLODA (`olcum_turu`): ikisi ayrı tablo olsaydı
--  iyileşme hesabı iki tabloyu birleştirmek zorunda kalırdı; oysa ölçüm
--  aynı ölçümdür, yalnız zamanı farklıdır.
-- =====================================================================

-- ------------------------------------------------------- kod listeleri ----
insert into public.kod_liste (kod, ad)
select v.kod, v.ad from (values
    ('dis.icon_olcum',        'ICON Ölçüm Türü'),
    ('dis.icon_karmasiklik',  'ICON Karmaşıklık Derecesi'),
    ('dis.icon_iyilesme',     'ICON İyileşme Derecesi')
  ) as v(kod, ad)
 where not exists (select 1 from public.kod_liste k where k.kod = v.kod);

insert into public.kod_deger (liste_id, deger, ad, sira, aktif, ekleyen)
select l.id, v.deger, v.ad, v.deger * 10, 1, 0
  from public.kod_liste l
  join (values
    ('dis.icon_olcum', 1, 'Tedavi öncesi'),
    ('dis.icon_olcum', 2, 'Tedavi sonrası'),
    ('dis.icon_karmasiklik', 1, 'Kolay'),
    ('dis.icon_karmasiklik', 2, 'Hafif'),
    ('dis.icon_karmasiklik', 3, 'Orta'),
    ('dis.icon_karmasiklik', 4, 'Zor'),
    ('dis.icon_karmasiklik', 5, 'Çok zor'),
    ('dis.icon_iyilesme', 1, 'Büyük ölçüde iyileşti'),
    ('dis.icon_iyilesme', 2, 'Belirgin iyileşti'),
    ('dis.icon_iyilesme', 3, 'Orta düzeyde iyileşti'),
    ('dis.icon_iyilesme', 4, 'Az iyileşti'),
    ('dis.icon_iyilesme', 5, 'İyileşmedi / kötüleşti')
  ) as v(liste, deger, ad) on v.liste = l.kod
 where not exists (select 1 from public.kod_deger d
                    where d.liste_id = l.id and d.deger = v.deger);

-- ---------------------------------------------------------- toplam ----
--  AĞIRLIKLAR TEK YERDE. Üretilmiş kolon da, ekrandaki canlı önizleme de
--  bu fonksiyonu çağırır: ikisi ayrı yazılsaydı, ağırlık değiştiğinde
--  kaydedilen skor ile ekranda görünen skor sessizce ayrışırdı.
create or replace function public.fn_dis_icon_toplam(
    p_estetik smallint, p_ust_ark smallint, p_capraz smallint,
    p_dikey smallint, p_bukkal smallint)
returns integer language sql immutable as $$
    select p_estetik * 7 + p_ust_ark * 5 + p_capraz * 5 + p_dikey * 4 + p_bukkal * 3;
$$;

comment on function public.fn_dis_icon_toplam(smallint, smallint, smallint, smallint, smallint) is
  '875: ICON agirlikli toplami - estetik*7 + ust_ark*5 + capraz*5 + dikey*4 + bukkal*3.';

--  INTEGER AŞIRI YÜKLEMESİ: PG tamsayı sabitini smallint'e KENDİLİĞİNDEN
--  indirmez; `fn_dis_icon_toplam(5,2,1,2,2)` "function does not exist" ile
--  döner. Üretilmiş kolon smallint sürümü kullanır (kolonlar smallint);
--  elle sorgu ve gelecekteki çağrılar için okunur bir yol bırakıyoruz.
create or replace function public.fn_dis_icon_toplam(
    p_estetik integer, p_ust_ark integer, p_capraz integer,
    p_dikey integer, p_bukkal integer)
returns integer language sql immutable as $$
    select public.fn_dis_icon_toplam(p_estetik::smallint, p_ust_ark::smallint,
                                     p_capraz::smallint, p_dikey::smallint, p_bukkal::smallint);
$$;

-- ------------------------------------------------------------- tablo ----
create table if not exists public.dis_icon_skor (
  id             integer generated by default as identity primary key,
  sube_id        integer  not null default 0,
  hasta_id       integer  not null references public.taraf(id),
  muayene_id     integer  references public.muayene(id),
  hekim_id       integer  references public.taraf(id),
  tarih          date     not null default current_date,
  olcum_turu     smallint not null default 1,          -- dis.icon_olcum
  -- Bileşenler. Sınırlar KISITTA: ekranın doğrulamasına güvenmek, API'den
  --   gelen 12'lik estetik puanını skoru sessizce şişirerek kabul etmekti.
  estetik        smallint not null default 1,          -- IOTN-AC 1-10
  ust_ark        smallint not null default 0,          -- 0-4
  capraz         smallint not null default 0,          -- 0 yok · 1 var
  dikey          smallint not null default 0,          -- 0-4
  bukkal         smallint not null default 0,          -- 0-4
  toplam         integer generated always as
                 (public.fn_dis_icon_toplam(estetik, ust_ark, capraz, dikey, bukkal)) stored,
  -- Tedavi sonrası ölçüm, hangi ölçümün sonrası olduğunu söyler.
  oncesi_id      integer  references public.dis_icon_skor(id),
  not_metin      varchar(400) not null default '',
  ekleyen        integer  not null default 0,
  ekleme_tarihi  timestamptz not null default now(),
  degistiren     integer  not null default 0,
  degistirme_tarihi timestamptz,
  constraint ck_dis_icon_estetik check (estetik between 1 and 10),
  constraint ck_dis_icon_ust_ark check (ust_ark between 0 and 4),
  constraint ck_dis_icon_capraz  check (capraz  between 0 and 1),
  constraint ck_dis_icon_dikey   check (dikey   between 0 and 4),
  constraint ck_dis_icon_bukkal  check (bukkal  between 0 and 4),
  constraint ck_dis_icon_olcum   check (olcum_turu in (1, 2))
);

create index if not exists ix_dis_icon_hasta on public.dis_icon_skor (hasta_id, tarih desc);

comment on table public.dis_icon_skor is
  '875: Ortodonti ICON skoru (KTS D9). Toplam uretilmis kolon: '
  'estetik*7 + ust_ark*5 + capraz*5 + dikey*4 + bukkal*3. Tedavi ihtiyaci '
  'esigi 43; karmasiklik fn_dis_icon_karmasiklik, iyilesme fn_dis_icon_iyilesme.';
comment on column public.dis_icon_skor.estetik is
  'IOTN estetik bilesen 1-10 (1 en iyi). Hekimin fotograf skalasindan verdigi puan.';
comment on column public.dis_icon_skor.oncesi_id is
  'Tedavi sonrasi olcumun bagli oldugu tedavi oncesi olcum - iyilesme bundan hesaplanir.';

-- --------------------------------------------------------- fonksiyonlar ----
--  Karmaşıklık, toplam puanın bandıdır.
create or replace function public.fn_dis_icon_karmasiklik(p_toplam integer)
returns smallint language sql immutable as $$
    select case
             when p_toplam is null then null
             when p_toplam < 29 then 1::smallint     -- kolay
             when p_toplam <= 50 then 2::smallint    -- hafif
             when p_toplam <= 63 then 3::smallint    -- orta
             when p_toplam <= 77 then 4::smallint    -- zor
             else 5::smallint                        -- çok zor
           end;
$$;

--  İYİLEŞME: önce − 4 × sonra. Katsayı 4, indeksin tanımından gelir -
--  tedavi sonrası kalan her puan, başlangıçtaki dört puana bedeldir.
create or replace function public.fn_dis_icon_iyilesme(p_once integer, p_sonra integer)
returns smallint language sql immutable as $$
    select case
             when p_once is null or p_sonra is null then null
             when (p_once - 4 * p_sonra) > -1  then 1::smallint   -- büyük ölçüde
             when (p_once - 4 * p_sonra) >= -25 then 2::smallint  -- belirgin
             when (p_once - 4 * p_sonra) >= -53 then 3::smallint  -- orta
             when (p_once - 4 * p_sonra) >= -85 then 4::smallint  -- az
             else 5::smallint                                     -- iyileşmedi
           end;
$$;

comment on function public.fn_dis_icon_karmasiklik(integer) is
  '875: ICON toplamindan karmasiklik bandi (1 kolay - 5 cok zor).';
comment on function public.fn_dis_icon_iyilesme(integer, integer) is
  '875: ICON iyilesme derecesi - once - 4*sonra formulunun bandi (1 en iyi).';

-- ------------------------------------------------------------ görünüm ----
create or replace view public.v_dis_icon_skor as
select s.id,
       s.sube_id,
       s.hasta_id,
       t.unvan                                   as hasta_adi,
       s.hekim_id,
       coalesce(h.unvan, '')                     as hekim_adi,
       s.tarih,
       s.olcum_turu,
       coalesce(ko.ad, '')                       as olcum_turu_adi,
       s.estetik, s.ust_ark, s.capraz, s.dikey, s.bukkal,
       s.toplam,
       case when s.toplam > 43 then 1 else 0 end::smallint as tedavi_gerekir,
       public.fn_dis_icon_karmasiklik(s.toplam)  as karmasiklik,
       coalesce(kk.ad, '')                       as karmasiklik_adi,
       s.oncesi_id,
       o.toplam                                  as oncesi_toplam,
       public.fn_dis_icon_iyilesme(o.toplam, s.toplam) as iyilesme,
       coalesce(ki.ad, '')                       as iyilesme_adi,
       s.not_metin,
       s.muayene_id,
       s.ekleme_tarihi
  from public.dis_icon_skor s
  join public.taraf t on t.id = s.hasta_id
  left join public.taraf h on h.id = s.hekim_id
  left join public.dis_icon_skor o on o.id = s.oncesi_id
  left join public.kod_liste lo on lo.kod = 'dis.icon_olcum'
  left join public.kod_deger ko on ko.liste_id = lo.id and ko.deger = s.olcum_turu
  left join public.kod_liste lk on lk.kod = 'dis.icon_karmasiklik'
  left join public.kod_deger kk on kk.liste_id = lk.id
                               and kk.deger = public.fn_dis_icon_karmasiklik(s.toplam)
  left join public.kod_liste li on li.kod = 'dis.icon_iyilesme'
  left join public.kod_deger ki on ki.liste_id = li.id
                               and ki.deger = public.fn_dis_icon_iyilesme(o.toplam, s.toplam);

comment on view public.v_dis_icon_skor is
  '875: ICON skoru + turetilmis degerler (tedavi_gerekir, karmasiklik, '
  'iyilesme). Ekran ve rapor bu gorunumden okur - hesap tek yerde.';

-- -------------------------------------------------------------- yetki ----
insert into public.yetki (kod, ad, grup, tur, sira, aktif)
select 'dis.icon', 'Ortodonti ICON skoru', 'Diş', 0, 11, 1
 where not exists (select 1 from public.yetki where kod = 'dis.icon');

-- YÖNETİCİYE AÇILIR (868'deki desen). Diğer roller ICON'u kendi yetki
--   ekranından alır: skor formu hasta kartının bir sekmesi olsa da yetkisi
--   ayrıdır - ortodontist olmayan hekime kapatılabilmeli.
insert into public.rol_yetki (rol_id, yetki_id, gor, ekle, degistir, sil, ekleyen)
select r.id, y.id, 1, 1, 1, 1, 0
  from public.rol r cross join public.yetki y
 where r.kod = 'yonetici' and y.kod = 'dis.icon'
   and not exists (select 1 from public.rol_yetki ry
                    where ry.rol_id = r.id and ry.yetki_id = y.id);
update public.rol set yetki_surumu = yetki_surumu + 1 where kod = 'yonetici';

