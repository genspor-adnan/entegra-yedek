begin;

-- --------------------------------------------------------------- yetki --
insert into public.yetki (kod, ad, grup, tur, sira, aktif, modul)
select 'kys.egitim', 'Eğitim ve yetkinlik kayıtları', 'Kalite', 0, 11, 1, 'kys'
 where not exists (select 1 from public.yetki where kod = 'kys.egitim');

insert into public.rol_yetki (rol_id, yetki_id, gor, ekle, degistir, sil, ekleyen)
select r.id, y.id, 1, 1, 1, 1, 0
  from public.rol r cross join public.yetki y
 where r.kod = 'yonetici' and y.kod = 'kys.egitim'
   and not exists (select 1 from public.rol_yetki ry where ry.rol_id = r.id and ry.yetki_id = y.id);
update public.rol set yetki_surumu = yetki_surumu + 1 where kod = 'yonetici';

-- ------------------------------------------------------ zorunlu eğitim --
create table if not exists public.kalite_zorunlu_egitim (
    id                 integer generated by default as identity primary key,
    egitim_adi         varchar(200) not null,
    departman_id       integer      references public.departman(id),
    periyot_ay         smallint,
    aktif              smallint     not null default 1,
    aciklama           varchar(400) not null default '',
    sube_id            integer      not null default 0,
    ekleyen            integer      not null default 0,
    ekleme_tarihi      timestamptz  not null default now(),
    degistiren         integer      not null default 0,
    degistirme_tarihi  timestamptz
);
comment on table public.kalite_zorunlu_egitim is
  'Kurumsal Kalite (1056): zorunlu eğitim tanımı. departman_id null = tüm personel; periyot_ay null = bir kez yeter.';

-- ---------------------------------------------------- tarih çevirici --
create or replace function public.fn_kys_egitim_tarih(p varchar)
returns date language plpgsql immutable as $$
begin
  p := trim(coalesce(p, ''));
  if p ~ '^\d{4}$' then return make_date(p::int, 1, 1); end if;
  if p ~ '^\d{4}-\d{1,2}-\d{1,2}$' then return to_date(p, 'YYYY-MM-DD'); end if;
  if p ~ '^\d{1,2}\.\d{1,2}\.\d{4}$' then return to_date(p, 'DD.MM.YYYY'); end if;
  return null;
exception when others then
  return null;
end $$;

-- Eşleşme anahtarı: kırpılmış, küçük harf; I / İ / ı hepsi 'i'. ICU tr-TR'de
--   lower('ISO') = 'ıso' olur - 'ISO Farkındalık' tanımı 'iso farkındalık'
--   kaydını tutmazdı. Noktalı / noktasız ayrımı eğitim adında anlam taşımaz.
create or replace function public.fn_kys_egitim_anahtar(p varchar)
returns varchar language sql immutable as $$
  select lower(translate(trim(coalesce(p, '')), 'Iİı', 'iii'))
$$;

-- ------------------------------------------------------------ görünümler --
create or replace view public.v_kalite_egitim as
select min(e.id)                                       as id,
       e.ad,
       e.tur,
       case e.tur when 2 then 'Sertifika' else 'Eğitim' end as tur_adi,
       e.kurum                                         as egitmen,
       e.tarih                                         as tarih_metin,
       public.fn_kys_egitim_tarih(e.tarih)             as tarih,
       max(e.gecerlilik)                               as gecerlilik,
       e.sube_id,
       count(*)::integer                               as katilimci,
       string_agg(public.fn_taraf_ad(t.unvan, t.ad, t.soyad)::varchar(120), ', '
                  order by t.ad, t.soyad)              as katilimcilar,
       case when exists (select 1 from public.kalite_zorunlu_egitim z
                          where z.aktif = 1 and public.fn_kys_egitim_anahtar(z.egitim_adi) = public.fn_kys_egitim_anahtar(e.ad))
            then 1 else 0 end::smallint                as zorunlu,
       case when exists (select 1 from public.kalite_zorunlu_egitim z
                          where z.aktif = 1 and public.fn_kys_egitim_anahtar(z.egitim_adi) = public.fn_kys_egitim_anahtar(e.ad))
            then 'Zorunlu' else 'İsteğe bağlı' end     as zorunlu_adi
  from public.personel_egitim e
  join public.taraf t on t.id = e.taraf_id
 where e.tur in (2, 3)
 group by e.ad, e.tur, e.kurum, e.tarih, e.sube_id;

create or replace view public.v_kalite_egitim_eksik as
select row_number() over (order by d.ad nulls last, t.ad, t.soyad, z.egitim_adi)::integer as id,
       t.id                                            as personel_id,
       public.fn_taraf_ad(t.unvan, t.ad, t.soyad)::varchar(120) as ad,
       t.departman::integer                            as departman_id,
       coalesce(d.ad, '')                              as birim,
       z.id                                            as zorunlu_id,
       z.egitim_adi                                    as eksik_egitim,
       s.son_alis,
       case when s.son_alis is not null and z.periyot_ay is not null
            then (s.son_alis + make_interval(months => z.periyot_ay))::date end as son_tarih,
       case when s.son_alis is null then 'Hiç almadı'
            when (s.son_alis + make_interval(months => z.periyot_ay))::date < current_date then 'Süresi geçti'
            else 'Yaklaşıyor' end                      as durum_adi
  from public.taraf t
  join public.kalite_zorunlu_egitim z
    on z.aktif = 1 and (z.departman_id is null or z.departman_id = t.departman)
  left join public.departman d on d.id = t.departman
  left join lateral (
        select max(public.fn_kys_egitim_tarih(e.tarih)) as son_alis
          from public.personel_egitim e
         where e.taraf_id = t.id and public.fn_kys_egitim_anahtar(e.ad) = public.fn_kys_egitim_anahtar(z.egitim_adi)) s on true
 where t.personel = 1 and t.durum = 1
   and (s.son_alis is null
        or (z.periyot_ay is not null
            and (s.son_alis + make_interval(months => z.periyot_ay))::date < current_date + 60));

create or replace view public.v_kalite_zorunlu_egitim as
select z.id, z.egitim_adi, z.departman_id, coalesce(d.ad, 'Tüm personel') as birim,
       z.periyot_ay,
       case when z.periyot_ay is null then 'Bir kez' else z.periyot_ay || ' ayda bir' end as periyot_adi,
       z.aktif, case when z.aktif = 1 then 'Aktif' else 'Pasif' end as aktif_adi,
       z.aciklama, z.sube_id,
       (select count(*) from public.v_kalite_egitim_eksik x where x.zorunlu_id = z.id)::integer as eksik
  from public.kalite_zorunlu_egitim z
  left join public.departman d on d.id = z.departman_id;

