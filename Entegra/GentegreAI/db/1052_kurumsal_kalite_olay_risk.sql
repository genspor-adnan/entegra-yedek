--  Kullanıcı (12.10.2026): "Dokümandan sonra Kalite menüsü aç ve oraya kalite
--  mockuplarını ekle", ardından "daha sade olabilir mi?". Mockuplar
--  Ekranlar/Kalite/kalite_olay_bildirim.html, kalite_risk_yonetimi.html -
--  yalnız liste + kart kısmı. Temel: 1048 (kys modülü, fn_kalite_no, komite).
--
--  OLAY (kalite_olay, OLY-2026-0001): tür, birim, zarar düzeyi, açıklama,
--    anlık müdahale, komite, değerlendirme notu, durum. ANONİM işaretliyse
--    listede bildiren "Anonim" görünür (görünüm kişiyi birleştirmez).
--  RİSK (kalite_risk, RSK-2026-001): süreç / birim, tanım, olasılık 1-5 ×
--    şiddet 1-5 = skor (GENERATED, elle yazılamaz). Düzey eşikleri ayardan
--    (kys.risk_esik_*, 1048) - fn_kys_risk_seviye.
--  DÖF bağı: DÖF (1050) kaynak_tur 2 olay / 4 risk ile kaynağı tutar; burada
--    dof_id (FK YOK - dilimler paralel yazıldı).
--  Numara insert tetikleyicisinde (generic kart da sunucuda numara alır).
--  İdempotent.
-- =============================================================================

begin;

-- ------------------------------------------------------------ kod listeleri --
insert into public.kod_liste (kod, ad)
select v.kod, v.ad from (values
    ('kys.olay_tur',   'Kalite Olay Türü'),
    ('kys.olay_zarar', 'Kalite Olay Zarar Düzeyi')
  ) as v(kod, ad)
 where not exists (select 1 from public.kod_liste k where k.kod = v.kod);

insert into public.kod_deger (liste_id, deger, ad, sira, aktif, ekleyen)
select l.id, v.deger, v.ad, v.deger * 10, 1, 0
  from public.kod_liste l
  join (values
    ('kys.olay_tur', 1, 'Hasta güvenliği'), ('kys.olay_tur', 2, 'Çalışan güvenliği'),
    ('kys.olay_tur', 3, 'Uygunsuzluk / sapma'), ('kys.olay_tur', 4, 'Tesis güvenliği'),
    ('kys.olay_zarar', 1, 'Ramak kala'), ('kys.olay_zarar', 2, 'Zarar yok'), ('kys.olay_zarar', 3, 'Hafif'),
    ('kys.olay_zarar', 4, 'Orta'), ('kys.olay_zarar', 5, 'Ciddi'), ('kys.olay_zarar', 6, 'Ölüm / kalıcı')
  ) as v(liste, deger, ad) on v.liste = l.kod
 where not exists (select 1 from public.kod_deger d where d.liste_id = l.id and d.deger = v.deger);

-- ===================================================================== OLAY ==
create table if not exists public.kalite_olay (
    id                 integer generated by default as identity primary key,
    no                 varchar(20)   not null default '',
    tarih              timestamptz   not null default now(),
    tur                smallint      not null default 1,            -- kys.olay_tur
    departman_id       integer       references public.departman(id),
    zarar              smallint      not null default 2,            -- kys.olay_zarar
    anonim             smallint      not null default 0,
    aciklama           varchar(2000) not null default '',
    anlik_mudahale     varchar(1000) not null default '',
    komite_id          integer       references public.kalite_komite(id),
    degerlendirme_notu varchar(2000) not null default '',
    dof_id             integer,                                     -- kalite_dof (1050), FK yok
    durum              smallint      not null default 1,            -- 1 yeni · 2 değerlendirmede · 3 kapandı
    sube_id            integer       not null default 0,
    ekleyen            integer       not null default 0,
    ekleme_tarihi      timestamptz   not null default now(),
    degistiren         integer       not null default 0,
    degistirme_tarihi  timestamptz
);
comment on table public.kalite_olay is
  'Kurumsal Kalite (1052): olay / ramak kala / uygunsuzluk bildirimi. anonim = 1 ise listede bildiren gösterilmez.';
create index if not exists ix_kalite_olay_tarih on public.kalite_olay (tarih);

-- ==================================================================== RİSK ==
create table if not exists public.kalite_risk (
    id                integer generated by default as identity primary key,
    no                varchar(20)   not null default '',
    surec             varchar(120)  not null default '',
    departman_id      integer       references public.departman(id),
    tanim             varchar(1000) not null default '',
    olasilik          smallint      not null default 3 check (olasilik between 1 and 5),
    siddet            smallint      not null default 3 check (siddet between 1 and 5),
    skor              smallint      generated always as (olasilik * siddet) stored,
    kontrol_onlem     varchar(1000) not null default '',
    sahip_id          integer       references public.taraf(id),
    gozden_gecirme    date,
    dof_id            integer,                                      -- kalite_dof (1050), FK yok
    durum             smallint      not null default 1,             -- 1 açık · 2 önlem uygulanıyor · 3 kabul edildi · 4 kapandı
    sube_id           integer       not null default 0,
    ekleyen           integer       not null default 0,
    ekleme_tarihi     timestamptz   not null default now(),
    degistiren        integer       not null default 0,
    degistirme_tarihi timestamptz
);
comment on table public.kalite_risk is
  'Kurumsal Kalite (1052): risk kaydı (ISO 9001 md. 6.1). Skor = olasılık × şiddet (generated).';

-- ----------------------------------------------------- numara tetikleyicisi --
create or replace function public.fn_kalite_olay_risk_no() returns trigger language plpgsql as $$
begin
  if coalesce(new.no, '') = '' then
    new.no := case tg_table_name when 'kalite_olay' then public.fn_kalite_no('OLY', 4)
                                 else public.fn_kalite_no('RSK', 3) end;
  end if;
  return new;
end $$;

drop trigger if exists tg_kalite_olay_no on public.kalite_olay;
create trigger tg_kalite_olay_no before insert on public.kalite_olay
  for each row execute function public.fn_kalite_olay_risk_no();
drop trigger if exists tg_kalite_risk_no on public.kalite_risk;
create trigger tg_kalite_risk_no before insert on public.kalite_risk
  for each row execute function public.fn_kalite_olay_risk_no();

-- Risk düzeyi: 1 düşük · 2 orta · 3 yüksek · 4 çok yüksek (eşikler ayardan, 1048).
create or replace function public.fn_kys_risk_seviye(p_skor integer) returns smallint
language sql stable as $$
  select case when p_skor is null then null
              when p_skor <= coalesce((select nullif(deger, '')::int from public.referans where anahtar = 'kys.risk_esik_dusuk'), 4) then 1
              when p_skor <= coalesce((select nullif(deger, '')::int from public.referans where anahtar = 'kys.risk_esik_orta'), 9) then 2
              when p_skor <= coalesce((select nullif(deger, '')::int from public.referans where anahtar = 'kys.risk_esik_yuksek'), 14) then 3
              else 4 end::smallint
$$;

-- =================================================================== GÖRÜNÜMLER ==
create or replace view public.v_kalite_olay as
select o.id, o.no, o.tarih, o.tur, coalesce(kt.ad, '') as tur_adi,
       o.departman_id, coalesce(d.ad, '') as birim_adi,
       o.zarar, coalesce(kz.ad, '') as zarar_adi,
       o.anonim,
       case when o.anonim = 1 then 'Anonim' else coalesce(e.unvan, '') end as bildiren_adi,
       o.komite_id, coalesce(k.ad, '') as komite_adi,
       o.dof_id, o.durum,
       case o.durum when 1 then 'Yeni' when 2 then 'Değerlendirmede' when 3 then 'Kapandı' else '' end as durum_adi,
       o.sube_id
  from public.kalite_olay o
  left join public.kod_liste lt on lt.kod = 'kys.olay_tur'
  left join public.kod_deger kt on kt.liste_id = lt.id and kt.deger = o.tur
  left join public.kod_liste lz on lz.kod = 'kys.olay_zarar'
  left join public.kod_deger kz on kz.liste_id = lz.id and kz.deger = o.zarar
  left join public.departman d on d.id = o.departman_id
  left join public.taraf e on e.id = o.ekleyen and o.anonim = 0
  left join public.kalite_komite k on k.id = o.komite_id;

create or replace view public.v_kalite_risk as
select r.id, r.no, r.surec, r.departman_id, coalesce(d.ad, '') as birim_adi, r.tanim,
       r.olasilik, r.siddet, r.skor,
       public.fn_kys_risk_seviye(r.skor) as seviye,
       case public.fn_kys_risk_seviye(r.skor) when 1 then 'Düşük' when 2 then 'Orta' when 3 then 'Yüksek' when 4 then 'Çok yüksek' end as seviye_adi,
       r.kontrol_onlem, r.sahip_id, coalesce(s.unvan, '') as sahip_adi,
       r.gozden_gecirme, (r.gozden_gecirme < current_date and r.durum in (1, 2))::int as gozden_gecirme_gecti,
       r.dof_id, r.durum,
       case r.durum when 1 then 'Açık' when 2 then 'Önlem uygulanıyor' when 3 then 'Kabul edildi' when 4 then 'Kapandı' else '' end as durum_adi,
       r.sube_id
  from public.kalite_risk r
  left join public.departman d on d.id = r.departman_id
  left join public.taraf s on s.id = r.sahip_id;

