--  039_il_ilce_ulke.sql
--
--  Kullanici: "il ilce ulke listesi ekle, sql'de vardi bunlar" - MSSQL BILIM'de
--  ILLER/ILCELER tablolari bulundu. ILLER aslinda IKI ANLAMLI: ILNO 1-81 Turkiye
--  illeri, ILNO 100+ ULKELER (ayni tabloda birlikte - Delphi'nin REHBERADRES
--  "Il/Ulke" tek combosu buradan geliyordu). Burada TEMIZ AYRILDI: public.il (81),
--  public.ulke (232, ILNO>=100), public.ilce (970, il_id FK).
--
--  taraf_adres.il/ilce/ulke kolonlarina DOKUNULMADI (hala varchar, ISIM tutuyor) -
--  bu tablolar sadece cascading SECIM listesi icin (bkz. GenDetayTablo.tsx "adresler"
--  ozel-durumu, id degil AD gonderilip kaydediliyor - semada risksiz).
-- ============================================================================
\set ON_ERROR_STOP on

create table if not exists public.il (
    id  smallint primary key,
    ad  varchar(60) not null
);

create table if not exists public.ulke (
    id  smallint primary key,
    ad  varchar(60) not null
);

create table if not exists public.ilce (
    id      integer primary key,
    il_id   smallint not null references public.il(id),
    ad      varchar(60) not null,
    aktif   smallint not null default 1
);

create index if not exists ix_ilce_il on public.ilce (il_id);

comment on table public.il is 'Turkiye illeri (eski MSSQL ILLER, ILNO 1-81).';
comment on table public.ulke is 'Ulkeler (eski MSSQL ILLER, ILNO >=100 - ayni tabloda iki-anlamli tutuluyordu).';
comment on table public.ilce is 'Ilceler (eski MSSQL ILCELER), il_id ile Turkiye iline bagli.';

