-- ------------------------------------------------------------- gorunum ----
-- Liste ekrani (firsat_listesi.html): musteri, sektor, temsilci ve AGIRLIKLI
--   tutar burada birlestirilir.
create or replace view public.v_firsat_liste as
select f.id, f.firsat_no, f.konu, f.taraf_id,
       coalesce(t.unvan, '') as taraf_unvan,
       coalesce(sk.ad, '')   as sektor,
       f.sorumlu_id, coalesce(s.unvan, '') as sorumlu_adi,
       f.kaynak, f.tur, f.asama, f.oncelik, f.durum,
       f.tahmini_tutar, f.doviz_cinsi, f.doviz_kuru, f.olasilik,
       round(f.tahmini_tutar * f.olasilik / 100.0, 2) as agirlikli_tutar,
       f.beklenen_kapanis, f.son_temas, f.sonraki_aksiyon,
       f.kapanis_tarihi, f.kayip_nedeni, f.aciklama, f.sube_id, f.ekleme_tarihi
  from public.firsat f
  left join public.taraf t on t.id = f.taraf_id
  left join public.taraf s on s.id = f.sorumlu_id
  left join public.kod_liste kls on kls.kod = 'taraf.sektor'
  left join public.kod_deger sk  on sk.liste_id = kls.id and sk.deger = t.sektor;

comment on view public.v_firsat_liste is
  'Firsat listesi (121): musteri/sektor/temsilci adlari + agirlikli tutar.';

