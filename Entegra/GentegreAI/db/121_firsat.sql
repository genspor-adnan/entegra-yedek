\set ON_ERROR_STOP on

create table if not exists public.firsat (
    id                bigint generated by default as identity primary key,
    firsat_no         varchar(30)  not null default '',
    konu              varchar(200) not null,
    aciklama          text         not null default '',

    -- KIM: musteri ya da henuz cari acilmamis ADAY (taraf kaydi yine acilir).
    taraf_id          bigint       references public.taraf(id),
    sorumlu_id        bigint       references public.taraf(id),

    kaynak            smallint     not null default 0,
    tur               smallint     not null default 0,
    asama             smallint     not null default 1,
    oncelik           smallint     not null default 2,
    -- 1 Açık · 2 Kazanıldı · 3 Kaybedildi · 0 İptal
    durum             smallint     not null default 1,

    tahmini_tutar     numeric(19,4) not null default 0,
    doviz_cinsi       varchar(6)    not null default 'TL',
    doviz_kuru        numeric(19,6) not null default 1,
    olasilik          smallint      not null default 0,

    beklenen_kapanis  date,
    son_temas         timestamp,
    sonraki_aksiyon   varchar(200) not null default '',
    kapanis_tarihi    timestamp,
    kayip_nedeni      varchar(200) not null default '',

    sube_id           integer      not null default 0,
    ekleyen           integer      not null default 0,
    ekleme_tarihi     timestamp    not null default now()::timestamp,
    degistiren        integer      not null default 0,
    degistirme_tarihi timestamp,

    constraint ck_firsat_olasilik check (olasilik between 0 and 100),
    constraint ck_firsat_durum    check (durum between 0 and 3)
);

comment on table public.firsat is
  'Satis firsati (121). Teklif oncesi surec: aday, asama, tahmini tutar, olasilik.';
comment on column public.firsat.olasilik is
  'Kapanma olasiligi %. Agirlikli tutar = tahmini_tutar x olasilik / 100 (SAKLANMAZ, hesaplanir).';
comment on column public.firsat.durum is '1 Açık · 2 Kazanıldı · 3 Kaybedildi · 0 İptal';

create index if not exists ix_firsat_taraf   on public.firsat (taraf_id);
create index if not exists ix_firsat_sorumlu on public.firsat (sorumlu_id, durum);
create index if not exists ix_firsat_asama   on public.firsat (asama, durum);
create index if not exists ix_firsat_kapanis on public.firsat (beklenen_kapanis) where durum = 1;
create unique index if not exists ux_firsat_no on public.firsat (firsat_no) where firsat_no <> '';

-- --------------------------------------------------------------- urunler ----
create table if not exists public.firsat_urun (
    id                bigint generated by default as identity primary key,
    firsat_id         bigint  not null references public.firsat(id) on delete cascade,
    sira              smallint not null default 0,
    stok_id           integer  references public.stok(id),
    hizmet_id         integer  references public.hizmet(id),
    aciklama          varchar(200) not null default '',
    miktar            numeric(19,4) not null default 0,
    birim_fiyat       numeric(19,4) not null default 0,
    tutar             numeric(19,4) not null default 0,
    ekleyen           integer      not null default 0,
    ekleme_tarihi     timestamp    not null default now()::timestamp,
    degistiren        integer      not null default 0,
    degistirme_tarihi timestamp
);

comment on table public.firsat_urun is
  'Firsatta talep edilen kalemler (121). TAHMINDIR - stok/cari etkilemez, belge degildir.';

create index if not exists ix_firsat_urun_firsat on public.firsat_urun (firsat_id);

-- -------------------------------------------------------- asama gecmisi ----
create table if not exists public.firsat_asama_gecmis (
    id            bigint generated by default as identity primary key,
    firsat_id     bigint   not null references public.firsat(id) on delete cascade,
    asama         smallint not null,
    olasilik      smallint not null default 0,
    giris         timestamp not null default now()::timestamp,
    cikis         timestamp,
    degistiren    integer  not null default 0
);

comment on table public.firsat_asama_gecmis is
  'Firsatin asamada ne kadar kaldigi (121). TETIKLE yazilir - ekran unutamaz.';

-- Asamada gecen GUN: SAKLANMAZ, gorunumde hesaplanir. Acik asamada "bugune
--   kadar" demek her gun degisen bir deger demektir; generated column bunu
--   kabul etmez (immutable degil) ve saklansa da bayatlardi.
create or replace view public.v_firsat_asama_gecmis as
select g.id, g.firsat_id, g.asama, g.olasilik, g.giris, g.cikis,
       greatest(0, (extract(epoch from (coalesce(g.cikis, now()::timestamp) - g.giris)) / 86400)::integer)
         as sure_gun
  from public.firsat_asama_gecmis g;

create index if not exists ix_firsat_asama_gecmis on public.firsat_asama_gecmis (firsat_id, giris);

-- ------------------------------------------------------------- tetikler ----
create or replace function public.fn_firsat_asama_izle() returns trigger
language plpgsql as $$
begin
    if tg_op = 'INSERT' then
        insert into public.firsat_asama_gecmis (firsat_id, asama, olasilik, degistiren)
        values (new.id, new.asama, new.olasilik, new.ekleyen);
        return new;
    end if;

    if new.asama is distinct from old.asama then
        update public.firsat_asama_gecmis
           set cikis = now()::timestamp
         where firsat_id = new.id and cikis is null;

        insert into public.firsat_asama_gecmis (firsat_id, asama, olasilik, degistiren)
        values (new.id, new.asama, new.olasilik, new.degistiren);
    end if;
    return new;
end $$;

comment on function public.fn_firsat_asama_izle() is
  'Asama degisimini firsat_asama_gecmis''e yazar (121).';

-- Firsat numarasi: kullanici bos birakirsa FRS.<yil>-<id> olarak uretilir.
--   Numara ID''den turedigi icin bosluk/mukerrer olusmaz.
create or replace function public.fn_firsat_no_uret() returns trigger
language plpgsql as $$
begin
    if coalesce(new.firsat_no, '') = '' then
        update public.firsat
           set firsat_no = 'FRS.' || to_char(coalesce(new.ekleme_tarihi, now()), 'YYYY')
                                  || '-' || lpad(new.id::text, 4, '0')
         where id = new.id and coalesce(firsat_no, '') = '';
    end if;
    return null;
end $$;

do $$
begin
    if not exists (select 1 from pg_trigger where tgname = 'trg_firsat_degistirme') then
        create trigger trg_firsat_degistirme before update on public.firsat
            for each row execute function public.fn_degistirme_tarihi();
    end if;
    if not exists (select 1 from pg_trigger where tgname = 'trg_firsat_urun_degistirme') then
        create trigger trg_firsat_urun_degistirme before update on public.firsat_urun
            for each row execute function public.fn_degistirme_tarihi();
    end if;
    if not exists (select 1 from pg_trigger where tgname = 'trg_firsat_asama') then
        create trigger trg_firsat_asama after insert or update on public.firsat
            for each row execute function public.fn_firsat_asama_izle();
    end if;
    if not exists (select 1 from pg_trigger where tgname = 'trg_firsat_no') then
        create trigger trg_firsat_no after insert on public.firsat
            for each row execute function public.fn_firsat_no_uret();
    end if;
end $$;

