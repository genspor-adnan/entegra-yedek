--
--  Kullanıcı (12.10.2026): "Dokümandan sonra Kalite menüsü aç ve oraya kalite
--  mockuplarını ekle", sonra "daha sade olabilir mi?". Mockuplar
--  Ekranlar/Kalite/kalite_hedef_gosterge.html ve kalite_ygg_toplanti.html;
--  yalnız çekirdekleri yapıldı:
--    GÖSTERGE: tanım (kod, ad, formül, hedef, yön, periyot, birim, sorumlu) +
--      dönem değerleri (dönem, değer). Listede son değer ve hedefte / hedef
--      dışı durumu. Yön 1 "≤ hedef" (düşük iyi) · 2 "≥ hedef" (yüksek iyi).
--      Klinik Kalite göstergeleri (711) AYRI modüldür.
--    TOPLANTI: tarih, komite (boş = YGG), yer, gündem ve katılımcılar metin;
--      kararlar (karar, sorumlu, termin, durum). Karar Takibi ayrı liste.
--  Temel: 1048 (kalite_komite, yetki kys.gosterge / kys.toplanti).
--  İdempotent.
-- =============================================================================

begin;

create table if not exists public.kalite_gosterge (
    id                 integer generated by default as identity primary key,
    kod                varchar(20)  not null,
    ad                 varchar(200) not null,
    formul             varchar(400) not null default '',
    hedef              numeric(18,4),
    yon                smallint     not null default 1,
    periyot_ay         smallint     not null default 1,
    departman_id       integer      references public.departman(id),
    sorumlu_id         integer      references public.taraf(id),
    aktif              smallint     not null default 1,
    sube_id            integer      not null default 0,
    ekleyen            integer      not null default 0,
    ekleme_tarihi      timestamptz  not null default now(),
    degistiren         integer      not null default 0,
    degistirme_tarihi  timestamptz
);
comment on table public.kalite_gosterge is
  'Kurumsal Kalite (1053): kurumun kalite göstergeleri. yon 1 ≤ hedef (düşük iyi) · 2 ≥ hedef (yüksek iyi); periyot_ay 1/3/6/12.';

create table if not exists public.kalite_gosterge_deger (
    id                 integer generated by default as identity primary key,
    gosterge_id        integer      not null references public.kalite_gosterge(id) on delete cascade,
    donem              date         not null,
    deger              numeric(18,4) not null,
    aciklama           varchar(400) not null default '',
    ekleyen            integer      not null default 0,
    ekleme_tarihi      timestamptz  not null default now(),
    constraint uq_kalite_gosterge_deger unique (gosterge_id, donem)
);

create table if not exists public.kalite_toplanti (
    id                 integer generated by default as identity primary key,
    tarih              timestamptz  not null,
    komite_id          integer      references public.kalite_komite(id),
    yer                varchar(120) not null default '',
    gundem             varchar(4000) not null default '',
    katilimcilar       varchar(2000) not null default '',
    sube_id            integer      not null default 0,
    ekleyen            integer      not null default 0,
    ekleme_tarihi      timestamptz  not null default now(),
    degistiren         integer      not null default 0,
    degistirme_tarihi  timestamptz
);
comment on table public.kalite_toplanti is
  'Kurumsal Kalite (1053): komite toplantıları; komite_id boş = Yönetimin Gözden Geçirmesi (YGG).';

create table if not exists public.kalite_karar (
    id                 integer generated by default as identity primary key,
    toplanti_id        integer      not null references public.kalite_toplanti(id),
    karar              varchar(1000) not null,
    sorumlu_id         integer      references public.taraf(id),
    termin             date,
    durum              smallint     not null default 1,
    sube_id            integer      not null default 0,
    ekleyen            integer      not null default 0,
    ekleme_tarihi      timestamptz  not null default now(),
    degistiren         integer      not null default 0,
    degistirme_tarihi  timestamptz
);
comment on table public.kalite_karar is 'Kurumsal Kalite (1053): toplantı kararları. durum 1 açık · 2 tamam · 3 iptal.';
create index if not exists ix_kalite_karar_toplanti on public.kalite_karar (toplanti_id);

create or replace view public.v_kalite_gosterge as
select g.id, g.kod, g.ad, g.formul, g.hedef, g.yon,
       case when g.hedef is null then '' else (case g.yon when 2 then '≥ ' else '≤ ' end)
            || trim(trailing '.' from to_char(g.hedef, 'FM999999990.####')) end as hedef_metin,
       g.periyot_ay, case g.periyot_ay when 1 then 'Aylık' when 3 then '3 aylık' when 6 then '6 aylık' when 12 then 'Yıllık'
                                       else g.periyot_ay || ' aylık' end as periyot_adi,
       g.departman_id, coalesce(dp.ad, '') as birim_adi,
       g.sorumlu_id, coalesce((public.fn_taraf_ad(t.unvan, t.ad, t.soyad))::varchar(120), '') as sorumlu_adi,
       s.donem as son_donem, s.deger as son_deger,
       case when g.aktif = 0 then 'Pasif'
            when s.deger is null or g.hedef is null then 'Veri yok'
            when (g.yon = 1 and s.deger <= g.hedef) or (g.yon = 2 and s.deger >= g.hedef) then 'Hedefte'
            else 'Hedef dışı' end as durum_adi,
       g.aktif, g.sube_id, g.ekleme_tarihi
  from public.kalite_gosterge g
  left join lateral (select d.donem, d.deger from public.kalite_gosterge_deger d
                      where d.gosterge_id = g.id order by d.donem desc limit 1) s on true
  left join public.departman dp on dp.id = g.departman_id
  left join public.taraf t on t.id = g.sorumlu_id;

create or replace view public.v_kalite_toplanti as
select tp.id, tp.tarih, tp.komite_id,
       coalesce(k.ad, 'Yönetimin Gözden Geçirmesi (YGG)') as kurul_adi,
       tp.yer, tp.gundem, tp.katilimcilar,
       (select count(*) from public.kalite_karar kr where kr.toplanti_id = tp.id)::int as karar_sayisi,
       (select count(*) from public.kalite_karar kr where kr.toplanti_id = tp.id and kr.durum = 1)::int as acik_karar,
       tp.sube_id, tp.ekleme_tarihi
  from public.kalite_toplanti tp
  left join public.kalite_komite k on k.id = tp.komite_id;

create or replace view public.v_kalite_karar as
select kr.id, kr.toplanti_id, tp.tarih as toplanti_tarihi,
       coalesce(k.ad, 'YGG') as kurul_adi,
       kr.karar, kr.sorumlu_id, coalesce((public.fn_taraf_ad(t.unvan, t.ad, t.soyad))::varchar(120), '') as sorumlu_adi,
       kr.termin, case when kr.durum = 1 and kr.termin is not null then kr.termin - current_date end as kalan_gun,
       kr.durum,
       case when kr.durum = 1 and kr.termin < current_date then 'Gecikti'
            else case kr.durum when 1 then 'Açık' when 2 then 'Tamam' when 3 then 'İptal' else '' end end as durum_adi,
       kr.sube_id, kr.ekleme_tarihi
  from public.kalite_karar kr
  join public.kalite_toplanti tp on tp.id = kr.toplanti_id
  left join public.kalite_komite k on k.id = tp.komite_id
  left join public.taraf t on t.id = kr.sorumlu_id;

create or replace view public.v_kalite_toplanti_lookup as
select tp.id, (to_char(tp.tarih, 'DD.MM.YYYY') || ' · ' || coalesce(k.ad, 'YGG'))::varchar(160) as ad, 1 as aktif, null::integer as ust_id
  from public.kalite_toplanti tp
  left join public.kalite_komite k on k.id = tp.komite_id;

insert into public.ai_rehber_ekran (kaynak, rota, baslik, yol, menu_grup, menu_ad,
                                    yetki_kodu, urun_modu, anahtar, aciklama, aksiyon_ekrani)
select v.kaynak, v.rota, v.baslik, v.yol, 'Kalite', v.menu_ad, v.yetki_kodu, 0, v.anahtar, v.aciklama, v.aksiyon
  from (values
    ('kys-gosterge', '/kys-gosterge', 'Kalite Göstergeleri', 'Kalite › Göstergeler', 'Göstergeler', 'kys.gosterge',
     'kalite gösterge hedef formül periyot dönem değeri hedef dışı',
     'Gösterge tanımı (kod, ad, formül, hedef, yön, periyot) ve dönem değerleri; listede son değer ve hedefte / hedef dışı.', 'kys-gosterge-liste'),
    ('kys-toplanti', '/kys-toplanti', 'Kalite Toplantıları', 'Kalite › Toplantılar', 'Toplantılar', 'kys.toplanti',
     'toplantı komite ygg yönetimin gözden geçirmesi gündem katılımcı karar',
     'Komite ve YGG toplantıları (komite boş = YGG); gündem, katılımcılar ve kararlar.', 'kys-toplanti-liste'),
    ('kys-karar', '/kys-karar', 'Karar Takibi', 'Kalite › Karar Takibi', 'Karar Takibi', 'kys.toplanti',
     'karar takibi sorumlu termin geciken açık karar',
     'Toplantı kararları: sorumlu, termin, kalan gün, durum (açık / gecikti / tamam).', 'kys-karar-liste'))
    as v(kaynak, rota, baslik, yol, menu_ad, yetki_kodu, anahtar, aciklama, aksiyon)
 where not exists (select 1 from public.ai_rehber_ekran e where e.kaynak = v.kaynak);

commit;
