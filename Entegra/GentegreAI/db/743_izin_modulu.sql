  from public.onay_akis k
  cross join (values
        -- ÂMİR HER İZİNDE: birimin ayakta kalıp kalmayacağını bilen kişi.
        (1::smallint, 'Birim Âmiri',   3::smallint, 0::smallint, null::numeric, '', 2::smallint),
        -- İK HER İZİNDE: bakiyeyi ve kanunî hakkı denetleyen yer.
        (2::smallint, 'İnsan Kaynakları', 1::smallint, 6::smallint, null::numeric, '', 3::smallint),
        -- UZUN İZİN ÜST YÖNETİME: on günü aşan izin birimi haftalarca etkiler.
        (3::smallint, 'Üst Yönetim',   1::smallint, 5::smallint, 10::numeric, '', 5::smallint),
        -- BAKİYESİZ İZİN ayrıca sorulur: hakkı olmayan personele izin
        --   vermek ücretsiz izin ya da avans izindir - ayrı bir karardır.
        (4::smallint, 'İK (bakiye aşımı)', 1::smallint, 6::smallint, null::numeric,
         'bakiye_asildi', 3::smallint)
      ) as x(sira, ad, sahip, rol, esik, bayrak, sure)
 where k.kod = 'personel.izin'
   and not exists (select 1 from public.onay_akis_adim a where a.akis_id = k.id);
