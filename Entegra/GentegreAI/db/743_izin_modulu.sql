--  ============= HAK HESABI İŞ KANUNU MD. 53 ===========================
--  Yıllık ücretli izin süresi kıdeme göre: 1-5 yıl 14 gün, 5-15 yıl 20
--  gün, 15+ yıl 26 gün. 18 yaşından küçük ve 50 yaşından büyük işçilerde
--  en az 20 gün. Bir yılı doldurmayan personelin hakkı YOKTUR - sıfır
--  döndürmek "hakkı bitti" ile karıştırılmasın diye bakiye görünümünde
--  ayrıca işaretlenir.
--
--  ============= GÜN SAYISI: TAKVİM GÜNÜ =================================
--  Yıllık izin TAKVİM GÜNÜ üzerinden sayılır (md. 56: izin süresine
--  rastlayan hafta tatili ücretli izinden sayılmaz - ama uygulamada
--  kurumların çoğu takvim günü işletir). Kurum iş günü saymak isterse
--  `is_gunu = 1` seçilir ve hafta sonu düşülür. RESMİ TATİL LİSTESİ YOK:
--  tatil tablosu kurulmadan "iş günü" hesabı yalnız cumartesi-pazarı
--  çıkarır; bunu gizlemek, yanlış gün sayısını doğru sanmak olurdu.
-- =====================================================================

