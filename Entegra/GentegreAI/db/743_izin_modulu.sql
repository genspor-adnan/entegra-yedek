--  `personel_izin` 052'den beri vardı ama yalnız bir KAYIT DEFTERİYDİ:
--  `durum` kolonu dışında onaylayanı, gerekçesi, hakkı yoktu. İzin
--  "onaylandı" yazılabiliyordu ama kimin onayladığı, personelin o günü
--  olup olmadığı hiçbir yerde durmuyordu.
