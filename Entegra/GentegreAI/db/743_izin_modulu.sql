-- ============================================================= HAKEDİŞ
-- YIL BAZLI HAK + DEVİR. Hak kıdemden hesaplanır ama tabloda TUTULUR:
--   kurum fazladan gün verebilir (toplu sözleşme, kıdem ödülü) ve
--   hesaplanan değeri her açılışta yeniden türetmek o kararı silerdi.
create table if not exists public.personel_izin_hak (
    id                integer      primary key generated by default as identity,
    taraf_id          integer      not null,
    yil               smallint     not null,
    -- Kanunî hak (kıdemden hesaplanan).
    hak_gun           numeric(6,2) not null default 0,
    -- Önceki yıldan devreden. İş Kanunu devri yasaklamaz; kurum kuralı.
    devir_gun         numeric(6,2) not null default 0,
    -- Kurumun ek verdiği gün (sözleşme, ödül).
    ek_gun            numeric(6,2) not null default 0,
    aciklama          varchar(300) not null default '',
    sube_id           integer,
    ekleyen           integer      not null default 0,
    ekleme_tarihi     timestamptz  not null default now(),
    degistiren        integer      not null default 0,
    degistirme_tarihi timestamptz
);

create unique index if not exists ux_personel_izin_hak
    on public.personel_izin_hak (taraf_id, yil);

comment on table public.personel_izin_hak is
  '743: yil bazli yillik izin hakki. Kidemden hesaplanir ama TUTULUR - '
  'kurumun ek verdigi gun her acilista silinmesin.';

-- =========================================== KIDEME GÖRE HAK (md. 53)
create or replace function public.fn_izin_hak_gun(
    p_ise_giris date, p_yil smallint, p_dogum date default null)
returns numeric
language plpgsql immutable as $$
declare
    v_kidem numeric;
    v_gun   numeric;
    v_yas   numeric;
begin
    -- İŞE GİRİŞ YOKSA HESAP YOK. Sıfır dönmek "hakkı bitti" ile
    --   karıştırılır; null "hesaplanamıyor" demektir ve bakiye görünümü
    --   bunu ayrıca söyler.
    if p_ise_giris is null or p_yil is null then return null; end if;

    -- Kıdem: izin yılının SONUNDA doldurulan yıl sayısı.
    v_kidem := extract(year from age(make_date(p_yil, 12, 31), p_ise_giris));

    if v_kidem < 1 then
        -- BİR YILI DOLDURMAYAN personelin yıllık izin hakkı doğmaz (md. 53).
        return 0;
    elsif v_kidem < 5 then
        v_gun := 14;
    elsif v_kidem < 15 then
        v_gun := 20;
    else
        v_gun := 26;
    end if;

    -- 18 YAŞ ALTI / 50 YAŞ ÜSTÜ: en az 20 gün (md. 53/4).
    if p_dogum is not null then
        v_yas := extract(year from age(make_date(p_yil, 12, 31), p_dogum));
        if (v_yas < 18 or v_yas > 50) and v_gun < 20 then v_gun := 20; end if;
    end if;

    return v_gun;
end $$;

comment on function public.fn_izin_hak_gun(date, smallint, date) is
  '743: Is Kanunu md.53 yillik izin hakki. NULL = ise giris yok, '
  'hesaplanamiyor (0 ile karistirilmasin).';

-- ================================================ GÜN SAYISI HESABI
create or replace function public.fn_izin_gun(
    p_bas date, p_bit date, p_is_gunu smallint default 0)
returns numeric
language sql immutable as $$
    select case
      when p_bas is null or p_bit is null or p_bit < p_bas then 0
      -- TAKVİM GÜNÜ: iki uç dahil.
      when coalesce(p_is_gunu, 0) = 0 then (p_bit - p_bas + 1)::numeric
      -- İŞ GÜNÜ: hafta sonu düşülür. RESMİ TATİL DÜŞÜLMEZ - tatil
      --   tablosu yok; olmayan bir listeye dayanıp "doğru" gün üretmek,
      --   yanlış sayıyı doğru sanmaktır (bkz. dosya başlığı).
      else (select count(*)::numeric from generate_series(p_bas, p_bit, interval '1 day') g
             where extract(isodow from g) < 6)
    end $$;

comment on function public.fn_izin_gun(date, date, smallint) is
  '743: izin gun sayisi. is_gunu=1 ise hafta sonu dusulur; RESMI TATIL '
  'dusulmez (tatil tablosu yok).';

-- ==================================================== BAKİYE GÖRÜNÜMÜ
-- KULLANILAN ile PLANLANAN AYRI: onaylanmış ama henüz başlamamış izin
--   bakiyeden düşer (o gün taahhüt edilmiştir) ama "kullanıldı" değildir.
--   Tek sayı gösterseydik personel "iznim duruyor" sanıp ikinci kez
--   talep ederdi.
create or replace view public.v_personel_izin_bakiye as
select t.id                                            as taraf_id,
       coalesce(nullif(t.unvan, ''), '')               as personel_ad,
       p.ise_giris_tarihi,
       y.yil,
       -- TANIMLI HAK varsa o, yoksa kıdemden hesaplanan.
       coalesce(h.hak_gun, public.fn_izin_hak_gun(p.ise_giris_tarihi, y.yil,
                                                  p.dogum_tarihi))  as hak_gun,
       coalesce(h.devir_gun, 0)                        as devir_gun,
       coalesce(h.ek_gun, 0)                           as ek_gun,
       -- YALNIZ YILLIK İZİN (tür 1) bakiyeden düşer: rapor ve ücretsiz
       --   izin yıllık izin hakkını tüketmez.
       coalesce((select sum(i.gun) from public.personel_izin i
                  where i.taraf_id = t.id and i.tur = 1 and i.durum = 2
                    and extract(year from i.baslangic_tarihi) = y.yil
                    and i.bitis_tarihi < current_date), 0)  as kullanilan_gun,
       coalesce((select sum(i.gun) from public.personel_izin i
                  where i.taraf_id = t.id and i.tur = 1 and i.durum = 2
                    and extract(year from i.baslangic_tarihi) = y.yil
                    and i.bitis_tarihi >= current_date), 0) as planlanan_gun,
       coalesce((select sum(i.gun) from public.personel_izin i
                  where i.taraf_id = t.id and i.tur = 1 and i.durum in (0, 1)
                    and extract(year from i.baslangic_tarihi) = y.yil), 0) as onayda_gun,
       p.sube_id
  from public.taraf t
  join public.taraf_personel p on p.id = t.id
  cross join (select extract(year from current_date)::smallint as yil) y
  left join public.personel_izin_hak h on h.taraf_id = t.id and h.yil = y.yil
 where t.personel = 1;

comment on view public.v_personel_izin_bakiye is
  '743: personelin bu yilki izin bakiyesi. KULLANILAN ile PLANLANAN ayri - '
  'onayli ama baslamamis izin bakiyeden duser, "kullanildi" degildir.';

-- ================================================== İZİN LİSTE GÖRÜNÜMÜ
create or replace view public.v_personel_izin as
select i.id,
       i.taraf_id,
       coalesce(nullif(t.unvan, ''), '')               as personel_ad,
       coalesce(nullif(p.gorev, ''), '')               as gorev_ad,
       p.yonetici_taraf_id,
       coalesce(nullif(am.unvan, ''), '')              as amir_ad,
       i.izin_no,
       i.tur,
       i.baslangic_tarihi,
       i.bitis_tarihi,
       i.gun,
       i.is_gunu,
       i.durum,
       i.aciklama,
       i.red_neden,
       i.iptal_neden,
       i.belge_no,
       i.yerine_id,
       coalesce(nullif(yt.unvan, ''), '')              as yerine_ad,
       i.talep_tarihi,
       i.sube_id,
       -- ONAY ZİNCİRİ (738 omurgası): bekleyen basamak ve gecikmesi.
       (select v.adim_ad from public.v_onay_bekleyen v
         where v.kaynak_tur = 904 and v.kaynak_id = i.id
         order by v.sira limit 1)                      as bekleyen_basamak,
       coalesce((select max(v.gecikme_gun) from public.v_onay_bekleyen v
                  where v.kaynak_tur = 904 and v.kaynak_id = i.id), 0)
                                                       as onay_gecikme_gun,
       -- ÇAKIŞMA: AYNI ÂMİRE BAĞLI başka personel aynı günlerde izinli mi.
       --   Onaylayanın sorması gereken soru "bu kişi gidebilir mi" değil,
       --   "ekip ayakta kalır mı".
       --
       --   BİRİM DEĞİL ÂMİR: `taraf_personel.gorev` serbest metindir,
       --   departman bağı taşımaz - departmana göre saymak, olmayan bir
       --   bağa dayanıp her zaman sıfır döndürmek olurdu. Âmir bağı ise
       --   gerçek bir kolon (`yonetici_taraf_id`) ve izni onaylayan da o.
       (select count(*) from public.personel_izin x
          join public.taraf_personel xp on xp.id = x.taraf_id
         where x.id <> i.id and x.durum = 2
           and p.yonetici_taraf_id is not null
           and xp.yonetici_taraf_id = p.yonetici_taraf_id
           and x.baslangic_tarihi <= i.bitis_tarihi
           and x.bitis_tarihi >= i.baslangic_tarihi)   as cakisan_izin,
       i.ekleme_tarihi,
       i.degistirme_tarihi
  from public.personel_izin i
  join public.taraf t            on t.id = i.taraf_id
  left join public.taraf_personel p on p.id = i.taraf_id
  left join public.taraf yt      on yt.id = i.yerine_id
  left join public.taraf am      on am.id = p.yonetici_taraf_id;

comment on view public.v_personel_izin is
  '743: izin listesi - bekleyen onay basamagi, gecikme ve ayni birimdeki '
  'cakisan izin sayisi.';

-- ========================================== ONAY AKIŞI (738 omurgası)
-- ÂMİR BASAMAĞI (sahip_turu 3): izin talebinin doğal ilk onayı kişinin
