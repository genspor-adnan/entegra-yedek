create index if not exists ix_konsultasyon_hedef   on public.konsultasyon (hedef_bolum_id, durum);
create index if not exists ix_konsultasyon_hekim   on public.konsultasyon (hedef_hekim_id) where hedef_hekim_id is not null;
create index if not exists ix_konsultasyon_isteyen on public.konsultasyon (isteyen_hekim_id);
create index if not exists ix_konsultasyon_muayene on public.konsultasyon (isteyen_muayene_id);
create unique index if not exists ux_konsultasyon_yanit on public.konsultasyon (yanit_muayene_id) where yanit_muayene_id is not null;
comment on table public.konsultasyon is
  '1107: konsültasyon İSTEĞİ (kime, ne kadar acil, nerede, kim yanıtladı). Yanıt tür 3 muayenedir (yanit_muayene_id).';

-- Numara + son zaman: süre aciliyetten; aciliyet değişince yeniden, yönlendirmede değil.
create or replace function public.tg_konsultasyon_kayit() returns trigger language plpgsql as $$
begin
  if tg_op = 'INSERT' and coalesce(new.no, '') = '' then
    new.no := public.fn_konsultasyon_no();
  end if;
  if tg_op = 'INSERT' or new.aciliyet is distinct from old.aciliyet or new.son_zaman is null then
    new.son_zaman := new.istek_zamani + case new.aciliyet when 3 then interval '30 minutes'
                                                          when 2 then interval '2 hours'
                                                          else interval '24 hours' end;
  end if;
  -- KART YALNIZ TASLAK <-> GÖNDERİLDİ (6 <-> 1) yapabilir; diğer geçişler uçlardadır
  --   (KonsultasyonUclari: set_config('kons.uc', '1', true)). Yanıtlanmaya alınmış
  --   isteğin sorusu değişmez - soru isteyen hekimindir.
  if coalesce(current_setting('kons.uc', true), '') <> '1' then
    if tg_op = 'INSERT' and new.durum not in (6, 1) then
      raise exception 'Konsültasyon taslak ya da gönderilmiş olarak açılır.' using errcode = 'P0001';
    end if;
    if tg_op = 'UPDATE' and new.durum is distinct from old.durum
       and not ((old.durum = 6 and new.durum = 1) or (old.durum = 1 and new.durum = 6 and old.yanitlayan_id is null)) then
      raise exception 'Konsültasyon durumu bu ekrandan değiştirilemez (yanıtla / yönlendir / reddet kullanın).' using errcode = 'P0001';
    end if;
    if tg_op = 'UPDATE' and old.durum not in (6, 1) and new.soru is distinct from old.soru then
      raise exception 'Yanıtlanmaya alınmış konsültasyonun sorusu değiştirilemez.' using errcode = 'P0001';
    end if;
  end if;
  if tg_op = 'UPDATE' then new.degistirme_tarihi := now(); end if;
  return new;
end $$;

-- Gönderilince (taslaktan 1'e ya da doğrudan 1 açılınca) akışın "İstek" adımı.
create or replace function public.tg_konsultasyon_gonderildi() returns trigger language plpgsql as $$
begin
  if new.durum = 1 and (tg_op = 'INSERT' or old.durum = 6)
     and not exists (select 1 from public.konsultasyon_hareket h where h.konsultasyon_id = new.id and h.tur = 1) then
    insert into public.konsultasyon_hareket (konsultasyon_id, tur, kullanici_id)
    values (new.id, 1, coalesce(nullif(new.degistiren, 0), new.ekleyen));
  end if;
  return new;
end $$;
drop trigger if exists trg_konsultasyon_kayit on public.konsultasyon;
create trigger trg_konsultasyon_kayit before insert or update on public.konsultasyon
  for each row execute function public.tg_konsultasyon_kayit();

-- ----------------------------------------------------------------- hareket --
--  Akış şeridinin zamanları ve ret / yönlendirme izi. tur: 1 istek gönderildi ·
--  2 yanıtlamaya alındı · 3 yönlendirildi · 4 reddedildi · 5 yanıtlandı · 6 isteyen gördü · 7 iptal
create table if not exists public.konsultasyon_hareket (
    id               integer generated by default as identity primary key,
    konsultasyon_id  integer      not null references public.konsultasyon(id) on delete cascade,
    tur              smallint     not null,
    aciklama         varchar(400) not null default '',
    eski_bolum_id    integer,
    yeni_bolum_id    integer,
    kullanici_id     integer      not null default 0,
    zaman            timestamptz  not null default now()
);
create index if not exists ix_konsultasyon_hareket on public.konsultasyon_hareket (konsultasyon_id, zaman);
drop trigger if exists trg_konsultasyon_gonderildi on public.konsultasyon;
create trigger trg_konsultasyon_gonderildi after insert or update of durum on public.konsultasyon
  for each row execute function public.tg_konsultasyon_gonderildi();

-- ---------------------------------------- yanıt muayenesi tamamlanınca --
--  Yanıt muayenesi tamamlanınca istek "yanıtlandı" olur (tamamlama ucunu
--  değiştirmeden; muayene durumu 3 = tamamlandı).
create or replace function public.tg_muayene_konsultasyon_yanit() returns trigger language plpgsql as $$
begin
  if new.durum = 3 and old.durum is distinct from 3 then
    perform set_config('kons.uc', '1', true);   -- kart dışı geçiş (tetik kapısı)
    update public.konsultasyon k
       set durum = 3, yanit_zamani = coalesce(k.yanit_zamani, now()), degistiren = coalesce(new.tamamlayan_id, k.degistiren)
     where k.yanit_muayene_id = new.id and k.durum in (1, 2);
    insert into public.konsultasyon_hareket (konsultasyon_id, tur, kullanici_id)
    select k.id, 5, coalesce(new.tamamlayan_id, 0) from public.konsultasyon k
     where k.yanit_muayene_id = new.id and k.durum = 3
       and not exists (select 1 from public.konsultasyon_hareket h where h.konsultasyon_id = k.id and h.tur = 5);
  end if;
  return new;
end $$;
drop trigger if exists trg_muayene_konsultasyon_yanit on public.muayene;
create trigger trg_muayene_konsultasyon_yanit after update of durum on public.muayene
  for each row execute function public.tg_muayene_konsultasyon_yanit();

-- ------------------------------------------------- eski konsültasyonlar --
--  1107 öncesi açılmış tür-3 / alt muayeneler: istek satırı geriye dönük
--  (bölüme gönderilmiş rutin istek). Tekrar çalışırsa çift satır açmaz.
do $$
begin
  perform set_config('kons.uc', '1', true);   -- tetik kapısı (taslak/gönderildi dışı durum)
  insert into public.konsultasyon (no, sube_id, belge_id, taraf_id, isteyen_muayene_id, isteyen_hekim_id,
                                   istek_bolum_id, istek_zamani, hedef_bolum_id, hedef_hekim_id, soru,
                                   durum, yanitlayan_id, yanitlama_zamani, yanit_muayene_id, yanit_zamani, ekleyen)
  select '', k.sube_id, k.belge_id, k.taraf_id, k.ust_muayene_id, u.personel_id,
         u.bolum_id, k.muayene_tarihi, k.bolum_id, k.personel_id, left(k.konsultasyon_soru, 500),
         case when k.durum = 3 then 3 when k.personel_id is not null then 2 else 1 end,
         k.personel_id, case when k.personel_id is not null then k.muayene_tarihi end,
         k.id, k.tamamlanma, 0
    from public.muayene k
    join public.muayene u on u.id = k.ust_muayene_id
   where not exists (select 1 from public.konsultasyon x where x.yanit_muayene_id = k.id);
end $$;

-- ---------------------------------------------------------------- yetki --
--  Menü kodu = yetki matrisi kodu (Muayene › Konsültasyon Listesi). Muayene
--  hakkı olan her role aynı hak (istek açmak muayenenin parçası).
insert into public.yetki (kod, ad, grup, tur, sira, aktif, modul, urun_modu)
select 'muayene.konsultasyon', 'Konsültasyonlar (Muayene)', 'Muayene', 0, 250, 1, 'muayene', 2
 where not exists (select 1 from public.yetki where kod = 'muayene.konsultasyon');
insert into public.rol_yetki (rol_id, yetki_id, gor, ekle, degistir, sil, ekleyen)
select ry.rol_id, y.id, ry.gor, ry.ekle, ry.degistir, 0, 0
  from public.rol_yetki ry
  join public.yetki e on e.id = ry.yetki_id and e.kod = 'muayene'
  cross join public.yetki y
 where y.kod = 'muayene.konsultasyon'
   and not exists (select 1 from public.rol_yetki x where x.rol_id = ry.rol_id and x.yetki_id = y.id);
update public.rol r set yetki_surumu = yetki_surumu + 1
 where exists (select 1 from public.rol_yetki ry join public.yetki y on y.id = ry.yetki_id
                where ry.rol_id = r.id and y.kod = 'muayene.konsultasyon');

-- Kontrol
