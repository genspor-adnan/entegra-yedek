    no                  varchar(20)  not null default '',
    sube_id             integer      not null default 0,
    belge_id            integer      references public.belge(id),
    taraf_id            integer      not null references public.taraf(id),
    isteyen_muayene_id  integer      references public.muayene(id),
    isteyen_hekim_id    integer      references public.taraf(id),
    sorumlu_hekim_id    integer      references public.taraf(id),
    istek_bolum_id      integer      references public.departman(id),
    istek_zamani        timestamptz  not null default now(),
    neden               smallint     not null default 1,
    merkez              smallint     not null default 1,
    dis_merkez          varchar(160) not null default '',
    hedef_bolum_id      integer      references public.departman(id),
    hedef_hekim_id      integer      references public.taraf(id),
    karsilama_yeri      smallint     not null default 1,
    aciliyet            smallint     not null default 1,
    son_zaman           timestamptz,
    soru                varchar(500) not null default '',
    durum               smallint     not null default 1,
    yanitlayan_id       integer      references public.taraf(id),
    yanitlama_zamani    timestamptz,
    hastada_zamani      timestamptz,
    yanit_muayene_id    integer      references public.muayene(id),
    yanit_zamani        timestamptz,
