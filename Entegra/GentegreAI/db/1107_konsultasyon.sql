-- ------------------------------------------------------------------ sayaç --
create table if not exists public.konsultasyon_sayac (
    yil     smallint not null primary key,
    son_no  integer  not null default 0
);

-- fn_konsultasyon_no() -> 'KN-2026-0001'
create or replace function public.fn_konsultasyon_no()
returns varchar language plpgsql as $$
declare v_yil smallint := extract(year from current_date)::smallint; v_no integer;
begin
  insert into public.konsultasyon_sayac (yil, son_no) values (v_yil, 1)
  on conflict (yil) do update set son_no = public.konsultasyon_sayac.son_no + 1
  returning son_no into v_no;
  return 'KN-' || v_yil || '-' || lpad(v_no::text, 4, '0');
end $$;

-- Süre metni (liste): 8 dk · 1 sa 34 dk · 19 sa · 2 gün 3 sa
create or replace function public.fn_kons_sure_metni(p_dk integer)
returns varchar language sql immutable as $$
  select case when p_dk is null then ''
              when p_dk < 60 then p_dk || ' dk'
              when p_dk < 1440 then (p_dk / 60) || ' sa' || case when p_dk % 60 > 0 and p_dk < 600 then ' ' || (p_dk % 60) || ' dk' else '' end
              else (p_dk / 1440) || ' gün' || case when (p_dk % 1440) / 60 > 0 then ' ' || ((p_dk % 1440) / 60) || ' sa' else '' end end
$$;

-- ---------------------------------------------------------------- istek --
create table if not exists public.konsultasyon (
