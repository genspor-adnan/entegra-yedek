-- ---------------------------------------------------------------------------
--  6) ETKİN MALİ AYAR: şube → merkez kaskadı.
--     Firma geneli alanlar HER ZAMAN merkezden gelir (şubede dolu olsa bile).
-- ---------------------------------------------------------------------------
create or replace function public.fn_sube_mali(p_sube_id integer)
returns table (
    sube_id integer, kaynak_sube_id integer, merkezden boolean,
    defter_turu smallint, kdv_donem smallint, gecici_vergi_donem smallint,
    donem_disi_engelle smallint, devir_fisi_otomatik smallint,
    muhasebe_entegrasyon smallint, fis_uretim smallint, fis_birlestirme smallint,
    masraf_merkezi_kullan smallint, yuvarlama_hesap_id integer,
    amortisman_yontem smallint, amortisman_kist smallint, amortisman_periyot smallint,
    amortisman_enflasyon smallint, birikmis_amortisman_hesap_id integer,
    amortisman_gider_hesap_id integer, amortisman_yilsonu_fis smallint,
    varsayilan_kdv smallint, tevkifat_modu smallint,
    yerel_para varchar, doviz_varsayilan varchar,
    tutar_ondalik smallint, fiyat_ondalik smallint, yuvarlama_adim numeric)
language sql stable as $$
    with s as (select * from public.sube where id = p_sube_id),
         m as (select * from public.sube
                where id = coalesce((select public.fn_sube_merkez_id(p_sube_id)), p_sube_id)),
         -- Şube kendi ayarlarını kullanıyorsa entegrasyon bloğu ondan, değilse merkezden.
         e as (select case when (select merkez_mali_kullan from s) = 1 then 'm' else 's' end as k)
    select s.id, m.id, (select merkez_mali_kullan from s) = 1,
           -- FİRMA GENELİ (her zaman merkez)
           m.defter_turu, m.kdv_donem, m.gecici_vergi_donem,
           m.donem_disi_engelle, m.devir_fisi_otomatik,
           -- ŞUBE BAZLI olabilenler
           case when (select k from e) = 'm' then m.muhasebe_entegrasyon  else s.muhasebe_entegrasyon  end,
           case when (select k from e) = 'm' then m.fis_uretim            else s.fis_uretim            end,
           case when (select k from e) = 'm' then m.fis_birlestirme       else s.fis_birlestirme       end,
           case when (select k from e) = 'm' then m.masraf_merkezi_kullan else s.masraf_merkezi_kullan end,
           case when (select k from e) = 'm' then m.yuvarlama_hesap_id    else s.yuvarlama_hesap_id    end,
           -- FİRMA GENELİ (amortisman: vergi mevzuatı, şubeye göre değişmez)
           m.amortisman_yontem, m.amortisman_kist, m.amortisman_periyot,
           m.amortisman_enflasyon, m.birikmis_amortisman_hesap_id,
           m.amortisman_gider_hesap_id, m.amortisman_yilsonu_fis,
           -- FİRMA GENELİ (vergi & biçim: farklı olursa mizan tutmaz)
           m.varsayilan_kdv, m.tevkifat_modu, m.yerel_para, m.doviz_varsayilan,
           m.tutar_ondalik, m.fiyat_ondalik, m.yuvarlama_adim
      from s, m
$$;

comment on function public.fn_sube_mali(integer) is
  'Şubenin ETKİN mali ayarları (192): firma geneli alanlar merkezden, entegrasyon bloğu merkez_mali_kullan bayrağına göre.';

-- ---------------------------------------------------------------------------
--  7) Fişleme bu ayarları dinlesin: entegrasyon kapalıysa fiş üretilmez,
--     "elle" seçiliyse kayıt sırasında üretilmez (toplu fişleme yine çalışır).
--     190'daki referans kontrolü şube ayarına genişletildi.
-- ---------------------------------------------------------------------------
create or replace function public.fn_belge_fis_uretilsin(p_sube_id integer)
returns boolean language sql stable as $$
    select coalesce((select ma.muhasebe_entegrasyon = 1 and ma.fis_uretim = 1
                       from public.fn_sube_mali(p_sube_id) ma), true)
       and coalesce((select deger from public.referans
                      where anahtar = 'muhasebe.otomatik_fis'), '1') <> '0'
$$;

comment on function public.fn_belge_fis_uretilsin(integer) is
  'Belge kaydında fiş üretilecek mi (192): şube entegrasyon ayarı + genel otomatik fiş anahtarı.';

-- Mevcut şubeler için mali dönem kaydı (bu yıl) - dönem yoksa belge tarihi
--   kontrolü yapılamaz.
insert into public.mali_donem (sube_id, yil, ad, baslangic, bitis, tur, durum)
select s.id, extract(year from now())::smallint,
       extract(year from now())::text || ' — Normal hesap dönemi',
       make_date(extract(year from now())::int, 1, 1),
       make_date(extract(year from now())::int, 12, 31), 1, 0
  from public.sube s
 where not exists (select 1 from public.mali_donem d
                    where d.sube_id = s.id and d.yil = extract(year from now())::smallint);

do $$
declare v_sube integer; v_donem integer;
begin
    select count(*) into v_sube from public.sube;
    select count(*) into v_donem from public.mali_donem;
    raise notice '192 tamam: mali_donem (% kayit / % sube), muhasebe_fis_hata, vergi_beyan, sube mali kolonlari, fn_sube_mali.',
                 v_donem, v_sube;
end $$;
