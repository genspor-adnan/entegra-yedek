--  Mockup: Ekranlar/firma_bilgileri.html › Mali sekmesi
--    Mali Dönem · Muhasebe Entegrasyonu · Amortisman · Vergi & Yuvarlama
--
--  ŞUBE BAZLI MI, FİRMA GENELİ Mİ? (kullanıcı sorusu)
--    Ayrım "şube ayrı VKN taşıyor mu" sorusuna bağlı ve bu şemada TAŞIYABİLİR
--    (sube.vkno + sube.ebelge_kimlik). Bu yüzden ayarlar `sube` tablosunda
--    tutulur ve şube boş bırakırsa MERKEZDEN miras alınır - e-Belge'deki
--    "merkez kimliği / kendi kimliği" deseninin aynısı (169).
--
--      merkez_mali_kullan = 1  -> tüm mali ayarlar merkezden okunur
--      merkez_mali_kullan = 0  -> şube kendi ayarlarını kullanır
--
--    Ancak bazı alanlar şubeye göre DEĞİŞEMEZ; iki şube farklı ondalıkla
--    çalışırsa aynı fişte iki yuvarlama çıkar ve mizan tutmaz. Bunlar
--    (defter türü, KDV/geçici vergi dönemi, para birimi, ondalık, yuvarlama
--    adımı, amortisman yöntemi) her zaman MERKEZDEN okunur - fn_sube_mali
--    şubede dolu olsalar bile merkez değerini döndürür.
--
--  Amortisman ayarları demirbaş modülü henüz YOKKEN de saklanır: modül
--  geldiğinde ayar zaten yerinde olsun, kullanıcı ikinci kez doldurmasın.
-- ============================================================================
\set ON_ERROR_STOP on

-- ---------------------------------------------------------------------------
--  1) MALİ DÖNEM (hesap dönemi = yıl). Bugün yalnız aylık `muhasebe_donem`
--     vardı; devir fişi, defter türü ve KDV periyodu YIL seviyesinde tutulur.
-- ---------------------------------------------------------------------------
create table if not exists public.mali_donem (
    id                 integer generated by default as identity primary key,
    sube_id            integer not null references public.sube(id),
    yil                smallint not null,
    ad                 varchar(60)  not null default '',
    baslangic          date         not null,
    bitis              date         not null,
    -- 1 normal · 2 özel hesap dönemi · 3 kıst (kuruluş/tasfiye yılı)
    tur                smallint     not null default 1,
    -- 0 açık · 1 kapandı (devir fişi verildi) · 2 kilitli
    durum              smallint     not null default 0,
    devir_fis_id       integer,
    aciklama           varchar(200) not null default '',
    ekleyen            integer not null default 0,
    ekleme_tarihi      timestamp not null default now()::timestamp,
    degistiren         integer not null default 0,
    degistirme_tarihi  timestamp,
    constraint ux_mali_donem unique (sube_id, yil)
);

comment on table public.mali_donem is
  'Hesap dönemi (yıl). Aylık dönemler muhasebe_donem''de, onlar buna bağlanır (192).';

alter table public.muhasebe_donem
    add column if not exists mali_donem_id integer references public.mali_donem(id),
    -- Şube bazlı kilit: bir şube ayı kapatmışken diğeri hâlâ kayıt giriyor
    --   olabilir. NULL = tüm şubeler (eski davranış korunur).
    add column if not exists sube_id integer references public.sube(id);

comment on column public.muhasebe_donem.sube_id is
  'Kilit hangi şubeye ait (192). NULL = firma geneli.';

-- ---------------------------------------------------------------------------
--  2) FİŞLENEMEYEN BELGE İZİ. Bugün fişleme hatası yalnız uyarı olarak
--     dönüyor, kalıcı iz kalmıyordu - "kaç belge hatalı" sorusu
--     cevaplanamıyordu (toplu fişlemede 34 belge atlanmıştı).
-- ---------------------------------------------------------------------------
create table if not exists public.muhasebe_fis_hata (
    id                 bigint generated by default as identity primary key,
    kaynak_tur         smallint not null,          -- 1 kasa işlemi · 2 belge
    kaynak_id          integer  not null,
    hata_mesaji        varchar(500) not null default '',
    deneme_tarihi      timestamp not null default now()::timestamp,
    cozuldu            smallint not null default 0,
    cozum_tarihi       timestamp,
    fis_id             integer,
    sube_id            integer,
    ekleyen            integer not null default 0
);

create unique index if not exists ux_fis_hata_kaynak
    on public.muhasebe_fis_hata (kaynak_tur, kaynak_id) where cozuldu = 0;
create index if not exists ix_fis_hata_acik
    on public.muhasebe_fis_hata (sube_id, deneme_tarihi desc) where cozuldu = 0;

comment on table public.muhasebe_fis_hata is
  'Fişlenemeyen belge/kasa işlemi izi (192); çözülünce cozuldu=1 işaretlenir.';

-- ---------------------------------------------------------------------------
--  3) VERGİ BEYAN (dönem özeti panelindeki "beyan bekliyor" satırı).
-- ---------------------------------------------------------------------------
create table if not exists public.vergi_beyan (
    id                 integer generated by default as identity primary key,
    sube_id            integer not null references public.sube(id),
    tur                smallint not null,          -- 1 KDV · 2 muhtasar · 3 geçici · 4 damga
    yil                smallint not null,
    donem              smallint not null,          -- ay ya da çeyrek
    matrah             numeric(19,2) not null default 0,
    tutar              numeric(19,2) not null default 0,
    -- 0 hesaplandı · 1 beyan edildi · 2 ödendi
    durum              smallint not null default 0,
    beyan_tarihi       date,
    tahakkuk_no        varchar(40) not null default '',
    kasa_islem_id      integer,
    aciklama           varchar(200) not null default '',
    ekleyen            integer not null default 0,
    ekleme_tarihi      timestamp not null default now()::timestamp,
    degistiren         integer not null default 0,
    degistirme_tarihi  timestamp,
    constraint ux_vergi_beyan unique (sube_id, tur, yil, donem)
);

comment on table public.vergi_beyan is
  'Dönem beyanları (KDV/muhtasar/geçici) ve tahakkuk durumu (192).';

