--  1217  RADYOLOJİ HAZIR YAPISAL ALAN PAKETLERİ (omurga + diz / omuz)
--
--  Kullanıcı (01.11.2026): "yapısal şablon ekleyebiliyor musun? kütüphane var mı?" -> "A ile başla, önce omurga
--  ve diz/omuz". Yapılandırılmış alan altyapısı vardı (radyoloji_sablon_alan: seçim / sayı / skor / evet-hayır /
--  metin) ama her şablona elle kuruluyordu; eski HBYS'den gelen 338 şablonun hiçbirinde alan yok.
--
--  PAKET = adlandırılmış alan kümesi. Şablona "Paketten ekle" ile (kartta) ya da şablon ADINA göre toplu
--  (listede / aktarımda) uygulanır: `desen` şablon adında aranır (büyük harf, Türkçe harf sadeleştirilmiş),
--  `haric_desen` eşleşirse uygulanmaz ("SERVIKAL MRA" damar tetkiki - omurga paketi almaz).
--
--  METNE YAZILIŞ (rapor ekranı "Metne ekle"): değer normal sınıfındaysa (Normal / Yok / İntakt / Korunmuş ile
--  başlıyorsa) `sifir_kalip` yazılır (boşsa hiçbir şey), değilse `kalip` - {değer} seçilen değerle değişir.
--  `rapora_bas` 0: değerler cümle olarak metne girer, ayrıca "Ölçüm / Skorlama" tablosuna basılmaz.
--
--  `grup` (yeni kolon): rapor ekranında alanlar başlık altında (Disk seviyeleri, Bağlar ...) gösterilir.
--  Paket içerikleri Türkçe, kurumun düzenleyebileceği başlangıç kümesidir (ACR / ESR terminolojisine uygun ama
--  onların metni değildir). Paket kodu tekil - göç yeniden çalışınca paketin alanları baştan yazılır;
--  şablonlara uygulanmış alanlara dokunulmaz. İdempotent.
-- =============================================================================

begin;

create table if not exists public.radyoloji_alan_paket (
    id            integer generated by default as identity primary key,
    kod           varchar(40)  not null unique,
    ad            varchar(120) not null,
    modalite      smallint,
    bolge         smallint,
    desen         varchar(300) not null default '',
    haric_desen   varchar(300) not null default '',
    aciklama      text         not null default '',
    durum         smallint     not null default 1,
    ekleme_tarihi timestamptz  not null default now()
);
comment on table public.radyoloji_alan_paket is
  '1217: hazır yapılandırılmış alan paketi; desen / haric_desen şablon ADINDA (büyük harf, ÇĞİÖŞÜ sadeleştirilmiş) aranır.';

create table if not exists public.radyoloji_alan_paket_alan (
    id          integer generated by default as identity primary key,
    paket_id    integer      not null references public.radyoloji_alan_paket(id) on delete cascade,
    sira        smallint     not null default 1,
    grup        varchar(40)  not null default '',
    alan_kod    varchar(40)  not null,
    alan_ad     varchar(80)  not null,
    tip         smallint     not null default 1,
    secenekler  varchar(400) not null default '',
    birim       varchar(20)  not null default '',
    alt_sinir   numeric(10,2),
    ust_sinir   numeric(10,2),
    kalip       varchar(300) not null default '',
    sifir_kalip varchar(300) not null default '',
    hedef_bolum varchar(60)  not null default 'Bulgular',
    zorunlu     smallint     not null default 0,
    rapora_bas  smallint     not null default 0,
    unique (paket_id, alan_kod)
);

alter table public.radyoloji_sablon_alan add column if not exists grup varchar(40) not null default '';
comment on column public.radyoloji_sablon_alan.grup is '1217: rapor ekranında alan başlığı (Disk seviyeleri, Bağlar ...).';

-- ---------------------------------------------------------------- uygula ----
-- Paketin alanlarını şablona ekler; şablonda aynı alan_kod varsa o alan atlanır. Dönen: eklenen alan sayısı.
create or replace function public.fn_rad_alan_paketi_uygula(p_paket integer, p_sablon integer, p_kullanici integer)
returns integer language plpgsql as $$
declare v_n integer;
begin
    with son as (select coalesce(max(sira), 0) as s from public.radyoloji_sablon_alan where sablon_id = p_sablon),
    yaz as (
        insert into public.radyoloji_sablon_alan (sablon_id, sira, grup, alan_kod, alan_ad, tip, secenekler, birim,
                                                  alt_sinir, ust_sinir, kalip, sifir_kalip, hedef_bolum, zorunlu,
                                                  rapora_bas, ekleyen)
        select p_sablon, (son.s + row_number() over (order by a.sira, a.id))::smallint, a.grup, a.alan_kod, a.alan_ad,
               a.tip, a.secenekler, a.birim, a.alt_sinir, a.ust_sinir, a.kalip, a.sifir_kalip, a.hedef_bolum,
               a.zorunlu, a.rapora_bas, p_kullanici
          from public.radyoloji_alan_paket_alan a, son
         where a.paket_id = p_paket
           and not exists (select 1 from public.radyoloji_sablon_alan x where x.sablon_id = p_sablon and x.alan_kod = a.alan_kod)
        returning 1)
    select count(*) into v_n from yaz;
    return v_n;
end $$;

-- Şablon adı paketin desenine uyuyor mu (liste önerisi + aktarım).
create or replace function public.fn_rad_alan_paketi_uyar(p_paket integer, p_ad text)
returns boolean language sql stable as $$
    select p.desen <> ''
       and translate(upper(coalesce(p_ad, '')), 'ÇĞİÖŞÜ', 'CGIOSU') ~ p.desen
       and (p.haric_desen = '' or translate(upper(coalesce(p_ad, '')), 'ÇĞİÖŞÜ', 'CGIOSU') !~ p.haric_desen)
      from public.radyoloji_alan_paket p where p.id = p_paket;
$$;

