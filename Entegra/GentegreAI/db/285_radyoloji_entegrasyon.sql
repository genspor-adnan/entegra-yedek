-- 285: RADYOLOJİ — ENTEGRASYON TABLOLARI (Faz 3).
--
-- PACS/DICOM olay izi ve ikinci okuma (teleradyoloji konsültasyonu).

-- ============================================================== PACS olayı ==
-- Entegrasyon hatası KALICI İZ bırakmazsa "hangi çekim kayboldu, neden
-- eşleşmedi" sorusu cevapsız kalır (ÜTS bildirim izinin aynısı). Her olay
-- ham mesajıyla saklanır: MWL gönderimi, dönen study, eşleşme hatası.
create table if not exists public.radyoloji_pacs_olay (
  id           integer generated by default as identity primary key,
  istem_id     integer references public.radyoloji_istem(id) on delete set null,
  accession_no varchar(24) not null default '',         -- istem silinse de iz kalsın
  olay         smallint not null default 1,             -- 1 MWL gönderildi · 2 study geldi
                                                        -- 3 eşleşmedi · 4 güncellendi · 5 hata
  yon          smallint not null default 1,             -- 1 giden (bize->cihaz) · 2 gelen
  cihaz_id     integer references public.radyoloji_cihaz(id),
  ae_title     varchar(32)  not null default '',
  study_uid    varchar(64)  not null default '',
  sonuc        smallint not null default 1,             -- 1 başarılı · 0 hata
  mesaj        varchar(500) not null default '',
  ham          text not null default '',                -- ham DICOM/HL7 gövdesi
  olay_zamani  timestamp not null default now()::timestamp,
  ekleyen      integer not null default 0
);
comment on table public.radyoloji_pacs_olay is
  'PACS/DICOM olay izi (285): MWL gönderimi, dönen study, eşleşme hatası.';
create index if not exists ix_rad_pacs_istem on public.radyoloji_pacs_olay (istem_id);
create index if not exists ix_rad_pacs_acc   on public.radyoloji_pacs_olay (accession_no);
create index if not exists ix_rad_pacs_hata  on public.radyoloji_pacs_olay (olay_zamani)
  where sonuc = 0;

-- ============================================================ konsültasyon ==
-- İkinci okuma / teleradyoloji: rapor dış radyoloğa gönderilir, görüşü döner.
-- Dış radyolog da bir TARAF'tır (hekim rolü, dis_mi = 1).
create table if not exists public.radyoloji_konsultasyon (
  id             integer generated by default as identity primary key,
  istem_id       integer not null references public.radyoloji_istem(id) on delete cascade,
  rapor_id       integer references public.radyoloji_rapor(id) on delete set null,
  hekim_id       integer references public.taraf(id),   -- görüş istenen radyolog
  kurum_id       integer references public.taraf(id),   -- teleradyoloji firması
  durum          smallint not null default 1,           -- 1 gönderildi · 2 görüş geldi · 3 iptal
  gonderim_zamani timestamp not null default now()::timestamp,
  donus_zamani   timestamp,
  gerekce        varchar(300) not null default '',
  gorus          text not null default '',
  -- Ücretlendirilen konsültasyon: gideri/hakedişi belgeye bağlanabilsin.
  belge_satir_id integer references public.belge_satir(id),
  ekleyen        integer not null default 0,
  ekleme_tarihi  timestamp not null default now()::timestamp,
  degistiren     integer not null default 0,
  degistirme_tarihi timestamp
);
comment on table public.radyoloji_konsultasyon is
  'İkinci okuma / teleradyoloji görüşü (285).';
create index if not exists ix_rad_konsul_istem on public.radyoloji_konsultasyon (istem_id);
create index if not exists ix_rad_konsul_bekleyen on public.radyoloji_konsultasyon (durum)
  where durum = 1;
