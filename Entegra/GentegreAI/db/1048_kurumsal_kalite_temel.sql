);
comment on table public.kalite_sayac is 'Kurumsal Kalite (1048): DÖF / DEN / OLY / RSK ... yıllık numara sayacı.';

-- fn_kalite_no('DÖF', 3) -> 'DÖF-2026-001'. Sayaç satırı kilitlenir (eşzamanlı
--   iki kayıt aynı numarayı alamaz). basamak 0 -> yılsız 'RSK-017' biçimi değil,
--   her zaman yıl içerir; yılsız numara isteyen ekran kendi biçimler.
create or replace function public.fn_kalite_no(p_onek varchar, p_basamak integer default 3)
returns varchar language plpgsql as $$
declare v_yil smallint := extract(year from current_date)::smallint; v_no integer;
begin
  insert into public.kalite_sayac (onek, yil, son_no) values (p_onek, v_yil, 1)
  on conflict (onek, yil) do update set son_no = public.kalite_sayac.son_no + 1
  returning son_no into v_no;
  return p_onek || '-' || v_yil || '-' || lpad(v_no::text, greatest(p_basamak, 1), '0');
end $$;

