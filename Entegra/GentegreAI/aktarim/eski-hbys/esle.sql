-- PAY DAĞILIMI (elle): kurumun payı = o satırın DIŞ KURUMA kesilmiş fatura satırları (FATURA.TUTAR KDV hariç),
--   kalan hasta. Ücretli başvuruda tamamı hasta. Kova: SGK -> sgk, diğer kurum -> oss.
create temp table zz_kurum_fatura_payi as
select f.paraid,
       sum(case when fb.kdvdurum = 'Dahil' then f.tutar::numeric / (1 + coalesce(f.kdv, 10) / 100.0) else f.tutar::numeric end) as kurum_hariç
  from eski.fatura f
  join eski.fatbaslik fb on fb.id = f.fatbasid
  join eski.gelisler g on g.id = fb.gelisid
 where fb.kime not ilike 'katk%' and fb.kime not ilike '%iptal%'
   and g.kurumid in (select eski_id from zz_kurum)
 group by f.paraid;

-- FATURALANMAMIŞ KURUM PAYI: kurumun başvurudaki payı TAHSILAT.TUR = 'ANLAŞ' satırlarında (KDV dahil, başvuru
--   başına). Faturadan gelen satır payları bunun altında kalırsa fark, satırların kalan (hasta) kısmına
--   orantılı dağıtılır - yoksa faturalanmamış kurum alacağı hastanın açık borcu görünürdü.
create temp table zz_kurum_pay as
with satir as (
    select s.id, p.gelisid, p.kurum_tur, round(s.tutar, 2) as tutar,
           least(round(coalesce(kf.kurum_hariç, 0), 2), round(s.tutar, 2)) as fatura_pay
      from public.belge_satir s
      join zz_para p on p.id = s.aktarim_id
      left join zz_kurum_fatura_payi kf on kf.paraid = p.id
     where s.aktarim_kaynak = 2 and s.aktarim_tablo = 'PARA'
), anlas as (
    select t.gelisid, sum(t.tahsil)::numeric / 1.10 as anlas_haric      -- KOSUYOLU: KDV hep %10 (eski.tanim PARA.KDV)
      from eski.tahsilat t where upper(btrim(t.tur)) = 'ANLAŞ' group by t.gelisid
), basvuru as (
    select st.gelisid, greatest(coalesce(a.anlas_haric, 0) - sum(st.fatura_pay), 0) as ek,
           sum(st.tutar - st.fatura_pay) as kalan
      from satir st left join anlas a on a.gelisid = st.gelisid
     where st.kurum_tur is not null
     group by st.gelisid, a.anlas_haric
)
select st.id, st.kurum_tur, st.tutar,
       case when st.kurum_tur is null then 0
            else least(st.tutar, st.fatura_pay + case when coalesce(b.kalan, 0) > 0
                                                      then round(least(b.ek, b.kalan) * (st.tutar - st.fatura_pay) / b.kalan, 2)
                                                      else 0 end) end as kurum_pay
  from satir st left join basvuru b on b.gelisid = st.gelisid;

