create temp table zz_isteyen_hekim as
select x.anahtar, x.doktorid, x.ad,
       case when x.doktorid is not null then 'DOKTORLAR' else 'GELISLER.DOKTOR' end as tablo,
       coalesce(x.doktorid, dense_rank() over (order by x.anahtar)) as aid,
       pg_temp.eski_hekim_onek(dl.unvan) as onek,
       pg_temp.eski_ad_bol(x.ad, false) as ad_kismi, pg_temp.eski_ad_bol(x.ad, true) as soyad,
       left(coalesce(btrim(dl.istel), ''), 30) as telefon, left(coalesce(btrim(dl.cep), ''), 30) as cep,
