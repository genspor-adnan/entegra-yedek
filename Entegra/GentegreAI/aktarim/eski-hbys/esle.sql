insert into public.belge_satir (belge_id, sira, tur, hizmet_id, aciklama, miktar, adet, birim_fiyat, birim_fiyat_kdvli,
                                iskonto, kdv, tutar, tutar_kdvli, doviz_cinsi, doviz_birim_fiyat, doviz_tutari, doviz_kuru,
                                sube_id, pay, kaynak_tur, kaynak_id, iskonto_kilit, aktarim_kaynak, aktarim_tablo, aktarim_id)
select b.id, coalesce(f.sirano, 0), 2, s.hizmet_id, left(coalesce(f.aciklama, ''), 200),
       coalesce(nullif(f.adet, 0), 1), coalesce(nullif(f.adet, 0), 1),
       round(x.haric / coalesce(nullif(f.adet, 0), 1)::numeric, 4),
       round(x.haric / coalesce(nullif(f.adet, 0), 1)::numeric * (1 + x.kdv / 100.0), 4),
       0, x.kdv, round(x.haric, 2), round(round(x.haric, 2) * (1 + x.kdv / 100.0), 2),
       'TL', round(x.haric / coalesce(nullif(f.adet, 0), 1)::numeric, 4), round(x.haric, 2), 1,
       1, z.pay, case when s.id is not null then 30 else 0 end, coalesce(s.id, 0), 1,
       2, 'FATURA', f.id
  from eski.fatura f
  cross join lateral (select coalesce(f.kdv, 10)::numeric as kdv) k0
  cross join lateral (select k0.kdv,
                             case when (select kdvdurum from eski.fatbaslik where id = f.fatbasid) = 'Dahil'
                                  then f.tutar::numeric / (1 + k0.kdv / 100) else f.tutar::numeric end as haric) x
  join zz_fb z on z.id = f.fatbasid
  join public.belge b on b.aktarim_kaynak = 2 and b.aktarim_tablo = 'FATBASLIK' and b.aktarim_id = z.id
  left join zz_satir s on s.eski_id = f.paraid;

