       (select departman_id from zz_gelis_isteyen z where z.anahtar = x.anahtar and z.departman_id is not null
         group by departman_id order by count(*) desc limit 1) as departman
  from (select distinct on (anahtar) anahtar, doktorid, ad from zz_gelis_isteyen order by anahtar, ad) x
  left join eski.doktorlar dl on dl.id = x.doktorid;

