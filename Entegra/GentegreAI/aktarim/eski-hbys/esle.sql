create or replace function pg_temp.eski_tarih(t timestamp) returns timestamp language sql immutable as $$
    select case when t between '1900-01-02' and now()::timestamp + interval '1 year' then t end
$$;
-- Modalite (rad.modalite): 1 BT · 2 MR · 3 USG · 4 Röntgen · 5 Mamografi · 6 DEXA · 7 Anjiyo · 8 Skopi.
--   KOSUYOLU kod önekleri (eski.tanim ISLEMLER.TUR=RAD); önek tanınmazsa addan.
create or replace function pg_temp.modalite(p_kod text, p_ad text) returns smallint language sql immutable as $$
    select (case
        when split_part(p_kod, '.', 1) in ('MR', 'MRA')             then 2
        when split_part(p_kod, '.', 1) = 'BT'                        then 1
        when split_part(p_kod, '.', 1) in ('US', 'D', 'Eko', 'EKO')  then 3
        when split_part(p_kod, '.', 1) = 'Ront'                      then 4
        when split_part(p_kod, '.', 1) = 'Mam'                       then 5
        when split_part(p_kod, '.', 1) = 'KD'                        then 6
        when split_part(p_kod, '.', 1) = 'A'                         then 7
        when split_part(p_kod, '.', 1) in ('KM', 'Res', 'SSK')       then 0   -- sarf / genel: tetkik değil
        when upper(p_ad) ~ '(\mMR\M|MANYET|MAGNET)'                    then 2
        when upper(p_ad) ~ '(\mBT\M|TOMOGRAF)'                          then 1
        when upper(p_ad) ~ '(\mUS\M|USG|ULTRASON|DOPPLER|EKOKARD)'      then 3
        when upper(p_ad) ~ '(MAMMOG|MAMOG)'                             then 5
        when upper(p_ad) ~ '(DANSİTOMETR|DANSITOMETR|DEXA)'             then 6
        when upper(p_ad) ~ '(ANJİO|ANJIO|ANGİO|ANGIO)'                  then 7
        when upper(p_ad) ~ '(GRAFİ|GRAFI|RÖNTGEN|RONTGEN)'              then 4
        else 0 end)::smallint
$$;

