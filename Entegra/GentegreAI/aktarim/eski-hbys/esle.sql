-- DAĞITIM: başvurunun hasta kovalarına (KDV dahil) tarih sırasıyla - aralık kesişimi (FIFO).
insert into public.kasa_islem_dagitim (kasa_islem_id, belge_satir_id, pay, tutar)
with kova as (
    select s.belge_id, s.id as satir_id,
           round(d.hasta_provizyon * (1 + s.kdv::numeric / 100), 2) as kap,
           sum(round(d.hasta_provizyon * (1 + s.kdv::numeric / 100), 2)) over (partition by s.belge_id order by s.sira, s.id) as bit
      from public.belge_satir s join public.belge_satir_dagilim d on d.belge_satir_id = s.id
     where s.aktarim_kaynak = 2 and s.aktarim_tablo = 'PARA' and d.hasta_provizyon > 0
), odeme as (
    select k.belge_id, k.id as islem_id, k.tutar,
           sum(k.tutar) over (partition by k.belge_id order by k.islem_tarihi, k.id) as bit
      from public.kasa_islem k where k.aktarim_kaynak = 2 and k.durum = 2 and k.tutar > 0
)
select o.islem_id, v.satir_id, 1,
       round(least(v.bit, o.bit) - greatest(v.bit - v.kap, o.bit - o.tutar), 2)
  from odeme o join kova v on v.belge_id = o.belge_id
 where least(v.bit, o.bit) - greatest(v.bit - v.kap, o.bit - o.tutar) > 0.004;

