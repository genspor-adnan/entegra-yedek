create temp table zz_gelis_isteyen as
select g.id as gelis_id,
       case when g.doktorid is not null then 'ID:' || g.doktorid else 'AD:' || upper(btrim(g.doktor)) end as anahtar,
       g.doktorid, left(btrim(coalesce(dl.doktor, g.doktor)), 200) as ad,
       (select d.id from public.departman d join zz_pol p on p.departman_ad = d.ad where p.eski = btrim(g.poliklinik) limit 1) as departman_id
  from eski.gelisler g
