-- Gelen (YON=2) e-belgelerde UBL durumu: hangi kolonda, C_UBL_OKU ne donuyor
SELECT TOP 15
    ID, FATBASLIKID,
    UBL_XML_LEN   = LEN(ISNULL(CAST(UBL_XML AS NVARCHAR(MAX)),'')),
    ZIP_VAR       = CASE WHEN UBL_XML_ZIP IS NULL THEN 'NULL' ELSE CONVERT(varchar(20),DATALENGTH(UBL_XML_ZIP)) END,
    DECOMP_LEN    = CASE WHEN UBL_XML_ZIP IS NULL THEN -1
                         ELSE LEN(CAST(DECOMPRESS(UBL_XML_ZIP) AS NVARCHAR(MAX))) END,
    OKUMA_LEN     = LEN(ISNULL(COALESCE(CAST(DECOMPRESS(UBL_XML_ZIP) AS NVARCHAR(MAX)),
                                        CAST(UBL_XML AS NVARCHAR(MAX))),''))
FROM EBELGE
WHERE YON = 2
ORDER BY ID DESC;

-- FATBASLIK'ta UBL_XML kolonu var mi (belirsizlik kontrolu)?
SELECT KOLON=COLUMN_NAME FROM INFORMATION_SCHEMA.COLUMNS
WHERE TABLE_NAME='FATBASLIK' AND COLUMN_NAME LIKE '%UBL%';
