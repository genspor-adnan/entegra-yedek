-- ============================================================
-- PILOT modul tablosu: DEPOLAR (ana DB tablosu -> public schema)
-- MSSQL: int IDENTITY / tinyint / smalldatetime getdate() / bit
-- ============================================================
DROP TABLE IF EXISTS public.depolar CASCADE;
CREATE TABLE public.depolar (
  id                 integer      GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,  -- int IDENTITY
  depoadi            varchar(50)  COLLATE depo.tr_ci NOT NULL,                   -- varchar + Turkce CI
  durum              smallint     DEFAULT 1,                                     -- tinyint
  ekleyen            smallint,
  eklemetarihi       timestamp(0) DEFAULT now(),                                 -- smalldatetime getdate()->now()
  degistiren         smallint,
  degistirmetarihi   timestamp(0),
  sonsayimtarihi     timestamp(3),
  varsayilan         smallint,
  subeid             smallint     DEFAULT -1,
  maliyeti_etkilesin boolean                                                     -- bit
);
CREATE UNIQUE INDEX ix_depolar_depoadi ON public.depolar (depoadi);
