CREATE OR REPLACE FUNCTION public.fn_api_mesaj_okunmadi_json(kosullar text DEFAULT '{}')
RETURNS text LANGUAGE plpgsql AS $$
DECLARE
  j jsonb := COALESCE(NULLIF(kosullar,'')::jsonb, '{}'::jsonb);
  v_kanalid integer := NULLIF(j->>'KanalId','')::integer;
  v_kulid integer := COALESCE(NULLIF(j#>>'{Oturum,KulId}','')::integer, 0);
  v_son bigint;
BEGIN
  IF v_kulid <= 0 THEN RAISE EXCEPTION 'Oturum.KulId zorunlu.' USING ERRCODE='P0001'; END IF;
  IF COALESCE(v_kanalid,0) <= 0 THEN RAISE EXCEPTION 'KanalId zorunlu.' USING ERRCODE='P0001'; END IF;
  IF NOT EXISTS (SELECT 1 FROM public.mesajkanaluye WHERE kanalid=v_kanalid AND rehberid=v_kulid AND ayrilmatarihi IS NULL) THEN
    RAISE EXCEPTION 'Bu sohbetin uyesi degilsiniz.' USING ERRCODE='P0001';
  END IF;
  SELECT max(m.id) INTO v_son
  FROM public.mesaj m
  WHERE m.kanalid=v_kanalid AND m.gonderenid<>v_kulid AND m.silindi=0
    AND NOT EXISTS (SELECT 1 FROM public.mesajgizli g WHERE g.mesajid=m.id AND g.rehberid=v_kulid);
  IF v_son IS NOT NULL THEN
    UPDATE public.mesajkanaluye SET sonokumaid=GREATEST(v_son-1, baslangicid) WHERE kanalid=v_kanalid AND rehberid=v_kulid AND ayrilmatarihi IS NULL;
  END IF;
  RETURN jsonb_build_object('Sonuc',1,'KanalId',v_kanalid,'SonMesajId',v_son)::text;
END;
$$;

CREATE OR REPLACE FUNCTION public.fn_api_mesaj_sil_json(kosullar text DEFAULT '{}')
RETURNS text LANGUAGE plpgsql AS $$
DECLARE
  j jsonb := COALESCE(NULLIF(kosullar,'')::jsonb, '{}'::jsonb);
  v_kulid integer := COALESCE(NULLIF(j#>>'{Oturum,KulId}','')::integer, 0);
  v_mesajid bigint := NULLIF(j->>'MesajId','')::bigint;
  v_kapsam text := lower(COALESCE(NULLIF(j->>'Kapsam',''), 'ben'));
  v_kanalid integer;
  v_gonderen integer;
  v_tur integer;
BEGIN
  IF v_kulid <= 0 OR COALESCE(v_mesajid,0) <= 0 THEN RAISE EXCEPTION 'MesajId ve Oturum.KulId zorunlu.' USING ERRCODE='P0001'; END IF;
  SELECT m.kanalid, m.gonderenid, k.tur INTO v_kanalid, v_gonderen, v_tur
  FROM public.mesaj m JOIN public.mesajkanal k ON k.id=m.kanalid
  WHERE m.id=v_mesajid;
  IF v_kanalid IS NULL THEN RAISE EXCEPTION 'Mesaj bulunamadi.' USING ERRCODE='P0001'; END IF;
  IF NOT EXISTS (SELECT 1 FROM public.mesajkanaluye WHERE kanalid=v_kanalid AND rehberid=v_kulid AND ayrilmatarihi IS NULL) THEN
    RAISE EXCEPTION 'Bu sohbetin uyesi degilsiniz.' USING ERRCODE='P0001';
  END IF;
  IF v_kapsam='herkes' THEN
    IF v_gonderen <> v_kulid AND NOT (v_tur=2 AND EXISTS (SELECT 1 FROM public.mesajkanaluye WHERE kanalid=v_kanalid AND rehberid=v_kulid AND rol=1 AND ayrilmatarihi IS NULL)) THEN
      RAISE EXCEPTION 'Bu mesaji yalnizca gonderen ya da grup yoneticisi herkesten silebilir.' USING ERRCODE='P0001';
    END IF;
    UPDATE public.mesaj SET silindi=1, silen=v_kulid, silmetarihi=now() WHERE id=v_mesajid AND silindi=0;
  ELSE
    INSERT INTO public.mesajgizli(mesajid, rehberid) VALUES (v_mesajid, v_kulid) ON CONFLICT DO NOTHING;
  END IF;
  RETURN jsonb_build_object('Sonuc',1,'MesajId',v_mesajid,'KanalId',v_kanalid,'Kapsam',v_kapsam)::text;
END;
$$;

CREATE OR REPLACE FUNCTION public.fn_api_mesaj_kanal_temizle_json(kosullar text DEFAULT '{}')
RETURNS text LANGUAGE plpgsql AS $$
DECLARE
  j jsonb := COALESCE(NULLIF(kosullar,'')::jsonb, '{}'::jsonb);
  v_kanalid integer := NULLIF(j->>'KanalId','')::integer;
  v_kulid integer := COALESCE(NULLIF(j#>>'{Oturum,KulId}','')::integer, 0);
  v_kapsam text := lower(COALESCE(NULLIF(j->>'Kapsam',''), 'ben'));
  v_adet integer := 0;
BEGIN
  IF v_kulid <= 0 THEN RAISE EXCEPTION 'Oturum.KulId zorunlu.' USING ERRCODE='P0001'; END IF;
  IF COALESCE(v_kanalid,0) <= 0 THEN RAISE EXCEPTION 'KanalId zorunlu.' USING ERRCODE='P0001'; END IF;
  IF NOT EXISTS (SELECT 1 FROM public.mesajkanaluye WHERE kanalid=v_kanalid AND rehberid=v_kulid AND ayrilmatarihi IS NULL) THEN
    RAISE EXCEPTION 'Bu sohbetin uyesi degilsiniz.' USING ERRCODE='P0001';
  END IF;
  IF v_kapsam='herkes' THEN
    IF NOT EXISTS (SELECT 1 FROM public.mesajkanaluye u JOIN public.mesajkanal k ON k.id=u.kanalid AND k.tur=2 WHERE u.kanalid=v_kanalid AND u.rehberid=v_kulid AND u.rol=1 AND u.ayrilmatarihi IS NULL) THEN
      RAISE EXCEPTION 'Sohbeti herkesten yalnizca grup yoneticisi temizleyebilir.' USING ERRCODE='P0001';
    END IF;
    SELECT count(*) INTO v_adet FROM public.mesaj WHERE kanalid=v_kanalid;
    DELETE FROM public.mesaj WHERE kanalid=v_kanalid;
    UPDATE public.mesajkanal SET sonmesajid=NULL, sonmesajtarih=NULL WHERE id=v_kanalid;
    UPDATE public.mesajkanaluye SET sonokumaid=0, baslangicid=0 WHERE kanalid=v_kanalid;
  ELSE
    INSERT INTO public.mesajgizli(mesajid, rehberid)
    SELECT m.id, v_kulid FROM public.mesaj m
    WHERE m.kanalid=v_kanalid
    ON CONFLICT DO NOTHING;
    GET DIAGNOSTICS v_adet = ROW_COUNT;
    UPDATE public.mesajkanaluye
       SET sonokumaid=COALESCE((SELECT max(id) FROM public.mesaj WHERE kanalid=v_kanalid), sonokumaid)
     WHERE kanalid=v_kanalid AND rehberid=v_kulid AND ayrilmatarihi IS NULL;
  END IF;
  RETURN jsonb_build_object('Sonuc',1,'KanalId',v_kanalid,'Kapsam',v_kapsam,'SilinenMesaj',v_adet)::text;
END;
