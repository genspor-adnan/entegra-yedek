CREATE OR REPLACE FUNCTION public.fn_api_mesaj_kanal_rol_json(kosullar text DEFAULT '{}')
RETURNS text LANGUAGE plpgsql AS $$
DECLARE
  j jsonb := COALESCE(NULLIF(kosullar,'')::jsonb, '{}'::jsonb);
  v_kanalid integer := NULLIF(j->>'KanalId','')::integer;
  v_rol integer := COALESCE(NULLIF(j->>'Rol','')::integer, 0);
  v_kulid integer := COALESCE(NULLIF(j#>>'{Oturum,KulId}','')::integer, 0);
  v_hedef_count integer;
BEGIN
  IF v_kulid <= 0 THEN RAISE EXCEPTION 'Oturum.KulId zorunlu.' USING ERRCODE='P0001'; END IF;
  IF COALESCE(v_kanalid,0) <= 0 THEN RAISE EXCEPTION 'KanalId zorunlu.' USING ERRCODE='P0001'; END IF;
  IF NOT EXISTS (SELECT 1 FROM public.mesajkanaluye WHERE kanalid=v_kanalid AND rehberid=v_kulid AND ayrilmatarihi IS NULL AND rol=1) THEN
    RAISE EXCEPTION 'Bu islem icin grup yoneticisi olmalisiniz.' USING ERRCODE='P0001';
  END IF;
  SELECT count(*) INTO v_hedef_count FROM jsonb_array_elements_text(COALESCE(j->'Uyeler','[]'::jsonb)) x WHERE x.value ~ '^[0-9]+$';
  IF v_hedef_count = 0 THEN RAISE EXCEPTION 'Uyeler zorunlu.' USING ERRCODE='P0001'; END IF;
  IF v_rol = 0 AND public.fn_prog_mesaj_yoneticisayisi(v_kanalid) <= (
    SELECT count(*) FROM public.mesajkanaluye u
    JOIN jsonb_array_elements_text(COALESCE(j->'Uyeler','[]'::jsonb)) x ON x.value ~ '^[0-9]+$' AND x.value::integer=u.rehberid
    WHERE u.kanalid=v_kanalid AND u.ayrilmatarihi IS NULL AND u.rol=1
  ) THEN
    RAISE EXCEPTION 'Grupta en az bir yonetici kalmali.' USING ERRCODE='P0001';
  END IF;
  UPDATE public.mesajkanaluye u
     SET rol=CASE WHEN v_rol=1 THEN 1 ELSE 0 END
    FROM jsonb_array_elements_text(COALESCE(j->'Uyeler','[]'::jsonb)) x
   WHERE x.value ~ '^[0-9]+$' AND u.kanalid=v_kanalid AND u.rehberid=x.value::integer AND u.ayrilmatarihi IS NULL;
  RETURN jsonb_build_object('Sonuc',1,'KanalId',v_kanalid,'Rol',v_rol,'YoneticiSayisi',public.fn_prog_mesaj_yoneticisayisi(v_kanalid))::text;
END;
$$;

