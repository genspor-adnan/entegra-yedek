CREATE TABLE IF NOT EXISTS public.mesajkanal (
  id              integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  tur             smallint NOT NULL DEFAULT 1,
  adi             varchar(100),
  olusturan       integer NOT NULL DEFAULT 0,
  olusturmatarihi timestamp NOT NULL DEFAULT now(),
  durum           smallint NOT NULL DEFAULT 1,
  sonmesajid      bigint,
  sonmesajtarih   timestamp,
  subeid          integer,
  dosyaid         integer
);

CREATE TABLE IF NOT EXISTS public.mesajkanaluye (
  id              integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  kanalid         integer NOT NULL REFERENCES public.mesajkanal(id) ON DELETE CASCADE,
  rehberid        integer NOT NULL,
  rol             smallint NOT NULL DEFAULT 0,
  katilmatarihi   timestamp NOT NULL DEFAULT now(),
  ayrilmatarihi   timestamp,
  sonokumaid      bigint NOT NULL DEFAULT 0,
  bildirim        smallint NOT NULL DEFAULT 1,
  baslangicid     bigint NOT NULL DEFAULT 0,
  favori          smallint NOT NULL DEFAULT 0,
  UNIQUE (kanalid, rehberid)
);

CREATE TABLE IF NOT EXISTS public.mesaj (
  id              bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  kanalid         integer NOT NULL REFERENCES public.mesajkanal(id) ON DELETE CASCADE,
  gonderenid      integer NOT NULL,
  tarih           timestamp NOT NULL DEFAULT now(),
  metin           text,
  yanitid         bigint,
  dosyaid         integer,
  dosyaadi        varchar(200),
  dosyaboyut      bigint,
  silindi         smallint NOT NULL DEFAULT 0,
  silen           integer,
  silmetarihi     timestamp
);

CREATE TABLE IF NOT EXISTS public.mesajgizli (
  mesajid         bigint NOT NULL REFERENCES public.mesaj(id) ON DELETE CASCADE,
  rehberid        integer NOT NULL,
  tarih           timestamp NOT NULL DEFAULT now(),
  PRIMARY KEY (mesajid, rehberid)
);

CREATE INDEX IF NOT EXISTS ix_mesajkanal_son ON public.mesajkanal(sonmesajtarih DESC);
CREATE INDEX IF NOT EXISTS ix_mesajkanaluye_kul ON public.mesajkanaluye(rehberid, ayrilmatarihi);
CREATE INDEX IF NOT EXISTS ix_mesaj_kanal ON public.mesaj(kanalid, id);
CREATE INDEX IF NOT EXISTS ix_mesajgizli_kul ON public.mesajgizli(rehberid, mesajid);

CREATE OR REPLACE FUNCTION public.fn_prog_mesaj_birebirkanal(p_kulid integer, p_karsiid integer)
RETURNS integer
LANGUAGE sql
AS $$
  SELECT k.id
  FROM public.mesajkanal k
  WHERE k.tur = 1
    AND k.durum = 1
    AND EXISTS (SELECT 1 FROM public.mesajkanaluye u WHERE u.kanalid = k.id AND u.rehberid = p_kulid AND u.ayrilmatarihi IS NULL)
    AND EXISTS (SELECT 1 FROM public.mesajkanaluye u WHERE u.kanalid = k.id AND u.rehberid = p_karsiid AND u.ayrilmatarihi IS NULL)
    AND (SELECT count(*) FROM public.mesajkanaluye u WHERE u.kanalid = k.id AND u.ayrilmatarihi IS NULL) = 2
  ORDER BY k.id
  LIMIT 1;
$$;

CREATE OR REPLACE FUNCTION public.fn_prog_mesaj_yoneticisayisi(p_kanalid integer)
RETURNS integer
LANGUAGE sql
AS $$
  SELECT count(*)::integer
  FROM public.mesajkanaluye
  WHERE kanalid = p_kanalid AND ayrilmatarihi IS NULL AND rol = 1;
$$;

CREATE OR REPLACE FUNCTION public.fn_api_mesaj_kanal_kaydet_json(kosullar text DEFAULT '{}')
RETURNS text
LANGUAGE plpgsql
AS $$
DECLARE
  j jsonb := COALESCE(NULLIF(kosullar,'')::jsonb, '{}'::jsonb);
  v_islem text := lower(COALESCE(NULLIF(j->>'Islem',''), 'birebir'));
  v_kanalid integer := NULLIF(j->>'KanalId','')::integer;
  v_karsiid integer := NULLIF(j->>'KarsiId','')::integer;
  v_adi text := j->>'Adi';
  v_bildirim integer := COALESCE(NULLIF(j->>'Bildirim','')::integer, 0);
  v_gecmis integer := COALESCE(NULLIF(j->>'EskiMesajlar','')::integer, 0);
  v_kulid integer := COALESCE(NULLIF(j#>>'{Oturum,KulId}','')::integer, 0);
  v_subeid integer := NULLIF(j#>>'{Oturum,SubeId}','')::integer;
  v_yeni integer := 0;
  v_sonid bigint := 0;
  v_cikanlar integer[];
BEGIN
  IF v_kulid <= 0 THEN RAISE EXCEPTION 'Oturum.KulId zorunlu.' USING ERRCODE='P0001'; END IF;

  IF v_islem = 'birebir' THEN
    IF COALESCE(v_karsiid,0) <= 0 THEN RAISE EXCEPTION 'KarsiId zorunlu.' USING ERRCODE='P0001'; END IF;
    IF v_karsiid = v_kulid THEN RAISE EXCEPTION 'Kendinizle sohbet acamazsiniz.' USING ERRCODE='P0001'; END IF;

    SELECT public.fn_prog_mesaj_birebirkanal(v_kulid, v_karsiid) INTO v_kanalid;
    IF v_kanalid IS NULL THEN
      INSERT INTO public.mesajkanal(tur, adi, olusturan, durum, subeid)
      VALUES (1, NULL, v_kulid, 1, v_subeid)
      RETURNING id INTO v_kanalid;
      v_yeni := 1;
      INSERT INTO public.mesajkanaluye(kanalid, rehberid, rol)
      VALUES (v_kanalid, v_kulid, 1), (v_kanalid, v_karsiid, 1);
    END IF;

  ELSIF v_islem = 'grup' THEN
    IF COALESCE(length(v_adi),0) = 0 THEN RAISE EXCEPTION 'Grup adi zorunlu.' USING ERRCODE='P0001'; END IF;
    INSERT INTO public.mesajkanal(tur, adi, olusturan, durum, subeid)
    VALUES (2, left(v_adi,100), v_kulid, 1, v_subeid)
    RETURNING id INTO v_kanalid;
    v_yeni := 1;
    INSERT INTO public.mesajkanaluye(kanalid, rehberid, rol) VALUES (v_kanalid, v_kulid, 1);
    INSERT INTO public.mesajkanaluye(kanalid, rehberid, rol)
    SELECT v_kanalid, x.value::integer, 0
    FROM jsonb_array_elements_text(COALESCE(j->'Uyeler','[]'::jsonb)) x
    WHERE x.value ~ '^[0-9]+$' AND x.value::integer <> v_kulid
    ON CONFLICT (kanalid, rehberid) DO NOTHING;

  ELSIF v_islem = 'uyeekle' THEN
    IF COALESCE(v_kanalid,0) <= 0 THEN RAISE EXCEPTION 'KanalId zorunlu.' USING ERRCODE='P0001'; END IF;
    IF NOT EXISTS (SELECT 1 FROM public.mesajkanaluye WHERE kanalid=v_kanalid AND rehberid=v_kulid AND ayrilmatarihi IS NULL) THEN
      RAISE EXCEPTION 'Bu sohbetin uyesi degilsiniz.' USING ERRCODE='P0001';
    END IF;
    IF (SELECT tur FROM public.mesajkanal WHERE id=v_kanalid) <> 2 THEN
      RAISE EXCEPTION 'Yalnizca gruplara uye eklenebilir.' USING ERRCODE='P0001';
    END IF;
    SELECT COALESCE(max(id),0) INTO v_sonid FROM public.mesaj WHERE kanalid=v_kanalid;
    UPDATE public.mesajkanaluye u
       SET ayrilmatarihi=NULL, katilmatarihi=now(), baslangicid=CASE WHEN v_gecmis=1 THEN 0 ELSE v_sonid END
      FROM jsonb_array_elements_text(COALESCE(j->'Uyeler','[]'::jsonb)) x
     WHERE u.kanalid=v_kanalid AND u.rehberid=x.value::integer AND u.ayrilmatarihi IS NOT NULL AND x.value ~ '^[0-9]+$';
    INSERT INTO public.mesajkanaluye(kanalid, rehberid, rol, baslangicid, sonokumaid)
    SELECT v_kanalid, x.value::integer, 0,
           CASE WHEN v_gecmis=1 THEN 0 ELSE v_sonid END,
           CASE WHEN v_gecmis=1 THEN 0 ELSE v_sonid END
    FROM jsonb_array_elements_text(COALESCE(j->'Uyeler','[]'::jsonb)) x
    WHERE x.value ~ '^[0-9]+$'
    ON CONFLICT (kanalid, rehberid) DO NOTHING;

  ELSIF v_islem = 'uyecikar' THEN
    IF COALESCE(v_kanalid,0) <= 0 THEN RAISE EXCEPTION 'KanalId zorunlu.' USING ERRCODE='P0001'; END IF;
    SELECT COALESCE(array_agg(x.value::integer), ARRAY[v_kulid])
      INTO v_cikanlar
      FROM jsonb_array_elements_text(COALESCE(j->'Uyeler','[]'::jsonb)) x
      WHERE x.value ~ '^[0-9]+$';
    IF EXISTS (SELECT 1 FROM unnest(v_cikanlar) c(id) WHERE c.id <> v_kulid)
       AND NOT EXISTS (SELECT 1 FROM public.mesajkanaluye WHERE kanalid=v_kanalid AND rehberid=v_kulid AND rol=1 AND ayrilmatarihi IS NULL) THEN
      RAISE EXCEPTION 'Uye cikarmak icin grup yoneticisi olmalisiniz.' USING ERRCODE='P0001';
    END IF;
    UPDATE public.mesajkanaluye SET ayrilmatarihi=now()
    WHERE kanalid=v_kanalid AND ayrilmatarihi IS NULL AND rehberid = ANY(v_cikanlar);

  ELSIF v_islem = 'addegistir' THEN
    IF COALESCE(v_kanalid,0) <= 0 OR COALESCE(length(v_adi),0) = 0 THEN
      RAISE EXCEPTION 'KanalId ve Adi zorunlu.' USING ERRCODE='P0001';
    END IF;
    IF NOT EXISTS (SELECT 1 FROM public.mesajkanaluye WHERE kanalid=v_kanalid AND rehberid=v_kulid AND ayrilmatarihi IS NULL) THEN
      RAISE EXCEPTION 'Bu sohbetin uyesi degilsiniz.' USING ERRCODE='P0001';
    END IF;
    UPDATE public.mesajkanal SET adi=left(v_adi,100) WHERE id=v_kanalid AND tur=2;

  ELSIF v_islem = 'sessize' THEN
    IF COALESCE(v_kanalid,0) <= 0 THEN RAISE EXCEPTION 'KanalId zorunlu.' USING ERRCODE='P0001'; END IF;
    UPDATE public.mesajkanaluye SET bildirim=v_bildirim WHERE kanalid=v_kanalid AND rehberid=v_kulid;
  ELSE
    RAISE EXCEPTION 'Bilinmeyen Islem.' USING ERRCODE='P0001';
  END IF;

  RETURN jsonb_build_object('Sonuc',1,'KanalId',v_kanalid,'Yeni',v_yeni)::text;
END;
$$;

CREATE OR REPLACE FUNCTION public.fn_api_mesaj_gonder_json(kosullar text DEFAULT '{}')
RETURNS text
LANGUAGE plpgsql
AS $$
DECLARE
  j jsonb := COALESCE(NULLIF(kosullar,'')::jsonb, '{}'::jsonb);
  v_kanalid integer := NULLIF(j->>'KanalId','')::integer;
  v_metin text := j->>'Metin';
  v_yanitid bigint := NULLIF(j->>'YanitId','')::bigint;
  v_dosyaid integer := NULLIF(j->>'DosyaId','')::integer;
  v_dosyaadi text := j->>'DosyaAdi';
  v_dosyaboyut bigint := NULLIF(j->>'DosyaBoyut','')::bigint;
  v_kulid integer := COALESCE(NULLIF(j#>>'{Oturum,KulId}','')::integer, 0);
  v_id bigint;
  v_trh timestamp := now();
BEGIN
  IF v_kulid <= 0 OR COALESCE(v_kanalid,0) <= 0 THEN RAISE EXCEPTION 'KanalId ve Oturum.KulId zorunlu.' USING ERRCODE='P0001'; END IF;
  IF COALESCE(length(v_metin),0) = 0 AND v_dosyaid IS NULL THEN RAISE EXCEPTION 'Bos mesaj gonderilemez.' USING ERRCODE='P0001'; END IF;
  IF NOT EXISTS (SELECT 1 FROM public.mesajkanaluye WHERE kanalid=v_kanalid AND rehberid=v_kulid AND ayrilmatarihi IS NULL) THEN
    RAISE EXCEPTION 'Bu sohbetin uyesi degilsiniz.' USING ERRCODE='P0001';
  END IF;

  INSERT INTO public.mesaj(kanalid,gonderenid,tarih,metin,yanitid,dosyaid,dosyaadi,dosyaboyut)
  VALUES (v_kanalid,v_kulid,v_trh,v_metin,v_yanitid,v_dosyaid,left(v_dosyaadi,200),v_dosyaboyut)
  RETURNING id INTO v_id;

  UPDATE public.mesajkanal SET sonmesajid=v_id, sonmesajtarih=v_trh WHERE id=v_kanalid;
  UPDATE public.mesajkanaluye SET sonokumaid=v_id WHERE kanalid=v_kanalid AND rehberid=v_kulid AND sonokumaid < v_id;

  RETURN jsonb_build_object('Sonuc',1,'MesajId',v_id,'KanalId',v_kanalid,'Tarih',to_char(v_trh,'YYYY-MM-DD"T"HH24:MI:SS'))::text;
END;
$$;

