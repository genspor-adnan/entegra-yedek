CREATE OR REPLACE FUNCTION public.fn_prog_izleme_yaz_json(kosullar text DEFAULT '{}')
RETURNS text
LANGUAGE plpgsql AS $$
DECLARE
  j jsonb := COALESCE(NULLIF(kosullar, '')::jsonb, '{}'::jsonb);
  v_tur integer := NULLIF(j#>>'{belge,tur}', '')::integer;
  v_baslikid integer := NULLIF(j#>>'{belge,baslikId}', '')::integer;
  v_satirid integer := NULLIF(j#>>'{belge,satirId}', '')::integer;
  v_islemtip integer := COALESCE(NULLIF(j#>>'{belge,islemTip}', '')::integer, 0);
  v_stokid integer := NULLIF(j->>'stokId', '')::integer;
  v_izlemtur integer := COALESCE(NULLIF(j->>'izlemTur', '')::integer, 0);
  v_girdepo integer := COALESCE(NULLIF(j->>'girDepo', '')::integer, 0);
  v_cikdepo integer := COALESCE(NULLIF(j->>'cikDepo', '')::integer, 0);
  v_stokhar integer := COALESCE(NULLIF(j->>'stokHareketi', '')::integer, 1);
  v_kaynaksatir integer := COALESCE(NULLIF(j->>'kaynakSatirId', '')::integer, 0);
  v_oncekisil integer := COALESCE(NULLIF(j->>'oncekiSil', '')::integer, 1);
  v_kulid integer := COALESCE(NULLIF(j->>'kullaniciId', '')::integer, 0);
  v_cikis boolean;
  r record;
  v_yeniid integer;
  v_hareket numeric;
  v_yazilan integer := 0;
  v_toplam numeric := 0;
BEGIN
  IF v_tur IS NULL THEN RAISE EXCEPTION 'belge.tur zorunlu.' USING ERRCODE = 'P0001'; END IF;
  IF v_baslikid IS NULL OR v_baslikid <= 0 THEN RAISE EXCEPTION 'belge.baslikId zorunlu.' USING ERRCODE = 'P0001'; END IF;
  IF v_satirid IS NULL OR v_satirid <= 0 THEN RAISE EXCEPTION 'belge.satirId zorunlu.' USING ERRCODE = 'P0001'; END IF;
  IF v_stokid IS NULL OR v_stokid <= 0 THEN RAISE EXCEPTION 'stokId zorunlu.' USING ERRCODE = 'P0001'; END IF;

  CREATE TEMP TABLE IF NOT EXISTS pg_temp.tmp_izleme_yaz_s(
    sira integer GENERATED BY DEFAULT AS IDENTITY,
    serilotid integer,
    izlemid integer,
    serino varchar(64),
    lotno varchar(50),
    skt timestamp,
    urt timestamp,
    adet numeric
  ) ON COMMIT DROP;
  TRUNCATE TABLE pg_temp.tmp_izleme_yaz_s;

  INSERT INTO pg_temp.tmp_izleme_yaz_s(serilotid, izlemid, serino, lotno, skt, urt, adet)
  SELECT NULLIF(x->>'serilotId', '')::integer,
         COALESCE(NULLIF(x->>'izlemId', '')::integer, 0),
         COALESCE(x->>'seriNo', ''),
         COALESCE(x->>'lotNo', ''),
         NULLIF(x->>'skt', '')::timestamp,
         NULLIF(x->>'urt', '')::timestamp,
         NULLIF(x->>'adet', '')::numeric
  FROM jsonb_array_elements(COALESCE(j->'satirlar', '[]'::jsonb)) x
  WHERE COALESCE(NULLIF(x->>'adet', '')::numeric, 0) > 0;

  v_cikis := v_tur IN (4, 14, 15, 16, 20, 101, 119);

  IF v_stokhar = 1 AND EXISTS (SELECT 1 FROM pg_temp.tmp_izleme_yaz_s)
     AND ((v_cikis AND v_cikdepo <= 0) OR ((NOT v_cikis) AND v_girdepo <= 0)) THEN
    RAISE EXCEPTION 'Bu belgede depo secilmedigi icin seri/lot hareketi kaydedilemez. Once belgenin giris/cikis deposunu secin.'
      USING ERRCODE = 'P0001';
  END IF;

  IF v_oncekisil = 1 THEN
    CREATE TEMP TABLE IF NOT EXISTS pg_temp.tmp_izleme_yaz_eski(id integer PRIMARY KEY) ON COMMIT DROP;
    TRUNCATE TABLE pg_temp.tmp_izleme_yaz_eski;

    INSERT INTO pg_temp.tmp_izleme_yaz_eski(id)
    SELECT id
    FROM public.stokizleme
    WHERE belgetur = v_tur
      AND stokid = v_stokid
      AND baslikid = v_baslikid
      AND satirid = v_satirid;

    -- Sira kasitli: parent once. BEFORE DELETE trigger depo hareketlerini geri alir.
    DELETE FROM public.stokizleme
    WHERE id IN (SELECT id FROM pg_temp.tmp_izleme_yaz_eski);

    DELETE FROM public.stokizlemedepo
    WHERE izlemid IN (SELECT id FROM pg_temp.tmp_izleme_yaz_eski);
  END IF;

  IF NOT EXISTS (SELECT 1 FROM pg_temp.tmp_izleme_yaz_s) THEN
    RETURN jsonb_build_object('Sonuc', 1, 'Yazilan', 0, 'ToplamAdet', 0)::text;
  END IF;

  UPDATE pg_temp.tmp_izleme_yaz_s s
     SET serilotid = ssl.id
    FROM public.stokserilot ssl
   WHERE COALESCE(s.serilotid, 0) = 0
     AND ssl.stokid = v_stokid
     AND COALESCE(ssl.serino, '') = COALESCE(s.serino, '')
     AND COALESCE(ssl.lotno, '') = COALESCE(s.lotno, '');

  IF EXISTS (
    SELECT 1 FROM pg_temp.tmp_izleme_yaz_s
    WHERE COALESCE(serilotid, 0) = 0 AND COALESCE(serino, '') = '' AND COALESCE(lotno, '') = ''
  ) THEN
    RAISE EXCEPTION 'Seri/lot karti olusturulamadi (seri no ve lot no bos olamaz).' USING ERRCODE = 'P0001';
  END IF;

  INSERT INTO public.stokserilot(stokid, serino, lotno, urt, skt)
  SELECT DISTINCT v_stokid, s.serino, s.lotno,
         COALESCE(s.urt, '1990-01-01'::timestamp),
         COALESCE(s.skt, '1990-01-01'::timestamp)
  FROM pg_temp.tmp_izleme_yaz_s s
  WHERE COALESCE(s.serilotid, 0) = 0
    AND NOT EXISTS (
      SELECT 1 FROM public.stokserilot ssl
      WHERE ssl.stokid = v_stokid
        AND COALESCE(ssl.serino, '') = COALESCE(s.serino, '')
        AND COALESCE(ssl.lotno, '') = COALESCE(s.lotno, '')
    );

  UPDATE pg_temp.tmp_izleme_yaz_s s
     SET serilotid = ssl.id
    FROM public.stokserilot ssl
   WHERE COALESCE(s.serilotid, 0) = 0
     AND ssl.stokid = v_stokid
     AND COALESCE(ssl.serino, '') = COALESCE(s.serino, '')
     AND COALESCE(ssl.lotno, '') = COALESCE(s.lotno, '');

  IF EXISTS (SELECT 1 FROM pg_temp.tmp_izleme_yaz_s WHERE COALESCE(serilotid, 0) = 0) THEN
    RAISE EXCEPTION 'Seri/lot karti olusturulamadi (seri no ve lot no bos olamaz).' USING ERRCODE = 'P0001';
  END IF;

  FOR r IN SELECT * FROM pg_temp.tmp_izleme_yaz_s ORDER BY sira LOOP
    INSERT INTO public.stokizleme(stokid, belgetur, baslikid, satirid, izlemtur,
                                  adet, kalan, yer, yerid, donusid, serilotid, ekleyen)
    VALUES (v_stokid, v_tur, v_baslikid, v_satirid, v_izlemtur,
            r.adet, r.adet, 0, 0,
            CASE WHEN v_kaynaksatir > 0 THEN COALESCE(r.izlemid, 0) ELSE 0 END,
            r.serilotid, v_kulid)
    RETURNING id INTO v_yeniid;

    v_hareket := CASE WHEN v_stokhar = 1 THEN r.adet ELSE 0 END;

    IF v_cikis THEN
      INSERT INTO public.stokizlemedepo(izlemid, depoid, adet)
      VALUES (v_yeniid, v_cikdepo, -1.0 * v_hareket);
    ELSE
      INSERT INTO public.stokizlemedepo(izlemid, depoid, adet)
      VALUES (v_yeniid, v_girdepo, v_hareket);
    END IF;

    IF v_tur IN (20, 119) THEN
      INSERT INTO public.stokizlemedepo(izlemid, depoid, adet)
      VALUES (v_yeniid, v_girdepo, v_hareket);
    ELSIF v_tur = 109 AND v_islemtip = 2 THEN
      INSERT INTO public.stokizlemedepo(izlemid, depoid, adet)
      VALUES (v_yeniid, v_cikdepo, -1.0 * v_hareket);
    END IF;

    v_yazilan := v_yazilan + 1;
    v_toplam := v_toplam + r.adet;
  END LOOP;

  RETURN jsonb_build_object('Sonuc', 1, 'Yazilan', v_yazilan, 'ToplamAdet', v_toplam)::text;
END;
$$;

CREATE OR REPLACE FUNCTION public.fn_prog_izleme_aktar_json(kosullar text DEFAULT '{}')
RETURNS text
LANGUAGE plpgsql AS $$
DECLARE
  j jsonb := COALESCE(NULLIF(kosullar, '')::jsonb, '{}'::jsonb);
  v_kaynaksatir integer := NULLIF(j#>>'{kaynak,satirId}', '')::integer;
  v_hedeftur integer := NULLIF(j#>>'{hedef,tur}', '')::integer;
  v_hedefbaslik integer := NULLIF(j#>>'{hedef,baslikId}', '')::integer;
  v_hedefsatir integer := NULLIF(j#>>'{hedef,satirId}', '')::integer;
  v_depoid integer := NULLIF(j->>'depoId', '')::integer;
  v_stokhar integer := COALESCE(NULLIF(j->>'stokHareketi', '')::integer, 1);
  v_kulid integer := COALESCE(NULLIF(j->>'kullaniciId', '')::integer, 0);
  v_istenen numeric := NULLIF(j->>'istenenAdet', '')::numeric;
  v_secimvar boolean := jsonb_typeof(j->'secim') = 'array' AND jsonb_array_length(j->'secim') > 0;
  v_depodan boolean := COALESCE(v_kaynaksatir, 0) <= 0;
  v_stokid integer;
  v_izlemtur integer;
  v_satiradet numeric;
  v_toplam numeric;
  v_mevcut numeric;
  v_yon integer;
  r record;
  v_yeniid integer;
  v_aktarilan integer := 0;
  v_toplamy numeric := 0;
BEGIN
  IF v_hedefsatir IS NULL OR v_hedefsatir <= 0 THEN RAISE EXCEPTION 'hedef.satirId zorunlu.' USING ERRCODE = 'P0001'; END IF;
  IF v_hedefbaslik IS NULL OR v_hedefbaslik <= 0 THEN RAISE EXCEPTION 'hedef.baslikId zorunlu.' USING ERRCODE = 'P0001'; END IF;
  IF v_hedeftur IS NULL THEN RAISE EXCEPTION 'hedef.tur zorunlu.' USING ERRCODE = 'P0001'; END IF;
  IF v_stokhar = 1 AND COALESCE(v_depoid, 0) <= 0 THEN
    RAISE EXCEPTION 'Stok hareketi yapilacaksa gecerli depoId zorunlu.' USING ERRCODE = 'P0001';
  END IF;
  IF v_depodan AND NOT v_secimvar THEN
    RAISE EXCEPTION 'Kaynak belgede seri/lot kaydi olmadigindan secim zorunlu (depodan secilir).' USING ERRCODE = 'P0001';
  END IF;

  CREATE TEMP TABLE IF NOT EXISTS pg_temp.tmp_izleme_aktar_t(
    sira integer GENERATED BY DEFAULT AS IDENTITY,
    kaynakizlemid integer,
    serilotid integer,
    stokid integer,
    izlemtur integer,
    yer integer,
    adet numeric
  ) ON COMMIT DROP;
  TRUNCATE TABLE pg_temp.tmp_izleme_aktar_t;

  IF v_depodan THEN
    SELECT f.urunid, COALESCE(f.izleme, 0), ABS(COALESCE(f.adet, 0))
      INTO v_stokid, v_izlemtur, v_satiradet
    FROM public.fatura f
    WHERE f.id = v_hedefsatir;

    IF v_stokid IS NULL THEN
      RAISE EXCEPTION 'hedef.satirId bulunamadi.' USING ERRCODE = 'P0001';
    END IF;

    INSERT INTO pg_temp.tmp_izleme_aktar_t(kaynakizlemid, serilotid, stokid, izlemtur, yer, adet)
    SELECT NULL::integer,
           NULLIF(x->>'serilotId', '')::integer,
           v_stokid, v_izlemtur, 0,
           SUM(NULLIF(x->>'adet', '')::numeric)
    FROM jsonb_array_elements(COALESCE(j->'secim', '[]'::jsonb)) x
    WHERE COALESCE(NULLIF(x->>'adet', '')::numeric, 0) > 0
      AND COALESCE(NULLIF(x->>'serilotId', '')::integer, 0) > 0
    GROUP BY NULLIF(x->>'serilotId', '')::integer;

    SELECT COALESCE(SUM(adet), 0) INTO v_toplam FROM pg_temp.tmp_izleme_aktar_t;
    IF v_satiradet > 0 AND ABS(v_toplam - v_satiradet) > 0.0001 THEN
      RAISE EXCEPTION 'Secilen seri/lot toplami (%) satir adediyle (%) ayni degil.',
        ROUND(v_toplam, 3), ROUND(v_satiradet, 3) USING ERRCODE = 'P0001';
    END IF;

    IF v_stokhar = 1 AND v_hedeftur IN (4, 14, 15, 16, 99, 119) THEN
      FOR r IN SELECT * FROM pg_temp.tmp_izleme_aktar_t LOOP
        SELECT COALESCE(sdi.kalan, 0) - COALESCE(k.kendi, 0)
          INTO v_mevcut
        FROM public.stokdurumizleme sdi
        LEFT JOIN LATERAL (
          SELECT SUM(COALESCE(d.adet, 0)) AS kendi
          FROM public.stokizlemedepo d
          INNER JOIN public.stokizleme si2 ON si2.id = d.izlemid
          WHERE si2.satirid = v_hedefsatir
            AND si2.serilotid = r.serilotid
            AND d.depoid = v_depoid
        ) k ON TRUE
        WHERE sdi.serilotid = r.serilotid AND sdi.depoid = v_depoid;

        IF COALESCE(v_mevcut, 0) + 0.0001 < r.adet THEN
          RAISE EXCEPTION 'Secilen seri/lot icin depoda yeterli miktar yok (mevcut: %, istenen: %).',
            ROUND(COALESCE(v_mevcut, 0), 3), ROUND(r.adet, 3) USING ERRCODE = 'P0001';
        END IF;
      END LOOP;
    END IF;

  ELSIF v_secimvar THEN
    INSERT INTO pg_temp.tmp_izleme_aktar_t(kaynakizlemid, serilotid, stokid, izlemtur, yer, adet)
    SELECT si.id, si.serilotid, si.stokid, si.izlemtur, si.yer,
           NULLIF(x->>'adet', '')::numeric
    FROM jsonb_array_elements(j->'secim') x
    INNER JOIN public.stokizleme si ON si.id = NULLIF(x->>'kaynakIzlemId', '')::integer
    WHERE COALESCE(NULLIF(x->>'adet', '')::numeric, 0) > 0
      AND COALESCE(NULLIF(x->>'kaynakIzlemId', '')::integer, 0) > 0
      AND si.satirid = v_kaynaksatir;

    INSERT INTO pg_temp.tmp_izleme_aktar_t(kaynakizlemid, serilotid, stokid, izlemtur, yer, adet)
    SELECT MIN(si.id), si.serilotid, MIN(si.stokid), MIN(si.izlemtur), MIN(si.yer),
           MIN(NULLIF(x->>'adet', '')::numeric)
    FROM jsonb_array_elements(j->'secim') x
    INNER JOIN public.stokizleme si
      ON si.satirid = v_kaynaksatir
     AND si.serilotid = NULLIF(x->>'serilotId', '')::integer
    WHERE COALESCE(NULLIF(x->>'adet', '')::numeric, 0) > 0
      AND COALESCE(NULLIF(x->>'kaynakIzlemId', '')::integer, 0) = 0
      AND NOT EXISTS (
        SELECT 1 FROM pg_temp.tmp_izleme_aktar_t t
        WHERE t.serilotid = NULLIF(x->>'serilotId', '')::integer
      )
    GROUP BY si.serilotid;

    FOR r IN SELECT t.*, si.kalan FROM pg_temp.tmp_izleme_aktar_t t INNER JOIN public.stokizleme si ON si.id = t.kaynakizlemid LOOP
      IF ABS(COALESCE(r.kalan, 0)) + 0.0001 < r.adet THEN
        RAISE EXCEPTION 'Secilen seri/lot icin kaynakta yeterli kalan yok (mevcut: %, istenen: %).',
          ROUND(ABS(COALESCE(r.kalan, 0)), 3), ROUND(r.adet, 3) USING ERRCODE = 'P0001';
      END IF;
    END LOOP;

  ELSIF COALESCE(v_istenen, 0) > 0 THEN
    SELECT COALESCE(SUM(ABS(COALESCE(si.kalan, 0))), 0)
      INTO v_mevcut
    FROM public.stokizleme si
    WHERE si.satirid = v_kaynaksatir;

    IF v_mevcut + 0.0001 < v_istenen THEN
      RAISE EXCEPTION 'Kaynak belgede tasinabilir seri/lot yetersiz (mevcut: %, istenen: %).',
        ROUND(v_mevcut, 3), ROUND(v_istenen, 3) USING ERRCODE = 'P0001';
    END IF;

    INSERT INTO pg_temp.tmp_izleme_aktar_t(kaynakizlemid, serilotid, stokid, izlemtur, yer, adet)
    SELECT k.id, k.serilotid, k.stokid, k.izlemtur, k.yer,
           CASE WHEN k.onceki + k.kalan <= v_istenen THEN k.kalan ELSE v_istenen - k.onceki END
    FROM (
      SELECT si.id, si.serilotid, si.stokid, si.izlemtur, si.yer,
             ABS(COALESCE(si.kalan, 0)) AS kalan,
             COALESCE(SUM(ABS(COALESCE(si.kalan, 0))) OVER (
               ORDER BY ssl.skt, si.id ROWS BETWEEN UNBOUNDED PRECEDING AND 1 PRECEDING
             ), 0) AS onceki
      FROM public.stokizleme si
      INNER JOIN public.stokserilot ssl ON ssl.id = si.serilotid
      WHERE si.satirid = v_kaynaksatir AND ABS(COALESCE(si.kalan, 0)) > 0.0001
    ) k
    WHERE k.onceki < v_istenen - 0.0001;
  ELSE
    INSERT INTO pg_temp.tmp_izleme_aktar_t(kaynakizlemid, serilotid, stokid, izlemtur, yer, adet)
    SELECT si.id, si.serilotid, si.stokid, si.izlemtur, si.yer, ABS(COALESCE(si.kalan, 0))
    FROM public.stokizleme si
    WHERE si.satirid = v_kaynaksatir AND ABS(COALESCE(si.kalan, 0)) > 0.0001;
  END IF;

  IF NOT EXISTS (SELECT 1 FROM pg_temp.tmp_izleme_aktar_t) THEN
    RETURN jsonb_build_object('Sonuc', 1, 'Aktarilan', 0, 'ToplamAdet', 0)::text;
  END IF;

  v_yon := CASE WHEN v_hedeftur IN (4, 14, 15, 16, 99, 119) THEN -1 ELSE 1 END;

  FOR r IN SELECT * FROM pg_temp.tmp_izleme_aktar_t ORDER BY sira LOOP
    INSERT INTO public.stokizleme(stokid, belgetur, baslikid, satirid, izlemtur,
                                  adet, kalan, yer, yerid, donusid, serilotid, ekleyen)
    VALUES (r.stokid, v_hedeftur, v_hedefbaslik, v_hedefsatir, r.izlemtur,
            r.adet, r.adet, COALESCE(r.yer, 0), 0, COALESCE(r.kaynakizlemid, 0),
            r.serilotid, v_kulid)
    RETURNING id INTO v_yeniid;

    INSERT INTO public.stokizlemedepo(izlemid, depoid, adet)
    VALUES (v_yeniid, COALESCE(v_depoid, 0), CASE WHEN v_stokhar = 1 THEN v_yon * r.adet ELSE 0 END);

    v_aktarilan := v_aktarilan + 1;
    v_toplamy := v_toplamy + r.adet;
  END LOOP;

  RETURN jsonb_build_object(
    'Sonuc', 1,
    'Aktarilan', v_aktarilan,
    'ToplamAdet', v_toplamy,
    'Kip', CASE WHEN v_depodan THEN 'depodan' ELSE 'tasima' END
  )::text;
END;
$$;
