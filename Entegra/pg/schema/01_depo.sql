-- ============================================================
-- PILOT: Gentegre LOG/DOSYA deposu -> PostgreSQL
-- MSSQL GENDEPO (AYRI veritabani) -> PG: 'depo' SCHEMA
--   (PG cross-database yapamaz -> ayri DB yerine schema kullanilir)
-- ============================================================

DROP SCHEMA IF EXISTS depo CASCADE;
CREATE SCHEMA depo;

-- Turkce CASE-INSENSITIVE collation
--   MSSQL varsayilani SQL_Latin1_General_CP1254_CI_AS (CI=buyuk/kucuk duyarsiz, AS=aksan duyarli).
--   PG string karsilastirmasi varsayilan CASE-SENSITIVE -> bu collation ile CI davranisi + Turkce (İ/ı).
--   ks-level2 = case-insensitive; deterministic=false (CI icin sart).
CREATE COLLATION depo.tr_ci (provider = icu, locale = 'tr-TR-u-ks-level2', deterministic = false);

-- ---- LOGCOZUM (ID->ad cozumleme kurallari) ----
CREATE TABLE depo.logcozum (
  id           integer     GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,   -- int IDENTITY
  tabloid      integer,
  alan         varchar(128) COLLATE depo.tr_ci NOT NULL,                   -- nvarchar
  kaynaktablo  varchar(256) NOT NULL,
  idkolon      varchar(128) NOT NULL,
  adkolon      varchar(128) NOT NULL,
  filtre       varchar(800),
  aktif        smallint    NOT NULL DEFAULT 1                              -- bit (MSSQL bit->smallint; app 0/1 yazar)
);
CREATE INDEX ix_logcozum_alan ON depo.logcozum (alan, tabloid);

-- ---- LOGREFERANS (kart adi/kodu; silinse de kalici) ----
CREATE TABLE depo.logreferans (
  id        bigint       GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  tabloid   integer      NOT NULL,
  kayitid   bigint       NOT NULL,
  ad        varchar(400) COLLATE depo.tr_ci,
  kod       varchar(120) COLLATE depo.tr_ci,
  silindi   smallint     NOT NULL DEFAULT 0,                                -- bit (MSSQL bit->smallint; app 0/1 yazar)
  sonislem  timestamp(3)                                                   -- datetime
);
CREATE INDEX ix_logreferans_ad    ON depo.logreferans (ad);
CREATE INDEX ix_logreferans_kod   ON depo.logreferans (kod);
CREATE INDEX ix_logreferans_kayit ON depo.logreferans (tabloid, kayitid, id);

-- ---- SNAPSHOT (geri-alinabilir oturum) ----
CREATE TABLE depo.snapshot (
  id           bigint        GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  oturumid     varchar(72)   COLLATE depo.tr_ci NOT NULL,
  anatabloadi  varchar(256)  COLLATE depo.tr_ci,
  anaid        bigint,
  sira         smallint      NOT NULL,
  tabloadi     varchar(256)  COLLATE depo.tr_ci NOT NULL,
  filtre       varchar(2000) COLLATE depo.tr_ci NOT NULL,
  kayitid      bigint,
  satirjson    jsonb,                                                      -- nvarchar(max) -> PG-native JSONB
  tarih        timestamp(6)  NOT NULL DEFAULT now()
);
CREATE INDEX ix_snapshot_oturum ON depo.snapshot (oturumid, sira, id);
CREATE INDEX ix_snapshot_ana    ON depo.snapshot (anatabloadi, anaid);

-- ---- DOSYA (icerik deposu) ----
--   MSSQL: ICERIK varbinary(max) FILESTREAM (Express 10 GB'i asmak icin).
--   PG:    ICERIK bytea. PG'de DB boyut limiti YOK -> FILESTREAM gerekcesi ORTADAN KALKAR.
--          (Cok buyuk/streaming icin Large Object 'lo' alternatifi de var.)
CREATE TABLE depo.dosya (
  id         bigint       GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  dosyaguid  uuid         NOT NULL DEFAULT gen_random_uuid() UNIQUE,       -- uniqueidentifier
  hash       bytea        NOT NULL UNIQUE,                                 -- binary(32) SHA-256
  boyut      bigint       NOT NULL,
  uzanti     varchar(40),
  mimetype   varchar(200),
  icerik     bytea        NOT NULL,                                        -- varbinary(max) FILESTREAM
  refsayac   integer      NOT NULL DEFAULT 1,
  ekleme     timestamp(6) NOT NULL DEFAULT now()
);

-- ---- LOG2026 (yillik audit log) ----
--   BILGI: MSSQL varbinary(max) = COMPRESS(json). PG'de JSONB (native, sorgulanabilir,
--          TOAST otomatik sikistirir) -> COMPRESS/DECOMPRESS ihtiyaci ORTADAN KALKAR.
CREATE TABLE depo.log2026 (
  id            bigint       GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  tarih         timestamp(6) NOT NULL DEFAULT now(),
  ip            varchar(45),
  istasyon      varchar(64),
  kullaniciid   integer,
  subeid        smallint,
  islemtipi     smallint     NOT NULL,                                     -- tinyint -> smallint
  usttabloid    integer,
  ustkayitid    bigint,
  tabloid       integer,
  kayitid       bigint,
  rehberid      bigint,
  stokid        bigint,
  bilgi         jsonb,                                                     -- varbinary+COMPRESS -> jsonb
  altislemtipi  smallint
);
CREATE INDEX ix_log2026_ust    ON depo.log2026 (usttabloid, ustkayitid);
CREATE INDEX ix_log2026_kayit  ON depo.log2026 (tabloid, kayitid);
CREATE INDEX ix_log2026_rehber ON depo.log2026 (rehberid);
CREATE INDEX ix_log2026_stok   ON depo.log2026 (stokid);
CREATE INDEX ix_log2026_tarih  ON depo.log2026 (tarih);

-- ---- ISLEMLOG (tum LOG<yyyy> birlesimi) ----
--   MSSQL: dinamik yeniden kurulan UNION view. PG: view (yeni yil -> UNION ekle) veya
--          PG-native declarative PARTITIONING (yil bazli) daha temiz olurdu.
CREATE VIEW depo.islemlog AS SELECT * FROM depo.log2026;

-- ============================================================
-- FONKSIYONLAR (T-SQL SP/trigger -> PL/pgSQL)
-- ============================================================

-- DOSYA kaydet (hash-dedup).
--   MSSQL: UPDATE...OUTPUT WHERE HASH=.. (varsa) ELSE INSERT...OUTPUT (2 adim, yaris riski).
--   PG:    tek ATOMIK upsert -> INSERT ... ON CONFLICT (hash) DO UPDATE. Daha temiz+guvenli.
CREATE OR REPLACE FUNCTION depo.dosya_kaydet(
  p_hash bytea, p_boyut bigint, p_uzanti varchar, p_mime varchar, p_icerik bytea)
RETURNS bigint LANGUAGE sql AS $$
  INSERT INTO depo.dosya (hash, boyut, uzanti, mimetype, icerik)
  VALUES (p_hash, p_boyut, p_uzanti, p_mime, p_icerik)
  ON CONFLICT (hash) DO UPDATE SET refsayac = depo.dosya.refsayac + 1
  RETURNING id;
$$;

-- DOSYA referans azalt; 0'a inince sil (MSSQL DosyaReferansAzalt karsiligi).
CREATE OR REPLACE FUNCTION depo.dosya_referans_azalt(p_id bigint)
RETURNS void LANGUAGE plpgsql AS $$
BEGIN
  UPDATE depo.dosya SET refsayac = refsayac - 1 WHERE id = p_id;
  DELETE FROM depo.dosya WHERE id = p_id AND refsayac <= 0;
END;
$$;
