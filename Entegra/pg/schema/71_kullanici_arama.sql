-- ============================================================
-- kullanici_arama — MSSQL KULLANICI_ARAMA PG portu
-- ------------------------------------------------------------
-- "Son Aranan / Sik Aranan" listelerinin kaynagi. Tablo PG semasinda eksikti;
--   Mod=5/6 sorgulari "relation kullanici_arama does not exist" ile patliyordu.
-- KULID+MODUL+KAYITID benzersiz (Tablo.AramaKaydet upsert bu tekil kayda yazar).
--   MODUL = gercek MODUL.MODULID (tab no DEGIL) - orn. Stok=27, Hizmetler=248002.
-- MSSQL: ID int identity, DEGISTIRMETARIHI smalldatetime.
-- ============================================================
CREATE TABLE IF NOT EXISTS public.kullanici_arama (
  id               integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  kulid            integer   NOT NULL,
  modul            integer   NOT NULL,
  kayitid          integer   NOT NULL,
  say              integer   NOT NULL DEFAULT 0,
  degistirmetarihi timestamp NOT NULL DEFAULT now()
);
CREATE UNIQUE INDEX IF NOT EXISTS ux_kullanici_arama ON public.kullanici_arama (kulid, modul, kayitid);
