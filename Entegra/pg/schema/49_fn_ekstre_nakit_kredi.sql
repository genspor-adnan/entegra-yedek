-- 2-parca: KASA + FATBASLIK(masraf fatura). Yuruyen bakiye window (TUR 60-79 haric),
-- Devir (pre-bastar, variant filtre), sonra pre-bastar at. MSSQL cursor->window.
-- doviz cari = GENINI BOLUM=-10135. NOT: birebir; differential veriyle dogrulanmali.
