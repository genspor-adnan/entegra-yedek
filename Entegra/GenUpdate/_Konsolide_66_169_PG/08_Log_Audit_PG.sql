-- MSSQL -> PG donusum notlari (bu dosyaya ozel):
--   EXEC sp_X @p OUTPUT       -> fonksiyon donus degeri  (v := fn_x(p))
--   'SELECT ... FOR JSON PATH,
--    WITHOUT_ARRAY_WRAPPER'   -> jsonb_build_object(...)::text  (tek nesne)
--   JSON_VALUE(@j,'$.A.B')    -> (j #>> '{A,B}')
--   TRY_CAST(x AS INT)        -> NULLIF(x,'') ~ sayi mi kontrolu + ::int
--   THROW 51001,'msg',1       -> RAISE EXCEPTION 'msg' USING ERRCODE='GN001'
--   OBJECT_ID(@t)             -> to_regclass(@t)
--   sys.columns / sys.types   -> information_schema.columns
--   COMPRESS(json) varbinary  -> JSONB (depo.log<yyyy>.bilgi zaten jsonb)
--   DECOMPRESS(...)           -> gereksiz (kolon jsonb)
--   JSON_MODIFY(x,'$.a',v)    -> jsonb_set(x,'{a}',to_jsonb(v))
--   FOR XML PATH ile kolon    -> to_jsonb(satir)  [PG satiri dogrudan JSON'a cevirir;
--     basina JSON kurma          MSSQL'deki kolon-kolon dinamik string kurma ORTADAN KALKAR]
--   dinamik sp_executesql     -> format(...) + EXECUTE ... USING  (parametreler baglanir,
--                                birlestirme yok -> enjeksiyon yok, MSSQL ile ayni guvenlik)
--   AYRI VERITABANI (GENDEPO) -> AYRI SEMA (depo)
--
-- DAVRANIS FARKI (bilerek):
--   MSSQL BILGI alani her degeri METIN olarak yaziyordu ("ADET":"12.000000").
--   PG'de bilgi JSONB; degerler yine METIN olarak yazilir (UInfo okuyucusu ayni kalsin diye),
--   yalnizca ondalik bicimi kaynaktaki gibi 6 haneye sabitlenir ve tarihler
--   'YYYY-MM-DD HH:MM:SS' (MSSQL 120 stili) olarak yazilir.
-- ============================================================================


-- ---- FUNCTION: fn_api_log_yiltablosu  (kaynak: GenDepoUpdate71) ----
-- Yil tablosunun TAM ADINI dondurur; yoksa olusturur.
-- MSSQL: '[GENDEPO].[dbo].[LOG2026]'   ->   PG: 'depo.log2026'
-- DDL, pg/schema/01_depo.sql'deki depo.log2026 ile BIREBIR aynidir.
DROP FUNCTION IF EXISTS public.fn_api_log_yiltablosu(integer);
CREATE OR REPLACE FUNCTION public.fn_api_log_yiltablosu(p_yil integer)
RETURNS text
LANGUAGE plpgsql AS $$
DECLARE
    v_sema  text := public.fn_api_depodbadi();
    v_ad    text := 'log' || p_yil::text;
    v_tam   text := v_sema || '.' || v_ad;
BEGIN
    IF to_regclass(v_tam) IS NOT NULL THEN
        RETURN v_tam;
    END IF;

    EXECUTE format($f$
        CREATE TABLE IF NOT EXISTS %I.%I (
            id            bigint       GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
            tarih         timestamp(6) NOT NULL DEFAULT now(),
            ip            varchar(45),
            istasyon      varchar(64),
            kullaniciid   integer,
            subeid        smallint,
            islemtipi     smallint     NOT NULL,
            altislemtipi  smallint,
            usttabloid    integer,
            ustkayitid    bigint,
            tabloid       integer,
            kayitid       bigint,
            rehberid      bigint,
            stokid        bigint,
            bilgi         jsonb
        )$f$, v_sema, v_ad);

    EXECUTE format('CREATE INDEX IF NOT EXISTS ix_%s_ust    ON %I.%I (usttabloid, ustkayitid)', v_ad, v_sema, v_ad);
    EXECUTE format('CREATE INDEX IF NOT EXISTS ix_%s_kayit  ON %I.%I (tabloid, kayitid)',       v_ad, v_sema, v_ad);
    EXECUTE format('CREATE INDEX IF NOT EXISTS ix_%s_rehber ON %I.%I (rehberid)',               v_ad, v_sema, v_ad);
    EXECUTE format('CREATE INDEX IF NOT EXISTS ix_%s_stok   ON %I.%I (stokid)',                 v_ad, v_sema, v_ad);
    EXECUTE format('CREATE INDEX IF NOT EXISTS ix_%s_tarih  ON %I.%I (tarih)',                  v_ad, v_sema, v_ad);

    RETURN v_tam;
END;
$$;


-- ---- FUNCTION: fn_api_log_yaz_ic  (kaynak: GenDepoUpdate157) ----
-- Silinmek/degistirilmek uzere olan satirlarin TAM ICERIGINI log tablosuna yazar.
-- Geriye YAZILAN SATIR SAYISI doner (MSSQL @Yazilan OUTPUT parametresinin karsiligi).
--
-- MSSQL tarafinda BILGI JSON'i kolon kolon dinamik string ile kuruluyordu
-- (FOR XML PATH + STRING_ESCAPE + COMPRESS). PG'de satirin kendisi to_jsonb ile
-- dogrudan JSON'a cevrilir; blob kolonlar ve NULL/bos degerler suzulur.
DROP FUNCTION IF EXISTS public.fn_api_log_yaz_ic(text, text, bigint, bigint, integer, integer, bigint, integer, integer, varchar, varchar, bigint, bigint, smallint);
CREATE OR REPLACE FUNCTION public.fn_api_log_yaz_ic(
    p_tablo     text,
    p_kosul     text        DEFAULT NULL,   -- icinde YALNIZ $1 (ust kayit/belge ID'si) kullanilabilir
    p_kosulpar  bigint      DEFAULT NULL,
    p_kayitid   bigint      DEFAULT NULL,
    p_tabno     integer     DEFAULT NULL,
    p_usttabno  integer     DEFAULT 0,
    p_ustid     bigint      DEFAULT 0,
    p_kulid     integer     DEFAULT 0,
    p_subeid    integer     DEFAULT 0,
    p_ip        varchar(45) DEFAULT NULL,
    p_istasyon  varchar(64) DEFAULT NULL,
    p_rehberid  bigint      DEFAULT 0,
    p_stokid    bigint      DEFAULT 0,
    p_islemtipi smallint    DEFAULT 0       -- 0=liSil (varsayilan), 1=liEkle, 2=liDegistir
)
RETURNS integer
LANGUAGE plpgsql AS $$
DECLARE
    v_reg        regclass;
    v_sema       text;
    v_ad         text;
    v_logtablo   text;
    v_idvar      boolean;
    v_rehifade   text;
    v_stkifade   text;
    v_kayitifade text;
    v_where      text;
    v_ustt       integer;
    v_reh        bigint;
    v_stk        bigint;
    v_rehkendi   boolean := false;
    v_stkkendi   boolean := false;
    v_bilgi      text;
    v_sql        text;
    v_yazilan    integer := 0;
BEGIN
    v_reg := to_regclass(p_tablo);
    IF v_reg IS NULL THEN
        RAISE EXCEPTION 'Tablo bulunamadi: %', p_tablo USING ERRCODE = 'GN002';
    END IF;

    SELECT n.nspname, c.relname INTO v_sema, v_ad
    FROM pg_class c JOIN pg_namespace n ON n.oid = c.relnamespace
    WHERE c.oid = v_reg;

    v_logtablo := public.fn_api_log_yiltablosu(extract(year from now())::int);

    -- ---- BILGI: satiri JSON'a cevir; blob kolonlar disarida, NULL/bos atilir ----
    --   MSSQL bicimleri korunur: tarih 'YYYY-MM-DD HH24:MI:SS', ondalik 6 hane,
    --   diger her sey metin.
    -- DIKKAT: jsonb_build_object en fazla 100 ARGUMAN alir (= 50 kolon). STOKLAR
    --   (~90 kolon), REHBER, FATBASLIK gibi genis tablolarda tek cagri
    --     ERROR: cannot pass more than 100 arguments to a function
    --   veriyordu. Kolonlar 45'erli gruplara bolunup jsonb_build_object(...) ||
    --   jsonb_build_object(...) seklinde birlestiriliyor - bicimleme ayni kaliyor.
    WITH kol AS (
    SELECT c.ordinal_position,
           format('%L, CASE WHEN t.%I IS NULL THEN NULL ELSE %s END',
                    c.column_name,
                    c.column_name,
                    CASE
                      WHEN c.data_type = 'date'
                        THEN format('to_char(t.%I, ''YYYY-MM-DD'')', c.column_name)
                      WHEN c.data_type IN ('timestamp without time zone','timestamp with time zone')
                        THEN format('to_char(t.%I, ''YYYY-MM-DD HH24:MI:SS'')', c.column_name)
                      WHEN c.data_type IN ('time without time zone','time with time zone')
                        THEN format('to_char(t.%I, ''HH24:MI:SS'')', c.column_name)
                      WHEN c.data_type IN ('numeric','money')
                        THEN format('trim(to_char(t.%I::numeric, ''FM9999999999999999990.000000''))', c.column_name)
                      WHEN c.data_type = 'boolean'
                        THEN format('CASE WHEN t.%I THEN ''True'' ELSE ''False'' END', c.column_name)
                      ELSE format('t.%I::text', c.column_name)
                    END) AS ifade
    FROM information_schema.columns c
    WHERE c.table_schema = v_sema
      AND c.table_name   = v_ad
      AND c.data_type NOT IN ('bytea','xml','USER-DEFINED')
      AND c.is_generated = 'NEVER'
    ), grup AS (
    SELECT ordinal_position, ifade,
           ((row_number() OVER (ORDER BY ordinal_position) - 1) / 45) AS g
    FROM kol
    ), parca AS (
    SELECT g, 'jsonb_build_object(' || string_agg(ifade, ', ' ORDER BY ordinal_position) || ')' AS p
    FROM grup GROUP BY g
    )
    SELECT string_agg(p, ' || ' ORDER BY g)
      INTO v_bilgi
    FROM parca;

    IF v_bilgi IS NULL THEN
        RETURN 0;
    END IF;

    -- NULL ve bos ('') degerler JSON'a girmez (MSSQL ile ayni kural)
    v_bilgi := format(
      '(SELECT jsonb_object_agg(k, v) FROM jsonb_each_text(jsonb_strip_nulls(%s)) AS e(k, v) WHERE v <> '''')',
      v_bilgi);

    v_idvar := EXISTS (SELECT 1 FROM information_schema.columns
                       WHERE table_schema = v_sema AND table_name = v_ad AND lower(column_name) = 'id');

    -- Satirin KENDI varlik kolonlari (ULog.LogVarlikIDleri onceligi: REHBERID > CARIID, STOKID > URUNID)
    SELECT CASE WHEN count(*) = 0 THEN 'NULL'
                ELSE 'COALESCE(' || string_agg(format('NULLIF(t.%I::bigint, 0)', column_name),
                                               ', ' ORDER BY CASE lower(column_name) WHEN 'rehberid' THEN 0 ELSE 1 END)
                     || ', NULL)' END
      INTO v_rehifade
    FROM information_schema.columns
    WHERE table_schema = v_sema AND table_name = v_ad AND lower(column_name) IN ('rehberid','cariid');

    SELECT CASE WHEN count(*) = 0 THEN 'NULL'
                ELSE 'COALESCE(' || string_agg(format('NULLIF(t.%I::bigint, 0)', column_name),
                                               ', ' ORDER BY CASE lower(column_name) WHEN 'stokid' THEN 0 ELSE 1 END)
                     || ', NULL)' END
      INTO v_stkifade
    FROM information_schema.columns
    WHERE table_schema = v_sema AND table_name = v_ad AND lower(column_name) IN ('stokid','urunid');

    v_kayitifade := CASE WHEN v_idvar THEN 't.id::bigint' ELSE '0::bigint' END;

    v_where := CASE
                 WHEN NULLIF(btrim(COALESCE(p_kosul, '')), '') IS NOT NULL THEN p_kosul
                 WHEN v_idvar AND p_kayitid IS NOT NULL THEN 't.id = $4'
                 ELSE '1=0'
               END;

    -- MSSQL yer tutucusu: cagiranlar kosulu 'ID=@pB' / 'GOREVID=@pB' seklinde
    --   yaziyor ve degeri p_kosulpar ile geciyor (sp_executesql @pB parametresi).
    --   PG'de bunu bagli parametreye ($14) cevirmezsek EXECUTE
    --     ERROR: column "pb" does not exist
    --   ile patlar - 22 silme/kaydetme fonksiyonu bu kalibi kullaniyor.
    v_where := regexp_replace(v_where, '@pB', '$14', 'gi');

    -- REHBERID / STOKID turetimi (ULog.LogYaz kurali)
    v_ustt := CASE WHEN COALESCE(p_usttabno, 0) = 0 THEN p_tabno ELSE p_usttabno END;
    v_reh  := NULLIF(COALESCE(p_rehberid, 0), 0);
    v_stk  := NULLIF(COALESCE(p_stokid,   0), 0);

    IF v_reh IS NULL THEN
        IF p_tabno IN (71, 73, 74) THEN v_rehkendi := true;
        ELSIF v_ustt IN (71, 73, 74) THEN v_reh := NULLIF(p_ustid, 0);
        END IF;
    END IF;
    IF v_stk IS NULL THEN
        IF p_tabno = 88 THEN v_stkkendi := true;
        ELSIF v_ustt = 88 THEN v_stk := NULLIF(p_ustid, 0);
        END IF;
    END IF;

    v_sql := format($f$
        INSERT INTO %s (ip, istasyon, kullaniciid, subeid, islemtipi, altislemtipi,
                        usttabloid, ustkayitid, tabloid, kayitid, rehberid, stokid, bilgi)
        SELECT $5, $6, $7, $8, $13, $13,
               $9,
               CASE WHEN COALESCE($10, 0) = 0 THEN %s ELSE $10 END,
               $1, %s,
               NULLIF(CASE WHEN $11 THEN %s ELSE COALESCE($2, %s) END, 0),
               NULLIF(CASE WHEN $12 THEN %s ELSE COALESCE($3, %s) END, 0),
               %s
        FROM %I.%I t
        WHERE %s
    $f$, v_logtablo,
         v_kayitifade, v_kayitifade,
         v_kayitifade, v_rehifade,
         v_kayitifade, v_stkifade,
         v_bilgi,
         v_sema, v_ad,
         v_where);

    EXECUTE v_sql
      USING p_tabno,      -- $1
            v_reh,        -- $2
            v_stk,        -- $3
            p_kayitid,    -- $4   ($4 ayrica p_kosul icinde de kullanilabilir)
            p_ip,         -- $5
            p_istasyon,   -- $6
            p_kulid,      -- $7
            p_subeid,     -- $8
            v_ustt,       -- $9
            p_ustid,      -- $10
            v_rehkendi,   -- $11
            v_stkkendi,   -- $12
            p_islemtipi,  -- $13
            p_kosulpar;   -- $14  (kosuldaki @pB yer tutucusu)
    GET DIAGNOSTICS v_yazilan = ROW_COUNT;

    RETURN v_yazilan;
END;
$$;


-- ---- FUNCTION: fn_api_log_kaynak_isaretle  (kaynak: GenDepoUpdate143) ----
-- IZ BIRAKICI: son "ekleme" log satirini kopya/donusum kaynagiyla isaretler.
--   p_alttip: 3 = kopya, 5 = donusum
-- MSSQL'de COMPRESS/DECOMPRESS + JSON_MODIFY gerekiyordu; PG'de bilgi zaten jsonb
-- -> tek jsonb_set yeter.
DROP FUNCTION IF EXISTS public.fn_api_log_kaynak_isaretle(integer, bigint, smallint, bigint, integer);
CREATE OR REPLACE FUNCTION public.fn_api_log_kaynak_isaretle(
    p_tabno       integer,
    p_kayitid     bigint,
    p_alttip      smallint,
    p_kaynakid    bigint,
    p_kaynaktabno integer DEFAULT NULL
)
RETURNS void
LANGUAGE plpgsql AS $$
DECLARE
    v_logtablo text;
    v_alan     text;
BEGIN
    IF COALESCE(p_kayitid, 0) <= 0 OR COALESCE(p_kaynakid, 0) <= 0 THEN
        RETURN;
    END IF;

    v_logtablo := public.fn_api_log_yiltablosu(extract(year from now())::int);
    IF to_regclass(v_logtablo) IS NULL THEN
        RETURN;
    END IF;

    v_alan := CASE WHEN p_alttip = 5 THEN '_DonusumKaynak' ELSE '_KopyaKaynak' END;

    EXECUTE format($f$
        UPDATE %s
           SET altislemtipi = $3,
               bilgi = CASE WHEN bilgi IS NULL THEN NULL
                            ELSE jsonb_set(
                                   jsonb_set(bilgi, ARRAY[$6], to_jsonb($4::text), true),
                                   ARRAY['_KaynakTablo'], to_jsonb(COALESCE($5, $1)::text), true)
                       END
         WHERE id = (SELECT id FROM %s
                      WHERE tabloid = $1 AND kayitid = $2 AND islemtipi = 1
                      ORDER BY id DESC LIMIT 1)
    $f$, v_logtablo, v_logtablo)
    USING p_tabno, p_kayitid, p_alttip, p_kaynakid, p_kaynaktabno, v_alan;
END;
$$;


-- ---- FUNCTION: fn_api_log_detaysil_json  (kaynak: GenDepoUpdate71) ----
-- MSSQL sp_Api_Log_DetaySil_Json karsiligi.  Cagri: select * from fn_api_log_detaysil_json('{...}')
DROP FUNCTION IF EXISTS public.fn_api_log_detaysil_json(text);
CREATE OR REPLACE FUNCTION public.fn_api_log_detaysil_json(p_kosullar text)
RETURNS TABLE(sonuc text)
LANGUAGE plpgsql AS $$
DECLARE
    j          jsonb := COALESCE(NULLIF(p_kosullar, '')::jsonb, '{}'::jsonb);
    v_tablo    text;
    v_kosul    text;
    v_tabno    integer;
    v_usttabno integer;
    v_ustid    bigint;
    v_rehberid bigint;
    v_stokid   bigint;
    v_kulid    integer;
    v_subeid   integer;
    v_ip       varchar(45);
    v_istasyon varchar(64);
    v_n        integer;
BEGIN
    v_tablo := j ->> 'Tablo';
    v_kosul := j ->> 'Kosul';
    v_tabno := NULLIF(j ->> 'TabNo', '')::integer;

    IF v_tablo IS NULL OR v_tabno IS NULL OR NULLIF(btrim(COALESCE(v_kosul, '')), '') IS NULL THEN
        RAISE EXCEPTION 'Tablo, TabNo ve Kosul zorunlu.' USING ERRCODE = 'GN001';
    END IF;

    v_usttabno := COALESCE(NULLIF(j ->> 'UstTabNo', '')::integer, 0);
    v_ustid    := COALESCE(NULLIF(j ->> 'UstId',    '')::bigint,  0);
    v_rehberid := COALESCE(NULLIF(j ->> 'RehberId', '')::bigint,  0);
    v_stokid   := COALESCE(NULLIF(j ->> 'StokId',   '')::bigint,  0);
    v_kulid    := COALESCE(NULLIF(j #>> '{Oturum,KulId}',  '')::integer, 0);
    v_subeid   := COALESCE(NULLIF(j #>> '{Oturum,SubeId}', '')::integer, 0);
    v_ip       := left(COALESCE(j #>> '{Oturum,Ip}',       ''), 45);
    v_istasyon := left(COALESCE(j #>> '{Oturum,Istasyon}', ''), 64);

    v_n := public.fn_api_log_yaz_ic(
             p_tablo    => v_tablo,
             p_kosul    => v_kosul,
             p_tabno    => v_tabno,
             p_usttabno => v_usttabno,  p_ustid   => v_ustid,
             p_kulid    => v_kulid,     p_subeid  => v_subeid,
             p_ip       => v_ip,        p_istasyon => v_istasyon,
             p_rehberid => v_rehberid,  p_stokid  => v_stokid);

    RETURN QUERY SELECT jsonb_build_object('Sonuc', 1, 'Yazilan', v_n)::text;
END;
$$;


