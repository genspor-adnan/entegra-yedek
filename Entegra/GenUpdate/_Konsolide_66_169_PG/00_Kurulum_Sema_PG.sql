-- Belge donusum istek kaydi. Ayni ISTEKID ile ikinci kez belge uretilmez.
CREATE TABLE IF NOT EXISTS public.BELGEDONUSUMISLEM (
    ID              integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    ISTEKID         uuid          NOT NULL,
    DONUSUMTURU     integer       NOT NULL,
    KULLANICIID     integer       NOT NULL,
    SUBEID          integer       NOT NULL,
    DURUM           varchar(12)   NOT NULL,   -- BASLADI | TAMAMLANDI | HATA
    HEDEFBASLIKID   integer       NULL,
    HEDEFTUR        integer       NULL,
    BASLAMATARIHI   timestamp     NOT NULL DEFAULT now()::timestamp,
    BITISTARIHI     timestamp     NULL,
    SONUCJSON       text          NULL,
    HATAKODU        integer       NULL
);
CREATE UNIQUE INDEX IF NOT EXISTS ux_belgedonusumislem_istekid
    ON public.BELGEDONUSUMISLEM (ISTEKID);
CREATE INDEX IF NOT EXISTS ix_belgedonusumislem_durum
    ON public.BELGEDONUSUMISLEM (DURUM, BASLAMATARIHI);

